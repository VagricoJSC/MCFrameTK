SELECT
	OWNER,
	OBJECT_NAME,
	OBJECT_TYPE,
	STATUS,
	CASE OBJECT_TYPE
		WHEN 'PACKAGE BODY' THEN
			'ALTER PACKAGE "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE BODY;'
		WHEN 'TYPE BODY' THEN
			'ALTER TYPE "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE BODY;'
		WHEN 'PACKAGE' THEN
			'ALTER PACKAGE "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		WHEN 'TYPE' THEN
			'ALTER TYPE "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		WHEN 'PROCEDURE' THEN
			'ALTER PROCEDURE "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		WHEN 'FUNCTION' THEN
			'ALTER FUNCTION "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		WHEN 'TRIGGER' THEN
			'ALTER TRIGGER "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		WHEN 'VIEW' THEN
			'ALTER VIEW "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		WHEN 'MATERIALIZED VIEW' THEN
			'ALTER MATERIALIZED VIEW "' || OWNER || '"."' || OBJECT_NAME || '" COMPILE;'
		ELSE NULL
	END AS RECOMPILE_SQL
FROM DBA_OBJECTS
WHERE STATUS = 'INVALID'
ORDER BY OWNER, OBJECT_TYPE, OBJECT_NAME;