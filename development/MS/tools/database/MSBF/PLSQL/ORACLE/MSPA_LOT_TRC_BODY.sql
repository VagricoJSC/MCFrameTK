	<IN>	I_LOT_NOT_MNG
				ロット管理しない
	<IN>	I_LOT_DUPL_ABL
				同一ロット許可
	<INOUT>	IO_ROWIDX
				行ＮＯ
	<HISTORY>
	**********************************************************/
	IS
		L_LIST F_H_TYPE;
		CURSOR L_CUR(
			I_HRRCHY IN NUMBER,
			I_ITM_CD IN MAPA_META.ITM_CD%TYPE,
			I_LOT_NO IN MAPA_META.LOT_NO%TYPE,
			I_SUBLOT_NO IN MAPA_META.SUBLOT_NO%TYPE,
