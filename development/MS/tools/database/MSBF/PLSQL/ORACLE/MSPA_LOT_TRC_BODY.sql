			I_SNO2 IN MAPA_META.SNO2%TYPE,
			I_SNO3 IN MAPA_META.SNO3%TYPE,
			I_SNO4 IN MAPA_META.SNO4%TYPE
		) RETURN MSW_LOT_TRACE_F_HRRCHY%ROWTYPE IS
		SELECT
			  NVL2(I_HRRCHY, I_HRRCHY + 1, 0) "HRRCHY"
			, 0
			, '0'
			, V.ITM_CD
			, V.LOT_NO
			, V.SUBLOT_NO
			, V.ITM_SUB1
			, V.ITM_SUB2
			, V.ITM_SUB3
			, V.SNO1
			, V.SNO2
			, V.SNO3
			, V.SNO4
			, V.PAR_ITM_CD
			, V.PAR_LOT_NO
			, V.PAR_SUBLOT_NO
			, V.PAR_ITM_SUB1
			, V.PAR_ITM_SUB2
			, V.PAR_ITM_SUB3
			, V.PAR_SNO1
			, V.PAR_SNO2
			, V.PAR_SNO3
			, V.PAR_SNO4
			, NVL(M2.ITM_NM, M1.ITM_NM)  AS ITM_NM
			, M1.LOT_MNG_TYP
			, M1.SUBLOT_MNG_TYP
            , NULL AS PEG_NO
		FROM
			(
