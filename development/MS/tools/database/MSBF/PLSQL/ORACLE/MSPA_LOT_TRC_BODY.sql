CREATE OR REPLACE PACKAGE BODY MSPA_LOT_TRC
IS

	FUNCTION IS_LOTLOOP_F_ITM(
		I_REC MSW_LOT_TRACE_F_HRRCHY%ROWTYPE,
		I_MODE NUMBER) RETURN NUMBER
	/*********************************************************
	<SYNOPSIS>
			MSW_LOTLOOP_PARSに存在するかどうかを判断する。
      （LOOPチェック）
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_REC
				検索対象レコード
			I_MODE
				0:正展開、1:逆展開
	<HISTORY>
	**********************************************************/
	IS
		L_CNT NUMBER;
	BEGIN
		IF I_MODE = 0 THEN
			SELECT COUNT(ROWNUM) INTO L_CNT FROM MSW_LOTLOOP_PARS T1
			WHERE T1.ITM_CD = I_REC.ITM_CD
			AND   T1.ITM_SUB1 = I_REC.ITM_SUB1
			AND   T1.ITM_SUB2 = I_REC.ITM_SUB2
			AND   T1.ITM_SUB3 = I_REC.ITM_SUB3
			AND   T1.LOT_NO = I_REC.LOT_NO
			AND   T1.SUBLOT_NO = I_REC.SUBLOT_NO
			AND   T1.SNO1 = I_REC.SNO1
			AND   T1.SNO2 = I_REC.SNO2
			AND   T1.SNO3 = I_REC.SNO3
			AND   T1.SNO4 = I_REC.SNO4;
		ELSE
			SELECT COUNT(ROWNUM) INTO L_CNT FROM MSW_LOTLOOP_PARS T1
			WHERE T1.ITM_CD = I_REC.PAR_ITM_CD
			AND   T1.ITM_SUB1 = I_REC.PAR_ITM_SUB1
			AND   T1.ITM_SUB2 = I_REC.PAR_ITM_SUB2
			AND   T1.ITM_SUB3 = I_REC.PAR_ITM_SUB3
			AND   T1.LOT_NO = I_REC.PAR_LOT_NO
			AND   T1.SUBLOT_NO = I_REC.PAR_SUBLOT_NO
			AND   T1.SNO1 = I_REC.PAR_SNO1
			AND   T1.SNO2 = I_REC.PAR_SNO2
			AND   T1.SNO3 = I_REC.PAR_SNO3
			AND   T1.SNO4 = I_REC.PAR_SNO4;
		END IF;

		RETURN L_CNT;
	END IS_LOTLOOP_F_ITM;

	PROCEDURE P_INS_LOTLOOP_F_PARS(
		I_REC MSW_LOT_TRACE_F_HRRCHY%ROWTYPE,
		I_MODE NUMBER)
	/*********************************************************
	<SYNOPSIS>
			MSW_LOTLOOP_PARSに追加する。
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_REC
				追加対象レコード
			I_MODE
				0:正展開、1:逆展開
	<HISTORY>
	**********************************************************/
	IS
	BEGIN
		IF I_MODE = 0 THEN
			INSERT INTO MSW_LOTLOOP_PARS(ITM_CD,LOT_NO,SUBLOT_NO,ITM_SUB1,ITM_SUB2,ITM_SUB3,SNO1,SNO2,SNO3,SNO4)
			VALUES (I_REC.ITM_CD,I_REC.LOT_NO,I_REC.SUBLOT_NO,I_REC.ITM_SUB1,I_REC.ITM_SUB2,I_REC.ITM_SUB3,I_REC.SNO1,I_REC.SNO2,I_REC.SNO3,I_REC.SNO4);
		ELSE
			INSERT INTO MSW_LOTLOOP_PARS(ITM_CD,LOT_NO,SUBLOT_NO,ITM_SUB1,ITM_SUB2,ITM_SUB3,SNO1,SNO2,SNO3,SNO4)
			VALUES (I_REC.PAR_ITM_CD,I_REC.PAR_LOT_NO,I_REC.PAR_SUBLOT_NO,I_REC.PAR_ITM_SUB1,I_REC.PAR_ITM_SUB2,I_REC.PAR_ITM_SUB3,I_REC.PAR_SNO1,I_REC.PAR_SNO2,I_REC.PAR_SNO3,I_REC.PAR_SNO4);
		END IF;
	END P_INS_LOTLOOP_F_PARS;

	PROCEDURE P_DEL_LOTLOOP_F_PARS(
		I_REC MSW_LOT_TRACE_F_HRRCHY%ROWTYPE)
	/*********************************************************
	<SYNOPSIS>
			MSW_LOOP_PARSを削除する。
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_REC
				削除対象レコード
	<HISTORY>
	**********************************************************/
	IS
	BEGIN
		DELETE FROM MSW_LOTLOOP_PARS
		WHERE I_REC.ITM_CD = ITM_CD
		AND I_REC.LOT_NO = LOT_NO
		AND I_REC.SUBLOT_NO = SUBLOT_NO
		AND I_REC.ITM_SUB1 = ITM_SUB1
		AND I_REC.ITM_SUB2 = ITM_SUB2
		AND I_REC.ITM_SUB3 = ITM_SUB3
		AND I_REC.SNO1 = SNO1
		AND I_REC.SNO2 = SNO2
		AND I_REC.SNO3 = SNO3
		AND I_REC.SNO4 = SNO4;
	END P_DEL_LOTLOOP_F_PARS;

	FUNCTION IS_LOTDUP_F_ITM(
		I_REC MSW_LOT_TRACE_F_HRRCHY%ROWTYPE,
		I_LOT_NOT_MNG IN NUMBER,
		I_LOT_DUPL_ABL IN NUMBER
	) RETURN NUMBER
	/*********************************************************
	<SYNOPSIS>
			ロット・サブロット管理区分による展開可否
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_REC
				対象レコード
	<IN>	I_LOT_NOT_MNG
				ロット管理しない
	<IN>	I_LOT_DUPL_ABL
				同一ロット許可
	<HISTORY>
	**********************************************************/
	IS
	BEGIN
		IF I_REC.LOT_MNG_TYP = MAC_LOT_MNG_TYP.UNIQ OR I_REC.SUBLOT_MNG_TYP = MAC_SUBLOT_MNG_TYP.UNIQ THEN
			RETURN 0;
		END IF;
		IF I_LOT_NOT_MNG = 1 AND (I_REC.LOT_MNG_TYP = MAC_LOT_MNG_TYP.NOT_MNG OR I_REC.SUBLOT_MNG_TYP = MAC_SUBLOT_MNG_TYP.NOT_MNG) THEN
			RETURN 0;
		END IF;
		IF I_LOT_DUPL_ABL = 1 AND (I_REC.LOT_MNG_TYP = MAC_LOT_MNG_TYP.DUPL_ABL OR I_REC.SUBLOT_MNG_TYP = MAC_SUBLOT_MNG_TYP.DUPL_ABL) THEN
			RETURN 0;
		END IF;

		RETURN 1;
	END IS_LOTDUP_F_ITM;

	PROCEDURE P_INS_LOT_TRC_HRRCHY_IMPL(
		I_ROW MSW_LOT_TRACE_F_HRRCHY%ROWTYPE,
		I_LOT_NOT_MNG IN NUMBER,
		I_LOT_DUPL_ABL IN NUMBER,
		IO_ROWIDX IN OUT NUMBER
	)
	/*********************************************************
	<SYNOPSIS>
		ロットトレース正展開（ループ）
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_ROW
				展開元レコード
	<IN>	I_LOT_NOT_MNG
				ロット管理しない
	<IN>	I_LOT_DUPL_ABL
				同一ロット許可
	<INOUT>	IO_ROWIDX
				行ＮＯ
	<HISTORY>
	**********************************************************/
	IS
		L_LIST F_H_TYPE;
		CURSOR L_CUR(
			I_HRRCHY IN NUMBER,
			I_ITM_CD IN MAPA_META.ITM_CD%TYPE,
			I_LOT_NO IN MAPA_META.LOT_NO%TYPE,
			I_SUBLOT_NO IN MAPA_META.SUBLOT_NO%TYPE,
			I_ITM_SUB1 IN MAPA_META.ITM_SUB1%TYPE,
			I_ITM_SUB2 IN MAPA_META.ITM_SUB2%TYPE,
			I_ITM_SUB3 IN MAPA_META.ITM_SUB3%TYPE,
			I_SNO1 IN MAPA_META.SNO1%TYPE,
			I_SNO2 IN MAPA_META.SNO2%TYPE,
			I_SNO3 IN MAPA_META.SNO3%TYPE,
			I_SNO4 IN MAPA_META.SNO4%TYPE
		) RETURN MSW_LOT_TRACE_F_HRRCHY%ROWTYPE IS
		SELECT
			  NVL2(I_HRRCHY, I_HRRCHY + 1, 0) "HRRCHY"
			, 0
			, '0'
			, V.ITM_CD
			, V.LOT_NO
			, V.SUBLOT_NO
			, V.ITM_SUB1
			, V.ITM_SUB2
			, V.ITM_SUB3
			, V.SNO1
			, V.SNO2
			, V.SNO3
			, V.SNO4
			, V.PAR_ITM_CD
			, V.PAR_LOT_NO
			, V.PAR_SUBLOT_NO
			, V.PAR_ITM_SUB1
			, V.PAR_ITM_SUB2
			, V.PAR_ITM_SUB3
			, V.PAR_SNO1
			, V.PAR_SNO2
			, V.PAR_SNO3
			, V.PAR_SNO4
			, NVL(M2.ITM_NM, M1.ITM_NM)  AS ITM_NM
			, M1.LOT_MNG_TYP
			, M1.SUBLOT_MNG_TYP
            , NULL AS PEG_NO
		FROM
			(
			SELECT /*+ LEADING ( T2 T1 ) */ DISTINCT 
				T1.ITM_CD,
				T1.LOT_NO,
				T1.SUBLOT_NO,
				T1.ITM_SUB1,
				T1.ITM_SUB2,
				T1.ITM_SUB3,
				T1.SNO1,
				T1.SNO2,
				T1.SNO3,
				T1.SNO4,
				T2.ITM_CD AS PAR_ITM_CD,
				T2.LOT_NO AS PAR_LOT_NO,
				T2.SUBLOT_NO AS PAR_SUBLOT_NO,
				T2.ITM_SUB1 AS PAR_ITM_SUB1,
				T2.ITM_SUB2 AS PAR_ITM_SUB2,
				T2.ITM_SUB3 AS PAR_ITM_SUB3,
				T2.SNO1 AS PAR_SNO1,
				T2.SNO2 AS PAR_SNO2,
				T2.SNO3 AS PAR_SNO3,
				T2.SNO4 AS PAR_SNO4
			FROM
				MST_LOT_TRACE_GI T1
				,MST_LOT_TRACE_GR T2
			WHERE
				0 = 0
			AND (
				(
					(MAC_MFG_INST_UNIT_TYP.IS_ITM(T2.MFG_INST_UNIT_TYP) = '1'
						AND (T2.MFG_ACT_NO = T1.MFG_ACT_NO
							OR (T2.ITM_MFG_INST_NO = T1.ITM_MFG_INST_NO AND MSC_SCHD_ACT_TYP.IS_SCHD(T2.SCHD_ACT_TYP) = '1')
						)
					)
					OR (MAC_MFG_INST_UNIT_TYP.IS_OPER(T2.MFG_INST_UNIT_TYP) = '1'
						AND T2.ITM_MFG_INST_NO = T1.ITM_MFG_INST_NO
					)
				)
				OR T2.STK_XFR_ACT_NO = T1.STK_XFR_ACT_NO
			)
			AND T2.ITM_CD = I_ITM_CD
			AND T2.ITM_SUB1 = I_ITM_SUB1
			AND T2.ITM_SUB2 = I_ITM_SUB2
			AND T2.ITM_SUB3 = I_ITM_SUB3
			AND T2.LOT_NO = I_LOT_NO
			AND T2.SUBLOT_NO = I_SUBLOT_NO
			AND T2.SNO1 = I_SNO1
			AND T2.SNO2 = I_SNO2
			AND T2.SNO3 = I_SNO3
			AND T2.SNO4 = I_SNO4
			AND T1.BASE_UNIT_QTY != 0
			) V
			, MAM_ITM  M1
			, MAM_SUNDRY_ITM  M2
		WHERE
			0 = 0
		AND V.ITM_CD = M1.ITM_CD(+)
		AND V.ITM_SUB1 = M1.ITM_SUB1(+)
		AND V.ITM_SUB2 = M1.ITM_SUB2(+)
		AND V.ITM_SUB3 = M1.ITM_SUB3(+)
		AND V.ITM_CD = M2.ITM_CD(+)
		AND V.ITM_SUB1 = M2.ITM_SUB1(+)
		AND V.ITM_SUB2 = M2.ITM_SUB2(+)
		AND V.ITM_SUB3 = M2.ITM_SUB3(+)
		AND V.SNO1 = M2.SNO1(+)
		AND V.SNO2 = M2.SNO2(+)
		AND V.SNO3 = M2.SNO3(+)
		AND V.SNO4 = M2.SNO4(+)
		ORDER BY
			V.ITM_CD,
			V.ITM_SUB1,
			V.ITM_SUB2,
			V.ITM_SUB3,
			V.LOT_NO,
			V.SUBLOT_NO,
			V.SNO1,
			V.SNO2,
			V.SNO3,
			V.SNO4,
			V.PAR_ITM_CD,
			V.PAR_ITM_SUB1,
			V.PAR_ITM_SUB2,
			V.PAR_ITM_SUB3,
			V.PAR_LOT_NO,
			V.PAR_SUBLOT_NO,
			V.PAR_SNO1,
			V.PAR_SNO2,
			V.PAR_SNO3,
			V.PAR_SNO4
		;

	BEGIN
		OPEN L_CUR(
			I_ROW.HRRCHY,
			I_ROW.ITM_CD,
			I_ROW.LOT_NO,
			I_ROW.SUBLOT_NO,
			I_ROW.ITM_SUB1,
			I_ROW.ITM_SUB2,
			I_ROW.ITM_SUB3,
			I_ROW.SNO1,
			I_ROW.SNO2,
			I_ROW.SNO3,
			I_ROW.SNO4
			);
		FETCH L_CUR BULK COLLECT INTO L_LIST;
		CLOSE L_CUR;
		IF L_LIST.COUNT() > 0 THEN
			FOR I IN L_LIST.FIRST..L_LIST.LAST LOOP
				IO_ROWIDX := IO_ROWIDX + 1;
				L_LIST(I).SORT_NO := IO_ROWIDX;
				L_LIST(I).LOOP_FLG := '0';
				IF IS_LOTLOOP_F_ITM(L_LIST(I),0) = 1  THEN
					L_LIST(I).LOOP_FLG := '1';
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
				ELSIF IS_LOTDUP_F_ITM(L_LIST(I),I_LOT_NOT_MNG,I_LOT_DUPL_ABL) > 0 THEN
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
				ELSE
					P_INS_LOTLOOP_F_PARS(L_LIST(I),0);
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
					P_INS_LOT_TRC_HRRCHY_IMPL(L_LIST(I),I_LOT_NOT_MNG,I_LOT_DUPL_ABL,IO_ROWIDX);
				END IF;
			END LOOP;
		END IF;

	EXCEPTION
		WHEN OTHERS THEN
		IF L_CUR%ISOPEN THEN
			CLOSE L_CUR;
		END IF;
		RAISE;
	END P_INS_LOT_TRC_HRRCHY_IMPL;

	PROCEDURE P_INS_LOT_TRC_HRRCHY(
		I_HRRCHY IN NUMBER,
		I_ITM_CD IN MAPA_META.ITM_CD%TYPE,
		I_ITM_SUB1 IN MAPA_META.ITM_SUB1%TYPE,
		I_ITM_SUB2 IN MAPA_META.ITM_SUB2%TYPE,
		I_ITM_SUB3 IN MAPA_META.ITM_SUB3%TYPE,
		I_LOT_NO IN MAPA_META.LOT_NO%TYPE,
		I_SUBLOT_NO IN MAPA_META.SUBLOT_NO%TYPE,
		I_SNO1 IN MAPA_META.SNO1%TYPE,
		I_SNO2 IN MAPA_META.SNO2%TYPE,
		I_SNO3 IN MAPA_META.SNO3%TYPE,
		I_SNO4 IN MAPA_META.SNO4%TYPE,
		I_LOT_NOT_MNG IN NUMBER,
		I_LOT_DUPL_ABL IN NUMBER,
		I_MODE IN NUMBER DEFAULT 0
	)
	/*********************************************************
	<SYNOPSIS>
		ロットトレース正展開
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_HRRCHY
				階層
	<IN>	I_ITM_CD
				品目ＣＤ
	<IN>	I_ITM_SUB1
				枝番１
	<IN>	I_ITM_SUB2
				枝番２
	<IN>	I_ITM_SUB3
				枝番３
	<IN>	I_LOT_NO
				ロットＮＯ
	<IN>	I_SUBLOT_NO
				サブロットＮＯ
	<IN>	I_SNO1
				手配ＮＯ１
	<IN>	I_SNO2
				手配ＮＯ２
	<IN>	I_SNO3
				手配ＮＯ３
	<IN>	I_SNO4
				手配ＮＯ４
	<IN>	I_LOT_NOT_MNG
				ロット管理しない
	<IN>	I_LOT_DUPL_ABL
				同一ロット許可
	<IN>	I_MODE
				呼び出し元（0は画面から）
	<HISTORY>
	**********************************************************/
	IS
		L_ROWIDX NUMBER := -1;
		L_LIST F_H_TYPE;

		CURSOR L_CUR (
			I_HRRCHY IN NUMBER,
			I_ITM_CD IN MAPA_META.ITM_CD%TYPE,
			I_LOT_NO IN MAPA_META.LOT_NO%TYPE,
			I_SUBLOT_NO IN MAPA_META.SUBLOT_NO%TYPE,
			I_ITM_SUB1 IN MAPA_META.ITM_SUB1%TYPE,
			I_ITM_SUB2 IN MAPA_META.ITM_SUB2%TYPE,
			I_ITM_SUB3 IN MAPA_META.ITM_SUB3%TYPE,
			I_SNO1 IN MAPA_META.SNO1%TYPE,
			I_SNO2 IN MAPA_META.SNO2%TYPE,
			I_SNO3 IN MAPA_META.SNO3%TYPE,
			I_SNO4 IN MAPA_META.SNO4%TYPE
		)
		RETURN MSW_LOT_TRACE_F_HRRCHY%ROWTYPE IS
		SELECT DISTINCT
			  DECODE(I_HRRCHY, NULL, 0, I_HRRCHY + 1) "HRRCHY"
			, 0
			, '0'
			, V.ITM_CD
			, V.LOT_NO
			, V.SUBLOT_NO
			, V.ITM_SUB1
			, V.ITM_SUB2
			, V.ITM_SUB3
			, V.SNO1
			, V.SNO2
			, V.SNO3
			, V.SNO4
			, null AS PAR_ITM_CD
			, null AS PAR_LOT_NO
			, null AS PAR_SUBLOT_NO
			, null AS PAR_ITM_SUB1
			, null AS PAR_ITM_SUB2
			, null AS PAR_ITM_SUB3
			, null AS PAR_SNO1
			, null AS PAR_SNO2
			, null AS PAR_SNO3
			, null AS PAR_SNO4
			, NVL(M2.ITM_NM, M1.ITM_NM)  AS ITM_NM
			, M1.LOT_MNG_TYP
			, M1.SUBLOT_MNG_TYP
            , NULL AS PEG_NO
		FROM
			(
			SELECT
				T1.ITM_CD,
				T1.LOT_NO,
				T1.SUBLOT_NO,
				T1.ITM_SUB1,
				T1.ITM_SUB2,
				T1.ITM_SUB3,
				T1.SNO1,
				T1.SNO2,
				T1.SNO3,
				T1.SNO4
			FROM
				MST_LOT_TRACE_GR T1
			WHERE
				0 = 0
			AND T1.ITM_CD = I_ITM_CD
			AND (T1.ITM_SUB1 LIKE I_ITM_SUB1 OR I_ITM_SUB1 IS NULL)
			AND (T1.ITM_SUB2 LIKE I_ITM_SUB2 OR I_ITM_SUB2 IS NULL)
			AND (T1.ITM_SUB3 LIKE I_ITM_SUB3 OR I_ITM_SUB3 IS NULL)
			AND (T1.LOT_NO LIKE I_LOT_NO OR I_LOT_NO IS NULL)
			AND (T1.SUBLOT_NO LIKE I_SUBLOT_NO OR I_SUBLOT_NO IS NULL)
			AND (T1.SNO1 LIKE I_SNO1 OR I_SNO1 IS NULL)
			AND (T1.SNO2 LIKE I_SNO2 OR I_SNO2 IS NULL)
			AND (T1.SNO3 LIKE I_SNO3 OR I_SNO3 IS NULL)
			AND (T1.SNO4 LIKE I_SNO4 OR I_SNO4 IS NULL)
			) V
			, MAM_ITM   M1
			, MAM_SUNDRY_ITM M2
		WHERE
			0 = 0
		AND V.ITM_CD = M1.ITM_CD(+)
		AND V.ITM_SUB1 = M1.ITM_SUB1(+)
		AND V.ITM_SUB2 = M1.ITM_SUB2(+)
		AND V.ITM_SUB3 = M1.ITM_SUB3(+)
		AND V.ITM_CD = M2.ITM_CD(+)
		AND V.ITM_SUB1 = M2.ITM_SUB1(+)
		AND V.ITM_SUB2 = M2.ITM_SUB2(+)
		AND V.ITM_SUB3 = M2.ITM_SUB3(+)
		AND V.SNO1 = M2.SNO1(+)
		AND V.SNO2 = M2.SNO2(+)
		AND V.SNO3 = M2.SNO3(+)
		AND V.SNO4 = M2.SNO4(+)
		ORDER BY
			V.ITM_CD,
			V.ITM_SUB1,
			V.ITM_SUB2,
			V.ITM_SUB3,
			V.LOT_NO,
			V.SUBLOT_NO,
			V.SNO1,
			V.SNO2,
			V.SNO3,
			V.SNO4
		;

	BEGIN
		IF I_MODE = 0 THEN
			DELETE FROM MSW_LOT_TRACE_F_HRRCHY;
		END IF;
		DELETE FROM MSW_LOTLOOP_PARS;

		OPEN L_CUR(
			I_HRRCHY,
			I_ITM_CD,
			I_LOT_NO,
			I_SUBLOT_NO,
			I_ITM_SUB1,
			I_ITM_SUB2,
			I_ITM_SUB3,
			I_SNO1,
			I_SNO2,
			I_SNO3,
			I_SNO4
			);
		FETCH L_CUR BULK COLLECT INTO L_LIST;
		CLOSE L_CUR;

		IF L_LIST.COUNT() > 0 THEN
			FOR I IN L_LIST.FIRST..L_LIST.LAST LOOP
				L_ROWIDX := L_ROWIDX + 1;
				L_LIST(I).SORT_NO := L_ROWIDX;
				L_LIST(I).LOOP_FLG := '0';

				IF IS_LOTLOOP_F_ITM(L_LIST(I),0) = 1 THEN
					L_LIST(I).LOOP_FLG := '1';
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
				ELSIF IS_LOTDUP_F_ITM(L_LIST(I),I_LOT_NOT_MNG,I_LOT_DUPL_ABL) > 0 THEN
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
				ELSE
					P_INS_LOTLOOP_F_PARS(L_LIST(I),0);
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
					P_INS_LOT_TRC_HRRCHY_IMPL(L_LIST(I),I_LOT_NOT_MNG,I_LOT_DUPL_ABL,L_ROWIDX);
				END IF;
			END LOOP;
		END IF;
	EXCEPTION
		WHEN OTHERS THEN
		IF L_CUR%ISOPEN THEN
			CLOSE L_CUR;
		END IF;
		RAISE;
	END P_INS_LOT_TRC_HRRCHY;

