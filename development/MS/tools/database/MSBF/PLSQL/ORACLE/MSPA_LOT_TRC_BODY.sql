				T1.LOT_NO,
				T1.SUBLOT_NO,
				T1.ITM_SUB1,
				T1.ITM_SUB2,
				T1.ITM_SUB3,
				T1.SNO1,
				T1.SNO2,
				T1.SNO3,
				T1.SNO4,
