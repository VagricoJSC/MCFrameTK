				T2.LOT_NO AS PAR_LOT_NO,
				T2.SUBLOT_NO AS PAR_SUBLOT_NO,
				T2.ITM_SUB1 AS PAR_ITM_SUB1,
				T2.ITM_SUB2 AS PAR_ITM_SUB2,
				T2.ITM_SUB3 AS PAR_ITM_SUB3,
				T2.SNO1 AS PAR_SNO1,
				T2.SNO2 AS PAR_SNO2,
				T2.SNO3 AS PAR_SNO3,
				T2.SNO4 AS PAR_SNO4
			FROM
				MST_LOT_TRACE_GI T1
				,MST_LOT_TRACE_GR T2
			WHERE
				0 = 0
			AND (
				(
					(MAC_MFG_INST_UNIT_TYP.IS_ITM(T2.MFG_INST_UNIT_TYP) = '1'
						AND (T2.MFG_ACT_NO = T1.MFG_ACT_NO
							OR (T2.ITM_MFG_INST_NO = T1.ITM_MFG_INST_NO AND MSC_SCHD_ACT_TYP.IS_SCHD(T2.SCHD_ACT_TYP) = '1')
						)
					)
					OR (MAC_MFG_INST_UNIT_TYP.IS_OPER(T2.MFG_INST_UNIT_TYP) = '1'
						AND T2.ITM_MFG_INST_NO = T1.ITM_MFG_INST_NO
					)
				)
				OR T2.STK_XFR_ACT_NO = T1.STK_XFR_ACT_NO
			)
			AND T1.ITM_CD = I_ITM_CD
			AND T1.ITM_SUB1 = I_ITM_SUB1
			AND T1.ITM_SUB2 = I_ITM_SUB2
			AND T1.ITM_SUB3 = I_ITM_SUB3
			AND T1.LOT_NO = I_LOT_NO
			AND T1.SUBLOT_NO = I_SUBLOT_NO
			AND T1.SNO1 = I_SNO1
			AND T1.SNO2 = I_SNO2
			AND T1.SNO3 = I_SNO3
			AND T1.SNO4 = I_SNO4
			AND T1.BASE_UNIT_QTY != 0
			) V
			, MAM_ITM   M1
			, MAM_SUNDRY_ITM M2

		WHERE
			0 = 0
		AND V.PAR_ITM_CD = M1.ITM_CD(+)
		AND V.PAR_ITM_SUB1 = M1.ITM_SUB1(+)
		AND V.PAR_ITM_SUB2 = M1.ITM_SUB2(+)
		AND V.PAR_ITM_SUB3 = M1.ITM_SUB3(+)
		AND V.PAR_ITM_CD = M2.ITM_CD(+)
		AND V.PAR_ITM_SUB1 = M2.ITM_SUB1(+)
		AND V.PAR_ITM_SUB2 = M2.ITM_SUB2(+)
		AND V.PAR_ITM_SUB3 = M2.ITM_SUB3(+)
		AND V.PAR_SNO1 = M2.SNO1(+)
		AND V.PAR_SNO2 = M2.SNO2(+)
		AND V.PAR_SNO3 = M2.SNO3(+)
		AND V.PAR_SNO4 = M2.SNO4(+)
		ORDER BY
			V.ITM_CD,
			V.ITM_SUB1,
			V.ITM_SUB2,
			V.ITM_SUB3,
			V.LOT_NO,
			V.SUBLOT_NO,
			V.SNO1,
			V.SNO2,
			V.SNO3,
			V.SNO4,
			V.PAR_ITM_CD,
			V.PAR_ITM_SUB1,
			V.PAR_ITM_SUB2,
			V.PAR_ITM_SUB3,
			V.PAR_LOT_NO,
			V.PAR_SUBLOT_NO,
			V.PAR_SNO1,
			V.PAR_SNO2,
			V.PAR_SNO3,
			V.PAR_SNO4
		;

	BEGIN
		OPEN L_CUR(
			I_ROW.HRRCHY,
			I_ROW.PAR_ITM_CD,
			I_ROW.PAR_LOT_NO,
			I_ROW.PAR_SUBLOT_NO,
			I_ROW.PAR_ITM_SUB1,
			I_ROW.PAR_ITM_SUB2,
			I_ROW.PAR_ITM_SUB3,
			I_ROW.PAR_SNO1,
			I_ROW.PAR_SNO2,
			I_ROW.PAR_SNO3,
			I_ROW.PAR_SNO4
			);
		FETCH L_CUR BULK COLLECT INTO L_LIST;
		CLOSE L_CUR;
		IF L_LIST.COUNT() > 0 THEN
			FOR I IN L_LIST.FIRST..L_LIST.LAST LOOP
				IO_ROWIDX := IO_ROWIDX + 1;
				L_LIST(I).SORT_NO := IO_ROWIDX;
				L_LIST(I).LOOP_FLG := '0';
				IF IS_LOTLOOP_F_ITM(L_LIST(I),1) = 1  THEN
					L_LIST(I).LOOP_FLG := '1';
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
				ELSIF IS_LOTDUP_F_ITM(L_LIST(I),I_LOT_NOT_MNG,I_LOT_DUPL_ABL) > 0 THEN
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
				ELSE
					P_INS_LOTLOOP_F_PARS(L_LIST(I),1);
					INSERT INTO MSW_LOT_TRACE_F_HRRCHY VALUES L_LIST(I);
					P_INS_LOT_TRC_HRRCHY_IMPL_BKWD(L_LIST(I),I_LOT_NOT_MNG,I_LOT_DUPL_ABL,IO_ROWIDX);
				END IF;
			END LOOP;
		END IF;

	EXCEPTION
		WHEN OTHERS THEN
		IF L_CUR%ISOPEN THEN
			CLOSE L_CUR;
		END IF;
		RAISE;
	END P_INS_LOT_TRC_HRRCHY_IMPL_BKWD;

