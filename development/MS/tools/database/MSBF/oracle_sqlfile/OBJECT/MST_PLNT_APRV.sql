SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_PLNT_APRV(
	PLNT_APRV_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SKIP_CHK_SHIP_FLG,
	PLNT_APRV_STS_TYP,
	APRV_DT,
	APRV_TM,
	PLNT_APRV_ROLE_CD,
	APRV_DPT_CD,
	APRV_USR_CD,
	APRV_RSN,
	PLNT_APRV_PRNT_FLG,
	PLNT_APRV_PRNT_TM,
	SEQ,
	SITE_CD,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PLNT_APRV_NO,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SKIP_CHK_SHIP_FLG,
	ORG.PLNT_APRV_STS_TYP,
	ORG.APRV_DT,
	ORG.APRV_TM,
	ORG.PLNT_APRV_ROLE_CD,
	ORG.APRV_DPT_CD,
	ORG.APRV_USR_CD,
	ORG.APRV_RSN,
	ORG.PLNT_APRV_PRNT_FLG,
	ORG.PLNT_APRV_PRNT_TM,
	ORG.SEQ,
	ORG.SITE_CD,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PLNT_APRV_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

