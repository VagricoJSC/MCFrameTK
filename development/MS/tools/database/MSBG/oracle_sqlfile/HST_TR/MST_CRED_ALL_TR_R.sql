				:NEW.CO_CD,
				:NEW.CRED_AMT,
				:NEW.AP_CRED_AMT,
				:NEW.AR_CRED_AMT,
				:NEW.SUB_CHAR1,
				:NEW.SUB_CHAR2,
				:NEW.SUB_CHAR3,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_TS,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_CNTR,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_TS,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
		);
	ELSIF UPDATING THEN
--keyに変更があるかどうかの判定
--keyに変更がある場合
		IF :OLD.CRED_CD <> :NEW.CRED_CD OR :OLD.TRD_CUR_CD <> :NEW.TRD_CUR_CD OR :OLD.CO_CD <> :NEW.CO_CD THEN
			SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
			H_TYP := 'D';
			INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
				VALUES (
					H_ID,
					H_TAB,
					H_ID,
					A_ID,
					H_TYP,
					RDATE,
					U_ID,
					COCD,
					EX_1,
					EX_2,
					EX_3
			);
			INSERT INTO MST_CRED_ALL_R (
				HST_ID,
				HST_TYPE,
				CRED_CD,
				TRD_CUR_CD,
				CO_CD,
				CRED_AMT,
				AP_CRED_AMT,
				AR_CRED_AMT,
				SUB_CHAR1,
				SUB_CHAR2,
				SUB_CHAR3,
				INS_USR_ID,
				INS_USR_NM,
				INS_TS,
				INS_FUNC_ID,
				UPD_CNTR,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_TS,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)
				VALUES (
					H_ID,
					H_TYP,
					:OLD.CRED_CD,
					:OLD.TRD_CUR_CD,
					:OLD.CO_CD,
					:OLD.CRED_AMT,
					:OLD.AP_CRED_AMT,
					:OLD.AR_CRED_AMT,
					:OLD.SUB_CHAR1,
					:OLD.SUB_CHAR2,
					:OLD.SUB_CHAR3,
					:OLD.INS_USR_ID,
					:OLD.INS_USR_NM,
					:OLD.INS_TS,
					:OLD.INS_FUNC_ID,
					:OLD.UPD_CNTR,
					:OLD.UPD_USR_ID,
					:OLD.UPD_USR_NM,
					:OLD.UPD_TS,
					:OLD.UPD_FUNC_ID,
					:OLD.UPD_SRV_REQ_NO
			);
			H_TYP := 'I';
		ELSE
			H_TYP := 'U';
		END IF;
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO MST_CRED_ALL_R (
			HST_ID,
			HST_TYPE,
			CRED_CD,
			TRD_CUR_CD,
			CO_CD,
			CRED_AMT,
			AP_CRED_AMT,
			AR_CRED_AMT,
			SUB_CHAR1,
			SUB_CHAR2,
			SUB_CHAR3,
			INS_USR_ID,
			INS_USR_NM,
			INS_TS,
			INS_FUNC_ID,
			UPD_CNTR,
			UPD_USR_ID,
			UPD_USR_NM,
			UPD_TS,
			UPD_FUNC_ID,
			UPD_SRV_REQ_NO
		)
			VALUES (
				H_ID,
				H_TYP,
				:NEW.CRED_CD,
				:NEW.TRD_CUR_CD,
				:NEW.CO_CD,
				:NEW.CRED_AMT,
				:NEW.AP_CRED_AMT,
				:NEW.AR_CRED_AMT,
				:NEW.SUB_CHAR1,
				:NEW.SUB_CHAR2,
				:NEW.SUB_CHAR3,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_TS,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_CNTR,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_TS,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
		);
	ELSIF DELETING THEN
		H_TYP := 'D';
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO MST_CRED_ALL_R (
			HST_ID,
			HST_TYPE,
			CRED_CD,
			TRD_CUR_CD,
			CO_CD,
			CRED_AMT,
			AP_CRED_AMT,
			AR_CRED_AMT,
			SUB_CHAR1,
			SUB_CHAR2,
			SUB_CHAR3,
			INS_USR_ID,
			INS_USR_NM,
			INS_TS,
			INS_FUNC_ID,
			UPD_CNTR,
			UPD_USR_ID,
			UPD_USR_NM,
			UPD_TS,
			UPD_FUNC_ID,
			UPD_SRV_REQ_NO
		)
			VALUES (
				H_ID,
				H_TYP,
				:OLD.CRED_CD,
				:OLD.TRD_CUR_CD,
				:OLD.CO_CD,
				:OLD.CRED_AMT,
				:OLD.AP_CRED_AMT,
				:OLD.AR_CRED_AMT,
				:OLD.SUB_CHAR1,
				:OLD.SUB_CHAR2,
				:OLD.SUB_CHAR3,
				:OLD.INS_USR_ID,
				:OLD.INS_USR_NM,
				:OLD.INS_TS,
				:OLD.INS_FUNC_ID,
				:OLD.UPD_CNTR,
				:OLD.UPD_USR_ID,
				:OLD.UPD_USR_NM,
				:OLD.UPD_TS,
				:OLD.UPD_FUNC_ID,
				:OLD.UPD_SRV_REQ_NO
		);
	END IF;
END;
END;

