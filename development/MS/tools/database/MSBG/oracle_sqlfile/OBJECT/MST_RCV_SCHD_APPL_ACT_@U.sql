CREATE OR REPLACE VIEW MST_RCV_SCHD_APPL_ACT_$U(
	RCV_SCHD_APPL_ACT_NO,
	BILL_MNG_NO,
	RCV_ACT_DT,
	RCV_MTD_CD,
	RCV_TYP,
	RCV_ACT_AMT,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.RCV_SCHD_APPL_ACT_NO,
	ORG.BILL_MNG_NO,
	ORG.RCV_ACT_DT,
	ORG.RCV_MTD_CD,
	ORG.RCV_TYP,
	ORG.RCV_ACT_AMT,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_RCV_SCHD_APPL_ACT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

