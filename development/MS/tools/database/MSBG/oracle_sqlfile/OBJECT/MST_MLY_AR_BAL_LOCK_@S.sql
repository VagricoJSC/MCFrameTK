CREATE OR REPLACE VIEW MST_MLY_AR_BAL_LOCK_$S(
	ACST_CD,
	AR_DPT_CD,
	TRD_CUR_CD,
	IV_NO,
	WRK_NO,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ACST_CD,
	ORG.AR_DPT_CD,
	ORG.TRD_CUR_CD,
	ORG.IV_NO,
	ORG.WRK_NO,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_MLY_AR_BAL_LOCK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

