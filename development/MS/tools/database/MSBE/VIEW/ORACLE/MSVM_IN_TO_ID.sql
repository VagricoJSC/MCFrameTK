	MSC_IN_TO_ID_TYP.SCST,
	M1.BP_CD,
	M1.BP_NM,
	M1.BP_ALT_NM1,
	M1.BP_ALT_NM2,
	M1.BP_ALT_NM3,
	M1.BP_ALT_NM4,
	M1.DLV_SUNDRY_FLG,
	M1.CNTRY_CD,
	M2.CNTRY_NM,
	M1.DEL_FLG,
	M1.DEL_USR_ID,
	M1.DEL_USR_NM,
	M1.DEL_TS
FROM
	MAM_BP M1
	LEFT JOIN MAM_CNTRY M2 ON (M2.CNTRY_CD = M1.CNTRY_CD)
WHERE
	M1.DLV_FLG = '1'
UNION ALL
