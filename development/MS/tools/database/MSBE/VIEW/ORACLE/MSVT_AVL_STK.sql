SELECT
	T1.*
FROM
	MST_STK T1
WHERE 0=0
AND T1.IN_XFR_TYP = MSC_IN_XFR_TYP.IN_LOC
AND T1.STK_INSP_TYP = MSC_STK_INSP_TYP.FIN
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.CSTSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.ACCPT_DFCT, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
AND (T1.STK_ARRV_BP_CD = MAC_STR.NULL_VAL
	OR EXISTS (
		SELECT 'X'
		FROM MAM_LOC M1
		WHERE 0=0
		AND M1.LOC_CD = T1.LOC_CD AND M1.SPPL_CD IS NOT NULL))
/
