CREATE OR REPLACE VIEW MST_ALLOC_STOP_LOT_$U(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	STOP_DT,
	STOP_USR_CD,
	STOP_RMRKS,
	REL_DT,
	REL_USR_CD,
	REL_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.STOP_DT,
	ORG.STOP_USR_CD,
	ORG.STOP_RMRKS,
	ORG.REL_DT,
	ORG.REL_USR_CD,
	ORG.REL_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_ALLOC_STOP_LOT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

