CREATE OR REPLACE VIEW MST_XFR_INST_$S(
	XFR_INST_NO,
	TRD_CD,
	TRD_PTN_TYP,
	WG_CD,
	LG_GRP_CD,
	GR_LOC_CD,
	GR_STK_ARRV_BP_CD,
	XFR_SCHD_DT,
	XFR_INST_DT,
	INST_USR_CD,
	INST_DPT_CD,
	INST_PRNT_FLG,
	INST_PRNT_TM,
	PICK_PRNT_FLG,
	PICK_PRNT_TM,
	DLV_PRNT_FLG,
	DLV_PRNT_TM,
	TRD_RMRKS,
	INST_RMRKS,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.XFR_INST_NO,
	ORG.TRD_CD,
	ORG.TRD_PTN_TYP,
	ORG.WG_CD,
	ORG.LG_GRP_CD,
	ORG.GR_LOC_CD,
	ORG.GR_STK_ARRV_BP_CD,
	ORG.XFR_SCHD_DT,
	ORG.XFR_INST_DT,
	ORG.INST_USR_CD,
	ORG.INST_DPT_CD,
	ORG.INST_PRNT_FLG,
	ORG.INST_PRNT_TM,
	ORG.PICK_PRNT_FLG,
	ORG.PICK_PRNT_TM,
	ORG.DLV_PRNT_FLG,
	ORG.DLV_PRNT_TM,
	ORG.TRD_RMRKS,
	ORG.INST_RMRKS,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_XFR_INST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

