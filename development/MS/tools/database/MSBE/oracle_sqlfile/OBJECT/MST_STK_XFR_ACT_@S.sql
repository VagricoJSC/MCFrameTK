	STK_XFR_ACT_NO,
	TRD_CD,
	TRD_PTN_TYP,
	LOC_CD,
	WG_CD,
	ACT_DPT_CD,
	ACT_USR_CD,
	STK_XFR_ACT_TM,
	AC_DT,
	INTR_RMRKS,
	TRD_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	STK_XFR_RSN_CD,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.STK_XFR_ACT_NO,
	ORG.TRD_CD,
	ORG.TRD_PTN_TYP,
	ORG.LOC_CD,
	ORG.WG_CD,
	ORG.ACT_DPT_CD,
	ORG.ACT_USR_CD,
	ORG.STK_XFR_ACT_TM,
	ORG.AC_DT,
	ORG.INTR_RMRKS,
	ORG.TRD_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.STK_XFR_RSN_CD,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_STK_XFR_ACT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

