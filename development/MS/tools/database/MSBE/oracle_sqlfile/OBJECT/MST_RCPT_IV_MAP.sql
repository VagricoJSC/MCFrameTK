CREATE OR REPLACE VIEW MST_RCPT_IV_MAP(
	RCPT_IV_D_NO,
	RCPT_IV_NO,
	ARR_SCHD_NO,
	ARR_ACT_NO,
	TRD_UNIT_QTY,
	BASE_UNIT_QTY,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.RCPT_IV_D_NO,
	ORG.RCPT_IV_NO,
	ORG.ARR_SCHD_NO,
	ORG.ARR_ACT_NO,
	ORG.TRD_UNIT_QTY,
	ORG.BASE_UNIT_QTY,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_RCPT_IV_MAP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

