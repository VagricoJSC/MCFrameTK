CREATE OR REPLACE VIEW MST_ACXFR_INST_$S(
	ACXFR_INST_NO,
	TRD_CD,
	TRD_PTN_TYP,
	LOC_CD,
	WG_CD,
	ACXFR_INST_DT,
	INST_DPT_CD,
	INST_USR_CD,
	INTR_RMRKS,
	TRD_RMRKS,
	INST_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ACXFR_INST_NO,
	ORG.TRD_CD,
	ORG.TRD_PTN_TYP,
	ORG.LOC_CD,
	ORG.WG_CD,
	ORG.ACXFR_INST_DT,
	ORG.INST_DPT_CD,
	ORG.INST_USR_CD,
	ORG.INTR_RMRKS,
	ORG.TRD_RMRKS,
	ORG.INST_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_ACXFR_INST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

