SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_SLO_RSN_$S(
	SLO_RSN_CD,
	SLO_RSN_NM,
	QTN_TERM_FLG,
	QTN_TERM_SORT_SEQ,
	QTN_RSLT_FLG,
	QTN_RSLT_SORT_SEQ,
	SLO_CAN_FLG,
	SLO_CAN_SORT_SEQ,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLO_RSN_CD,
	ORG.SLO_RSN_NM,
	ORG.QTN_TERM_FLG,
	ORG.QTN_TERM_SORT_SEQ,
	ORG.QTN_RSLT_FLG,
	ORG.QTN_RSLT_SORT_SEQ,
	ORG.SLO_CAN_FLG,
	ORG.SLO_CAN_SORT_SEQ,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SLO_RSN_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mst_slo_rsn'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

