CREATE OR REPLACE VIEW MST_SLO_PRMS_$S(
	SLO_PRMS_NO,
	SLO_PRMS_REV,
	SLO_NO,
	SLO_D_NO,
	SLO_PRMS_H_NO,
	DLV_INST_RCPT_NO,
	PRMS_DLV_TM,
	TRD_UNIT_PRMS_QTY,
	BASE_UNIT_PRMS_QTY,
	CAN_FLG,
	PRMS_RMRKS,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLO_PRMS_NO,
	ORG.SLO_PRMS_REV,
	ORG.SLO_NO,
	ORG.SLO_D_NO,
	ORG.SLO_PRMS_H_NO,
	ORG.DLV_INST_RCPT_NO,
	ORG.PRMS_DLV_TM,
	ORG.TRD_UNIT_PRMS_QTY,
	ORG.BASE_UNIT_PRMS_QTY,
	ORG.CAN_FLG,
	ORG.PRMS_RMRKS,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SLO_PRMS_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

