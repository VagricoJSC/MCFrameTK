CREATE OR REPLACE VIEW MST_CST_FRCST_H_$S(
	CST_FRCST_NO,
	CST_CD,
	DLV_CD,
	CST_FRCST_PRNT_DT,
	CST_FRCST_SLIP_NO,
	FRCST_DPT_CD,
	FRCST_USR_CD,
	WRK_NO,
	RCPT_DT,
	CAN_RSN_CD,
	CAN_FLG,
	CAN_RMRKS,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CST_FRCST_NO,
	ORG.CST_CD,
	ORG.DLV_CD,
	ORG.CST_FRCST_PRNT_DT,
	ORG.CST_FRCST_SLIP_NO,
	ORG.FRCST_DPT_CD,
	ORG.FRCST_USR_CD,
	ORG.WRK_NO,
	ORG.RCPT_DT,
	ORG.CAN_RSN_CD,
	ORG.CAN_FLG,
	ORG.CAN_RMRKS,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_CST_FRCST_H_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

