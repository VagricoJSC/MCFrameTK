	LEFT OUTER JOIN mavm_loc_if_all msvt_litemes_alert_mavm_loc_if_all_m1 ON (msvt_litemes_alert_mst_itm_mfg_inst_all_t12.mfg_loc_cd = msvt_litemes_alert_mavm_loc_if_all_m1.loc_cd AND msvt_litemes_alert_mst_itm_mfg_inst_all_t12.co_cd = msvt_litemes_alert_mavm_loc_if_all_m1.co_cd)
