SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MRP_DLY_RQMT(
	RQMT_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STRG_LOC_CD,
	MFG_LOC_CD,
	SPPL_CD,
	RQST_LOC_CD,
	DUE_DT,
	RQMT_QTY,
	SNO1,
	SNO1_TYP,
	SNO2,
	SNO2_TYP,
	SNO3,
	SNO3_TYP,
	SNO4,
	SNO4_TYP,
	WG_CD,
	RQMT_TYP
)
AS
SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY
	,T1.SNO1
	,T1.SNO1_TYP
	,T1.SNO2
	,T1.SNO2_TYP
	,T1.SNO3
	,T1.SNO3_TYP
	,T1.SNO4
	,T1.SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
FROM
	MSVT_MRP_DLY_DMND T1,
	MAVM_ITM_WG M1
WHERE 0=0
	AND T1.ITM_CD = M1.ITM_CD(+)
	AND T1.ITM_SUB1 = M1.ITM_SUB1(+)
	AND T1.ITM_SUB2 = M1.ITM_SUB2(+)
	AND T1.ITM_SUB3 = M1.ITM_SUB3(+)
	AND T1.WG_CD = M1.WG_CD(+)
 	AND M1.PROD_PLN_TYP = MAC_PROD_PLN_TYP.DMND_USE
 	AND M1.RQMT_TYP = MAC_RQMT_TYP.ALLOC
 	AND T1.DMND_TYP = MSC_DMND_TYP.MISC
UNION ALL
SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY
	,T1.SNO1
	,T1.SNO1_TYP
	,T1.SNO2
	,T1.SNO2_TYP
	,T1.SNO3
	,T1.SNO3_TYP
	,T1.SNO4
	,T1.SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
FROM
	MSVT_MRP_DLY_SD T1,
	MAVM_ITM_WG M1
WHERE 0=0
	AND T1.ITM_CD = M1.ITM_CD(+)
	AND T1.ITM_SUB1 = M1.ITM_SUB1(+)
	AND T1.ITM_SUB2 = M1.ITM_SUB2(+)
	AND T1.ITM_SUB3 = M1.ITM_SUB3(+)
	AND T1.WG_CD = M1.WG_CD(+)
 	AND M1.PROD_PLN_TYP = MAC_PROD_PLN_TYP.DMND_USE
 	AND NVL(M1.RQMT_TYP, MAC_RQMT_TYP.NON) = MAC_RQMT_TYP.NON
;

