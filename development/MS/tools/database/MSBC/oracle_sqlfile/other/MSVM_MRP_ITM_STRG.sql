SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVM_MRP_ITM_STRG(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	PRIO,
	WG_CD
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.LOC_CD
	,T1.PRIO
	,T2.WG_CD
FROM MAM_ITM_STRG T1, MAM_LOC T2
WHERE 0=0
AND T1.LOC_CD = T2.LOC_CD
AND T1.DEL_FLG = '0'
;

