SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MRP_PRCD_RQMT(
	RQMT_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STRG_LOC_CD,
	MFG_LOC_CD,
	SPPL_CD,
	RQST_LOC_CD,
	DUE_DT,
	RQMT_QTY,
	SNO1,
	SNO1_TYP,
	SNO2,
	SNO2_TYP,
	SNO3,
	SNO3_TYP,
	SNO4,
	SNO4_TYP,
	WG_CD,
	RQMT_TYP
)
AS
SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY
	,T1.SNO1
	,CAST(DECODE(T1.SNO1, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO1_TYP
	,T1.SNO2
	,CAST(DECODE(T1.SNO2, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO2_TYP
	,T1.SNO3
	,CAST(DECODE(T1.SNO3, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO3_TYP
	,T1.SNO4
	,CAST(DECODE(T1.SNO4, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
FROM
	MST_PRCD_RQMT T1
WHERE 0=0
AND T1.FIX_FLG = '0'
UNION ALL
SELECT
	 T2.RQMT_NO
	,T2.ITM_CD
	,T2.ITM_SUB1
	,T2.ITM_SUB2
	,T2.ITM_SUB3
	,T2.STRG_LOC_CD
	,T2.MFG_LOC_CD
	,T2.SPPL_CD
	,T2.RQST_LOC_CD
	,T2.DUE_DT
	,T2.RQMT_QTY
	,T2.SNO1
	,T2.SNO1_TYP
	,T2.SNO2
	,T2.SNO2_TYP
	,T2.SNO3
	,T2.SNO3_TYP
	,T2.SNO4
	,T2.SNO4_TYP
	,T2.WG_CD
	,T2.RQMT_TYP
FROM
	MSVT_MRP_RQMT T2
;

