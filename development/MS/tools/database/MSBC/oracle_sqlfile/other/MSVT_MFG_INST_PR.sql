SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MFG_INST_PR(
	MFG_INST_NO,
	MFG_STS_TYP,
	ITM_MFG_INST_NO,
	BASE_UNIT_MFG_QTY,
	BASE_UNIT_MFG_REM_QTY,
	BASE_UNIT_MFG_ABORT_QTY,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
)
AS
SELECT
	T1.MFG_INST_NO,
	T1.MFG_STS_TYP,
	T1.ITM_MFG_INST_NO,
	T1.BASE_UNIT_MFG_QTY,
	T1.BASE_UNIT_MFG_REM_QTY,
	T1.BASE_UNIT_MFG_ABORT_QTY,
	T1.SUB_CHAR1,
	T1.SUB_CHAR2,
	T1.SUB_CHAR3
FROM
	MST_MFG_ACT_REM T1
WHERE 0=0
AND	T1.DIV_SEQ = 0
;

