CREATE OR REPLACE VIEW MSVT_MRP_IO_SCHD_GR(
	ITM_ORD_NO,
	IO_SCHD_NO,
	IO_SCHD_TYP,
	IO_SCHD_STS_TYP,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	VER_NO,
	LOC_CD,
	BASE_UNIT_QTY,
	AVL_SCHD_DT,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	GD_CD,
	LMT_DT,
	WG_CD
)
AS
SELECT
	 T1.IO_SCHD_PR_NO AS ITM_ORD_NO
	,T1.IO_SCHD_NO
	,T1.IO_SCHD_TYP
	,T1.IO_SCHD_STS_TYP
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOC_CD
	,T1.BASE_UNIT_QTY
	,T1.SCHD_DT - NVL(T3.MRP_ALLOC_MARGIN_DAYS, 0) AS AVL_SCHD_DT
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,T2.LMT_DT
	,T1.WG_CD
FROM
	MSVT_AVL_IO_SCHD T1
	,MSVT_LOT_LIST T2
	,MAVM_ITM_WG T3
WHERE 0=0
AND T1.QUALITY_TYP = MAC_QUALITY_TYP.GOOD
AND T1.IO_TYP = MSC_IO_TYP.GR
-- 仕入直送の受払予定は出庫、入庫とも対象外とする
AND	T1.IO_SCHD_TYP NOT IN
	(
	MSC_IO_SCHD_TYP.PURC_GR_DDLV --仕入入庫（直送）
	)
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
AND T1.IO_SCHD_PR_NO IS NOT NULL
AND T1.ITM_CD = T2.ITM_CD(+)
AND T1.ITM_SUB1 = T2.ITM_SUB1(+)
AND T1.ITM_SUB2 = T2.ITM_SUB2(+)
AND T1.ITM_SUB3 = T2.ITM_SUB3(+)
AND T1.LOT_NO = T2.LOT_NO(+)
AND T1.SUBLOT_NO = T2.SUBLOT_NO(+)
AND T1.ITM_CD = T3.ITM_CD(+)
AND T1.ITM_SUB1 = T3.ITM_SUB1(+)
AND T1.ITM_SUB2 = T3.ITM_SUB2(+)
AND T1.ITM_SUB3 = T3.ITM_SUB3(+)
AND T1.WG_CD = T3.WG_CD(+)
;

