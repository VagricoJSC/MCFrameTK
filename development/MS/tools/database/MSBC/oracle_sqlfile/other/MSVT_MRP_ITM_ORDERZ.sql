CREATE OR REPLACE VIEW MSVT_MRP_ITM_ORDERZ(
	ITM_ORD_NO,
	ITM_ORD_TYP,
	ITM_ORD_STS_TYP,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	VER_NO,
	STRG_LOC_CD,
	BOM_PTN,
	OPER_PTN,
	MFG_LOC_CD,
	SPPL_CD,
	MAKER_CD,
	RQST_LOC_CD,
	RQST_WG_CD,
	YIELD_SCHD_QTY,
	MASTER_DT,
	PO_SCHD_DT,
	GI_SCHD_DT,
	MFG_ST_SCHD_DT,
	MFG_END_SCHD_DT,
	STRG_SCHD_DT,
	ACCPT_SCHD_DT,
	INSP_ST_SCHD_DT,
	INSP_END_SCHD_DT,
	AVL_SCHD_DT,
	SNO1,
	SNO_TYP1,
	SNO2,
	SNO_TYP2,
	SNO3,
	SNO_TYP3,
	SNO4,
	SNO_TYP4,
	LMT_DT,
	RQMT_NO,
	WG_CD
)
AS
SELECT
	 T1.ITM_ORD_NO
	,T1.ITM_ORD_TYP
	,T1.ITM_ORD_STS_TYP
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.STRG_LOC_CD
	,T1.BOM_PTN
	,T1.OPER_PTN
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.MAKER_CD
	,T1.RQST_LOC_CD
	,T1.RQST_WG_CD
	,T1.YIELD_SCHD_QTY
	,T1.MASTER_DT
	,T1.PO_SCHD_DT
	,T1.GI_SCHD_DT
	,T1.MFG_ST_SCHD_DT
	,T1.MFG_END_SCHD_DT
	,T1.STRG_SCHD_DT
	,T1.ACCPT_SCHD_DT
	,T1.INSP_ST_SCHD_DT
	,T1.INSP_END_SCHD_DT
	,T1.AVL_SCHD_DT - NVL(T2.MRP_ALLOC_MARGIN_DAYS, 0) AS AVL_SCHD_DT
	,T1.SNO1
	,T1.SNO_TYP1
	,T1.SNO2
	,T1.SNO_TYP2
	,T1.SNO3
	,T1.SNO_TYP3
	,T1.SNO4
	,T1.SNO_TYP4
	,T1.LMT_DT
	,T1.RQMT_NO
	,T1.WG_CD
FROM
	 MST_ITM_ORDER T1
	,MAVM_ITM_WG T2
WHERE 0=0
AND T1.ITM_CD = T2.ITM_CD(+)
AND T1.ITM_SUB1 = T2.ITM_SUB1(+)
AND T1.ITM_SUB2 = T2.ITM_SUB2(+)
AND T1.ITM_SUB3 = T2.ITM_SUB3(+)
AND T1.WG_CD = T2.WG_CD(+)
AND T1.ITM_ORD_STS_TYP in (MSC_ITM_ORD_STS_TYP.SAV, MSC_ITM_ORD_STS_TYP.OPN)
;

