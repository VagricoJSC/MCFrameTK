CREATE OR REPLACE VIEW MSVT_IO_SCHD_GR(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	VER_NO,
	LOT_NO,
	SUBLOT_NO,
	IO_SCHD_SUB_NO1,
	LOC_CD,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	IO_SCHD_TYP
)
AS
SELECT
	T1.ITM_CD,
	T1.ITM_SUB1,
	T1.ITM_SUB2,
	T1.ITM_SUB3,
	T1.VER_NO,
	T1.LOT_NO,
	T1.SUBLOT_NO,
	T1.IO_SCHD_SUB_NO1,
	T1.LOC_CD,
	T1.SNO1,
	T1.SNO2,
	T1.SNO3,
	T1.SNO4,
	T1.IO_SCHD_TYP
FROM
	MST_ORD_IO_SCHD T1
WHERE 0=0
AND T1.IO_TYP = MSC_IO_TYP.GR
AND T1.IO_SCHD_SUB_TYP1 = MSC_IO_SCHD_SUB_TYP.ITM_ORD_NO
UNION ALL
SELECT
	T2.ITM_CD,
	T2.ITM_SUB1,
	T2.ITM_SUB2,
	T2.ITM_SUB3,
	T2.VER_NO,
	T2.LOT_NO,
	T2.SUBLOT_NO,
	T2.IO_SCHD_SUB_NO1,
	T2.LOC_CD,
	T2.SNO1,
	T2.SNO2,
	T2.SNO3,
	T2.SNO4,
	T2.IO_SCHD_TYP
FROM
	MST_IO_SCHD T2
WHERE 0=0
AND T2.IO_TYP = MSC_IO_TYP.GR
AND T2.IO_SCHD_SUB_TYP1 = MSC_IO_SCHD_SUB_TYP.ITM_ORD_NO
;

