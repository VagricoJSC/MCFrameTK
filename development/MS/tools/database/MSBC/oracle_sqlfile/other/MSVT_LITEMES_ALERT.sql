			TA1.MFG_INST_NO,
			TA1.MFG_STS_TYP,
			TA1.ITM_MFG_INST_NO,
			TA1.BASE_UNIT_MFG_QTY,
			TA1.BASE_UNIT_MFG_REM_QTY,
