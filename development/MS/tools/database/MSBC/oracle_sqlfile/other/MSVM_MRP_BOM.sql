SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVM_MRP_BOM(
	PAR_ITM_CD,
	PAR_ITM_SUB1,
	PAR_ITM_SUB2,
	PAR_ITM_SUB3,
	BOM_PTN,
	OPER_CD,
	OPER_SEQ,
	CHD_ITM_CD,
	CHD_ITM_SUB1,
	CHD_ITM_SUB2,
	CHD_ITM_SUB3,
	VER_NO,
	PH_FLG,
	PH_BOM_PTN,
	ALT_GRP_CD,
	ALT_GRP_SEQ,
	ALT_ITM_TYP,
	ALT_ITM_RATIO,
	ALT_ALLOC_PRIO,
	PAR_INST_QTY,
	CHD_RQMT_QTY,
	FXD_CHD_RQMT_QTY,
	SNO_TYP1,
	MIN_SNO1,
	MAX_SNO1,
	SNO_TYP2,
	MIN_SNO2,
	MAX_SNO2,
	SNO_TYP3,
	MIN_SNO3,
	MAX_SNO3,
	SNO_TYP4,
	MIN_SNO4,
	MAX_SNO4,
	IN_OFFST_TYP,
	IN_OFFST,
	INPT_CTL_TYP,
	ST_DT,
	END_DT,
	WG_CD
)
AS
SELECT
	 T1.PAR_ITM_CD
	,T1.PAR_ITM_SUB1
	,T1.PAR_ITM_SUB2
	,T1.PAR_ITM_SUB3
	,T1.BOM_PTN
	,T1.OPER_CD
	,T1.OPER_SEQ
	,T1.CHD_ITM_CD
	,T1.CHD_ITM_SUB1
	,T1.CHD_ITM_SUB2
	,T1.CHD_ITM_SUB3
	,T1.VER_NO
	,T1.PH_FLG
	,T1.PH_BOM_PTN
	,T1.ALT_GRP_CD
	,DECODE(T1.ALT_GRP_CD, NULL, NULL, DECODE(T1.ALT_ITM_FLG, '1', T1.BOM_ROWNUM, 0)) AS ALT_GRP_SEQ
	,T1.ALT_ITM_TYP
	,T1.ALT_ITM_RATIO
	,T1.ALT_ALLOC_PRIO
	,T1.PAR_INST_QTY
	,T1.CHD_RQMT_QTY
	,T1.FXD_CHD_RQMT_QTY
	,CAST(T1.SNO_TYP1 AS VARCHAR2(1 CHAR)) SNO1_TYP
	,T1.MIN_SNO1
	,T1.MAX_SNO1
	,CAST(T1.SNO_TYP2 AS VARCHAR2(1 CHAR)) SNO2_TYP
	,T1.MIN_SNO2
	,T1.MAX_SNO2
	,CAST(T1.SNO_TYP3 AS VARCHAR2(1 CHAR)) SNO3_TYP
	,T1.MIN_SNO3
	,T1.MAX_SNO3
	,CAST(T1.SNO_TYP4 AS VARCHAR2(1 CHAR)) SNO4_TYP
	,T1.MIN_SNO4
	,T1.MAX_SNO4
	,T1.IN_OFFST_TYP
	,T1.IN_OFFST
	,T1.INPT_CTL_TYP
	,T1.ST_DT
	,T1.END_DT
	,T1.WG_CD
FROM MAVM_BOM T1
WHERE 0=0
AND T1.BYPROD_FLG = '0'
AND T1.INPT_CTL_TYP <> MAC_INPT_CTL_TYP.NO_MRP_INST
;

