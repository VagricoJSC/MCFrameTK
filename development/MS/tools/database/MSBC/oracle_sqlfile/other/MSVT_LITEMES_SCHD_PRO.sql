CREATE OR REPLACE VIEW MSVT_LITEMES_SCHD_PRO(
	CO_CD,
	SA,
	SA_LCL,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	QTY,
	TM,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	MFG_LOC_CD,
	MFG_STR_LN_CD,
	INST_ABORT_FLG,
	MFG_INST_NO,
	MFG_INST_REV,
	ITM_MFG_INST_NO
	)
AS
-- 目標の始点
SELECT
	T11.CO_CD,
	'目標' AS SA,
	'GOAL' AS SA_LCL,
	T12.ITM_CD,
	T12.ITM_SUB1,
	T12.ITM_SUB2,
	T12.ITM_SUB3,
	T11.BASE_UNIT_INST_QTY - T13.BASE_UNIT_MFG_ABORT_QTY AS QTY,
	LEAST(T11.ST_SCHD_TM, NVL(T14.MIN_ST_ACT_TM, T11.ST_SCHD_TM)) AS TM,
	T12.LOT_NO,
	T12.SUBLOT_NO,
	T12.SNO1,
	T12.SNO2,
	T12.SNO3,
	T12.SNO4,
	T12.MFG_LOC_CD,
	T12.MFG_STR_LN_CD AS MFG_STR_LN_CD,
	T11.ABORT_FLG AS INST_ABORT_FLG,
	T11.MFG_INST_NO,
	T11.MFG_INST_REV,
	T11.ITM_MFG_INST_NO
FROM
	MST_MFG_INST_ALL T11
	JOIN MST_ITM_MFG_INST_ALL T12 ON (T11.ITM_MFG_INST_NO = T12.ITM_MFG_INST_NO AND T11.CO_CD = T12.CO_CD)
	JOIN (SELECT
			T1.MFG_INST_NO,
			T1.MFG_STS_TYP,
			T1.ITM_MFG_INST_NO,
			T1.BASE_UNIT_MFG_ABORT_QTY,
			T1.CO_CD
		FROM
			MST_MFG_ACT_REM_ALL T1
		WHERE 0=0
		AND	T1.DIV_SEQ = 0
		AND T1.MFG_STS_TYP IN (MSC_MFG_STS_TYP.ORD, MSC_MFG_STS_TYP.STT, MSC_MFG_STS_TYP.CMPL)
		) T13 ON (T11.MFG_INST_NO = T13.MFG_INST_NO AND T11.CO_CD = T13.CO_CD)
	LEFT OUTER JOIN (SELECT
						MIN(TA1.ST_ACT_TM) MIN_ST_ACT_TM,
						TA1.ITM_MFG_INST_NO,
						TA1.CO_CD
					FROM
						MST_OPER_ACT_ALL TA1
					GROUP BY
						TA1.ITM_MFG_INST_NO,
						TA1.CO_CD
		) T14 ON (T12.ITM_MFG_INST_NO = T14.ITM_MFG_INST_NO AND T12.CO_CD = T14.CO_CD)
WHERE 0=0
AND T11.CAN_FLG = '0'
-- 目標の終点
UNION ALL
SELECT
	T11.CO_CD,
	'目標' AS SA,
	'GOAL' AS SA_LCL,
	T12.ITM_CD,
	T12.ITM_SUB1,
	T12.ITM_SUB2,
	T12.ITM_SUB3,
	T11.BASE_UNIT_INST_QTY - T13.BASE_UNIT_MFG_ABORT_QTY AS QTY,
	CASE GREATEST(T11.END_SCHD_TM, NVL(T14.MAX_END_ACT_TM, T11.END_SCHD_TM), NVL(T15.MAX_ACT_TM, T11.END_SCHD_TM))
		WHEN T11.END_SCHD_TM THEN TO_DATE(REPLACE(TO_CHAR(GREATEST(T11.END_SCHD_TM, NVL(T14.MAX_END_ACT_TM, T11.END_SCHD_TM), NVL(T15.MAX_ACT_TM, T11.END_SCHD_TM)),'YYYY/MM/DD HH24:MI:SS'), '00:00:00', '23:59:00'),'YYYY/MM/DD HH24:MI:SS')
		ELSE GREATEST(T11.END_SCHD_TM, NVL(T14.MAX_END_ACT_TM, T11.END_SCHD_TM), NVL(T15.MAX_ACT_TM, T11.END_SCHD_TM))
	END AS TM,
	T12.LOT_NO,
	T12.SUBLOT_NO,
	T12.SNO1,
	T12.SNO2,
	T12.SNO3,
	T12.SNO4,
	T12.MFG_LOC_CD,
	T12.MFG_STR_LN_CD AS MFG_STR_LN_CD,
	T11.ABORT_FLG AS INST_ABORT_FLG,
	T11.MFG_INST_NO,
	T11.MFG_INST_REV,
	T11.ITM_MFG_INST_NO
FROM
	MST_MFG_INST_ALL T11
	JOIN MST_ITM_MFG_INST_ALL T12 ON (T11.ITM_MFG_INST_NO = T12.ITM_MFG_INST_NO AND T11.CO_CD = T12.CO_CD)
	JOIN (SELECT
			T1.MFG_INST_NO,
			T1.MFG_STS_TYP,
			T1.ITM_MFG_INST_NO,
			T1.BASE_UNIT_MFG_ABORT_QTY,
			T1.CO_CD
		FROM
			MST_MFG_ACT_REM_ALL T1
		WHERE 0=0
		AND	T1.DIV_SEQ = 0
		AND T1.MFG_STS_TYP IN (MSC_MFG_STS_TYP.ORD, MSC_MFG_STS_TYP.STT, MSC_MFG_STS_TYP.CMPL)
		) T13 ON (T11.MFG_INST_NO = T13.MFG_INST_NO AND T11.CO_CD = T13.CO_CD)
	LEFT OUTER JOIN (SELECT
						MAX(TA1.END_ACT_TM) MAX_END_ACT_TM,
						TA1.ITM_MFG_INST_NO,
						TA1.CO_CD
					FROM
						MST_OPER_ACT_ALL TA1
					GROUP BY
						TA1.ITM_MFG_INST_NO,
						TA1.CO_CD
		) T14 ON (T12.ITM_MFG_INST_NO = T14.ITM_MFG_INST_NO AND T12.CO_CD = T14.CO_CD)
	LEFT OUTER JOIN (SELECT
						MAX(TA2.ACT_TM) MAX_ACT_TM,
						TA2.ITM_MFG_INST_NO,
						TA2.CO_CD
					FROM
						MST_YIELD_ACT_ALL TA2
					GROUP BY
						TA2.ITM_MFG_INST_NO,
						TA2.CO_CD
		) T15 ON (T12.ITM_MFG_INST_NO = T15.ITM_MFG_INST_NO AND T12.CO_CD = T15.CO_CD)
WHERE 0=0
AND T11.CAN_FLG = '0'
-- 予定の始点
UNION ALL
SELECT
	T11.CO_CD,
	'予定' AS SA,
	'SCHD' AS SA_LCL,
	T12.ITM_CD,
	T12.ITM_SUB1,
	T12.ITM_SUB2,
	T12.ITM_SUB3,
	0 AS QTY,
	T11.ST_SCHD_TM AS TM,
	T12.LOT_NO,
	T12.SUBLOT_NO,
	T12.SNO1,
	T12.SNO2,
	T12.SNO3,
	T12.SNO4,
	T12.MFG_LOC_CD,
	T12.MFG_STR_LN_CD AS MFG_STR_LN_CD,
	T11.ABORT_FLG AS INST_ABORT_FLG,
	T11.MFG_INST_NO,
	T11.MFG_INST_REV,
	T11.ITM_MFG_INST_NO
FROM
	MST_MFG_INST_ALL T11
	JOIN MST_ITM_MFG_INST_ALL T12 ON (T11.ITM_MFG_INST_NO = T12.ITM_MFG_INST_NO AND T11.CO_CD = T12.CO_CD)
WHERE 0=0
AND T11.CAN_FLG = '0'
-- 予定の終点
UNION ALL
SELECT
	T11.CO_CD,
	'予定' AS SA,
	'SCHD' AS SA_LCL,
	T12.ITM_CD,
	T12.ITM_SUB1,
	T12.ITM_SUB2,
	T12.ITM_SUB3,
	T11.BASE_UNIT_INST_QTY - T13.BASE_UNIT_MFG_ABORT_QTY AS QTY,
	TO_DATE(REPLACE(TO_CHAR(T11.END_SCHD_TM,'YYYY/MM/DD HH24:MI:SS'), '00:00:00', '23:59:00'),'YYYY/MM/DD HH24:MI:SS') AS TM,
	T12.LOT_NO,
	T12.SUBLOT_NO,
	T12.SNO1,
	T12.SNO2,
	T12.SNO3,
	T12.SNO4,
	T12.MFG_LOC_CD,
	T12.MFG_STR_LN_CD AS MFG_STR_LN_CD,
	T11.ABORT_FLG AS INST_ABORT_FLG,
	T11.MFG_INST_NO,
	T11.MFG_INST_REV,
	T11.ITM_MFG_INST_NO
FROM
	MST_MFG_INST_ALL T11
	JOIN MST_ITM_MFG_INST_ALL T12 ON (T11.ITM_MFG_INST_NO = T12.ITM_MFG_INST_NO AND T11.CO_CD = T12.CO_CD)
	JOIN (SELECT
			T1.MFG_INST_NO,
			T1.MFG_STS_TYP,
			T1.ITM_MFG_INST_NO,
			T1.BASE_UNIT_MFG_ABORT_QTY,
			T1.CO_CD
		FROM
			MST_MFG_ACT_REM_ALL T1
		WHERE 0=0
		AND	T1.DIV_SEQ = 0
		AND T1.MFG_STS_TYP IN (MSC_MFG_STS_TYP.ORD, MSC_MFG_STS_TYP.STT, MSC_MFG_STS_TYP.CMPL)
		) T13 ON (T11.MFG_INST_NO = T13.MFG_INST_NO AND T11.CO_CD = T13.CO_CD)
WHERE 0=0
AND T11.CAN_FLG = '0'
-- 実績の始点
UNION ALL
SELECT
	T11.CO_CD,
	'実績' AS SA,
	'ACT' AS SA_LCL,
	T12.ITM_CD,
	T12.ITM_SUB1,
	T12.ITM_SUB2,
	T12.ITM_SUB3,
	0 AS QTY,
	T14.MIN_ST_ACT_TM AS TM,
	T12.LOT_NO,
	T12.SUBLOT_NO,
	T12.SNO1,
	T12.SNO2,
	T12.SNO3,
	T12.SNO4,
	T12.MFG_LOC_CD,
	T12.MFG_STR_LN_CD AS MFG_STR_LN_CD,
	T11.ABORT_FLG AS INST_ABORT_FLG,
	T11.MFG_INST_NO,
	T11.MFG_INST_REV,
	T11.ITM_MFG_INST_NO
FROM
	MST_MFG_INST_ALL T11
	JOIN MST_ITM_MFG_INST_ALL T12 ON (T11.ITM_MFG_INST_NO = T12.ITM_MFG_INST_NO AND T11.CO_CD = T12.CO_CD)
	JOIN (SELECT
			MIN(TA1.ST_ACT_TM) MIN_ST_ACT_TM,
			TA1.ITM_MFG_INST_NO,
			TA1.CO_CD
		FROM
			MST_OPER_ACT_ALL TA1
		GROUP BY
			TA1.ITM_MFG_INST_NO,
			TA1.CO_CD
		) T14 ON (T12.ITM_MFG_INST_NO = T14.ITM_MFG_INST_NO AND T12.CO_CD = T14.CO_CD)
WHERE 0=0
AND T11.CAN_FLG = '0'
-- 実績データ
UNION ALL
SELECT
	T11.CO_CD,
	'実績' AS SA,
	'ACT' AS SA_LCL,
	T12.ITM_CD,
	T12.ITM_SUB1,
	T12.ITM_SUB2,
	T12.ITM_SUB3,
	NVL(T15.TOTAL_QTY,0) AS QTY,
	T15.ACT_TM AS TM,
	T12.LOT_NO,
	T12.SUBLOT_NO,
	T12.SNO1,
	T12.SNO2,
	T12.SNO3,
	T12.SNO4,
	T12.MFG_LOC_CD,
	T12.MFG_STR_LN_CD AS MFG_STR_LN_CD,
	T11.ABORT_FLG AS INST_ABORT_FLG,
	T11.MFG_INST_NO,
	T11.MFG_INST_REV,
	T11.ITM_MFG_INST_NO
FROM
	MST_MFG_INST_ALL T11
	JOIN MST_ITM_MFG_INST_ALL T12 ON (T11.ITM_MFG_INST_NO = T12.ITM_MFG_INST_NO AND T11.CO_CD = T12.CO_CD)
	JOIN (SELECT
			TA1.ITM_MFG_INST_NO,
			TA1.CO_CD,
			TA1.ACT_TM,
			TA1.BASE_UNIT_QTY,
			SUM(TA2.BASE_UNIT_QTY) AS TOTAL_QTY
		FROM
			(SELECT
				ITM_MFG_INST_NO,
				CO_CD,
				ACT_TM,
				SUM(BASE_UNIT_QTY) AS BASE_UNIT_QTY
			FROM
				MST_YIELD_ACT_ALL
			GROUP BY
				ITM_MFG_INST_NO,
				CO_CD,
				ACT_TM) TA1 
			JOIN 
			(SELECT
				ITM_MFG_INST_NO,
				CO_CD,
				ACT_TM,
				SUM(BASE_UNIT_QTY) AS BASE_UNIT_QTY
			FROM
				MST_YIELD_ACT_ALL
			GROUP BY
				ITM_MFG_INST_NO,
				CO_CD,
				ACT_TM) TA2 ON (TA1.ACT_TM >= TA2.ACT_TM AND TA1.ITM_MFG_INST_NO = TA2.ITM_MFG_INST_NO AND TA1.CO_CD = TA2.CO_CD)
		GROUP BY
			TA1.ITM_MFG_INST_NO,
			TA1.CO_CD,
			TA1.ACT_TM,
			TA1.BASE_UNIT_QTY
		ORDER BY
			TA1.ACT_TM
		) T15 ON (T12.ITM_MFG_INST_NO = T15.ITM_MFG_INST_NO AND T12.CO_CD = T15.CO_CD)
WHERE 0=0
AND T11.CAN_FLG = '0'

/
show errors;


