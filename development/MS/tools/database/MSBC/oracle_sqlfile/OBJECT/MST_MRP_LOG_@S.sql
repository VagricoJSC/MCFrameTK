CREATE OR REPLACE VIEW MST_MRP_LOG_$S(
	WG_CD,
	MRP_CALC_NO,
	SEQ_NO,
	MRP_TYP,
	LOG_TIME,
	MSG_ID,
	MSG,
	GP_BATCH_GRP_CD,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WG_CD,
	ORG.MRP_CALC_NO,
	ORG.SEQ_NO,
	ORG.MRP_TYP,
	ORG.LOG_TIME,
	ORG.MSG_ID,
	ORG.MSG,
	ORG.GP_BATCH_GRP_CD,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_MRP_LOG_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

