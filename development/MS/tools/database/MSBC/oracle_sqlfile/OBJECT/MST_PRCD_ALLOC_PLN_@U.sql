CREATE OR REPLACE VIEW MST_PRCD_ALLOC_PLN_$U(
	RQMT_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	VER_NO,
	LOT_NO,
	SUBLOT_NO,
	LOC_CD,
	IO_SCHD_PR_NO,
	SCHD_ALLOC_QTY,
	GI_SCHD_DT,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ALLOC_AVL_DT,
	AVL_QTY,
	LMT_DT,
	WG_CD,
	SIM_MRP_NO,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.RQMT_NO,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.VER_NO,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.LOC_CD,
	ORG.IO_SCHD_PR_NO,
	ORG.SCHD_ALLOC_QTY,
	ORG.GI_SCHD_DT,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.ALLOC_AVL_DT,
	ORG.AVL_QTY,
	ORG.LMT_DT,
	ORG.WG_CD,
	ORG.SIM_MRP_NO,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PRCD_ALLOC_PLN_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

