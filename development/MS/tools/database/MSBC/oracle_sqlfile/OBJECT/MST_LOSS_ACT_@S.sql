CREATE OR REPLACE VIEW MST_LOSS_ACT_$S(
	LOSS_ACT_NO,
	INPT_ACT_NO,
	LOSS_RSN_CD,
	BASE_UNIT_QTY,
	CONT_QTY,
	FXD_LOSS_FLG,
	INTR_RMRKS,
	TRD_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.LOSS_ACT_NO,
	ORG.INPT_ACT_NO,
	ORG.LOSS_RSN_CD,
	ORG.BASE_UNIT_QTY,
	ORG.CONT_QTY,
	ORG.FXD_LOSS_FLG,
	ORG.INTR_RMRKS,
	ORG.TRD_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_LOSS_ACT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

