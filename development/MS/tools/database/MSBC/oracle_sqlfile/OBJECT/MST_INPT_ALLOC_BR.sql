SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_INPT_ALLOC_BR(
	BATCH_DATA_NO,
	BATCH_LOG_NO,
	LOG_SUB_KEY1,
	LOG_SUB_KEY2,
	EXE_STS_TYP,
	MFG_INST_NO,
	PAR_ITM_CD,
	PAR_ITM_SUB1,
	PAR_ITM_SUB2,
	PAR_ITM_SUB3,
	MFG_LOC_CD,
	ST_SCHD_TM,
	END_SCHD_TM,
	ALLOC_TGT_CNT,
	ALLOC_SUCCESS_CNT,
	ALLOC_FAILURE_CNT,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BATCH_DATA_NO,
	ORG.BATCH_LOG_NO,
	ORG.LOG_SUB_KEY1,
	ORG.LOG_SUB_KEY2,
	ORG.EXE_STS_TYP,
	ORG.MFG_INST_NO,
	ORG.PAR_ITM_CD,
	ORG.PAR_ITM_SUB1,
	ORG.PAR_ITM_SUB2,
	ORG.PAR_ITM_SUB3,
	ORG.MFG_LOC_CD,
	ORG.ST_SCHD_TM,
	ORG.END_SCHD_TM,
	ORG.ALLOC_TGT_CNT,
	ORG.ALLOC_SUCCESS_CNT,
	ORG.ALLOC_FAILURE_CNT,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_INPT_ALLOC_BR_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

