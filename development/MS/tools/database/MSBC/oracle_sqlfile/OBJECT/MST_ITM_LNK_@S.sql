CREATE OR REPLACE VIEW MST_ITM_LNK_$S(
	ITM_ORD_NO,
	PAR_ITM_ORD_NO,
	PAR_OPER_ORD_NO,
	SIM_MRP_NO,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	WG_CD,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_ORD_NO,
	ORG.PAR_ITM_ORD_NO,
	ORG.PAR_OPER_ORD_NO,
	ORG.SIM_MRP_NO,
	ORG.OPER_PTN,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.WG_CD,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_ITM_LNK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

