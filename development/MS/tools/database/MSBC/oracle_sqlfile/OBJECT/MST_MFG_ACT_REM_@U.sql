CREATE OR REPLACE VIEW MST_MFG_ACT_REM_$U(
	MFG_INST_NO,
	DIV_SEQ,
	MFG_STS_TYP,
	ITM_MFG_INST_NO,
	BASE_UNIT_MFG_QTY,
	BASE_UNIT_MFG_REM_QTY,
	BASE_UNIT_MFG_ABORT_QTY,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.MFG_INST_NO,
	ORG.DIV_SEQ,
	ORG.MFG_STS_TYP,
	ORG.ITM_MFG_INST_NO,
	ORG.BASE_UNIT_MFG_QTY,
	ORG.BASE_UNIT_MFG_REM_QTY,
	ORG.BASE_UNIT_MFG_ABORT_QTY,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_MFG_ACT_REM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

