SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_INPT_ALLOC_STS(
	INPT_ALLOC_STS_NO,
	INPT_SCHD_NO,
	MFG_INST_NO,
	ITM_MFG_INST_NO,
	OPER_INST_NO,
	BASE_UNIT_QTY,
	STK_ID_TYP,
	STK_BP_CD,
	STK_ARRV_BP_CD,
	TO_STK_ID_TYP,
	TO_STK_BP_CD,
	TO_STK_ARRV_BP_CD,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.INPT_ALLOC_STS_NO,
	ORG.INPT_SCHD_NO,
	ORG.MFG_INST_NO,
	ORG.ITM_MFG_INST_NO,
	ORG.OPER_INST_NO,
	ORG.BASE_UNIT_QTY,
	ORG.STK_ID_TYP,
	ORG.STK_BP_CD,
	ORG.STK_ARRV_BP_CD,
	ORG.TO_STK_ID_TYP,
	ORG.TO_STK_BP_CD,
	ORG.TO_STK_ARRV_BP_CD,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_INPT_ALLOC_STS_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

