SELECT
	T1.YIELD_ACT_NO,
	NULL AS ARR_ACT_NO,
	T1.MFG_ACT_NO,
	T1.ITM_MFG_INST_NO,
	T1.MFG_MTD_TYP,
	T1.ITM_CD,
	T1.ITM_SUB1,
	T1.ITM_SUB2,
	T1.ITM_SUB3,
	T1.TRD_UNIT_QTY,
	T1.TRD_UNIT_CD,
	T1.BASE_UNIT_QTY,
	T1.BASE_UNIT_CD,
	T1.LOT_NO,
	T1.SUBLOT_NO,
	T1.SNO1,
	T1.SNO2,
	T1.SNO3,
	T1.SNO4,
	T1.ACT_TM,
	T1.AC_DT
FROM
	MST_YIELD_ACT T1
WHERE 0=0
AND	T1.MFG_MTD_TYP = MSC_MFG_MTD_TYP.INTNL
AND	T1.YIELD_TYP IN (MAC_YIELD_TYP.GOOD, MAC_YIELD_TYP.DFCT)
UNION ALL
SELECT
	NULL AS YIELD_ACT_NO,
	T1.ARR_ACT_NO,
	T3.MFG_ACT_NO,
	T3.ITM_MFG_INST_NO,
	MSC_MFG_MTD_TYP.EXTNL,
	T1.ITM_CD,
	T1.ITM_SUB1,
	T1.ITM_SUB2,
	T1.ITM_SUB3,
	T1.TRD_UNIT_QTY,
	T1.TRD_UNIT_CD,
	T1.BASE_UNIT_QTY,
	T1.BASE_UNIT_CD,
	T1.LOT_NO,
	T1.SUBLOT_NO,
	T1.SNO1,
	T1.SNO2,
	T1.SNO3,
	T1.SNO4,
	T1.ARR_TM AS ACT_TM,
	T1.AC_DT
FROM
	MST_ARR_ACT T1
	JOIN MST_ARR_SCHD T2 ON (T1.ARR_SCHD_NO = T2.ARR_SCHD_NO)
	JOIN MST_MFG_ACT T3 ON (T2.MFG_INST_NO = T3.MFG_INST_NO)
WHERE 0=0
AND T1.CAN_FLG = '0'
/
