SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.WG_CD
	,CAST(T1.MRP_PROC_TYP AS VARCHAR2(1 CHAR)) AS MRP_PROC_TYP
	,T1.UNIT_CD
	,T1.DEC_PLACE
	,T1.SCH_FLG
	,T1.RQMT_RSTR_QTY
	,T1.SHIP_TERM_CD
	,T1.LOT_MNG_TYP
	,T1.SUBLOT_MNG_TYP
	,T1.SNO1_MNG_TYP
	,T1.SNO2_MNG_TYP
	,T1.SNO3_MNG_TYP
	,T1.SNO4_MNG_TYP
	,T2.ORDER_STOP_DT
	,T1.RELEASE_FLG
FROM MAVM_ITM_WG T1, MAM_ITM_STOP T2
WHERE 0=0
AND T1.ITM_CD = T2.ITM_CD(+)
AND T1.ITM_SUB1 = T2.ITM_SUB1(+)
AND T1.ITM_SUB2 = T2.ITM_SUB2(+)
AND T1.ITM_SUB3 = T2.ITM_SUB3(+)
AND T1.DEL_FLG = '0'
AND T2.DEL_FLG(+) = '0'
/
