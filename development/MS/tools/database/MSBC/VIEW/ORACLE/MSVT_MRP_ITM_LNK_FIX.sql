SELECT
	 T1.ITM_ORD_NO
	,T1.PAR_ITM_ORD_NO
	,T4.OPER_ORD_NO
	,T2.ITM_CD
	,T2.ITM_SUB1
	,T2.ITM_SUB2
	,T2.ITM_SUB3
	,T1.WG_CD
FROM  MST_ITM_LNK_FIX T1
	INNER JOIN MST_ITM_ORDER T2 ON (T1.ITM_ORD_NO = T2.ITM_ORD_NO AND T1.WG_CD = T2.WG_CD)
	INNER JOIN MST_ITM_ORDER T3 ON (T1.PAR_ITM_ORD_NO = T3.ITM_ORD_NO AND T1.WG_CD = T3.WG_CD)
	LEFT OUTER JOIN MST_OPER_ORDER T4 ON (T1.PAR_ITM_ORD_NO = T4.ITM_ORD_NO AND T1.OPER_PTN = T4.OPER_PTN AND T1.OPER_CD = T4.OPER_CD AND T1.OPER_SEQ = T4.OPER_SEQ AND T1.WG_CD = T4.WG_CD)
WHERE 0=0
AND T2.ITM_ORD_STS_TYP in (MSC_ITM_ORD_STS_TYP.SAV, MSC_ITM_ORD_STS_TYP.FIX, MSC_ITM_ORD_STS_TYP.PART_INST, MSC_ITM_ORD_STS_TYP.INST )
AND T3.ITM_ORD_STS_TYP in (MSC_ITM_ORD_STS_TYP.SAV, MSC_ITM_ORD_STS_TYP.FIX, MSC_ITM_ORD_STS_TYP.PART_INST, MSC_ITM_ORD_STS_TYP.INST )
/