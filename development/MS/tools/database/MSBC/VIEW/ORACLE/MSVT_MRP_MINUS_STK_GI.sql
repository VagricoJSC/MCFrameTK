SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.LOC_CD
	,SUM(-1 * T1.BASE_UNIT_QTY) AS BASE_UNIT_QTY
	,NULL AS FIRST_GR_DT
	,NULL AS LOT_SEQ
	,NULL AS AVL_SCHD_DT
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,NULL AS LMT_DT
	,T1.WG_CD
FROM
	 MSVT_AVL_IO_SCHD T1
WHERE 0=0
AND T1.IO_TYP = MSC_IO_TYP.GI
-- 以下の受払予定からオーダ生成されないようにマイナス在庫としてIFする
-- ※良品在庫かつ検収不良でない在庫を仕入返品または廃棄しようとした場合の考慮
-- 不良品の在庫はMRPにIFしていないため、出庫予定もIFしない
AND	T1.IO_SCHD_TYP IN
	(
	MSC_IO_SCHD_TYP.ARR_RTN, --入荷返品
	MSC_IO_SCHD_TYP.ARR_RTN_PROV, --入荷返品（支給）
	MSC_IO_SCHD_TYP.SCRP -- 廃棄
	)
AND T1.QUALITY_TYP = MAC_QUALITY_TYP.GOOD
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
GROUP BY
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.LOC_CD
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,T1.WG_CD
/
