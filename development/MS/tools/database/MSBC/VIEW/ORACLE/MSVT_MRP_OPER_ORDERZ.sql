SELECT
	  T1.OPER_ORD_NO
	 ,T1.OPER_ORD_STS_TYP
	 ,T1.ITM_ORD_NO
	 ,T1.LOC_CD
	 ,T1.OPER_SCHD_QTY
	 ,T1.ST_SCHD_TM
	 ,T1.END_SCHD_TM
	 ,T1.OPER_PTN
	 ,T1.OPER_CD
	 ,T1.OPER_SEQ
	 ,T1.DISP_SEQ
	 ,T1.WG_CD
FROM
	 MST_OPER_ORDER T1
	,MST_ITM_ORDER T2
WHERE 0=0
AND T1.ITM_ORD_NO = T2.ITM_ORD_NO
AND T1.ITM_ORD_STS_TYP in (MSC_ITM_ORD_STS_TYP.SAV, MSC_ITM_ORD_STS_TYP.OPN)
/
