SELECT
	 T1.ITM_ORD_NO
	,T1.IO_SCHD_NO
	,T1.IO_SCHD_TYP
	,T1.IO_SCHD_STS_TYP
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOC_CD
	,T1.BASE_UNIT_QTY
	,T1.AVL_SCHD_DT
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,T1.LMT_DT
	,T1.WG_CD
FROM
	MSVT_MRP_IO_SCHD_GR T1
UNION ALL
SELECT
	 T1.RQMT_NO AS ITM_ORD_NO
	,T1.RQMT_NO AS IO_SCHD_NO
	,NULL AS IO_SCHD_TYP
	,NULL AS IO_SCHD_STS_TYP
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,NULL AS VER_NO
	,T1.STRG_LOC_CD AS LOC_CD
	,T1.RQMT_QTY AS BASE_UNIT_QTY
	,T1.DUE_DT AS AVL_SCHD_DT
	,NULL AS LOT_NO
	,NULL AS SUBLOT_NO
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T2.GD_CD
	,NULL AS LMT_DT
	,T1.WG_CD
FROM
	MSVT_MRP_DLY_SD T1
	,(SELECT MAPA_UTIL.F_GET_DEF_GD_CD AS GD_CD FROM DUAL) T2
WHERE 0=0
AND NOT EXISTS (
	SELECT NULL
	FROM MST_ITM_ORDER TMP
	WHERE 0=0
	AND TMP.RQMT_NO = T1.RQMT_NO
)
/
