CREATE OR REPLACE PACKAGE BODY MSC_MSC_SLS_COND_TYP
/*****************************
売上条件区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION SLS_SHIP RETURN VARCHAR2 DETERMINISTIC IS -- 出荷売上
	BEGIN RETURN '0'; END SLS_SHIP;
	FUNCTION SLS_INVENTORY RETURN VARCHAR2 DETERMINISTIC IS -- 営業在庫品
	BEGIN RETURN '1'; END SLS_INVENTORY;
	FUNCTION SLS_OFFICE RETURN VARCHAR2 DETERMINISTIC IS -- 営業所等経由
	BEGIN RETURN '2'; END SLS_OFFICE;
	FUNCTION SLS_CSTN_COMP RETURN VARCHAR2 DETERMINISTIC IS -- 工事完了後
	BEGIN RETURN '3'; END SLS_CSTN_COMP;
	FUNCTION SLS_B_L RETURN VARCHAR2 DETERMINISTIC IS -- Ｂ／Ｌ入手後
	BEGIN RETURN '4'; END SLS_B_L;
	FUNCTION SLS_ORDER_RECPT RETURN VARCHAR2 DETERMINISTIC IS -- 受注同時
	BEGIN RETURN '6'; END SLS_ORDER_RECPT;
	FUNCTION SLS_SRV RETURN VARCHAR2 DETERMINISTIC IS -- 役務売上
	BEGIN RETURN '7'; END SLS_SRV;

	FUNCTION IS_SLS_SHIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出荷売上かどうか
	BEGIN
		IF I_VALUE = SLS_SHIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_SHIP;

	FUNCTION IS_SLS_INVENTORY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 営業在庫品かどうか
	BEGIN
		IF I_VALUE = SLS_INVENTORY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_INVENTORY;

	FUNCTION IS_SLS_OFFICE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 営業所等経由かどうか
	BEGIN
		IF I_VALUE = SLS_OFFICE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_OFFICE;

	FUNCTION IS_SLS_CSTN_COMP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工事完了後かどうか
	BEGIN
		IF I_VALUE = SLS_CSTN_COMP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_CSTN_COMP;

	FUNCTION IS_SLS_B_L(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Ｂ／Ｌ入手後かどうか
	BEGIN
		IF I_VALUE = SLS_B_L THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_B_L;

	FUNCTION IS_SLS_ORDER_RECPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受注同時かどうか
	BEGIN
		IF I_VALUE = SLS_ORDER_RECPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_ORDER_RECPT;

	FUNCTION IS_SLS_SRV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 役務売上かどうか
	BEGIN
		IF I_VALUE = SLS_SRV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_SRV;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SLS_SHIP
		OR I_VALUE = SLS_INVENTORY
		OR I_VALUE = SLS_OFFICE
		OR I_VALUE = SLS_CSTN_COMP
		OR I_VALUE = SLS_B_L
		OR I_VALUE = SLS_ORDER_RECPT
		OR I_VALUE = SLS_SRV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_MSC_SLS_COND_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_MSC_SLS_COND_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_MSC_SLS_COND_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_MSC_SLS_COND_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_MSC_SLS_COND_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_MSC_SLS_COND_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_MSC_SLS_COND_TYP;
