CREATE OR REPLACE PACKAGE BODY MSC_OPER_ORD_STS_TYP
/*****************************
工程オーダ状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION OPN RETURN VARCHAR2 DETERMINISTIC IS -- 未確定
	BEGIN RETURN '1'; END OPN;
	FUNCTION SAV RETURN VARCHAR2 DETERMINISTIC IS -- 保存
	BEGIN RETURN '2'; END SAV;
	FUNCTION FIX RETURN VARCHAR2 DETERMINISTIC IS -- 確定
	BEGIN RETURN '3'; END FIX;
	FUNCTION PART_INST RETURN VARCHAR2 DETERMINISTIC IS -- 一部指図済
	BEGIN RETURN '4'; END PART_INST;
	FUNCTION INST RETURN VARCHAR2 DETERMINISTIC IS -- 指図済
	BEGIN RETURN '5'; END INST;
	FUNCTION CMPL RETURN VARCHAR2 DETERMINISTIC IS -- 完了
	BEGIN RETURN '6'; END CMPL;

	FUNCTION IS_OPN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未確定かどうか
	BEGIN
		IF I_VALUE = OPN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OPN;

	FUNCTION IS_SAV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 保存かどうか
	BEGIN
		IF I_VALUE = SAV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SAV;

	FUNCTION IS_FIX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 確定かどうか
	BEGIN
		IF I_VALUE = FIX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FIX;

	FUNCTION IS_PART_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一部指図済かどうか
	BEGIN
		IF I_VALUE = PART_INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PART_INST;

	FUNCTION IS_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指図済かどうか
	BEGIN
		IF I_VALUE = INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INST;

	FUNCTION IS_CMPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 完了かどうか
	BEGIN
		IF I_VALUE = CMPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CMPL;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = OPN
		OR I_VALUE = SAV
		OR I_VALUE = FIX
		OR I_VALUE = PART_INST
		OR I_VALUE = INST
		OR I_VALUE = CMPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_OPER_ORD_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_OPER_ORD_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_OPER_ORD_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_OPER_ORD_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_OPER_ORD_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_OPER_ORD_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_OPER_ORD_STS_TYP;
