CREATE OR REPLACE PACKAGE BODY MSC_SCHD_STK_TYP
/*****************************
予定在庫区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION TGT_GR_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 引当対象入庫予定
	BEGIN RETURN '1'; END TGT_GR_SCHD;
	FUNCTION NOTGT_GR_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 引当対象外入庫予定
	BEGIN RETURN '2'; END NOTGT_GR_SCHD;
	FUNCTION LOC_GI_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 場所引当済出庫予定
	BEGIN RETURN '3'; END LOC_GI_SCHD;
	FUNCTION GRS_GI_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 総量引当済出庫予定
	BEGIN RETURN '4'; END GRS_GI_SCHD;
	FUNCTION LOC_WAIT_GI_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 場所引当保留出庫予定
	BEGIN RETURN '5'; END LOC_WAIT_GI_SCHD;
	FUNCTION GRS_WAIT_GI_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 総量引当保留出庫予定
	BEGIN RETURN '6'; END GRS_WAIT_GI_SCHD;
	FUNCTION STK RETURN VARCHAR2 DETERMINISTIC IS -- 在庫
	BEGIN RETURN '7'; END STK;
	FUNCTION MINUS_STK RETURN VARCHAR2 DETERMINISTIC IS -- マイナス在庫
	BEGIN RETURN '8'; END MINUS_STK;
	FUNCTION GR_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 入庫予定
	BEGIN RETURN 'A'; END GR_SCHD;
	FUNCTION GR_ACT RETURN VARCHAR2 DETERMINISTIC IS -- 入庫実績
	BEGIN RETURN 'B'; END GR_ACT;
	FUNCTION GI_SCHD RETURN VARCHAR2 DETERMINISTIC IS -- 出庫予定
	BEGIN RETURN 'C'; END GI_SCHD;
	FUNCTION GI_ACT RETURN VARCHAR2 DETERMINISTIC IS -- 出庫実績
	BEGIN RETURN 'D'; END GI_ACT;

	FUNCTION IS_TGT_GR_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 引当対象入庫予定かどうか
	BEGIN
		IF I_VALUE = TGT_GR_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TGT_GR_SCHD;

	FUNCTION IS_NOTGT_GR_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 引当対象外入庫予定かどうか
	BEGIN
		IF I_VALUE = NOTGT_GR_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOTGT_GR_SCHD;

	FUNCTION IS_LOC_GI_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 場所引当済出庫予定かどうか
	BEGIN
		IF I_VALUE = LOC_GI_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOC_GI_SCHD;

	FUNCTION IS_GRS_GI_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 総量引当済出庫予定かどうか
	BEGIN
		IF I_VALUE = GRS_GI_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRS_GI_SCHD;

	FUNCTION IS_LOC_WAIT_GI_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 場所引当保留出庫予定かどうか
	BEGIN
		IF I_VALUE = LOC_WAIT_GI_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOC_WAIT_GI_SCHD;

	FUNCTION IS_GRS_WAIT_GI_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 総量引当保留出庫予定かどうか
	BEGIN
		IF I_VALUE = GRS_WAIT_GI_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRS_WAIT_GI_SCHD;

	FUNCTION IS_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 在庫かどうか
	BEGIN
		IF I_VALUE = STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STK;

	FUNCTION IS_MINUS_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- マイナス在庫かどうか
	BEGIN
		IF I_VALUE = MINUS_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MINUS_STK;

	FUNCTION IS_GR_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入庫予定かどうか
	BEGIN
		IF I_VALUE = GR_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GR_SCHD;

	FUNCTION IS_GR_ACT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入庫実績かどうか
	BEGIN
		IF I_VALUE = GR_ACT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GR_ACT;

	FUNCTION IS_GI_SCHD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出庫予定かどうか
	BEGIN
		IF I_VALUE = GI_SCHD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GI_SCHD;

	FUNCTION IS_GI_ACT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出庫実績かどうか
	BEGIN
		IF I_VALUE = GI_ACT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GI_ACT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TGT_GR_SCHD
		OR I_VALUE = NOTGT_GR_SCHD
		OR I_VALUE = LOC_GI_SCHD
		OR I_VALUE = GRS_GI_SCHD
		OR I_VALUE = LOC_WAIT_GI_SCHD
		OR I_VALUE = GRS_WAIT_GI_SCHD
		OR I_VALUE = STK
		OR I_VALUE = MINUS_STK
		OR I_VALUE = GR_SCHD
		OR I_VALUE = GR_ACT
		OR I_VALUE = GI_SCHD
		OR I_VALUE = GI_ACT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION SCHD_STK_PRIO(
		I_SCHD_STK_TYP IN VARCHAR2
	)RETURN NUMBER
	 DETERMINISTIC IS
	BEGIN
		IF (I_SCHD_STK_TYP = TGT_GR_SCHD) THEN
			RETURN 1;
		ELSIF (I_SCHD_STK_TYP = NOTGT_GR_SCHD) THEN
			RETURN 2;
		ELSIF (I_SCHD_STK_TYP = LOC_GI_SCHD) THEN
			RETURN 2;
		ELSIF (I_SCHD_STK_TYP = GRS_GI_SCHD) THEN
			RETURN 3;
		ELSIF (I_SCHD_STK_TYP = LOC_WAIT_GI_SCHD) THEN
			RETURN 4;
		ELSIF (I_SCHD_STK_TYP = GRS_WAIT_GI_SCHD) THEN
			RETURN 5;
		ELSIF (I_SCHD_STK_TYP = STK) THEN
			RETURN 3;
		ELSIF (I_SCHD_STK_TYP = MINUS_STK) THEN
			RETURN 1;
		ELSIF (I_SCHD_STK_TYP = GR_SCHD) THEN
			RETURN NULL;
		ELSIF (I_SCHD_STK_TYP = GR_ACT) THEN
			RETURN NULL;
		ELSIF (I_SCHD_STK_TYP = GI_SCHD) THEN
			RETURN NULL;
		ELSIF (I_SCHD_STK_TYP = GI_ACT) THEN
			RETURN NULL;
		ELSE
			RETURN NULL;
		END IF;
	END SCHD_STK_PRIO;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_SCHD_STK_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_SCHD_STK_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_SCHD_STK_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_SCHD_STK_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_SCHD_STK_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_SCHD_STK_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_SCHD_STK_TYP;
