CREATE OR REPLACE PACKAGE BODY MSC_DMND_TYP
/*****************************
需要区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION PRE_SLO RETURN VARCHAR2 DETERMINISTIC IS -- 仮受注
	BEGIN RETURN '1'; END PRE_SLO;
	FUNCTION SLO RETURN VARCHAR2 DETERMINISTIC IS -- 本受注
	BEGIN RETURN '2'; END SLO;
	FUNCTION CST_FRCST RETURN VARCHAR2 DETERMINISTIC IS -- 顧客内示
	BEGIN RETURN '3'; END CST_FRCST;
	FUNCTION PLN_SLS RETURN VARCHAR2 DETERMINISTIC IS -- 販売計画
	BEGIN RETURN '4'; END PLN_SLS;
	FUNCTION MISC RETURN VARCHAR2 DETERMINISTIC IS -- その他
	BEGIN RETURN '5'; END MISC;

	FUNCTION IS_PRE_SLO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 仮受注かどうか
	BEGIN
		IF I_VALUE = PRE_SLO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRE_SLO;

	FUNCTION IS_SLO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 本受注かどうか
	BEGIN
		IF I_VALUE = SLO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLO;

	FUNCTION IS_CST_FRCST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 顧客内示かどうか
	BEGIN
		IF I_VALUE = CST_FRCST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CST_FRCST;

	FUNCTION IS_PLN_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 販売計画かどうか
	BEGIN
		IF I_VALUE = PLN_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PLN_SLS;

	FUNCTION IS_MISC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- その他かどうか
	BEGIN
		IF I_VALUE = MISC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MISC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = PRE_SLO
		OR I_VALUE = SLO
		OR I_VALUE = CST_FRCST
		OR I_VALUE = PLN_SLS
		OR I_VALUE = MISC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_DMND_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_DMND_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_DMND_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_DMND_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_DMND_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_DMND_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_DMND_TYP;
