CREATE OR REPLACE PACKAGE BODY MSC_BILL_CL_STS_TYP
/*****************************
請求締状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NOT_BILL RETURN VARCHAR2 DETERMINISTIC IS -- 未処理
	BEGIN RETURN '1'; END NOT_BILL;
	FUNCTION CL_SCRN RETURN VARCHAR2 DETERMINISTIC IS -- 締請求（画面）
	BEGIN RETURN '2'; END CL_SCRN;
	FUNCTION CL_BATCH RETURN VARCHAR2 DETERMINISTIC IS -- 締請求（バッチ）
	BEGIN RETURN '3'; END CL_BATCH;
	FUNCTION EACH_SLS RETURN VARCHAR2 DETERMINISTIC IS -- 売上都度請求
	BEGIN RETURN '4'; END EACH_SLS;
	FUNCTION CL_CAN RETURN VARCHAR2 DETERMINISTIC IS -- 締解除
	BEGIN RETURN '5'; END CL_CAN;

	FUNCTION IS_NOT_BILL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未処理かどうか
	BEGIN
		IF I_VALUE = NOT_BILL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_BILL;

	FUNCTION IS_CL_SCRN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 締請求（画面）かどうか
	BEGIN
		IF I_VALUE = CL_SCRN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CL_SCRN;

	FUNCTION IS_CL_BATCH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 締請求（バッチ）かどうか
	BEGIN
		IF I_VALUE = CL_BATCH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CL_BATCH;

	FUNCTION IS_EACH_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上都度請求かどうか
	BEGIN
		IF I_VALUE = EACH_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EACH_SLS;

	FUNCTION IS_CL_CAN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 締解除かどうか
	BEGIN
		IF I_VALUE = CL_CAN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CL_CAN;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NOT_BILL
		OR I_VALUE = CL_SCRN
		OR I_VALUE = CL_BATCH
		OR I_VALUE = EACH_SLS
		OR I_VALUE = CL_CAN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_BILL_CL_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_BILL_CL_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_BILL_CL_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_BILL_CL_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_BILL_CL_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_BILL_CL_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_BILL_CL_STS_TYP;
