CREATE OR REPLACE PACKAGE BODY MSC_PR_STS_TYP
/*****************************
進捗状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NOT_INST RETURN VARCHAR2 DETERMINISTIC IS -- 未指図
	BEGIN RETURN 'A1'; END NOT_INST;
	FUNCTION INST RETURN VARCHAR2 DETERMINISTIC IS -- 指図済
	BEGIN RETURN 'B1'; END INST;
	FUNCTION NOT_SHIP RETURN VARCHAR2 DETERMINISTIC IS -- 未出荷
	BEGIN RETURN 'B2'; END NOT_SHIP;
	FUNCTION PART_SHIP RETURN VARCHAR2 DETERMINISTIC IS -- 一部出荷
	BEGIN RETURN 'C1'; END PART_SHIP;
	FUNCTION SHIP RETURN VARCHAR2 DETERMINISTIC IS -- 出荷済
	BEGIN RETURN 'D1'; END SHIP;
	FUNCTION NOT_ARR RETURN VARCHAR2 DETERMINISTIC IS -- 未入荷
	BEGIN RETURN 'E1'; END NOT_ARR;
	FUNCTION PART_ARR RETURN VARCHAR2 DETERMINISTIC IS -- 一部入荷
	BEGIN RETURN 'F1'; END PART_ARR;
	FUNCTION PART_EXT_ARR RETURN VARCHAR2 DETERMINISTIC IS -- 一部着荷
	BEGIN RETURN 'F2'; END PART_EXT_ARR;
	FUNCTION ARR RETURN VARCHAR2 DETERMINISTIC IS -- 入荷済
	BEGIN RETURN 'G1'; END ARR;
	FUNCTION EXT_ARR RETURN VARCHAR2 DETERMINISTIC IS -- 着荷済
	BEGIN RETURN 'G2'; END EXT_ARR;
	FUNCTION PART_COMP RETURN VARCHAR2 DETERMINISTIC IS -- 一部完了
	BEGIN RETURN 'Z1'; END PART_COMP;
	FUNCTION COMP RETURN VARCHAR2 DETERMINISTIC IS -- 完了
	BEGIN RETURN 'Z2'; END COMP;

	FUNCTION IS_NOT_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未指図かどうか
	BEGIN
		IF I_VALUE = NOT_INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_INST;

	FUNCTION IS_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指図済かどうか
	BEGIN
		IF I_VALUE = INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INST;

	FUNCTION IS_NOT_SHIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未出荷かどうか
	BEGIN
		IF I_VALUE = NOT_SHIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_SHIP;

	FUNCTION IS_PART_SHIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一部出荷かどうか
	BEGIN
		IF I_VALUE = PART_SHIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PART_SHIP;

	FUNCTION IS_SHIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出荷済かどうか
	BEGIN
		IF I_VALUE = SHIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SHIP;

	FUNCTION IS_NOT_ARR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未入荷かどうか
	BEGIN
		IF I_VALUE = NOT_ARR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_ARR;

	FUNCTION IS_PART_ARR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一部入荷かどうか
	BEGIN
		IF I_VALUE = PART_ARR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PART_ARR;

	FUNCTION IS_PART_EXT_ARR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一部着荷かどうか
	BEGIN
		IF I_VALUE = PART_EXT_ARR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PART_EXT_ARR;

	FUNCTION IS_ARR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入荷済かどうか
	BEGIN
		IF I_VALUE = ARR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ARR;

	FUNCTION IS_EXT_ARR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 着荷済かどうか
	BEGIN
		IF I_VALUE = EXT_ARR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXT_ARR;

	FUNCTION IS_PART_COMP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一部完了かどうか
	BEGIN
		IF I_VALUE = PART_COMP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PART_COMP;

	FUNCTION IS_COMP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 完了かどうか
	BEGIN
		IF I_VALUE = COMP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_COMP;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NOT_INST
		OR I_VALUE = INST
		OR I_VALUE = NOT_SHIP
		OR I_VALUE = PART_SHIP
		OR I_VALUE = SHIP
		OR I_VALUE = NOT_ARR
		OR I_VALUE = PART_ARR
		OR I_VALUE = PART_EXT_ARR
		OR I_VALUE = ARR
		OR I_VALUE = EXT_ARR
		OR I_VALUE = PART_COMP
		OR I_VALUE = COMP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_PR_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_PR_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_PR_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_PR_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_PR_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_PR_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_PR_STS_TYP;
