CREATE OR REPLACE PACKAGE BODY MSC_STK_INSP_TYP
/*****************************
在庫検査区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION YET RETURN VARCHAR2 DETERMINISTIC IS -- 検査待
	BEGIN RETURN '1'; END YET;
	FUNCTION ING RETURN VARCHAR2 DETERMINISTIC IS -- 検査中
	BEGIN RETURN '2'; END ING;
	FUNCTION WAIT_JUDG RETURN VARCHAR2 DETERMINISTIC IS -- 判定待
	BEGIN RETURN '3'; END WAIT_JUDG;
	FUNCTION FIN RETURN VARCHAR2 DETERMINISTIC IS -- 検査済
	BEGIN RETURN '4'; END FIN;

	FUNCTION IS_YET(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 検査待かどうか
	BEGIN
		IF I_VALUE = YET THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_YET;

	FUNCTION IS_ING(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 検査中かどうか
	BEGIN
		IF I_VALUE = ING THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ING;

	FUNCTION IS_WAIT_JUDG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 判定待かどうか
	BEGIN
		IF I_VALUE = WAIT_JUDG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WAIT_JUDG;

	FUNCTION IS_FIN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 検査済かどうか
	BEGIN
		IF I_VALUE = FIN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FIN;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = YET
		OR I_VALUE = ING
		OR I_VALUE = WAIT_JUDG
		OR I_VALUE = FIN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_OTH(
		I_STK_INSP_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_STK_INSP_TYP = YET) THEN
			RETURN '0';
		ELSIF (I_STK_INSP_TYP = ING) THEN
			RETURN '0';
		ELSIF (I_STK_INSP_TYP = WAIT_JUDG) THEN
			RETURN '0';
		ELSIF (I_STK_INSP_TYP = FIN) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_OTH;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_STK_INSP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_STK_INSP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_STK_INSP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_STK_INSP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_STK_INSP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_STK_INSP_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_STK_INSP_TYP;

/
show errors;


