CREATE OR REPLACE PACKAGE BODY MSC_SIM_MRP_TYP
/*****************************
シミュレーションＭＲＰ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION GP_SIM RETURN VARCHAR2 DETERMINISTIC IS -- 汎用シミュレーション
	BEGIN RETURN '1'; END GP_SIM;
	FUNCTION MST_CHK RETURN VARCHAR2 DETERMINISTIC IS -- リリース前マスタチェック用
	BEGIN RETURN '2'; END MST_CHK;
	FUNCTION SD_ADJST RETURN VARCHAR2 DETERMINISTIC IS -- 需給調整用
	BEGIN RETURN '3'; END SD_ADJST;
	FUNCTION PRMS RETURN VARCHAR2 DETERMINISTIC IS -- 納期回答用
	BEGIN RETURN '4'; END PRMS;

	FUNCTION IS_GP_SIM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 汎用シミュレーションかどうか
	BEGIN
		IF I_VALUE = GP_SIM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GP_SIM;

	FUNCTION IS_MST_CHK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- リリース前マスタチェック用かどうか
	BEGIN
		IF I_VALUE = MST_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MST_CHK;

	FUNCTION IS_SD_ADJST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 需給調整用かどうか
	BEGIN
		IF I_VALUE = SD_ADJST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SD_ADJST;

	FUNCTION IS_PRMS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 納期回答用かどうか
	BEGIN
		IF I_VALUE = PRMS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRMS;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = GP_SIM
		OR I_VALUE = MST_CHK
		OR I_VALUE = SD_ADJST
		OR I_VALUE = PRMS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_SIM_MRP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_SIM_MRP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_SIM_MRP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_SIM_MRP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_SIM_MRP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_SIM_MRP_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_SIM_MRP_TYP;

/
show errors;


