CREATE OR REPLACE PACKAGE BODY MSC_MRP_DATA_TYP
/*****************************
ＭＲＰ用データ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ORDZ RETURN VARCHAR2 DETERMINISTIC IS -- オーダ残
	BEGIN RETURN '1'; END ORDZ;
	FUNCTION SCHDI RETURN VARCHAR2 DETERMINISTIC IS -- 入庫予定
	BEGIN RETURN '2'; END SCHDI;
	FUNCTION SCHDO RETURN VARCHAR2 DETERMINISTIC IS -- 出庫予定
	BEGIN RETURN '3'; END SCHDO;
	FUNCTION STK RETURN VARCHAR2 DETERMINISTIC IS -- 在庫
	BEGIN RETURN '4'; END STK;
	FUNCTION KORDZ RETURN VARCHAR2 DETERMINISTIC IS -- 工程オーダ残
	BEGIN RETURN '5'; END KORDZ;

	FUNCTION IS_ORDZ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- オーダ残かどうか
	BEGIN
		IF I_VALUE = ORDZ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ORDZ;

	FUNCTION IS_SCHDI(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入庫予定かどうか
	BEGIN
		IF I_VALUE = SCHDI THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SCHDI;

	FUNCTION IS_SCHDO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出庫予定かどうか
	BEGIN
		IF I_VALUE = SCHDO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SCHDO;

	FUNCTION IS_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 在庫かどうか
	BEGIN
		IF I_VALUE = STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STK;

	FUNCTION IS_KORDZ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工程オーダ残かどうか
	BEGIN
		IF I_VALUE = KORDZ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_KORDZ;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ORDZ
		OR I_VALUE = SCHDI
		OR I_VALUE = SCHDO
		OR I_VALUE = STK
		OR I_VALUE = KORDZ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_MRP_DATA_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_MRP_DATA_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_MRP_DATA_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_MRP_DATA_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_MRP_DATA_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_MRP_DATA_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_MRP_DATA_TYP;

/
show errors;


