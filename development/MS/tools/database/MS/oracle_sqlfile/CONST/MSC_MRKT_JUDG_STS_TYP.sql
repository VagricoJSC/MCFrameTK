CREATE OR REPLACE PACKAGE BODY MSC_MRKT_JUDG_STS_TYP
/*****************************
市場出荷判定状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION OPN RETURN VARCHAR2 DETERMINISTIC IS -- 未判定
	BEGIN RETURN '1'; END OPN;
	FUNCTION ACPT RETURN VARCHAR2 DETERMINISTIC IS -- 出荷許可
	BEGIN RETURN '9'; END ACPT;
	FUNCTION NOT_ACPT RETURN VARCHAR2 DETERMINISTIC IS -- 出荷禁止
	BEGIN RETURN 'C'; END NOT_ACPT;

	FUNCTION IS_OPN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未判定かどうか
	BEGIN
		IF I_VALUE = OPN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OPN;

	FUNCTION IS_ACPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出荷許可かどうか
	BEGIN
		IF I_VALUE = ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACPT;

	FUNCTION IS_NOT_ACPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出荷禁止かどうか
	BEGIN
		IF I_VALUE = NOT_ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_ACPT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = OPN
		OR I_VALUE = ACPT
		OR I_VALUE = NOT_ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_MRKT_JUDG_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_MRKT_JUDG_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_MRKT_JUDG_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_MRKT_JUDG_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_MRKT_JUDG_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_MRKT_JUDG_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
