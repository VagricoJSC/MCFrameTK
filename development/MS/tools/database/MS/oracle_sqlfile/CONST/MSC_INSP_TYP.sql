CREATE OR REPLACE PACKAGE BODY MSC_INSP_TYP
/*****************************
検査種類区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION PRDCT RETURN VARCHAR2 DETERMINISTIC IS -- 製造検査
	BEGIN RETURN '1'; END PRDCT;
	FUNCTION ACCPT RETURN VARCHAR2 DETERMINISTIC IS -- 受入検査
	BEGIN RETURN '2'; END ACCPT;
	FUNCTION LOT RETURN VARCHAR2 DETERMINISTIC IS -- ロット検査
	BEGIN RETURN '3'; END LOT;
	FUNCTION PRCD RETURN VARCHAR2 DETERMINISTIC IS -- 先行検査
	BEGIN RETURN '4'; END PRCD;

	FUNCTION IS_PRDCT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製造検査かどうか
	BEGIN
		IF I_VALUE = PRDCT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRDCT;

	FUNCTION IS_ACCPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受入検査かどうか
	BEGIN
		IF I_VALUE = ACCPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACCPT;

	FUNCTION IS_LOT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ロット検査かどうか
	BEGIN
		IF I_VALUE = LOT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOT;

	FUNCTION IS_PRCD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 先行検査かどうか
	BEGIN
		IF I_VALUE = PRCD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRCD;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = PRDCT
		OR I_VALUE = ACCPT
		OR I_VALUE = LOT
		OR I_VALUE = PRCD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_BI_TGT(
		I_INSP_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_INSP_TYP = PRDCT) THEN
			RETURN '0';
		ELSIF (I_INSP_TYP = ACCPT) THEN
			RETURN '1';
		ELSIF (I_INSP_TYP = LOT) THEN
			RETURN '0';
		ELSIF (I_INSP_TYP = PRCD) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_BI_TGT;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_INSP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_INSP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_INSP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_INSP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_INSP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_INSP_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_INSP_TYP;

/
show errors;


