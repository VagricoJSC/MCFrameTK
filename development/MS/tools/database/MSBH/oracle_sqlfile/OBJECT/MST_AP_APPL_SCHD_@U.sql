CREATE OR REPLACE VIEW MST_AP_APPL_SCHD_$U(
	AP_APPL_SCHD_NO,
	PAY_SCHD_NO,
	PURC_ACT_NO,
	RCPT_IV_MNG_NO,
	RCPT_IV_NO,
	TRD_CUR_AMT,
	TRD_CUR_COM_PAID_TAX_AMT,
	TRD_CUR_EXC_COM_PAID,
	TRD_CUR_APPL_AMT,
	PAY_STS_TYP,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.AP_APPL_SCHD_NO,
	ORG.PAY_SCHD_NO,
	ORG.PURC_ACT_NO,
	ORG.RCPT_IV_MNG_NO,
	ORG.RCPT_IV_NO,
	ORG.TRD_CUR_AMT,
	ORG.TRD_CUR_COM_PAID_TAX_AMT,
	ORG.TRD_CUR_EXC_COM_PAID,
	ORG.TRD_CUR_APPL_AMT,
	ORG.PAY_STS_TYP,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_AP_APPL_SCHD_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

