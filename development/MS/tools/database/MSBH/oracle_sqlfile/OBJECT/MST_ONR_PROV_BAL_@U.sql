CREATE OR REPLACE VIEW MST_ONR_PROV_BAL_$U(
	ASPPL_CD,
	AP_DPT_CD,
	AC_YM,
	TRD_CUR_CD,
	INIT_BAL,
	ONR_PROV_AMT,
	ONR_PROV_RET_AMT,
	SETOFF_AMT,
	TAX_AMT,
	END_BAL,
	BASE_CUR_CD,
	BASE_CUR_INIT_BAL,
	BASE_CUR_ONR_PROV_AMT,
	BASE_CUR_ONR_PROV_RET_AMT,
	BASE_CUR_SETOFF_AMT,
	BASE_CUR_TAX_AMT,
	BASE_CUR_END_BAL,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ASPPL_CD,
	ORG.AP_DPT_CD,
	ORG.AC_YM,
	ORG.TRD_CUR_CD,
	ORG.INIT_BAL,
	ORG.ONR_PROV_AMT,
	ORG.ONR_PROV_RET_AMT,
	ORG.SETOFF_AMT,
	ORG.TAX_AMT,
	ORG.END_BAL,
	ORG.BASE_CUR_CD,
	ORG.BASE_CUR_INIT_BAL,
	ORG.BASE_CUR_ONR_PROV_AMT,
	ORG.BASE_CUR_ONR_PROV_RET_AMT,
	ORG.BASE_CUR_SETOFF_AMT,
	ORG.BASE_CUR_TAX_AMT,
	ORG.BASE_CUR_END_BAL,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_ONR_PROV_BAL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

