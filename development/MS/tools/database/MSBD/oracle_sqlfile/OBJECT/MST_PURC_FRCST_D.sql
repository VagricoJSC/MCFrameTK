CREATE OR REPLACE VIEW MST_PURC_FRCST_D(
	PURC_FRCST_D_NO,
	PURC_FRCST_NO,
	PURC_FRCST_FIX_NO,
	PF_PERIOD_TYP,
	PF_PERIOD_ST_DT,
	PF_PERIOD_END_DT,
	FIX_PERIOD_FLG,
	TRD_UNIT_PF_QTY,
	BASE_UNIT_PF_QTY,
	TRD_UNIT_SCHD_QTY,
	BASE_UNIT_SCHD_QTY,
	TRD_UNIT_PRMS_QTY,
	BASE_UNIT_PRMS_QTY,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PURC_FRCST_D_NO,
	ORG.PURC_FRCST_NO,
	ORG.PURC_FRCST_FIX_NO,
	ORG.PF_PERIOD_TYP,
	ORG.PF_PERIOD_ST_DT,
	ORG.PF_PERIOD_END_DT,
	ORG.FIX_PERIOD_FLG,
	ORG.TRD_UNIT_PF_QTY,
	ORG.BASE_UNIT_PF_QTY,
	ORG.TRD_UNIT_SCHD_QTY,
	ORG.BASE_UNIT_SCHD_QTY,
	ORG.TRD_UNIT_PRMS_QTY,
	ORG.BASE_UNIT_PRMS_QTY,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PURC_FRCST_D_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

