CREATE OR REPLACE VIEW MSVT_PO_REG_BR(
	BATCH_DATA_NO,
	BATCH_LOG_NO,
	LOG_SUB_KEY1,
	LOG_SUB_KEY2,
	EXE_STS_TYP,
	PO_SCHD_NO,
	WG_CD,
	SPPL_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_NM,
	PO_SCHD_DT,
	DLV_RQST_TM,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT
	T1.BATCH_DATA_NO,
	T1.BATCH_LOG_NO,
	T1.LOG_SUB_KEY1,
	T1.LOG_SUB_KEY2,
	T1.EXE_STS_TYP,
	T1.PO_SCHD_NO,
	T1.WG_CD,
	T1.SPPL_CD,
	T1.ITM_CD,
	T1.ITM_SUB1,
	T1.ITM_SUB2,
	T1.ITM_SUB3,
	NVL(T1.ITM_NM, M1.ITM_NM),
	T1.PO_SCHD_DT,
	T1.DLV_RQST_TM,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO
FROM
	MST_PO_REG_BR T1
	LEFT OUTER JOIN MAM_ITM M1 ON
		(T1.ITM_CD = M1.ITM_CD AND
		T1.ITM_SUB1 = M1.ITM_SUB1 AND
		T1.ITM_SUB2 = M1.ITM_SUB2 AND
		T1.ITM_SUB3 = M1.ITM_SUB3)
WHERE
	0 = 0
;

