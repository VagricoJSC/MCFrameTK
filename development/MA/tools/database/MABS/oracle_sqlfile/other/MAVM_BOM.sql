SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_BOM(
	BOM_KEY,
	WG_CD,
	PAR_ITM_CD,
	PAR_ITM_SUB1,
	PAR_ITM_SUB2,
	PAR_ITM_SUB3,
	BOM_PTN,
	OPER_CD,
	OPER_SEQ,
	CHD_ITM_CD,
	CHD_ITM_SUB1,
	CHD_ITM_SUB2,
	CHD_ITM_SUB3,
	VER_NO,
	PH_FLG,
	PH_BOM_PTN,
	ALT_ITM_FLG,
	ALT_GRP_CD,
	ALT_ITM_TYP,
	ALT_ITM_RATIO,
	ALT_ALLOC_PRIO,
	SNO_TYP1,
	SNO_TYP2,
	SNO_TYP3,
	SNO_TYP4,
	MIN_SNO1,
	MAX_SNO1,
	MIN_SNO2,
	MAX_SNO2,
	MIN_SNO3,
	MAX_SNO3,
	MIN_SNO4,
	MAX_SNO4,
	PAR_INST_QTY,
	CHD_INPT_QTY,
	CHD_RQMT_QTY,
	CHD_INPT_RATIO,
	CHD_RQMT_RATIO,
	FXD_CHD_RQMT_QTY,
	BYPROD_FLG,
	IN_OFFST_TYP,
	IN_OFFST,
	BKF_TYP,
	INST_LOT_FIX_FLG,
	LOT_MIX_FLG,
	SUBLOT_MIX_FLG,
	ALLOC_CTL_TYP,
	MAIN_ITM_FLG,
	YIELD_CALC_FLG,
	INPT_CTL_TYP,
	DISP_SEQ,
	CHNG_NO,
	EXT_SYS_NO_BOM,
	NOT_COST_FLG,
	ST_DT,
	END_DT,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	BOM_ROWNUM
)
AS
SELECT
	M1.BOM_KEY,
	M1.WG_CD,
	M1.PAR_ITM_CD,
	M1.PAR_ITM_SUB1,
	M1.PAR_ITM_SUB2,
	M1.PAR_ITM_SUB3,
	M1.BOM_PTN,
	M1.OPER_CD,
	M1.OPER_SEQ,
	DECODE(M3.ALT_GRP_CD, NULL, M1.CHD_ITM_CD, M3.CHD_ITM_CD) 	CHD_ITM_CD,
	DECODE(M3.ALT_GRP_CD, NULL, M1.CHD_ITM_SUB1, M3.CHD_ITM_SUB1)	CHD_ITM_SUB1,
	DECODE(M3.ALT_GRP_CD, NULL, M1.CHD_ITM_SUB2, M3.CHD_ITM_SUB2)	CHD_ITM_SUB2,
	DECODE(M3.ALT_GRP_CD, NULL, M1.CHD_ITM_SUB3, M3.CHD_ITM_SUB3)	CHD_ITM_SUB3,
	DECODE(M3.ALT_GRP_CD, NULL, M1.VER_NO, M3.VER_NO)		VER_NO,
	M1.PH_FLG,
	M1.PH_BOM_PTN,
	M1.ALT_ITM_FLG,
	M1.ALT_GRP_CD,
	DECODE(M2.ALT_GRP_CD, NULL, M1.ALT_ITM_TYP, M2.ALT_ITM_TYP) 		ALT_ITM_TYP,
	DECODE(M3.ALT_GRP_CD, NULL, M1.ALT_ITM_RATIO, M3.ALT_ITM_RATIO)		ALT_ITM_RATIO,
	DECODE(M3.ALT_GRP_CD, NULL, M1.ALT_ALLOC_PRIO, M3.ALT_ALLOC_PRIO) 	ALT_ALLOC_PRIO,
	DECODE(M4.SNO1_MNG_TYP, 
			MAC_SNO_MNG_TYP.NOT_MNG, MAC_SNO_TYP.NO_EXTND, 
			MAC_SNO_MNG_TYP.MNG_REQ, MAC_SNO_TYP.EXTND, 
			MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_SNO_TYP.EXTND_NULL, 
			M1.SNO_TYP1)	SNO_TYP1,
	DECODE(M4.SNO2_MNG_TYP, 
			MAC_SNO_MNG_TYP.NOT_MNG, MAC_SNO_TYP.NO_EXTND, 
			MAC_SNO_MNG_TYP.MNG_REQ, MAC_SNO_TYP.EXTND, 
			MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_SNO_TYP.EXTND_NULL, 
			M1.SNO_TYP2)	SNO_TYP2,
	DECODE(M4.SNO3_MNG_TYP, 
			MAC_SNO_MNG_TYP.NOT_MNG, MAC_SNO_TYP.NO_EXTND, 
			MAC_SNO_MNG_TYP.MNG_REQ, MAC_SNO_TYP.EXTND, 
			MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_SNO_TYP.EXTND_NULL, 
			M1.SNO_TYP3)	SNO_TYP3,
	DECODE(M4.SNO4_MNG_TYP, 
			MAC_SNO_MNG_TYP.NOT_MNG, MAC_SNO_TYP.NO_EXTND, 
			MAC_SNO_MNG_TYP.MNG_REQ, MAC_SNO_TYP.EXTND, 
			MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_SNO_TYP.EXTND_NULL, 
			M1.SNO_TYP4)	SNO_TYP4,
	M1.MIN_SNO1,
	M1.MAX_SNO1,
	M1.MIN_SNO2,
	M1.MAX_SNO2,
	M1.MIN_SNO3,
	M1.MAX_SNO3,
	M1.MIN_SNO4,
	M1.MAX_SNO4,
	M1.PAR_INST_QTY,
	DECODE(M3.ALT_GRP_CD, NULL, M1.CHD_INPT_QTY, M1.CHD_INPT_QTY * M3.CHD_INPT_RATIO)	CHD_INPT_QTY,
	DECODE(M3.ALT_GRP_CD, NULL, M1.CHD_RQMT_QTY, M1.CHD_RQMT_QTY * M3.CHD_RQMT_RATIO)	CHD_RQMT_QTY,
	M3.CHD_INPT_RATIO,
	M3.CHD_RQMT_RATIO,
	DECODE(
		DECODE(M2.ALT_GRP_CD, NULL, M1.ALT_ITM_TYP, M2.ALT_ITM_TYP), 
			MAC_ALT_ITM_TYP.MIX, 0, -- 代替混在可の場合は常に0,
			DECODE(M3.ALT_GRP_CD, NULL, M1.FXD_CHD_RQMT_QTY, M1.FXD_CHD_RQMT_QTY + M3.FXD_CHD_RQMT_QTY)
		)	FXD_CHD_RQMT_QTY,
	M1.BYPROD_FLG,
	M1.IN_OFFST_TYP,
	M1.IN_OFFST,
	M1.BKF_TYP,
	M1.INST_LOT_FIX_FLG,
	DECODE(M4.LOT_MNG_TYP, 
			NULL, M1.LOT_MIX_FLG,
			MAC_LOT_MNG_TYP.NOT_MNG, '0',
			DECODE(M2.ALT_ITM_TYP, MAC_ALT_ITM_TYP.MIX, '1', M1.LOT_MIX_FLG)
			)	LOT_MIX_FLG,
	DECODE(M4.SUBLOT_MNG_TYP, 
			NULL, M1.SUBLOT_MIX_FLG, 
			MAC_SUBLOT_MNG_TYP.NOT_MNG, '0',
			DECODE(M2.ALT_ITM_TYP, MAC_ALT_ITM_TYP.MIX, '1', M1.SUBLOT_MIX_FLG)
			)	SUBLOT_MIX_FLG,
	M1.ALLOC_CTL_TYP,
	M1.MAIN_ITM_FLG,
	M1.YIELD_CALC_FLG,
	M1.INPT_CTL_TYP,
	M1.DISP_SEQ,
	M1.CHNG_NO,
	M1.EXT_SYS_NO_BOM,
	DECODE(M3.ALT_GRP_CD, NULL, M1.NOT_COST_FLG, M3.NOT_COST_FLG)	NOT_COST_FLG,
	GREATEST(M1.ST_DT, NVL(M3.ST_DT, M1.ST_DT))	ST_DT,
	LEAST(M1.END_DT, NVL(M3.END_DT, M1.END_DT))	END_DT,
	M1.MEMO1,
	M1.MEMO2,
	M1.MEMO3,
	M1.DEL_FLG,
	M1.BOM_ROWNUM
FROM
	(SELECT M1.*, ROW_NUMBER() OVER (order by null) AS BOM_ROWNUM  FROM MAM_BOM M1 WHERE M1.DEL_FLG = '0') M1
	LEFT OUTER JOIN MAM_ALT_GRP_ M2 ON (M1.ALT_ITM_FLG = '1' AND M1.ALT_GRP_CD = M2.ALT_GRP_CD AND M1.WG_CD = M2.WG_CD AND M2.DEL_FLG = '0')
	LEFT OUTER JOIN MAM_ALT_ITM M3 ON (M1.ALT_ITM_FLG = '1' AND M1.ALT_GRP_CD = M3.ALT_GRP_CD AND M1.WG_CD = M3.WG_CD AND M3.DEL_FLG = '0')
	LEFT OUTER JOIN MAM_ITM_COM M4 ON
		(0=0
		AND	M3.CHD_ITM_CD = M4.ITM_CD 
		AND	M3.CHD_ITM_SUB1 = M4.ITM_SUB1
		AND	M3.CHD_ITM_SUB2 = M4.ITM_SUB2
		AND	M3.CHD_ITM_SUB3 = M4.ITM_SUB3
		AND	M4.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
		AND	M4.DEL_FLG = '0'
		)
WHERE	0=0
AND	GREATEST(M1.ST_DT, NVL(M3.ST_DT, M1.ST_DT)) <= LEAST(M1.END_DT, NVL(M3.END_DT, M1.END_DT))
AND NOT (M1.ALT_ITM_FLG = '1' AND (M2.ALT_GRP_CD IS NULL OR M3.ALT_GRP_CD IS NULL))
;

