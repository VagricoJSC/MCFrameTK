	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ROWIDTOCHAR(ORG.ROWID)	ROW_ID,
	ORG.WG_CD	ORG_WG_CD
FROM 
	MAM_CST_SLS_UPRI_ALL ORG
WHERE 
	0 = 0
AND ORG.DEL_FLG = '0'
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD <> MAC_STR.NULL_VAL
UNION ALL
SELECT 
	ORG.CST_CD,
	ORG.DLV_CD,
	ORG.DEST_CD1,
	ORG.DEST_CD2,
	ORG.DEST_CD3,
	ORG.SLS_UPRI_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.UNIT_CD,
	ORG.LOT_QTY,
	ORG.CUR_CD,
	WG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.UPRI,
	ORG.UPRI_BF,
	ORG.INTERIM_FLG,
	ORG.UPRI_RATE,
	ORG.UPRI_RATE_BF,
	ORG.SUB_UPRI1,
	ORG.SUB_UPRI2,
	ORG.SUB_UPRI3,
	ORG.NOT_COST_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ROWIDTOCHAR(ORG.ROWID)	ROW_ID,
	ORG.WG_CD	ORG_WG_CD
FROM 
	MAM_WG WG,
	MAM_CST_SLS_UPRI_ALL ORG
WHERE 
	0 = 0
AND ORG.DEL_FLG = '0'
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD = MAC_STR.NULL_VAL
	AND WG.SLS_FLG = '1'
	AND NOT EXISTS (
		SELECT	'X'
		FROM	MAM_CST_SLS_UPRI_ALL x
		WHERE	0=0
		AND	x.CO_CD = ORG.CO_CD
		AND	x.CST_CD = ORG.CST_CD
		AND	x.SLS_UPRI_GRP_CD = ORG.SLS_UPRI_GRP_CD
		AND	x.ITM_CD = ORG.ITM_CD
		AND	x.ITM_SUB1 = ORG.ITM_SUB1
		AND	x.ITM_SUB2 = ORG.ITM_SUB2
		AND	x.ITM_SUB3 = ORG.ITM_SUB3
		AND	x.WG_CD = WG.WG_CD
		AND 	x.DEL_FLG = '0'
		)

/
show errors;


