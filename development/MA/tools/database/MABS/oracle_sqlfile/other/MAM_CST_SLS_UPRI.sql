	ORG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.UPRI,
	ORG.UPRI_BF,
	ORG.INTERIM_FLG,
	ORG.UPRI_RATE,
	ORG.UPRI_RATE_BF,
	ORG.SUB_UPRI1,
	ORG.SUB_UPRI2,
	ORG.SUB_UPRI3,
