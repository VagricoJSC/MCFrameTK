CREATE OR REPLACE VIEW MAM_PROV_UPRI(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	PRSPPL_CD,
	CUR_CD,
	WG_CD,
	ST_DT,
	END_DT,
	PROV_TYP,
	UPRI,
	UPRI_BF,
	SUB_UPRI1,
	SUB_UPRI2,
	SUB_UPRI3,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	ROW_ID,
	ORG_WG_CD
	)
AS
SELECT 
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.PRSPPL_CD,
	ORG.CUR_CD,
	ORG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.PROV_TYP,
	ORG.UPRI,
	ORG.UPRI_BF,
	ORG.SUB_UPRI1,
	ORG.SUB_UPRI2,
	ORG.SUB_UPRI3,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ROWIDTOCHAR(ORG.ROWID)	ROW_ID,
	ORG.WG_CD	ORG_WG_CD
FROM 
	MAM_PROV_UPRI_ALL ORG
WHERE 
	0 = 0
AND ORG.DEL_FLG = '0'
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD <> MAC_STR.NULL_VAL
UNION ALL
SELECT 
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.PRSPPL_CD,
	ORG.CUR_CD,
	WG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.PROV_TYP,
	ORG.UPRI,
	ORG.UPRI_BF,
	ORG.SUB_UPRI1,
	ORG.SUB_UPRI2,
	ORG.SUB_UPRI3,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ROWIDTOCHAR(ORG.ROWID)	ROW_ID,
	ORG.WG_CD	ORG_WG_CD
FROM 
	MAM_WG WG,
	MAM_PROV_UPRI_ALL ORG
WHERE 
	0 = 0
AND ORG.DEL_FLG = '0'
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD = MAC_STR.NULL_VAL
	AND (WG.LG_FLG = '1' OR WG.MFG_FLG = '1')
	AND NOT EXISTS (
		SELECT	'X'
		FROM	MAM_PROV_UPRI_ALL x
		WHERE	0=0
		AND	x.CO_CD = ORG.CO_CD
		AND	x.ITM_CD = ORG.ITM_CD
		AND	x.ITM_SUB1 = ORG.ITM_SUB1
		AND	x.ITM_SUB2 = ORG.ITM_SUB2
		AND	x.ITM_SUB3 = ORG.ITM_SUB3
		AND	x.WG_CD = WG.WG_CD
		AND 	x.DEL_FLG = '0'
		)

/
show errors;


