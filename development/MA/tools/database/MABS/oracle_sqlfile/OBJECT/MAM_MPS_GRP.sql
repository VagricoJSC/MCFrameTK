CREATE OR REPLACE VIEW MAM_MPS_GRP(
	MPS_GRP_CD,
	MPS_GRP_NM,
	BASE_MPS_GRP_NM,
	RQMT_MONS,
	PRCD_MONS,
	DATE_DIV_MONS,
	WEEK_DIV_MONS,
	PERIOD_DIV_MONS,
	DATE_DIV_TYP,
	MON01_PROD_QTY,
	MON02_PROD_QTY,
	MON03_PROD_QTY,
	MON04_PROD_QTY,
	MON05_PROD_QTY,
	MON06_PROD_QTY,
	MON07_PROD_QTY,
	MON08_PROD_QTY,
	MON09_PROD_QTY,
	MON10_PROD_QTY,
	MON11_PROD_QTY,
	MON12_PROD_QTY,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.MPS_GRP_CD,
	LCL.MPS_GRP_NM,
	ORG.MPS_GRP_NM AS BASE_MPS_GRP_NM,
	ORG.RQMT_MONS,
	ORG.PRCD_MONS,
	ORG.DATE_DIV_MONS,
	ORG.WEEK_DIV_MONS,
	ORG.PERIOD_DIV_MONS,
	ORG.DATE_DIV_TYP,
	ORG.MON01_PROD_QTY,
	ORG.MON02_PROD_QTY,
	ORG.MON03_PROD_QTY,
	ORG.MON04_PROD_QTY,
	ORG.MON05_PROD_QTY,
	ORG.MON06_PROD_QTY,
	ORG.MON07_PROD_QTY,
	ORG.MON08_PROD_QTY,
	ORG.MON09_PROD_QTY,
	ORG.MON10_PROD_QTY,
	ORG.MON11_PROD_QTY,
	ORG.MON12_PROD_QTY,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_MPS_GRP_ALL ORG,
	mam_mps_grp_lcl_all LCL
WHERE
	0 = 0
	AND ORG.MPS_GRP_CD = LCL.MPS_GRP_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_mps_grp'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

