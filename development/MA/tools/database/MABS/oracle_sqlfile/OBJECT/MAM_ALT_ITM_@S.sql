CREATE OR REPLACE VIEW MAM_ALT_ITM_$S(
	ALT_GRP_CD,
	CHD_ITM_CD,
	CHD_ITM_SUB1,
	CHD_ITM_SUB2,
	CHD_ITM_SUB3,
	VER_NO,
	WG_CD,
	ST_DT,
	END_DT,
	CHD_INPT_RATIO,
	CHD_RQMT_RATIO,
	FXD_CHD_RQMT_QTY,
	ALT_ITM_RATIO,
	ALT_ALLOC_PRIO,
	NOT_COST_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ALT_GRP_CD,
	ORG.CHD_ITM_CD,
	ORG.CHD_ITM_SUB1,
	ORG.CHD_ITM_SUB2,
	ORG.CHD_ITM_SUB3,
	ORG.VER_NO,
	ORG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.CHD_INPT_RATIO,
	ORG.CHD_RQMT_RATIO,
	ORG.FXD_CHD_RQMT_QTY,
	ORG.ALT_ITM_RATIO,
	ORG.ALT_ALLOC_PRIO,
	ORG.NOT_COST_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ALT_ITM_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_alt_itm'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

