CREATE OR REPLACE VIEW MAM_ITEM_SHIP_COMP_$S(
	PROD_ITM_CD,
	PROD_ITM_SUB1,
	PROD_ITM_SUB2,
	PROD_ITM_SUB3,
	SURV_LINE_QTY,
	DIAMETER,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	QTY,
	SPEC_CD,
	DISP_SEQ,
	BODY_FLG,
	COMP_FLG,
	SHIP_PRNT_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PROD_ITM_CD,
	ORG.PROD_ITM_SUB1,
	ORG.PROD_ITM_SUB2,
	ORG.PROD_ITM_SUB3,
	ORG.SURV_LINE_QTY,
	ORG.DIAMETER,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.QTY,
	ORG.SPEC_CD,
	ORG.DISP_SEQ,
	ORG.BODY_FLG,
	ORG.COMP_FLG,
	ORG.SHIP_PRNT_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ITEM_SHIP_COMP_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_item_ship_comp'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

