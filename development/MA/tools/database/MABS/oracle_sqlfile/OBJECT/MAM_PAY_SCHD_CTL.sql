SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_PAY_SCHD_CTL(
	BSPPL_CD,
	CUR_CD,
	MIN_AMT,
	STTL_CD,
	WG_CD,
	RATE,
	CRRYOVR_MONS_TYP,
	PAY_DAY1,
	PAY_DAY2,
	PAY_DAY3,
	PAY_DAY4,
	PAY_DAY5,
	PAY_CRRYOVR_MONS1,
	PAY_CRRYOVR_MONS2,
	PAY_CRRYOVR_MONS3,
	PAY_CRRYOVR_MONS4,
	PAY_CRRYOVR_MONS5,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BSPPL_CD,
	ORG.CUR_CD,
	ORG.MIN_AMT,
	ORG.STTL_CD,
	ORG.WG_CD,
	ORG.RATE,
	ORG.CRRYOVR_MONS_TYP,
	ORG.PAY_DAY1,
	ORG.PAY_DAY2,
	ORG.PAY_DAY3,
	ORG.PAY_DAY4,
	ORG.PAY_DAY5,
	ORG.PAY_CRRYOVR_MONS1,
	ORG.PAY_CRRYOVR_MONS2,
	ORG.PAY_CRRYOVR_MONS3,
	ORG.PAY_CRRYOVR_MONS4,
	ORG.PAY_CRRYOVR_MONS5,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_PAY_SCHD_CTL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_pay_schd_ctl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

