SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_FB_IF_CTL(
	IF_PROC_TYP,
	BP_CD,
	BP_CD_NULL_FLG,
	AR_STTL_TYP,
	BANK_CD,
	BANK_AC_CD,
	ST_DT,
	END_DT,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.IF_PROC_TYP,
	ORG.BP_CD,
	ORG.BP_CD_NULL_FLG,
	ORG.AR_STTL_TYP,
	ORG.BANK_CD,
	ORG.BANK_AC_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_FB_IF_CTL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_fb_if_ctl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

