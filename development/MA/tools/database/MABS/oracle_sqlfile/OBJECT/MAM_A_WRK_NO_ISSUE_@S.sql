CREATE OR REPLACE VIEW MAM_A_WRK_NO_ISSUE_$S(
	ISSUE_TYP,
	DEPT_CD,
	PROD_CD,
	YM,
	OPE_TYP,
	WRK_SEQ,
	WRK_SUB_SEQ,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ISSUE_TYP,
	ORG.DEPT_CD,
	ORG.PROD_CD,
	ORG.YM,
	ORG.OPE_TYP,
	ORG.WRK_SEQ,
	ORG.WRK_SUB_SEQ,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_A_WRK_NO_ISSUE_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

