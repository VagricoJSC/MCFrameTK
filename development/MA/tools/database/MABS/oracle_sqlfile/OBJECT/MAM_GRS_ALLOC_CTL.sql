SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_GRS_ALLOC_CTL(
	ALLOC_GRP_CD,
	ITM_SHIP_GRP_CD,
	LG_GRP_CD,
	LOC_CD,
	ALLOC_SCOPE_TYP,
	PRIO,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ALLOC_GRP_CD,
	ORG.ITM_SHIP_GRP_CD,
	ORG.LG_GRP_CD,
	ORG.LOC_CD,
	ORG.ALLOC_SCOPE_TYP,
	ORG.PRIO,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_GRS_ALLOC_CTL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_grs_alloc_ctl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

