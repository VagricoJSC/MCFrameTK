CREATE OR REPLACE VIEW MAM_ITM_WG(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	WG_CD,
	MFG_INST_UNIT_TYP,
	MRP_PROC_TYP,
	RQMT_TYP,
	PROD_PLN_TYP,
	DMND_DATE_DIV_MONS,
	ALLOC_MARGIN_DAYS,
	MRP_ALLOC_MARGIN_DAYS,
	MRP_OPN_XFR_DAYS,
	RQMT_RSTR_QTY,
	INPT_ITM_ADD_TYP,
	INPT_ITM_DEL_TYP,
	SCH_TGT_TYP,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	TRACE_TGT_TYP,
	UNIT_EXP_FLG
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.WG_CD,
	ORG.MFG_INST_UNIT_TYP,
	ORG.MRP_PROC_TYP,
	ORG.RQMT_TYP,
	ORG.PROD_PLN_TYP,
	ORG.DMND_DATE_DIV_MONS,
	ORG.ALLOC_MARGIN_DAYS,
	ORG.MRP_ALLOC_MARGIN_DAYS,
	ORG.MRP_OPN_XFR_DAYS,
	ORG.RQMT_RSTR_QTY,
	ORG.INPT_ITM_ADD_TYP,
	ORG.INPT_ITM_DEL_TYP,
	ORG.SCH_TGT_TYP,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ORG.TRACE_TGT_TYP,
	ORG.UNIT_EXP_FLG
FROM
	MAM_ITM_WG_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_itm_wg'))
	AND (1=MAPA_CONTEXT.F_ITM_WG) --MAVM_ITM_WGを使用する
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

