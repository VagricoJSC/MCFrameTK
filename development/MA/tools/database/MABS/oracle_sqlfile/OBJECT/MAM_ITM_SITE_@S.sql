CREATE OR REPLACE VIEW MAM_ITM_SITE_$S(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SITE_CD,
	NTFY_NM,
	PLNT_APRV_FLG,
	PLNT_APRV_ROLE_CD,
	INSP_APRV_FLG,
	INSP_APRV_ROLE_CD,
	MFG_APRV_FLG,
	MFG_APRV_ROLE_CD,
	XFR_LOT_FLG,
	SO_PRMT_INSP_FLG,
	IN_PRMT_INSP_FLG,
	NUM_ID,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.SITE_CD,
	ORG.NTFY_NM,
	ORG.PLNT_APRV_FLG,
	ORG.PLNT_APRV_ROLE_CD,
	ORG.INSP_APRV_FLG,
	ORG.INSP_APRV_ROLE_CD,
	ORG.MFG_APRV_FLG,
	ORG.MFG_APRV_ROLE_CD,
	ORG.XFR_LOT_FLG,
	ORG.SO_PRMT_INSP_FLG,
	ORG.IN_PRMT_INSP_FLG,
	ORG.NUM_ID,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ITM_SITE_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_itm_site'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

