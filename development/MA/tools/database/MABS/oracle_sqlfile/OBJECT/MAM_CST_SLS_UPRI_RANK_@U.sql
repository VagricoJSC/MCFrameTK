CREATE OR REPLACE VIEW MAM_CST_SLS_UPRI_RANK_$U(
	CST_CD,
	DLV_CD,
	DEST_CD1,
	DEST_CD2,
	DEST_CD3,
	ST_DT,
	END_DT,
	SLS_UPRI_RANK_CD,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CST_CD,
	ORG.DLV_CD,
	ORG.DEST_CD1,
	ORG.DEST_CD2,
	ORG.DEST_CD3,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.SLS_UPRI_RANK_CD,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_CST_SLS_UPRI_RANK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

