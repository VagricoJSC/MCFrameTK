CREATE OR REPLACE VIEW MAVM_RD_ALLOC_GRP(
	ALLOC_GRP_CD,
	ALLOC_GRP_NM,
	BASE_ALLOC_GRP_NM,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT	m.*
FROM	MAT_DA_ALLOC_GRP t , MAM_ALLOC_GRP m
WHERE	0 = 0
AND	t.ALLOC_GRP_CD = m.ALLOC_GRP_CD
AND	t.RD_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.*
FROM	MAM_ALLOC_GRP m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	w.FULL_DA_FLG = '1'
;

