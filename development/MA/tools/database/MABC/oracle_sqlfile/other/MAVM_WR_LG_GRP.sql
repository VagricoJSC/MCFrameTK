CREATE OR REPLACE VIEW MAVM_WR_LG_GRP(
	LG_GRP_CD,
	LG_GRP_NM,
	BASE_LG_GRP_NM,
	LOC_FLG,
	WG_CD,
	SHIP_SLIP_FLG,
	PICK_LIST_FLG,
	SHIP_INST_FLG,
	SHIP_SLIP_ACT_FLG,
	CAL_CD,
	SITE_CO_CD,
	GI_MINUS_STK_CHK_FLG,
	SHIP_LOC_PRIO_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT	m.*
FROM	MAT_DA_LG_GRP t , MAM_LG_GRP m
WHERE	0 = 0
AND	t.LG_GRP_CD = m.LG_GRP_CD
AND	t.WR_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.*
FROM	MAM_LG_GRP m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	w.FULL_DA_FLG = '1'
;

