SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_AREA_MST(
	AREA_CD,
	AREA_NM,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	AREA_NM_LCL1,
	AREA_NM_LCL2,
	AREA_NM_LCL3,
	AREA_NM_LCL4,
	AREA_NM_LCL5
)
AS
SELECT
	T1.AREA_CD,
	T1.AREA_NM,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--地域名（ロケール１）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_ALL T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND	T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	AREA_NM_LCL1,
	--地域名（ロケール２）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_ALL T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND	T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	AREA_NM_LCL2,
	--地域名（ロケール３）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_ALL T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND	T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	AREA_NM_LCL3,
	--地域名（ロケール４）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_ALL T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND	T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	AREA_NM_LCL4,
	--地域名（ロケール５）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_ALL T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND	T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	AREA_NM_LCL5
	FROM MAM_AREA_ALL T1
	WHERE 0=0
	AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_AREA
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_AREA
			)
		)
	)
UNION ALL
SELECT
	T1.AREA_CD,
	T1.AREA_NM,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	MAC_STR.NULL_VAL CO_CD,
	--地域名（ロケール１）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_CMN T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND T.LCL_CD = 'ja_JP'
	)	AREA_NM_LCL1,
	--地域名（ロケール２）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_CMN T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND T.LCL_CD = 'en_US'
	)	AREA_NM_LCL2,
	--地域名（ロケール３）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_CMN T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND T.LCL_CD = 'TBD3'
	)	AREA_NM_LCL3,
	--地域名（ロケール４）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_CMN T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND T.LCL_CD = 'TBD4'
	)	AREA_NM_LCL4,
	--地域名（ロケール５）
	(SELECT T.AREA_NM
		FROM MAM_AREA_LCL_CMN T
		WHERE 0 = 0
		AND T.AREA_CD = T1.AREA_CD
		AND T.LCL_CD = 'TBD5'
	)	AREA_NM_LCL5
	FROM MAM_AREA_CMN T1
	WHERE 0=0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_AREA
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

