CREATE OR REPLACE VIEW MAM_CAL_$U(
	CAL_CD,
	ST_DT,
	END_DT,
	SUN_OFF_FLG,
	MON_OFF_FLG,
	TUE_OFF_FLG,
	WED_OFF_FLG,
	THU_OFF_FLG,
	FRI_OFF_FLG,
	SAT_OFF_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CAL_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.SUN_OFF_FLG,
	ORG.MON_OFF_FLG,
	ORG.TUE_OFF_FLG,
	ORG.WED_OFF_FLG,
	ORG.THU_OFF_FLG,
	ORG.FRI_OFF_FLG,
	ORG.SAT_OFF_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_CAL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

