CREATE OR REPLACE VIEW MAM_PO_PRINT_$U(
	PO_PRINT_CD,
	PO_PRINT_NM,
	TXT_NEW_OFF,
	TXT_MOD_OFF,
	TXT_DEL_OFF,
	TXT_NEW_ON,
	TXT_MOD_ON,
	TXT_DEL_ON,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PO_PRINT_CD,
	ORG.PO_PRINT_NM,
	ORG.TXT_NEW_OFF,
	ORG.TXT_MOD_OFF,
	ORG.TXT_DEL_OFF,
	ORG.TXT_NEW_ON,
	ORG.TXT_MOD_ON,
	ORG.TXT_DEL_ON,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_PO_PRINT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

