SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_SPLN_ITM(
	SPLN_ITM_CD,
	SPLN_ITM_NM,
	BASE_SPLN_ITM_NM,
	SPLN_SET_TYP,
	ITM_GRP_CD1,
	ITM_GRP_CD2,
	ITM_GRP_CD3,
	ITM_GRP_CD4,
	ITM_GRP_CD5,
	ITM_GRP_CD6,
	ITM_GRP_CD7,
	ITM_GRP_CD8,
	ITM_GRP_CD9,
	ITM_GRP_CD10,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SPLN_ITM_CD,
	LCL.SPLN_ITM_NM,
	ORG.SPLN_ITM_NM AS BASE_SPLN_ITM_NM,
	ORG.SPLN_SET_TYP,
	ORG.ITM_GRP_CD1,
	ORG.ITM_GRP_CD2,
	ORG.ITM_GRP_CD3,
	ORG.ITM_GRP_CD4,
	ORG.ITM_GRP_CD5,
	ORG.ITM_GRP_CD6,
	ORG.ITM_GRP_CD7,
	ORG.ITM_GRP_CD8,
	ORG.ITM_GRP_CD9,
	ORG.ITM_GRP_CD10,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SPLN_ITM_ALL ORG,
	mam_spln_itm_lcl_all LCL
WHERE
	0 = 0
	AND ORG.SPLN_ITM_CD = LCL.SPLN_ITM_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_spln_itm'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

