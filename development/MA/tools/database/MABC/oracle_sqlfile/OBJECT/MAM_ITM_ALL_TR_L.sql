SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_ITM_ALL_TR_L
AFTER INSERT OR UPDATE ON MAM_ITM_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
	SME BOOLEAN;
BEGIN
	IF (:OLD.ITM_NM IS NOT NULL AND :NEW.ITM_NM IS NOT NULL) THEN
		SME := (:OLD.ITM_NM = :NEW.ITM_NM);
	ELSE
		SME := (:OLD.ITM_NM IS NULL AND :NEW.ITM_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ITM_ALT_NM1 IS NOT NULL AND :NEW.ITM_ALT_NM1 IS NOT NULL) THEN
		SME := (:OLD.ITM_ALT_NM1 = :NEW.ITM_ALT_NM1);
	ELSE
		SME := (:OLD.ITM_ALT_NM1 IS NULL AND :NEW.ITM_ALT_NM1 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ITM_ALT_NM2 IS NOT NULL AND :NEW.ITM_ALT_NM2 IS NOT NULL) THEN
		SME := (:OLD.ITM_ALT_NM2 = :NEW.ITM_ALT_NM2);
	ELSE
		SME := (:OLD.ITM_ALT_NM2 IS NULL AND :NEW.ITM_ALT_NM2 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ITM_ALT_NM3 IS NOT NULL AND :NEW.ITM_ALT_NM3 IS NOT NULL) THEN
		SME := (:OLD.ITM_ALT_NM3 = :NEW.ITM_ALT_NM3);
	ELSE
		SME := (:OLD.ITM_ALT_NM3 IS NULL AND :NEW.ITM_ALT_NM3 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ITM_ALT_NM4 IS NOT NULL AND :NEW.ITM_ALT_NM4 IS NOT NULL) THEN
		SME := (:OLD.ITM_ALT_NM4 = :NEW.ITM_ALT_NM4);
	ELSE
		SME := (:OLD.ITM_ALT_NM4 IS NULL AND :NEW.ITM_ALT_NM4 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	<<MDIFF>>
	IF INSERTING OR (UPDATING AND NOT SME) THEN
	MERGE INTO MAM_ITM_LCL_ALL LCL
		USING  DUAL
		ON (0=0
			AND LCL.LCL_CD = FCPA_CONTEXT.F_GET_DEF_LOCALE_CD
			AND LCL.ITM_CD = :NEW.ITM_CD
			AND LCL.ITM_SUB1 = :NEW.ITM_SUB1
			AND LCL.ITM_SUB2 = :NEW.ITM_SUB2
			AND LCL.ITM_SUB3 = :NEW.ITM_SUB3
			AND LCL.CO_CD = :NEW.CO_CD
		)
		WHEN MATCHED THEN
			UPDATE
			SET
				LCL.ITM_NM=:NEW.ITM_NM,
				LCL.ITM_ALT_NM1=:NEW.ITM_ALT_NM1,
				LCL.ITM_ALT_NM2=:NEW.ITM_ALT_NM2,
				LCL.ITM_ALT_NM3=:NEW.ITM_ALT_NM3,
				LCL.ITM_ALT_NM4=:NEW.ITM_ALT_NM4,
				LCL.INS_USR_ID=:NEW.INS_USR_ID,
				LCL.INS_USR_NM=:NEW.INS_USR_NM,
				LCL.INS_FUNC_ID=:NEW.INS_FUNC_ID,
				LCL.UPD_USR_ID=:NEW.UPD_USR_ID,
				LCL.UPD_USR_NM=:NEW.UPD_USR_NM,
				LCL.UPD_FUNC_ID=:NEW.UPD_FUNC_ID,
				LCL.UPD_SRV_REQ_NO=:NEW.UPD_SRV_REQ_NO
		WHEN NOT MATCHED THEN
			INSERT(
				LCL_CD,
				ITM_CD,
				ITM_SUB1,
				ITM_SUB2,
				ITM_SUB3,
				ITM_NM,
				ITM_ALT_NM1,
				ITM_ALT_NM2,
				ITM_ALT_NM3,
				ITM_ALT_NM4,
				CO_CD,
				INS_USR_ID,
				INS_USR_NM,
				INS_FUNC_ID,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)VALUES(
				FCPA_CONTEXT.F_GET_DEF_LOCALE_CD,
				:NEW.ITM_CD,
				:NEW.ITM_SUB1,
				:NEW.ITM_SUB2,
				:NEW.ITM_SUB3,
				:NEW.ITM_NM,
				:NEW.ITM_ALT_NM1,
				:NEW.ITM_ALT_NM2,
				:NEW.ITM_ALT_NM3,
				:NEW.ITM_ALT_NM4,
				:NEW.CO_CD,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
			)
		;
	END IF;
END;

