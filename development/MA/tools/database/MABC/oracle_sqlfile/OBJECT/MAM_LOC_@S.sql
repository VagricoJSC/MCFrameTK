	LOC_CD,
	LOC_NM,
	BASE_LOC_NM,
	ASST_DPT_CD,
	SLS_DPT_CD,
	WG_CD,
	SITE_CD,
	LG_GRP_CD,
	LG_DEF_FLG,
	LOC_GRP_CD,
	ALLOC_GRP_CD,
	SPPL_CD,
	MAKER_CD,
	PRE_OUTSRC_ACT_FLG,
	DDLV_PROV_INSP_FLG,
	CAL_CD,
	LOC_MNG_TYP,
	PRNT_LCL_CD,
	CNTRY_CD,
	NUM_ID,
	STKTK_TGT_FLG,
	STKTK_TOR_DISP_FLG,
	STKTK_TOR_EX_ZERO_FLG,
	STKTK_ACT_EX_ZERO_FLG,
	STKTK_AMT_FLG,
	STR_LN_TGT_FLG,
	ALLOC_LMT_FLG,
	GI_PACK_XFER_FLG,
	GI_VMI_FLG,
	RSRC_CD1,
	RSRC_CD2,
	EXT_SYS_LOC_TYP,
	LOC_ALC_GRP,
	ADDR_FLG,
	ZIP_CD,
	BASE_ZIP_CD,
	ADDR1,
	BASE_ADDR1,
	ADDR2,
	BASE_ADDR2,
	ADDR3,
	BASE_ADDR3,
	ADDR4,
	BASE_ADDR4,
	TEL,
	BASE_TEL,
	FAX,
	BASE_FAX,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.LOC_CD,
	LCL.LOC_NM,
	ORG.LOC_NM AS BASE_LOC_NM,
	ORG.ASST_DPT_CD,
	ORG.SLS_DPT_CD,
	ORG.WG_CD,
	ORG.SITE_CD,
	ORG.LG_GRP_CD,
	ORG.LG_DEF_FLG,
	ORG.LOC_GRP_CD,
	ORG.ALLOC_GRP_CD,
	ORG.SPPL_CD,
	ORG.MAKER_CD,
	ORG.PRE_OUTSRC_ACT_FLG,
	ORG.DDLV_PROV_INSP_FLG,
	ORG.CAL_CD,
	ORG.LOC_MNG_TYP,
	ORG.PRNT_LCL_CD,
	ORG.CNTRY_CD,
	ORG.NUM_ID,
	ORG.STKTK_TGT_FLG,
	ORG.STKTK_TOR_DISP_FLG,
	ORG.STKTK_TOR_EX_ZERO_FLG,
	ORG.STKTK_ACT_EX_ZERO_FLG,
	ORG.STKTK_AMT_FLG,
	ORG.STR_LN_TGT_FLG,
	ORG.ALLOC_LMT_FLG,
	ORG.GI_PACK_XFER_FLG,
	ORG.GI_VMI_FLG,
	ORG.RSRC_CD1,
	ORG.RSRC_CD2,
	ORG.EXT_SYS_LOC_TYP,
	ORG.LOC_ALC_GRP,
	ORG.ADDR_FLG,
	LCL.ZIP_CD,
	ORG.ZIP_CD AS BASE_ZIP_CD,
	LCL.ADDR1,
	ORG.ADDR1 AS BASE_ADDR1,
	LCL.ADDR2,
	ORG.ADDR2 AS BASE_ADDR2,
	LCL.ADDR3,
	ORG.ADDR3 AS BASE_ADDR3,
	LCL.ADDR4,
	ORG.ADDR4 AS BASE_ADDR4,
	LCL.TEL,
	ORG.TEL AS BASE_TEL,
	LCL.FAX,
	ORG.FAX AS BASE_FAX,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_LOC_ALL ORG,
	mam_loc_lcl_all LCL
WHERE
	0 = 0
	AND ORG.LOC_CD = LCL.LOC_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_loc'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

