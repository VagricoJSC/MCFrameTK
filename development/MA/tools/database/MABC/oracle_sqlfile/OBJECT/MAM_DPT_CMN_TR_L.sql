SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_DPT_CMN_TR_L
AFTER INSERT OR UPDATE ON MAM_DPT_CMN
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
	SME BOOLEAN;
BEGIN
	IF (:OLD.END_DT IS NOT NULL AND :NEW.END_DT IS NOT NULL) THEN
		SME := (:OLD.END_DT = :NEW.END_DT);
	ELSE
		SME := (:OLD.END_DT IS NULL AND :NEW.END_DT IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.DPT_NM IS NOT NULL AND :NEW.DPT_NM IS NOT NULL) THEN
		SME := (:OLD.DPT_NM = :NEW.DPT_NM);
	ELSE
		SME := (:OLD.DPT_NM IS NULL AND :NEW.DPT_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ZIP_CD IS NOT NULL AND :NEW.ZIP_CD IS NOT NULL) THEN
		SME := (:OLD.ZIP_CD = :NEW.ZIP_CD);
	ELSE
		SME := (:OLD.ZIP_CD IS NULL AND :NEW.ZIP_CD IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ADDR1 IS NOT NULL AND :NEW.ADDR1 IS NOT NULL) THEN
		SME := (:OLD.ADDR1 = :NEW.ADDR1);
	ELSE
		SME := (:OLD.ADDR1 IS NULL AND :NEW.ADDR1 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ADDR2 IS NOT NULL AND :NEW.ADDR2 IS NOT NULL) THEN
		SME := (:OLD.ADDR2 = :NEW.ADDR2);
	ELSE
		SME := (:OLD.ADDR2 IS NULL AND :NEW.ADDR2 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ADDR3 IS NOT NULL AND :NEW.ADDR3 IS NOT NULL) THEN
		SME := (:OLD.ADDR3 = :NEW.ADDR3);
	ELSE
		SME := (:OLD.ADDR3 IS NULL AND :NEW.ADDR3 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.ADDR4 IS NOT NULL AND :NEW.ADDR4 IS NOT NULL) THEN
		SME := (:OLD.ADDR4 = :NEW.ADDR4);
	ELSE
		SME := (:OLD.ADDR4 IS NULL AND :NEW.ADDR4 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.TEL IS NOT NULL AND :NEW.TEL IS NOT NULL) THEN
		SME := (:OLD.TEL = :NEW.TEL);
	ELSE
		SME := (:OLD.TEL IS NULL AND :NEW.TEL IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.FAX IS NOT NULL AND :NEW.FAX IS NOT NULL) THEN
		SME := (:OLD.FAX = :NEW.FAX);
	ELSE
		SME := (:OLD.FAX IS NULL AND :NEW.FAX IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	<<MDIFF>>
	IF INSERTING OR (UPDATING AND NOT SME) THEN
	MERGE INTO MAM_DPT_LCL_CMN LCL
		USING  DUAL
		ON (0=0
			AND LCL.LCL_CD = FCPA_CONTEXT.F_GET_DEF_LOCALE_CD
			AND LCL.DPT_CD = :NEW.DPT_CD
			AND LCL.ST_DT = :NEW.ST_DT
		)
		WHEN MATCHED THEN
			UPDATE
			SET
				LCL.END_DT=:NEW.END_DT,
				LCL.DPT_NM=:NEW.DPT_NM,
				LCL.ZIP_CD=:NEW.ZIP_CD,
				LCL.ADDR1=:NEW.ADDR1,
				LCL.ADDR2=:NEW.ADDR2,
				LCL.ADDR3=:NEW.ADDR3,
				LCL.ADDR4=:NEW.ADDR4,
				LCL.TEL=:NEW.TEL,
				LCL.FAX=:NEW.FAX,
				LCL.INS_USR_ID=:NEW.INS_USR_ID,
				LCL.INS_USR_NM=:NEW.INS_USR_NM,
				LCL.INS_FUNC_ID=:NEW.INS_FUNC_ID,
				LCL.UPD_USR_ID=:NEW.UPD_USR_ID,
				LCL.UPD_USR_NM=:NEW.UPD_USR_NM,
				LCL.UPD_FUNC_ID=:NEW.UPD_FUNC_ID,
				LCL.UPD_SRV_REQ_NO=:NEW.UPD_SRV_REQ_NO
		WHEN NOT MATCHED THEN
			INSERT(
				LCL_CD,
				DPT_CD,
				ST_DT,
				END_DT,
				DPT_NM,
				ZIP_CD,
				ADDR1,
				ADDR2,
				ADDR3,
				ADDR4,
				TEL,
				FAX,
				INS_USR_ID,
				INS_USR_NM,
				INS_FUNC_ID,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)VALUES(
				FCPA_CONTEXT.F_GET_DEF_LOCALE_CD,
				:NEW.DPT_CD,
				:NEW.ST_DT,
				:NEW.END_DT,
				:NEW.DPT_NM,
				:NEW.ZIP_CD,
				:NEW.ADDR1,
				:NEW.ADDR2,
				:NEW.ADDR3,
				:NEW.ADDR4,
				:NEW.TEL,
				:NEW.FAX,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
			)
		;
	END IF;
END;

/
show errors;


