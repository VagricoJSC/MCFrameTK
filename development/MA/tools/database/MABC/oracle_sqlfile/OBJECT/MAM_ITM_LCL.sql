CREATE OR REPLACE VIEW MAM_ITM_LCL(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_NM,
	ITM_ALT_NM1,
	ITM_ALT_NM2,
	ITM_ALT_NM3,
	ITM_ALT_NM4,
	MEMO1,
	MEMO2,
	MEMO3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	LCL_CD
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_NM,
	ORG.ITM_ALT_NM1,
	ORG.ITM_ALT_NM2,
	ORG.ITM_ALT_NM3,
	ORG.ITM_ALT_NM4,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ORG.LCL_CD
FROM
	MAM_ITM_LCL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

