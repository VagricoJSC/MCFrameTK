SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_EXT_SYS(
	EXT_SYS_CD,
	EXT_SYS_NM,
	BASE_EXT_SYS_NM,
	EXT_SYS_TYP,
	WEB_API_FLG,
	CMD_EXEC_FLG,
	REAL_IMP_FLG,
	NOT_SEND_UPD_FLG,
	NOT_DUP_IMP_FLG,
	IF_UPD_TYP,
	DLV_SLIP_SPLIT_FLG,
	NULL_VAL_IF_FLG,
	UPRI_NOT_CHK_FLG,
	AMT_NOT_CHK_FLG,
	TAX_NOT_CHK_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.EXT_SYS_CD,
	LCL.EXT_SYS_NM,
	ORG.EXT_SYS_NM AS BASE_EXT_SYS_NM,
	ORG.EXT_SYS_TYP,
	ORG.WEB_API_FLG,
	ORG.CMD_EXEC_FLG,
	ORG.REAL_IMP_FLG,
	ORG.NOT_SEND_UPD_FLG,
	ORG.NOT_DUP_IMP_FLG,
	ORG.IF_UPD_TYP,
	ORG.DLV_SLIP_SPLIT_FLG,
	ORG.NULL_VAL_IF_FLG,
	ORG.UPRI_NOT_CHK_FLG,
	ORG.AMT_NOT_CHK_FLG,
	ORG.TAX_NOT_CHK_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_EXT_SYS_ALL ORG,
	mam_ext_sys_lcl_all LCL
WHERE
	0 = 0
	AND ORG.EXT_SYS_CD = LCL.EXT_SYS_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_ext_sys'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

