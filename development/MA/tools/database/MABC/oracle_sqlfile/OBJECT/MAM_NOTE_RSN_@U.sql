CREATE OR REPLACE VIEW MAM_NOTE_RSN_$U(
	NOTE_RSN_CD,
	NOTE_RSN_NM,
	DPT_ID_FLG,
	SLIP_CNT_ID,
	AC_CD,
	SUB_AC_CD,
	ABS_B_TYP,
	ABSTRACT2,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.NOTE_RSN_CD,
	ORG.NOTE_RSN_NM,
	ORG.DPT_ID_FLG,
	ORG.SLIP_CNT_ID,
	ORG.AC_CD,
	ORG.SUB_AC_CD,
	ORG.ABS_B_TYP,
	ORG.ABSTRACT2,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_NOTE_RSN_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

