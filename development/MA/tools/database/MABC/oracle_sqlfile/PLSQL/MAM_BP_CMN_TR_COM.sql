SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_BP_CMN_TR_COM
BEFORE INSERT OR DELETE OR UPDATE
ON MAM_BP_CMN
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
BEGIN
	IF INSERTING AND :NEW.ALL_COM_FLG = '0' THEN
		MERGE INTO MAM_BP_COM m
		USING (
			SELECT	:NEW.BP_CD BP_CD
			FROM	DUAL
			) x
		ON	(x.BP_CD = m.BP_CD)
		WHEN MATCHED THEN
			UPDATE	SET m.EX_FLG = '0'
		WHEN NOT MATCHED THEN
			INSERT (BP_CD, EX_FLG) VALUES (x.BP_CD, '0')
		;
	ELSIF DELETING THEN
		DELETE MAM_BP_COM_ALL WHERE BP_CD = :OLD.BP_CD ;
	END IF ;
END ;

/
show errors;


