SELECT
	T1.SITE_CD,
	T1.SITE_NM,
	T1.ARR_FLG,
	T1.ZIP_CD,
	T1.ADDR1,
	T1.ADDR2,
	T1.ADDR3,
	T1.ADDR4,
	T1.TEL,
	T1.FAX,
	T1.DEF_LOC_GRP_CD,
	T1.DEF_ALLOC_GRP_CD,
	T1.DEF_LG_GRP_CD,
	T1.DEF_CAL_CD,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--工場・物流倉庫名（ロケール１）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_ALL T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	SITE_NM_LCL1,
	--工場・物流倉庫名（ロケール２）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_ALL T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	SITE_NM_LCL2,
	--工場・物流倉庫名（ロケール３）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_ALL T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	SITE_NM_LCL3,
	--工場・物流倉庫名（ロケール４）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_ALL T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	SITE_NM_LCL4,
	--工場・物流倉庫名（ロケール５）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_ALL T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	SITE_NM_LCL5
	FROM MAM_SITE_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_SITE
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_SITE
			)
		)
	)
UNION ALL
SELECT
	T1.SITE_CD,
	T1.SITE_NM,
	T1.ARR_FLG,
	T1.ZIP_CD,
	T1.ADDR1,
	T1.ADDR2,
	T1.ADDR3,
	T1.ADDR4,
	T1.TEL,
	T1.FAX,
	T1.DEF_LOC_GRP_CD,
	T1.DEF_ALLOC_GRP_CD,
	T1.DEF_LG_GRP_CD,
	T1.DEF_CAL_CD,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	MAC_STR.NULL_VAL CO_CD,
	--工場・物流倉庫名（ロケール１）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_CMN T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.LCL_CD = 'ja_JP'
	)	SITE_NM_LCL1,
	--工場・物流倉庫名（ロケール２）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_CMN T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.LCL_CD = 'en_US'
	)	SITE_NM_LCL2,
	--工場・物流倉庫名（ロケール３）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_CMN T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.LCL_CD = 'TBD3'
	)	SITE_NM_LCL3,
	--工場・物流倉庫名（ロケール４）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_CMN T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.LCL_CD = 'TBD4'
	)	SITE_NM_LCL4,
	--工場・物流倉庫名（ロケール５）
	(SELECT T.SITE_NM
		FROM MAM_SITE_LCL_CMN T
		WHERE 0 = 0
		AND T.SITE_CD = T1.SITE_CD
		AND T.LCL_CD = 'TBD5'
	)	SITE_NM_LCL5
	FROM MAM_SITE_CMN T1
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_SITE
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
