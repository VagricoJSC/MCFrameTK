SELECT
	T1.LOC_GRP_CD,
	T1.LOC_GRP_NM,
	T1.WG_CD,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--製造場所グループ名（ロケール１）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	LOC_GRP_NM_LCL1,
	--製造場所グループ名（ロケール２）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	LOC_GRP_NM_LCL2,
	--製造場所グループ名（ロケール３）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	LOC_GRP_NM_LCL3,
	--製造場所グループ名（ロケール４）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	LOC_GRP_NM_LCL4,
	--製造場所グループ名（ロケール５）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	LOC_GRP_NM_LCL5
	FROM MAM_LOC_GRP_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_LOC_GRP
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_LOC_GRP
			)
		)
	)
UNION ALL
SELECT
	T1.LOC_GRP_CD,
	T1.LOC_GRP_NM,
	T1.WG_CD,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	MAC_STR.NULL_VAL CO_CD,
	--製造場所グループ名（ロケール１）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.LCL_CD = 'ja_JP'
	)	LOC_GRP_NM_LCL1,
	--製造場所グループ名（ロケール２）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.LCL_CD = 'en_US'
	)	LOC_GRP_NM_LCL2,
	--製造場所グループ名（ロケール３）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.LCL_CD = 'TBD3'
	)	LOC_GRP_NM_LCL3,
	--製造場所グループ名（ロケール４）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.LCL_CD = 'TBD4'
	)	LOC_GRP_NM_LCL4,
	--製造場所グループ名（ロケール５）
	(SELECT T.LOC_GRP_NM
		FROM MAM_LOC_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_GRP_CD = T1.LOC_GRP_CD
		AND T.LCL_CD = 'TBD5'
	)	LOC_GRP_NM_LCL5
	FROM MAM_LOC_GRP_CMN T1
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_LOC_GRP
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
