SELECT
	T1.CUR_CD,
	T1.CUR_NM,
	T1.AMT_DEC_PLACE,
	T1.UPRI_DEC_PLACE,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--通貨名（ロケール１）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_ALL T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	CUR_NM_LCL1,
	--通貨名（ロケール２）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_ALL T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	CUR_NM_LCL2,
	--通貨名（ロケール３）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_ALL T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	CUR_NM_LCL3,
	--通貨名（ロケール４）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_ALL T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	CUR_NM_LCL4,
	--通貨名（ロケール５）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_ALL T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	CUR_NM_LCL5
	FROM MAM_CUR_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_CUR
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_CUR
			)
		)
	)
UNION ALL
SELECT
	T1.CUR_CD,
	T1.CUR_NM,
	T1.AMT_DEC_PLACE,
	T1.UPRI_DEC_PLACE,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--通貨名（ロケール１）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_CMN T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.LCL_CD = 'ja_JP'
	)	CUR_NM_LCL1,
	--通貨名（ロケール２）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_CMN T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.LCL_CD = 'en_US'
	)	CUR_NM_LCL2,
	--通貨名（ロケール３）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_CMN T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.LCL_CD = 'TBD3'
	)	CUR_NM_LCL3,
	--通貨名（ロケール４）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_CMN T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.LCL_CD = 'TBD4'
	)	CUR_NM_LCL4,
	--通貨名（ロケール５）
	(SELECT T.CUR_NM
		FROM MAM_CUR_LCL_CMN T
		WHERE 0 = 0
		AND T.CUR_CD = T1.CUR_CD
		AND T.LCL_CD = 'TBD5'
	)	CUR_NM_LCL5
	FROM MAM_CUR_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_CUR
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
/
