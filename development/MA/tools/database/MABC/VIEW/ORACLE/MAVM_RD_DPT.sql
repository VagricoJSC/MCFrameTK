SELECT	t.DPT_CD
FROM	MAT_DA_DPT t
WHERE	0 = 0
AND	t.RD_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.DPT_CD
FROM	MAM_DPT m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	m.ST_DT <= FCPA_DATE_UTIL.F_GET_TODAY
AND	m.END_DT >= FCPA_DATE_UTIL.F_GET_TODAY
AND	w.FULL_DA_FLG = '1'
/
