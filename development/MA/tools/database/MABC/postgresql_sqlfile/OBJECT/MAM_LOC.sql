CREATE OR REPLACE VIEW mam_loc(
	loc_cd,
	loc_nm,
	base_loc_nm,
	asst_dpt_cd,
	sls_dpt_cd,
	wg_cd,
	site_cd,
	lg_grp_cd,
	lg_def_flg,
	loc_grp_cd,
	alloc_grp_cd,
	sppl_cd,
	maker_cd,
	pre_outsrc_act_flg,
	ddlv_prov_insp_flg,
	cal_cd,
	loc_mng_typ,
	prnt_lcl_cd,
	cntry_cd,
	num_id,
	stktk_tgt_flg,
	stktk_tor_disp_flg,
	stktk_tor_ex_zero_flg,
	stktk_act_ex_zero_flg,
	stktk_amt_flg,
	str_ln_tgt_flg,
	alloc_lmt_flg,
	gi_pack_xfer_flg,
	gi_vmi_flg,
	rsrc_cd1,
	rsrc_cd2,
	ext_sys_loc_typ,
	loc_alc_grp,
	addr_flg,
	zip_cd,
	base_zip_cd,
	addr1,
	base_addr1,
	addr2,
	base_addr2,
	addr3,
	base_addr3,
	addr4,
	base_addr4,
	tel,
	base_tel,
	fax,
	base_fax,
	memo1,
	memo2,
	memo3,
	del_flg,
	del_usr_id,
	del_usr_nm,
	del_ts,
	ins_usr_id,
	ins_usr_nm,
	ins_ts,
	ins_func_id,
	upd_cntr,
	upd_usr_id,
	upd_usr_nm,
	upd_ts,
	upd_func_id,
	upd_srv_req_no
	)
AS
SELECT
	mam_loc_mam_loc_all_org.loc_cd,
	mam_loc_mam_loc_lcl_all_lcl.loc_nm,
	mam_loc_mam_loc_all_org.loc_nm AS base_loc_nm,
	mam_loc_mam_loc_all_org.asst_dpt_cd,
	mam_loc_mam_loc_all_org.sls_dpt_cd,
	mam_loc_mam_loc_all_org.wg_cd,
	mam_loc_mam_loc_all_org.site_cd,
	mam_loc_mam_loc_all_org.lg_grp_cd,
	mam_loc_mam_loc_all_org.lg_def_flg,
	mam_loc_mam_loc_all_org.loc_grp_cd,
	mam_loc_mam_loc_all_org.alloc_grp_cd,
	mam_loc_mam_loc_all_org.sppl_cd,
	mam_loc_mam_loc_all_org.maker_cd,
	mam_loc_mam_loc_all_org.pre_outsrc_act_flg,
	mam_loc_mam_loc_all_org.ddlv_prov_insp_flg,
	mam_loc_mam_loc_all_org.cal_cd,
	mam_loc_mam_loc_all_org.loc_mng_typ,
	mam_loc_mam_loc_all_org.prnt_lcl_cd,
	mam_loc_mam_loc_all_org.cntry_cd,
	mam_loc_mam_loc_all_org.num_id,
	mam_loc_mam_loc_all_org.stktk_tgt_flg,
	mam_loc_mam_loc_all_org.stktk_tor_disp_flg,
	mam_loc_mam_loc_all_org.stktk_tor_ex_zero_flg,
	mam_loc_mam_loc_all_org.stktk_act_ex_zero_flg,
	mam_loc_mam_loc_all_org.stktk_amt_flg,
	mam_loc_mam_loc_all_org.str_ln_tgt_flg,
	mam_loc_mam_loc_all_org.alloc_lmt_flg,
	mam_loc_mam_loc_all_org.gi_pack_xfer_flg,
	mam_loc_mam_loc_all_org.gi_vmi_flg,
	mam_loc_mam_loc_all_org.rsrc_cd1,
	mam_loc_mam_loc_all_org.rsrc_cd2,
	mam_loc_mam_loc_all_org.ext_sys_loc_typ,
	mam_loc_mam_loc_all_org.loc_alc_grp,
	mam_loc_mam_loc_all_org.addr_flg,
	mam_loc_mam_loc_lcl_all_lcl.zip_cd,
	mam_loc_mam_loc_all_org.zip_cd AS base_zip_cd,
	mam_loc_mam_loc_lcl_all_lcl.addr1,
	mam_loc_mam_loc_all_org.addr1 AS base_addr1,
	mam_loc_mam_loc_lcl_all_lcl.addr2,
	mam_loc_mam_loc_all_org.addr2 AS base_addr2,
	mam_loc_mam_loc_lcl_all_lcl.addr3,
	mam_loc_mam_loc_all_org.addr3 AS base_addr3,
	mam_loc_mam_loc_lcl_all_lcl.addr4,
	mam_loc_mam_loc_all_org.addr4 AS base_addr4,
	mam_loc_mam_loc_lcl_all_lcl.tel,
	mam_loc_mam_loc_all_org.tel AS base_tel,
	mam_loc_mam_loc_lcl_all_lcl.fax,
	mam_loc_mam_loc_all_org.fax AS base_fax,
	mam_loc_mam_loc_all_org.memo1,
	mam_loc_mam_loc_all_org.memo2,
	mam_loc_mam_loc_all_org.memo3,
	mam_loc_mam_loc_all_org.del_flg,
	mam_loc_mam_loc_all_org.del_usr_id,
	mam_loc_mam_loc_all_org.del_usr_nm,
	mam_loc_mam_loc_all_org.del_ts,
	mam_loc_mam_loc_all_org.ins_usr_id,
	mam_loc_mam_loc_all_org.ins_usr_nm,
	mam_loc_mam_loc_all_org.ins_ts,
	mam_loc_mam_loc_all_org.ins_func_id,
	mam_loc_mam_loc_all_org.upd_cntr,
	mam_loc_mam_loc_all_org.upd_usr_id,
	mam_loc_mam_loc_all_org.upd_usr_nm,
	mam_loc_mam_loc_all_org.upd_ts,
	mam_loc_mam_loc_all_org.upd_func_id,
	mam_loc_mam_loc_all_org.upd_srv_req_no
FROM
	mam_loc_all mam_loc_mam_loc_all_org
LEFT OUTER JOIN
	mam_loc_lcl_all mam_loc_mam_loc_lcl_all_lcl
ON
	mam_loc_mam_loc_all_org.loc_cd = mam_loc_mam_loc_lcl_all_lcl.loc_cd
	AND mam_loc_mam_loc_all_org.co_cd = mam_loc_mam_loc_lcl_all_lcl.co_cd
	AND mam_loc_mam_loc_lcl_all_lcl.lcl_cd = (SELECT lcl_cd FROM fct_context mam_loc_fct_context WHERE pid = pg_backend_pid())
WHERE
	0 = 0
	AND mam_loc_mam_loc_all_org.co_cd = (SELECT co_cd FROM fct_context mam_loc_fct_context WHERE pid = pg_backend_pid())
	AND (mam_loc_mam_loc_all_org.del_flg = '0' OR mapa_context$f_get_del_flg_ctl() = '0' OR EXISTS( SELECT 1 FROM maw_del_flg_ctl mam_loc_maw_del_flg_ctl_W WHERE lower(mam_loc_maw_del_flg_ctl_W.tbl_nm) = 'mam_loc'))
;

