CREATE OR REPLACE VIEW mam_dpt(
	dpt_cd,
	st_dt,
	end_dt,
	base_end_dt,
	dpt_nm,
	base_dpt_nm,
	dpt_lvl_cd,
	up_lv_dpt_cd,
	ac_dpt_cd,
	cost_dpt_cd,
	new_dpt_cd,
	zip_cd,
	base_zip_cd,
	addr1,
	base_addr1,
	addr2,
	base_addr2,
	addr3,
	base_addr3,
	addr4,
	base_addr4,
	tel,
	base_tel,
	fax,
	base_fax,
	wg_cd,
	rcv_bank_ac_cd,
	pay_bank_ac_cd,
	cal_cd,
	asst_dpt_flg,
	ar_dpt_flg,
	ap_dpt_flg,
	sls_dpt_flg,
	purc_dpt_flg,
	ship_dpt_flg,
	arr_dpt_flg,
	mfg_dpt_flg,
	sd_dpt_flg,
	insp_dpt_flg,
	bd_dpt_flg,
	memo1,
	memo2,
	memo3,
	del_flg,
	del_usr_id,
	del_usr_nm,
	del_ts,
	ins_usr_id,
	ins_usr_nm,
	ins_ts,
	ins_func_id,
	upd_cntr,
	upd_usr_id,
	upd_usr_nm,
	upd_ts,
	upd_func_id,
	upd_srv_req_no
	)
AS
SELECT
	mam_dpt_mam_dpt_all_org.dpt_cd,
	mam_dpt_mam_dpt_all_org.st_dt,
	mam_dpt_mam_dpt_lcl_all_lcl.end_dt,
	mam_dpt_mam_dpt_all_org.end_dt AS base_end_dt,
	mam_dpt_mam_dpt_lcl_all_lcl.dpt_nm,
	mam_dpt_mam_dpt_all_org.dpt_nm AS base_dpt_nm,
	mam_dpt_mam_dpt_all_org.dpt_lvl_cd,
	mam_dpt_mam_dpt_all_org.up_lv_dpt_cd,
	mam_dpt_mam_dpt_all_org.ac_dpt_cd,
	mam_dpt_mam_dpt_all_org.cost_dpt_cd,
	mam_dpt_mam_dpt_all_org.new_dpt_cd,
	mam_dpt_mam_dpt_lcl_all_lcl.zip_cd,
	mam_dpt_mam_dpt_all_org.zip_cd AS base_zip_cd,
	mam_dpt_mam_dpt_lcl_all_lcl.addr1,
	mam_dpt_mam_dpt_all_org.addr1 AS base_addr1,
	mam_dpt_mam_dpt_lcl_all_lcl.addr2,
	mam_dpt_mam_dpt_all_org.addr2 AS base_addr2,
	mam_dpt_mam_dpt_lcl_all_lcl.addr3,
	mam_dpt_mam_dpt_all_org.addr3 AS base_addr3,
	mam_dpt_mam_dpt_lcl_all_lcl.addr4,
	mam_dpt_mam_dpt_all_org.addr4 AS base_addr4,
	mam_dpt_mam_dpt_lcl_all_lcl.tel,
	mam_dpt_mam_dpt_all_org.tel AS base_tel,
	mam_dpt_mam_dpt_lcl_all_lcl.fax,
	mam_dpt_mam_dpt_all_org.fax AS base_fax,
	mam_dpt_mam_dpt_all_org.wg_cd,
	mam_dpt_mam_dpt_all_org.rcv_bank_ac_cd,
	mam_dpt_mam_dpt_all_org.pay_bank_ac_cd,
	mam_dpt_mam_dpt_all_org.cal_cd,
	mam_dpt_mam_dpt_all_org.asst_dpt_flg,
	mam_dpt_mam_dpt_all_org.ar_dpt_flg,
	mam_dpt_mam_dpt_all_org.ap_dpt_flg,
	mam_dpt_mam_dpt_all_org.sls_dpt_flg,
	mam_dpt_mam_dpt_all_org.purc_dpt_flg,
	mam_dpt_mam_dpt_all_org.ship_dpt_flg,
	mam_dpt_mam_dpt_all_org.arr_dpt_flg,
	mam_dpt_mam_dpt_all_org.mfg_dpt_flg,
	mam_dpt_mam_dpt_all_org.sd_dpt_flg,
	mam_dpt_mam_dpt_all_org.insp_dpt_flg,
	mam_dpt_mam_dpt_all_org.bd_dpt_flg,
	mam_dpt_mam_dpt_all_org.memo1,
	mam_dpt_mam_dpt_all_org.memo2,
	mam_dpt_mam_dpt_all_org.memo3,
	mam_dpt_mam_dpt_all_org.del_flg,
	mam_dpt_mam_dpt_all_org.del_usr_id,
	mam_dpt_mam_dpt_all_org.del_usr_nm,
	mam_dpt_mam_dpt_all_org.del_ts,
	mam_dpt_mam_dpt_all_org.ins_usr_id,
	mam_dpt_mam_dpt_all_org.ins_usr_nm,
	mam_dpt_mam_dpt_all_org.ins_ts,
	mam_dpt_mam_dpt_all_org.ins_func_id,
	mam_dpt_mam_dpt_all_org.upd_cntr,
	mam_dpt_mam_dpt_all_org.upd_usr_id,
	mam_dpt_mam_dpt_all_org.upd_usr_nm,
	mam_dpt_mam_dpt_all_org.upd_ts,
	mam_dpt_mam_dpt_all_org.upd_func_id,
	mam_dpt_mam_dpt_all_org.upd_srv_req_no
FROM
	mam_dpt_all mam_dpt_mam_dpt_all_org
LEFT OUTER JOIN
	mam_dpt_lcl_all mam_dpt_mam_dpt_lcl_all_lcl
ON
	mam_dpt_mam_dpt_all_org.dpt_cd = mam_dpt_mam_dpt_lcl_all_lcl.dpt_cd
	AND mam_dpt_mam_dpt_all_org.st_dt = mam_dpt_mam_dpt_lcl_all_lcl.st_dt
	AND mam_dpt_mam_dpt_all_org.co_cd = mam_dpt_mam_dpt_lcl_all_lcl.co_cd
	AND mam_dpt_mam_dpt_lcl_all_lcl.lcl_cd = (SELECT lcl_cd FROM fct_context mam_dpt_fct_context WHERE pid = pg_backend_pid())
WHERE
	0 = 0
	AND mam_dpt_mam_dpt_all_org.co_cd = (SELECT co_cd FROM fct_context mam_dpt_fct_context WHERE pid = pg_backend_pid())
	AND (mam_dpt_mam_dpt_all_org.del_flg = '0' OR mapa_context$f_get_del_flg_ctl() = '0' OR EXISTS( SELECT 1 FROM maw_del_flg_ctl mam_dpt_maw_del_flg_ctl_W WHERE lower(mam_dpt_maw_del_flg_ctl_W.tbl_nm) = 'mam_dpt'))
;

