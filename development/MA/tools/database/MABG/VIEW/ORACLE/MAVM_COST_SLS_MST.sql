SELECT
	T1.COST_SLS_TYP,
	T1.COST_SLS_CD,
	T1.COST_SLS_NM,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--売上分類名（ロケール１）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_ALL T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	COST_SLS_NM_LCL1,
	--売上分類名（ロケール２）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_ALL T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	COST_SLS_NM_LCL2,
	--売上分類名（ロケール３）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_ALL T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	COST_SLS_NM_LCL3,
	--売上分類名（ロケール４）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_ALL T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	COST_SLS_NM_LCL4,
	--売上分類名（ロケール５）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_ALL T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	COST_SLS_NM_LCL5
	FROM MAM_COST_SLS_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_COST_SLS
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_COST_SLS
			)
		)
	)
UNION ALL
SELECT
	T1.COST_SLS_TYP,
	T1.COST_SLS_CD,
	T1.COST_SLS_NM,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--売上分類名（ロケール１）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_CMN T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.LCL_CD = 'ja_JP'
	)	COST_SLS_NM_LCL1,
	--売上分類名（ロケール２）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_CMN T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.LCL_CD = 'en_US'
	)	COST_SLS_NM_LCL2,
	--売上分類名（ロケール３）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_CMN T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.LCL_CD = 'TBD3'
	)	COST_SLS_NM_LCL3,
	--売上分類名（ロケール４）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_CMN T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.LCL_CD = 'TBD4'
	)	COST_SLS_NM_LCL4,
	--売上分類名（ロケール５）
	(SELECT T.COST_SLS_NM
		FROM MAM_COST_SLS_LCL_CMN T
		WHERE 0 = 0
		AND T.COST_SLS_TYP = T1.COST_SLS_TYP
		AND T.COST_SLS_CD = T1.COST_SLS_CD
		AND T.LCL_CD = 'TBD5'
	)	COST_SLS_NM_LCL5
	FROM MAM_COST_SLS_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_COST_SLS
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
