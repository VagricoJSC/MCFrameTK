SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_CO_TR_DEF_MG
BEFORE INSERT OR DELETE OR UPDATE OF CO_CD
ON MAM_CO_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW 
BEGIN
	IF INSERTING THEN
		MAPA_COST_SYS.P_INIT_NON_MOV_CTL(:NEW.CO_CD) ;
	ELSIF UPDATING THEN
		IF :OLD.CO_CD <> :NEW.CO_CD THEN
			MAPA_COST_SYS.P_DEL_NON_MOV_CTL(:OLD.CO_CD) ;
			MAPA_COST_SYS.P_INIT_NON_MOV_CTL(:NEW.CO_CD) ;
		END IF ;
	ELSIF DELETING THEN
		MAPA_COST_SYS.P_DEL_NON_MOV_CTL(:OLD.CO_CD) ;
	END IF ;
END ;

/
show errors;


