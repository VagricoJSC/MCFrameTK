SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_CALC_GRP(
	CALC_GRP_CD,
	CALC_GRP_NM,
	BASE_CALC_GRP_NM,
	COST_CALC_TYP,
	EVAL_TYP,
	MAX_MONS,
	CALC_CNT,
	SA_TYP,
	EXP_CALC_TYP,
	PRE_ALC_CALC_TYP,
	ALC_CALC_TYP,
	INPT_CALC_FLG,
	WK_CALC_FLG,
	PROV_CALC_FLG,
	XFR_CALC_FLG,
	XRATE_CD,
	CALC_SEQ_GRP,
	CALC_SEQ,
	RUNTIME_WG_CD,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_GRP_CD,
	LCL.CALC_GRP_NM,
	ORG.CALC_GRP_NM AS BASE_CALC_GRP_NM,
	ORG.COST_CALC_TYP,
	ORG.EVAL_TYP,
	ORG.MAX_MONS,
	ORG.CALC_CNT,
	ORG.SA_TYP,
	ORG.EXP_CALC_TYP,
	ORG.PRE_ALC_CALC_TYP,
	ORG.ALC_CALC_TYP,
	ORG.INPT_CALC_FLG,
	ORG.WK_CALC_FLG,
	ORG.PROV_CALC_FLG,
	ORG.XFR_CALC_FLG,
	ORG.XRATE_CD,
	ORG.CALC_SEQ_GRP,
	ORG.CALC_SEQ,
	ORG.RUNTIME_WG_CD,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_CALC_GRP_ALL ORG,
	mam_calc_grp_lcl_all LCL
WHERE
	0 = 0
	AND ORG.CALC_GRP_CD = LCL.CALC_GRP_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_calc_grp'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

