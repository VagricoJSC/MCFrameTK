SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_RPT_CMP_CONF_$S(
	CMP_PTN_CD,
	COL_CD,
	COL_NM,
	BASE_COL_NM,
	PRINT_SORT,
	SML_FLG,
	CALC_GRP_CD,
	ST_MONTH,
	END_MONTH,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CMP_PTN_CD,
	ORG.COL_CD,
	LCL.COL_NM,
	ORG.COL_NM AS BASE_COL_NM,
	ORG.PRINT_SORT,
	ORG.SML_FLG,
	ORG.CALC_GRP_CD,
	ORG.ST_MONTH,
	ORG.END_MONTH,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_RPT_CMP_CONF_ALL ORG,
	mam_rpt_cmp_conf_lcl_all LCL
WHERE
	0 = 0
	AND ORG.CMP_PTN_CD = LCL.CMP_PTN_CD(+)
	AND ORG.COL_CD = LCL.COL_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_rpt_cmp_conf'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

