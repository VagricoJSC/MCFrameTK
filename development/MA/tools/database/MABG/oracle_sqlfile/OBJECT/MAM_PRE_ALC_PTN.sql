CREATE OR REPLACE VIEW MAM_PRE_ALC_PTN(
	PRE_ALC_PTN_CD,
	PRE_ALC_PTN_NM,
	BASE_PRE_ALC_PTN_NM,
	DPT_ALC_TYP,
	LOC_ALC_TYP,
	OPER_ALC_TYP,
	BP_ALC_TYP,
	CTG_ALC_TYP,
	ITM_ALC_TYP,
	LOT_ALC_TYP,
	SUBLOT_ALC_TYP,
	SNO1_ALC_TYP,
	SNO2_ALC_TYP,
	SNO3_ALC_TYP,
	SNO4_ALC_TYP,
	INST_ALC_TYP,
	IV_ALC_TYP,
	PO_ALC_TYP,
	SLO_ALC_TYP,
	ALC_AC_ALC_TYP,
	WG_ALC_TYP,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PRE_ALC_PTN_CD,
	LCL.PRE_ALC_PTN_NM,
	ORG.PRE_ALC_PTN_NM AS BASE_PRE_ALC_PTN_NM,
	ORG.DPT_ALC_TYP,
	ORG.LOC_ALC_TYP,
	ORG.OPER_ALC_TYP,
	ORG.BP_ALC_TYP,
	ORG.CTG_ALC_TYP,
	ORG.ITM_ALC_TYP,
	ORG.LOT_ALC_TYP,
	ORG.SUBLOT_ALC_TYP,
	ORG.SNO1_ALC_TYP,
	ORG.SNO2_ALC_TYP,
	ORG.SNO3_ALC_TYP,
	ORG.SNO4_ALC_TYP,
	ORG.INST_ALC_TYP,
	ORG.IV_ALC_TYP,
	ORG.PO_ALC_TYP,
	ORG.SLO_ALC_TYP,
	ORG.ALC_AC_ALC_TYP,
	ORG.WG_ALC_TYP,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_PRE_ALC_PTN_ALL ORG,
	mam_pre_alc_ptn_lcl_all LCL
WHERE
	0 = 0
	AND ORG.PRE_ALC_PTN_CD = LCL.PRE_ALC_PTN_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_pre_alc_ptn'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

