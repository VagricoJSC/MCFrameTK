CREATE OR REPLACE PACKAGE BODY MAPA_COST_IMP
IS
	PROCEDURE P_MAIN (
		I_TERM	IN	MAPA_META.YM%TYPE,
		I_DT	IN	MAPA_META.DT%TYPE
	)
	/*********************************************************
	<SYNOPSIS>
		品目情報を原価管理の標準単価関連データに連携する
	<REMARKS>
		
	<ARGUMENTS>
	<IN>	I_TERM
			期
	<IN>	I_DT
			対象日
	<HISTORY>
	**********************************************************/
	IS
		L_CNT	NUMBER ;

		L_SQL_SET_DTL CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_DTL.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_DTL CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_DTL.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_DTL CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_DTL.P_IMP_MGT(:TERM) ; END;
					';

		L_SQL_SET_BOM CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_BOM.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_BOM CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_BOM.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_BOM CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_BOM.P_IMP_MGT(:TERM) ; END;
					';

		L_SQL_SET_OPER CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_OPER.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_OPER CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_OPER.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_OPER CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_OPER.P_IMP_MGT(:TERM) ; END;
					' ;

		L_SQL_SET_PROC CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PROC.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_PROC CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PROC.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_PROC CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PROC.P_IMP_MGT(:TERM) ; END;
					' ;

		L_SQL_SET_PROV CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PROV.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_PROV CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PROV.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_PROV CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PROV.P_IMP_MGT(:TERM) ; END;
					' ;

		L_SQL_SET_PURC CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PURC.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_PURC CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PURC.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_PURC CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_PURC.P_IMP_MGT(:TERM) ; END;
					' ;

		L_SQL_SET_SLS CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_SLS.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_SLS CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_SLS.P_INS_MGW(NULL, NULL, :TERM, :DT, :SLS_UPRI_IMP_TYP) ; END;
					' ;
		L_SQL_IMP_SLS CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_SLS.P_IMP_MGT(:TERM) ; END;
					' ;

		L_SQL_SET_WK CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_WK.P_SET_KEY(:TERM, :DT) ; END;
					' ;
		L_SQL_INS_WK CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_WK.P_INS_MGW(NULL, NULL, :TERM, :DT) ; END;
					' ;
		L_SQL_IMP_WK CONSTANT VARCHAR2(10000) := 
					'
					BEGIN MGPA_IMP_ITM_WK.P_IMP_MGT(:TERM) ; END;
					' ;

		L_DTL_FLG	MAPA_META.FLG%TYPE ;
		L_BOM_FLG	MAPA_META.FLG%TYPE ;
		L_OPER_FLG	MAPA_META.FLG%TYPE ;
		L_PROC_FLG	MAPA_META.FLG%TYPE ;
		L_PROV_FLG	MAPA_META.FLG%TYPE ;
		L_PURC_FLG	MAPA_META.FLG%TYPE ;
		L_WK_FLG	MAPA_META.FLG%TYPE ;
		L_SLS_TYP	MAPA_META.SLS_UPRI_IMP_TYP%TYPE ;
	BEGIN
		SELECT	COUNT(*)
		INTO	L_CNT
		FROM 	USER_TABLES t
		WHERE	0=0
		AND	t.TABLE_NAME = 'MGW_IMP_INTERACTIVE_KEY'
		;

		IF L_CNT = 0 THEN
			RETURN ;
		END IF ;

		L_DTL_FLG := '0' ;
		L_BOM_FLG := '0' ;
		L_OPER_FLG := '0' ;
		L_PROC_FLG := '0' ;
		L_PROV_FLG := '0' ;
		L_PURC_FLG := '0' ;
		L_WK_FLG := '0' ;
		L_SLS_TYP := NULL ;
		FOR x IN (
			SELECT	m.PARM_KEY,
				m.PARM_VAL
			FROM	MAM_SYS_PARM m
			WHERE	0=0
			AND	m.PARM_KEY LIKE 'COST_REF_%'
			AND	m.PARM_VAL IS NOT NULL
			AND	m.DEL_FLG = '0'
			)
		LOOP
			IF x.PARM_KEY = 'COST_REF_DTL_FLG' AND x.PARM_VAL = '1' THEN
				L_DTL_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_BOM_FLG' AND x.PARM_VAL = '1' THEN
				L_BOM_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_OPER_FLG' AND x.PARM_VAL = '1' THEN
				L_OPER_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_PROC_FLG' AND x.PARM_VAL = '1' THEN
				L_PROC_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_PROV_FLG' AND x.PARM_VAL = '1' THEN
				L_PROV_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_PURC_FLG' AND x.PARM_VAL = '1' THEN
				L_PURC_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_WK_FLG' AND x.PARM_VAL = '1' THEN
				L_WK_FLG := '1' ;
			END IF ;

			IF x.PARM_KEY = 'COST_REF_SLS_TYP' AND MAC_SLS_UPRI_IMP_TYP.CONTAINS(x.PARM_VAL) = '1' THEN
				L_SLS_TYP := x.PARM_VAL ;
			END IF ;
		END LOOP ;

		IF L_DTL_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_DTL USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_DTL USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_DTL USING IN I_TERM ;
		END IF ;

		IF L_BOM_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_BOM USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_BOM USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_BOM USING IN I_TERM ;
		END IF ;

		IF L_OPER_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_OPER USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_OPER USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_OPER USING IN I_TERM ;
		END IF ;

		IF L_PROC_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_PROC USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_PROC USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_PROC USING IN I_TERM ;
		END IF ;

		IF L_PROV_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_PROV USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_PROV USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_PROV USING IN I_TERM ;
		END IF ;

		IF L_PURC_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_PURC USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_PURC USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_PURC USING IN I_TERM ;
		END IF ;

		IF L_SLS_TYP IS NOT NULL THEN
			EXECUTE IMMEDIATE L_SQL_SET_SLS USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_SLS USING IN I_TERM, I_DT, L_SLS_TYP ;
			EXECUTE IMMEDIATE L_SQL_IMP_SLS USING IN I_TERM ;
		END IF ;

		IF L_WK_FLG = '1' THEN
			EXECUTE IMMEDIATE L_SQL_SET_WK USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_INS_WK USING IN I_TERM, I_DT ;
			EXECUTE IMMEDIATE L_SQL_IMP_WK USING IN I_TERM ;
		END IF ;


	END P_MAIN ;
END MAPA_COST_IMP ;
/
