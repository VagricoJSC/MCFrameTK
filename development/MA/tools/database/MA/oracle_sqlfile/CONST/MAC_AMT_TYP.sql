CREATE OR REPLACE PACKAGE BODY MAC_AMT_TYP
/*****************************
仕訳金額区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ZERO RETURN VARCHAR2 DETERMINISTIC IS -- 金額は0とする
	BEGIN RETURN '1'; END ZERO;
	FUNCTION AMT_TAX RETURN VARCHAR2 DETERMINISTIC IS -- 税抜(評価)金額(税額は別項目に出力)
	BEGIN RETURN '2'; END AMT_TAX;
	FUNCTION AMT_ONLY RETURN VARCHAR2 DETERMINISTIC IS -- 税抜(評価)金額(税額は出力しない)
	BEGIN RETURN '3'; END AMT_ONLY;
	FUNCTION TAX_IN_AMT RETURN VARCHAR2 DETERMINISTIC IS -- 税金額(金額項目に出力)
	BEGIN RETURN '4'; END TAX_IN_AMT;
	FUNCTION TAX_IN_TAX RETURN VARCHAR2 DETERMINISTIC IS -- 税金額(税額項目に出力)
	BEGIN RETURN '5'; END TAX_IN_TAX;
	FUNCTION SML RETURN VARCHAR2 DETERMINISTIC IS -- 税抜金額 + 税金額
	BEGIN RETURN '6'; END SML;
	FUNCTION STD RETURN VARCHAR2 DETERMINISTIC IS -- 標準評価金額
	BEGIN RETURN '7'; END STD;
	FUNCTION AMT_STD RETURN VARCHAR2 DETERMINISTIC IS -- 税抜(評価)金額 - 標準評価金額
	BEGIN RETURN '8'; END AMT_STD;
	FUNCTION NON_JNL RETURN VARCHAR2 DETERMINISTIC IS -- 仕訳対象外
	BEGIN RETURN 'X'; END NON_JNL;
	FUNCTION PROC_AMT_TAX RETURN VARCHAR2 DETERMINISTIC IS -- 加工金額(税額は別項目に出力)
	BEGIN RETURN 'A'; END PROC_AMT_TAX;
	FUNCTION PROC_AMT_ONLY RETURN VARCHAR2 DETERMINISTIC IS -- 加工金額(税額は出力しない)
	BEGIN RETURN 'B'; END PROC_AMT_ONLY;
	FUNCTION PROC_SML RETURN VARCHAR2 DETERMINISTIC IS -- 加工金額 + 税金額
	BEGIN RETURN 'C'; END PROC_SML;
	FUNCTION ONR_PROV_AMT RETURN VARCHAR2 DETERMINISTIC IS -- 有償支給金額
	BEGIN RETURN 'D'; END ONR_PROV_AMT;

	FUNCTION IS_ZERO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 金額は0とするかどうか
	BEGIN
		IF I_VALUE = ZERO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ZERO;

	FUNCTION IS_AMT_TAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税抜(評価)金額(税額は別項目に出力)かどうか
	BEGIN
		IF I_VALUE = AMT_TAX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AMT_TAX;

	FUNCTION IS_AMT_ONLY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税抜(評価)金額(税額は出力しない)かどうか
	BEGIN
		IF I_VALUE = AMT_ONLY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AMT_ONLY;

	FUNCTION IS_TAX_IN_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税金額(金額項目に出力)かどうか
	BEGIN
		IF I_VALUE = TAX_IN_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TAX_IN_AMT;

	FUNCTION IS_TAX_IN_TAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税金額(税額項目に出力)かどうか
	BEGIN
		IF I_VALUE = TAX_IN_TAX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TAX_IN_TAX;

	FUNCTION IS_SML(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税抜金額 + 税金額かどうか
	BEGIN
		IF I_VALUE = SML THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SML;

	FUNCTION IS_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準評価金額かどうか
	BEGIN
		IF I_VALUE = STD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD;

	FUNCTION IS_AMT_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税抜(評価)金額 - 標準評価金額かどうか
	BEGIN
		IF I_VALUE = AMT_STD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AMT_STD;

	FUNCTION IS_NON_JNL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 仕訳対象外かどうか
	BEGIN
		IF I_VALUE = NON_JNL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON_JNL;

	FUNCTION IS_PROC_AMT_TAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 加工金額(税額は別項目に出力)かどうか
	BEGIN
		IF I_VALUE = PROC_AMT_TAX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROC_AMT_TAX;

	FUNCTION IS_PROC_AMT_ONLY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 加工金額(税額は出力しない)かどうか
	BEGIN
		IF I_VALUE = PROC_AMT_ONLY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROC_AMT_ONLY;

	FUNCTION IS_PROC_SML(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 加工金額 + 税金額かどうか
	BEGIN
		IF I_VALUE = PROC_SML THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROC_SML;

	FUNCTION IS_ONR_PROV_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 有償支給金額かどうか
	BEGIN
		IF I_VALUE = ONR_PROV_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ONR_PROV_AMT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ZERO
		OR I_VALUE = AMT_TAX
		OR I_VALUE = AMT_ONLY
		OR I_VALUE = TAX_IN_AMT
		OR I_VALUE = TAX_IN_TAX
		OR I_VALUE = SML
		OR I_VALUE = STD
		OR I_VALUE = AMT_STD
		OR I_VALUE = NON_JNL
		OR I_VALUE = PROC_AMT_TAX
		OR I_VALUE = PROC_AMT_ONLY
		OR I_VALUE = PROC_SML
		OR I_VALUE = ONR_PROV_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_AMT_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_AMT_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_AMT_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_AMT_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_AMT_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_AMT_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_AMT_TYP;

