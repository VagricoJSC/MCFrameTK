		OR I_VALUE = DLVSLIP
		OR I_VALUE = IV
		OR I_VALUE = SHIPINST
		OR I_VALUE = SHIPINSTD
		OR I_VALUE = SHIPACT
		OR I_VALUE = ARRACT
		OR I_VALUE = XFRSCHD
		OR I_VALUE = XFRINST
		OR I_VALUE = XFRINSTD
		OR I_VALUE = XFRACT
