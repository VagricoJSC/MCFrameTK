CREATE OR REPLACE PACKAGE BODY MAC_MRP_PROC_TYP
/*****************************
ＭＲＰ処理区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION RATE RETURN VARCHAR2 DETERMINISTIC IS -- オーダ比率
	BEGIN RETURN '1'; END RATE;
	FUNCTION BATCH_REP RETURN VARCHAR2 DETERMINISTIC IS -- バッチ（繰返）
	BEGIN RETURN '2'; END BATCH_REP;
	FUNCTION BATCH_AVE RETURN VARCHAR2 DETERMINISTIC IS -- バッチ（平均）
	BEGIN RETURN '3'; END BATCH_AVE;
	FUNCTION EXCLD RETURN VARCHAR2 DETERMINISTIC IS -- 対象外
	BEGIN RETURN '4'; END EXCLD;
	FUNCTION EXTND RETURN VARCHAR2 DETERMINISTIC IS -- 展開のみ対象
	BEGIN RETURN '5'; END EXTND;

	FUNCTION IS_RATE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- オーダ比率かどうか
	BEGIN
		IF I_VALUE = RATE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RATE;

	FUNCTION IS_BATCH_REP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- バッチ（繰返）かどうか
	BEGIN
		IF I_VALUE = BATCH_REP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_BATCH_REP;

	FUNCTION IS_BATCH_AVE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- バッチ（平均）かどうか
	BEGIN
		IF I_VALUE = BATCH_AVE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_BATCH_AVE;

	FUNCTION IS_EXCLD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 対象外かどうか
	BEGIN
		IF I_VALUE = EXCLD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXCLD;

	FUNCTION IS_EXTND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 展開のみ対象かどうか
	BEGIN
		IF I_VALUE = EXTND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXTND;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = RATE
		OR I_VALUE = BATCH_REP
		OR I_VALUE = BATCH_AVE
		OR I_VALUE = EXCLD
		OR I_VALUE = EXTND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_MRP_PROC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_MRP_PROC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_MRP_PROC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_MRP_PROC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_MRP_PROC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_MRP_PROC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_MRP_PROC_TYP;

