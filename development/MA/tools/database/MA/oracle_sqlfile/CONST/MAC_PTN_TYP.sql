CREATE OR REPLACE PACKAGE BODY MAC_PTN_TYP
/*****************************
仕訳パタン設定区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MST RETURN VARCHAR2 DETERMINISTIC IS -- マスタ値
	BEGIN RETURN 'M'; END MST;
	FUNCTION RSN RETURN VARCHAR2 DETERMINISTIC IS -- 会計理由科目
	BEGIN RETURN '1'; END RSN;
	FUNCTION JNL RETURN VARCHAR2 DETERMINISTIC IS -- 品目仕訳科目
	BEGIN RETURN '2'; END JNL;
	FUNCTION AC RETURN VARCHAR2 DETERMINISTIC IS -- 口座科目
	BEGIN RETURN '3'; END AC;

	FUNCTION IS_MST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- マスタ値かどうか
	BEGIN
		IF I_VALUE = MST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MST;

	FUNCTION IS_RSN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計理由科目かどうか
	BEGIN
		IF I_VALUE = RSN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RSN;

	FUNCTION IS_JNL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目仕訳科目かどうか
	BEGIN
		IF I_VALUE = JNL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_JNL;

	FUNCTION IS_AC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 口座科目かどうか
	BEGIN
		IF I_VALUE = AC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MST
		OR I_VALUE = RSN
		OR I_VALUE = JNL
		OR I_VALUE = AC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_PTN_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_PTN_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_PTN_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_PTN_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_PTN_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_PTN_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_PTN_TYP;

/
show errors;


