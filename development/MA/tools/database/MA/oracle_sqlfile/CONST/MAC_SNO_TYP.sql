CREATE OR REPLACE PACKAGE BODY MAC_SNO_TYP
/*****************************
手配ＮＯ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION EXTND RETURN VARCHAR2 DETERMINISTIC IS -- 展開
	BEGIN RETURN '1'; END EXTND;
	FUNCTION NO_EXTND RETURN VARCHAR2 DETERMINISTIC IS -- 展開しない
	BEGIN RETURN '2'; END NO_EXTND;
	FUNCTION EXTND_NULL RETURN VARCHAR2 DETERMINISTIC IS -- 展開（無し可）
	BEGIN RETURN '3'; END EXTND_NULL;

	FUNCTION IS_EXTND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 展開かどうか
	BEGIN
		IF I_VALUE = EXTND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXTND;

	FUNCTION IS_NO_EXTND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 展開しないかどうか
	BEGIN
		IF I_VALUE = NO_EXTND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NO_EXTND;

	FUNCTION IS_EXTND_NULL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 展開（無し可）かどうか
	BEGIN
		IF I_VALUE = EXTND_NULL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXTND_NULL;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = EXTND
		OR I_VALUE = NO_EXTND
		OR I_VALUE = EXTND_NULL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SNO_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SNO_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SNO_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SNO_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SNO_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SNO_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SNO_TYP;

/
show errors;


