CREATE OR REPLACE PACKAGE BODY MAC_COST_SLS_TYP
/*****************************
原価売上分類区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION S1 RETURN VARCHAR2 DETERMINISTIC IS -- 売上分類１
	BEGIN RETURN '1'; END S1;
	FUNCTION S2 RETURN VARCHAR2 DETERMINISTIC IS -- 売上分類２
	BEGIN RETURN '2'; END S2;
	FUNCTION S3 RETURN VARCHAR2 DETERMINISTIC IS -- 売上分類３
	BEGIN RETURN '3'; END S3;
	FUNCTION S4 RETURN VARCHAR2 DETERMINISTIC IS -- 売上分類４
	BEGIN RETURN '4'; END S4;
	FUNCTION S5 RETURN VARCHAR2 DETERMINISTIC IS -- 売上分類５
	BEGIN RETURN '5'; END S5;

	FUNCTION IS_S1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上分類１かどうか
	BEGIN
		IF I_VALUE = S1 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_S1;

	FUNCTION IS_S2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上分類２かどうか
	BEGIN
		IF I_VALUE = S2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_S2;

	FUNCTION IS_S3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上分類３かどうか
	BEGIN
		IF I_VALUE = S3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_S3;

	FUNCTION IS_S4(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上分類４かどうか
	BEGIN
		IF I_VALUE = S4 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_S4;

	FUNCTION IS_S5(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上分類５かどうか
	BEGIN
		IF I_VALUE = S5 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_S5;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = S1
		OR I_VALUE = S2
		OR I_VALUE = S3
		OR I_VALUE = S4
		OR I_VALUE = S5 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_COST_SLS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_COST_SLS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_COST_SLS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_COST_SLS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_COST_SLS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_COST_SLS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_COST_SLS_TYP;

