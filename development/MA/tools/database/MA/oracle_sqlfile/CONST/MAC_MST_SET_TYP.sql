CREATE OR REPLACE PACKAGE BODY MAC_MST_SET_TYP
/*****************************
マスタ設定区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ALL_COM RETURN VARCHAR2 DETERMINISTIC IS -- ★共通
	BEGIN RETURN '1'; END ALL_COM;
	FUNCTION COM RETURN VARCHAR2 DETERMINISTIC IS -- 会社別
	BEGIN RETURN '2'; END COM;
	FUNCTION ALL_COM_COM RETURN VARCHAR2 DETERMINISTIC IS -- ★共通・会社別
	BEGIN RETURN '3'; END ALL_COM_COM;

	FUNCTION IS_ALL_COM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ★共通かどうか
	BEGIN
		IF I_VALUE = ALL_COM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALL_COM;

	FUNCTION IS_COM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会社別かどうか
	BEGIN
		IF I_VALUE = COM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_COM;

	FUNCTION IS_ALL_COM_COM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ★共通・会社別かどうか
	BEGIN
		IF I_VALUE = ALL_COM_COM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALL_COM_COM;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ALL_COM
		OR I_VALUE = COM
		OR I_VALUE = ALL_COM_COM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_MST_SET_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_MST_SET_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_MST_SET_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_MST_SET_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_MST_SET_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_MST_SET_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_MST_SET_TYP;

/
show errors;


