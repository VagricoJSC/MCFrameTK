CREATE OR REPLACE PACKAGE BODY MAC_SUMMARY_TYP
/*****************************
集計区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- 集計しない
	BEGIN RETURN 'X'; END NON;
	FUNCTION SLIP RETURN VARCHAR2 DETERMINISTIC IS -- 伝票単位
	BEGIN RETURN '1'; END SLIP;
	FUNCTION DD RETURN VARCHAR2 DETERMINISTIC IS -- 日単位(計上日)
	BEGIN RETURN '2'; END DD;
	FUNCTION MM RETURN VARCHAR2 DETERMINISTIC IS -- 月単位
	BEGIN RETURN '3'; END MM;

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計しないかどうか
	BEGIN
		IF I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON;

	FUNCTION IS_SLIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 伝票単位かどうか
	BEGIN
		IF I_VALUE = SLIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLIP;

	FUNCTION IS_DD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日単位(計上日)かどうか
	BEGIN
		IF I_VALUE = DD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DD;

	FUNCTION IS_MM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月単位かどうか
	BEGIN
		IF I_VALUE = MM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MM;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NON
		OR I_VALUE = SLIP
		OR I_VALUE = DD
		OR I_VALUE = MM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SUMMARY_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SUMMARY_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SUMMARY_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SUMMARY_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SUMMARY_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SUMMARY_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SUMMARY_TYP;

/
show errors;


