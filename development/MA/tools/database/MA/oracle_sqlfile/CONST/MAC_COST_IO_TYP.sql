CREATE OR REPLACE PACKAGE BODY MAC_COST_IO_TYP
/*****************************
原価入出庫区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION FFR_PROV RETURN VARCHAR2 DETERMINISTIC IS -- 無償支給
	BEGIN RETURN '11'; END FFR_PROV;
	FUNCTION ONR_PROV RETURN VARCHAR2 DETERMINISTIC IS -- 有償支給
	BEGIN RETURN '12'; END ONR_PROV;
	FUNCTION STK_IN RETURN VARCHAR2 DETERMINISTIC IS -- 入庫
	BEGIN RETURN '20'; END STK_IN;
	FUNCTION STK_OUT RETURN VARCHAR2 DETERMINISTIC IS -- 出庫
	BEGIN RETURN '30'; END STK_OUT;
	FUNCTION STK_IO RETURN VARCHAR2 DETERMINISTIC IS -- 入出庫
	BEGIN RETURN '40'; END STK_IO;

	FUNCTION IS_FFR_PROV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 無償支給かどうか
	BEGIN
		IF I_VALUE = FFR_PROV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FFR_PROV;

	FUNCTION IS_ONR_PROV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 有償支給かどうか
	BEGIN
		IF I_VALUE = ONR_PROV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ONR_PROV;

	FUNCTION IS_STK_IN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入庫かどうか
	BEGIN
		IF I_VALUE = STK_IN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STK_IN;

	FUNCTION IS_STK_OUT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出庫かどうか
	BEGIN
		IF I_VALUE = STK_OUT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STK_OUT;

	FUNCTION IS_STK_IO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入出庫かどうか
	BEGIN
		IF I_VALUE = STK_IO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STK_IO;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = FFR_PROV
		OR I_VALUE = ONR_PROV
		OR I_VALUE = STK_IN
		OR I_VALUE = STK_OUT
		OR I_VALUE = STK_IO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_COST_IO_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_COST_IO_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_COST_IO_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_COST_IO_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_COST_IO_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_COST_IO_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_COST_IO_TYP;

/
show errors;


