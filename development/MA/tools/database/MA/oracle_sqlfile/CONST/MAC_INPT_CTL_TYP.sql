CREATE OR REPLACE PACKAGE BODY MAC_INPT_CTL_TYP
/*****************************
投入制御区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MRP_INPT RETURN VARCHAR2 DETERMINISTIC IS -- ＭＲＰ・投入対象
	BEGIN RETURN '1'; END MRP_INPT;
	FUNCTION NO_MRP RETURN VARCHAR2 DETERMINISTIC IS -- ＭＲＰ対象外（投入可）
	BEGIN RETURN '2'; END NO_MRP;
	FUNCTION NO_MRP_INST RETURN VARCHAR2 DETERMINISTIC IS -- ＭＲＰ対象外（指図書のみ）
	BEGIN RETURN '3'; END NO_MRP_INST;
	FUNCTION MRP_NOT_FIX RETURN VARCHAR2 DETERMINISTIC IS -- ＭＲＰ対象・オーダ確定不可
	BEGIN RETURN '4'; END MRP_NOT_FIX;

	FUNCTION IS_MRP_INPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＭＲＰ・投入対象かどうか
	BEGIN
		IF I_VALUE = MRP_INPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MRP_INPT;

	FUNCTION IS_NO_MRP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＭＲＰ対象外（投入可）かどうか
	BEGIN
		IF I_VALUE = NO_MRP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NO_MRP;

	FUNCTION IS_NO_MRP_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＭＲＰ対象外（指図書のみ）かどうか
	BEGIN
		IF I_VALUE = NO_MRP_INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NO_MRP_INST;

	FUNCTION IS_MRP_NOT_FIX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＭＲＰ対象・オーダ確定不可かどうか
	BEGIN
		IF I_VALUE = MRP_NOT_FIX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MRP_NOT_FIX;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MRP_INPT
		OR I_VALUE = NO_MRP
		OR I_VALUE = NO_MRP_INST
		OR I_VALUE = MRP_NOT_FIX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_INPT_CTL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_INPT_CTL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_INPT_CTL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_INPT_CTL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_INPT_CTL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_INPT_CTL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_INPT_CTL_TYP;

/
show errors;


