CREATE OR REPLACE PACKAGE BODY MAC_ITM_TYP
/*****************************
品目区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION GOODS RETURN VARCHAR2 DETERMINISTIC IS -- 商品
	BEGIN RETURN '1'; END GOODS;
	FUNCTION PROD RETURN VARCHAR2 DETERMINISTIC IS -- 製品
	BEGIN RETURN '2'; END PROD;
	FUNCTION INT_PROD RETURN VARCHAR2 DETERMINISTIC IS -- 中間品
	BEGIN RETURN '3'; END INT_PROD;
	FUNCTION PART RETURN VARCHAR2 DETERMINISTIC IS -- 部品
	BEGIN RETURN '4'; END PART;
	FUNCTION MATERIAL RETURN VARCHAR2 DETERMINISTIC IS -- 資材
	BEGIN RETURN '5'; END MATERIAL;
	FUNCTION RM RETURN VARCHAR2 DETERMINISTIC IS -- 原料
	BEGIN RETURN '6'; END RM;
	FUNCTION PHANTOM RETURN VARCHAR2 DETERMINISTIC IS -- 架空品
	BEGIN RETURN '7'; END PHANTOM;
	FUNCTION OTHER RETURN VARCHAR2 DETERMINISTIC IS -- その他
	BEGIN RETURN '9'; END OTHER;

	FUNCTION IS_GOODS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 商品かどうか
	BEGIN
		IF I_VALUE = GOODS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GOODS;

	FUNCTION IS_PROD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製品かどうか
	BEGIN
		IF I_VALUE = PROD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROD;

	FUNCTION IS_INT_PROD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 中間品かどうか
	BEGIN
		IF I_VALUE = INT_PROD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INT_PROD;

	FUNCTION IS_PART(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 部品かどうか
	BEGIN
		IF I_VALUE = PART THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PART;

	FUNCTION IS_MATERIAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 資材かどうか
	BEGIN
		IF I_VALUE = MATERIAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MATERIAL;

	FUNCTION IS_RM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 原料かどうか
	BEGIN
		IF I_VALUE = RM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RM;

	FUNCTION IS_PHANTOM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 架空品かどうか
	BEGIN
		IF I_VALUE = PHANTOM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PHANTOM;

	FUNCTION IS_OTHER(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- その他かどうか
	BEGIN
		IF I_VALUE = OTHER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OTHER;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = GOODS
		OR I_VALUE = PROD
		OR I_VALUE = INT_PROD
		OR I_VALUE = PART
		OR I_VALUE = MATERIAL
		OR I_VALUE = RM
		OR I_VALUE = PHANTOM
		OR I_VALUE = OTHER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_ITM_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_ITM_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_ITM_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_ITM_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_ITM_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_ITM_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_ITM_TYP;

/
show errors;


