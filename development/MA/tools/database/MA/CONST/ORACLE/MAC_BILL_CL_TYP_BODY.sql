CREATE OR REPLACE PACKAGE BODY MAC_BILL_CL_TYP
/*****************************
請求締処理区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION BATCH RETURN VARCHAR2 DETERMINISTIC IS -- バッチ締日請求
	BEGIN RETURN '1'; END BATCH;
	FUNCTION MANUAL RETURN VARCHAR2 DETERMINISTIC IS -- マニュアル締日請求
	BEGIN RETURN '2'; END MANUAL;
	FUNCTION SEL RETURN VARCHAR2 DETERMINISTIC IS -- マニュアル選択請求
	BEGIN RETURN '3'; END SEL;
	FUNCTION EACH_SLS RETURN VARCHAR2 DETERMINISTIC IS -- 売上都度請求
	BEGIN RETURN '4'; END EACH_SLS;

	FUNCTION IS_BATCH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- バッチ締日請求かどうか
	BEGIN
		IF I_VALUE = BATCH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_BATCH;

	FUNCTION IS_MANUAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- マニュアル締日請求かどうか
	BEGIN
		IF I_VALUE = MANUAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MANUAL;

	FUNCTION IS_SEL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- マニュアル選択請求かどうか
	BEGIN
		IF I_VALUE = SEL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SEL;

	FUNCTION IS_EACH_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上都度請求かどうか
	BEGIN
		IF I_VALUE = EACH_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EACH_SLS;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = BATCH
		OR I_VALUE = MANUAL
		OR I_VALUE = SEL
		OR I_VALUE = EACH_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_BILL_CL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_BILL_CL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_BILL_CL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_BILL_CL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_BILL_CL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_BILL_CL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_BILL_CL_TYP;
