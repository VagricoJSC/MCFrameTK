CREATE OR REPLACE PACKAGE BODY MAC_DPT_CONFIG_TYP
/*****************************
部門構成区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- 部門構成対象外
	BEGIN RETURN '1'; END NON;
	FUNCTION CONFIG RETURN VARCHAR2 DETERMINISTIC IS -- 部門構成マスタ
	BEGIN RETURN '2'; END CONFIG;
	FUNCTION LG_GRP RETURN VARCHAR2 DETERMINISTIC IS -- 物流Ｇ
	BEGIN RETURN '3'; END LG_GRP;
	FUNCTION LOC_GRP RETURN VARCHAR2 DETERMINISTIC IS -- 製造場所Ｇ
	BEGIN RETURN '4'; END LOC_GRP;
	FUNCTION WG RETURN VARCHAR2 DETERMINISTIC IS -- ＷＧ
	BEGIN RETURN '5'; END WG;
	FUNCTION SITE RETURN VARCHAR2 DETERMINISTIC IS -- 工場・物流倉庫
	BEGIN RETURN '6'; END SITE;

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 部門構成対象外かどうか
	BEGIN
		IF I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON;

	FUNCTION IS_CONFIG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 部門構成マスタかどうか
	BEGIN
		IF I_VALUE = CONFIG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CONFIG;

	FUNCTION IS_LG_GRP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 物流Ｇかどうか
	BEGIN
		IF I_VALUE = LG_GRP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LG_GRP;

	FUNCTION IS_LOC_GRP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製造場所Ｇかどうか
	BEGIN
		IF I_VALUE = LOC_GRP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOC_GRP;

	FUNCTION IS_WG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＷＧかどうか
	BEGIN
		IF I_VALUE = WG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WG;

	FUNCTION IS_SITE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工場・物流倉庫かどうか
	BEGIN
		IF I_VALUE = SITE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SITE;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NON
		OR I_VALUE = CONFIG
		OR I_VALUE = LG_GRP
		OR I_VALUE = LOC_GRP
		OR I_VALUE = WG
		OR I_VALUE = SITE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_DPT_CONFIG_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_DPT_CONFIG_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_DPT_CONFIG_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_DPT_CONFIG_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_DPT_CONFIG_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_DPT_CONFIG_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_DPT_CONFIG_TYP;
