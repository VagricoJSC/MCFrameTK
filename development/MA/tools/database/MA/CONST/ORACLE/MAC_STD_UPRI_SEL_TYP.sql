CREATE OR REPLACE PACKAGE MAC_STD_UPRI_SEL_TYP
/*****************************
標準単価取得区分の定数定義パッケージ
*****************************/
IS

	FUNCTION STD_UPRI RETURN VARCHAR2 DETERMINISTIC ; -- 標準単価
	FUNCTION SUB_UPRI1 RETURN VARCHAR2 DETERMINISTIC ; -- 予備単価１→標準単価
	FUNCTION SUB_UPRI2 RETURN VARCHAR2 DETERMINISTIC ; -- 予備単価２→標準単価
	FUNCTION SUB_UPRI3 RETURN VARCHAR2 DETERMINISTIC ; -- 予備単価３→標準単価

	FUNCTION IS_STD_UPRI(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 標準単価であるか
	FUNCTION IS_SUB_UPRI1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 予備単価１→標準単価であるか
	FUNCTION IS_SUB_UPRI2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 予備単価２→標準単価であるか
	FUNCTION IS_SUB_UPRI3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 予備単価３→標準単価であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
