CREATE OR REPLACE PACKAGE BODY MAC_COMPOUND_JNL_TYP
/*****************************
複合仕訳区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION D1C1 RETURN VARCHAR2 DETERMINISTIC IS -- １対１
	BEGIN RETURN '1'; END D1C1;
	FUNCTION DNC1 RETURN VARCHAR2 DETERMINISTIC IS -- Ｎ対１
	BEGIN RETURN '2'; END DNC1;
	FUNCTION D1CN RETURN VARCHAR2 DETERMINISTIC IS -- １対Ｎ
	BEGIN RETURN '3'; END D1CN;
	FUNCTION OTHER RETURN VARCHAR2 DETERMINISTIC IS -- 制御しない
	BEGIN RETURN '9'; END OTHER;

	FUNCTION IS_D1C1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- １対１かどうか
	BEGIN
		IF I_VALUE = D1C1 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_D1C1;

	FUNCTION IS_DNC1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Ｎ対１かどうか
	BEGIN
		IF I_VALUE = DNC1 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DNC1;

	FUNCTION IS_D1CN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- １対Ｎかどうか
	BEGIN
		IF I_VALUE = D1CN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_D1CN;

	FUNCTION IS_OTHER(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 制御しないかどうか
	BEGIN
		IF I_VALUE = OTHER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OTHER;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = D1C1
		OR I_VALUE = DNC1
		OR I_VALUE = D1CN
		OR I_VALUE = OTHER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_COMPOUND_JNL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_COMPOUND_JNL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_COMPOUND_JNL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_COMPOUND_JNL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_COMPOUND_JNL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_COMPOUND_JNL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_COMPOUND_JNL_TYP;
