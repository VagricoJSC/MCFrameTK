CREATE OR REPLACE PACKAGE MAC_DAY_WEEK_TYP
/*****************************
曜日区分の定数定義パッケージ
*****************************/
IS

	FUNCTION SUN RETURN VARCHAR2 DETERMINISTIC ; -- Sun.
	FUNCTION MON RETURN VARCHAR2 DETERMINISTIC ; -- Mon.
	FUNCTION TUE RETURN VARCHAR2 DETERMINISTIC ; -- Tue.
	FUNCTION WED RETURN VARCHAR2 DETERMINISTIC ; -- Wed.
	FUNCTION THU RETURN VARCHAR2 DETERMINISTIC ; -- Thu.
	FUNCTION FRI RETURN VARCHAR2 DETERMINISTIC ; -- Fri.
	FUNCTION SAT RETURN VARCHAR2 DETERMINISTIC ; -- Sat.

	FUNCTION IS_SUN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Sun.であるか
	FUNCTION IS_MON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Mon.であるか
	FUNCTION IS_TUE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Tue.であるか
	FUNCTION IS_WED(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Wed.であるか
	FUNCTION IS_THU(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Thu.であるか
	FUNCTION IS_FRI(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Fri.であるか
	FUNCTION IS_SAT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Sat.であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
