	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = QTN_SLO
		OR I_VALUE = SLO
		OR I_VALUE = SLS_DSCNT
		OR I_VALUE = SLS_XTRA
		OR I_VALUE = PO
		OR I_VALUE = XPNS_PO
		OR I_VALUE = SCRP
		OR I_VALUE = STK_OTH_GI
		OR I_VALUE = STK_OTH_GR
		OR I_VALUE = PAY_SCHD
		OR I_VALUE = MST_STD_SLS_UPRI
		OR I_VALUE = MST_ITM_SLS_UPRI
		OR I_VALUE = MST_CST_SLS_UPRI
		OR I_VALUE = MST_PURC_UPRI
		OR I_VALUE = MST_PROC_UPRI
		OR I_VALUE = MST_PROV_UPRI THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

