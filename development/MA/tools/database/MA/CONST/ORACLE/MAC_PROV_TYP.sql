CREATE OR REPLACE PACKAGE MAC_PROV_TYP
/*****************************
支給区分の定数定義パッケージ
*****************************/
IS

	FUNCTION FFR_PROV RETURN VARCHAR2 DETERMINISTIC ; -- 無償支給
	FUNCTION ONR_PROV RETURN VARCHAR2 DETERMINISTIC ; -- 有償支給
	FUNCTION SS RETURN VARCHAR2 DETERMINISTIC ; -- 自給

	FUNCTION IS_FFR_PROV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 無償支給であるか
	FUNCTION IS_ONR_PROV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 有償支給であるか
	FUNCTION IS_SS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 自給であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
