	FUNCTION NOT_MNG RETURN VARCHAR2 DETERMINISTIC ; -- 管理しない
	FUNCTION MNG_REQ RETURN VARCHAR2 DETERMINISTIC ; -- 管理する（必須）
	FUNCTION MNG_ARB RETURN VARCHAR2 DETERMINISTIC ; -- 管理する（任意）
	FUNCTION MNG_NOT_STK RETURN VARCHAR2 DETERMINISTIC ; -- 管理する（任意：在庫対象外）

	FUNCTION IS_NOT_MNG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 管理しないであるか
	FUNCTION IS_MNG_REQ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 管理する（必須）であるか
	FUNCTION IS_MNG_ARB(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 管理する（任意）であるか
