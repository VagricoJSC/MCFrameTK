CREATE OR REPLACE PACKAGE BODY MAC_INPT_LOC_TYP
/*****************************
投入場所区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION DPT RETURN VARCHAR2 DETERMINISTIC IS -- 部門構成
	BEGIN RETURN '1'; END DPT;
	FUNCTION LOC RETURN VARCHAR2 DETERMINISTIC IS -- 場所
	BEGIN RETURN '2'; END LOC;
	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- 指定なし
	BEGIN RETURN '3'; END NON;
	FUNCTION MNG_DPT RETURN VARCHAR2 DETERMINISTIC IS -- 管理部門
	BEGIN RETURN '4'; END MNG_DPT;

	FUNCTION IS_DPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 部門構成かどうか
	BEGIN
		IF I_VALUE = DPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DPT;

	FUNCTION IS_LOC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 場所かどうか
	BEGIN
		IF I_VALUE = LOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOC;

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指定なしかどうか
	BEGIN
		IF I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON;

	FUNCTION IS_MNG_DPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 管理部門かどうか
	BEGIN
		IF I_VALUE = MNG_DPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MNG_DPT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = DPT
		OR I_VALUE = LOC
		OR I_VALUE = NON
		OR I_VALUE = MNG_DPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_INPT_LOC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_INPT_LOC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_INPT_LOC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_INPT_LOC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_INPT_LOC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_INPT_LOC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_INPT_LOC_TYP;
