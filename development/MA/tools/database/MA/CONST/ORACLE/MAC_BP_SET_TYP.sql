CREATE OR REPLACE PACKAGE MAC_BP_SET_TYP
/*****************************
取引先出力区分の定数定義パッケージ
*****************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC ; -- 使用しない
	FUNCTION AR RETURN VARCHAR2 DETERMINISTIC ; -- 売掛先
	FUNCTION CST RETURN VARCHAR2 DETERMINISTIC ; -- 得意先
	FUNCTION SPL RETURN VARCHAR2 DETERMINISTIC ; -- 発注先
	FUNCTION AP RETURN VARCHAR2 DETERMINISTIC ; -- 買掛先
	FUNCTION CRE RETURN VARCHAR2 DETERMINISTIC ; -- 入金先/支払先
	FUNCTION FIX_CST RETURN VARCHAR2 DETERMINISTIC ; -- 固定値(取引先区分=1)
	FUNCTION FIX_SPL RETURN VARCHAR2 DETERMINISTIC ; -- 固定値(取引先区分=2)
	FUNCTION SO_CST RETURN VARCHAR2 DETERMINISTIC ; -- 相殺先(取引先区分=1)
	FUNCTION SO_SPL RETURN VARCHAR2 DETERMINISTIC ; -- 相殺先(取引先区分=2)

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 使用しないであるか
	FUNCTION IS_AR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 売掛先であるか
	FUNCTION IS_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 得意先であるか
	FUNCTION IS_SPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 発注先であるか
	FUNCTION IS_AP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 買掛先であるか
	FUNCTION IS_CRE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 入金先/支払先であるか
	FUNCTION IS_FIX_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 固定値(取引先区分=1)であるか
	FUNCTION IS_FIX_SPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 固定値(取引先区分=2)であるか
	FUNCTION IS_SO_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 相殺先(取引先区分=1)であるか
	FUNCTION IS_SO_SPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 相殺先(取引先区分=2)であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
