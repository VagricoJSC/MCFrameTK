CREATE OR REPLACE PACKAGE BODY MAC_UPRI_SET_TYP
/*****************************
評価単価設定区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION STD RETURN VARCHAR2 DETERMINISTIC IS -- 標準単価計算結果
	BEGIN RETURN '1'; END STD;
	FUNCTION AVG_PURC RETURN VARCHAR2 DETERMINISTIC IS -- 指定期間での平均仕入単価
	BEGIN RETURN '2'; END AVG_PURC;
	FUNCTION AVG_SLS RETURN VARCHAR2 DETERMINISTIC IS -- 指定期間での平均販売単価
	BEGIN RETURN '3'; END AVG_SLS;
	FUNCTION PREV_PURC RETURN VARCHAR2 DETERMINISTIC IS -- 指定期間での直近仕入単価
	BEGIN RETURN '4'; END PREV_PURC;
	FUNCTION PREV_SLS RETURN VARCHAR2 DETERMINISTIC IS -- 指定期間での直近販売単価
	BEGIN RETURN '5'; END PREV_SLS;

	FUNCTION IS_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準単価計算結果かどうか
	BEGIN
		IF I_VALUE = STD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD;

	FUNCTION IS_AVG_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指定期間での平均仕入単価かどうか
	BEGIN
		IF I_VALUE = AVG_PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AVG_PURC;

	FUNCTION IS_AVG_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指定期間での平均販売単価かどうか
	BEGIN
		IF I_VALUE = AVG_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AVG_SLS;

	FUNCTION IS_PREV_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指定期間での直近仕入単価かどうか
	BEGIN
		IF I_VALUE = PREV_PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PREV_PURC;

	FUNCTION IS_PREV_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指定期間での直近販売単価かどうか
	BEGIN
		IF I_VALUE = PREV_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PREV_SLS;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = STD
		OR I_VALUE = AVG_PURC
		OR I_VALUE = AVG_SLS
		OR I_VALUE = PREV_PURC
		OR I_VALUE = PREV_SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_UPRI_SET_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_UPRI_SET_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_UPRI_SET_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_UPRI_SET_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_UPRI_SET_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_UPRI_SET_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_UPRI_SET_TYP;
