	FUNCTION DNC1 RETURN VARCHAR2 DETERMINISTIC ; -- Ｎ対１
	FUNCTION D1CN RETURN VARCHAR2 DETERMINISTIC ; -- １対Ｎ
	FUNCTION OTHER RETURN VARCHAR2 DETERMINISTIC ; -- 制御しない

	FUNCTION IS_D1C1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- １対１であるか
	FUNCTION IS_DNC1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- Ｎ対１であるか
