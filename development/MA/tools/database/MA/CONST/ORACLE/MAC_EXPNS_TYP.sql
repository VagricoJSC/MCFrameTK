/*****************************
費目区分の定数定義パッケージ
*****************************/
IS

	FUNCTION PROD RETURN VARCHAR2 DETERMINISTIC ; -- 製造・売上原価費目
	FUNCTION SGA RETURN VARCHAR2 DETERMINISTIC ; -- 販売・一般管理費目
	FUNCTION SPPL RETURN VARCHAR2 DETERMINISTIC ; -- 有償差額費目

	FUNCTION IS_PROD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 製造・売上原価費目であるか
	FUNCTION IS_SGA(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 販売・一般管理費目であるか
