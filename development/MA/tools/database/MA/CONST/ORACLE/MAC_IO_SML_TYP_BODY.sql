CREATE OR REPLACE PACKAGE BODY MAC_IO_SML_TYP
/*****************************
受払集計単位区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION IO_TGT RETURN VARCHAR2 DETERMINISTIC IS -- 受払対象単位
	BEGIN RETURN '1'; END IO_TGT;
	FUNCTION AC_SLIP RETURN VARCHAR2 DETERMINISTIC IS -- 受払対象・会計伝票単位
	BEGIN RETURN '2'; END AC_SLIP;
	FUNCTION AC_RSN RETURN VARCHAR2 DETERMINISTIC IS -- 受払対象・会計伝票・会計理由単位
	BEGIN RETURN '3'; END AC_RSN;

	FUNCTION IS_IO_TGT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受払対象単位かどうか
	BEGIN
		IF I_VALUE = IO_TGT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IO_TGT;

	FUNCTION IS_AC_SLIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受払対象・会計伝票単位かどうか
	BEGIN
		IF I_VALUE = AC_SLIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_SLIP;

	FUNCTION IS_AC_RSN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受払対象・会計伝票・会計理由単位かどうか
	BEGIN
		IF I_VALUE = AC_RSN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_RSN;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = IO_TGT
		OR I_VALUE = AC_SLIP
		OR I_VALUE = AC_RSN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_IO_SML_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_IO_SML_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_IO_SML_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_IO_SML_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_IO_SML_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_IO_SML_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_IO_SML_TYP;
