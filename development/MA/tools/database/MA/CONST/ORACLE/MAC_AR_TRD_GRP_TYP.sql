	FUNCTION SLS_RTN RETURN VARCHAR2 DETERMINISTIC ; -- 売上返品
	FUNCTION SLS_DSCNT RETURN VARCHAR2 DETERMINISTIC ; -- 売上値引
	FUNCTION RCV RETURN VARCHAR2 DETERMINISTIC ; -- 入金
	FUNCTION SETOFF RETURN VARCHAR2 DETERMINISTIC ; -- 相殺
	FUNCTION ARSW RETURN VARCHAR2 DETERMINISTIC ; -- 債権残高振替
	FUNCTION TAX_DIFF RETURN VARCHAR2 DETERMINISTIC ; -- 税差額

	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 売上であるか
	FUNCTION IS_SLS_RTN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 売上返品であるか
	FUNCTION IS_SLS_DSCNT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 売上値引であるか
	FUNCTION IS_RCV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 入金であるか
	FUNCTION IS_SETOFF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 相殺であるか
