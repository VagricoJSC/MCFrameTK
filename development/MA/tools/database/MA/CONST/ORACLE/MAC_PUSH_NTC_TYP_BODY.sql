	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = APRV_RQST_MAIN
		OR I_VALUE = APRV_RQST_SUB
		OR I_VALUE = APRV_RESULT
		OR I_VALUE = APRV_DEPUTY
		OR I_VALUE = WG_RQST
		OR I_VALUE = WG_RQST_PRMS
		OR I_VALUE = MFG_INST_APRV_RQST
		OR I_VALUE = MFG_INST_APRV_RESULT
		OR I_VALUE = MFG_ACT_APRV_RQST
		OR I_VALUE = MFG_ACT_APRV_RESULT
		OR I_VALUE = INSP_APRV_RQST
		OR I_VALUE = INSP_APRV_RESULT
		OR I_VALUE = INSP_JUDG_RQST
		OR I_VALUE = INSP_JUDG_RESULT
		OR I_VALUE = PLNT_APRV_RQST
		OR I_VALUE = PLNT_APRV_RESULT
		OR I_VALUE = MRKT_JUDG_RQST
		OR I_VALUE = MRKT_JUDG_RESULT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

