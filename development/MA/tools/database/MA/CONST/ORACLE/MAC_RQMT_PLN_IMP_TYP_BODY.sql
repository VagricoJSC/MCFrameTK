CREATE OR REPLACE PACKAGE BODY MAC_RQMT_PLN_IMP_TYP
/*****************************
月次計画取込区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MLY_RQMT RETURN VARCHAR2 DETERMINISTIC IS -- 月次生産依頼
	BEGIN RETURN '1'; END MLY_RQMT;
	FUNCTION RQMT RETURN VARCHAR2 DETERMINISTIC IS -- 日次生産依頼
	BEGIN RETURN '2'; END RQMT;
	FUNCTION DMND RETURN VARCHAR2 DETERMINISTIC IS -- 日次需要情報
	BEGIN RETURN '3'; END DMND;
	FUNCTION DMND_RQMT RETURN VARCHAR2 DETERMINISTIC IS -- 日次生産依頼＋日次需要情報
	BEGIN RETURN '4'; END DMND_RQMT;
	FUNCTION PRCD_RQMT RETURN VARCHAR2 DETERMINISTIC IS -- 日次生産依頼＋先行手配日次生産依頼
	BEGIN RETURN '5'; END PRCD_RQMT;
	FUNCTION SIM_RQMT RETURN VARCHAR2 DETERMINISTIC IS -- シミュレーション用依頼
	BEGIN RETURN '6'; END SIM_RQMT;

	FUNCTION IS_MLY_RQMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月次生産依頼かどうか
	BEGIN
		IF I_VALUE = MLY_RQMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MLY_RQMT;

	FUNCTION IS_RQMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日次生産依頼かどうか
	BEGIN
		IF I_VALUE = RQMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RQMT;

	FUNCTION IS_DMND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日次需要情報かどうか
	BEGIN
		IF I_VALUE = DMND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DMND;

	FUNCTION IS_DMND_RQMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日次生産依頼＋日次需要情報かどうか
	BEGIN
		IF I_VALUE = DMND_RQMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DMND_RQMT;

	FUNCTION IS_PRCD_RQMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日次生産依頼＋先行手配日次生産依頼かどうか
	BEGIN
		IF I_VALUE = PRCD_RQMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRCD_RQMT;

	FUNCTION IS_SIM_RQMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- シミュレーション用依頼かどうか
	BEGIN
		IF I_VALUE = SIM_RQMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SIM_RQMT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MLY_RQMT
		OR I_VALUE = RQMT
		OR I_VALUE = DMND
		OR I_VALUE = DMND_RQMT
		OR I_VALUE = PRCD_RQMT
		OR I_VALUE = SIM_RQMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_RQMT_PLN_IMP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_RQMT_PLN_IMP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_RQMT_PLN_IMP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_RQMT_PLN_IMP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_RQMT_PLN_IMP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_RQMT_PLN_IMP_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_RQMT_PLN_IMP_TYP;
