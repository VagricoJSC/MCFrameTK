CREATE OR REPLACE PACKAGE BODY MAC_DATA_TYP
/*****************************
データ状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ERR RETURN VARCHAR2 DETERMINISTIC IS -- 仕訳処理エラー
	BEGIN RETURN '1'; END ERR;
	FUNCTION JNL_MK RETURN VARCHAR2 DETERMINISTIC IS -- 仕訳作成済み
	BEGIN RETURN '2'; END JNL_MK;
	FUNCTION AC_MK RETURN VARCHAR2 DETERMINISTIC IS -- 送信済み
	BEGIN RETURN '3'; END AC_MK;

	FUNCTION IS_ERR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 仕訳処理エラーかどうか
	BEGIN
		IF I_VALUE = ERR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ERR;

	FUNCTION IS_JNL_MK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 仕訳作成済みかどうか
	BEGIN
		IF I_VALUE = JNL_MK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_JNL_MK;

	FUNCTION IS_AC_MK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 送信済みかどうか
	BEGIN
		IF I_VALUE = AC_MK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_MK;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ERR
		OR I_VALUE = JNL_MK
		OR I_VALUE = AC_MK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_DATA_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_DATA_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_DATA_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_DATA_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_DATA_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_DATA_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_DATA_TYP;
