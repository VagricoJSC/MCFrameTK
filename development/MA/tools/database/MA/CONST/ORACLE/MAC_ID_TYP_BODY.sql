	BEGIN
		IF I_VALUE = PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC;

	FUNCTION IS_AP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 債務部門かどうか
	BEGIN
		IF I_VALUE = AP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AP;

	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上部門かどうか
