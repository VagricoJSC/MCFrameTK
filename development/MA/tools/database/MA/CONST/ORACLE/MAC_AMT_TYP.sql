CREATE OR REPLACE PACKAGE MAC_AMT_TYP
/*****************************
仕訳金額区分の定数定義パッケージ
*****************************/
IS

	FUNCTION ZERO RETURN VARCHAR2 DETERMINISTIC ; -- 金額は0とする
	FUNCTION AMT_TAX RETURN VARCHAR2 DETERMINISTIC ; -- 税抜(評価)金額(税額は別項目に出力)
	FUNCTION AMT_ONLY RETURN VARCHAR2 DETERMINISTIC ; -- 税抜(評価)金額(税額は出力しない)
	FUNCTION TAX_IN_AMT RETURN VARCHAR2 DETERMINISTIC ; -- 税金額(金額項目に出力)
	FUNCTION TAX_IN_TAX RETURN VARCHAR2 DETERMINISTIC ; -- 税金額(税額項目に出力)
	FUNCTION SML RETURN VARCHAR2 DETERMINISTIC ; -- 税抜金額 + 税金額
	FUNCTION STD RETURN VARCHAR2 DETERMINISTIC ; -- 標準評価金額
	FUNCTION AMT_STD RETURN VARCHAR2 DETERMINISTIC ; -- 税抜(評価)金額 - 標準評価金額
	FUNCTION NON_JNL RETURN VARCHAR2 DETERMINISTIC ; -- 仕訳対象外
	FUNCTION PROC_AMT_TAX RETURN VARCHAR2 DETERMINISTIC ; -- 加工金額(税額は別項目に出力)
	FUNCTION PROC_AMT_ONLY RETURN VARCHAR2 DETERMINISTIC ; -- 加工金額(税額は出力しない)
	FUNCTION PROC_SML RETURN VARCHAR2 DETERMINISTIC ; -- 加工金額 + 税金額
	FUNCTION ONR_PROV_AMT RETURN VARCHAR2 DETERMINISTIC ; -- 有償支給金額

	FUNCTION IS_ZERO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 金額は0とするであるか
	FUNCTION IS_AMT_TAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 税抜(評価)金額(税額は別項目に出力)であるか
	FUNCTION IS_AMT_ONLY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 税抜(評価)金額(税額は出力しない)であるか
	FUNCTION IS_TAX_IN_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 税金額(金額項目に出力)であるか
	FUNCTION IS_TAX_IN_TAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 税金額(税額項目に出力)であるか
	FUNCTION IS_SML(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 税抜金額 + 税金額であるか
	FUNCTION IS_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 標準評価金額であるか
	FUNCTION IS_AMT_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 税抜(評価)金額 - 標準評価金額であるか
	FUNCTION IS_NON_JNL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 仕訳対象外であるか
	FUNCTION IS_PROC_AMT_TAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 加工金額(税額は別項目に出力)であるか
	FUNCTION IS_PROC_AMT_ONLY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 加工金額(税額は出力しない)であるか
	FUNCTION IS_PROC_SML(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 加工金額 + 税金額であるか
	FUNCTION IS_ONR_PROV_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 有償支給金額であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
