	FUNCTION IO RETURN VARCHAR2 DETERMINISTIC ; -- 入出庫
	FUNCTION SLS RETURN VARCHAR2 DETERMINISTIC ; -- 売上
	FUNCTION IO_IN RETURN VARCHAR2 DETERMINISTIC ; -- 入出庫（入庫）
	FUNCTION IO_OUT RETURN VARCHAR2 DETERMINISTIC ; -- 入出庫（出庫）

	FUNCTION IS_INPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 投入であるか
	FUNCTION IS_IO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 入出庫であるか
	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 売上であるか
