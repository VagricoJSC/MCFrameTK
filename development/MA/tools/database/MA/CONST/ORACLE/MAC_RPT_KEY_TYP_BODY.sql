		IF I_VALUE = ITM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM;

	FUNCTION IS_ITM_JNL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目仕訳かどうか
	BEGIN
		IF I_VALUE = ITM_JNL THEN
			RETURN '1';
		END IF;
