	BEGIN
		IF I_VALUE = GRP10 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP10;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MNG_DPT
		OR I_VALUE = WG
		OR I_VALUE = ITM
		OR I_VALUE = ITM_JNL
		OR I_VALUE = GRP1
		OR I_VALUE = GRP2
		OR I_VALUE = GRP3
		OR I_VALUE = GRP4
		OR I_VALUE = GRP5
		OR I_VALUE = GRP6
		OR I_VALUE = GRP7
		OR I_VALUE = GRP8
		OR I_VALUE = GRP9
		OR I_VALUE = GRP10 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION ITM_GRP(
		I_RPT_KEY_TYP IN VARCHAR2
	)RETURN VARCHAR2
	 DETERMINISTIC IS
	BEGIN
		IF (I_RPT_KEY_TYP = MNG_DPT) THEN
			RETURN NULL;
		ELSIF (I_RPT_KEY_TYP = WG) THEN
			RETURN NULL;
		ELSIF (I_RPT_KEY_TYP = ITM) THEN
			RETURN NULL;
		ELSIF (I_RPT_KEY_TYP = ITM_JNL) THEN
			RETURN NULL;
		ELSIF (I_RPT_KEY_TYP = GRP1) THEN
			RETURN MAC_ITM_GRP_TYP.GRP1();
		ELSIF (I_RPT_KEY_TYP = GRP2) THEN
			RETURN MAC_ITM_GRP_TYP.GRP2();
		ELSIF (I_RPT_KEY_TYP = GRP3) THEN
			RETURN MAC_ITM_GRP_TYP.GRP3();
		ELSIF (I_RPT_KEY_TYP = GRP4) THEN
			RETURN MAC_ITM_GRP_TYP.GRP4();
		ELSIF (I_RPT_KEY_TYP = GRP5) THEN
			RETURN MAC_ITM_GRP_TYP.GRP5();
		ELSIF (I_RPT_KEY_TYP = GRP6) THEN
			RETURN MAC_ITM_GRP_TYP.GRP6();
		ELSIF (I_RPT_KEY_TYP = GRP7) THEN
			RETURN MAC_ITM_GRP_TYP.GRP7();
		ELSIF (I_RPT_KEY_TYP = GRP8) THEN
			RETURN MAC_ITM_GRP_TYP.GRP8();
		ELSIF (I_RPT_KEY_TYP = GRP9) THEN
			RETURN MAC_ITM_GRP_TYP.GRP9();
		ELSIF (I_RPT_KEY_TYP = GRP10) THEN
			RETURN MAC_ITM_GRP_TYP.GRP10();
		ELSE
			RETURN NULL;
		END IF;
	END ITM_GRP;

