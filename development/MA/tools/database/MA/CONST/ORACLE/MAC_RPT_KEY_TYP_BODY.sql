	BEGIN RETURN 'E'; END GRP5;
	FUNCTION GRP6 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類６
	BEGIN RETURN 'F'; END GRP6;
	FUNCTION GRP7 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類７
	BEGIN RETURN 'G'; END GRP7;
	FUNCTION GRP8 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類８
	BEGIN RETURN 'H'; END GRP8;
	FUNCTION GRP9 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類９
	BEGIN RETURN 'I'; END GRP9;
