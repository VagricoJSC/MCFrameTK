	END IS_GRP3;

	FUNCTION IS_GRP4(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類４かどうか
	BEGIN
		IF I_VALUE = GRP4 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP4;

	FUNCTION IS_GRP5(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類５かどうか
	BEGIN
