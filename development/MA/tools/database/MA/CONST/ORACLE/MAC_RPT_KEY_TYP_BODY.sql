			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP5;

	FUNCTION IS_GRP6(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類６かどうか
	BEGIN
		IF I_VALUE = GRP6 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP6;

	FUNCTION IS_GRP7(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類７かどうか
	BEGIN
		IF I_VALUE = GRP7 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP7;

	FUNCTION IS_GRP8(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類８かどうか
	BEGIN
		IF I_VALUE = GRP8 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP8;

	FUNCTION IS_GRP9(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類９かどうか
