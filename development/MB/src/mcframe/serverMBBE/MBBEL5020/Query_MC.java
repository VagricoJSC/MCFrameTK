	/**
	 * -- MBBEL5020_MBT_BP_SND_IF_EXT_Query_I01
	 */
	static MCQueryPlan MBBEL5020_MBT_BP_SND_IF_EXT_I01() {
		MBT_BP_SND_IF_EXT_R S0 = MBT_BP_SND_IF_EXT_R.create();
		MCTempView S1_BP = createTempView("BP");
		MCTempView S1_IFBP = createTempView("IFBP");
		MAM_BP_R S2_BP = MAM_BP_R.create("BP");
		MAM_BP_SUB_R S2_SUB = MAM_BP_SUB_R.create("SUB");
		MAM_BP_LCL_R S2_LCL = MAM_BP_LCL_R.create("LCL");
		MCTempView S3_BASE = createTempView("BASE");
		MBT_BP_SND_IF_EXT_R S3_SUB = MBT_BP_SND_IF_EXT_R.create("SUB");
		MBT_BP_SND_IF_EXT_R S4 = MBT_BP_SND_IF_EXT_R.create();
		
		
		return createQueryPlan()
			.setQuery(
				sql("MBBEL5020_MBT_BP_SND_IF_EXT_Query_I01")
					.insert(S0)
					.columns(
						S0.data_lno,
						S0.data_no,
						S0.exe_sts_typ,
						S0.data_crud_typ,
						S0.ext_sys_cd,
						S0.ext_master_typ,
						S0.bp_cd
					)
					.query(
						subQuery()
						.select(
							MAPA_NUM$F_GET_SEQ(value("MBS_BP_SND_IF_EXT_DATA_LNO")),
							bind("data_no"),
							value(MAC_EXE_STS_TYP.NOT_EXE.value()),
							cases()
								.when(
									S1_BP.pr(S2_BP.bp_cd).isNotNull()
									.and(
										S1_IFBP.pr(S4.bp_cd).isNull()
										.or(S1_IFBP.pr(S3_SUB.data_crud_typ).eq(value(MAC_DATA_CRUD_TYP.DEL.value())))
									)
								)
									.then(value(MAC_DATA_CRUD_TYP.CRT.value()))
								.when(
									S1_BP.pr(S2_BP.bp_cd).isNull()
									.and(S1_IFBP.pr(S4.bp_cd).isNotNull())
								)
									.then(value(MAC_DATA_CRUD_TYP.DEL.value()))
								.otherwise(value(MAC_DATA_CRUD_TYP.UPD.value())).as("data_crud_typ"),
							bind("ext_sys_cd"),
							bind("ext_master_typ"),
							cases()
								.when(S1_BP.pr(S2_BP.bp_cd).isNotNull())
									.then(S1_BP.pr(S2_BP.bp_cd))
								.otherwise(S1_IFBP.pr(S4.bp_cd)).as("bp_cd")
						)
						.from(
							subQuery()
							.select(
								S2_BP.bp_cd,
								greatest(
									max(S2_BP.upd_ts),
									max(
										nvl(
											S2_SUB.upd_ts,
											toTimestamp(
												value("1900-01-01"),
												MCDateTimeFmt.YYYY,
												MCDateTimeFmt.HYPHEN,
												MCDateTimeFmt.MM,
												MCDateTimeFmt.HYPHEN,
												MCDateTimeFmt.DD
											)
										)
									),
									max(
										nvl(
											S2_LCL.upd_ts,
											toTimestamp(
												value("1900-01-01"),
												MCDateTimeFmt.YYYY,
												MCDateTimeFmt.HYPHEN,
												MCDateTimeFmt.MM,
												MCDateTimeFmt.HYPHEN,
												MCDateTimeFmt.DD
											)
										)
									)
								).as("upd_ts")
							)
							.from(
								S2_BP
								.leftOuterJoin(S2_SUB).on(S2_BP.bp_cd.eq(S2_SUB.bp_cd))
								.leftOuterJoin(S2_LCL).on(S2_BP.bp_cd.eq(S2_LCL.bp_cd))
							)
							.where(
								S2_BP.cst_flg.eq(value(true))
							)
							.groupBy(S2_BP.bp_cd).view(S1_BP)
							.fullOuterJoin(
								subQuery()
								.select(
									S3_BASE.pr(S4.ext_master_typ),
									S3_BASE.pr(S4.bp_cd),
									S3_BASE.pr("ins_ts"),
									S3_SUB.exe_sts_typ,
									S3_SUB.data_crud_typ
								)
								.from(
									subQuery()
									.select(
										S4.ext_sys_cd,
										S4.ext_master_typ,
										S4.bp_cd,
										max(S4.ins_ts).as("ins_ts")
									)
									.from(S4)
									.where(
										S4.ext_sys_cd.eq(bind("ext_sys_cd"))
										.and(S4.ext_master_typ.eq(value(MAC_EXT_MASTER_TYP.CST_BP.value())))
									)
									.groupBy(
										S4.ext_sys_cd,
										S4.ext_master_typ,
										S4.bp_cd
									).view(S3_BASE)
									.innerJoin(S3_SUB).on(
										S3_BASE.pr(S4.ext_sys_cd).eq(S3_SUB.ext_sys_cd)
										.and(S3_BASE.pr(S4.ext_master_typ).eq(S3_SUB.ext_master_typ))
										.and(S3_BASE.pr(S4.bp_cd).eq(S3_SUB.bp_cd))
										.and(S3_BASE.pr("ins_ts").eq(S3_SUB.ins_ts))
									)
								).view(S1_IFBP)
							).on(S1_BP.pr(S2_BP.bp_cd).eq(S1_IFBP.pr(S4.bp_cd)))
						)
						.where(
							bracket(
								S1_BP.pr(S2_BP.bp_cd).isNotNull()
								.and(
									S1_IFBP.pr(S4.ext_master_typ).isNull()
									.or(
										S1_IFBP.pr(S3_SUB.exe_sts_typ).eq(value(MAC_EXE_STS_TYP.OK.value()))
										.and(S1_IFBP.pr(S3_SUB.data_crud_typ).eq(value(MAC_DATA_CRUD_TYP.DEL.value())))
									)
								)
							)
							.or(
								S1_BP.pr(S2_BP.bp_cd).isNull()
								.and(S1_IFBP.pr(S3_SUB.exe_sts_typ).eq(value(MAC_EXE_STS_TYP.OK.value())))
								.and(S1_IFBP.pr(S3_SUB.data_crud_typ).neq(value(MAC_DATA_CRUD_TYP.DEL.value())))
							)
							.or(
								S1_BP.pr(S2_BP.bp_cd).isNotNull()
								.and(S1_IFBP.pr(S3_SUB.exe_sts_typ).eq(value(MAC_EXE_STS_TYP.OK.value())))
								.and(S1_BP.pr("upd_ts").gt(S1_IFBP.pr("ins_ts")))
								.and(S1_IFBP.pr(S3_SUB.data_crud_typ).neq(value(MAC_DATA_CRUD_TYP.DEL.value())))
							)
						)
						.orderBy(
							S1_BP.pr(S2_BP.bp_cd).asc(),
							S1_IFBP.pr(S4.bp_cd).asc()
						)
					)
			);
	}
	
