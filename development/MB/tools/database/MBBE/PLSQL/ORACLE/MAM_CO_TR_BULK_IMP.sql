CREATE OR REPLACE TRIGGER MAM_CO_TR_BULK_IMP
BEFORE INSERT OR DELETE OR UPDATE
ON MAM_CO_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW 
BEGIN
	IF INSERTING THEN
		MBPA_BULK_IMP.P_INIT_BULK_IMP(:NEW.CO_CD) ;
	ELSIF UPDATING THEN
		IF :OLD.CO_CD <> :NEW.CO_CD THEN
			MBPA_BULK_IMP.P_INIT_BULK_IMP(:NEW.CO_CD) ;
		END IF ;
	ELSIF DELETING THEN
		MBPA_BULK_IMP.P_DEL_BULK_IMP(:OLD.CO_CD) ;
	END IF ;
END ;
/
