\encoding UTF-8

CREATE OR REPLACE VIEW mgvt_mst_rqmt(
rqmt_no,
itm_cd,
itm_sub1,
itm_sub2,
itm_sub3,
strg_loc_cd,
due_dt,
rqmt_qty,
mfg_loc_cd,
sppl_cd,
rqst_loc_cd,
fix_flg,
sno1,
sno2,
sno3,
sno4,
wg_cd,
rqmt_gnrt_typ,
rqmt_typ,
intr_rmrks,
sub_char1,
sub_char2,
sub_char3,
ins_usr_id,
ins_usr_nm,
ins_ts,
ins_func_id,
upd_cntr,
upd_usr_id,
upd_usr_nm,
upd_ts,
upd_func_id,
upd_srv_req_no
)
AS
SELECT
	null::varchar (15) AS rqmt_no,
	null::varchar (40) AS itm_cd,
	null::varchar (5) AS itm_sub1,
	null::varchar (5) AS itm_sub2,
	null::varchar (5) AS itm_sub3,
	null::varchar (20) AS strg_loc_cd,
	null::timestamp(0) AS due_dt,
	null::numeric (21,8) AS rqmt_qty,
	null::varchar (20) AS mfg_loc_cd,
	null::varchar (20) AS sppl_cd,
	null::varchar (20) AS rqst_loc_cd,
	null::char (1) AS fix_flg,
	null::varchar (15) AS sno1,
	null::varchar (15) AS sno2,
	null::varchar (15) AS sno3,
	null::varchar (15) AS sno4,
	null::varchar (10) AS wg_cd,
	null::varchar (1) AS rqmt_gnrt_typ,
	null::varchar (1) AS rqmt_typ,
	null::varchar (100) AS intr_rmrks,
	null::varchar (20) AS sub_char1,
	null::varchar (20) AS sub_char2,
	null::varchar (20) AS sub_char3,
	null::varchar (500) AS ins_usr_id,
	null::varchar (100) AS ins_usr_nm,
	null::timestamp(3) AS ins_ts,
	null::varchar (50) AS ins_func_id,
	null::numeric (9,0) AS upd_cntr,
	null::varchar (500) AS upd_usr_id,
	null::varchar (100) AS upd_usr_nm,
	null::timestamp(3) AS upd_ts,
	null::varchar (50) AS upd_func_id,
	null::varchar (50) AS upd_srv_req_no
;;

