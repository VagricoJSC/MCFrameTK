SELECT	t1.ST_WIP_KEY,
	t1.EXPNS_CD,
	t2.ITM_CD,
	t2.ITM_SUB1,
	t2.ITM_SUB2,
	t2.ITM_SUB3,
	t2.ITM_EXT,
	t2.WG_CD,
	t1.WIP_AMT,
	t1.INPT_AMT
FROM	MGW_ARG w1, MGT_ST_WIP_EXPNS t1, MGVT_ST_WIP t2
WHERE	0=0
AND	w1.COST_CALC_TYP IN (MAC_COST_CALC_TYP.CALC_STK, MAC_COST_CALC_TYP.NOT_STK)
AND	t1.ST_WIP_KEY = t2.ST_WIP_KEY
AND	(t1.WIP_AMT <> 0 OR t1.INPT_AMT <> 0)
/
