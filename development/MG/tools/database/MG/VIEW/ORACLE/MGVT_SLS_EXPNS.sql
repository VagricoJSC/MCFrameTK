SELECT	t1.ACT_SLS_ID,
	t1.ACT_SLS_ID_SUB,
	t1.EXPNS_CD,
	t2.ITM_CD,
	t2.ITM_SUB1,
	t2.ITM_SUB2,
	t2.ITM_SUB3,
	t2.ITM_EXT,
	t2.WG_CD,
	t1.AMT
FROM	MGW_ARG w1, MGT_ACT_SLS_EXPNS t1, MGVT_SLS t2
WHERE	0=0
AND	w1.SA_TYP = MAC_SA_TYP.ACT
AND	t1.ACT_SLS_ID = t2.ACT_SLS_ID
AND	t1.ACT_SLS_ID_SUB = t2.ACT_SLS_ID_SUB
AND	t2.REC_EVAL_TYP = MGC_REC_EVAL_TYP.EXPNS
AND	t1.AMT <> 0
/
