SELECT	t2.WG_CD,
	t1.ST_STK_KEY,
	t1.EXPNS_CD,
	t2.ITM_CD,
	t2.ITM_SUB1,
	t2.ITM_SUB2,
	t2.ITM_SUB3,
	t2.ITM_EXT,
	t1.AMT
FROM	MGW_ARG w1, MGT_ST_STK_EXPNS t1, MGVT_ST_STK t2
WHERE	0=0
AND	w1.COST_CALC_TYP = MAC_COST_CALC_TYP.CALC_STK
AND	t1.ST_STK_KEY = t2.ST_STK_KEY
AND	t1.AMT <> 0
