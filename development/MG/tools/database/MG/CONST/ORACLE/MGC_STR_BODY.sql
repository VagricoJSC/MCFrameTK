CREATE OR REPLACE PACKAGE BODY MGC_STR
/*****************************
文字列用定数の定数定義パッケージ本体
******************************/
IS

	FUNCTION ACT_ID_DLM RETURN VARCHAR2 DETERMINISTIC IS -- 区切り文字１
	BEGIN RETURN '-'; END ACT_ID_DLM;
	FUNCTION CHK_STR_DLM RETURN VARCHAR2 DETERMINISTIC IS -- 区切り文字２
	BEGIN RETURN '#'; END CHK_STR_DLM;
	FUNCTION COL_DLM RETURN VARCHAR2 DETERMINISTIC IS -- 区切り文字３
	BEGIN RETURN '^'; END COL_DLM;
	FUNCTION ITM_DLM RETURN VARCHAR2 DETERMINISTIC IS -- 品目区切り文字
	BEGIN RETURN ':'; END ITM_DLM;
	FUNCTION ITM_MFG_INST_NO_PREFIX RETURN VARCHAR2 DETERMINISTIC IS -- 品目製造指図ＮＯ用接頭語（負担品目）
	BEGIN RETURN 'G'; END ITM_MFG_INST_NO_PREFIX;
	FUNCTION ITM_MFG_INST_NO_PREFIX2 RETURN VARCHAR2 DETERMINISTIC IS -- 品目製造指図ＮＯ用接頭語（工数）
	BEGIN RETURN 'W'; END ITM_MFG_INST_NO_PREFIX2;
	FUNCTION ITM_MFG_INST_NO_PREFIX3 RETURN VARCHAR2 DETERMINISTIC IS -- 品目製造指図ＮＯ用接頭語（場所指定）
	BEGIN RETURN 'L'; END ITM_MFG_INST_NO_PREFIX3;
	FUNCTION TRD_PREFIX RETURN VARCHAR2 DETERMINISTIC IS -- 振替Ｇ用接頭語（振替用部門）
	BEGIN RETURN 'T'; END TRD_PREFIX;
	FUNCTION TRD_PREFIX2 RETURN VARCHAR2 DETERMINISTIC IS -- 振替Ｇ用接頭語（在庫振替）
	BEGIN RETURN 'S'; END TRD_PREFIX2;
	FUNCTION TRD_PREFIX3 RETURN VARCHAR2 DETERMINISTIC IS -- 振替Ｇ用接頭語（在庫振替以外）
	BEGIN RETURN 'G'; END TRD_PREFIX3;

	FUNCTION IS_ACT_ID_DLM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 区切り文字１かどうか
	BEGIN
		IF I_VALUE = ACT_ID_DLM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACT_ID_DLM;

	FUNCTION IS_CHK_STR_DLM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 区切り文字２かどうか
	BEGIN
		IF I_VALUE = CHK_STR_DLM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CHK_STR_DLM;

	FUNCTION IS_COL_DLM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 区切り文字３かどうか
	BEGIN
		IF I_VALUE = COL_DLM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_COL_DLM;

	FUNCTION IS_ITM_DLM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目区切り文字かどうか
	BEGIN
		IF I_VALUE = ITM_DLM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_DLM;

	FUNCTION IS_ITM_MFG_INST_NO_PREFIX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目製造指図ＮＯ用接頭語（負担品目）かどうか
	BEGIN
		IF I_VALUE = ITM_MFG_INST_NO_PREFIX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_MFG_INST_NO_PREFIX;

	FUNCTION IS_ITM_MFG_INST_NO_PREFIX2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目製造指図ＮＯ用接頭語（工数）かどうか
	BEGIN
		IF I_VALUE = ITM_MFG_INST_NO_PREFIX2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_MFG_INST_NO_PREFIX2;

	FUNCTION IS_ITM_MFG_INST_NO_PREFIX3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目製造指図ＮＯ用接頭語（場所指定）かどうか
	BEGIN
		IF I_VALUE = ITM_MFG_INST_NO_PREFIX3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_MFG_INST_NO_PREFIX3;

	FUNCTION IS_TRD_PREFIX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 振替Ｇ用接頭語（振替用部門）かどうか
	BEGIN
		IF I_VALUE = TRD_PREFIX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TRD_PREFIX;

	FUNCTION IS_TRD_PREFIX2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 振替Ｇ用接頭語（在庫振替）かどうか
	BEGIN
		IF I_VALUE = TRD_PREFIX2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TRD_PREFIX2;

	FUNCTION IS_TRD_PREFIX3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 振替Ｇ用接頭語（在庫振替以外）かどうか
	BEGIN
		IF I_VALUE = TRD_PREFIX3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TRD_PREFIX3;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ACT_ID_DLM
		OR I_VALUE = CHK_STR_DLM
		OR I_VALUE = COL_DLM
		OR I_VALUE = ITM_DLM
		OR I_VALUE = ITM_MFG_INST_NO_PREFIX
		OR I_VALUE = ITM_MFG_INST_NO_PREFIX2
		OR I_VALUE = ITM_MFG_INST_NO_PREFIX3
		OR I_VALUE = TRD_PREFIX
		OR I_VALUE = TRD_PREFIX2
		OR I_VALUE = TRD_PREFIX3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MGC_STR', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MGC_STR', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MGC_STR', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MGC_STR', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MGC_STR', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MGC_STR', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MGC_STR;
/