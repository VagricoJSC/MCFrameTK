CREATE OR REPLACE PACKAGE BODY MGC_INPT_ALC_TYP
/*****************************
入力費用区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ALC_AMT RETURN VARCHAR2 DETERMINISTIC IS -- 配賦費用
	BEGIN RETURN '1'; END ALC_AMT;
	FUNCTION PRE_ALC RETURN VARCHAR2 DETERMINISTIC IS -- 一次配賦
	BEGIN RETURN '2'; END PRE_ALC;
	FUNCTION ALC_RATE RETURN VARCHAR2 DETERMINISTIC IS -- 予定配賦率
	BEGIN RETURN '3'; END ALC_RATE;
	FUNCTION STD_RATE RETURN VARCHAR2 DETERMINISTIC IS -- 標準配賦率
	BEGIN RETURN '4'; END STD_RATE;
	FUNCTION SO_ALC RETURN VARCHAR2 DETERMINISTIC IS -- 出庫振替
	BEGIN RETURN '5'; END SO_ALC;
	FUNCTION WK_ALC RETURN VARCHAR2 DETERMINISTIC IS -- 工数振替
	BEGIN RETURN '6'; END WK_ALC;

	FUNCTION IS_ALC_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 配賦費用かどうか
	BEGIN
		IF I_VALUE = ALC_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALC_AMT;

	FUNCTION IS_PRE_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一次配賦かどうか
	BEGIN
		IF I_VALUE = PRE_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRE_ALC;

	FUNCTION IS_ALC_RATE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 予定配賦率かどうか
	BEGIN
		IF I_VALUE = ALC_RATE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALC_RATE;

	FUNCTION IS_STD_RATE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準配賦率かどうか
	BEGIN
		IF I_VALUE = STD_RATE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD_RATE;

	FUNCTION IS_SO_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出庫振替かどうか
	BEGIN
		IF I_VALUE = SO_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SO_ALC;

	FUNCTION IS_WK_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工数振替かどうか
	BEGIN
		IF I_VALUE = WK_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WK_ALC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ALC_AMT
		OR I_VALUE = PRE_ALC
		OR I_VALUE = ALC_RATE
		OR I_VALUE = STD_RATE
		OR I_VALUE = SO_ALC
		OR I_VALUE = WK_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MGC_INPT_ALC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MGC_INPT_ALC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MGC_INPT_ALC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MGC_INPT_ALC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MGC_INPT_ALC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MGC_INPT_ALC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MGC_INPT_ALC_TYP;
