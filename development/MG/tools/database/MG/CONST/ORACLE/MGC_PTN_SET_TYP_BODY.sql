CREATE OR REPLACE PACKAGE BODY MGC_PTN_SET_TYP
/*****************************
構成/工程パタン設定区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ITM RETURN VARCHAR2 DETERMINISTIC IS -- 同一品目は同じパタンとする
	BEGIN RETURN '1'; END ITM;
	FUNCTION IN_OUT RETURN VARCHAR2 DETERMINISTIC IS -- 同一品目でも内製・外製でパタンを分ける
	BEGIN RETURN '2'; END IN_OUT;
	FUNCTION LOC RETURN VARCHAR2 DETERMINISTIC IS -- 場所毎にパタンを分ける
	BEGIN RETURN '3'; END LOC;

	FUNCTION IS_ITM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 同一品目は同じパタンとするかどうか
	BEGIN
		IF I_VALUE = ITM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM;

	FUNCTION IS_IN_OUT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 同一品目でも内製・外製でパタンを分けるかどうか
	BEGIN
		IF I_VALUE = IN_OUT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IN_OUT;

	FUNCTION IS_LOC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 場所毎にパタンを分けるかどうか
	BEGIN
		IF I_VALUE = LOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ITM
		OR I_VALUE = IN_OUT
		OR I_VALUE = LOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MGC_PTN_SET_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MGC_PTN_SET_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MGC_PTN_SET_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MGC_PTN_SET_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MGC_PTN_SET_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MGC_PTN_SET_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MGC_PTN_SET_TYP;
