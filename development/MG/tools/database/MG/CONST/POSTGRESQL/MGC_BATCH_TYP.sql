CREATE OR REPLACE FUNCTION MGC_BATCH_TYP$BATCH_NM(
		IN I_BATCH_TYP VARCHAR
)RETURNS VARCHAR
 AS
$BODY$ BEGIN
	IF (I_BATCH_TYP = MGC_BATCH_TYP$WIP_LOC()) THEN
		RETURN 'MGPA_WIP_LOC$P_MAIN';
	ELSIF (I_BATCH_TYP = MGC_BATCH_TYP$IO()) THEN
