CREATE OR REPLACE PROCEDURE MGC_BATCH_TYP$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF MGC_BATCH_TYP$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
