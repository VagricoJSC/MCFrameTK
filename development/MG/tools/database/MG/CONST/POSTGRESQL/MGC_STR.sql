CREATE OR REPLACE FUNCTION MGC_STR$CONTAINS(IN I_VALUE VARCHAR) RETURNS CHAR(1) AS -- 定数に含まれるかどうか
$BODY$ BEGIN
	IF I_VALUE = MGC_STR$ACT_ID_DLM()
	OR I_VALUE = MGC_STR$CHK_STR_DLM()
	OR I_VALUE = MGC_STR$COL_DLM()
	OR I_VALUE = MGC_STR$ITM_DLM()
	OR I_VALUE = MGC_STR$ITM_MFG_INST_NO_PREFIX()
	OR I_VALUE = MGC_STR$ITM_MFG_INST_NO_PREFIX2()
	OR I_VALUE = MGC_STR$ITM_MFG_INST_NO_PREFIX3()
	OR I_VALUE = MGC_STR$TRD_PREFIX()
	OR I_VALUE = MGC_STR$TRD_PREFIX2()
	OR I_VALUE = MGC_STR$TRD_PREFIX3() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE MGC_STR$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF MGC_STR$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
