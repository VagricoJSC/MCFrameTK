SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVT_INPT_EXPNS(
	ACT_INPT_ID,
	ACT_INPT_ID_SUB,
	EXPNS_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	WG_CD,
	AMT
)
AS
SELECT	t1.ACT_INPT_ID,
	t1.ACT_INPT_ID_SUB,
	t1.EXPNS_CD,
	t2.PAR_ITM_CD	ITM_CD,
	t2.PAR_ITM_SUB1	ITM_SUB1,
	t2.PAR_ITM_SUB2	ITM_SUB2,
	t2.PAR_ITM_SUB3	ITM_SUB3,
	t2.PAR_ITM_EXT	ITM_EXT,
	t2.WG_CD,
	t1.AMT
FROM	MGW_ARG w1, MGT_ACT_INPT_EXPNS t1, MGVT_INPT t2
WHERE	0=0
AND	w1.SA_TYP = MAC_SA_TYP.ACT
AND	t1.ACT_INPT_ID = t2.ACT_INPT_ID
AND	t1.ACT_INPT_ID_SUB = t2.ACT_INPT_ID_SUB
AND	t2.REC_EVAL_TYP = MGC_REC_EVAL_TYP.EXPNS
AND	t1.AMT <> 0
;

