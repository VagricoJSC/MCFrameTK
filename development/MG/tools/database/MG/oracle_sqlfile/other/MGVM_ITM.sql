CREATE OR REPLACE VIEW MGVM_ITM(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	WG_CD,
	ITM_TYP,
	CALC_PTN_CD,
	STD_QTY,
	RND_TYP,
	DEC_PLACE
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.WG_CD,
	DECODE(m1.ASSET_MNG_TYP, MAC_ASSET_MNG_TYP.MNG, '0', '1')	ITM_TYP,
	t1.CALC_PTN_CD,
	t1.STD_QTY,
	MAC_RND_TYP.RNDUP	RND_TYP, --切り上げ固定,
	NVL(m1.DEC_PLACE, 2)	DEC_PLACE
FROM	MGW_ARG w1, MGT_CALC_ITM t1, MAM_ITM_CMN_ m1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
AND	t1.ITM_CD = m1.ITM_CD
AND	t1.ITM_SUB1 = m1.ITM_SUB1
AND	t1.ITM_SUB2 = m1.ITM_SUB2
AND	t1.ITM_SUB3 = m1.ITM_SUB3
;

