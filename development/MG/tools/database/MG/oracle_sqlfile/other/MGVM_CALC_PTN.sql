CREATE OR REPLACE VIEW MGVM_CALC_PTN(
	CALC_PTN_CD,
	MFG_PURC_TYP,
	EVAL_TYP,
	DPT_TYP,
	LOT_TYP,
	SUBLOT_TYP,
	SNO1_TYP,
	SNO2_TYP,
	SNO3_TYP,
	SNO4_TYP,
	LOT_EXP_TYP,
	SUBLOT_EXP_TYP,
	SNO1_EXP_TYP,
	SNO2_EXP_TYP,
	SNO3_EXP_TYP,
	SNO4_EXP_TYP,
	STD_RND_TYP,
	STD_DEC_PLACE,
	AMT_RND_TYP,
	AMT_DEC_PLACE,
	AVE_RND_TYP,
	AVE_DEC_PLACE,
	ADJ_TYP,
	WIP_TYP,
	BD_AGG_TYP,
	MRGN_EXPNS_CD,
	PURC_EXPNS_CD,
	OUT_EXPNS_CD,
	INPT_EXPNS_CD,
	SS_EXPNS_CD,
	PROV_EXPNS_CD,
	EXP_ALLOC_TYP
)
AS
SELECT	t1.CALC_PTN_CD,
	t1.MFG_PURC_TYP,
	t1.EVAL_TYP,
	t1.DPT_TYP,
	t1.LOT_TYP,
	t1.SUBLOT_TYP,
	t1.SNO1_TYP,
	t1.SNO2_TYP,
	t1.SNO3_TYP,
	t1.SNO4_TYP,
	t1.LOT_EXP_TYP,
	t1.SUBLOT_EXP_TYP,
	t1.SNO1_EXP_TYP,
	t1.SNO2_EXP_TYP,
	t1.SNO3_EXP_TYP,
	t1.SNO4_EXP_TYP,
	t1.STD_RND_TYP,
	t1.STD_DEC_PLACE,
	t1.AMT_RND_TYP,
	t1.AMT_DEC_PLACE,
	t1.AVE_RND_TYP,
	t1.AVE_DEC_PLACE,
	t1.ADJ_TYP,
	t1.WIP_TYP,
	t1.BD_AGG_TYP,
	t1.MRGN_EXPNS_CD,
	t1.PURC_EXPNS_CD,
	t1.OUT_EXPNS_CD,
	t1.INPT_EXPNS_CD,
	t1.SS_EXPNS_CD,
	t1.PROV_EXPNS_CD,
	t1.EXP_ALLOC_TYP
FROM	MGW_ARG w1, MGT_CALC_PTN t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

