SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVT_RQMT(
	WG_CD,
	YM,
	MNG_DPT_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ASST_TYP,
	QTY
)
AS
SELECT	t1.WG_CD,
	t1.YM,
	t1.MNG_DPT_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.ASST_TYP,
	t1.QTY
FROM	MGW_ARG w1, MGT_CALC_RQMT t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

