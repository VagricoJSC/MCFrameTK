CREATE OR REPLACE VIEW MGVM_ITM_DTL(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	SPPL_CD,
	RQST_WG_CD,
	WG_CD,
	COST_RATIO,
	OPER_PTN,
	BOM_PTN,
	MIN_LOT_QTY,
	BATCH_LOT_QTY,
	FXD_LOT_QTY,
	FXD_YIELD_QTY,
	NMR_QTY,
	DNM_QTY,
	ALC_DPT_CD,
	EXP_DPT_CD,
	EXP_PRIO,
	MAX_QTY,
	ALC_VAL1,
	ALC_VAL2,
	ALC_VAL3,
	ALC_VAL4,
	ALC_VAL5
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.LOC_CD,
	t1.SPPL_CD,
	t1.RQST_WG_CD,
	t1.WG_CD,
	t1.COST_RATIO,
	t1.OPER_PTN,
	t1.BOM_PTN,
	t1.MIN_LOT_QTY,
	t1.BATCH_LOT_QTY,
	t1.FXD_LOT_QTY,
	t1.FXD_YIELD_QTY,
	t1.NMR_QTY,
	t1.DNM_QTY,
	t1.ALC_DPT_CD,
	t1.EXP_DPT_CD,
	t1.EXP_PRIO,
	t1.MAX_QTY,
	t1.ALC_VAL1,
	t1.ALC_VAL2,
	t1.ALC_VAL3,
	t1.ALC_VAL4,
	t1.ALC_VAL5
FROM	MGW_ARG w1, MGT_CALC_ITM_DTL t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

