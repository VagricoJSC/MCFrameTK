CREATE OR REPLACE VIEW MGVM_ALC_RULE(
	ALC_PTN_CD,
	ALC_TGT_TYP,
	ALC_RULE_TYP,
	EXPNS_CD,
	DIFF_CALC_TYP,
	RND_TYP,
	DEC_PLACE,
	ALC_COEF_CD,
	COEF_LIMIT_FLG,
	ASST_TYP,
	NON_MINUS_FLG,
	NON_OS_FLG,
	SCST_ALC_FLG,
	STD_ALC_FLG
)
AS
SELECT	m1.ALC_PTN_CD,
	m1.ALC_TGT_TYP,
	m1.ALC_RULE_TYP,
	m1.EXPNS_CD,
	m1.DIFF_CALC_TYP,
	m1.RND_TYP,
	m1.DEC_PLACE,
	m1.ALC_COEF_CD,
	m1.COEF_LIMIT_FLG,
	m1.ASST_TYP,
	m1.NON_MINUS_FLG,
	m1.NON_OS_FLG,
	m1.SCST_ALC_FLG,
	m1.STD_ALC_FLG
FROM	MGW_ARG w1, MAM_ALC_RULE m1
WHERE	0=0
AND	w1.TERM = m1.TERM
;

