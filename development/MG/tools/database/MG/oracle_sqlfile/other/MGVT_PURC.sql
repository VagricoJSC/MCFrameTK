CREATE OR REPLACE VIEW MGVT_PURC(
	WG_CD,
	YM,
	AC_DT,
	MNG_DPT_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	SPPL_CD,
	PO_NO,
	SLO_NO,
	IV_NO,
	ALC_DPT_CD,
	AC_SLIP_TYP,
	AC_RSN_CD,
	ASST_TYP,
	EXPNS_CD,
	QTY,
	AMT,
	CUR_CD,
	CUR_AMT,
	XRATE,
	ALC_VAL1,
	ALC_VAL2,
	ALC_VAL3,
	ALC_VAL4,
	ALC_VAL5
)
AS
SELECT	t1.WG_CD,
	t1.YM,
	t1.AC_DT,
	t1.MNG_DPT_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.SPPL_CD,
	t1.PO_NO,
	t1.SLO_NO,
	t1.IV_NO,
	t1.ALC_DPT_CD,
	t1.AC_SLIP_TYP,
	t1.AC_RSN_CD,
	t1.ASST_TYP,
	t1.EXPNS_CD,
	t1.QTY,
	t1.AMT,
	t1.CUR_CD,
	t1.CUR_AMT,
	t1.XRATE,
	t1.ALC_VAL1,
	t1.ALC_VAL2,
	t1.ALC_VAL3,
	t1.ALC_VAL4,
	t1.ALC_VAL5
FROM	MGW_ARG w1, MGT_CALC_PURC t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

