CREATE OR REPLACE VIEW MGVT_ARG(
	SA_TYP,
	ST_YM,
	END_YM,
	EVAL_TYP,
	EXP_CALC_TYP,
	INPT_CALC_FLG,
	WK_CALC_FLG,
	PROV_CALC_FLG,
	XFR_CALC_FLG,
	ALC_CALC_TYP,
	COST_CALC_TYP
)
AS
SELECT	t1.SA_TYP,
	t1.ST_YM,
	t1.END_YM,
	t1.EVAL_TYP,
	t1.EXP_CALC_TYP,
	t1.INPT_CALC_FLG,
	t1.WK_CALC_FLG,
	t1.PROV_CALC_FLG,
	t1.XFR_CALC_FLG,
	t1.ALC_CALC_TYP,
	t1.COST_CALC_TYP
FROM	MGW_ARG t1
WHERE	0=0
;

