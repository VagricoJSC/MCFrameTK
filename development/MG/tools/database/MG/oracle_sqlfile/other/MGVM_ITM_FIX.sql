CREATE OR REPLACE VIEW MGVM_ITM_FIX(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	EXPNS_CD,
	WG_CD,
	BASE_QTY,
	STD_UPRI
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.EXPNS_CD,
	t1.WG_CD,
	t1.BASE_QTY,
	t1.STD_UPRI
FROM	MGW_ARG w1, MGT_CALC_ITM_FIX t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

