CREATE OR REPLACE VIEW MGVM_ITM_PROV(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	PRSPPL_CD,
	WG_CD,
	PROV_TYP,
	BASE_QTY,
	CUR_CD,
	UPRI,
	BASE_CUR_UPRI
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.PRSPPL_CD,
	t1.WG_CD,
	t1.PROV_TYP,
	t1.BASE_QTY,
	t1.CUR_CD,
	t1.UPRI,
	t1.BASE_CUR_UPRI
FROM	MGW_ARG w1, MGT_CALC_ITM_PROV t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

