SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVM_COEF_CONFIG(
	ALC_COEF_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	LOC_CD,
	OPER_CD,
	BP_CD,
	COEF_VAL
)
AS
SELECT	m1.ALC_COEF_CD,
	m1.ITM_CD,
	m1.ITM_SUB1,
	m1.ITM_SUB2,
	m1.ITM_SUB3,
	m1.LOT_NO,
	m1.SUBLOT_NO,
	m1.SNO1,
	m1.SNO2,
	m1.SNO3,
	m1.SNO4,
	m1.LOC_CD,
	m1.OPER_CD,
	m1.BP_CD,
	m1.COEF_VAL
FROM	MGW_ARG w1, MAVM_COEF_CONFIG m1
WHERE	0=0
AND	w1.TERM = m1.TERM
AND m1.DEL_FLG = '0'
AND	EXISTS (
		SELECT	'X'
		FROM	MGVM_ALC_RULE x1
		WHERE	0=0
		AND	x1.ALC_COEF_CD = m1.ALC_COEF_CD
	)
AND	EXISTS (
		SELECT	'X'
		FROM	MGT_CALC_ITM x2
		WHERE	0=0
		AND	x2.CALC_NO = w1.CALC_NO
		AND	x2.CALC_GRP_CD = w1.CALC_GRP_CD
		AND	x2.ITM_CD = m1.ITM_CD
		AND	x2.ITM_SUB1 = m1.ITM_SUB1
		AND	x2.ITM_SUB2 = m1.ITM_SUB2
		AND	x2.ITM_SUB3 = m1.ITM_SUB3
	)
;

