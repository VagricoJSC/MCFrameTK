CREATE OR REPLACE VIEW MGT_ACC_TOP_TMP(
	CALC_NO,
	CALC_GRP_CD,
	TOP_REC_NO,
	CALC_REC_TYP,
	COST_IO_TYP,
	ACT_ID,
	ACT_ID_SUB,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.TOP_REC_NO,
	ORG.CALC_REC_TYP,
	ORG.COST_IO_TYP,
	ORG.ACT_ID,
	ORG.ACT_ID_SUB,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_ACC_TOP_TMP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

