SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGT_CALC_PARM(
	CALC_NO,
	CALC_GRP_CD,
	PARM_KEY,
	PARM_VAL,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.PARM_KEY,
	ORG.PARM_VAL,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3
FROM
	MGT_CALC_PARM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

