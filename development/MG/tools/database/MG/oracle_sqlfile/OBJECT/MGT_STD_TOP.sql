CREATE OR REPLACE VIEW MGT_STD_TOP(
	CALC_NO,
	CALC_GRP_CD,
	TOP_REC_NO,
	WG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	MFG_PURC_TYP,
	LOC_CD,
	SPPL_CD,
	DPT_CD,
	CST_CD,
	DLV_CD,
	DEST_CD1,
	DEST_CD2,
	DEST_CD3,
	QTY,
	AMT,
	SLS_AMT,
	CUR_CD,
	CUR_AMT,
	SLS_FLG,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.TOP_REC_NO,
	ORG.WG_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.MFG_PURC_TYP,
	ORG.LOC_CD,
	ORG.SPPL_CD,
	ORG.DPT_CD,
	ORG.CST_CD,
	ORG.DLV_CD,
	ORG.DEST_CD1,
	ORG.DEST_CD2,
	ORG.DEST_CD3,
	ORG.QTY,
	ORG.AMT,
	ORG.SLS_AMT,
	ORG.CUR_CD,
	ORG.CUR_AMT,
	ORG.SLS_FLG,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_STD_TOP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

