PROCEDURE P_CHK_RATE_CANCEL (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	標準配賦率の確定解除チェック
<REMARKS>

<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<HISTORY>
**************************************************************************/
IS
	L_ARG	MGT_ARG%ROWTYPE ;
	L_CNT	NUMBER ;
BEGIN
	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	MGPA_ARG.P_LOCK(I_CALC_GRP_CD, I_CALC_NO, '0') ;

	IF L_ARG.RUNTIME_WG_CD IS NULL THEN
		INSERT INTO MAW_GRP_WG_KEY
		SELECT m.CALC_GRP_CD, m.WG_CD FROM MAM_GRP_WG m WHERE m.CALC_GRP_CD = I_CALC_GRP_CD ;
	ELSE
		INSERT INTO MAW_GRP_WG_KEY VALUES (I_CALC_GRP_CD, L_ARG.RUNTIME_WG_CD) ;
	END IF ;

	FOR x IN (
		SELECT	DISTINCT
			t.CALC_CTG_CD,
			t.WG_CD
		FROM	MGT_STD_ALC_RATE t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t.TERM = L_ARG.TERM
		)
	LOOP
		FOR y IN (
			SELECT	DISTINCT
					m.CALC_GRP_CD
			FROM	MAM_GRP_CTG m, MAW_GRP_WG_KEY m2
			WHERE	0=0
			AND	m.CALC_CTG_TYP = MAC_CALC_CTG_TYP.ALC_RATE_M
			AND	m.CALC_CTG_CD = x.CALC_CTG_CD
			AND	m2.WG_CD = x.WG_CD
			AND	m.CALC_GRP_CD = m2.CALC_GRP_CD
			)
		LOOP
			FOR z IN (
				SELECT	DISTINCT
						m.CALC_CTG_CD, m2.WG_CD
				FROM	MAM_GRP_CTG m, MAW_GRP_WG_KEY m2
				WHERE	0=0
				AND	m.CALC_CTG_TYP = MAC_CALC_CTG_TYP.CALC_ITM
				AND	m.CALC_GRP_CD = y.CALC_GRP_CD
				AND	m2.CALC_GRP_CD = y.CALC_GRP_CD
				)
			LOOP
				SELECT	COUNT(*)
				INTO	L_CNT
				FROM	MGT_STD_FIX t
				WHERE	0=0
				AND	t.TERM = L_ARG.TERM
				AND	t.CALC_CTG_CD = z.CALC_CTG_CD
				AND	t.WG_CD = z.WG_CD
				;

				IF L_CNT > 0 THEN
					G_MSG := FCPA_ERR.MSG_BINDER(FCPA_DATE_UTIL.F_TO_CHAR(L_ARG.TERM, FCPA_DATE_UTIL.Y4M), z.CALC_CTG_CD, z.WG_CD) ;
					FCPA_ERR.RAISE_APP_ERR('MGBED0004', G_MSG) ;
				END IF ;
			END LOOP ;
		END LOOP ;
	END LOOP ;
END P_CHK_RATE_CANCEL ;

