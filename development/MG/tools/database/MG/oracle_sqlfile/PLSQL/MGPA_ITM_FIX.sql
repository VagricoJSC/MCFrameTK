PROCEDURE P_FIX_MAIN (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	標準単価確定メイン処理
<REMARKS>

<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<HISTORY>
**************************************************************************/
IS
	L_ARG	MGT_ARG%ROWTYPE ;

	L_CNT	NUMBER ;
	L_TS	MAPA_META.SYS_TS%TYPE ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_ITM_FIX.P_FIX_MAIN') ;

	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	MGPA_ARG.P_LOCK(I_CALC_GRP_CD, I_CALC_NO, '0') ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGW_FIX_ITM w
	WHERE	0=0
	;

	IF L_CNT = 0 THEN
		RETURN ;
	END IF ;

	-- 対象品目のロック
	BEGIN
		OPEN LOCK_ITM(L_ARG.TERM) ;
		CLOSE LOCK_ITM ;
	EXCEPTION
	WHEN LOCK_ERROR THEN
		FCPA_ERR.RAISE_APP_ERR('MGBXD0029') ;
	END ;

	SELECT	MAX(t.UPD_TS)
	INTO	L_TS
	FROM	MGT_STD_FIX t
	WHERE	0=0
	AND	t.TERM	= L_ARG.TERM
	AND	(t.CALC_NO != I_CALC_NO OR t.CALC_GRP_CD != I_CALC_GRP_CD)
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_FIX_ITM w
			WHERE	0=0
			AND	w.ITM_CD = t.ITM_CD
			AND	w.ITM_SUB1 = t.ITM_SUB1
			AND	w.ITM_SUB2 = t.ITM_SUB2
			AND	w.ITM_SUB3 = t.ITM_SUB3
			AND	w.WG_CD = t.WG_CD
			AND	w.CALC_CTG_CD = t.CALC_CTG_CD
		)
	;

	IF L_TS IS NOT NULL AND L_TS > L_ARG.INS_TS THEN
		FCPA_ERR.RAISE_APP_ERR('MGBED0002') ;
	END IF ;

	-- 確定品目の削除
	DELETE	MGW_FIX_ITM w
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_STD_FIX t
			WHERE	0=0
			AND	t.TERM	= L_ARG.TERM
			AND	t.ITM_CD = w.ITM_CD
			AND	t.ITM_SUB1 = w.ITM_SUB1
			AND	t.ITM_SUB2 = w.ITM_SUB2
			AND	t.ITM_SUB3 = w.ITM_SUB3
			AND	t.WG_CD = w.WG_CD
			AND	t.CALC_CTG_CD = w.CALC_CTG_CD
			)
	;

	-- MGT_STD_TOPに存在しないデータは対象外とする
	DELETE	MGW_FIX_ITM w
	WHERE	0=0
	AND	NOT EXISTS (
			SELECT	'X'
			FROM	MGT_STD_TOP t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t.ITM_CD = w.ITM_CD
			AND	t.ITM_SUB1 = w.ITM_SUB1
			AND	t.ITM_SUB2 = w.ITM_SUB2
			AND	t.ITM_SUB3 = w.ITM_SUB3
			AND	t.WG_CD = w.WG_CD
			AND	t.SLS_FLG = '0'
			)
	;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGW_FIX_ITM w
	WHERE	0=0
	;

	IF L_CNT = 0 THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBED0007') ;
		RETURN ;
	END IF ;

	UPDATE	MGW_FIX_ITM w
	SET	(w.CALC_PTN_CD, w.STD_QTY)
		=
		(
		SELECT	t.CALC_PTN_CD, t.STD_QTY
		FROM	MGT_CALC_ITM t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t.ITM_CD = w.ITM_CD
		AND	t.ITM_SUB1 = w.ITM_SUB1
		AND	t.ITM_SUB2 = w.ITM_SUB2
		AND	t.ITM_SUB3 = w.ITM_SUB3
		AND	t.WG_CD = w.WG_CD
		)
	WHERE	0=0
	;

	MERGE INTO MGT_ITM t2
	USING	MGW_FIX_ITM t
	ON	(0=0
		AND	t2.TERM = L_ARG.TERM
		AND	t.ITM_CD = t2.ITM_CD
		AND	t.ITM_SUB1 = t2.ITM_SUB1
		AND	t.ITM_SUB2 = t2.ITM_SUB2
		AND	t.ITM_SUB3 = t2.ITM_SUB3
		AND	t.WG_CD = t2.WG_CD
		AND	t.CALC_CTG_CD = t2.CALC_CTG_CD
		)
	WHEN MATCHED THEN
		UPDATE
		SET	t2.CALC_PTN_CD = t.CALC_PTN_CD,
			t2.STD_QTY = t.STD_QTY,
			t2.FIX_FLG = '1',
			t2.NON_CALC_FLG = '0'
	WHEN NOT MATCHED THEN
		INSERT (
			ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, TERM,
			CALC_CTG_CD, WG_CD, CALC_PTN_CD,
			STD_QTY,
			FIX_FLG,
			RMRKS, SUB_CHAR1, SUB_CHAR2, SUB_CHAR3
			)
		VALUES	(
			t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3, L_ARG.TERM,
			t.CALC_CTG_CD, t.WG_CD, t.CALC_PTN_CD,
			t.STD_QTY,
			'1',
			NULL, NULL, NULL, NULL
			)
	;

	DELETE	MGT_ITM_DTL t2
	WHERE	0=0
	AND	t2.TERM = L_ARG.TERM
	AND	(L_TS IS NULL OR t2.WG_CD <> G_NULL_VAL)
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_ITM_DTL t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t.CALC_CTG_CD = t2.CALC_CTG_CD
			AND	t.ITM_CD = t2.ITM_CD
			AND	t.ITM_SUB1 = t2.ITM_SUB1
			AND	t.ITM_SUB2 = t2.ITM_SUB2
			AND	t.ITM_SUB3 = t2.ITM_SUB3
			AND	t.WG_CD = t2.WG_CD
		)
	AND	EXISTS (
			SELECT 'X'
			FROM	MGW_FIX_ITM w
			WHERE	0=0
			AND	w.ITM_CD = t2.ITM_CD
			AND	w.ITM_SUB1 = t2.ITM_SUB1
			AND	w.ITM_SUB2 = t2.ITM_SUB2
			AND	w.ITM_SUB3 = t2.ITM_SUB3
			AND	(t2.WG_CD = G_NULL_VAL OR w.WG_CD = t2.WG_CD)
		)
	;

	DELETE MGW_FIX_ITM_DTL ;

	INSERT INTO MGW_FIX_ITM_DTL (
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		LOC_CD, SPPL_CD, RQST_WG_CD,
		TERM,
		CALC_CTG_CD, WG_CD,
		COST_RATIO,
		OPER_PTN, BOM_PTN,
		MIN_LOT_QTY, BATCH_LOT_QTY,
		FXD_LOT_QTY, FXD_YIELD_QTY,
		NMR_QTY, DNM_QTY,
		ALC_DPT_CD,
		EXP_DPT_CD, EXP_PRIO, MAX_QTY,
		ALC_VAL1, ALC_VAL2, ALC_VAL3, ALC_VAL4, ALC_VAL5,
		RMRKS, SUB_CHAR1, SUB_CHAR2, SUB_CHAR3
		)
	SELECT	t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOC_CD, t.SPPL_CD, t.RQST_WG_CD,
		L_ARG.TERM,
		t.CALC_CTG_CD, t.WG_CD,
		t.COST_RATIO,
		t.OPER_PTN, t.BOM_PTN,
		t.MIN_LOT_QTY, t.BATCH_LOT_QTY,
		t.FXD_LOT_QTY, t.FXD_YIELD_QTY,
		t.NMR_QTY, t.DNM_QTY,
		t.ALC_DPT_CD,
		t.EXP_DPT_CD, t.EXP_PRIO, t.MAX_QTY,
		t.ALC_VAL1, t.ALC_VAL2, t.ALC_VAL3, t.ALC_VAL4, t.ALC_VAL5,
		t.RMRKS, t.SUB_CHAR1, t.SUB_CHAR2, t.SUB_CHAR3
	FROM	MGT_CALC_ITM_DTL t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	(L_TS IS NULL OR t.WG_CD <> G_NULL_VAL)
	AND	EXISTS (
			SELECT 'X'
			FROM	MGW_FIX_ITM w
			WHERE	0=0
			AND	w.ITM_CD = t.ITM_CD
			AND	w.ITM_SUB1 = t.ITM_SUB1
			AND	w.ITM_SUB2 = t.ITM_SUB2
			AND	w.ITM_SUB3 = t.ITM_SUB3
			AND	(t.WG_CD = G_NULL_VAL OR w.WG_CD = t.WG_CD)
		)
	;

	-- 原価品目工程情報に存在しない工程パタンはNULLに更新する
	UPDATE	MGW_FIX_ITM_DTL w
	SET	w.OPER_PTN = NULL
	WHERE	0=0
	AND	NOT EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_ITM_OPER t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t.ITM_CD = w.ITM_CD
			AND	t.ITM_SUB1 = w.ITM_SUB1
			AND	t.ITM_SUB2 = w.ITM_SUB2
			AND	t.ITM_SUB3 = w.ITM_SUB3
			AND	(t.WG_CD = G_NULL_VAL OR w.WG_CD = G_NULL_VAL OR t.WG_CD = w.WG_CD)
			AND	t.OPER_PTN = w.OPER_PTN
		)
	;

	-- 原価ＢＯＭ情報に存在しない構成パタンはNULLに更新する
	UPDATE	MGW_FIX_ITM_DTL w
	SET	w.BOM_PTN = G_NULL_VAL
	WHERE	0=0
	AND	NOT EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_BOM t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t.PAR_ITM_CD = w.ITM_CD
			AND	t.PAR_ITM_SUB1 = w.ITM_SUB1
			AND	t.PAR_ITM_SUB2 = w.ITM_SUB2
			AND	t.PAR_ITM_SUB3 = w.ITM_SUB3
			AND	(t.WG_CD = G_NULL_VAL OR w.WG_CD = G_NULL_VAL OR t.WG_CD = w.WG_CD)
			AND	t.BOM_PTN = w.BOM_PTN
		)
	;

	INSERT INTO MGT_ITM_DTL (
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		LOC_CD, SPPL_CD, RQST_WG_CD,
		TERM,
		CALC_CTG_CD, WG_CD,
		COST_RATIO,
		OPER_PTN, BOM_PTN,
		MIN_LOT_QTY, BATCH_LOT_QTY,
		FXD_LOT_QTY, FXD_YIELD_QTY,
		NMR_QTY, DNM_QTY,
		ALC_DPT_CD,
		EXP_DPT_CD, EXP_PRIO, MAX_QTY,
		ALC_VAL1, ALC_VAL2, ALC_VAL3, ALC_VAL4, ALC_VAL5,
		RMRKS, SUB_CHAR1, SUB_CHAR2, SUB_CHAR3
		)
	SELECT	w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3,
		w.LOC_CD, w.SPPL_CD, w.RQST_WG_CD,
		L_ARG.TERM,
		w.CALC_CTG_CD, w.WG_CD,
		w.COST_RATIO,
		w.OPER_PTN, NVL(w.BOM_PTN, G_NULL_VAL),
		w.MIN_LOT_QTY, w.BATCH_LOT_QTY,
		w.FXD_LOT_QTY, w.FXD_YIELD_QTY,
		w.NMR_QTY, w.DNM_QTY,
		w.ALC_DPT_CD,
		w.EXP_DPT_CD, w.EXP_PRIO, w.MAX_QTY,
		w.ALC_VAL1, w.ALC_VAL2, w.ALC_VAL3, w.ALC_VAL4, w.ALC_VAL5,
		w.RMRKS, w.SUB_CHAR1, w.SUB_CHAR2, w.SUB_CHAR3
	FROM	MGW_FIX_ITM_DTL w
	WHERE	0=0
	;

	DELETE	MGT_ITM_OPER t2
	WHERE	0=0
	AND	t2.TERM = L_ARG.TERM
	AND	(L_TS IS NULL OR t2.WG_CD <> G_NULL_VAL)
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_ITM_OPER t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t.CALC_CTG_CD = t2.CALC_CTG_CD
			AND	t.ITM_CD = t2.ITM_CD
			AND	t.ITM_SUB1 = t2.ITM_SUB1
			AND	t.ITM_SUB2 = t2.ITM_SUB2
			AND	t.ITM_SUB3 = t2.ITM_SUB3
			AND	t.WG_CD = t2.WG_CD
		)
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_FIX_ITM_DTL w
			WHERE	0=0
			AND	w.ITM_CD = t2.ITM_CD
			AND	w.ITM_SUB1 = t2.ITM_SUB1
			AND	w.ITM_SUB2 = t2.ITM_SUB2
			AND	w.ITM_SUB3 = t2.ITM_SUB3
			AND	(w.WG_CD = G_NULL_VAL OR t2.WG_CD = G_NULL_VAL OR w.WG_CD = t2.WG_CD)
		)
	;

	INSERT INTO MGT_ITM_OPER (
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		LOC_CD, OPER_PTN,
		OPER_CD, OPER_SEQ,
		TERM,
		CALC_CTG_CD, WG_CD,
		DISP_SEQ,
		NMR_QTY, DNM_QTY,
		YIELD_OPER_FLG,
		OPER_UNIT_CD, OPER_STD_QTY, OPER_CONV_QTY,
		DEC_PLACE, UNIT_CONV_RND_TYP,
		RMRKS, SUB_CHAR1, SUB_CHAR2, SUB_CHAR3
		)
	SELECT	t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOC_CD, t.OPER_PTN,
		t.OPER_CD, t.OPER_SEQ,
		L_ARG.TERM,
		t.CALC_CTG_CD, t.WG_CD,
		t.DISP_SEQ,
		t.NMR_QTY, t.DNM_QTY,
