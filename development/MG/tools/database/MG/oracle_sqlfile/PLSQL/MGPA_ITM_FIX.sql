	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE,
	I_WG_CD		IN	MAPA_META.WG_CD%TYPE,
	I_TERM		IN	MAPA_META.YM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	標準単価一括解除処理
<REMARKS>
	原価計算ＮＯもしくは期のいずれかは必須
<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<IN> I_WG_CD
	ワーキンググループＣＤ
<IN> I_TERM
	期
<HISTORY>
**************************************************************************/
IS
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_ITM_FIX.P_BULK_CANCEL') ;

	FOR x IN (
		SELECT	DISTINCT
			t.CALC_NO
		FROM	MGT_STD_FIX t
		WHERE	0=0
		AND	(t.CALC_NO = I_CALC_NO OR I_CALC_NO IS NULL AND t.TERM = I_TERM)
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t.WG_CD = I_WG_CD
		)
	LOOP
		DELETE MGW_FIX_ITM ;

		INSERT INTO MGW_FIX_ITM (
			ITM_CD,
			ITM_SUB1,
			ITM_SUB2,
			ITM_SUB3,
			WG_CD,
			CALC_CTG_CD
