PROCEDURE P_SET_PARENT (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE,
	I_FLG		IN	MAPA_META.FLG%TYPE
)
/**************************************************************************
<SYNOPSIS>
	確定済みの親品目を確定解除対象に含める
<REMARKS>

<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<IN> I_FLG
	品目件数チェックＦＬＧ
<HISTORY>
**************************************************************************/
IS
	L_CNT	NUMBER ;
	L_CNT1	NUMBER ;
	L_CNT2	NUMBER ;

	L_ARG	MGT_ARG%ROWTYPE ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_ITM_FIX.P_SET_PARENT') ;

	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	IF L_ARG.CALC_ERR_FLG = '1' THEN
		FCPA_ERR.RAISE_APP_ERR('MGBED0003') ;
	END IF ;

	IF I_FLG = '1' THEN
		/** 品目をすべて対象としたときはチェックなし **/
		SELECT	COUNT(*)
		INTO	L_CNT1
		FROM	MGT_CALC_ITM t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		;

		SELECT	COUNT(*)
		INTO	L_CNT2
		FROM	MGW_FIX_ITM w
		WHERE	0=0
		;

		IF L_CNT1 = L_CNT2 THEN
			GOTO SKIP_PARENT_ADD ;
		END IF ;
	END IF ;

	-- 確定済親品目を格納
	LOOP
		INSERT INTO MGW_FIX_ITM (
			ITM_CD,
			ITM_SUB1,
			ITM_SUB2,
			ITM_SUB3,
			WG_CD,
			CALC_CTG_CD
			)
		SELECT	t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.WG_CD,
			t.CALC_CTG_CD
		FROM	MGT_CALC_ITM t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_FIX_ITM w
				WHERE	0=0
				AND	w.ITM_CD = t.ITM_CD
				AND	w.ITM_SUB1 = t.ITM_SUB1
				AND	w.ITM_SUB2 = t.ITM_SUB2
				AND	w.ITM_SUB3 = t.ITM_SUB3
				AND	w.WG_CD = t.WG_CD
				AND	w.CALC_CTG_CD = t.CALC_CTG_CD
				)
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_STD_TOP w
				WHERE	0=0
				AND	w.CALC_NO = t.CALC_NO
				AND	w.CALC_GRP_CD = t.CALC_GRP_CD
				AND	w.ITM_CD = t.ITM_CD
				AND	w.ITM_SUB1 = t.ITM_SUB1
				AND	w.ITM_SUB2 = t.ITM_SUB2
				AND	w.ITM_SUB3 = t.ITM_SUB3
				AND	w.WG_CD = t.WG_CD
				AND	w.SLS_FLG = '0'
				AND	EXISTS (
						SELECT	'X'
						FROM	MGT_STD_INPT w1, MGW_FIX_ITM w2
						WHERE	0=0
						AND	w1.CALC_NO = w.CALC_NO
						AND	w1.CALC_GRP_CD = w.CALC_GRP_CD
						AND	w1.TOP_REC_NO = w.TOP_REC_NO
						AND	w1.LVL >= 1
						AND	w1.ITM_CD = w2.ITM_CD
						AND	w1.ITM_SUB1 = w2.ITM_SUB1
						AND	w1.ITM_SUB2 = w2.ITM_SUB2
						AND	w1.ITM_SUB3 = w2.ITM_SUB3
						AND	w1.WG_CD = w2.WG_CD
					)
			)
		;
		L_CNT := SQL%ROWCOUNT ;

		-- 依頼元の確定済親品目を格納
		INSERT INTO MGW_FIX_ITM (
			ITM_CD,
			ITM_SUB1,
			ITM_SUB2,
			ITM_SUB3,
			WG_CD,
			CALC_CTG_CD
			)
		SELECT DISTINCT
			t4.ITM_CD,
			t4.ITM_SUB1,
			t4.ITM_SUB2,
			t4.ITM_SUB3,
			t4.WG_CD,
			t4.CALC_CTG_CD
		FROM	MGW_FIX_ITM w,
			MGT_CALC_ITM_DTL t1,
			MGT_STD_INPT t2,
			MGT_STD_TOP t3,
			MGT_CALC_ITM t4
		WHERE	0=0
		AND	t1.CALC_NO = I_CALC_NO
		AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t1.ITM_CD = w.ITM_CD
		AND	t1.ITM_SUB1 = w.ITM_SUB1
		AND	t1.ITM_SUB2 = w.ITM_SUB2
		AND	t1.ITM_SUB3 = w.ITM_SUB3
		AND	t1.RQST_WG_CD = w.WG_CD
		AND	t2.CALC_NO = t1.CALC_NO
		AND	t2.CALC_GRP_CD = t1.CALC_GRP_CD
		AND	t2.ITM_CD = t1.ITM_CD
		AND	t2.ITM_SUB1 = t1.ITM_SUB1
		AND	t2.ITM_SUB2 = t1.ITM_SUB2
		AND	t2.ITM_SUB3 = t1.ITM_SUB3
		AND	t2.WG_CD = t1.WG_CD
		AND	t3.CALC_NO = t2.CALC_NO
		AND	t3.CALC_GRP_CD = t2.CALC_GRP_CD
		AND	t3.TOP_REC_NO = t2.TOP_REC_NO
		AND	t3.SLS_FLG = '0'
		AND	t4.CALC_NO = t3.CALC_NO
		AND	t4.CALC_GRP_CD = t3.CALC_GRP_CD
		AND	t4.ITM_CD = t3.ITM_CD
		AND	t4.ITM_SUB1 = t3.ITM_SUB1
		AND	t4.ITM_SUB2 = t3.ITM_SUB2
		AND	t4.ITM_SUB3 = t3.ITM_SUB3
		AND	t4.WG_CD = t3.WG_CD
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_FIX_ITM w
				WHERE	0=0
				AND	w.ITM_CD = t4.ITM_CD
				AND	w.ITM_SUB1 = t4.ITM_SUB1
				AND	w.ITM_SUB2 = t4.ITM_SUB2
				AND	w.ITM_SUB3 = t4.ITM_SUB3
				AND	w.WG_CD = t4.WG_CD
				AND	w.CALC_CTG_CD = t4.CALC_CTG_CD
				)
		;
		L_CNT := L_CNT + SQL%ROWCOUNT ;

		IF L_CNT = 0 THEN
			EXIT ;
		END IF ;
	END LOOP ;

	<<SKIP_PARENT_ADD>>
		NULL ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_ITM_FIX.P_SET_PARENT') ;

END P_SET_PARENT ;

PROCEDURE P_CANCEL_MAIN (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	標準単価解除メイン処理
<REMARKS>

<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<HISTORY>
**************************************************************************/
IS
	L_ARG	MGT_ARG%ROWTYPE ;
	L_CNT	NUMBER ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_ITM_FIX.P_CANCEL_MAIN') ;

	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	MGPA_ARG.P_LOCK(I_CALC_GRP_CD, I_CALC_NO, '0') ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGW_FIX_ITM w
	WHERE	0=0
	;

	IF L_CNT = 0 THEN
		FCPA_ERR.RAISE_APP_ERR('MGBED0008') ;
	END IF ;

	-- 対象品目のロック
	BEGIN
		OPEN LOCK_ITM(L_ARG.TERM) ;
		CLOSE LOCK_ITM ;
	EXCEPTION
	WHEN LOCK_ERROR THEN
		FCPA_ERR.RAISE_APP_ERR('MGBXD0029') ;
	END ;

	UPDATE	MGT_ITM t
	SET	t.FIX_FLG = '0'
	WHERE	0=0
	AND	t.TERM = L_ARG.TERM
	AND	t.FIX_FLG = '1'
	AND 	EXISTS (
			SELECT	'X'
			FROM	MGW_FIX_ITM w
			WHERE	0=0
			AND	w.ITM_CD = t.ITM_CD
			AND	w.ITM_SUB1 = t.ITM_SUB1
			AND	w.ITM_SUB2 = t.ITM_SUB2
			AND	w.ITM_SUB3 = t.ITM_SUB3
			AND	w.WG_CD = t.WG_CD
			AND	w.CALC_CTG_CD = t.CALC_CTG_CD
			)
	;

	DELETE	MGT_STD_FIX t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_FIX_ITM w
			WHERE	0=0
			AND	w.ITM_CD = t.ITM_CD
			AND	w.ITM_SUB1 = t.ITM_SUB1
			AND	w.ITM_SUB2 = t.ITM_SUB2
			AND	w.ITM_SUB3 = t.ITM_SUB3
			AND	w.WG_CD = t.WG_CD
			AND	w.CALC_CTG_CD = t.CALC_CTG_CD
		)
	;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_STD_FIX t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	IF L_CNT = 0 THEN
		UPDATE	MGT_ARG t
		SET	FIX_FLG = '0'
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		;

		FOR x IN (
			SELECT	t.XRATE_CD,
				t.TERM
			FROM	MGT_ARG t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t.XRATE_CD IS NOT NULL
			)
		LOOP
			SELECT	COUNT(*)
			INTO	L_CNT
			FROM	MGT_ARG t
			WHERE	0=0
			AND	t.TERM = x.TERM
			AND	t.XRATE_CD = x.XRATE_CD
			AND	t.FIX_FLG = '1'
			AND	t.COST_CALC_TYP = MAC_COST_CALC_TYP.COST_STD
			;

			IF L_CNT = 0 THEN
				UPDATE	MGT_CUR_XRATE t
				SET	t.FIX_FLG = '0'
				WHERE	0=0
				AND	t.TERM = x.TERM
				AND	t.XRATE_CD = x.XRATE_CD
				AND	t.FIX_FLG = '1'
				;
			END IF ;
		END LOOP ;
	END IF ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_ITM_FIX.P_CANCEL_MAIN') ;

END P_CANCEL_MAIN ;

