			t.CALC_CTG_CD
		FROM	MGT_STD_FIX t
		WHERE	0=0
		AND	t.CALC_NO = x.CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t.WG_CD = I_WG_CD
		;

		P_SET_PARENT(I_CALC_GRP_CD, x.CALC_NO, '1') ;
		P_CANCEL_MAIN(I_CALC_GRP_CD, x.CALC_NO) ;
	END LOOP ;

	IF I_CALC_NO IS NOT NULL THEN
		P_CANCEL_ADD_CALC_NO(I_CALC_GRP_CD, I_CALC_NO) ;
	END IF ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_ITM_FIX.P_BULK_CANCEL') ;

