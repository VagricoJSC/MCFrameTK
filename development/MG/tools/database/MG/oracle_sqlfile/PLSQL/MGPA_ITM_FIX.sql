CREATE OR REPLACE PACKAGE BODY MGPA_ITM_FIX
IS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	/** 対象品目のロック用のカーソル **/
	CURSOR LOCK_ITM (
		CI_TERM IN MGT_ARG.TERM%TYPE
		)
	IS
		SELECT	t.ITM_CD
		FROM	MGT_ITM t
		WHERE	0=0
		AND	t.TERM = CI_TERM
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_FIX_ITM w
				WHERE 	0=0
				AND	w.ITM_CD = t.ITM_CD
				AND	w.ITM_SUB1 = t.ITM_SUB1
				AND	w.ITM_SUB2 = t.ITM_SUB2
				AND	w.ITM_SUB3 = t.ITM_SUB3
				AND	w.WG_CD = t.WG_CD
				AND	w.CALC_CTG_CD = t.CALC_CTG_CD
			)
		FOR UPDATE NOWAIT
	;

	G_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;

	G_EXPNS_PROD	CONSTANT MAPA_META.EXPNS_TYP%TYPE := MAC_EXPNS_TYP.PROD ;

	G_MSG		FCPA_ERR.MSG_BINDER ;
	G_LOG_NO	MAPA_META.BATCH_LOG_NO%TYPE ;
	G_LOG_SUB_KEY1	MAPA_META.BATCH_LOG_SUB_KEY1%TYPE ;
	G_LOG_SUB_KEY2	MAPA_META.BATCH_LOG_SUB_KEY2%TYPE ;

PROCEDURE P_CHK_STD_RATE (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	標準配賦率の確定チェック
<REMARKS>

<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<HISTORY>
**************************************************************************/
IS
	L_ARG	MGT_ARG%ROWTYPE ;

	L_CNT1	NUMBER ;
	L_CNT2	NUMBER ;
	L_TS	MAPA_META.SYS_TS%TYPE ;
BEGIN
	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	IF L_ARG.CALC_ERR_FLG = '1' THEN
		FCPA_ERR.RAISE_APP_ERR('MGBED0003') ;
	END IF ;

	SELECT	COUNT(*)
	INTO	L_CNT1
	FROM	MGT_CALC_STD_ALC_RATE t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	IF L_ARG.ALC_CALC_TYP != MAC_ALC_CALC_TYP.NON AND L_CNT1 = 0 THEN
		SELECT	COUNT(*)
		INTO	L_CNT2
		FROM	MGT_ALC_CALC_RATE t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		;

		IF L_CNT2 <> 0 THEN
			FCPA_ERR.RAISE_APP_ERR('MGBED0005') ;
		END IF ;
	END IF ;

	SELECT	COUNT(*)
	INTO	L_CNT2
	FROM	MGT_CALC_STD_ALC_RATE t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_STD_ALC_RATE t2
			WHERE	0=0
			AND	t2.FIX_FLG = '1'
			AND	t2.TERM = L_ARG.TERM
			AND	t2.ALC_AC_CD = t.ALC_AC_CD
			AND	t2.CALC_CTG_CD = t.CALC_CTG_CD
			AND	t2.WG_CD = t.WG_CD
			AND	NVL(t2.DPT_CD, G_NULL_VAL) = NVL(t.DPT_CD, G_NULL_VAL)
			AND	NVL(t2.LOC_CD, G_NULL_VAL) = NVL(t.LOC_CD, G_NULL_VAL)
			AND	NVL(t2.OPER_CD,G_NULL_VAL) = NVL(t.OPER_CD,G_NULL_VAL)
			AND	NVL(t2.BP_CD,  G_NULL_VAL) = NVL(t.BP_CD,  G_NULL_VAL)
			AND	NVL(t2.CTG_CD, G_NULL_VAL) = NVL(t.CTG_CD, G_NULL_VAL)
			AND	NVL(t2.ITM_CD, G_NULL_VAL) = NVL(t.ITM_CD, G_NULL_VAL)
			AND	NVL(t2.ITM_SUB1, G_NULL_VAL) = NVL(t.ITM_SUB1, G_NULL_VAL)
			AND	NVL(t2.ITM_SUB2, G_NULL_VAL) = NVL(t.ITM_SUB2, G_NULL_VAL)
			AND	NVL(t2.ITM_SUB3, G_NULL_VAL) = NVL(t.ITM_SUB3, G_NULL_VAL)
		)
	;

	IF L_CNT1 <> L_CNT2 THEN
		FCPA_ERR.RAISE_APP_ERR('MGBED0005') ;
	END IF ;

	SELECT	MAX(t.UPD_TS)
	INTO	L_TS
	FROM	MGT_STD_ALC_RATE t
	WHERE	0=0
	AND	t.TERM = L_ARG.TERM
	AND	t.FIX_FLG = '1'
	AND	(t.CALC_NO != I_CALC_NO OR t.CALC_GRP_CD != I_CALC_GRP_CD)
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_STD_ALC_RATE t2
			WHERE	0=0
			AND	t2.CALC_NO = I_CALC_NO
			AND	t2.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t2.ALC_AC_CD = t.ALC_AC_CD
			AND	t2.CALC_CTG_CD = t.CALC_CTG_CD
			AND	t2.WG_CD = t.WG_CD
			AND	NVL(t2.DPT_CD, G_NULL_VAL) = NVL(t.DPT_CD, G_NULL_VAL)
			AND	NVL(t2.LOC_CD, G_NULL_VAL) = NVL(t.LOC_CD, G_NULL_VAL)
			AND	NVL(t2.OPER_CD,G_NULL_VAL) = NVL(t.OPER_CD,G_NULL_VAL)
			AND	NVL(t2.BP_CD,  G_NULL_VAL) = NVL(t.BP_CD,  G_NULL_VAL)
			AND	NVL(t2.CTG_CD, G_NULL_VAL) = NVL(t.CTG_CD, G_NULL_VAL)
			AND	NVL(t2.ITM_CD, G_NULL_VAL) = NVL(t.ITM_CD, G_NULL_VAL)
			AND	NVL(t2.ITM_SUB1, G_NULL_VAL) = NVL(t.ITM_SUB1, G_NULL_VAL)
			AND	NVL(t2.ITM_SUB2, G_NULL_VAL) = NVL(t.ITM_SUB2, G_NULL_VAL)
			AND	NVL(t2.ITM_SUB3, G_NULL_VAL) = NVL(t.ITM_SUB3, G_NULL_VAL)
		)
	;

	IF L_TS IS NOT NULL AND L_TS > L_ARG.INS_TS THEN
		FCPA_ERR.RAISE_APP_ERR('MGBED0006') ;
	END IF ;

END P_CHK_STD_RATE ;

PROCEDURE P_SET_CHILD (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	未確定の子品目を確定対象に含める
<REMARKS>

<ARGUMENTS>
<IN> I_CALC_GRP_CD
	計算グループＣＤ
<IN> I_CALC_NO
	原価計算ＮＯ
<HISTORY>
**************************************************************************/
IS
	L_CNT	NUMBER ;
	L_CNT1	NUMBER ;
	L_CNT2	NUMBER ;

	L_ARG	MGT_ARG%ROWTYPE ;
	L_STD_FIX_FLG	MAPA_META.FLG%TYPE ;
	L_STD_FIX_MAX	NUMBER ;
	L_PARM	MAPA_META.PARM_VAL%TYPE ;

BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_ITM_FIX.P_SET_CHILD') ;

	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	/** 品目をすべて対象としたときはチェックなし **/
	SELECT	COUNT(*)
	INTO	L_CNT1
	FROM	MGT_CALC_ITM t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	SELECT	COUNT(*)
	INTO	L_CNT2
	FROM	MGW_FIX_ITM w
	WHERE	0=0
	;

	IF L_CNT1 = L_CNT2 THEN
		GOTO SKIP_CHILD_ADD ;
	END IF ;

	L_STD_FIX_MAX := NULL ;
	L_STD_FIX_FLG := '0' ;

	FOR x IN (
		SELECT	t.PARM_KEY,
			t.PARM_VAL
		FROM	MGT_PARM t
		WHERE	0=0
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t.PARM_KEY LIKE 'STD%'
		)
	LOOP
		IF x.PARM_KEY = 'STD_FIX_CHD' AND x.PARM_VAL = '1' THEN
			L_STD_FIX_FLG := '1' ;
		END IF ;

		IF x.PARM_KEY = 'STD_FIX_CHD_MAX' THEN
			L_STD_FIX_MAX := x.PARM_VAL ;
		END IF ;
	END LOOP ;

	L_PARM := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;

	-- 未確定子品目を格納
	LOOP
		IF L_STD_FIX_FLG = '0' THEN
			GOTO SKIP_CHECK ;
		END IF ;

		L_CNT := -1 ;
		FOR x IN (
			SELECT	t.ITM_CD,
				t.ITM_SUB1,
				t.ITM_SUB2,
				t.ITM_SUB3,
				t.WG_CD,
				t.CALC_CTG_CD
			FROM	MGT_CALC_ITM t
			WHERE	0=0
			AND	t.CALC_NO = I_CALC_NO
			AND	t.CALC_GRP_CD = I_CALC_GRP_CD
			AND	NOT EXISTS (
					SELECT	'X'
					FROM	MGW_FIX_ITM w
					WHERE	0=0
					AND	w.ITM_CD = t.ITM_CD
					AND	w.ITM_SUB1 = t.ITM_SUB1
					AND	w.ITM_SUB2 = t.ITM_SUB2
					AND	w.ITM_SUB3 = t.ITM_SUB3
					AND	w.WG_CD = t.WG_CD
					AND	w.CALC_CTG_CD = t.CALC_CTG_CD
					)
			AND	EXISTS (
					SELECT	'X'
					FROM	MGT_STD_INPT w
					WHERE	0=0
					AND	w.CALC_NO = t.CALC_NO
					AND	w.CALC_GRP_CD = t.CALC_GRP_CD
					AND	w.ITM_CD = t.ITM_CD
					AND	w.ITM_SUB1 = t.ITM_SUB1
					AND	w.ITM_SUB2 = t.ITM_SUB2
					AND	w.ITM_SUB3 = t.ITM_SUB3
					AND	w.WG_CD = t.WG_CD
					AND	w.LVL = 1
					AND	EXISTS (
							SELECT	'X'
							FROM	MGT_STD_TOP w1, MGW_FIX_ITM w2
							WHERE	0=0
							AND	w1.CALC_NO = w.CALC_NO
							AND	w1.CALC_GRP_CD = w.CALC_GRP_CD
							AND	w1.TOP_REC_NO = w.TOP_REC_NO
							AND	w1.SLS_FLG = '0'
							AND	w1.ITM_CD = w2.ITM_CD
							AND	w1.ITM_SUB1 = w2.ITM_SUB1
							AND	w1.ITM_SUB2 = w2.ITM_SUB2
							AND	w1.ITM_SUB3 = w2.ITM_SUB3
							AND	w1.WG_CD = w2.WG_CD
						)
				)
			AND	NOT EXISTS (
					SELECT	'X'
					FROM	MGT_STD_FIX t1
					WHERE	0=0
					AND	t1.ITM_CD = t.ITM_CD
					AND	t1.ITM_SUB1 = t.ITM_SUB1
					AND	t1.ITM_SUB2 = t.ITM_SUB2
					AND	t1.ITM_SUB3 = t.ITM_SUB3
					AND	t1.CALC_CTG_CD = t.CALC_CTG_CD
					AND	t1.WG_CD = t.WG_CD
					AND	t1.TERM = L_ARG.TERM
				)
			)
		LOOP
			L_CNT := L_CNT + 1 ;

			IF L_STD_FIX_MAX IS NOT NULL AND L_CNT >= L_STD_FIX_MAX THEN
				FCPA_ERR.RAISE_APP_ERR('MGBED0010') ;
			END IF ;

			FCPA_BATCH_LOG.P_DATA_LOG('MGBED0009',
										G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
										MAPA_COMM.F_TO_DISP_ITM(x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3, L_PARM),
										x.CALC_CTG_CD, x.WG_CD) ;
		END LOOP ;

		-- 依頼先の未確定子品目チェック
		FOR x IN (
			SELECT DISTINCT
				t4.ITM_CD,
				t4.ITM_SUB1,
				t4.ITM_SUB2,
				t4.ITM_SUB3,
				t4.WG_CD,
				t4.CALC_CTG_CD
			FROM	MGW_FIX_ITM w,
				MGT_STD_TOP t1,
				MGT_STD_INPT t2,
				MGT_CALC_ITM_DTL t3,
				MGT_CALC_ITM t4
			WHERE	0=0
			AND	t1.CALC_NO = I_CALC_NO
			AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t1.SLS_FLG = '0'
			AND	t1.ITM_CD = w.ITM_CD
			AND	t1.ITM_SUB1 = w.ITM_SUB1
			AND	t1.ITM_SUB2 = w.ITM_SUB2
			AND	t1.ITM_SUB3 = w.ITM_SUB3
			AND	t1.WG_CD = w.WG_CD
			AND	t2.CALC_NO = t1.CALC_NO
			AND	t2.CALC_GRP_CD = t1.CALC_GRP_CD
			AND	t2.TOP_REC_NO = t1.TOP_REC_NO
			AND	t2.LVL <= 1
			AND	t3.CALC_NO = t2.CALC_NO
			AND	t3.CALC_GRP_CD = t2.CALC_GRP_CD
			AND	t3.ITM_CD = t2.ITM_CD
			AND	t3.ITM_SUB1 = t2.ITM_SUB1
			AND	t3.ITM_SUB2 = t2.ITM_SUB2
			AND	t3.ITM_SUB3 = t2.ITM_SUB3
			AND	t3.WG_CD = t2.WG_CD
			AND	t4.CALC_NO = t3.CALC_NO
			AND	t4.CALC_GRP_CD = t3.CALC_GRP_CD
			AND	t4.ITM_CD = t3.ITM_CD
			AND	t4.ITM_SUB1 = t3.ITM_SUB1
			AND	t4.ITM_SUB2 = t3.ITM_SUB2
			AND	t4.ITM_SUB3 = t3.ITM_SUB3
			AND	t4.WG_CD = t3.RQST_WG_CD
			AND	NOT EXISTS (
					SELECT	'X'
					FROM	MGW_FIX_ITM w1
					WHERE	0=0
					AND	w1.ITM_CD = t4.ITM_CD
					AND	w1.ITM_SUB1 = t4.ITM_SUB1
					AND	w1.ITM_SUB2 = t4.ITM_SUB2
					AND	w1.ITM_SUB3 = t4.ITM_SUB3
					AND	w1.WG_CD = t4.WG_CD
					AND	w1.CALC_CTG_CD = t4.CALC_CTG_CD
					)
			AND	NOT EXISTS (
					SELECT	'X'
					FROM	MGT_STD_FIX w2
					WHERE	0=0
					AND	w2.ITM_CD = t4.ITM_CD
					AND	w2.ITM_SUB1 = t4.ITM_SUB1
					AND	w2.ITM_SUB2 = t4.ITM_SUB2
					AND	w2.ITM_SUB3 = t4.ITM_SUB3
					AND	w2.CALC_CTG_CD = t4.CALC_CTG_CD
					AND	w2.WG_CD = t4.WG_CD
					AND	w2.TERM = L_ARG.TERM
					)
			)
		LOOP
			L_CNT := L_CNT + 1 ;

			IF L_STD_FIX_MAX IS NOT NULL AND L_CNT >= L_STD_FIX_MAX THEN
				FCPA_ERR.RAISE_APP_ERR('MGBED0010') ;
			END IF ;

			FCPA_BATCH_LOG.P_DATA_LOG('MGBED0009',
										G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
										MAPA_COMM.F_TO_DISP_ITM(x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3, L_PARM),
										x.CALC_CTG_CD, x.WG_CD) ;
		END LOOP ;

		IF L_CNT >= 0 THEN
			FCPA_ERR.RAISE_APP_ERR('MGBED0010') ;
		ELSE
			EXIT ;
		END IF ;

		<<SKIP_CHECK>>

		INSERT INTO MGW_FIX_ITM (
			ITM_CD,
			ITM_SUB1,
			ITM_SUB2,
			ITM_SUB3,
			WG_CD,
			CALC_CTG_CD
			)
		SELECT	t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.WG_CD,
			t.CALC_CTG_CD
		FROM	MGT_CALC_ITM t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_FIX_ITM w
				WHERE	0=0
				AND	w.ITM_CD = t.ITM_CD
				AND	w.ITM_SUB1 = t.ITM_SUB1
				AND	w.ITM_SUB2 = t.ITM_SUB2
				AND	w.ITM_SUB3 = t.ITM_SUB3
				AND	w.WG_CD = t.WG_CD
				AND	w.CALC_CTG_CD = t.CALC_CTG_CD
				)
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_STD_INPT w
				WHERE	0=0
				AND	w.CALC_NO = t.CALC_NO
				AND	w.CALC_GRP_CD = t.CALC_GRP_CD
				AND	w.ITM_CD = t.ITM_CD
				AND	w.ITM_SUB1 = t.ITM_SUB1
				AND	w.ITM_SUB2 = t.ITM_SUB2
				AND	w.ITM_SUB3 = t.ITM_SUB3
				AND	w.WG_CD = t.WG_CD
				AND	w.LVL >= 1
				AND	EXISTS (
						SELECT	'X'
						FROM	MGT_STD_TOP w1, MGW_FIX_ITM w2
						WHERE	0=0
						AND	w1.CALC_NO = w.CALC_NO
						AND	w1.CALC_GRP_CD = w.CALC_GRP_CD
						AND	w1.TOP_REC_NO = w.TOP_REC_NO
						AND	w1.SLS_FLG = '0'
						AND	w1.ITM_CD = w2.ITM_CD
						AND	w1.ITM_SUB1 = w2.ITM_SUB1
						AND	w1.ITM_SUB2 = w2.ITM_SUB2
						AND	w1.ITM_SUB3 = w2.ITM_SUB3
						AND	w1.WG_CD = w2.WG_CD
					)
			)
		;
		L_CNT := SQL%ROWCOUNT ;

		-- 依頼先の未確定子品目を格納
		INSERT INTO MGW_FIX_ITM (
			ITM_CD,
			ITM_SUB1,
			ITM_SUB2,
			ITM_SUB3,
			WG_CD,
			CALC_CTG_CD
			)
		SELECT	DISTINCT
			t4.ITM_CD,
			t4.ITM_SUB1,
			t4.ITM_SUB2,
			t4.ITM_SUB3,
			t4.WG_CD,
			t4.CALC_CTG_CD
		FROM	MGW_FIX_ITM w,
