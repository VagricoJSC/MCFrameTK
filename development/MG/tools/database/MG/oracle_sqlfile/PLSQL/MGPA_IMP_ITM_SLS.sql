							m21.ITM_SUB1,
							m21.ITM_SUB2,
							m21.ITM_SUB3,
							m21.CST_CD,
							m21.DLV_CD,
							m21.DEST_CD1,
							m21.DEST_CD2,
							m21.DEST_CD3,
							m21.UNIT_CD,
							m21.LOT_QTY,
							m21.CUR_CD,
							m21.WG_CD ORDER BY m21.ST_DT) AS ST_DT_RN
					FROM	MAM_CST_SLS_UPRI_ m21, MAM_ITM_SRCH m22, MAM_TERM m23, MAM_BP m24, MAM_CUR m25
