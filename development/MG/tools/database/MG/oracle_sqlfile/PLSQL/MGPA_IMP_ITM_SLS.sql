				m01.DEST_CD2,
				m01.DEST_CD3,
				m01.TERM,
				L_CALC_CTG_CD AS CALC_CTG_CD,
				m01.WG_CD,
				CASE m01.UNIT_CD
					WHEN m01.BASE_UNIT_CD THEN 1
					ELSE NVL(MAPA_CALC.F_RND(m02.CONV_QTY / m02.CONV_BASE_QTY, m01.BASE_UNIT_DEC_PLACE, m01.BASE_UNIT_RND_TYP), 1)
				END AS BASE_QTY,
