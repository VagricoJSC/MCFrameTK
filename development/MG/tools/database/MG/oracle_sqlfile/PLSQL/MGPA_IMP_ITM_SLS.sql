					m11.ITM_SUB2,
					m11.ITM_SUB3,
					m11.CST_CD,
					m11.DLV_CD,
					m11.DEST_CD1,
					m11.DEST_CD2,
					m11.DEST_CD3,
					m11.TERM,
					m11.WG_CD,
					m11.CUR_CD,
