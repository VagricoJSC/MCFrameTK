						m21.ITM_CD,
						m21.ITM_SUB1,
						m21.ITM_SUB2,
						m21.ITM_SUB3,
						C_NULL_VAL AS CST_CD,
						C_NULL_VAL AS DLV_CD,
						C_NULL_VAL AS DEST_CD1,
						C_NULL_VAL AS DEST_CD2,
						C_NULL_VAL AS DEST_CD3,
						m23.TERM,
						m21.WG_CD,
						m21.CUR_CD,
						m21.UPRI,
						NULL AS UPRI_RATE,
						m21.LOT_QTY,
						690 AS PRIO,
						m21.MEMO1,
						NVL(I_DT, GREATEST(m23.TERM, m21.ST_DT)) AS DT,
						m25.UPRI_DEC_PLACE,
						m21.UNIT_CD,
						m22.UNIT_CD AS BASE_UNIT_CD,
						m22.DEC_PLACE BASE_UNIT_DEC_PLACE,
						m22.RND_TYP BASE_UNIT_RND_TYP,
						MAPA_TAX.F_GET_SLS_TAX_CD(
							m21.ITM_CD,
							m21.ITM_SUB1,
							m21.ITM_SUB2,
							m21.ITM_SUB3,
							NULL,
							NVL(I_DT, GREATEST(m23.TERM, m21.ST_DT))) AS SLS_TAX_CD,
						C_RNDOFF AS SLS_TAX_RND_TYP,
						CASE
							WHEN m21.CUR_CD = C_MYCUR AND m21.UNIT_CD = m22.UNIT_CD THEN 1
							WHEN m21.CUR_CD <> C_MYCUR AND m21.UNIT_CD = m22.UNIT_CD THEN 2
							WHEN m21.CUR_CD = C_MYCUR AND m21.UNIT_CD <> m22.UNIT_CD THEN 3
							WHEN m21.CUR_CD <> C_MYCUR AND m21.UNIT_CD <> m22.UNIT_CD THEN 4
						END UNIT_CUR_PRIO,
						MAPA_XCHNG.F_XCHNG(
							m21.UPRI,
							MAPA_XCHNG.F_GET_SLS_XRATE_NE(m21.CUR_CD, NVL(I_DT, GREATEST(m23.TERM, m21.ST_DT))),
							m25.UPRI_DEC_PLACE,
							L_CO.XRATE_RND_TYP) AS BASE_CUR_UPRI,
						ROW_NUMBER() OVER (PARTITION BY
							m21.ITM_CD,
							m21.ITM_SUB1,
							m21.ITM_SUB2,
							m21.ITM_SUB3,
							m21.UNIT_CD,
							m21.LOT_QTY,
							m21.CUR_CD,
							m21.WG_CD ORDER BY m21.ST_DT) AS ST_DT_RN
					FROM	MAM_STD_SLS_UPRI_ m21, MAM_ITM_SRCH m22, MAM_TERM m23, MAM_CUR m25
					WHERE	0=0
					AND	m21.ITM_CD = m22.ITM_CD
					AND	m21.ITM_SUB1 = m22.ITM_SUB1
					AND	m21.ITM_SUB2 = m22.ITM_SUB2
					AND	m21.ITM_SUB3 = m22.ITM_SUB3
					AND	m22.DEL_FLG = C_OFF
					AND (
						I_DT IS NOT NULL AND m21.ST_DT <= I_DT AND m21.END_DT >= I_DT
						OR
						I_DT IS NULL AND m21.ST_DT < m23.TERM_END_YM AND m21.END_DT >= m23.TERM
						)
					AND	m21.CUR_CD = m25.CUR_CD
					AND	m21.DEL_FLG = C_OFF
					AND	L_STD_UPRI_FLG = C_ON
					AND	m21.NOT_COST_FLG = C_OFF
					AND	m23.TERM = I_TERM
					AND	(L_WG_CD IS NULL OR m21.WG_CD = L_WG_CD)
					AND	(I_IMP_OPE_TYP = MGC_IMP_OPE_TYP.BATCH
							OR EXISTS (
								SELECT	'X'
								FROM	MGW_IMP_INTERACTIVE_KEY wk
								WHERE	0=0
								AND	wk.ITM_CD = m21.ITM_CD
								AND	wk.ITM_SUB1 = m21.ITM_SUB1
								AND	wk.ITM_SUB2 = m21.ITM_SUB2
								AND	wk.ITM_SUB3 = m21.ITM_SUB3
								AND	wk.WG_CD = m21.WG_CD
							)
						)
					) m11, MAM_TAX m12, MAM_BP m13
				WHERE	0=0
				AND	m11.SLS_TAX_CD = m12.TAX_CD
				AND	m11.CST_CD = m13.BP_CD(+)
				AND	m11.ST_DT_RN = 1
				) m01, MAVM_ITM_UNIT m02
			WHERE	0=0
			AND	m01.ITM_CD = m02.ITM_CD
			AND	m01.ITM_SUB1 = m02.ITM_SUB1
			AND	m01.ITM_SUB2 = m02.ITM_SUB2
			AND	m01.ITM_SUB3 = m02.ITM_SUB3
			AND	m01.UNIT_CD = m02.UNIT_CD
			AND	m01.RN = 1
			ORDER BY
				m01.ITM_CD, m01.ITM_SUB1, m01.ITM_SUB2, m01.ITM_SUB3,
				m01.CST_CD, m01.DLV_CD, m01.DEST_CD1, m01.DEST_CD2, m01.DEST_CD3
			)
		LOOP
			IF x.UPRI_RATE IS NOT NULL AND x.UPRI IS NULL THEN
				-- 掛率の計算
				BEGIN
					SELECT	MAPA_CALC.F_RND(x.UPRI_RATE / 100 * m11s.UPRI, x.UPRI_DEC_PLACE, x.SLS_UPRI_RND_TYP)
					INTO	x.UPRI
					FROM	(
						SELECT
							m21s.*,
							ROW_NUMBER() OVER (
								PARTITION BY
									m21s.ITM_CD,
									m21s.ITM_SUB1,
									m21s.ITM_SUB2,
									m21s.ITM_SUB3,
									m21s.UNIT_CD,
									m21s.CUR_CD,
									m21s.ST_DT
								ORDER BY
									CASE m21s.WG_CD WHEN C_NULL_VAL THEN 2 ELSE 1 END, m21s.LOT_QTY) AS RN
						FROM	MAM_STD_SLS_UPRI_ m21s
						WHERE	0=0
						AND	m21s.ITM_CD = x.ITM_CD
						AND	m21s.ITM_SUB1 = x.ITM_SUB1
						AND	m21s.ITM_SUB2 = x.ITM_SUB2
						AND	m21s.ITM_SUB3 = x.ITM_SUB3
						AND	m21s.UNIT_CD = x.UNIT_CD
						AND	m21s.CUR_CD = x.CUR_CD
						AND	m21s.WG_CD IN (x.WG_CD, C_NULL_VAL)
						AND	m21s.ST_DT <= x.DT
						AND	m21s.END_DT >= x.DT
						AND	m21s.NOT_COST_FLG = C_OFF
						AND	m21s.DEL_FLG = C_OFF
						) m11s
					WHERE	0=0
					AND	m11s.RN = 1 ;
				EXCEPTION
				WHEN NO_DATA_FOUND THEN				
					--掛率が指定されていますが、標準販売単価マスタまたは通貨マスタが取得できません。
					--販売単価を取り込みません。品目：{1}得意先：{2}納品先：{3}通貨：{4}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0051', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						MAPA_COMM.F_TO_DISP_ITM(x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3, L_PARM),
						x.CST_CD,
						x.DLV_CD,
						x.CUR_CD) ;
	
					G_ERR_FLG := C_ON ;
					GOTO NEXT_LOOP ;
				END ;
			END IF ;

			i := i + 1 ;

			L_INS(i).ITM_CD := x.ITM_CD ;
			L_INS(i).ITM_SUB1 := x.ITM_SUB1 ;
			L_INS(i).ITM_SUB2 := x.ITM_SUB2 ;
			L_INS(i).ITM_SUB3 := x.ITM_SUB3 ;
			L_INS(i).DPT_CD := x.DPT_CD ;
			L_INS(i).CST_CD := x.CST_CD ;
			L_INS(i).DLV_CD := x.DLV_CD ;
			L_INS(i).DEST_CD1 := x.DEST_CD1 ;
			L_INS(i).DEST_CD2 := x.DEST_CD2 ;
			L_INS(i).DEST_CD3 := x.DEST_CD3 ;
			L_INS(i).TERM := x.TERM ;
			L_INS(i).CALC_CTG_CD := x.CALC_CTG_CD ;
			L_INS(i).WG_CD := x.WG_CD ;
			L_INS(i).BASE_QTY := x.BASE_QTY ;
			L_INS(i).CUR_CD := x.CUR_CD ;
			L_INS(i).UPRI := x.UPRI ;
			L_INS(i).PRIO := x.PRIO ;
			L_INS(i).ALC_VAL1 := x.ALC_VAL1 ;
			L_INS(i).ALC_VAL2 := x.ALC_VAL2 ;
			L_INS(i).ALC_VAL3 := x.ALC_VAL3 ;
			L_INS(i).ALC_VAL4 := x.ALC_VAL4 ;
			L_INS(i).ALC_VAL5 := x.ALC_VAL5 ;
			L_INS(i).RMRKS := x.RMRKS ;
			L_INS(i).SUB_CHAR1 := x.SUB_CHAR1 ;
			L_INS(i).SUB_CHAR2 := x.SUB_CHAR2 ;
			L_INS(i).SUB_CHAR3 := x.SUB_CHAR3 ;
			L_INS(i).NON_CALC_FLG := x.NON_CALC_FLG ;
			L_INS(i).IMP_ERR_FLG := x.IMP_ERR_FLG ;
			L_INS(i).IMP_FLG := x.IMP_FLG ;

			--税込単価の場合は税抜単価に換算する
			IF L_INS(i).UPRI <> 0 AND x.INC_TAX_FLG = C_ON THEN
				L_INS(i).UPRI := NVL(
					MAPA_AMT.F_GET_EXC_TAX_AMT(
						x.UPRI,
						1,
						x.SLS_TAX_RND_TYP,
						x.SLS_TAX_RND_TYP,
						x.UPRI_DEC_PLACE,
						'1',
						x.TAX_RATE,
						0)
					, x.UPRI) ;
			END IF ;

			IF i > C_MAX_CNT THEN
				FORALL j IN 1..i
					INSERT INTO MGW_IMP_ITM_SLS VALUES L_INS(j) ;
				L_INS.DELETE ;
				i := 0 ;
			END IF ;

			<<NEXT_LOOP>>
			NULL ;
		END LOOP ;

		IF i > 0 THEN
			FORALL j IN 1..i
				INSERT INTO MGW_IMP_ITM_SLS VALUES L_INS(j) ;
			L_INS.DELETE ;
		END IF ;

		L_INS.DELETE ;

	END P_INS_MGW_MAIN ;

	PROCEDURE P_IMP_MGT_MAIN (
		I_TERM			IN	MAPA_META.YM%TYPE,
		I_IMP_OPE_TYP		IN	MGPA_META.IMP_OPE_TYP%TYPE
	)
	/*********************************************************
	<SYNOPSIS>
			原価マスタ取込(品目販売)
	<REMARKS>
			取込メイン処理用プロシージャ
	<ARGUMENTS>
	<IN>	I_TERM
			期
	<IN>	I_IMP_OPE_TYP
			マスタ取込処理区分
	<HISTORY>
	**********************************************************/
	IS
		TYPE IMP_LIST IS TABLE OF MGT_ITM_SLS%ROWTYPE INDEX BY BINARY_INTEGER ;
		L_IMP		IMP_LIST ;
		L_IMP_TMP	IMP_LIST ;

		i		INTEGER := 0 ;
		k		INTEGER := 0 ;

		L_CHK_FLG	MAPA_META.FLG%TYPE ;
		L_PARM		MAPA_META.PARM_VAL%TYPE ;
		L_CALC_CTG_CD	MAPA_META.CALC_CTG_CD%TYPE ;
	BEGIN
		L_PARM := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;

		-- 個別取込ならデフォルトの計算カテゴリＣＤを使う
		-- 通常取込なら無視する
		IF I_IMP_OPE_TYP = MGC_IMP_OPE_TYP.INTERACTIVE THEN
			L_CALC_CTG_CD := MGPA_CO_PARM.F_GET_CALC_CTG_CD(NULL) ;
		ELSE
			L_CALC_CTG_CD := NULL;
		END IF;
		
		FOR z IN (
			SELECT	t.*,
				m.ASSET_MNG_TYP ASSET_MNG_TYP
			FROM	(
				SELECT	DISTINCT
					w.ITM_CD,
					w.ITM_SUB1,
					w.ITM_SUB2,
					w.ITM_SUB3
				FROM	MGW_IMP_ITM_SLS w
				WHERE	0=0
				AND	w.IMP_FLG = C_ON
				AND	w.UPD_USR_ID = G_USR
				AND	w.TERM = I_TERM
				AND	(L_CALC_CTG_CD IS NULL OR w.CALC_CTG_CD = L_CALC_CTG_CD)
				AND	(I_IMP_OPE_TYP = MGC_IMP_OPE_TYP.BATCH
							AND w.UPD_SRV_REQ_NO = FCPA_CONTEXT.F_GET_PROCESSID
						OR EXISTS (
							SELECT	'X'
							FROM	MGW_IMP_INTERACTIVE_KEY wk
							WHERE	0=0
							AND	wk.ITM_CD = w.ITM_CD
							AND	wk.ITM_SUB1 = w.ITM_SUB1
							AND	wk.ITM_SUB2 = w.ITM_SUB2
							AND	wk.ITM_SUB3 = w.ITM_SUB3
							AND	wk.WG_CD = w.WG_CD
						)
					)
				) t,
				MAM_ITM_SRCH m
			WHERE	0=0
			AND	t.ITM_CD = m.ITM_CD(+)
			AND	t.ITM_SUB1 = m.ITM_SUB1(+)
			AND	t.ITM_SUB2 = m.ITM_SUB2(+)
			AND	t.ITM_SUB3 = m.ITM_SUB3(+)
			AND	m.DEL_FLG(+) = C_OFF
			)
		LOOP
			/*** 品目チェック処理、エラーとなった品目と同じ品目のワークのデータは全件をエラーとして、取り込まない ***/
			IF z.ASSET_MNG_TYP IS NULL THEN
				-- 品目マスタに有効な品目として登録されていません。品目：{1}
				FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0023', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
					MAPA_COMM.F_TO_DISP_ITM(z.ITM_CD, z.ITM_SUB1, z.ITM_SUB2, z.ITM_SUB3, L_PARM)) ;

			UPDATE	MGW_IMP_ITM_SLS w
			SET	w.IMP_ERR_FLG = C_ON
			WHERE	0=0
			AND	w.ITM_CD = z.ITM_CD
			AND	w.ITM_SUB1 = z.ITM_SUB1
			AND	w.ITM_SUB2 = z.ITM_SUB2
			AND	w.ITM_SUB3 = z.ITM_SUB3
			AND	w.IMP_FLG = C_ON
			AND	w.UPD_USR_ID = G_USR
			AND	w.TERM = I_TERM
			;
			
			G_ERR_FLG := C_ON ;
			
			END IF ;
		END LOOP ;

		FOR x IN (
			SELECT	DISTINCT
				w.ITM_CD,
				w.ITM_SUB1,
				w.ITM_SUB2,
				w.ITM_SUB3,
				w.WG_CD,
				w.TERM,
				w.CALC_CTG_CD
			FROM	MGW_IMP_ITM_SLS w
			WHERE	0=0
			AND	w.IMP_FLG = C_ON
			AND	w.IMP_ERR_FLG = C_OFF
			AND	w.UPD_USR_ID = G_USR
			AND	w.TERM = I_TERM
			AND	(L_CALC_CTG_CD IS NULL OR w.CALC_CTG_CD = L_CALC_CTG_CD)
			AND	(I_IMP_OPE_TYP = MGC_IMP_OPE_TYP.BATCH
						AND w.UPD_SRV_REQ_NO = FCPA_CONTEXT.F_GET_PROCESSID
					OR EXISTS (
						SELECT	'X'
						FROM	MGW_IMP_INTERACTIVE_KEY wk
						WHERE	0=0
						AND	wk.ITM_CD = w.ITM_CD
						AND	wk.ITM_SUB1 = w.ITM_SUB1
						AND	wk.ITM_SUB2 = w.ITM_SUB2
						AND	wk.ITM_SUB3 = w.ITM_SUB3
						AND	wk.WG_CD = w.WG_CD
					)
				)
			)
		LOOP
			k := 0 ;
			FOR y IN (
				SELECT /*+INDEX(w MGW_IMP_ITM_SLS_ALL_IE03)*/
					w.ITM_CD,
					w.ITM_SUB1,
					w.ITM_SUB2,
					w.ITM_SUB3,
					w.DPT_CD,
					w.CST_CD,
					w.DLV_CD,
					w.DEST_CD1,
					w.DEST_CD2,
					w.DEST_CD3,
					w.TERM,
					w.CALC_CTG_CD,
					w.WG_CD,
					w.BASE_QTY,
					w.CUR_CD,
					w.UPRI,
					w.PRIO,
					w.ALC_VAL1,
					w.ALC_VAL2,
					w.ALC_VAL3,
					w.ALC_VAL4,
					w.ALC_VAL5,
					w.RMRKS,
					w.SUB_CHAR1,
					w.SUB_CHAR2,
					w.SUB_CHAR3,
					w.NON_CALC_FLG,
					w.IMP_ERR_FLG,
					w.IMP_FLG,
					m1.DPT_CD AS COST_DPT_CD,
					m2.BP_CD AS CST_BP_CD,
					m3.BP_CD AS DLV_BP_CD,
					m4.BP_CD AS DEST_CD1_BP_CD,
					m5.BP_CD AS DEST_CD2_BP_CD,
					m6.BP_CD AS DEST_CD3_BP_CD
				FROM	MGW_IMP_ITM_SLS w, MAM_COST_DPT m1, MAM_BP m2, MAM_BP m3, MAM_BP m4, MAM_BP m5, MAM_BP m6
				WHERE	0=0
				AND	w.DPT_CD = m1.DPT_CD(+)
				AND	w.TERM = m1.TERM(+)
				AND	w.CST_CD = m2.BP_CD(+)
				AND	w.DLV_CD = m3.BP_CD(+)
				AND	w.DEST_CD1 = m4.BP_CD(+)
				AND	w.DEST_CD2 = m5.BP_CD(+)
				AND	w.DEST_CD3 = m6.BP_CD(+)
				AND	w.ITM_CD = x.ITM_CD
				AND	w.ITM_SUB1 = x.ITM_SUB1
				AND	w.ITM_SUB2 = x.ITM_SUB2
				AND	w.ITM_SUB3 = x.ITM_SUB3
				AND	w.WG_CD = x.WG_CD
				AND	w.TERM = x.TERM
				AND	w.CALC_CTG_CD = x.CALC_CTG_CD
				AND	w.UPD_USR_ID = G_USR
				AND	w.IMP_FLG = C_ON
				)
			LOOP
				L_CHK_FLG := C_OFF ;

				/*** 取込対象データのチェック、品目、ワーキンググループ、期、計算カテゴリ、ユーザ単位でチェックする ***/
				IF y.BASE_QTY <= 0 THEN
					--基準数には正の数字を設定してください。
					--品目：{1} ワーキンググループ：{2} 期：{3} 計算カテゴリ：{4} 基準数：{5}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0037', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						MAPA_COMM.F_TO_DISP_ITM(x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3, L_PARM),
						x.WG_CD,
						FCPA_DATE_UTIL.F_TO_CHAR(x.TERM, FCPA_DATE_UTIL.Y4M),
						x.CALC_CTG_CD,
						y.BASE_QTY
						) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF y.DPT_CD <> C_NULL_VAL AND y.COST_DPT_CD IS NULL THEN
					--原価部門マスタに登録されていません。部門：{1}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBXD0041', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						y.DPT_CD,
						FCPA_DATE_UTIL.F_TO_CHAR(x.TERM, FCPA_DATE_UTIL.Y4M)) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF y.CST_CD <> C_NULL_VAL AND y.CST_BP_CD IS NULL THEN
					--取引先マスタに有効な取引先として登録されていません。得意先：{1}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0061', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						y.CST_CD) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF y.DLV_CD <> C_NULL_VAL AND y.DLV_BP_CD IS NULL THEN
					--取引先マスタに有効な取引先として登録されていません。納品先：{1}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0062', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						y.DLV_CD) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF y.DEST_CD1 <> C_NULL_VAL AND y.DEST_CD1_BP_CD IS NULL THEN
					--取引先マスタに有効な取引先として登録されていません。仕向先１：{1}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0063', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						y.DEST_CD1) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF y.DEST_CD2 <> C_NULL_VAL AND y.DEST_CD2_BP_CD IS NULL THEN
					--取引先マスタに有効な取引先として登録されていません。仕向先２：{1}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0064', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						y.DEST_CD2) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF y.DEST_CD3 <> C_NULL_VAL AND y.DEST_CD3_BP_CD IS NULL THEN
					--取引先マスタに有効な取引先として登録されていません。仕向先３：{1}
					FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0065', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
						y.DEST_CD3) ;
					L_CHK_FLG := C_ON ;
				END IF ;

				IF L_CHK_FLG = C_ON THEN
					UPDATE	MGW_IMP_ITM_SLS w
					SET	w.IMP_ERR_FLG = C_ON
					WHERE	0=0
					AND	w.ITM_CD = x.ITM_CD
					AND	w.ITM_SUB1 = x.ITM_SUB1
					AND	w.ITM_SUB2 = x.ITM_SUB2
					AND	w.ITM_SUB3 = x.ITM_SUB3
					AND	w.WG_CD = x.WG_CD
					AND	w.TERM = x.TERM
					AND	w.CALC_CTG_CD = x.CALC_CTG_CD
					AND	w.UPD_USR_ID = G_USR
					;

					G_ERR_FLG := C_ON ;

					GOTO NEXT_LOOP ;
				END IF ;

				k := k + 1 ;

				L_IMP_TMP(k).ITM_CD := y.ITM_CD ;
				L_IMP_TMP(k).ITM_SUB1 := y.ITM_SUB1 ;
				L_IMP_TMP(k).ITM_SUB2 := y.ITM_SUB2 ;
				L_IMP_TMP(k).ITM_SUB3 := y.ITM_SUB3 ;
				L_IMP_TMP(k).DPT_CD := y.DPT_CD ;
				L_IMP_TMP(k).CST_CD := y.CST_CD ;
				L_IMP_TMP(k).DLV_CD := y.DLV_CD ;
				L_IMP_TMP(k).DEST_CD1 := y.DEST_CD1 ;
				L_IMP_TMP(k).DEST_CD2 := y.DEST_CD2 ;
				L_IMP_TMP(k).DEST_CD3 := y.DEST_CD3 ;
				L_IMP_TMP(k).TERM := y.TERM ;
				L_IMP_TMP(k).CALC_CTG_CD := y.CALC_CTG_CD ;
				L_IMP_TMP(k).WG_CD := y.WG_CD ;
				L_IMP_TMP(k).BASE_QTY := y.BASE_QTY ;
				L_IMP_TMP(k).CUR_CD := y.CUR_CD ;
				L_IMP_TMP(k).UPRI := y.UPRI ;
				L_IMP_TMP(k).PRIO := y.PRIO ;
				L_IMP_TMP(k).ALC_VAL1 := y.ALC_VAL1 ;
				L_IMP_TMP(k).ALC_VAL2 := y.ALC_VAL2 ;
				L_IMP_TMP(k).ALC_VAL3 := y.ALC_VAL3 ;
				L_IMP_TMP(k).ALC_VAL4 := y.ALC_VAL4 ;
				L_IMP_TMP(k).ALC_VAL5 := y.ALC_VAL5 ;
				L_IMP_TMP(k).RMRKS := y.RMRKS ;
				L_IMP_TMP(k).SUB_CHAR1 := y.SUB_CHAR1 ;
				L_IMP_TMP(k).SUB_CHAR2 := y.SUB_CHAR2 ;
				L_IMP_TMP(k).SUB_CHAR3 := y.SUB_CHAR3 ;
				L_IMP_TMP(k).NON_CALC_FLG := y.NON_CALC_FLG ;
			END LOOP ;

			FOR l IN 1..k LOOP
				i := i + 1 ;
				L_IMP(i) := L_IMP_TMP(l) ;
			END LOOP ;

			IF i > C_MAX_CNT THEN
				FORALL j IN 1..i
					DELETE /*+INDEX(m MGT_ITM_SLS_ALL_PK)*/ MGT_ITM_SLS m
					WHERE	0=0
					AND	m.ITM_CD = L_IMP(j).ITM_CD
					AND	m.ITM_SUB1 = L_IMP(j).ITM_SUB1
					AND	m.ITM_SUB2 = L_IMP(j).ITM_SUB2
					AND	m.ITM_SUB3 = L_IMP(j).ITM_SUB3
					AND	m.TERM = L_IMP(j).TERM
					AND	m.CALC_CTG_CD = L_IMP(j).CALC_CTG_CD
					AND	m.WG_CD = L_IMP(j).WG_CD
					;
				FORALL j IN 1..i
					INSERT INTO MGT_ITM_SLS VALUES L_IMP(j) ;
				L_IMP.DELETE ;
				i := 0 ;
			END IF ;

			<<NEXT_LOOP>>
				L_IMP_TMP.DELETE ;
		END LOOP ;

		IF i > 0 THEN
			FORALL j IN 1..i
				DELETE /*+INDEX(m MGT_ITM_SLS_ALL_PK)*/ MGT_ITM_SLS m
				WHERE	0=0
				AND	m.ITM_CD = L_IMP(j).ITM_CD
				AND	m.ITM_SUB1 = L_IMP(j).ITM_SUB1
				AND	m.ITM_SUB2 = L_IMP(j).ITM_SUB2
				AND	m.ITM_SUB3 = L_IMP(j).ITM_SUB3
				AND	m.TERM = L_IMP(j).TERM
				AND	m.CALC_CTG_CD = L_IMP(j).CALC_CTG_CD
				AND	m.WG_CD = L_IMP(j).WG_CD
				;
			FORALL j IN 1..i
				INSERT INTO MGT_ITM_SLS VALUES L_IMP(j) ;
			L_IMP.DELETE ;
		END IF ;

		L_IMP_TMP.DELETE ;
		L_IMP.DELETE ;

	END P_IMP_MGT_MAIN ;

	PROCEDURE P_INS_MGW (
		I_CALC_CTG		IN	MAPA_META.CALC_CTG_CD%TYPE,
		I_WG_CD			IN	MAPA_META.WG_CD%TYPE,
