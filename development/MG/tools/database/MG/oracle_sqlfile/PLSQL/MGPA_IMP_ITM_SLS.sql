							WHEN m21.DLV_CD <> C_NULL_VAL AND m21.DEST_CD1 = C_NULL_VAL AND m21.DEST_CD2 = C_NULL_VAL AND m21.DEST_CD3 = C_NULL_VAL AND m21.UPRI IS NOT NULL THEN 150
