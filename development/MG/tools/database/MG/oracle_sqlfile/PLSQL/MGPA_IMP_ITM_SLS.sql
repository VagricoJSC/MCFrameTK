						END AS PRIO,
						m21.MEMO1,
						NVL(I_DT, GREATEST(m23.TERM, m21.ST_DT)) AS DT,
						m25.UPRI_DEC_PLACE,
						m21.UNIT_CD,
						m22.UNIT_CD AS BASE_UNIT_CD,
						m22.DEC_PLACE BASE_UNIT_DEC_PLACE,
