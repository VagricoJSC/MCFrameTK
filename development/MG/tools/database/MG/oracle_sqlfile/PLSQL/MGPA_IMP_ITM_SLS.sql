						END UNIT_CUR_PRIO,
						MAPA_XCHNG.F_XCHNG(
							m21.UPRI,
							MAPA_XCHNG.F_GET_SLS_XRATE_NE(m21.CUR_CD, NVL(I_DT, GREATEST(m23.TERM, m21.ST_DT))),
							m25.UPRI_DEC_PLACE,
							L_CO.XRATE_RND_TYP) AS BASE_CUR_UPRI,
						ROW_NUMBER() OVER (PARTITION BY
