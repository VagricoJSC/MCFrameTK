CREATE OR REPLACE PACKAGE BODY MGPA_IMP_ITM_SLS
IS
	C_OFF		CONSTANT MAPA_META.FLG%TYPE := '0' ;
	C_ON		CONSTANT MAPA_META.FLG%TYPE := '1' ;

	C_MAX_CNT	CONSTANT INTEGER := 50000 ; --バルクインサートでの最大レコード数
	C_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;
	C_RNDOFF	CONSTANT MAPA_META.RND_TYP%TYPE := MAC_RND_TYP.RNDOFF ;

	C_IMP_STD		CONSTANT MAPA_META.SLS_UPRI_IMP_TYP%TYPE := MAC_SLS_UPRI_IMP_TYP.STD ;
	C_IMP_ITM		CONSTANT MAPA_META.SLS_UPRI_IMP_TYP%TYPE := MAC_SLS_UPRI_IMP_TYP.ITM ;
	C_IMP_CST		CONSTANT MAPA_META.SLS_UPRI_IMP_TYP%TYPE := MAC_SLS_UPRI_IMP_TYP.CST ;
	C_IMP_STD_ITM		CONSTANT MAPA_META.SLS_UPRI_IMP_TYP%TYPE := MAC_SLS_UPRI_IMP_TYP.STD_ITM ;
	C_IMP_STD_ITM_CST	CONSTANT MAPA_META.SLS_UPRI_IMP_TYP%TYPE := MAC_SLS_UPRI_IMP_TYP.STD_ITM_CST ;

	G_ERR_FLG	MAPA_META.FLG%TYPE ;
	G_USR		MAPA_META.USR_ID%TYPE ;

   	G_LOG_NO	MAPA_META.BATCH_LOG_NO%TYPE ;
	G_LOG_SUB_KEY1	MAPA_META.BATCH_LOG_SUB_KEY1%TYPE ;
	G_LOG_SUB_KEY2	MAPA_META.BATCH_LOG_SUB_KEY2%TYPE ;

	PROCEDURE P_INS_MGW_MAIN (
		I_CALC_CTG		IN	MAPA_META.CALC_CTG_CD%TYPE,
		I_WG_CD			IN	MAPA_META.WG_CD%TYPE,
		I_TERM			IN	MAPA_META.YM%TYPE,
		I_DT			IN	MAPA_META.DT%TYPE,
		I_SLS_UPRI_IMP_TYP	IN	MAPA_META.SLS_UPRI_IMP_TYP%TYPE,
		I_IMP_OPE_TYP		IN	MGPA_META.IMP_OPE_TYP%TYPE
	)
	/*********************************************************
	<SYNOPSIS>
			品目販売マスタ用のデータをコピー用ワークテーブルに作成する
	<REMARKS>
			ワークテーブル作成メイン処理用プロシージャ
	<ARGUMENTS>
	<IN>	I_CALC_CTG
			計算カテゴリＣＤ
	<IN>	I_WG_CD
			ワーキンググループＣＤ
	<IN>	I_TERM
			期
	<IN>	I_DT
			対象日
	<IN>	I_SLS_UPRI_IMP_TYP
			販売単価取込区分
	<IN>	I_IMP_OPE_TYP
			マスタ取込処理区分
	<HISTORY>
	**********************************************************/
	IS
		TYPE INS_LIST IS TABLE OF MGW_IMP_ITM_SLS%ROWTYPE INDEX BY BINARY_INTEGER ;
		L_INS	INS_LIST ;
		i	INTEGER := 0 ;

		C_MYCUR	CONSTANT MAPA_META.CUR_CD%TYPE := MAPA_XCHNG.F_GET_BASE_CUR_CD ;

		L_STD_UPRI_FLG	MAPA_META.FLG%TYPE := C_OFF ;
		L_CST_UPRI_FLG	MAPA_META.FLG%TYPE := C_OFF ;
		L_ITM_UPRI_FLG	MAPA_META.FLG%TYPE := C_OFF ;

		L_CALC_CTG_CD	MAPA_META.CALC_CTG_CD%TYPE ;
		L_WG_CD		MAPA_META.WG_CD%TYPE ;
		L_PARM		MAPA_META.PARM_VAL%TYPE ;
		L_CO		MAM_CO%ROWTYPE := MAPA_CO.F_GET_CO_REC() ;
	BEGIN
	
		L_PARM := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;

		IF I_IMP_OPE_TYP = MGC_IMP_OPE_TYP.INTERACTIVE THEN
			-- デフォルトの計算カテゴリＣＤを使い、ワーキンググループＣＤは無視する
			L_CALC_CTG_CD := MGPA_CO_PARM.F_GET_CALC_CTG_CD(NULL) ;
			L_WG_CD := NULL ;
		ELSE
			L_CALC_CTG_CD := I_CALC_CTG;
			L_WG_CD := I_WG_CD ;
		END IF;

		DELETE	MGW_IMP_ITM_SLS w
		WHERE	0=0
		AND	w.CALC_CTG_CD = L_CALC_CTG_CD
		AND	w.TERM = I_TERM
		AND	(L_WG_CD IS NULL OR w.WG_CD = L_WG_CD)
		AND	(I_IMP_OPE_TYP = MGC_IMP_OPE_TYP.BATCH
				OR EXISTS (
					SELECT	'X'
					FROM	MGW_IMP_INTERACTIVE_KEY wk
					WHERE	0=0
					AND	wk.ITM_CD = w.ITM_CD
					AND	wk.ITM_SUB1 = w.ITM_SUB1
					AND	wk.ITM_SUB2 = w.ITM_SUB2
					AND	wk.ITM_SUB3 = w.ITM_SUB3
					AND	wk.WG_CD = w.WG_CD
				)
			)
		;

		IF I_SLS_UPRI_IMP_TYP = C_IMP_STD THEN
			L_STD_UPRI_FLG := C_ON ;
		ELSIF I_SLS_UPRI_IMP_TYP = C_IMP_ITM THEN
			L_ITM_UPRI_FLG := C_ON ;
		ELSIF I_SLS_UPRI_IMP_TYP = C_IMP_CST THEN
			L_CST_UPRI_FLG := C_ON ;
		ELSIF I_SLS_UPRI_IMP_TYP = C_IMP_STD_ITM THEN
			L_STD_UPRI_FLG := C_ON ;
			L_ITM_UPRI_FLG := C_ON ;
		ELSIF I_SLS_UPRI_IMP_TYP = C_IMP_STD_ITM_CST THEN
			L_STD_UPRI_FLG := C_ON ;
			L_ITM_UPRI_FLG := C_ON ;
			L_CST_UPRI_FLG := C_ON ;
		ELSE
			L_STD_UPRI_FLG := C_ON ;
			L_CST_UPRI_FLG := C_ON ;
			L_ITM_UPRI_FLG := C_ON ;
		END IF ;

		/*** ＳＣＭのマスタからコピーする ***/
		FOR x IN (
			SELECT
				m01.ITM_CD,
				m01.ITM_SUB1,
				m01.ITM_SUB2,
				m01.ITM_SUB3,
				C_NULL_VAL AS DPT_CD,
