CREATE OR REPLACE PACKAGE BODY MGC_ALC_REC_TYP
/*****************************
費用発生区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION AC_IMP RETURN VARCHAR2 DETERMINISTIC IS -- 費用取込
	BEGIN RETURN '1'; END AC_IMP;
	FUNCTION PURC_ALC RETURN VARCHAR2 DETERMINISTIC IS -- 購買振替
	BEGIN RETURN '2'; END PURC_ALC;
	FUNCTION OTHER_WG RETURN VARCHAR2 DETERMINISTIC IS -- 他ワーキンググループ
	BEGIN RETURN '3'; END OTHER_WG;
	FUNCTION MY_WG RETURN VARCHAR2 DETERMINISTIC IS -- 自ワーキンググループ
	BEGIN RETURN '4'; END MY_WG;
	FUNCTION CARRY RETURN VARCHAR2 DETERMINISTIC IS -- 繰越
	BEGIN RETURN '5'; END CARRY;

	FUNCTION IS_AC_IMP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 費用取込かどうか
	BEGIN
		IF I_VALUE = AC_IMP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_IMP;

	FUNCTION IS_PURC_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買振替かどうか
	BEGIN
		IF I_VALUE = PURC_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC_ALC;

	FUNCTION IS_OTHER_WG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 他ワーキンググループかどうか
	BEGIN
		IF I_VALUE = OTHER_WG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OTHER_WG;

	FUNCTION IS_MY_WG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 自ワーキンググループかどうか
	BEGIN
		IF I_VALUE = MY_WG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MY_WG;

	FUNCTION IS_CARRY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 繰越かどうか
	BEGIN
		IF I_VALUE = CARRY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CARRY;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = AC_IMP
		OR I_VALUE = PURC_ALC
		OR I_VALUE = OTHER_WG
		OR I_VALUE = MY_WG
		OR I_VALUE = CARRY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MGC_ALC_REC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MGC_ALC_REC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MGC_ALC_REC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MGC_ALC_REC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MGC_ALC_REC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MGC_ALC_REC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MGC_ALC_REC_TYP;

/
