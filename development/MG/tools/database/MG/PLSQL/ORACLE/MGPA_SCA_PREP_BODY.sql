PROCEDURE P_ITM_ADD
/**************************************************************************
<SYNOPSIS>
	品目指定計算を行ったときに関連する子品目を追加する
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
	TYPE ITM_LIST IS TABLE OF MGT_USR_ITM%ROWTYPE INDEX BY BINARY_INTEGER ;
	L_ITMS	ITM_LIST ;
	i	INTEGER ;
	L_USR	MAPA_META.FCM_USR_ID%TYPE ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_PREP.P_ITM_ADD') ;

	MGPA_CALC_CTG.P_SET_WORK(G_ARG.CALC_GRP_CD, MAC_CALC_CTG_TYP.BOM) ;
	L_USR := FCPA_CONTEXT.F_GET_USERID ;
	LOOP
		i := 0 ;
		FOR x IN (
			SELECT	DISTINCT
				m.CHD_ITM_CD,
				m.CHD_ITM_SUB1,
				m.CHD_ITM_SUB2,
				m.CHD_ITM_SUB3
			FROM	MGT_USR_ITM t, MGT_BOM m
			WHERE	0=0
			AND	t.USR_CD = L_USR
			AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
			AND	t.ITM_CD = m.PAR_ITM_CD
			AND	t.ITM_SUB1 = m.PAR_ITM_SUB1
			AND	t.ITM_SUB2 = m.PAR_ITM_SUB2
			AND	t.ITM_SUB3 = m.PAR_ITM_SUB3
			AND	m.TERM = G_ARG.TERM
			AND	EXISTS (
					SELECT	'X'
					FROM	MGW_CALC_CTG w
					WHERE	0=0
					AND	w.CALC_CTG_CD = m.CALC_CTG_CD
					)
			AND	(
				m.WG_CD = G_NULL_VAL
				OR EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG w2
					WHERE	0=0
					AND	w2.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	w2.WG_CD = m.WG_CD
					)
				)
			AND	NOT EXISTS (
					SELECT	'X'
					FROM	MGT_USR_ITM t2
					WHERE	0=0
					AND	t2.USR_CD = L_USR
					AND	t2.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	t2.ITM_CD = m.CHD_ITM_CD
					AND	t2.ITM_SUB1 = m.CHD_ITM_SUB1
					AND	t2.ITM_SUB2 = m.CHD_ITM_SUB2
					AND	t2.ITM_SUB3 = m.CHD_ITM_SUB3
					)
			)
		LOOP
			i := i + 1 ;
			L_ITMS(i).USR_CD := L_USR ;
			L_ITMS(i).CALC_GRP_CD := G_ARG.CALC_GRP_CD ;
			L_ITMS(i).ITM_CD := x.CHD_ITM_CD ;
			L_ITMS(i).ITM_SUB1 := x.CHD_ITM_SUB1 ;
			L_ITMS(i).ITM_SUB2 := x.CHD_ITM_SUB2 ;
			L_ITMS(i).ITM_SUB3 := x.CHD_ITM_SUB3 ;
		END LOOP ;

		EXIT WHEN i = 0 ;

		FORALL t IN 1..i
			INSERT INTO MGT_USR_ITM VALUES L_ITMS(t) ;

		L_ITMS.DELETE ;
	END LOOP ;

	L_ITMS.DELETE ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SCA_PREP.P_ITM_ADD') ;
END P_ITM_ADD ;

PROCEDURE P_SET_ALC
/**************************************************************************
<SYNOPSIS>
	予定配賦率の設定や配賦パタンの設定を行う
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
	L_CNT	NUMBER ;
	L_ROWID	ROWID ;

	TYPE ALC_KEY_REC IS RECORD (
		ROW_ID		ROWID,
		ALC_AC_CD	MAPA_META.ALC_AC_CD%TYPE,
		DPT_CD		MAPA_META.COST_DPT_CD%TYPE,
		LOC_CD		MAPA_META.LOC_CD%TYPE,
		OPER_CD		MAPA_META.OPER_CD%TYPE,
		BP_CD		MAPA_META.BP_CD%TYPE,
		CTG_CD		MAPA_META.COST_CTG_CD%TYPE,
		ITM_CD		MAPA_META.ITM_CD%TYPE,
		ITM_SUB1	MAPA_META.ITM_SUB1%TYPE,
		ITM_SUB2	MAPA_META.ITM_SUB2%TYPE,
		ITM_SUB3	MAPA_META.ITM_SUB3%TYPE,
		WG_CD		MAPA_META.WG_CD%TYPE,
		ALC_PTN_CD	MAPA_META.ALC_PTN_CD%TYPE,
		EXPNS_CD	MAPA_META.EXPNS_CD%TYPE
	) ;

	TYPE LIST_ALC_KEY IS TABLE OF ALC_KEY_REC INDEX BY BINARY_INTEGER ;
	ALC_KEY	LIST_ALC_KEY ;

	CURSOR CUR_CALC_STD_ALC_RATE
	IS
		SELECT	t.ROWID, t.ALC_AC_CD, t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD, t.CTG_CD,
				t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3, t.WG_CD, NULL, NULL
		FROM	MGT_CALC_STD_ALC_RATE t
		WHERE	0=0
		AND	t.CALC_NO = G_ARG.CALC_NO
		AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	t.ALC_PTN_CD IS NULL
	;

	CURSOR CUR_CALC_ALC_AMT
	IS
		SELECT	t.ROWID, t.ALC_AC_CD, t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD, t.CTG_CD,
				t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3, t.WG_CD, NULL, NULL
		FROM	MGT_CALC_ALC_AMT t
		WHERE	0=0
		AND	t.CALC_NO = G_ARG.CALC_NO
		AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	t.ALC_PTN_CD IS NULL
	;

	CURSOR CUR_CALC_IO
	IS
	SELECT	t.ROWID, t.ALC_AC_CD, t.ALC_DPT_CD, t.ALC_LOC_CD, t.ALC_OPER_CD, t.ALC_BP_CD, t.ALC_CTG_CD,
			t.ALC_ITM_CD, t.ALC_ITM_SUB1, t.ALC_ITM_SUB2, t.ALC_ITM_SUB3, DECODE(L_CNT, 0, t.WG_CD, NVL(t.ALC_WG_CD, t.WG_CD)), NULL, NULL
		FROM	MGT_CALC_IO t
		WHERE	0=0
		AND	t.CALC_NO = G_ARG.CALC_NO
		AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	t.ALC_AC_CD IS NOT NULL
		AND	t.ALC_AMT_FLG = '0'
		AND	t.ALC_PTN_CD IS NULL
	;

	C_MAX_ALC_KEY_CNT	CONSTANT BINARY_INTEGER := 10000 ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_PREP.P_SET_ALC') ;

	IF G_ARG.ALC_CALC_TYP = MAC_ALC_CALC_TYP.NON THEN
		GOTO SKIP_ALC_RATE_T ;
	END IF ;

	L_CNT := 0 ;
	DELETE MGW_ALC_RATE t ;
	MGPA_CALC_CTG.P_SET_WORK(G_ARG.CALC_GRP_CD, MAC_CALC_CTG_TYP.ALC_RATE_T) ;
	FOR L12 IN CTG_LIST LOOP
		INSERT INTO MGW_ALC_RATE (
			WG_CD,
			YM,
			ALC_AC_CD,
			DPT_CD, LOC_CD, OPER_CD, BP_CD,
			CTG_CD, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
			LOT_NO, SUBLOT_NO, SNO1, SNO2, SNO3, SNO4,
			ITM_MFG_INST_NO, IV_NO, PO_NO, SLO_NO,
			ALC_RATE
			)
		SELECT
			t.WG_CD,
			t.YM,
			t.ALC_AC_CD,
			t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
			t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
			t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
			t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
			t.ALC_RATE
		FROM	MGT_ALC_RATE t
		WHERE	0=0
		AND	(
			G_ARG.ALC_CALC_TYP = G_ALC_CALC_MONTH
					AND t.YM BETWEEN G_ARG.ST_YM AND G_ARG.END_YM
			OR
			G_ARG.ALC_CALC_TYP = G_ALC_CALC_TERM
					AND t.YM = G_ARG.END_YM
			)
		AND	t.CALC_CTG_CD = L12.CALC_CTG_CD
		AND	t.NO_CALC_FLG = '0'
		AND	(
			t.WG_CD = G_ARG.RUNTIME_WG_CD
			OR 
			G_ARG.RUNTIME_WG_CD IS NULL
				AND	EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG w2
					WHERE	0=0
					AND	w2.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	w2.WG_CD = t.WG_CD
				)
			)
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_RATE w
				WHERE	0=0
				AND	w.WG_CD = t.WG_CD
				AND	w.YM = t.YM
				AND	w.ALC_AC_CD = t.ALC_AC_CD
				AND	NVL(w.DPT_CD, G_NULL_VAL) = NVL(t.DPT_CD, G_NULL_VAL)
				AND	NVL(w.LOC_CD, G_NULL_VAL) = NVL(t.LOC_CD, G_NULL_VAL)
				AND	NVL(w.OPER_CD, G_NULL_VAL) = NVL(t.OPER_CD, G_NULL_VAL)
				AND	NVL(w.BP_CD, G_NULL_VAL) = NVL(t.BP_CD, G_NULL_VAL)
				AND	NVL(w.CTG_CD, G_NULL_VAL) = NVL(t.CTG_CD, G_NULL_VAL)
				AND	NVL(w.ITM_CD, G_NULL_VAL) = NVL(t.ITM_CD, G_NULL_VAL)
				AND	NVL(w.ITM_SUB1, G_NULL_VAL) = NVL(t.ITM_SUB1, G_NULL_VAL)
				AND	NVL(w.ITM_SUB2, G_NULL_VAL) = NVL(t.ITM_SUB2, G_NULL_VAL)
				AND	NVL(w.ITM_SUB3, G_NULL_VAL) = NVL(t.ITM_SUB3, G_NULL_VAL)
				AND	NVL(w.LOT_NO, G_NULL_VAL) = NVL(t.LOT_NO, G_NULL_VAL)
				AND	NVL(w.SUBLOT_NO, G_NULL_VAL) = NVL(t.SUBLOT_NO, G_NULL_VAL)
				AND	NVL(w.SNO1, G_NULL_VAL) = NVL(t.SNO1, G_NULL_VAL)
				AND	NVL(w.SNO2, G_NULL_VAL) = NVL(t.SNO2, G_NULL_VAL)
				AND	NVL(w.SNO3, G_NULL_VAL) = NVL(t.SNO3, G_NULL_VAL)
				AND	NVL(w.SNO4, G_NULL_VAL) = NVL(t.SNO4, G_NULL_VAL)
				AND	NVL(w.ITM_MFG_INST_NO, G_NULL_VAL) = NVL(t.ITM_MFG_INST_NO, G_NULL_VAL)
				AND	NVL(w.IV_NO, G_NULL_VAL) = NVL(t.IV_NO, G_NULL_VAL)
				AND	NVL(w.PO_NO, G_NULL_VAL) = NVL(t.PO_NO, G_NULL_VAL)
				AND	NVL(w.SLO_NO, G_NULL_VAL) = NVL(t.SLO_NO, G_NULL_VAL)
			)
		;

		L_CNT := L_CNT + SQL%ROWCOUNT ;
	END LOOP ;

	IF L_CNT = 0 THEN
		GOTO SKIP_ALC_RATE_T ;
	END IF ;

	FOR x IN (
		SELECT	w.*
		FROM	MGW_ALC_RATE w
		WHERE	0=0
		)
	LOOP
		L_ROWID := NULL ;
		FOR y IN (
			SELECT	t.ROWID ROW_ID,
				t.AMT
			FROM	MGT_CALC_ALC_AMT t
			WHERE	0=0
			AND	t.CALC_NO = G_ARG.CALC_NO
			AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
			AND	t.WG_CD = x.WG_CD
			AND	t.YM = x.YM
			AND	t.ALC_AC_CD = x.ALC_AC_CD
			AND	NVL(t.DPT_CD, G_NULL_VAL) = NVL(x.DPT_CD, G_NULL_VAL)
			AND	NVL(t.LOC_CD, G_NULL_VAL) = NVL(x.LOC_CD, G_NULL_VAL)
			AND	NVL(t.OPER_CD, G_NULL_VAL) = NVL(x.OPER_CD, G_NULL_VAL)
			AND	NVL(t.BP_CD, G_NULL_VAL) = NVL(x.BP_CD, G_NULL_VAL)
			AND	NVL(t.CTG_CD, G_NULL_VAL) = NVL(x.CTG_CD, G_NULL_VAL)
			AND	NVL(t.ITM_CD, G_NULL_VAL) = NVL(x.ITM_CD, G_NULL_VAL)
			AND	NVL(t.ITM_SUB1, G_NULL_VAL) = NVL(x.ITM_SUB1, G_NULL_VAL)
			AND	NVL(t.ITM_SUB2, G_NULL_VAL) = NVL(x.ITM_SUB2, G_NULL_VAL)
			AND	NVL(t.ITM_SUB3, G_NULL_VAL) = NVL(x.ITM_SUB3, G_NULL_VAL)
			AND	NVL(t.LOT_NO, G_NULL_VAL) = NVL(x.LOT_NO, G_NULL_VAL)
			AND	NVL(t.SUBLOT_NO, G_NULL_VAL) = NVL(x.SUBLOT_NO, G_NULL_VAL)
			AND	NVL(t.SNO1, G_NULL_VAL) = NVL(x.SNO1, G_NULL_VAL)
			AND	NVL(t.SNO2, G_NULL_VAL) = NVL(x.SNO2, G_NULL_VAL)
			AND	NVL(t.SNO3, G_NULL_VAL) = NVL(x.SNO3, G_NULL_VAL)
			AND	NVL(t.SNO4, G_NULL_VAL) = NVL(x.SNO4, G_NULL_VAL)
			AND	NVL(t.ITM_MFG_INST_NO, G_NULL_VAL) = NVL(x.ITM_MFG_INST_NO, G_NULL_VAL)
			AND	NVL(t.IV_NO, G_NULL_VAL) = NVL(x.IV_NO, G_NULL_VAL)
			AND	NVL(t.PO_NO, G_NULL_VAL) = NVL(x.PO_NO, G_NULL_VAL)
			AND	NVL(t.SLO_NO, G_NULL_VAL) = NVL(x.SLO_NO, G_NULL_VAL)
			)
		LOOP
			IF L_ROWID IS NULL THEN
				L_ROWID := y.ROW_ID ;
			ELSE
				UPDATE	MGT_CALC_ALC_AMT t
				SET	t.AMT = t.AMT + y.AMT
				WHERE	0=0
				AND	t.ROWID = L_ROWID
				;

				DELETE	MGT_CALC_ALC_AMT t WHERE	t.ROWID = y.ROW_ID ;
			END IF ;
		END LOOP ;
	END LOOP ;

	MERGE INTO MGT_CALC_ALC_AMT t
	USING	(
		SELECT	w.*
		FROM	MGW_ALC_RATE w
		WHERE	0=0
		) x
	ON	(0=0
		AND	t.CALC_NO = G_ARG.CALC_NO
		AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	t.WG_CD = x.WG_CD
		AND	t.YM = x.YM
		AND	t.ALC_AC_CD = x.ALC_AC_CD
		AND	NVL(t.DPT_CD, G_NULL_VAL) = NVL(x.DPT_CD, G_NULL_VAL)
		AND	NVL(t.LOC_CD, G_NULL_VAL) = NVL(x.LOC_CD, G_NULL_VAL)
		AND	NVL(t.OPER_CD, G_NULL_VAL) = NVL(x.OPER_CD, G_NULL_VAL)
		AND	NVL(t.BP_CD, G_NULL_VAL) = NVL(x.BP_CD, G_NULL_VAL)
		AND	NVL(t.CTG_CD, G_NULL_VAL) = NVL(x.CTG_CD, G_NULL_VAL)
		AND	NVL(t.ITM_CD, G_NULL_VAL) = NVL(x.ITM_CD, G_NULL_VAL)
		AND	NVL(t.ITM_SUB1, G_NULL_VAL) = NVL(x.ITM_SUB1, G_NULL_VAL)
		AND	NVL(t.ITM_SUB2, G_NULL_VAL) = NVL(x.ITM_SUB2, G_NULL_VAL)
		AND	NVL(t.ITM_SUB3, G_NULL_VAL) = NVL(x.ITM_SUB3, G_NULL_VAL)
		AND	NVL(t.LOT_NO, G_NULL_VAL) = NVL(x.LOT_NO, G_NULL_VAL)
		AND	NVL(t.SUBLOT_NO, G_NULL_VAL) = NVL(x.SUBLOT_NO, G_NULL_VAL)
		AND	NVL(t.SNO1, G_NULL_VAL) = NVL(x.SNO1, G_NULL_VAL)
		AND	NVL(t.SNO2, G_NULL_VAL) = NVL(x.SNO2, G_NULL_VAL)
		AND	NVL(t.SNO3, G_NULL_VAL) = NVL(x.SNO3, G_NULL_VAL)
		AND	NVL(t.SNO4, G_NULL_VAL) = NVL(x.SNO4, G_NULL_VAL)
		AND	NVL(t.ITM_MFG_INST_NO, G_NULL_VAL) = NVL(x.ITM_MFG_INST_NO, G_NULL_VAL)
		AND	NVL(t.IV_NO, G_NULL_VAL) = NVL(x.IV_NO, G_NULL_VAL)
		AND	NVL(t.PO_NO, G_NULL_VAL) = NVL(x.PO_NO, G_NULL_VAL)
		AND	NVL(t.SLO_NO, G_NULL_VAL) = NVL(x.SLO_NO, G_NULL_VAL)
		)
	WHEN MATCHED THEN
		UPDATE
		SET	t.INPT_ALC_TYP = G_INPT_ALC_ALC_RATE,
			t.ALC_RATE = x.ALC_RATE
	WHEN NOT MATCHED THEN
		INSERT	(
			CALC_NO, CALC_GRP_CD,
			INPT_ALC_TYP,
			WG_CD,
			YM, ALC_AC_CD,
			DPT_CD, LOC_CD, OPER_CD, BP_CD,
			CTG_CD, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
			LOT_NO, SUBLOT_NO,
			SNO1, SNO2, SNO3, SNO4,
			ITM_MFG_INST_NO,
			IV_NO, PO_NO, SLO_NO,
			AMT,
			ALC_RATE
			)
		VALUES	(
			G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
			G_INPT_ALC_ALC_RATE,
			x.WG_CD,
			x.YM, x.ALC_AC_CD,
			x.DPT_CD, x.LOC_CD, x.OPER_CD, x.BP_CD,
			x.CTG_CD, x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3,
			x.LOT_NO, x.SUBLOT_NO,
			x.SNO1, x.SNO2, x.SNO3, x.SNO4,
			x.ITM_MFG_INST_NO,
			x.IV_NO, x.PO_NO, x.SLO_NO,
			0,
			x.ALC_RATE
			)
		;

