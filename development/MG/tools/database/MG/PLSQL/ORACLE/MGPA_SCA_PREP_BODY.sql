		m.PARM_KEY,
		m.PARM_VAL,
		m.RMRKS,
		m.SUB_CHAR1,
		m.SUB_CHAR2,
		m.SUB_CHAR3
	FROM	(
		SELECT	m1.PARM_KEY,
			m1.PARM_VAL,
			m1.RMRKS,
			m1.SUB_CHAR1,
			m1.SUB_CHAR2,
			m1.SUB_CHAR3
		FROM	MGT_PARM m1
		WHERE	0=0
		AND	m1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	m1.PARM_VAL IS NOT NULL
