PROCEDURE P_SET_OTHER_TRD
/**************************************************************************
<SYNOPSIS>
	異なる計算グループ間の振替処理
<REMARKS>
	計算グループに対して計算順序グループが設定されていないときは引継ぎの処理は行わない
	1. 異なる計算グループからの振替出庫金額を対応する振替入庫の費目別原価に設定する
	2. 異なる計算グループへの振替出庫及び入庫の振替グループをＮＵＬＬにする
<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
	C_AMT_OTHER	CONSTANT MGPA_META.AMT_ADD_TYP%TYPE := MGC_AMT_ADD_TYP.OTHER_CALC ;

	C_EVAL_EXPNS	CONSTANT MGPA_META.REC_EVAL_TYP%TYPE := MGC_REC_EVAL_TYP.EXPNS ;

	C_COST_IO_STK_IN	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_IN ;
	C_COST_IO_STK_OUT	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_OUT ;

	TYPE LIST_YM IS TABLE OF MAPA_META.YM%TYPE INDEX BY BINARY_INTEGER ;
	rec_ym	LIST_YM ;
	idx	INTEGER ;

	L_CNT		NUMBER ;
	L_YM		MAPA_META.YM%TYPE ;
	L_CALC_NO	MAPA_META.CALC_NO%TYPE ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_PREP.P_SET_OTHER_TRD') ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_CALC_GRP m
	WHERE	0=0
	AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	m.CALC_SEQ_GRP IS NOT NULL
	AND	m.DEL_FLG = '0'
	;

	IF L_CNT = 0 THEN
		GOTO PROC_FIN ;
	END IF ;

	rec_ym.DELETE ;
	idx := 0 ;
	L_YM := G_ARG.ST_YM ;
	LOOP
		idx := idx + 1 ;
		rec_ym(idx) := L_YM ;

		IF L_YM >= G_ARG.END_YM THEN
			EXIT ;
		END IF ;

		L_YM := ADD_MONTHS(L_YM, 1) ;
	END LOOP ;

	IF idx = 0 THEN
		GOTO PROC_FIN ;
	END IF ;

	DELETE	MGW_CALC_IO_EXPNS_AMT ;

	--計算グループ間のチェック
	FOR x IN (
		SELECT	m1.CALC_GRP_CD,
			m1.CALC_SEQ_GRP,
			NVL(m1.CALC_SEQ, 0)	CALC_SEQ,
			m2.CALC_GRP_CD		CALC_GRP_CD2,
			NVL(m2.CALC_SEQ, 0)	CALC_SEQ2
		FROM	MAM_CALC_GRP m1, MAM_CALC_GRP m2
		WHERE	0=0
		AND	m1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	m1.CALC_SEQ_GRP IS NOT NULL
		AND	m1.DEL_FLG = '0'
		AND	m1.CALC_GRP_CD <> m2.CALC_GRP_CD
		AND	m1.CALC_SEQ_GRP = m2.CALC_SEQ_GRP
		AND	m2.DEL_FLG = '0'
		AND	NVL(m1.CALC_SEQ, 0) > NVL(m2.CALC_SEQ, 0)
		)
	LOOP
		FOR i IN 1..idx LOOP
			SELECT	MAX(t.CALC_NO)
			INTO	L_CALC_NO
			FROM	MGT_YM_NO t
			WHERE	0=0
			AND	t.CALC_GRP_CD = x.CALC_GRP_CD2
			AND	t.YM = rec_ym(i)
			;

			IF L_CALC_NO IS NULL THEN
				G_MSG := FCPA_ERR.MSG_BINDER(
						x.CALC_GRP_CD, x.CALC_SEQ_GRP, x.CALC_SEQ,
						x.CALC_GRP_CD2, x.CALC_SEQ2,
						FCPA_DATE_UTIL.F_TO_CHAR(rec_ym(i), FCPA_DATE_UTIL.Y4M)
						) ;
				FCPA_ERR.RAISE_APP_ERR('MGBDD0017', G_MSG) ;
			END IF ;

			--1. 異なる計算グループからの振替出庫金額を対応する振替入庫の費目別原価に設定する
			INSERT INTO MGW_CALC_IO_EXPNS_AMT (
				ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, ITM_EXT,
				WG_CD,
				ACT_IO_ID, ACT_IO_ID_SUB,
				EXPNS_CD,
				AMT
				)
			SELECT	/*+ LEADING(t1 w t2 t3 t4) */
				t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3, t1.ITM_EXT,
				t1.WG_CD,
				t1.ACT_IO_ID, t1.ACT_IO_ID_SUB,
				t4.EXPNS_CD,
				SUM(t4.ACT_COST)
			FROM	MGT_CALC_IO t1, MGT_CALC_IO_TRD t2,
				MGT_ACC_TOP t3, MGT_ACC_SML_COST t4
			WHERE	0=0
			AND	t1.CALC_NO = G_ARG.CALC_NO
			AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
			AND	t1.COST_IO_TYP = C_COST_IO_STK_IN
			AND	t1.REC_EVAL_TYP IS NULL
			AND	t1.TRD_GRP IS NOT NULL
			AND	t1.OTHER_WG_CD IS NOT NULL
			AND	t1.OTHER_WG_CD <> t1.WG_CD
			AND	NOT EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG w
					WHERE	0=0
					AND	w.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	w.WG_CD = t1.OTHER_WG_CD
					)
			AND	t1.YM = rec_ym(i)
			AND	t1.YM = t2.YM
			AND	t1.TRD_GRP = t2.TRD_GRP
			AND	t2.CALC_NO = L_CALC_NO
			AND	t2.CALC_GRP_CD = x.CALC_GRP_CD2
			AND	t2.CALC_NO = t3.CALC_NO
			AND	t2.CALC_GRP_CD = t3.CALC_GRP_CD
			AND	t2.ACT_IO_ID = t3.ACT_ID
			AND	t2.ACT_IO_ID_SUB = t3.ACT_ID_SUB
			AND	t3.CALC_REC_TYP = G_CALC_REC_IO
			AND	t3.COST_IO_TYP = C_COST_IO_STK_OUT
			AND	t3.CALC_NO = t4.CALC_NO
			AND	t3.CALC_GRP_CD = t4.CALC_GRP_CD
			AND	t3.TOP_REC_NO = t4.TOP_REC_NO
			GROUP BY t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3, t1.ITM_EXT,
				t1.WG_CD,
				t1.ACT_IO_ID, t1.ACT_IO_ID_SUB,
				t4.EXPNS_CD
			;

			INSERT INTO MGT_CALC_TRD_CALC_NO (
				CALC_NO, CALC_GRP_CD,
				YM,
				TRD_CALC_NO, TRD_CALC_GRP_CD
				)
			VALUES	(
				G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
				rec_ym(i),
				L_CALC_NO, x.CALC_GRP_CD2
				)
			;
		END LOOP ;
	END LOOP ;

	DELETE	MGT_CALC_IO_EXPNS_AMT t
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.AMT_ADD_TYP = C_AMT_OTHER
	;

	INSERT INTO MGT_CALC_IO_EXPNS_AMT (
		CALC_NO, CALC_GRP_CD,
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, ITM_EXT,
		WG_CD,
		ACT_IO_ID, ACT_IO_ID_SUB,
		EXPNS_CD,
		AMT_ADD_TYP,
		AMT
		)
	SELECT	G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
		w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, w.ITM_EXT,
		NVL(G_ARG.RUNTIME_WG_CD, w.WG_CD),
		w.ACT_IO_ID, w.ACT_IO_ID_SUB,
		w.EXPNS_CD,
		C_AMT_OTHER,
		SUM(w.AMT)
	FROM	MGW_CALC_IO_EXPNS_AMT w
	WHERE	0=0
	GROUP BY w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, w.ITM_EXT,
		NVL(G_ARG.RUNTIME_WG_CD, w.WG_CD),
		w.ACT_IO_ID, w.ACT_IO_ID_SUB,
		w.EXPNS_CD
	;

	UPDATE	MGT_CALC_IO t
	SET	t.REC_EVAL_TYP = C_EVAL_EXPNS
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.COST_IO_TYP = C_COST_IO_STK_IN
	AND	t.REC_EVAL_TYP IS NULL
	AND	t.TRD_GRP IS NOT NULL
	AND	t.OTHER_WG_CD IS NOT NULL
	AND	t.OTHER_WG_CD <> t.WG_CD
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_IO_EXPNS_AMT w
			WHERE	0=0
			AND	w.CALC_NO = t.CALC_NO
			AND	w.CALC_GRP_CD = t.CALC_GRP_CD
			AND	w.ITM_CD = t.ITM_CD
			AND	w.ITM_SUB1 = t.ITM_SUB1
			AND	w.ITM_SUB2 = t.ITM_SUB2
			AND	w.ITM_SUB3 = t.ITM_SUB3
			AND	w.ITM_EXT = t.ITM_EXT
			AND	w.WG_CD = t.WG_CD
			AND	w.ACT_IO_ID = t.ACT_IO_ID
			AND	w.ACT_IO_ID_SUB = t.ACT_IO_ID_SUB
			AND	w.AMT_ADD_TYP = C_AMT_OTHER
		)
	;

	--2. 異なる計算グループへの振替出庫及び入庫の振替グループをＮＵＬＬにする
	DELETE MGT_CALC_IO_TRD t WHERE t.CALC_NO = G_ARG.CALC_NO AND t.CALC_GRP_CD = G_ARG.CALC_GRP_CD ;
	INSERT INTO MGT_CALC_IO_TRD (
		CALC_NO, CALC_GRP_CD,
		ACT_IO_ID, ACT_IO_ID_SUB,
		YM, TRD_GRP,
		WG_CD, OTHER_WG_CD,
		COST_IO_TYP
		)
	SELECT	t.CALC_NO, t.CALC_GRP_CD,
		t.ACT_IO_ID, t.ACT_IO_ID_SUB,
		t.YM, t.TRD_GRP,
		t.WG_CD, t.OTHER_WG_CD,
		t.COST_IO_TYP
	FROM	MGT_CALC_IO t
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.COST_IO_TYP IN (C_COST_IO_STK_OUT, C_COST_IO_STK_IN)
	AND	t.TRD_GRP IS NOT NULL
	AND	t.OTHER_WG_CD IS NOT NULL
	AND	t.OTHER_WG_CD <> t.WG_CD
	AND	NOT EXISTS (
			SELECT	'X'
			FROM	MAM_GRP_WG w
			WHERE	0=0
			AND	w.CALC_GRP_CD = G_ARG.CALC_GRP_CD
			AND	w.WG_CD = t.OTHER_WG_CD
			)
	;

	UPDATE	MGT_CALC_IO t
	SET	t.TRD_GRP = NULL,
		t.TRD_RATIO = NULL,
		t.ALC_AC_CD = NULL
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.COST_IO_TYP IN (C_COST_IO_STK_OUT, C_COST_IO_STK_IN)
	AND	t.TRD_GRP IS NOT NULL
	AND	t.OTHER_WG_CD IS NOT NULL
	AND	t.OTHER_WG_CD <> t.WG_CD
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_IO_TRD w
			WHERE	0=0
			AND	w.CALC_NO = t.CALC_NO
			AND	w.CALC_GRP_CD = t.CALC_GRP_CD
			AND	w.ACT_IO_ID = t.ACT_IO_ID
			AND	w.ACT_IO_ID_SUB = t.ACT_IO_ID_SUB
		)
	;

	<<PROC_FIN>>
		NULL ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SCA_PREP.P_SET_OTHER_TRD') ;

END P_SET_OTHER_TRD ;

