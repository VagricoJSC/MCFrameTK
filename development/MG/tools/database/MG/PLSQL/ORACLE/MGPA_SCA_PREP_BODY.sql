			G_NULL_VAL	PARM_VAL,
			NULL		RMRKS,
			NULL		SUB_CHAR1,
			NULL		SUB_CHAR2,
			NULL		SUB_CHAR3
		FROM	DUAL
		WHERE	0=0
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGT_PARM x
				WHERE	0=0
				AND	x.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	x.PARM_KEY = 'SCA_NULL_VAL'
				AND	x.PARM_VAL IS NOT NULL
			)
		UNION ALL
		SELECT	'SCA_CHK'	PARM_KEY,
			'1'		PARM_VAL,
			NULL		RMRKS,
			NULL		SUB_CHAR1,
			NULL		SUB_CHAR2,
			NULL		SUB_CHAR3
		FROM	DUAL
		WHERE	0=0
		AND	G_ARG.DATA_CHECK_FLG = '1'
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGT_PARM x
				WHERE	0=0
				AND	x.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	x.PARM_KEY = 'SCA_CHK'
				AND	x.PARM_VAL IS NOT NULL
			)
		UNION ALL
		SELECT	'SCA_BCUR'	PARM_KEY,
			L_CO.BASE_CUR_CD	PARM_VAL,
			NULL		RMRKS,
			NULL		SUB_CHAR1,
			NULL		SUB_CHAR2,
			NULL		SUB_CHAR3
		FROM	DUAL
		WHERE	0=0
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGT_PARM x
				WHERE	0=0
				AND	x.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	x.PARM_KEY = 'SCA_BCUR'
				AND	x.PARM_VAL IS NOT NULL
			)
		UNION ALL
		SELECT	'ETC_STK_CALC_GRP'	PARM_KEY,
			G_ARG.CALC_GRP_CD	PARM_VAL,
			NULL			RMRKS,
			NULL			SUB_CHAR1,
			NULL			SUB_CHAR2,
			NULL			SUB_CHAR3
		FROM	DUAL
		WHERE	0=0
		AND	NOT EXISTS (
				SELECT	'X'
