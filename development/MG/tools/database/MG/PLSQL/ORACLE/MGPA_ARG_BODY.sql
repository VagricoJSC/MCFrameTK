PROCEDURE P_LOCK (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE,
	I_ERR_FLG	IN	MAPA_META.FLG%TYPE
)
/**************************************************************************
<SYNOPSIS>
	ロック処理
<REMARKS>
	NOWAITでロックする
	I_ERR_FLGが1となるときは対象となるデータが存在しないときはエラーとする
<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<IN>	I_ERR_FLG
		存在チェックＦＬＧ
<HISTORY>
**************************************************************************/
AS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	CURSOR LOCK_ARG
	IS
		SELECT	t.CALC_NO
		FROM	MGT_ARG t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		FOR UPDATE NOWAIT
	;

	L_REC	MGT_ARG%ROWTYPE ;
BEGIN
	IF I_ERR_FLG = '1' THEN
		L_REC := F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;
	END IF ;

	OPEN LOCK_ARG ;
	CLOSE LOCK_ARG ;

EXCEPTION
WHEN LOCK_ERROR THEN
	G_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, I_CALC_NO) ;
	FCPA_ERR.RAISE_APP_ERR('MGBXD0009', G_MSG) ;
END P_LOCK ;

END MGPA_ARG ;
