CREATE OR REPLACE PACKAGE BODY MGPA_ARG
IS
	G_MSG	FCPA_ERR.MSG_BINDER ;
	G_DEF_LENGTH	CONSTANT INTEGER := MAPA_META.CALC_NO_L ;
	G_MIN_LENGTH	CONSTANT INTEGER := 5 ;

PROCEDURE P_GET_CALC_NO_SUB (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_LENGTH	IN	INTEGER,
	O_CALC_NO	OUT	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	原価計算ＮＯの発番・取得を行う
<REMARKS>
	MGT_CALC_NOの更新
<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_LENGTH
		原価計算ＮＯの桁数
<OUT>	O_CALC_NO
		原価計算ＮＯ
<HISTORY>
**************************************************************************/
AS
BEGIN

	SELECT	TO_CHAR(TO_NUMBER(t.CALC_NO) + 1)
	INTO	O_CALC_NO
	FROM	MGT_CALC_NO t
	WHERE	0=0
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	FOR UPDATE
	;

	IF LENGTH(O_CALC_NO) < I_LENGTH THEN
		O_CALC_NO := LPAD(O_CALC_NO, I_LENGTH, '0') ;
	END IF ;

	UPDATE	MGT_CALC_NO t
	SET	t.CALC_NO = O_CALC_NO
	WHERE 	0=0
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

END P_GET_CALC_NO_SUB ;

PROCEDURE P_GET_CALC_NO (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	O_CALC_NO	OUT	MAPA_META.CALC_NO%TYPE
)
/**************************************************************************
<SYNOPSIS>
	原価計算ＮＯの発番・取得を行う
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<OUT>	O_CALC_NO
		原価計算ＮＯ
<HISTORY>
**************************************************************************/
AS
	L_CNT		NUMBER ;
	L_CALC_LENGTH	INTEGER ;
BEGIN
	O_CALC_NO := NULL ;

	BEGIN
		SELECT	NVL(MIN(m.PARM_VAL), G_DEF_LENGTH)
		INTO	L_CALC_LENGTH
		FROM	MGT_PARM m
		WHERE	0=0
		AND	m.CALC_GRP_CD = I_CALC_GRP_CD
		AND	m.PARM_KEY = 'ETC_CALC_LENGTH'
		;

		IF L_CALC_LENGTH < G_MIN_LENGTH OR L_CALC_LENGTH > G_DEF_LENGTH THEN
			L_CALC_LENGTH := G_DEF_LENGTH ;
		END IF ;
	EXCEPTION
	WHEN OTHERS THEN
		L_CALC_LENGTH := G_DEF_LENGTH ;
	END ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_CALC_NO t
	WHERE	0=0
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	IF L_CNT = 0 THEN
		O_CALC_NO := LPAD('1', L_CALC_LENGTH, '0') ;
		BEGIN
			INSERT INTO MGT_CALC_NO (
				CALC_GRP_CD,
				CALC_NO
				)
			VALUES	(
				I_CALC_GRP_CD,
				O_CALC_NO
				)
			;
		EXCEPTION
		WHEN OTHERS THEN
			P_GET_CALC_NO_SUB(I_CALC_GRP_CD, L_CALC_LENGTH, O_CALC_NO) ;
		END ;
	ELSE
		P_GET_CALC_NO_SUB(I_CALC_GRP_CD, L_CALC_LENGTH, O_CALC_NO) ;
	END IF ;

	IF O_CALC_NO IS NULL THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0006', G_MSG) ;
	END IF ;

	FOR x IN (
		SELECT	m.PARM_VAL	PRE
		FROM	MGT_PARM m
		WHERE	0=0
		AND	m.CALC_GRP_CD = I_CALC_GRP_CD
		AND	m.PARM_KEY = 'ETC_CALC_PRE'
		AND	m.PARM_VAL IS NOT NULL
		)
	LOOP
		O_CALC_NO := x.PRE || O_CALC_NO ;
	END LOOP ;

END P_GET_CALC_NO ;

PROCEDURE P_SET_ARG (
	I_TERM		IN	MAPA_META.YM%TYPE,
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_ST_YM	IN	MAPA_META.YM%TYPE,
	I_END_YM	IN	MAPA_META.YM%TYPE,
	I_XRATE_CD	IN	MAPA_META.XRATE_CD%TYPE,
	I_ITM_LIMIT_FLG	IN	MAPA_META.FLG%TYPE,
	I_CHECK_FLG	IN	MAPA_META.FLG%TYPE,
	I_CARRY_FLG	IN	MAPA_META.FLG%TYPE,
	I_RMRKS	IN	MGPA_META.CALC_ARG_RMRKS%TYPE,
	I_SUB_CHAR1	IN	MGPA_META.CALC_ARG_SUB_CHAR1%TYPE,
	I_SUB_CHAR2	IN	MGPA_META.CALC_ARG_SUB_CHAR2%TYPE,
	I_SUB_CHAR3	IN	MGPA_META.CALC_ARG_SUB_CHAR3%TYPE,
	O_CALC_NO	OUT	MAPA_META.CALC_NO%TYPE,
	O_CALC_CNT	OUT	MGPA_META.CALC_CNT%TYPE
)
/**************************************************************************
<SYNOPSIS>
	MGT_ARG_USRに対するデータ作成を行う
<REMARKS>

<ARGUMENTS>
<IN>	I_TERM
		対象期
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_ST_YM
		対象期間先頭月
<IN>	I_END_YM
		対象期間末尾月
<IN>	I_XRATE_CD
		為替レートＣＤ
<IN>	I_ITM_LIMIT_FLG
		品目指定ＦＬＧ
<IN>	I_CHECK_FLG
		データ確認計算ＦＬＧ
<IN>	I_CARRY_FLG
		繰越ＦＬＧ
<IN>	I_RMRKS
		備考
<IN>	I_SUB_CHAR1
		予備１
<IN>	I_SUB_CHAR2
		予備２
<IN>	I_SUB_CHAR3
		予備３
<OUT>	O_CALC_NO
		原価計算ＮＯ
<OUT>	O_CALC_CNT
		計算回数
<HISTORY>
**************************************************************************/
AS
	L_CALC_GRP	MAM_CALC_GRP%ROWTYPE ;
	L_USR		MAPA_META.FCM_USR_ID%TYPE ;
	L_PARM_CNT	NUMBER ;
	L_ITM_LIMIT_FLG	MAPA_META.FLG%TYPE ;
	L_STK_CALC_GRP_CD	MAPA_META.CALC_GRP_CD%TYPE ;
	L_WIP_CALC_GRP_CD	MAPA_META.CALC_GRP_CD%TYPE ;
	L_ETC_ITM_EXT	MAPA_META.CALC_PARM_VAL%TYPE ;
	L_PRE_CALC_GRP	MAPA_META.CALC_GRP_CD%TYPE ;
	L_PRE_CALC_NO	MAPA_META.CALC_NO%TYPE ;
	L_PRE_ETC_ITM_EXT	MAPA_META.CALC_PARM_VAL%TYPE ;
BEGIN
	/*** 原価計算ＮＯの取得 ***/
	P_GET_CALC_NO(I_CALC_GRP_CD, O_CALC_NO) ;

	/*** 計算グループマスタ情報の取得 ***/
	L_CALC_GRP := MGPA_CALC_GRP.F_GET_REC(I_CALC_GRP_CD) ;

	/*** 原価計算設定情報の作成 ***/
	SELECT	MAX(t.INS_USR_ID)
	INTO	L_USR
	FROM	MGT_ARG_USR t
	WHERE	0=0
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	IF L_USR IS NOT NULL THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, L_USR) ;
		FCPA_ERR.RAISE_APP_ERR('MGBDD0009', G_MSG) ;
	END IF ;

	SELECT	MIN(m.PARM_VAL)
	INTO	L_STK_CALC_GRP_CD
	FROM	MGT_PARM m
	WHERE	0=0
	AND	m.CALC_GRP_CD = I_CALC_GRP_CD
	AND	m.PARM_KEY = 'ETC_STK_CALC_GRP'
	AND	m.PARM_VAL IS NOT NULL
	AND m.PARM_VAL <> I_CALC_GRP_CD
	;

	SELECT	MIN(m.PARM_VAL)
	INTO	L_WIP_CALC_GRP_CD
	FROM	MGT_PARM m
	WHERE	0=0
	AND	m.CALC_GRP_CD = I_CALC_GRP_CD
	AND	m.PARM_KEY = 'ETC_WIP_CALC_GRP'
	AND	m.PARM_VAL IS NOT NULL
	AND m.PARM_VAL <> I_CALC_GRP_CD
	;

	SELECT	MIN(m.PARM_VAL)
	INTO	L_ETC_ITM_EXT
	FROM	MGT_PARM m
	WHERE	0=0
	AND	m.CALC_GRP_CD = I_CALC_GRP_CD
	AND	m.PARM_KEY = 'ETC_ITM_EXT'
	AND	m.PARM_VAL IS NOT NULL
	;

	BEGIN
		IF L_STK_CALC_GRP_CD IS NOT NULL THEN
			SELECT	t.CALC_GRP_CD, t.CALC_NO, t.PARM_VAL
			INTO	L_PRE_CALC_GRP, L_PRE_CALC_NO, L_PRE_ETC_ITM_EXT
			FROM	(
				SELECT	w.CALC_GRP_CD, w.CALC_NO, m.PARM_VAL
				FROM	MGVT_ARG_USR w, MGT_PARM m
				WHERE	0=0
				AND	w.CALC_GRP_CD = L_STK_CALC_GRP_CD
				AND	w.CALC_GRP_CD = m.CALC_GRP_CD(+)
				AND	m.PARM_KEY = 'ETC_ITM_EXT'
				ORDER BY	m.PARM_VAL
			) t
			WHERE	0=0
			AND	ROWNUM = 1
			;
		ELSE
			SELECT	t.CALC_GRP_CD, t.CALC_NO, t.PARM_VAL
			INTO	L_PRE_CALC_GRP, L_PRE_CALC_NO, L_PRE_ETC_ITM_EXT
			FROM	(
				SELECT	w.CALC_GRP_CD, w.CALC_NO, m2.PARM_VAL
				FROM	MGVT_ARG_USR w, MGT_PARM m1, MGT_PARM m2
				WHERE	0=0
				AND	w.CALC_GRP_CD = m1.CALC_GRP_CD
				AND	m1.PARM_KEY = 'ETC_STK_CALC_GRP'
				AND	m1.PARM_VAL = I_CALC_GRP_CD
				AND	w.CALC_GRP_CD = m2.CALC_GRP_CD(+)
				AND	m2.PARM_KEY = 'ETC_ITM_EXT'
				ORDER BY	m2.PARM_VAL
			) t
			WHERE	0=0
			AND	ROWNUM = 1
			;
		END IF ;
	EXCEPTION
	WHEN NO_DATA_FOUND THEN
		L_PRE_CALC_GRP := NULL ;
		L_PRE_CALC_NO := NULL ;
		L_PRE_ETC_ITM_EXT := NULL ;
	END ;

	IF L_PRE_CALC_GRP IS NOT NULL AND (L_ETC_ITM_EXT IS NOT NULL OR L_PRE_ETC_ITM_EXT IS NOT NULL) THEN
		G_MSG := FCPA_ERR.MSG_BINDER(L_PRE_CALC_GRP, L_PRE_CALC_NO) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0009', G_MSG) ;
	END IF ;

	BEGIN
		IF L_WIP_CALC_GRP_CD IS NOT NULL THEN
			SELECT	t.CALC_GRP_CD, t.CALC_NO, t.PARM_VAL
			INTO	L_PRE_CALC_GRP, L_PRE_CALC_NO, L_PRE_ETC_ITM_EXT
			FROM	(
				SELECT	w.CALC_GRP_CD, w.CALC_NO, m.PARM_VAL
				FROM	MGVT_ARG_USR w, MGT_PARM m
				WHERE	0=0
				AND	w.CALC_GRP_CD = L_WIP_CALC_GRP_CD
				AND	w.CALC_GRP_CD = m.CALC_GRP_CD(+)
				AND	m.PARM_KEY = 'ETC_ITM_EXT'
				ORDER BY	m.PARM_VAL
			) t
			WHERE	0=0
			AND	ROWNUM = 1
			;
		ELSE
			SELECT	t.CALC_GRP_CD, t.CALC_NO, t.PARM_VAL
			INTO	L_PRE_CALC_GRP, L_PRE_CALC_NO, L_PRE_ETC_ITM_EXT
			FROM	(
				SELECT	w.CALC_GRP_CD, w.CALC_NO, m2.PARM_VAL
				FROM	MGVT_ARG_USR w, MGT_PARM m1, MGT_PARM m2
				WHERE	0=0
				AND	w.CALC_GRP_CD = m1.CALC_GRP_CD
				AND	m1.PARM_KEY = 'ETC_WIP_CALC_GRP'
				AND	m1.PARM_VAL = I_CALC_GRP_CD
				AND	w.CALC_GRP_CD = m2.CALC_GRP_CD(+)
				AND	m2.PARM_KEY = 'ETC_ITM_EXT'
				ORDER BY	m2.PARM_VAL
			) t
			WHERE	0=0
			AND	ROWNUM = 1
			;
		END IF ;
	EXCEPTION
	WHEN NO_DATA_FOUND THEN
		L_PRE_CALC_GRP := NULL ;
		L_PRE_CALC_NO := NULL ;
		L_PRE_ETC_ITM_EXT := NULL ;
	END ;

	IF L_PRE_CALC_GRP IS NOT NULL AND (L_ETC_ITM_EXT IS NOT NULL OR L_PRE_ETC_ITM_EXT IS NOT NULL) THEN
		G_MSG := FCPA_ERR.MSG_BINDER(L_PRE_CALC_GRP, L_PRE_CALC_NO) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0009', G_MSG) ;
	END IF ;

	L_ITM_LIMIT_FLG := I_ITM_LIMIT_FLG ;
	IF L_ITM_LIMIT_FLG = '0' THEN
		SELECT	COUNT(*)
		INTO	L_PARM_CNT
		FROM	MGT_PARM m
		WHERE	0=0
		AND	m.CALC_GRP_CD = I_CALC_GRP_CD
		AND	m.PARM_KEY = 'ETC_ITM_LIMIT'
		AND	m.PARM_VAL = '1'
		;

		IF L_PARM_CNT > 0 THEN
			L_ITM_LIMIT_FLG := '1' ;
		END IF ;
	END IF ;

	IF I_CHECK_FLG = '0' THEN
		O_CALC_CNT := L_CALC_GRP.CALC_CNT ;
	ELSE
		O_CALC_CNT := 1 ;
	END IF ;

	INSERT INTO MGT_ARG_USR (
		CALC_NO,
		CALC_GRP_CD,
		TERM,
		ST_YM,
		END_YM,
		SA_TYP,
		EXP_CALC_TYP,
		PRE_ALC_CALC_TYP,
		ALC_CALC_TYP,
		COST_CALC_TYP,
		EVAL_TYP,
		INPT_CALC_FLG,
		WK_CALC_FLG,
		PROV_CALC_FLG,
		XFR_CALC_FLG,
		CALC_CNT,
		XRATE_CD,
		RUNTIME_WG_CD,
		CALC_ST,
		ITM_LIMIT_FLG,
		DATA_CHECK_FLG,
		CARRY_FLG,
		INS_SRV_REQ_NO,
		BATCH_LOG_NO,
		RMRKS,
		SUB_CHAR1,
		SUB_CHAR2,
		SUB_CHAR3
		)
	VALUES	(
		O_CALC_NO,
		I_CALC_GRP_CD,
		I_TERM,
		I_ST_YM,
		I_END_YM,
		L_CALC_GRP.SA_TYP,
		L_CALC_GRP.EXP_CALC_TYP,
		L_CALC_GRP.PRE_ALC_CALC_TYP,
		L_CALC_GRP.ALC_CALC_TYP,
		L_CALC_GRP.COST_CALC_TYP,
		L_CALC_GRP.EVAL_TYP,
		L_CALC_GRP.INPT_CALC_FLG,
		L_CALC_GRP.WK_CALC_FLG,
		L_CALC_GRP.PROV_CALC_FLG,
		L_CALC_GRP.XFR_CALC_FLG,
		O_CALC_CNT,
		NVL(I_XRATE_CD, L_CALC_GRP.XRATE_CD),
		L_CALC_GRP.RUNTIME_WG_CD,
		FCPA_DATE_UTIL.F_MCSYSTIMESTAMP,
		L_ITM_LIMIT_FLG,
		I_CHECK_FLG,
		I_CARRY_FLG,
		FCPA_CONTEXT.F_GET_PROCESSID,
		FCPA_BATCH_LOG.F_GET_LOG_NO,
		I_RMRKS,
		I_SUB_CHAR1,
		I_SUB_CHAR2,
		I_SUB_CHAR3
		)
	;

	COMMIT ; --ロック開放のため

END P_SET_ARG ;

FUNCTION F_GET_ARG_USR (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
RETURN MGT_ARG%ROWTYPE
/*********************************************************
<SYNOPSIS>
	MGT_ARG_USRのレコードを返す
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<RETURNVALUE>
	対象となるMGT_ARG_USRのレコード
<HISTORY>
**********************************************************/
AS
	L_REC	MGT_ARG%ROWTYPE ;
BEGIN
	BEGIN
		SELECT	t.*
		INTO	L_REC
		FROM	MGVT_ARG_USR t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		;
	EXCEPTION
	WHEN NO_DATA_FOUND THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, I_CALC_NO) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0007', G_MSG) ;
	END ;

	RETURN L_REC ;

END F_GET_ARG_USR ;

FUNCTION F_GET_ARG (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE
)
RETURN MGT_ARG%ROWTYPE
/*********************************************************
<SYNOPSIS>
	MGT_ARGのレコードを返す
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<RETURNVALUE>
	対象となるMGT_ARGのレコード
<HISTORY>
**********************************************************/
AS
	L_CNT	NUMBER ;
	L_REC	MGT_ARG%ROWTYPE ;
BEGIN
	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ARG t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	IF L_CNT > 0 THEN
		SELECT	t.*
		INTO	L_REC
		FROM	MGT_ARG t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		;
	ELSE
		L_REC := F_GET_ARG_USR(I_CALC_GRP_CD, I_CALC_NO) ;
	END IF ;

	RETURN L_REC ;

END F_GET_ARG ;


PROCEDURE P_CALC_FIN (
	I_CALC_GRP_CD	IN	MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN	MAPA_META.CALC_NO%TYPE,
	I_CALC_ERR_FLG	IN	MAPA_META.FLG%TYPE
)
/*********************************************************
<SYNOPSIS>
	計算終了処理
<REMARKS>
	MGT_ARG_USRからMGT_ARGにデータを作成する
<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<IN>	I_CALC_ERR_FLG
		エラーＦＬＧ
<HISTORY>
**********************************************************/
AS
	C_CALC_REC_ADJ		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.ADJ ;
	C_CALC_REC_END_STK	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.END_STK ;

	L_ALC_ERR_FLG	MAPA_META.FLG%TYPE ;
	L_TRD_AMT_FLG	MAPA_META.FLG%TYPE ;
	L_ADJ_AMT_FLG	MAPA_META.FLG%TYPE ;
	L_MINUS_STK_FLG	MAPA_META.FLG%TYPE ;
	L_OTHER_CHK_FLG	MAPA_META.FLG%TYPE ;

	L_CNT		NUMBER ;

	L_USR		MAPA_META.FCM_USR_ID%TYPE ;
BEGIN
	L_ALC_ERR_FLG := '0' ;
	L_TRD_AMT_FLG := '0' ;
	L_ADJ_AMT_FLG := '0' ;
	L_MINUS_STK_FLG := '0' ;
	L_OTHER_CHK_FLG := '0' ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ALC_CALC_ERR t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	t.AMT != 0
	;

	IF L_CNT > 0 THEN
		L_ALC_ERR_FLG := '1' ;
	END IF ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ACC_TRD t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	t.AMT != 0
	;

	IF L_CNT > 0 THEN
		L_TRD_AMT_FLG := '1' ;
	END IF ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ACC_TOP t1, MGT_ACC_SML_COST t2
	WHERE	0=0
	AND	t1.CALC_NO = I_CALC_NO
	AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
	AND	t1.CALC_REC_TYP = C_CALC_REC_ADJ
	AND	t1.CALC_NO = t2.CALC_NO
	AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
	AND	t1.TOP_REC_NO = t2.TOP_REC_NO
	AND	t2.ACT_COST != 0
	;

	IF L_CNT > 0 THEN
		L_ADJ_AMT_FLG := '1' ;
	END IF ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ACC_TOP t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	t.CALC_REC_TYP = C_CALC_REC_END_STK
	AND	t.QTY < 0
	;

	IF L_CNT > 0 THEN
		L_MINUS_STK_FLG := '1' ;
	END IF ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_CALC_CHK m
	WHERE	0=0
	AND	m.CALC_GRP_CD = I_CALC_GRP_CD
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_LOG w
			WHERE	0=0
			AND	w.CALC_NO = I_CALC_NO
			AND	w.CALC_GRP_CD = m.CALC_GRP_CD
			AND	w.MSG_ID LIKE m.MSG_ID
		)
	;

	IF L_CNT > 0 THEN
		L_OTHER_CHK_FLG := '1' ;
	END IF ;

	UPDATE 	MGT_ARG_USR t
	SET	t.CALC_FIN = FCPA_DATE_UTIL.F_MCSYSTIMESTAMP,
		t.ALC_ERR_FLG = L_ALC_ERR_FLG,
		t.TRD_AMT_FLG = L_TRD_AMT_FLG,
		t.ADJ_AMT_FLG = L_ADJ_AMT_FLG,
		t.MINUS_STK_FLG = L_MINUS_STK_FLG,
		t.OTHER_CHK_FLG = L_OTHER_CHK_FLG,
		t.CALC_ERR_FLG = I_CALC_ERR_FLG
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	INSERT INTO MGT_ARG
	SELECT	t.*
	FROM	MGT_ARG_USR t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	;

	DELETE	MGT_ARG_USR t WHERE t.CALC_NO = I_CALC_NO AND t.CALC_GRP_CD = I_CALC_GRP_CD ;

	L_USR := FCPA_CONTEXT.F_GET_USERID ;
	DELETE	MGT_USR_ITM t WHERE t.CALC_GRP_CD = I_CALC_GRP_CD AND t.USR_CD = L_USR ;

	IF I_CALC_ERR_FLG = '0' THEN
		SELECT	COUNT(*)
		INTO	L_CNT
		FROM	MGT_ARG t
		WHERE	0=0
		AND	t.CALC_NO = I_CALC_NO
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD
		AND	t.COST_CALC_TYP = MAC_COST_CALC_TYP.COST_STD
		AND	t.ALC_CALC_TYP <> MAC_ALC_CALC_TYP.NON
		;

		IF L_CNT > 0 THEN
			DELETE MGT_CALC_STD_ALC_RATE t WHERE t.CALC_NO = I_CALC_NO AND t.CALC_GRP_CD = I_CALC_GRP_CD ;
		END IF ;
	END IF ;
END P_CALC_FIN ;


