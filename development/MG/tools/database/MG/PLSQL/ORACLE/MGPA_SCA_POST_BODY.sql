PROCEDURE P_PROCZ
/**************************************************************************
<SYNOPSIS>
	複数回の計算を行うときの最後の処理
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
	C_WIP_LOC	CONSTANT MGPA_META.BATCH_TYP%TYPE:= MGC_BATCH_TYP.WIP_LOC ; -- 場所別仕掛原価データ作成処理
	C_IO		CONSTANT MGPA_META.BATCH_TYP%TYPE:= MGC_BATCH_TYP.IO ; -- 原価受払表データ作成処理

	L_WIP_LOC_FLG	MAPA_META.FLG%TYPE ;
	L_IO_FLG	MAPA_META.FLG%TYPE ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_POST.P_PROCZ') ;

	MGPA_SET_ITM_EXT.P_ITM_EXT_NULL(G_ARG) ;

	IF G_ARG.DATA_CHECK_FLG = '1' THEN
		GOTO PROC_FIN ;
	END IF ;

	L_WIP_LOC_FLG := '1' ;
	L_IO_FLG := '1' ;
	FOR x IN (
		SELECT	t.BATCH_TYP
		FROM	MGT_BATCH_OUT t
		WHERE	0=0
		AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		)
	LOOP
		CASE x.BATCH_TYP
		WHEN C_WIP_LOC THEN
			L_WIP_LOC_FLG := '0' ;
		WHEN C_IO THEN
			L_IO_FLG := '0' ;
		ELSE
			NULL ;
		END CASE ;
	END LOOP ;

	IF G_ARG.COST_CALC_TYP = MAC_COST_CALC_TYP.CALC_STK THEN
		P_SET_OTHER_TRD() ;
		IF L_IO_FLG = '1' THEN
			MGPA_IO.P_MAIN(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO) ;
		END IF ;
	END IF ;

	IF G_ARG.COST_CALC_TYP IN (MAC_COST_CALC_TYP.CALC_STK, MAC_COST_CALC_TYP.NOT_STK) THEN
		IF L_WIP_LOC_FLG = '1' THEN
			MGPA_WIP_LOC.P_MAIN(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO) ;
		END IF ;

		IF MGPA_CALC_FIX.F_CHK_FIX(G_ARG.CALC_GRP_CD, G_ARG.END_YM) = '0' THEN
			--最終年月が未確定のときのみ参照用のレコード及び前月データを作成する
			P_SET_ST_DATA() ;
			MGPA_CALC_FIX.P_INS_YM_NO(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO) ;
			COMMIT ;
		END IF ;

	END IF ;

	FOR x1 IN (
		SELECT	m.RPT_PTN_CD,
			m.RPT_KEY_CD
		FROM	MAM_CALC_RPT_PTN m
		WHERE	0=0
		AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	m.AUTO_FLG = '1'
		)
	LOOP
		MGPA_RPT.P_MAIN(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO, x1.RPT_PTN_CD, x1.RPT_KEY_CD, '0') ;
	END LOOP ;

	FOR x2 IN (
		SELECT	m.COST_IO_ID
		FROM	MAM_CALC_COST_IO m
		WHERE	0=0
		AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	m.AUTO_FLG = '1'
		)
	LOOP
		MGPA_COST_IO.P_MAIN(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO, x2.COST_IO_ID, '0') ;
	END LOOP ;

	IF G_ARG.CARRY_FLG = '1'
	AND G_ARG.COST_CALC_TYP IN (MAC_COST_CALC_TYP.CALC_STK, MAC_COST_CALC_TYP.NOT_STK) THEN
		MGPA_CARRY_OVER.P_MAIN(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO) ;
	END IF ;

	<<PROC_FIN>>
		NULL ;

	MGPA_ARG.P_CALC_FIN(G_ARG.CALC_GRP_CD, G_ARG.CALC_NO, '0') ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SCA_POST.P_PROCZ') ;

END P_PROCZ ;


