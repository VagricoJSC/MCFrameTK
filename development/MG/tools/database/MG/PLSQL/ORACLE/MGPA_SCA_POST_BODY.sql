CREATE OR REPLACE PACKAGE BODY MGPA_SCA_POST
IS
	G_ARG	MGT_ARG%ROWTYPE ;

	G_CALC_REC_IO		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.IO ;
	G_CALC_REC_INST		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.INST ;
	G_CALC_REC_ST_WIP	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.ST_WIP ;

	G_COST_IO_STK_IN	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_IN ;
	G_COST_IO_STK_OUT	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_OUT ;

	G_AMT_ALC	CONSTANT MGPA_META.AMT_ADD_TYP%TYPE := MGC_AMT_ADD_TYP.ALC ;

	G_EVAL_EXPNS	CONSTANT MGPA_META.REC_EVAL_TYP%TYPE := MGC_REC_EVAL_TYP.EXPNS ;
	G_EVAL_ZERO	CONSTANT MGPA_META.REC_EVAL_TYP%TYPE := MGC_REC_EVAL_TYP.ZERO ;
	G_LOG_NO	MAPA_META.BATCH_LOG_NO%TYPE ;
	G_LOG_SUB_KEY1	MAPA_META.BATCH_LOG_SUB_KEY1%TYPE ;
	G_LOG_SUB_KEY2	MAPA_META.BATCH_LOG_SUB_KEY2%TYPE ;
	G_PARM_ITM_SUB_TYP	MAPA_META.PARM_VAL%TYPE := NULL ;
	G_PARM_SNO_TYP	MAPA_META.PARM_VAL%TYPE := NULL ;

PROCEDURE P_SET_SO_ALC
/**************************************************************************
<SYNOPSIS>
	出庫による配賦金額を配賦費用へ設定する
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_POST.P_SET_SO_ALC') ;

	G_PARM_ITM_SUB_TYP := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;
	G_PARM_SNO_TYP := MAPA_COMM.F_GET_PARM('SNO_TYP') ;


	DELETE	MGT_CALC_IO_EXPNS_AMT t
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.AMT_ADD_TYP = G_AMT_ALC
	;

	INSERT INTO MGT_CALC_IO_EXPNS_AMT (
		CALC_NO, CALC_GRP_CD,
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, ITM_EXT,
		WG_CD,
		ACT_IO_ID, ACT_IO_ID_SUB,
		EXPNS_CD,
		AMT_ADD_TYP,
		AMT
		)
	SELECT	G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
		t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3, t1.ITM_EXT,
		t1.WG_CD,
		t1.ACT_IO_ID, t1.ACT_IO_ID_SUB,
		t3.EXPNS_CD,
		G_AMT_ALC,
		SUM(t3.ACT_COST)
	FROM	MGT_CALC_IO t1, MGT_ACC_TOP_TMP t2, MGT_ACC_SML_COST_TMP t3
	WHERE	0=0
	AND	t1.CALC_NO = G_ARG.CALC_NO
	AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t1.ALC_AC_CD IS NOT NULL
	AND	t1.ALC_AMT_FLG = '1'
	AND	t1.COST_IO_TYP = G_COST_IO_STK_OUT
	AND	t1.CALC_NO = t2.CALC_NO
	AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
	AND	t1.ACT_IO_ID = t2.ACT_ID
	AND	t1.ACT_IO_ID_SUB = t2.ACT_ID_SUB
	AND	t1.COST_IO_TYP = t2.COST_IO_TYP
	AND	t2.CALC_REC_TYP = G_CALC_REC_IO
	AND	t2.CALC_NO = t3.CALC_NO
	AND	t2.CALC_GRP_CD = t3.CALC_GRP_CD
	AND	t2.TOP_REC_NO = t3.TOP_REC_NO
	AND	t3.ACT_COST != 0
	GROUP BY t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3, t1.ITM_EXT,
		t1.WG_CD,
		t1.ACT_IO_ID, t1.ACT_IO_ID_SUB,
		t3.EXPNS_CD
	;

	FOR x IN (
		SELECT t1.CALC_NO, t1.CALC_GRP_CD, t1.ACT_IO_ID, t1.ACT_IO_ID_SUB,
			t1.YM, t1.WG_CD, t1.MNG_DPT_CD, t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
			t1.LOT_NO, t1.SUBLOT_NO, t1.SNO1, t1.SNO2, t1.SNO3, t1.SNO4, t1.ASST_TYP, t1.ALC_AC_CD
		FROM MGT_CALC_IO t1, MGT_ACC_TOP_TMP t2
		WHERE 0=0
		AND t1.CALC_NO = G_ARG.CALC_NO
		AND t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND t1.ALC_AC_CD IS NOT NULL
		AND t1.ALC_AMT_FLG = '1'
		AND t1.COST_IO_TYP = G_COST_IO_STK_OUT
		AND t1.CALC_NO = t2.CALC_NO
		AND t1.CALC_GRP_CD = t2.CALC_GRP_CD
		AND t1.ACT_IO_ID = t2.ACT_ID
		AND t1.ACT_IO_ID_SUB = t2.ACT_ID_SUB
		AND t1.COST_IO_TYP = t2.COST_IO_TYP
		AND t2.CALC_REC_TYP = G_CALC_REC_IO
		AND t1.REC_EVAL_TYP IS NULL
		AND NOT EXISTS (
			SELECT 'X' FROM MGT_CALC_IO_EXPNS_AMT w
			WHERE w.CALC_NO = t1.CALC_NO
			AND w.CALC_GRP_CD = t1.CALC_GRP_CD
			AND w.ACT_IO_ID = t1.ACT_IO_ID
			AND w.ACT_IO_ID_SUB = t1.ACT_IO_ID_SUB)
		)
	LOOP
		UPDATE MGT_CALC_IO t1
		SET t1.REC_EVAL_TYP = G_EVAL_ZERO
		WHERE 0=0
		AND t1.CALC_NO = x.CALC_NO
		AND t1.CALC_GRP_CD = x.CALC_GRP_CD
		AND t1.ACT_IO_ID = x.ACT_IO_ID
		AND t1.ACT_IO_ID_SUB = x.ACT_IO_ID_SUB
		;

		FCPA_BATCH_LOG.P_DATA_LOG('MGBXD0049', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
			FCPA_DATE_UTIL.F_TO_CHAR(x.YM, FCPA_DATE_UTIL.Y4M), x.WG_CD, x.MNG_DPT_CD,
			MAPA_COMM.F_TO_DISP_ITM(x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3, G_PARM_ITM_SUB_TYP),
			x.LOT_NO, x.SUBLOT_NO,
			MAPA_COMM.F_TO_DISP_SNO(x.SNO1, x.SNO2, x.SNO3, x.SNO4, G_PARM_SNO_TYP),
			x.ASST_TYP, x.ALC_AC_CD, x.ACT_IO_ID, x.ACT_IO_ID_SUB);
	END LOOP ;

	UPDATE	MGT_CALC_IO t1
	SET	t1.REC_EVAL_TYP = G_EVAL_EXPNS
	WHERE	0=0
	AND	t1.CALC_NO = G_ARG.CALC_NO
	AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t1.ALC_AC_CD IS NOT NULL
	AND	t1.ALC_AMT_FLG = '1'
	AND	t1.COST_IO_TYP = G_COST_IO_STK_OUT
	AND	t1.REC_EVAL_TYP IS NULL
	;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SCA_POST.P_SET_SO_ALC') ;

END P_SET_SO_ALC ;

PROCEDURE P_SET_OTHER_TRD
/**************************************************************************
<SYNOPSIS>
	異なる計算グループ間の振替処理
<REMARKS>
	MGPA_SCA_PREPでＮＵＬＬにした振替グループを計算結果へ設定する
<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_POST.P_SET_OTHER_TRD') ;

	UPDATE	MGT_ACC_TOP t
	SET	t.TRD_GRP = (
			SELECT	x.TRD_GRP
			FROM	MGT_CALC_IO_TRD x
			WHERE	0=0
			AND	x.CALC_NO = t.CALC_NO
			AND	x.CALC_GRP_CD = t.CALC_GRP_CD
			AND	x.ACT_IO_ID = t.ACT_ID
			AND	x.ACT_IO_ID_SUB = t.ACT_ID_SUB
			)
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.TRD_GRP IS NULL
	AND	t.CALC_REC_TYP = G_CALC_REC_IO
	AND	t.COST_IO_TYP IN (G_COST_IO_STK_OUT, G_COST_IO_STK_IN)
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_CALC_IO_TRD w
			WHERE	0=0
			AND	w.CALC_NO = t.CALC_NO
			AND	w.CALC_GRP_CD = t.CALC_GRP_CD
			AND	w.ACT_IO_ID = t.ACT_ID
			AND	w.ACT_IO_ID_SUB = t.ACT_ID_SUB
		)
	;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SCA_POST.P_SET_OTHER_TRD') ;
END P_SET_OTHER_TRD ;

PROCEDURE P_SET_ST_DATA
/**************************************************************************
<SYNOPSIS>
	月初情報を前月データの計算結果として作成する
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
	L_CNT		NUMBER ;
	L_YM		MAPA_META.YM%TYPE ;
	L_TMP_NO	CONSTANT MAPA_META.CALC_NO%TYPE := '0' ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SCA_POST.P_SET_ST_DATA') ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ARG t
	WHERE	0=0
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.ST_YM < G_ARG.ST_YM
	;

	IF L_CNT > 0 THEN
		RETURN ;
	END IF ;

	L_YM := ADD_MONTHS(G_ARG.ST_YM, -1) ;

	DELETE	MGT_YM_NO t
	WHERE	0=0
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	(t.YM = L_YM OR t.CALC_NO = L_TMP_NO)
	;

	INSERT INTO MGT_YM_NO (
		CALC_GRP_CD,
		YM,
		CALC_NO
		)
	VALUES	(
		G_ARG.CALC_GRP_CD,
		L_YM,
		L_TMP_NO
		)
	;

	-- 月初仕掛データの作成（内訳照会用）
	DELETE MGT_ACC_TOP  t WHERE t.CALC_GRP_CD = G_ARG.CALC_GRP_CD AND t.CALC_NO = L_TMP_NO ;
	DELETE MGT_ACC_INPT t WHERE t.CALC_GRP_CD = G_ARG.CALC_GRP_CD AND t.CALC_NO = L_TMP_NO ;
	DELETE MGT_ACC_COST t WHERE t.CALC_GRP_CD = G_ARG.CALC_GRP_CD AND t.CALC_NO = L_TMP_NO ;

	INSERT INTO MGT_ACC_TOP (
		CALC_NO, CALC_GRP_CD,
		TOP_REC_NO,
		CALC_REC_TYP,
		WG_CD,
		YM, AC_DT,
		MNG_DPT_CD,
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		MFG_PURC_TYP,
		LOT_NO, SUBLOT_NO, SNO1, SNO2, SNO3, SNO4,
		COST_IO_TYP,
		AC_SLIP_TYP, AC_RSN_CD,
		ITM_MFG_INST_NO,
		MFG_ACT_NO,
		LOC_CD, STR_LN_CD,
		OPER_ACT_NO, OPER_CD, OPER_SEQ,
		BP_CD, STK_BP_CD,
		PO_NO, SLO_NO, IV_NO,
		ACT_ID, ACT_ID_SUB,
		ALC_DPT_CD, OTHER_DPT_CD,
		ASST_TYP,
		QTY, AMT,
		STD_QTY, STD_AMT,
		TRD_GRP,
		ACT_UPRI, STD_UPRI,
		SO_ACT_AMT, SO_STD_AMT,
		PER, MFG_COST_RATIO,
		ALC_AC_CD, REC_EVAL_TYP,
		PAR_ITM_CD, PAR_ITM_SUB1, PAR_ITM_SUB2, PAR_ITM_SUB3
		)
	SELECT	L_TMP_NO, t.CALC_GRP_CD,
		t.TOP_REC_NO,
		G_CALC_REC_INST,
		t.WG_CD,
		L_YM, t.AC_DT,
		t.MNG_DPT_CD,
		t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.MFG_PURC_TYP,
		t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
		t.COST_IO_TYP,
		t.AC_SLIP_TYP, t.AC_RSN_CD,
		t.ITM_MFG_INST_NO,
		t.MFG_ACT_NO,
		t.LOC_CD, t.STR_LN_CD,
		t.OPER_ACT_NO, t.OPER_CD, t.OPER_SEQ,
		t.BP_CD, t.STK_BP_CD,
		t.PO_NO, t.SLO_NO, t.IV_NO,
		t.ACT_ID, t.ACT_ID_SUB,
		t.ALC_DPT_CD, t.OTHER_DPT_CD,
		t.ASST_TYP,
		0, t.AMT,
		0, t.STD_AMT,
		t.TRD_GRP,
		t.ACT_UPRI, t.STD_UPRI,
		t.SO_ACT_AMT, t.SO_STD_AMT,
		t.PER, t.MFG_COST_RATIO,
		t.ALC_AC_CD, t.REC_EVAL_TYP,
		t.PAR_ITM_CD, t.PAR_ITM_SUB1, t.PAR_ITM_SUB2, t.PAR_ITM_SUB3
	FROM	MGT_ACC_TOP t
	WHERE	0=0
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_REC_TYP = G_CALC_REC_ST_WIP
	;

	INSERT INTO MGT_ACC_INPT (
		CALC_NO, CALC_GRP_CD,
		INPT_REC_NO, TOP_REC_NO,
		LVL,
		WG_CD,
		YM, AC_DT,
		MNG_DPT_CD,
		ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		MFG_PURC_TYP,
		LOT_NO, SUBLOT_NO, SNO1, SNO2, SNO3, SNO4,
		LOC_CD, STR_LN_CD,
		OPER_ACT_NO, OPER_CD, OPER_SEQ,
		AC_SLIP_TYP, AC_RSN_CD,
		ASST_TYP,
		ACT_QTY, STD_QTY,
		ACT_UPRI, STD_UPRI
		)
	SELECT	L_TMP_NO, t2.CALC_GRP_CD,
		t2.TOP_REC_NO, t2.TOP_REC_NO,
		t2.LVL,
		t2.WG_CD,
		L_YM, t2.AC_DT,
		t2.MNG_DPT_CD,
		t2.ITM_CD, t2.ITM_SUB1, t2.ITM_SUB2, t2.ITM_SUB3,
		t2.MFG_PURC_TYP,
		t2.LOT_NO, t2.SUBLOT_NO, t2.SNO1, t2.SNO2, t2.SNO3, t2.SNO4,
		t2.LOC_CD, t2.STR_LN_CD,
		t2.OPER_ACT_NO, t2.OPER_CD, t2.OPER_SEQ,
		t2.AC_SLIP_TYP, t2.AC_RSN_CD,
		t2.ASST_TYP,
		0, 0,
		t2.ACT_UPRI, t2.STD_UPRI
	FROM	MGT_ACC_TOP t1, MGT_ACC_INPT t2
	WHERE	0=0
	AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t1.CALC_NO = G_ARG.CALC_NO
	AND	t1.CALC_REC_TYP = G_CALC_REC_ST_WIP
	AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
	AND	t1.CALC_NO = t2.CALC_NO
	AND	t1.TOP_REC_NO = t2.TOP_REC_NO
	AND	t2.LVL = 0
	;

	INSERT INTO MGT_ACC_COST (
		CALC_NO, CALC_GRP_CD,
		INPT_REC_NO, WK_REC_NO,
		OPER_ACT_NO, OPER_CD, OPER_SEQ,
		EXPNS_CD,
		ACT_COST, STD_COST,
		SML_INPT_REC_NO, TOP_REC_NO,
		LOC_CD, STR_LN_CD,
		OPER_COST_FLG, EXPNS_TYP,
		DIFF_QTY, DIFF_WK, DIFF_UP, DIFF_RT, DIFF_STD,
		DIFF_A, DIFF_B, DIFF_C, DIFF_D, DIFF_E
		)
	SELECT	L_TMP_NO, t2.CALC_GRP_CD,
		t2.TOP_REC_NO, MIN(t2.WK_REC_NO),
		MIN(t2.OPER_ACT_NO), MIN(t2.OPER_CD), MIN(t2.OPER_SEQ),
		t2.EXPNS_CD,
		SUM(t2.ACT_COST), SUM(t2.STD_COST),
		t2.TOP_REC_NO, t2.TOP_REC_NO,
		MIN(t2.LOC_CD), MIN(t2.STR_LN_CD),
		MIN(t2.OPER_COST_FLG), t2.EXPNS_TYP,
		SUM(t2.DIFF_QTY), SUM(t2.DIFF_WK), SUM(t2.DIFF_UP), SUM(t2.DIFF_RT), SUM(t2.DIFF_STD),
		SUM(t2.DIFF_A), SUM(t2.DIFF_B), SUM(t2.DIFF_C), SUM(t2.DIFF_D), SUM(t2.DIFF_E)
	FROM	MGT_ACC_TOP t1, MGT_ACC_COST t2
	WHERE	0=0
	AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t1.CALC_NO = G_ARG.CALC_NO
	AND	t1.CALC_REC_TYP = G_CALC_REC_ST_WIP
	AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
	AND	t1.CALC_NO = t2.CALC_NO
	AND	t1.TOP_REC_NO = t2.TOP_REC_NO
	GROUP BY t2.CALC_GRP_CD, t2.TOP_REC_NO,
		t2.EXPNS_CD, t2.EXPNS_TYP
	;

	COMMIT ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SCA_POST.P_SET_ST_DATA') ;
END P_SET_ST_DATA ;
