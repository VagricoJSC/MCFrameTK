CREATE OR REPLACE PACKAGE BODY MGPA_COPY_ST
IS
	G_CALC_GRP	MAM_CALC_GRP%ROWTYPE ;

	G_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;
	G_MAX_CNT	CONSTANT INTEGER := 10000 ; --バルクインサートでの最大レコード数

	G_ASST_PROD	CONSTANT MAPA_META.ASST_TYP%TYPE := MAC_ASST_TYP.CO_PROD ;
	G_ASST_OTH	CONSTANT MAPA_META.ASST_TYP%TYPE := MAC_ASST_TYP.OTH ;

PROCEDURE P_STK (
	I_CALC_GRP_CD_FROM	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_YM_FROM		IN MAPA_META.YM%TYPE,
	I_CALC_GRP_CD_TO	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_YM_TO			IN MAPA_META.YM%TYPE,
	I_LOT_NO_FLG		IN MAPA_META.FLG%TYPE,
	I_SUBLOT_NO_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO1_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO2_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO3_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO4_FLG		IN MAPA_META.FLG%TYPE,
	I_BP_FLG		IN MAPA_META.FLG%TYPE,
	I_ASST_FLG		IN MAPA_META.FLG%TYPE,
	I_DEL_FLG		IN MAPA_META.FLG%TYPE
)
/*********************************************************
<SYNOPSIS>
	月初在庫コピー処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD_FROM
		コピー元計算グループＣＤ
<IN>	I_YM_FROM
		コピー元年月
<IN>	I_CALC_GRP_CD_TO
		コピー先計算グループＣＤ
<IN>	I_YM_TO
		コピー先年月
<IN>	I_LOT_NO_FLG
		ロットＮＯ引継ＦＬＧ
<IN>	I_SUBLOT_NO_FLG
		サブロットＮＯ引継ＦＬＧ
<IN>	I_SNO1_FLG
		手配ＮＯ１引継ＦＬＧ
<IN>	I_SNO2_FLG
		手配ＮＯ２引継ＦＬＧ
<IN>	I_SNO3_FLG
		手配ＮＯ３引継ＦＬＧ
<IN>	I_SNO4_FLG
		手配ＮＯ４引継ＦＬＧ
<IN>	I_BP_FLG
		取引先引継ＦＬＧ
<IN>	I_ASST_FLG
		資産区分引継ＦＬＧ
<IN>	I_DEL_FLG
		削除後再作成ＦＬＧ
<HISTORY>
**********************************************************/
AS
	C_STK_SEQ	CONSTANT MAPA_META.ORA_OBJ_NM%TYPE := MGC_NUM_SYS_TYP.ST_STK_KEY ;

	CURSOR LOCK_STK
	IS
		SELECT	t.ST_STK_KEY
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	(
			t.CALC_GRP_CD = I_CALC_GRP_CD_FROM AND t.YM = I_YM_FROM
			OR
			t.CALC_GRP_CD = I_CALC_GRP_CD_TO AND t.YM = I_YM_TO
			)
		FOR UPDATE NOWAIT
	;

	L_STK	MGT_ST_STK%ROWTYPE ;

	L_CNT		NUMBER ;
	L_ROW_ID	MAPA_META.ROW_ID%TYPE ;
BEGIN
	IF G_CALC_GRP.COST_CALC_TYP != MAC_COST_CALC_TYP.CALC_STK
	AND G_CALC_GRP.EXP_CALC_TYP = MAC_EXP_CALC_TYP.NON THEN
		RETURN ;
	END IF ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_COPY_ST.P_STK') ;

	OPEN LOCK_STK ;
	CLOSE LOCK_STK ;

	IF I_DEL_FLG = '1' THEN
		DELETE	MGT_ST_STK_EXPNS t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_ST_STK x
				WHERE	0=0
				AND	x.ST_STK_KEY = t.ST_STK_KEY
				AND	x.CALC_GRP_CD = I_CALC_GRP_CD_TO
				AND	x.YM = I_YM_TO
			)
		;

		DELETE	MGT_ST_STK_DIFF t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_ST_STK x
				WHERE	0=0
				AND	x.ST_STK_KEY = t.ST_STK_KEY
				AND	x.CALC_GRP_CD = I_CALC_GRP_CD_TO
				AND	x.YM = I_YM_TO
			)
		;

		DELETE MGT_ST_STK t WHERE t.CALC_GRP_CD = I_CALC_GRP_CD_TO AND t.YM = I_YM_TO ;
	ELSE
		SELECT	COUNT(*)
		INTO	L_CNT
		FROM	MGT_ST_STK_DIFF t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_ST_STK x
				WHERE	0=0
				AND	x.ST_STK_KEY = t.ST_STK_KEY
				AND	x.CALC_GRP_CD = I_CALC_GRP_CD_TO
				AND	x.YM = I_YM_TO
			)
		;

		IF L_CNT > 0 THEN
			FCPA_ERR.RAISE_APP_ERR('MGBBD0004') ;
		END IF ;
	END IF ;

	FOR x IN (
		SELECT	t.ST_STK_KEY,
			t.WG_CD,
			t.MNG_DPT_CD,
			t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			DECODE(I_LOT_NO_FLG, '1', t.LOT_NO, G_NULL_VAL)	LOT_NO,
			DECODE(I_SUBLOT_NO_FLG, '1', t.SUBLOT_NO, G_NULL_VAL)	SUBLOT_NO,
			DECODE(I_SNO1_FLG, '1', t.SNO1, G_NULL_VAL)	SNO1,
			DECODE(I_SNO2_FLG, '1', t.SNO2, G_NULL_VAL)	SNO2,
			DECODE(I_SNO3_FLG, '1', t.SNO3, G_NULL_VAL)	SNO3,
			DECODE(I_SNO4_FLG, '1', t.SNO4, G_NULL_VAL)	SNO4,
			t.BP_CD,
			t.ASST_TYP,
			t.REPURC_OBLI_FLG,
			t.QTY
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD_FROM
		AND	t.YM = I_YM_FROM
		)
	LOOP
		L_STK.WG_CD := x.WG_CD ;
		L_STK.MNG_DPT_CD := x.MNG_DPT_CD ;
		L_STK.ITM_CD := x.ITM_CD ;
		L_STK.ITM_SUB1 := x.ITM_SUB1 ;
		L_STK.ITM_SUB2 := x.ITM_SUB2 ;
		L_STK.ITM_SUB3 := x.ITM_SUB3 ;
		L_STK.LOT_NO := x.LOT_NO ;
		L_STK.SUBLOT_NO := x.SUBLOT_NO ;
		L_STK.SNO1 := x.SNO1 ;
		L_STK.SNO2 := x.SNO2 ;
		L_STK.SNO3 := x.SNO3 ;
		L_STK.SNO4 := x.SNO4 ;
		L_STK.REPURC_OBLI_FLG := x.REPURC_OBLI_FLG ;

		IF I_ASST_FLG = '1' OR x.ASST_TYP =  G_ASST_OTH THEN
			L_STK.ASST_TYP := x.ASST_TYP ;
		ELSE
			L_STK.ASST_TYP := G_ASST_PROD ;
		END IF ;

		IF I_BP_FLG = '1' OR L_STK.ASST_TYP = G_ASST_OTH OR L_STK.REPURC_OBLI_FLG = '1' THEN
			L_STK.BP_CD := x.BP_CD ;
		ELSE
			L_STK.BP_CD := NULL ;
		END IF ;

		SELECT	MAX(t.ST_STK_KEY)
		INTO	L_ROW_ID
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD_TO
		AND	t.WG_CD = L_STK.WG_CD
		AND	t.YM = I_YM_TO
		AND	t.MNG_DPT_CD = L_STK.MNG_DPT_CD
		AND	t.ITM_CD = L_STK.ITM_CD
		AND	t.ITM_SUB1 = L_STK.ITM_SUB1
		AND	t.ITM_SUB2 = L_STK.ITM_SUB2
		AND	t.ITM_SUB3 = L_STK.ITM_SUB3
		AND	t.LOT_NO = L_STK.LOT_NO
		AND	t.SUBLOT_NO = L_STK.SUBLOT_NO
		AND	t.SNO1 = L_STK.SNO1
		AND	t.SNO2 = L_STK.SNO2
		AND	t.SNO3 = L_STK.SNO3
		AND	t.SNO4 = L_STK.SNO4
		AND	NVL(t.BP_CD, G_NULL_VAL) = NVL(L_STK.BP_CD, G_NULL_VAL)
		AND	t.ASST_TYP = L_STK.ASST_TYP
		AND	t.REPURC_OBLI_FLG = L_STK.REPURC_OBLI_FLG
		;

		IF L_ROW_ID IS NOT NULL THEN
			UPDATE	MGT_ST_STK t
			SET	t.QTY = t.QTY + x.QTY
			WHERE	0=0
			AND	t.ST_STK_KEY = L_ROW_ID
			;

			MERGE INTO MGT_ST_STK_EXPNS t
			USING	(
				SELECT	t1.EXPNS_CD,
					t1.AMT
				FROM	MGT_ST_STK_EXPNS t1
				WHERE	0=0
				AND	t1.ST_STK_KEY = x.ST_STK_KEY
				) w
			ON	(0=0
				AND	t.ST_STK_KEY = L_ROW_ID
				AND	t.EXPNS_CD = w.EXPNS_CD
				)
			WHEN MATCHED THEN
				UPDATE
				SET	t.AMT = t.AMT + w.AMT
			WHEN NOT MATCHED THEN
				INSERT	(
					ST_STK_KEY, EXPNS_CD, AMT
					)
				VALUES	(
					L_ROW_ID, w.EXPNS_CD, w.AMT
					)
			;
		ELSE
			L_ROW_ID := MAPA_NUM.F_GET_SEQ(C_STK_SEQ) ;

			INSERT INTO MGT_ST_STK (
				ST_STK_KEY,
				CALC_GRP_CD, WG_CD, YM,
				MNG_DPT_CD,
				ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
				LOT_NO, SUBLOT_NO,
				SNO1, SNO2, SNO3, SNO4,
				BP_CD, ASST_TYP,
				REPURC_OBLI_FLG,
				QTY
				)
			VALUES	(
				L_ROW_ID,
				I_CALC_GRP_CD_TO, L_STK.WG_CD, I_YM_TO,
				L_STK.MNG_DPT_CD,
				L_STK.ITM_CD, L_STK.ITM_SUB1, L_STK.ITM_SUB2, L_STK.ITM_SUB3,
				L_STK.LOT_NO, L_STK.SUBLOT_NO,
				L_STK.SNO1, L_STK.SNO2, L_STK.SNO3, L_STK.SNO4,
				L_STK.BP_CD, L_STK.ASST_TYP,
				L_STK.REPURC_OBLI_FLG,
				x.QTY
				)
			;

			DELETE	MGT_ST_STK_EXPNS t
			WHERE	0=0
			AND	t.ST_STK_KEY = L_ROW_ID ;

			INSERT INTO MGT_ST_STK_EXPNS (
				ST_STK_KEY,
				EXPNS_CD,
				AMT
				)
			SELECT	L_ROW_ID,
				t.EXPNS_CD,
				t.AMT
			FROM	MGT_ST_STK_EXPNS t
			WHERE	0=0
			AND	t.ST_STK_KEY = x.ST_STK_KEY
			;
		END IF ;

	END LOOP ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_COPY_ST.P_STK') ;
END P_STK ;

PROCEDURE P_WIP (
	I_CALC_GRP_CD_FROM	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_YM_FROM		IN MAPA_META.YM%TYPE,
	I_CALC_GRP_CD_TO	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_YM_TO			IN MAPA_META.YM%TYPE,
	I_DEL_FLG		IN MAPA_META.FLG%TYPE
)
/*********************************************************
<SYNOPSIS>
	月初仕掛コピー処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD_FROM
		コピー元計算グループＣＤ
<IN>	I_YM_FROM
		コピー元年月
<IN>	I_CALC_GRP_CD_TO
		コピー先計算グループＣＤ
<IN>	I_YM_TO
		コピー先年月
<IN>	I_DEL_FLG
		削除後再作成ＦＬＧ
<HISTORY>
**********************************************************/
AS
	C_WIP_SEQ	CONSTANT MAPA_META.ORA_OBJ_NM%TYPE := MGC_NUM_SYS_TYP.ST_WIP_KEY ;

	CURSOR LOCK_WIP
	IS
		SELECT	t.ST_WIP_KEY
		FROM	MGT_ST_WIP t
		WHERE	0=0
		AND	(
			t.CALC_GRP_CD = I_CALC_GRP_CD_FROM AND t.YM = I_YM_FROM
			OR
			t.CALC_GRP_CD = I_CALC_GRP_CD_TO AND t.YM = I_YM_TO
			)
		FOR UPDATE NOWAIT
	;

	TYPE LIST_WIP IS TABLE OF MGT_ST_WIP%ROWTYPE INDEX BY BINARY_INTEGER ;
	reci	LIST_WIP ;
	i	INTEGER ;

	TYPE LIST_WIP_EXPNS IS TABLE OF MGT_ST_WIP_EXPNS%ROWTYPE INDEX BY BINARY_INTEGER ;
	recj	LIST_WIP_EXPNS ;
	j	INTEGER ;

	L_ROW_ID	MAPA_META.ROW_ID%TYPE ;
/**********************************************************/
PROCEDURE P_WIP_INSERT
AS
BEGIN
	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MGT_ST_WIP VALUES reci(t) ;
		reci.DELETE ;
		i := 0 ;
	END IF ;

	IF j > 0 THEN
		FORALL t IN 1..j
			INSERT INTO MGT_ST_WIP_EXPNS VALUES recj(t) ;
		recj.DELETE ;
		j := 0 ;
	END IF ;
END ;
/**********************************************************/
BEGIN
	IF G_CALC_GRP.COST_CALC_TYP != MAC_COST_CALC_TYP.NOT_STK
	AND G_CALC_GRP.COST_CALC_TYP != MAC_COST_CALC_TYP.CALC_STK THEN
		RETURN ;
	END IF ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_COPY_ST.P_WIP') ;

	OPEN LOCK_WIP ;
	CLOSE LOCK_WIP ;

	IF I_DEL_FLG = '1' THEN
		DELETE	MGT_ST_WIP_EXPNS t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_ST_WIP x
				WHERE	0=0
				AND	x.ST_WIP_KEY = t.ST_WIP_KEY
				AND	x.CALC_GRP_CD = I_CALC_GRP_CD_TO
				AND	x.YM = I_YM_TO
			)
		;
		DELETE MGT_ST_WIP t WHERE t.CALC_GRP_CD = I_CALC_GRP_CD_TO AND t.YM = I_YM_TO ;
	END IF ;

	i := 0 ;
	j := 0 ;
	FOR x IN (
		SELECT	t.ST_WIP_KEY,
			t.WG_CD,
			t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.ITM_MFG_INST_NO,
			t.MFG_ACT_NO,
			t.OPER_ACT_NO,
			t.LOC_CD,
			t.STR_LN_CD,
			t.OPER_CD,
			t.OPER_SEQ,
			t.WIP_QTY,
			t.WIP_PER
		FROM	MGT_ST_WIP t
		WHERE	0=0
		AND	t.CALC_GRP_CD = I_CALC_GRP_CD_FROM
		AND	t.YM = I_YM_FROM
		)
	LOOP
		L_ROW_ID := MAPA_NUM.F_GET_SEQ(C_WIP_SEQ) ;

		i := i + 1 ;

		reci(i).ST_WIP_KEY := L_ROW_ID ;
		reci(i).CALC_GRP_CD := I_CALC_GRP_CD_TO ;
		reci(i).WG_CD	:= x.WG_CD ;
		reci(i).YM	:= I_YM_TO ;
		reci(i).ITM_CD	:= x.ITM_CD ;
		reci(i).ITM_SUB1	:= x.ITM_SUB1 ;
		reci(i).ITM_SUB2	:= x.ITM_SUB2 ;
		reci(i).ITM_SUB3	:= x.ITM_SUB3 ;
		reci(i).ITM_EXT	:= G_NULL_VAL ;
		reci(i).ITM_MFG_INST_NO := x.ITM_MFG_INST_NO ;
		reci(i).MFG_ACT_NO	:= x.MFG_ACT_NO ;
		reci(i).OPER_ACT_NO := x.OPER_ACT_NO ;
		reci(i).LOC_CD	:= x.LOC_CD ;
		reci(i).STR_LN_CD := x.STR_LN_CD ;
		reci(i).OPER_CD	:= x.OPER_CD ;
		reci(i).OPER_SEQ := x.OPER_SEQ ;
		reci(i).WIP_QTY	:= x.WIP_QTY ;
		reci(i).WIP_PER	:= x.WIP_PER ;

		FOR y IN (
			SELECT	t.EXPNS_CD,
				t.WIP_AMT,
				t.INPT_AMT
			FROM	MGT_ST_WIP_EXPNS t
			WHERE	0=0
			AND	t.ST_WIP_KEY = x.ST_WIP_KEY
			AND	(t.WIP_AMT <> 0 OR t.INPT_AMT <> 0)
			)
		LOOP
			j := j + 1 ;

			recj(j).ST_WIP_KEY := L_ROW_ID ;
			recj(j).EXPNS_CD := y.EXPNS_CD ;
			recj(j).WIP_AMT	 := y.WIP_AMT ;
			recj(j).INPT_AMT := y.INPT_AMT ;
		END LOOP ;

		IF i + j > G_MAX_CNT THEN
			P_WIP_INSERT() ;
		END IF ;
	END LOOP ;

	P_WIP_INSERT() ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_COPY_ST.P_WIP') ;
END P_WIP ;

PROCEDURE P_MAIN (
	I_CALC_GRP_CD_FROM	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_YM_FROM		IN MAPA_META.YM%TYPE,
	I_CALC_GRP_CD_TO	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_YM_TO			IN MAPA_META.YM%TYPE,
	I_STK_FLG		IN MAPA_META.FLG%TYPE,
	I_WIP_FLG		IN MAPA_META.FLG%TYPE,
	I_LOT_NO_FLG		IN MAPA_META.FLG%TYPE,
	I_SUBLOT_NO_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO1_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO2_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO3_FLG		IN MAPA_META.FLG%TYPE,
	I_SNO4_FLG		IN MAPA_META.FLG%TYPE,
	I_BP_FLG		IN MAPA_META.FLG%TYPE,
	I_ASST_FLG		IN MAPA_META.FLG%TYPE,
	I_DEL_FLG		IN MAPA_META.FLG%TYPE
)
/*********************************************************
<SYNOPSIS>
	月初データコピーメイン処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD_FROM
		コピー元計算グループＣＤ
<IN>	I_YM_FROM
		コピー元年月
<IN>	I_CALC_GRP_CD_TO
		コピー先計算グループＣＤ
<IN>	I_YM_TO
		コピー先年月
<IN>	I_STK_FLG
		月初在庫作成ＦＬＧ
<IN>	I_WIP_FLG
		月初仕掛作成ＦＬＧ
<IN>	I_LOT_NO_FLG
		ロットＮＯ引継ＦＬＧ
<IN>	I_SUBLOT_NO_FLG
		サブロットＮＯ引継ＦＬＧ
<IN>	I_SNO1_FLG
		手配ＮＯ１引継ＦＬＧ
<IN>	I_SNO2_FLG
		手配ＮＯ２引継ＦＬＧ
<IN>	I_SNO3_FLG
		手配ＮＯ３引継ＦＬＧ
<IN>	I_SNO4_FLG
		手配ＮＯ４引継ＦＬＧ
<IN>	I_BP_FLG
		取引先引継ＦＬＧ
<IN>	I_ASST_FLG
		資産区分引継ＦＬＧ
<IN>	I_DEL_FLG
		削除後再作成ＦＬＧ
<HISTORY>
**********************************************************/
AS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;
BEGIN
	/*** コピー先年月に対する確定状況の確認 ***/
	MGPA_CALC_FIX.P_CHK_FIX(I_CALC_GRP_CD_TO, I_YM_TO) ;

	G_CALC_GRP := MGPA_CALC_GRP.F_GET_REC(I_CALC_GRP_CD_TO) ;

	IF I_STK_FLG = '1' THEN
		P_STK(I_CALC_GRP_CD_FROM, I_YM_FROM, I_CALC_GRP_CD_TO, I_YM_TO,
			I_LOT_NO_FLG, I_SUBLOT_NO_FLG, I_SNO1_FLG, I_SNO2_FLG, I_SNO3_FLG, I_SNO4_FLG,
			I_BP_FLG, I_ASST_FLG, I_DEL_FLG
			) ;
	END IF ;

	IF I_WIP_FLG = '1' THEN
		P_WIP(I_CALC_GRP_CD_FROM, I_YM_FROM, I_CALC_GRP_CD_TO, I_YM_TO, I_DEL_FLG) ;
	END IF ;

EXCEPTION
WHEN LOCK_ERROR THEN
	FCPA_ERR.RAISE_APP_ERR('MGBXD0029') ;
END P_MAIN ;

END MGPA_COPY_ST ;
