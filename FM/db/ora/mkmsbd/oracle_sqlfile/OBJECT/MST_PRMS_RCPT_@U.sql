CREATE OR REPLACE VIEW MST_PRMS_RCPT_$U(
	PRMS_RCPT_NO,
	PRMS_RCPT_REV,
	PRMS_RCPT_GRP_NO,
	PO_D_NO,
	ARR_SCHD_REFL_FLG,
	ARR_SCHD_REFL_DT,
	PRMS_RCPT_DT,
	EDI_FLG,
	CAN_FLG,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PRMS_RCPT_NO,
	ORG.PRMS_RCPT_REV,
	ORG.PRMS_RCPT_GRP_NO,
	ORG.PO_D_NO,
	ORG.ARR_SCHD_REFL_FLG,
	ORG.ARR_SCHD_REFL_DT,
	ORG.PRMS_RCPT_DT,
	ORG.EDI_FLG,
	ORG.CAN_FLG,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PRMS_RCPT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

