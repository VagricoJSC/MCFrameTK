CREATE OR REPLACE VIEW MST_DLV_INST_$U(
	DLV_INST_NO,
	DLV_INST_REV,
	DLV_INST_SEQ,
	DLV_INST_GRP_NO,
	PO_D_NO,
	DLV_INST_PRINT_DT,
	DLV_INST_PRINT_FLG,
	LAST_DLV_INST_REV,
	DLV_INST_DT,
	EDI_FLG,
	CAN_FLG,
	DLV_INST_PRINT_RMRKS,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.DLV_INST_NO,
	ORG.DLV_INST_REV,
	ORG.DLV_INST_SEQ,
	ORG.DLV_INST_GRP_NO,
	ORG.PO_D_NO,
	ORG.DLV_INST_PRINT_DT,
	ORG.DLV_INST_PRINT_FLG,
	ORG.LAST_DLV_INST_REV,
	ORG.DLV_INST_DT,
	ORG.EDI_FLG,
	ORG.CAN_FLG,
	ORG.DLV_INST_PRINT_RMRKS,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_DLV_INST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

