CREATE OR REPLACE VIEW MST_WRK_ACT_HIST_$U(
	WRK_NO,
	HIST_NO,
	ACT_STS_CD,
	ACT_HIST,
	ACT_SCHD_DT,
	ACT_SCHD,
	ACT_ACT_DT,
	ACT_ACT,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WRK_NO,
	ORG.HIST_NO,
	ORG.ACT_STS_CD,
	ORG.ACT_HIST,
	ORG.ACT_SCHD_DT,
	ORG.ACT_SCHD,
	ORG.ACT_ACT_DT,
	ORG.ACT_ACT,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_WRK_ACT_HIST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

