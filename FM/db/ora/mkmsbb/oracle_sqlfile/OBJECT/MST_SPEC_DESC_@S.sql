CREATE OR REPLACE VIEW MST_SPEC_DESC_$S(
	SPEC_DESC_NO,
	SLS_ITM_SPEC_NO,
	SLS_ITM_NO,
	SLS_ITM_SPEC_LNO,
	SPEC_CD,
	SPEC_DESC_CD,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SPEC_DESC_NO,
	ORG.SLS_ITM_SPEC_NO,
	ORG.SLS_ITM_NO,
	ORG.SLS_ITM_SPEC_LNO,
	ORG.SPEC_CD,
	ORG.SPEC_DESC_CD,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SPEC_DESC_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

