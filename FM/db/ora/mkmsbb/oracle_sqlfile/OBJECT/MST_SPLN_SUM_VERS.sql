CREATE OR REPLACE VIEW MST_SPLN_SUM_VERS(
	DPT_CD,
	CST_CD,
	WRK_NO,
	YM,
	SPLN_VERS,
	EDITED_FLG,
	ADOPTED_FLG,
	LOCKED_FLG,
	REF_VERS,
	USR_CD,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.DPT_CD,
	ORG.CST_CD,
	ORG.WRK_NO,
	ORG.YM,
	ORG.SPLN_VERS,
	ORG.EDITED_FLG,
	ORG.ADOPTED_FLG,
	ORG.LOCKED_FLG,
	ORG.REF_VERS,
	ORG.USR_CD,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SPLN_SUM_VERS_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

