SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_WRK(
	WRK_NO,
	WRK_NM,
	ST_DT,
	END_DT,
	WRK_DESC,
	TERM_COND,
	PRJ_NO,
	WRK_STS_CD,
	SLO_ACC_CD,
	CUR_CD,
	BUDGET,
	SLO_RSN,
	FAIL_RSN,
	WRK_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	WRK_AR_FLG,
	WRK_AP_FLG,
	CAN_FLG,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WRK_NO,
	ORG.WRK_NM,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.WRK_DESC,
	ORG.TERM_COND,
	ORG.PRJ_NO,
	ORG.WRK_STS_CD,
	ORG.SLO_ACC_CD,
	ORG.CUR_CD,
	ORG.BUDGET,
	ORG.SLO_RSN,
	ORG.FAIL_RSN,
	ORG.WRK_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.WRK_AR_FLG,
	ORG.WRK_AP_FLG,
	ORG.CAN_FLG,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_WRK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

