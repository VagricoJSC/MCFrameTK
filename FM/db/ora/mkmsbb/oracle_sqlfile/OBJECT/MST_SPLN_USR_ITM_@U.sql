CREATE OR REPLACE VIEW MST_SPLN_USR_ITM_$U(
	USR_CD,
	YM,
	DPT_CD,
	CST_CD,
	WRK_NO,
	SPLN_ITM_CD,
	CUR_CD,
	SPLN_YM,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SPLN_QTY,
	SPLN_AMT,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.USR_CD,
	ORG.YM,
	ORG.DPT_CD,
	ORG.CST_CD,
	ORG.WRK_NO,
	ORG.SPLN_ITM_CD,
	ORG.CUR_CD,
	ORG.SPLN_YM,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.SPLN_QTY,
	ORG.SPLN_AMT,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SPLN_USR_ITM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

