CREATE OR REPLACE VIEW MST_SLS_ITM_$U(
	SLS_ITM_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_NM,
	ITM_COMP_REV_NO,
	QTN_D_NO,
	QTN_NO,
	QTN_REV,
	REL_FLG,
	NO_ITM_CD_FLG,
	TRD_UNIT_CD,
	TRD_UNIT_QTY,
	BASE_UNIT_CD,
	BASE_UNIT_QTY,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLS_ITM_NO,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_NM,
	ORG.ITM_COMP_REV_NO,
	ORG.QTN_D_NO,
	ORG.QTN_NO,
	ORG.QTN_REV,
	ORG.REL_FLG,
	ORG.NO_ITM_CD_FLG,
	ORG.TRD_UNIT_CD,
	ORG.TRD_UNIT_QTY,
	ORG.BASE_UNIT_CD,
	ORG.BASE_UNIT_QTY,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SLS_ITM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

