CREATE OR REPLACE VIEW MST_NOTE(
	NOTE_MNG_NO,
	NOTE_NO,
	NOTE_TYP,
	DRAW_DT,
	DUE_DT,
	DRAWER_NM,
	DRAW_BANK_CD,
	DRAW_BRANCH_CD,
	ENDRSR,
	ACCPTR,
	NOTE_RSN_CD,
	NOTE_AMT,
	APPL_AMT,
	NOT_APPL_BAL,
	SUSP_AMT,
	ADV_AMT,
	MAT_FLG,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	CAN_FLG,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.NOTE_MNG_NO,
	ORG.NOTE_NO,
	ORG.NOTE_TYP,
	ORG.DRAW_DT,
	ORG.DUE_DT,
	ORG.DRAWER_NM,
	ORG.DRAW_BANK_CD,
	ORG.DRAW_BRANCH_CD,
	ORG.ENDRSR,
	ORG.ACCPTR,
	ORG.NOTE_RSN_CD,
	ORG.NOTE_AMT,
	ORG.APPL_AMT,
	ORG.NOT_APPL_BAL,
	ORG.SUSP_AMT,
	ORG.ADV_AMT,
	ORG.MAT_FLG,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.CAN_FLG,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_NOTE_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

