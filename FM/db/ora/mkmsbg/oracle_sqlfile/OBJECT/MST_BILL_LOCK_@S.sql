SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_BILL_LOCK_$S(
	BCST_CD,
	TRD_CUR_CD,
	IV_NO,
	WRK_NO,
	BILL_DPT_CD,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BCST_CD,
	ORG.TRD_CUR_CD,
	ORG.IV_NO,
	ORG.WRK_NO,
	ORG.BILL_DPT_CD,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_BILL_LOCK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

