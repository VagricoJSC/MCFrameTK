CREATE OR REPLACE VIEW MST_AR_APPL_SCHD_$S(
	AR_APPL_SCHD_NO,
	BILL_ACST_NO,
	IV_NO,
	AR_TYP,
	RCV_MTD_CD,
	RCV_SCHD_DT,
	APPL_TGT_AMT,
	APPL_AMT,
	NOT_APPL_BAL,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.AR_APPL_SCHD_NO,
	ORG.BILL_ACST_NO,
	ORG.IV_NO,
	ORG.AR_TYP,
	ORG.RCV_MTD_CD,
	ORG.RCV_SCHD_DT,
	ORG.APPL_TGT_AMT,
	ORG.APPL_AMT,
	ORG.NOT_APPL_BAL,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_AR_APPL_SCHD_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

