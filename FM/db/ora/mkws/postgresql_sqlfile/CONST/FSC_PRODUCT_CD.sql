CREATE OR REPLACE FUNCTION FSC_PRODUCT_CD$CONTAINS(IN I_VALUE VARCHAR) RETURNS CHAR(1) AS -- 定数に含まれるかどうか
$BODY$ BEGIN
	IF I_VALUE = FSC_PRODUCT_CD$SCM()
	OR I_VALUE = FSC_PRODUCT_CD$SCMRefer()
	OR I_VALUE = FSC_PRODUCT_CD$SCMService()
	OR I_VALUE = FSC_PRODUCT_CD$Seisan()
	OR I_VALUE = FSC_PRODUCT_CD$SeisanRefer()
	OR I_VALUE = FSC_PRODUCT_CD$SeisanService()
	OR I_VALUE = FSC_PRODUCT_CD$Hanbai()
	OR I_VALUE = FSC_PRODUCT_CD$HanbaiRefer()
	OR I_VALUE = FSC_PRODUCT_CD$HanbaiService()
	OR I_VALUE = FSC_PRODUCT_CD$Genka()
	OR I_VALUE = FSC_PRODUCT_CD$GenkaRefer()
	OR I_VALUE = FSC_PRODUCT_CD$GenkaService()
	OR I_VALUE = FSC_PRODUCT_CD$Keiei()
	OR I_VALUE = FSC_PRODUCT_CD$KeieiRefer()
	OR I_VALUE = FSC_PRODUCT_CD$KeieiService()
	OR I_VALUE = FSC_PRODUCT_CD$Shonin()
	OR I_VALUE = FSC_PRODUCT_CD$MultiDeviceSCM()
	OR I_VALUE = FSC_PRODUCT_CD$CFP()
	OR I_VALUE = FSC_PRODUCT_CD$CFPRefer()
	OR I_VALUE = FSC_PRODUCT_CD$CFPService()
	OR I_VALUE = FSC_PRODUCT_CD$MedicineOption()
	OR I_VALUE = FSC_PRODUCT_CD$SaikenOption()
	OR I_VALUE = FSC_PRODUCT_CD$SaikenOptionRefer()
	OR I_VALUE = FSC_PRODUCT_CD$SaikenOptionShonin()
	OR I_VALUE = FSC_PRODUCT_CD$SaimuOption()
	OR I_VALUE = FSC_PRODUCT_CD$SaimuOptionRefer()
	OR I_VALUE = FSC_PRODUCT_CD$SaimuOptionShonin()
	OR I_VALUE = FSC_PRODUCT_CD$MultiDeviceOption()
	OR I_VALUE = FSC_PRODUCT_CD$NXOption()
	OR I_VALUE = FSC_PRODUCT_CD$FSOption()
	OR I_VALUE = FSC_PRODUCT_CD$PLMOption()
	OR I_VALUE = FSC_PRODUCT_CD$BSOption() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE FSC_PRODUCT_CD$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF FSC_PRODUCT_CD$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
