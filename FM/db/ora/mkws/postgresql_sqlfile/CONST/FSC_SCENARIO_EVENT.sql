	OR I_VALUE = FSC_SCENARIO_EVENT$EVENT_MOUSE_MOVE()
	OR I_VALUE = FSC_SCENARIO_EVENT$EVENT_MOUSE_DRAG()
	OR I_VALUE = FSC_SCENARIO_EVENT$EVENT_KEY_PRESS()
	OR I_VALUE = FSC_SCENARIO_EVENT$EVENT_KEY_RELEASE()
	OR I_VALUE = FSC_SCENARIO_EVENT$WAIT_100()
	OR I_VALUE = FSC_SCENARIO_EVENT$WAIT_500()
	OR I_VALUE = FSC_SCENARIO_EVENT$WAIT_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$KEY_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$SCREEN_CLEAR_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$COMMAND_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$BIND_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$SPECIAL_KEY_PRESS_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$SPECIAL_KEY_RELEASE_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$POPUP_ITEM_EVENT()
	OR I_VALUE = FSC_SCENARIO_EVENT$SNAPSHOT_EVENT() THEN
