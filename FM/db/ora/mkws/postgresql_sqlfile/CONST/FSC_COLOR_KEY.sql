CREATE OR REPLACE FUNCTION FSC_COLOR_KEY$CONTAINS(IN I_VALUE VARCHAR) RETURNS CHAR(1) AS -- 定数に含まれるかどうか
$BODY$ BEGIN
	IF I_VALUE = FSC_COLOR_KEY$ROOTPANEL_BG()
	OR I_VALUE = FSC_COLOR_KEY$PANEL_BG2() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE FSC_COLOR_KEY$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF FSC_COLOR_KEY$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
CREATE OR REPLACE PROCEDURE FSC_COLOR_KEY$CONTAINS_EX(IN I_VALUE VARCHAR) AS -- 定数に含まれるかどうか
	$BODY$ BEGIN
	CALL FSC_COLOR_KEY$CONTAINS_EX(I_VALUE, 'FCBCC5011');
END;
$BODY$ LANGUAGE plpgsql;

