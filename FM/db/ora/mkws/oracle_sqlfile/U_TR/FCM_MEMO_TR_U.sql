SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER FCM_MEMO_TR_U
BEFORE INSERT OR UPDATE ON FCM_MEMO
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
BEGIN
	IF INSERTING THEN
		:NEW.INS_TS := FCPA_DATE_UTIL.F_MCSYSTIMESTAMP;
		:NEW.INS_USR_ID := NVL(:NEW.INS_USR_ID, NVL(FCPA_CONTEXT.F_GET_USERID, FCPA_CONTEXT.F_GET_OS_USR));
		:NEW.INS_USR_NM := NVL(:NEW.INS_USR_NM, FCPA_CONTEXT.F_GET_USERNM);
		:NEW.INS_FUNC_ID := NVL(:NEW.INS_FUNC_ID, FCPA_CONTEXT.F_GET_CALL_PG_ID);
		:NEW.UPD_CNTR := 0;
		:NEW.UPD_TS := :NEW.INS_TS;
		:NEW.UPD_USR_ID := :NEW.INS_USR_ID;
		:NEW.UPD_USR_NM := :NEW.INS_USR_NM;
		:NEW.UPD_FUNC_ID := :NEW.INS_FUNC_ID;
		:NEW.UPD_SRV_REQ_NO := NVL(:NEW.UPD_SRV_REQ_NO, FCPA_CONTEXT.F_GET_PROCESSID);
	ELSIF UPDATING THEN
		:NEW.UPD_CNTR := :OLD.UPD_CNTR + 1;
		:NEW.UPD_TS := FCPA_DATE_UTIL.F_MCSYSTIMESTAMP;
		IF :NEW.UPD_SRV_REQ_NO IS NULL OR :NEW.UPD_SRV_REQ_NO = :OLD.UPD_SRV_REQ_NO THEN
			:NEW.UPD_USR_ID := NVL(FCPA_CONTEXT.F_GET_USERID, FCPA_CONTEXT.F_GET_OS_USR);
			:NEW.UPD_USR_NM := FCPA_CONTEXT.F_GET_USERNM;
			:NEW.UPD_FUNC_ID := FCPA_CONTEXT.F_GET_CALL_PG_ID;
			:NEW.UPD_SRV_REQ_NO := FCPA_CONTEXT.F_GET_PROCESSID;
		END IF;
	END IF;
END;

/
show errors;


