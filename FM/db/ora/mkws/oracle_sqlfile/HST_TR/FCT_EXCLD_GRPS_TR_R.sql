SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER FCT_EXCLD_GRPS_TR_R
AFTER INSERT OR DELETE OR UPDATE
ON FCT_EXCLD_GRPS
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
BEGIN
DECLARE
	H_ID FCT_HST_HEADER.HST_ID%TYPE;
	A_ID FCT_OPRHISTORY.ACTION_ID%TYPE;
	H_TYP FCT_HST_HEADER.HST_TYPE%TYPE;
	H_TAB FCT_HST_HEADER.TABLE_NAME%TYPE;
	U_ID FCM_USER.USER_ID%TYPE;
	COCD FCT_HST_HEADER.CO_CD%TYPE;
	EX_1 FCT_HST_HEADER.EXT_ATTR1%TYPE ;
	EX_2 FCT_HST_HEADER.EXT_ATTR2%TYPE ;
	EX_3 FCT_HST_HEADER.EXT_ATTR3%TYPE ;
	RDATE DATE;
BEGIN
	H_TAB := 'FCT_EXCLD_GRPS_R';
	A_ID := FCPA_CONTEXT.F_GET_ACTION_ID;
	U_ID := NVL(FCPA_CONTEXT.F_GET_USERID, FCPA_CONTEXT.F_GET_OS_USR);
	COCD := FCPA_CONTEXT.F_GET_CO_CD;
	EX_1 := FCPA_CONTEXT.F_GET_EXT_ATTR1;
	EX_2 := FCPA_CONTEXT.F_GET_EXT_ATTR2;
	EX_3 := FCPA_CONTEXT.F_GET_EXT_ATTR3;
	RDATE := FCPA_DATE_UTIL.F_MCSYSDATE;
	IF INSERTING THEN
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		H_TYP := 'I';
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCT_EXCLD_GRPS_R (
			HST_ID,
			HST_TYPE,
			REQ_NO,
			OPE_ID,
			GID,
			MAN_FLG
		)
			VALUES (
				H_ID,
				H_TYP,
				:NEW.REQ_NO,
				:NEW.OPE_ID,
				:NEW.GID,
				:NEW.MAN_FLG
		);
	ELSIF UPDATING THEN
--keyに変更があるかどうかの判定
--keyに変更がある場合
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		H_TYP := 'D';
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCT_EXCLD_GRPS_R (
			HST_ID,
			HST_TYPE,
			REQ_NO,
			OPE_ID,
			GID,
			MAN_FLG
		)
			VALUES (
				H_ID,
				H_TYP,
				:OLD.REQ_NO,
				:OLD.OPE_ID,
				:OLD.GID,
				:OLD.MAN_FLG
		);		H_TYP := 'I';
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCT_EXCLD_GRPS_R (
			HST_ID,
			HST_TYPE,
			REQ_NO,
			OPE_ID,
			GID,
			MAN_FLG
		)
			VALUES (
				H_ID,
				H_TYP,
				:NEW.REQ_NO,
				:NEW.OPE_ID,
				:NEW.GID,
				:NEW.MAN_FLG
		);
	ELSIF DELETING THEN
		H_TYP := 'D';
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCT_EXCLD_GRPS_R (
			HST_ID,
			HST_TYPE,
			REQ_NO,
			OPE_ID,
			GID,
			MAN_FLG
		)
			VALUES (
				H_ID,
				H_TYP,
				:OLD.REQ_NO,
				:OLD.OPE_ID,
				:OLD.GID,
				:OLD.MAN_FLG
		);
	END IF;
END;
END;

/
show errors;



ALTER TRIGGER FCT_EXCLD_GRPS_TR_R DISABLE
/
show errors;


