CREATE OR REPLACE PACKAGE BODY FSC_OPERATION_STS
/*****************************
オペレーションステータスの定数定義パッケージ本体
******************************/
IS

	FUNCTION RUNNING RETURN VARCHAR2 DETERMINISTIC IS -- 実行中
	BEGIN RETURN '0'; END RUNNING;
	FUNCTION SUCCESS RETURN VARCHAR2 DETERMINISTIC IS -- 終了
	BEGIN RETURN '1'; END SUCCESS;
	FUNCTION INI RETURN VARCHAR2 DETERMINISTIC IS -- 初期化中
	BEGIN RETURN '2'; END INI;
	FUNCTION ERROR RETURN VARCHAR2 DETERMINISTIC IS -- エラー
	BEGIN RETURN '3'; END ERROR;
	FUNCTION SYSERR RETURN VARCHAR2 DETERMINISTIC IS -- システムエラー
	BEGIN RETURN '4'; END SYSERR;
	FUNCTION INIERR RETURN VARCHAR2 DETERMINISTIC IS -- 初期化エラー
	BEGIN RETURN '5'; END INIERR;

	FUNCTION IS_RUNNING(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 実行中かどうか
	BEGIN
		IF I_VALUE = RUNNING THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RUNNING;

	FUNCTION IS_SUCCESS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 終了かどうか
	BEGIN
		IF I_VALUE = SUCCESS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUCCESS;

	FUNCTION IS_INI(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 初期化中かどうか
	BEGIN
		IF I_VALUE = INI THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INI;

	FUNCTION IS_ERROR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- エラーかどうか
	BEGIN
		IF I_VALUE = ERROR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ERROR;

	FUNCTION IS_SYSERR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- システムエラーかどうか
	BEGIN
		IF I_VALUE = SYSERR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SYSERR;

	FUNCTION IS_INIERR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 初期化エラーかどうか
	BEGIN
		IF I_VALUE = INIERR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INIERR;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = RUNNING
		OR I_VALUE = SUCCESS
		OR I_VALUE = INI
		OR I_VALUE = ERROR
		OR I_VALUE = SYSERR
		OR I_VALUE = INIERR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_OPERATION_STS', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_OPERATION_STS', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_OPERATION_STS', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_OPERATION_STS', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_OPERATION_STS', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_OPERATION_STS', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_OPERATION_STS;

/
show errors;


