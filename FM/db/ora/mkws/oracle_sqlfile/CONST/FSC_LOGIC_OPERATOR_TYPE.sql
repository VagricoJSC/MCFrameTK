CREATE OR REPLACE PACKAGE BODY FSC_LOGIC_OPERATOR_TYPE
/*****************************
論理演算子の定数定義パッケージ本体
******************************/
IS

	FUNCTION TYPE_AND RETURN VARCHAR2 DETERMINISTIC IS -- AND
	BEGIN RETURN 'AND'; END TYPE_AND;
	FUNCTION TYPE_OR RETURN VARCHAR2 DETERMINISTIC IS -- OR
	BEGIN RETURN 'OR'; END TYPE_OR;

	FUNCTION IS_TYPE_AND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ANDかどうか
	BEGIN
		IF I_VALUE = TYPE_AND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_AND;

	FUNCTION IS_TYPE_OR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ORかどうか
	BEGIN
		IF I_VALUE = TYPE_OR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_OR;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TYPE_AND
		OR I_VALUE = TYPE_OR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_LOGIC_OPERATOR_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_LOGIC_OPERATOR_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_LOGIC_OPERATOR_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_LOGIC_OPERATOR_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_LOGIC_OPERATOR_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_LOGIC_OPERATOR_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_LOGIC_OPERATOR_TYPE;

/
show errors;


