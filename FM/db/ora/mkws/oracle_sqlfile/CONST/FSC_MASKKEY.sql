CREATE OR REPLACE PACKAGE BODY FSC_MASKKEY
/*****************************
マスクキーの定数定義パッケージ本体
******************************/
IS

	FUNCTION SHIFT_MASK RETURN VARCHAR2 DETERMINISTIC IS -- Ｓｈｉｆｔキー
	BEGIN RETURN 'SHIFT_MASK'; END SHIFT_MASK;
	FUNCTION CTRL_MASK RETURN VARCHAR2 DETERMINISTIC IS -- Ｃｔｒｌキー
	BEGIN RETURN 'CTRL_MASK'; END CTRL_MASK;
	FUNCTION META_MASK RETURN VARCHAR2 DETERMINISTIC IS -- Ｍｅｔａキー
	BEGIN RETURN 'META_MASK'; END META_MASK;
	FUNCTION ALT_MASK RETURN VARCHAR2 DETERMINISTIC IS -- Ａｌｔキー
	BEGIN RETURN 'ALT_MASK'; END ALT_MASK;

	FUNCTION IS_SHIFT_MASK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Ｓｈｉｆｔキーかどうか
	BEGIN
		IF I_VALUE = SHIFT_MASK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SHIFT_MASK;

	FUNCTION IS_CTRL_MASK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Ｃｔｒｌキーかどうか
	BEGIN
		IF I_VALUE = CTRL_MASK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CTRL_MASK;

	FUNCTION IS_META_MASK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Ｍｅｔａキーかどうか
	BEGIN
		IF I_VALUE = META_MASK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_META_MASK;

	FUNCTION IS_ALT_MASK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Ａｌｔキーかどうか
	BEGIN
		IF I_VALUE = ALT_MASK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALT_MASK;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SHIFT_MASK
		OR I_VALUE = CTRL_MASK
		OR I_VALUE = META_MASK
		OR I_VALUE = ALT_MASK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_MASKKEY', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_MASKKEY', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_MASKKEY', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_MASKKEY', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_MASKKEY', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_MASKKEY', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_MASKKEY;

/
show errors;


