CREATE OR REPLACE PACKAGE BODY FSC_DATA_TYPE
/*****************************
データ型の定数定義パッケージ本体
******************************/
IS

	FUNCTION STRING_TYPE RETURN VARCHAR2 DETERMINISTIC IS -- 文字列
	BEGIN RETURN 'STRING'; END STRING_TYPE;
	FUNCTION NUMBER_TYPE RETURN VARCHAR2 DETERMINISTIC IS -- 数値
	BEGIN RETURN 'NUMBER'; END NUMBER_TYPE;
	FUNCTION DATE_TYPE RETURN VARCHAR2 DETERMINISTIC IS -- 日付(DATE型)
	BEGIN RETURN 'DATE'; END DATE_TYPE;
	FUNCTION TIMESTAMP_TYPE RETURN VARCHAR2 DETERMINISTIC IS -- 日付(TIMESTAMP型)
	BEGIN RETURN 'TIMESTAMP'; END TIMESTAMP_TYPE;
	FUNCTION BOOLEAN_TYPE RETURN VARCHAR2 DETERMINISTIC IS -- ブール値
	BEGIN RETURN 'BOOLEAN'; END BOOLEAN_TYPE;

	FUNCTION IS_STRING_TYPE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 文字列かどうか
	BEGIN
		IF I_VALUE = STRING_TYPE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STRING_TYPE;

	FUNCTION IS_NUMBER_TYPE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 数値かどうか
	BEGIN
		IF I_VALUE = NUMBER_TYPE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NUMBER_TYPE;

	FUNCTION IS_DATE_TYPE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日付(DATE型)かどうか
	BEGIN
		IF I_VALUE = DATE_TYPE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DATE_TYPE;

	FUNCTION IS_TIMESTAMP_TYPE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日付(TIMESTAMP型)かどうか
	BEGIN
		IF I_VALUE = TIMESTAMP_TYPE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TIMESTAMP_TYPE;

	FUNCTION IS_BOOLEAN_TYPE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ブール値かどうか
	BEGIN
		IF I_VALUE = BOOLEAN_TYPE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_BOOLEAN_TYPE;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = STRING_TYPE
		OR I_VALUE = NUMBER_TYPE
		OR I_VALUE = DATE_TYPE
		OR I_VALUE = TIMESTAMP_TYPE
		OR I_VALUE = BOOLEAN_TYPE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION DB_KEY(
		I_DATA_TYPE IN VARCHAR2
	)RETURN VARCHAR2
	 DETERMINISTIC IS
	BEGIN
		IF (I_DATA_TYPE = STRING_TYPE) THEN
			RETURN '1';
		ELSIF (I_DATA_TYPE = NUMBER_TYPE) THEN
			RETURN '2';
		ELSIF (I_DATA_TYPE = DATE_TYPE) THEN
			RETURN '3';
		ELSIF (I_DATA_TYPE = TIMESTAMP_TYPE) THEN
			RETURN '4';
		ELSIF (I_DATA_TYPE = BOOLEAN_TYPE) THEN
			RETURN '5';
		ELSE
			RETURN NULL;
		END IF;
	END DB_KEY;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_DATA_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_DATA_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_DATA_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_DATA_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_DATA_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_DATA_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_DATA_TYPE;

/
show errors;


