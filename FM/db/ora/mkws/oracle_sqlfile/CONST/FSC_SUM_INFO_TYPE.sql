CREATE OR REPLACE PACKAGE BODY FSC_SUM_INFO_TYPE
/*****************************
集計情報区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION TYPE_GROUP RETURN VARCHAR2 DETERMINISTIC IS -- グループ化
	BEGIN RETURN '1'; END TYPE_GROUP;
	FUNCTION TYPE_SUM RETURN VARCHAR2 DETERMINISTIC IS -- 合計
	BEGIN RETURN '2'; END TYPE_SUM;
	FUNCTION TYPE_AVG RETURN VARCHAR2 DETERMINISTIC IS -- 平均
	BEGIN RETURN '3'; END TYPE_AVG;
	FUNCTION TYPE_MAX RETURN VARCHAR2 DETERMINISTIC IS -- 最大値
	BEGIN RETURN '4'; END TYPE_MAX;
	FUNCTION TYPE_MIN RETURN VARCHAR2 DETERMINISTIC IS -- 最小値
	BEGIN RETURN '5'; END TYPE_MIN;
	FUNCTION TYPE_COUNT RETURN VARCHAR2 DETERMINISTIC IS -- 件数
	BEGIN RETURN '6'; END TYPE_COUNT;
	FUNCTION TYPE_AFTER_CALC RETURN VARCHAR2 DETERMINISTIC IS -- 集計後計算
	BEGIN RETURN '7'; END TYPE_AFTER_CALC;

	FUNCTION IS_TYPE_GROUP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- グループ化かどうか
	BEGIN
		IF I_VALUE = TYPE_GROUP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_GROUP;

	FUNCTION IS_TYPE_SUM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 合計かどうか
	BEGIN
		IF I_VALUE = TYPE_SUM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_SUM;

	FUNCTION IS_TYPE_AVG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 平均かどうか
	BEGIN
		IF I_VALUE = TYPE_AVG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_AVG;

	FUNCTION IS_TYPE_MAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 最大値かどうか
	BEGIN
		IF I_VALUE = TYPE_MAX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_MAX;

	FUNCTION IS_TYPE_MIN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 最小値かどうか
	BEGIN
		IF I_VALUE = TYPE_MIN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_MIN;

	FUNCTION IS_TYPE_COUNT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 件数かどうか
	BEGIN
		IF I_VALUE = TYPE_COUNT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_COUNT;

	FUNCTION IS_TYPE_AFTER_CALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計後計算かどうか
	BEGIN
		IF I_VALUE = TYPE_AFTER_CALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_AFTER_CALC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TYPE_GROUP
		OR I_VALUE = TYPE_SUM
		OR I_VALUE = TYPE_AVG
		OR I_VALUE = TYPE_MAX
		OR I_VALUE = TYPE_MIN
		OR I_VALUE = TYPE_COUNT
		OR I_VALUE = TYPE_AFTER_CALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION COLUMN_NM(
		I_SUM_INFO_TYPE IN VARCHAR2
	)RETURN VARCHAR2
	 DETERMINISTIC IS
	BEGIN
		IF (I_SUM_INFO_TYPE = TYPE_GROUP) THEN
			RETURN NULL;
		ELSIF (I_SUM_INFO_TYPE = TYPE_SUM) THEN
			RETURN '_sum';
		ELSIF (I_SUM_INFO_TYPE = TYPE_AVG) THEN
			RETURN '_avg';
		ELSIF (I_SUM_INFO_TYPE = TYPE_MAX) THEN
			RETURN '_max';
		ELSIF (I_SUM_INFO_TYPE = TYPE_MIN) THEN
			RETURN '_min';
		ELSIF (I_SUM_INFO_TYPE = TYPE_COUNT) THEN
			RETURN '_count';
		ELSIF (I_SUM_INFO_TYPE = TYPE_AFTER_CALC) THEN
			RETURN '_after_calc';
		ELSE
			RETURN NULL;
		END IF;
	END COLUMN_NM;

	FUNCTION IS_NUM(
		I_SUM_INFO_TYPE IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_SUM_INFO_TYPE = TYPE_GROUP) THEN
			RETURN '0';
		ELSIF (I_SUM_INFO_TYPE = TYPE_SUM) THEN
			RETURN '1';
		ELSIF (I_SUM_INFO_TYPE = TYPE_AVG) THEN
			RETURN '1';
		ELSIF (I_SUM_INFO_TYPE = TYPE_MAX) THEN
			RETURN '1';
		ELSIF (I_SUM_INFO_TYPE = TYPE_MIN) THEN
			RETURN '1';
		ELSIF (I_SUM_INFO_TYPE = TYPE_COUNT) THEN
			RETURN '0';
		ELSIF (I_SUM_INFO_TYPE = TYPE_AFTER_CALC) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_NUM;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_SUM_INFO_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_SUM_INFO_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_SUM_INFO_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_SUM_INFO_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_SUM_INFO_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_SUM_INFO_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_SUM_INFO_TYPE;

/
show errors;


