CREATE OR REPLACE PACKAGE BODY FSC_DAY_OF_WEEK_TYPE
/*****************************
曜日の定数定義パッケージ本体
******************************/
IS

	FUNCTION TYPE_SUNDAY RETURN VARCHAR2 DETERMINISTIC IS -- 日曜日
	BEGIN RETURN '1'; END TYPE_SUNDAY;
	FUNCTION TYPE_MONDAY RETURN VARCHAR2 DETERMINISTIC IS -- 月曜日
	BEGIN RETURN '2'; END TYPE_MONDAY;
	FUNCTION TYPE_TUESDAY RETURN VARCHAR2 DETERMINISTIC IS -- 火曜日
	BEGIN RETURN '3'; END TYPE_TUESDAY;
	FUNCTION TYPE_WEDNESDAY RETURN VARCHAR2 DETERMINISTIC IS -- 水曜日
	BEGIN RETURN '4'; END TYPE_WEDNESDAY;
	FUNCTION TYPE_THURSDAY RETURN VARCHAR2 DETERMINISTIC IS -- 木曜日
	BEGIN RETURN '5'; END TYPE_THURSDAY;
	FUNCTION TYPE_FRIDAY RETURN VARCHAR2 DETERMINISTIC IS -- 金曜日
	BEGIN RETURN '6'; END TYPE_FRIDAY;
	FUNCTION TYPE_SATURDAY RETURN VARCHAR2 DETERMINISTIC IS -- 土曜日
	BEGIN RETURN '7'; END TYPE_SATURDAY;

	FUNCTION IS_TYPE_SUNDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_SUNDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_SUNDAY;

	FUNCTION IS_TYPE_MONDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_MONDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_MONDAY;

	FUNCTION IS_TYPE_TUESDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 火曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_TUESDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_TUESDAY;

	FUNCTION IS_TYPE_WEDNESDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 水曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_WEDNESDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_WEDNESDAY;

	FUNCTION IS_TYPE_THURSDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 木曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_THURSDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_THURSDAY;

	FUNCTION IS_TYPE_FRIDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 金曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_FRIDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_FRIDAY;

	FUNCTION IS_TYPE_SATURDAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 土曜日かどうか
	BEGIN
		IF I_VALUE = TYPE_SATURDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_SATURDAY;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TYPE_SUNDAY
		OR I_VALUE = TYPE_MONDAY
		OR I_VALUE = TYPE_TUESDAY
		OR I_VALUE = TYPE_WEDNESDAY
		OR I_VALUE = TYPE_THURSDAY
		OR I_VALUE = TYPE_FRIDAY
		OR I_VALUE = TYPE_SATURDAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_DAY_OF_WEEK_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_DAY_OF_WEEK_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_DAY_OF_WEEK_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_DAY_OF_WEEK_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_DAY_OF_WEEK_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_DAY_OF_WEEK_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_DAY_OF_WEEK_TYPE;

/
show errors;


