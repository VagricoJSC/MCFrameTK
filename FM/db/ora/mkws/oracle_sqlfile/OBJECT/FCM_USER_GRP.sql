SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW FCM_USER_GRP(
	UGID,
	GROUP_ID,
	GROUP_NM,
	CO_CD,
	EXT_ATTR1,
	EXT_ATTR2,
	EXT_ATTR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.UGID,
	ORG.GROUP_ID,
	LCL.GROUP_NM,
	ORG.CO_CD,
	ORG.EXT_ATTR1,
	ORG.EXT_ATTR2,
	ORG.EXT_ATTR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	FCM_USER_GRP_ALL ORG,
	fcm_user_grp_lcl_all LCL
WHERE
	0 = 0
	AND ORG.UGID = LCL.UGID(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)

;

