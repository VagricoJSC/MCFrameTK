SET SQLBLANKLINES ON

CREATE GLOBAL TEMPORARY TABLE FCW_UPD_TABLES
(TABLE_NAME VARCHAR2 (30 char) NOT NULL
) ON COMMIT DELETE ROWS;


-- FOR DYNAMIC SAMPLING
DECLARE
	L_S VARCHAR2(30);
	L_T VARCHAR2(30);
BEGIN
	L_S:=SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
	L_T:='FCW_UPD_TABLES';
	DBMS_STATS.DELETE_TABLE_STATS(L_S, L_T);
	DBMS_STATS.LOCK_TABLE_STATS(L_S, L_T);
END;

/
show errors;


