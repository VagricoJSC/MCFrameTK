CREATE OR REPLACE VIEW FCM_GP_BATCH_GRP_$U(
	GP_BATCH_GRP_CD,
	GP_BATCH_GRP_NM,
	MODULE_ID,
	LOGIC_ID,
	FUNC_TYP,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.GP_BATCH_GRP_CD,
	ORG.GP_BATCH_GRP_NM,
	ORG.MODULE_ID,
	ORG.LOGIC_ID,
	ORG.FUNC_TYP,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	FCM_GP_BATCH_GRP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

