CREATE OR REPLACE PACKAGE BODY FSC_COLOR_KEY
/*****************************
色設定キーの定数定義パッケージ本体
******************************/
IS

	FUNCTION ROOTPANEL_BG RETURN VARCHAR2 DETERMINISTIC IS -- 画面の背景色
	BEGIN RETURN 'ROOTPANEL_BG'; END ROOTPANEL_BG;
	FUNCTION PANEL_BG2 RETURN VARCHAR2 DETERMINISTIC IS -- 画面枠内の色
	BEGIN RETURN 'PANEL_BG2'; END PANEL_BG2;

	FUNCTION IS_ROOTPANEL_BG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 画面の背景色かどうか
	BEGIN
		IF I_VALUE = ROOTPANEL_BG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ROOTPANEL_BG;

	FUNCTION IS_PANEL_BG2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 画面枠内の色かどうか
	BEGIN
		IF I_VALUE = PANEL_BG2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PANEL_BG2;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ROOTPANEL_BG
		OR I_VALUE = PANEL_BG2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION SORT_ORDER(
		I_COLOR_KEY IN VARCHAR2
	)RETURN NUMBER
	 DETERMINISTIC IS
	BEGIN
		IF (I_COLOR_KEY = ROOTPANEL_BG) THEN
			RETURN 1;
		ELSIF (I_COLOR_KEY = PANEL_BG2) THEN
			RETURN 2;
		ELSE
			RETURN NULL;
		END IF;
	END SORT_ORDER;

	FUNCTION RESOURCE_TYPE(
		I_COLOR_KEY IN VARCHAR2
	)RETURN VARCHAR2
	 DETERMINISTIC IS
	BEGIN
		IF (I_COLOR_KEY = ROOTPANEL_BG) THEN
			RETURN 'MCBeans';
		ELSIF (I_COLOR_KEY = PANEL_BG2) THEN
			RETURN 'MCBeans';
		ELSE
			RETURN NULL;
		END IF;
	END RESOURCE_TYPE;

	FUNCTION RESOURCE_KEY(
		I_COLOR_KEY IN VARCHAR2
	)RETURN VARCHAR2
	 DETERMINISTIC IS
	BEGIN
		IF (I_COLOR_KEY = ROOTPANEL_BG) THEN
			RETURN 'rootpanel.p_bg';
		ELSIF (I_COLOR_KEY = PANEL_BG2) THEN
			RETURN 'panel.bg2';
		ELSE
			RETURN NULL;
		END IF;
	END RESOURCE_KEY;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_COLOR_KEY', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_COLOR_KEY', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_COLOR_KEY', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_COLOR_KEY', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_COLOR_KEY', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_COLOR_KEY', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_COLOR_KEY;
