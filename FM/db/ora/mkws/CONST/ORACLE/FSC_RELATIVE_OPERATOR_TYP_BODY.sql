CREATE OR REPLACE PACKAGE BODY FSC_RELATIVE_OPERATOR_TYP
/*****************************
比較演算子の定数定義パッケージ本体
******************************/
IS

	FUNCTION TYPE_EQUAL RETURN VARCHAR2 DETERMINISTIC IS -- =
	BEGIN RETURN 'EQUAL'; END TYPE_EQUAL;
	FUNCTION TYPE_NOT_EQUAL RETURN VARCHAR2 DETERMINISTIC IS -- <>
	BEGIN RETURN 'NOT_EQUAL'; END TYPE_NOT_EQUAL;
	FUNCTION TYPE_LESS_THAN RETURN VARCHAR2 DETERMINISTIC IS -- <
	BEGIN RETURN 'LESS_THAN'; END TYPE_LESS_THAN;
	FUNCTION TYPE_LESS_THAN_EQUAL RETURN VARCHAR2 DETERMINISTIC IS -- <=
	BEGIN RETURN 'LESS_THAN_EQUAL'; END TYPE_LESS_THAN_EQUAL;
	FUNCTION TYPE_GREATER_THAN RETURN VARCHAR2 DETERMINISTIC IS -- >
	BEGIN RETURN 'GREATER_THAN'; END TYPE_GREATER_THAN;
	FUNCTION TYPE_GREATER_THAN_EQUAL RETURN VARCHAR2 DETERMINISTIC IS -- >=
	BEGIN RETURN 'GREATER_THAN_EQUAL'; END TYPE_GREATER_THAN_EQUAL;
	FUNCTION TYPE_START_WITH RETURN VARCHAR2 DETERMINISTIC IS -- 始まる
	BEGIN RETURN 'START_WITH'; END TYPE_START_WITH;
	FUNCTION TYPE_NOT_START_WITH RETURN VARCHAR2 DETERMINISTIC IS -- 始まらない
	BEGIN RETURN 'NOT_START_WITH'; END TYPE_NOT_START_WITH;
	FUNCTION TYPE_END_WITH RETURN VARCHAR2 DETERMINISTIC IS -- 終わる
	BEGIN RETURN 'END_WITH'; END TYPE_END_WITH;
	FUNCTION TYPE_NOT_END_WITH RETURN VARCHAR2 DETERMINISTIC IS -- 終わらない
	BEGIN RETURN 'NOT_END_WITH'; END TYPE_NOT_END_WITH;
	FUNCTION TYPE_CONTAINS RETURN VARCHAR2 DETERMINISTIC IS -- 含む
	BEGIN RETURN 'CONTAINS'; END TYPE_CONTAINS;
	FUNCTION TYPE_NOT_CONTAINS RETURN VARCHAR2 DETERMINISTIC IS -- 含まない
	BEGIN RETURN 'NOT_CONTAINS'; END TYPE_NOT_CONTAINS;

	FUNCTION IS_TYPE_EQUAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- =かどうか
	BEGIN
		IF I_VALUE = TYPE_EQUAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_EQUAL;

	FUNCTION IS_TYPE_NOT_EQUAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- <>かどうか
	BEGIN
		IF I_VALUE = TYPE_NOT_EQUAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_NOT_EQUAL;

	FUNCTION IS_TYPE_LESS_THAN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- <かどうか
	BEGIN
		IF I_VALUE = TYPE_LESS_THAN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_LESS_THAN;

	FUNCTION IS_TYPE_LESS_THAN_EQUAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- <=かどうか
	BEGIN
		IF I_VALUE = TYPE_LESS_THAN_EQUAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_LESS_THAN_EQUAL;

	FUNCTION IS_TYPE_GREATER_THAN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- >かどうか
	BEGIN
		IF I_VALUE = TYPE_GREATER_THAN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_GREATER_THAN;

	FUNCTION IS_TYPE_GREATER_THAN_EQUAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- >=かどうか
	BEGIN
		IF I_VALUE = TYPE_GREATER_THAN_EQUAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_GREATER_THAN_EQUAL;

	FUNCTION IS_TYPE_START_WITH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 始まるかどうか
	BEGIN
		IF I_VALUE = TYPE_START_WITH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_START_WITH;

	FUNCTION IS_TYPE_NOT_START_WITH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 始まらないかどうか
	BEGIN
		IF I_VALUE = TYPE_NOT_START_WITH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_NOT_START_WITH;

	FUNCTION IS_TYPE_END_WITH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 終わるかどうか
	BEGIN
		IF I_VALUE = TYPE_END_WITH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_END_WITH;

	FUNCTION IS_TYPE_NOT_END_WITH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 終わらないかどうか
	BEGIN
		IF I_VALUE = TYPE_NOT_END_WITH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_NOT_END_WITH;

	FUNCTION IS_TYPE_CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 含むかどうか
	BEGIN
		IF I_VALUE = TYPE_CONTAINS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_CONTAINS;

	FUNCTION IS_TYPE_NOT_CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 含まないかどうか
	BEGIN
		IF I_VALUE = TYPE_NOT_CONTAINS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_NOT_CONTAINS;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TYPE_EQUAL
		OR I_VALUE = TYPE_NOT_EQUAL
		OR I_VALUE = TYPE_LESS_THAN
		OR I_VALUE = TYPE_LESS_THAN_EQUAL
		OR I_VALUE = TYPE_GREATER_THAN
		OR I_VALUE = TYPE_GREATER_THAN_EQUAL
		OR I_VALUE = TYPE_START_WITH
		OR I_VALUE = TYPE_NOT_START_WITH
		OR I_VALUE = TYPE_END_WITH
		OR I_VALUE = TYPE_NOT_END_WITH
		OR I_VALUE = TYPE_CONTAINS
		OR I_VALUE = TYPE_NOT_CONTAINS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_RELATIVE_OPERATOR_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_RELATIVE_OPERATOR_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_RELATIVE_OPERATOR_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_RELATIVE_OPERATOR_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_RELATIVE_OPERATOR_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_RELATIVE_OPERATOR_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_RELATIVE_OPERATOR_TYP;
