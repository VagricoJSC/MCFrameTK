CREATE OR REPLACE PACKAGE FSC_PRINTER_TYPE
/*****************************
プリンタタイプの定数定義パッケージ
*****************************/
IS

	FUNCTION OS RETURN VARCHAR2 DETERMINISTIC ; -- OS
	FUNCTION MCFrame_Report RETURN VARCHAR2 DETERMINISTIC ; -- mcframe_Report
	FUNCTION SlimPrint RETURN VARCHAR2 DETERMINISTIC ; -- SlimPrint

	FUNCTION IS_OS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- OSであるか
	FUNCTION IS_MCFrame_Report(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- mcframe_Reportであるか
	FUNCTION IS_SlimPrint(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- SlimPrintであるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
