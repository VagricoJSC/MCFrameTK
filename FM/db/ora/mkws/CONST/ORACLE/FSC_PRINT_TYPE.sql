CREATE OR REPLACE PACKAGE FSC_PRINT_TYPE
/*****************************
印刷タイプの定数定義パッケージ
*****************************/
IS

	FUNCTION Client_Server RETURN VARCHAR2 DETERMINISTIC ; -- クライアント－サーバ印刷
	FUNCTION Server RETURN VARCHAR2 DETERMINISTIC ; -- サーバ印刷
	FUNCTION Client RETURN VARCHAR2 DETERMINISTIC ; -- クライアント印刷
	FUNCTION Retry RETURN VARCHAR2 DETERMINISTIC ; -- クライアント再印刷
	FUNCTION File_Donwload RETURN VARCHAR2 DETERMINISTIC ; -- ファイルダウンロード
	FUNCTION Unknown RETURN VARCHAR2 DETERMINISTIC ; -- 不明

	FUNCTION IS_Client_Server(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- クライアント－サーバ印刷であるか
	FUNCTION IS_Server(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- サーバ印刷であるか
	FUNCTION IS_Client(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- クライアント印刷であるか
	FUNCTION IS_Retry(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- クライアント再印刷であるか
	FUNCTION IS_File_Donwload(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- ファイルダウンロードであるか
	FUNCTION IS_Unknown(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 不明であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
