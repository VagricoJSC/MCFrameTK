CREATE OR REPLACE PACKAGE BODY FXC_BATCH_LOG_TYP
/*****************************
バッチログ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION START_LOG RETURN VARCHAR2 DETERMINISTIC IS -- 開始ログ
	BEGIN RETURN 'S'; END START_LOG;
	FUNCTION DATA_LOG RETURN VARCHAR2 DETERMINISTIC IS -- データ
	BEGIN RETURN 'D'; END DATA_LOG;
	FUNCTION PROC_LOG RETURN VARCHAR2 DETERMINISTIC IS -- 処理経過
	BEGIN RETURN 'P'; END PROC_LOG;
	FUNCTION END_LOG RETURN VARCHAR2 DETERMINISTIC IS -- 終了ログ
	BEGIN RETURN 'E'; END END_LOG;

	FUNCTION IS_START_LOG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 開始ログかどうか
	BEGIN
		IF I_VALUE = START_LOG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_START_LOG;

	FUNCTION IS_DATA_LOG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- データかどうか
	BEGIN
		IF I_VALUE = DATA_LOG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DATA_LOG;

	FUNCTION IS_PROC_LOG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 処理経過かどうか
	BEGIN
		IF I_VALUE = PROC_LOG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROC_LOG;

	FUNCTION IS_END_LOG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 終了ログかどうか
	BEGIN
		IF I_VALUE = END_LOG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_END_LOG;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = START_LOG
		OR I_VALUE = DATA_LOG
		OR I_VALUE = PROC_LOG
		OR I_VALUE = END_LOG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FXC_BATCH_LOG_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FXC_BATCH_LOG_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FXC_BATCH_LOG_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FXC_BATCH_LOG_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FXC_BATCH_LOG_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FXC_BATCH_LOG_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FXC_BATCH_LOG_TYP;
