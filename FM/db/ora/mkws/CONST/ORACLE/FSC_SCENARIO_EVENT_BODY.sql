	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = EVENT_MOUSE_CLICK
		OR I_VALUE = EVENT_MOUSE_RELEASE
		OR I_VALUE = EVENT_MOUSE_MOVE
		OR I_VALUE = EVENT_MOUSE_DRAG
		OR I_VALUE = EVENT_KEY_PRESS
		OR I_VALUE = EVENT_KEY_RELEASE
		OR I_VALUE = WAIT_100
		OR I_VALUE = WAIT_500
		OR I_VALUE = WAIT_EVENT
		OR I_VALUE = KEY_EVENT
		OR I_VALUE = SCREEN_CLEAR_EVENT
		OR I_VALUE = COMMAND_EVENT
		OR I_VALUE = BIND_EVENT
		OR I_VALUE = SPECIAL_KEY_PRESS_EVENT
		OR I_VALUE = SPECIAL_KEY_RELEASE_EVENT
		OR I_VALUE = POPUP_ITEM_EVENT
		OR I_VALUE = SNAPSHOT_EVENT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

