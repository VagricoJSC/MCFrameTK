/*****************************
オペレーション区分の定数定義パッケージ
*****************************/
IS

	FUNCTION Scn_Opn RETURN VARCHAR2 DETERMINISTIC ; -- 画面オープン
	FUNCTION Scn_Cls RETURN VARCHAR2 DETERMINISTIC ; -- 画面クローズ
	FUNCTION Btn_Push RETURN VARCHAR2 DETERMINISTIC ; -- ボタン押下
	FUNCTION Xls_Out RETURN VARCHAR2 DETERMINISTIC ; -- Excel出力
	FUNCTION Csv_Out RETURN VARCHAR2 DETERMINISTIC ; -- CSV出力

	FUNCTION IS_Scn_Opn(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 画面オープンであるか
	FUNCTION IS_Scn_Cls(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 画面クローズであるか
	FUNCTION IS_Btn_Push(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- ボタン押下であるか
