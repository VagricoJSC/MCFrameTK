CREATE OR REPLACE PACKAGE BODY FSC_SEARCH_TYPE
/*****************************
検索タイプの定数定義パッケージ本体
******************************/
IS

	FUNCTION ALL_DATA RETURN VARCHAR2 DETERMINISTIC IS -- すべて
	BEGIN RETURN '1'; END ALL_DATA;
	FUNCTION EXT_ATTR_EQ RETURN VARCHAR2 DETERMINISTIC IS -- ユーザの会社で検索
	BEGIN RETURN '2'; END EXT_ATTR_EQ;
	FUNCTION USER_EXT_ATTR_EQ RETURN VARCHAR2 DETERMINISTIC IS -- ユーザID、ユーザの会社で検索
	BEGIN RETURN '3'; END USER_EXT_ATTR_EQ;

	FUNCTION IS_ALL_DATA(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- すべてかどうか
	BEGIN
		IF I_VALUE = ALL_DATA THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALL_DATA;

	FUNCTION IS_EXT_ATTR_EQ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ユーザの会社で検索かどうか
	BEGIN
		IF I_VALUE = EXT_ATTR_EQ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXT_ATTR_EQ;

	FUNCTION IS_USER_EXT_ATTR_EQ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ユーザID、ユーザの会社で検索かどうか
	BEGIN
		IF I_VALUE = USER_EXT_ATTR_EQ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_USER_EXT_ATTR_EQ;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ALL_DATA
		OR I_VALUE = EXT_ATTR_EQ
		OR I_VALUE = USER_EXT_ATTR_EQ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_SEARCH_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_SEARCH_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_SEARCH_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_SEARCH_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_SEARCH_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_SEARCH_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_SEARCH_TYPE;
/