CREATE OR REPLACE PACKAGE BODY FXC_RESOURCE_SETTING_UNIT
/*****************************
リソース設定単位の定数定義パッケージ本体
******************************/
IS

	FUNCTION TYPE_USER RETURN VARCHAR2 DETERMINISTIC IS -- ユーザ
	BEGIN RETURN 'USER'; END TYPE_USER;
	FUNCTION TYPE_EXT RETURN VARCHAR2 DETERMINISTIC IS -- 会社共通
	BEGIN RETURN 'EXT'; END TYPE_EXT;
	FUNCTION TYPE_SYS RETURN VARCHAR2 DETERMINISTIC IS -- システム共通
	BEGIN RETURN 'SYS'; END TYPE_SYS;
	FUNCTION TYPE_PGM RETURN VARCHAR2 DETERMINISTIC IS -- プログラム
	BEGIN RETURN 'PGM'; END TYPE_PGM;
	FUNCTION TYPE_BARCODE RETURN VARCHAR2 DETERMINISTIC IS -- バーコード
	BEGIN RETURN 'BARCODE'; END TYPE_BARCODE;

	FUNCTION IS_TYPE_USER(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ユーザかどうか
	BEGIN
		IF I_VALUE = TYPE_USER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_USER;

	FUNCTION IS_TYPE_EXT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会社共通かどうか
	BEGIN
		IF I_VALUE = TYPE_EXT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_EXT;

	FUNCTION IS_TYPE_SYS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- システム共通かどうか
	BEGIN
		IF I_VALUE = TYPE_SYS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_SYS;

	FUNCTION IS_TYPE_PGM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- プログラムかどうか
	BEGIN
		IF I_VALUE = TYPE_PGM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_PGM;

	FUNCTION IS_TYPE_BARCODE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- バーコードかどうか
	BEGIN
		IF I_VALUE = TYPE_BARCODE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_BARCODE;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TYPE_USER
		OR I_VALUE = TYPE_EXT
		OR I_VALUE = TYPE_SYS
		OR I_VALUE = TYPE_PGM
		OR I_VALUE = TYPE_BARCODE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FXC_RESOURCE_SETTING_UNIT', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FXC_RESOURCE_SETTING_UNIT', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FXC_RESOURCE_SETTING_UNIT', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FXC_RESOURCE_SETTING_UNIT', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FXC_RESOURCE_SETTING_UNIT', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FXC_RESOURCE_SETTING_UNIT', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FXC_RESOURCE_SETTING_UNIT;
