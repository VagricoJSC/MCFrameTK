	FUNCTION TYPE_DESC RETURN VARCHAR2 DETERMINISTIC ; -- 全て降順
	FUNCTION TYPE_ASC_NULL_AHEAD RETURN VARCHAR2 DETERMINISTIC ; -- 全て昇順（空白優先）
	FUNCTION TYPE_DESC_NULL_AHEAD RETURN VARCHAR2 DETERMINISTIC ; -- 全て降順（空白優先）

	FUNCTION IS_TYPE_ASC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 全て昇順であるか
	FUNCTION IS_TYPE_DESC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 全て降順であるか
