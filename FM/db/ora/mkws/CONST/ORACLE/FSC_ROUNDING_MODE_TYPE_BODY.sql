CREATE OR REPLACE PACKAGE BODY FSC_ROUNDING_MODE_TYPE
/*****************************
端数処理区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MODE_UP RETURN VARCHAR2 DETERMINISTIC IS -- 切り上げ
	BEGIN RETURN '1'; END MODE_UP;
	FUNCTION MODE_DOWN RETURN VARCHAR2 DETERMINISTIC IS -- 切り捨て
	BEGIN RETURN '2'; END MODE_DOWN;
	FUNCTION MODE_HALF_UP RETURN VARCHAR2 DETERMINISTIC IS -- 四捨五入
	BEGIN RETURN '3'; END MODE_HALF_UP;

	FUNCTION IS_MODE_UP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 切り上げかどうか
	BEGIN
		IF I_VALUE = MODE_UP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MODE_UP;

	FUNCTION IS_MODE_DOWN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 切り捨てかどうか
	BEGIN
		IF I_VALUE = MODE_DOWN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MODE_DOWN;

	FUNCTION IS_MODE_HALF_UP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 四捨五入かどうか
	BEGIN
		IF I_VALUE = MODE_HALF_UP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MODE_HALF_UP;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MODE_UP
		OR I_VALUE = MODE_DOWN
		OR I_VALUE = MODE_HALF_UP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_ROUNDING_MODE_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_ROUNDING_MODE_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_ROUNDING_MODE_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_ROUNDING_MODE_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_ROUNDING_MODE_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_ROUNDING_MODE_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_ROUNDING_MODE_TYPE;
