CREATE OR REPLACE PACKAGE BODY FSC_PRINTER_TYPE
/*****************************
プリンタタイプの定数定義パッケージ本体
******************************/
IS

	FUNCTION OS RETURN VARCHAR2 DETERMINISTIC IS -- OS
	BEGIN RETURN '1'; END OS;
	FUNCTION MCFrame_Report RETURN VARCHAR2 DETERMINISTIC IS -- mcframe_Report
	BEGIN RETURN '2'; END MCFrame_Report;
	FUNCTION SlimPrint RETURN VARCHAR2 DETERMINISTIC IS -- SlimPrint
	BEGIN RETURN '3'; END SlimPrint;

	FUNCTION IS_OS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- OSかどうか
	BEGIN
		IF I_VALUE = OS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OS;

	FUNCTION IS_MCFrame_Report(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- mcframe_Reportかどうか
	BEGIN
		IF I_VALUE = MCFrame_Report THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MCFrame_Report;

	FUNCTION IS_SlimPrint(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- SlimPrintかどうか
	BEGIN
		IF I_VALUE = SlimPrint THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SlimPrint;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = OS
		OR I_VALUE = MCFrame_Report
		OR I_VALUE = SlimPrint THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_PRINTER_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_PRINTER_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_PRINTER_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_PRINTER_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_PRINTER_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_PRINTER_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_PRINTER_TYPE;
/