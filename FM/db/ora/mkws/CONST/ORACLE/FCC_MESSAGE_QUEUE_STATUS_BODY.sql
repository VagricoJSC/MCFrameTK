CREATE OR REPLACE PACKAGE BODY FCC_MESSAGE_QUEUE_STATUS
/*****************************
メッセージキューステータスの定数定義パッケージ本体
******************************/
IS

	FUNCTION WAIT_FOR_EXECUTION RETURN VARCHAR2 DETERMINISTIC IS -- 実行待機中
	BEGIN RETURN '1'; END WAIT_FOR_EXECUTION;
	FUNCTION WAIT_FOR_REPLAY RETURN VARCHAR2 DETERMINISTIC IS -- 再実行待機中
	BEGIN RETURN '2'; END WAIT_FOR_REPLAY;
	FUNCTION RUNNING RETURN VARCHAR2 DETERMINISTIC IS -- 実行中
	BEGIN RETURN '3'; END RUNNING;
	FUNCTION NORMAL_END RETURN VARCHAR2 DETERMINISTIC IS -- 正常終了
	BEGIN RETURN '4'; END NORMAL_END;
	FUNCTION ABNORMAL_END RETURN VARCHAR2 DETERMINISTIC IS -- 異常終了
	BEGIN RETURN '5'; END ABNORMAL_END;

	FUNCTION IS_WAIT_FOR_EXECUTION(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 実行待機中かどうか
	BEGIN
		IF I_VALUE = WAIT_FOR_EXECUTION THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WAIT_FOR_EXECUTION;

	FUNCTION IS_WAIT_FOR_REPLAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 再実行待機中かどうか
	BEGIN
		IF I_VALUE = WAIT_FOR_REPLAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WAIT_FOR_REPLAY;

	FUNCTION IS_RUNNING(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 実行中かどうか
	BEGIN
		IF I_VALUE = RUNNING THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RUNNING;

	FUNCTION IS_NORMAL_END(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 正常終了かどうか
	BEGIN
		IF I_VALUE = NORMAL_END THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NORMAL_END;

	FUNCTION IS_ABNORMAL_END(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 異常終了かどうか
	BEGIN
		IF I_VALUE = ABNORMAL_END THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ABNORMAL_END;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = WAIT_FOR_EXECUTION
		OR I_VALUE = WAIT_FOR_REPLAY
		OR I_VALUE = RUNNING
		OR I_VALUE = NORMAL_END
		OR I_VALUE = ABNORMAL_END THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FCC_MESSAGE_QUEUE_STATUS', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FCC_MESSAGE_QUEUE_STATUS', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FCC_MESSAGE_QUEUE_STATUS', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FCC_MESSAGE_QUEUE_STATUS', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FCC_MESSAGE_QUEUE_STATUS', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FCC_MESSAGE_QUEUE_STATUS', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FCC_MESSAGE_QUEUE_STATUS;
