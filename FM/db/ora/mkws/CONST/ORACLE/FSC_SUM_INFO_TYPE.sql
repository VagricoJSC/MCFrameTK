CREATE OR REPLACE PACKAGE FSC_SUM_INFO_TYPE
/*****************************
集計情報区分の定数定義パッケージ
*****************************/
IS

	FUNCTION TYPE_GROUP RETURN VARCHAR2 DETERMINISTIC ; -- グループ化
	FUNCTION TYPE_SUM RETURN VARCHAR2 DETERMINISTIC ; -- 合計
	FUNCTION TYPE_AVG RETURN VARCHAR2 DETERMINISTIC ; -- 平均
	FUNCTION TYPE_MAX RETURN VARCHAR2 DETERMINISTIC ; -- 最大値
	FUNCTION TYPE_MIN RETURN VARCHAR2 DETERMINISTIC ; -- 最小値
	FUNCTION TYPE_COUNT RETURN VARCHAR2 DETERMINISTIC ; -- 件数
	FUNCTION TYPE_AFTER_CALC RETURN VARCHAR2 DETERMINISTIC ; -- 集計後計算

	FUNCTION IS_TYPE_GROUP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- グループ化であるか
	FUNCTION IS_TYPE_SUM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 合計であるか
	FUNCTION IS_TYPE_AVG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 平均であるか
	FUNCTION IS_TYPE_MAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 最大値であるか
	FUNCTION IS_TYPE_MIN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 最小値であるか
	FUNCTION IS_TYPE_COUNT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 件数であるか
	FUNCTION IS_TYPE_AFTER_CALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 集計後計算であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION COLUMN_NM(
		I_SUM_INFO_TYPE IN VARCHAR2
	)
	RETURN VARCHAR2 DETERMINISTIC ;

	FUNCTION IS_NUM(
		I_SUM_INFO_TYPE IN VARCHAR2
	)
	RETURN CHAR DETERMINISTIC ;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
