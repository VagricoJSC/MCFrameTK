CREATE OR REPLACE PACKAGE BODY FSC_OPERATION_CD
/*****************************
オペレーション区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION Scn_Opn RETURN VARCHAR2 DETERMINISTIC IS -- 画面オープン
	BEGIN RETURN 'SO'; END Scn_Opn;
	FUNCTION Scn_Cls RETURN VARCHAR2 DETERMINISTIC IS -- 画面クローズ
	BEGIN RETURN 'SC'; END Scn_Cls;
	FUNCTION Btn_Push RETURN VARCHAR2 DETERMINISTIC IS -- ボタン押下
	BEGIN RETURN 'BP'; END Btn_Push;
	FUNCTION Xls_Out RETURN VARCHAR2 DETERMINISTIC IS -- Excel出力
	BEGIN RETURN 'EX'; END Xls_Out;
	FUNCTION Csv_Out RETURN VARCHAR2 DETERMINISTIC IS -- CSV出力
	BEGIN RETURN 'CS'; END Csv_Out;

	FUNCTION IS_Scn_Opn(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 画面オープンかどうか
	BEGIN
		IF I_VALUE = Scn_Opn THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Scn_Opn;

	FUNCTION IS_Scn_Cls(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 画面クローズかどうか
	BEGIN
		IF I_VALUE = Scn_Cls THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Scn_Cls;

	FUNCTION IS_Btn_Push(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ボタン押下かどうか
	BEGIN
		IF I_VALUE = Btn_Push THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Btn_Push;

	FUNCTION IS_Xls_Out(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Excel出力かどうか
	BEGIN
		IF I_VALUE = Xls_Out THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Xls_Out;

	FUNCTION IS_Csv_Out(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- CSV出力かどうか
	BEGIN
		IF I_VALUE = Csv_Out THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Csv_Out;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = Scn_Opn
		OR I_VALUE = Scn_Cls
		OR I_VALUE = Btn_Push
		OR I_VALUE = Xls_Out
		OR I_VALUE = Csv_Out THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_OPERATION_CD', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_OPERATION_CD', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_OPERATION_CD', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_OPERATION_CD', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_OPERATION_CD', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_OPERATION_CD', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_OPERATION_CD;
