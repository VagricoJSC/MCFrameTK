CREATE OR REPLACE PACKAGE BODY FSC_MENU_TYPE
/*****************************
メニュー種別の定数定義パッケージ本体
******************************/
IS

	FUNCTION MENU RETURN VARCHAR2 DETERMINISTIC IS -- サブメニュー
	BEGIN RETURN 'F'; END MENU;
	FUNCTION ITEM RETURN VARCHAR2 DETERMINISTIC IS -- アイテム
	BEGIN RETURN 'I'; END ITEM;
	FUNCTION EXEC RETURN VARCHAR2 DETERMINISTIC IS -- メソッド実行
	BEGIN RETURN 'E'; END EXEC;
	FUNCTION NEWLINE RETURN VARCHAR2 DETERMINISTIC IS -- 改行
	BEGIN RETURN 'L'; END NEWLINE;
	FUNCTION SEP RETURN VARCHAR2 DETERMINISTIC IS -- セパレータ
	BEGIN RETURN 'S'; END SEP;

	FUNCTION IS_MENU(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- サブメニューかどうか
	BEGIN
		IF I_VALUE = MENU THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MENU;

	FUNCTION IS_ITEM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- アイテムかどうか
	BEGIN
		IF I_VALUE = ITEM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITEM;

	FUNCTION IS_EXEC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- メソッド実行かどうか
	BEGIN
		IF I_VALUE = EXEC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXEC;

	FUNCTION IS_NEWLINE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 改行かどうか
	BEGIN
		IF I_VALUE = NEWLINE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NEWLINE;

	FUNCTION IS_SEP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- セパレータかどうか
	BEGIN
		IF I_VALUE = SEP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SEP;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MENU
		OR I_VALUE = ITEM
		OR I_VALUE = EXEC
		OR I_VALUE = NEWLINE
		OR I_VALUE = SEP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_MENU_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_MENU_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_MENU_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_MENU_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_MENU_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_MENU_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_MENU_TYPE;
