CREATE OR REPLACE PACKAGE BODY FSC_TABLE_TYP
/*****************************
テーブル種別の定数定義パッケージ本体
******************************/
IS

	FUNCTION Constant_typ RETURN VARCHAR2 DETERMINISTIC IS -- 定数
	BEGIN RETURN 'C'; END Constant_typ;
	FUNCTION Master_typ RETURN VARCHAR2 DETERMINISTIC IS -- マスタ
	BEGIN RETURN 'M'; END Master_typ;
	FUNCTION Save_typ RETURN VARCHAR2 DETERMINISTIC IS -- 退避
	BEGIN RETURN 'S'; END Save_typ;
	FUNCTION Transaction_typ RETURN VARCHAR2 DETERMINISTIC IS -- トランザクション
	BEGIN RETURN 'T'; END Transaction_typ;
	FUNCTION Work_typ RETURN VARCHAR2 DETERMINISTIC IS -- ワーク
	BEGIN RETURN 'W'; END Work_typ;

	FUNCTION IS_Constant_typ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数かどうか
	BEGIN
		IF I_VALUE = Constant_typ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Constant_typ;

	FUNCTION IS_Master_typ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- マスタかどうか
	BEGIN
		IF I_VALUE = Master_typ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Master_typ;

	FUNCTION IS_Save_typ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 退避かどうか
	BEGIN
		IF I_VALUE = Save_typ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Save_typ;

	FUNCTION IS_Transaction_typ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- トランザクションかどうか
	BEGIN
		IF I_VALUE = Transaction_typ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Transaction_typ;

	FUNCTION IS_Work_typ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ワークかどうか
	BEGIN
		IF I_VALUE = Work_typ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Work_typ;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = Constant_typ
		OR I_VALUE = Master_typ
		OR I_VALUE = Save_typ
		OR I_VALUE = Transaction_typ
		OR I_VALUE = Work_typ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_TABLE_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_TABLE_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_TABLE_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_TABLE_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_TABLE_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_TABLE_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_TABLE_TYP;
