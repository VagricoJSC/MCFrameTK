CREATE OR REPLACE PACKAGE BODY FSC_SEARCH_OPERATOR
/*****************************
演算子の定数定義パッケージ本体
******************************/
IS

	FUNCTION Opr_Eq RETURN VARCHAR2 DETERMINISTIC IS -- 
	BEGIN RETURN '='; END Opr_Eq;
	FUNCTION Opr_Gt RETURN VARCHAR2 DETERMINISTIC IS -- 
	BEGIN RETURN '>'; END Opr_Gt;
	FUNCTION Opr_GE RETURN VARCHAR2 DETERMINISTIC IS -- 
	BEGIN RETURN '>='; END Opr_GE;
	FUNCTION Opr_Ls RETURN VARCHAR2 DETERMINISTIC IS -- 
	BEGIN RETURN '<'; END Opr_Ls;
	FUNCTION Opr_LE RETURN VARCHAR2 DETERMINISTIC IS -- 
	BEGIN RETURN '<='; END Opr_LE;
	FUNCTION Ope_Like RETURN VARCHAR2 DETERMINISTIC IS -- 
	BEGIN RETURN 'LIKE'; END Ope_Like;

	FUNCTION IS_Opr_Eq(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- かどうか
	BEGIN
		IF I_VALUE = Opr_Eq THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Opr_Eq;

	FUNCTION IS_Opr_Gt(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- かどうか
	BEGIN
		IF I_VALUE = Opr_Gt THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Opr_Gt;

	FUNCTION IS_Opr_GE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- かどうか
	BEGIN
		IF I_VALUE = Opr_GE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Opr_GE;

	FUNCTION IS_Opr_Ls(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- かどうか
	BEGIN
		IF I_VALUE = Opr_Ls THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Opr_Ls;

	FUNCTION IS_Opr_LE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- かどうか
	BEGIN
		IF I_VALUE = Opr_LE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Opr_LE;

	FUNCTION IS_Ope_Like(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- かどうか
	BEGIN
		IF I_VALUE = Ope_Like THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Ope_Like;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = Opr_Eq
		OR I_VALUE = Opr_Gt
		OR I_VALUE = Opr_GE
		OR I_VALUE = Opr_Ls
		OR I_VALUE = Opr_LE
		OR I_VALUE = Ope_Like THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_SEARCH_OPERATOR', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_SEARCH_OPERATOR', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_SEARCH_OPERATOR', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_SEARCH_OPERATOR', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_SEARCH_OPERATOR', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_SEARCH_OPERATOR', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_SEARCH_OPERATOR;
