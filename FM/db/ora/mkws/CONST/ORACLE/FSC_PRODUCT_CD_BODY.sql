		OR I_VALUE = SaikenOption
		OR I_VALUE = SaikenOptionRefer
		OR I_VALUE = SaikenOptionShonin
		OR I_VALUE = SaimuOption
		OR I_VALUE = SaimuOptionRefer
		OR I_VALUE = SaimuOptionShonin
		OR I_VALUE = MultiDeviceOption
		OR I_VALUE = NXOption
		OR I_VALUE = FSOption
		OR I_VALUE = PLMOption
		OR I_VALUE = BSOption THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

