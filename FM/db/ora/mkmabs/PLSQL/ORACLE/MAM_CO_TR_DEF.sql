CREATE OR REPLACE TRIGGER MAM_CO_TR_DEF
BEFORE INSERT OR DELETE OR UPDATE
ON MAM_CO_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
BEGIN
	IF INSERTING THEN
		MAPA_CO.P_INIT_SYS_PARM(:NEW.CO_CD) ;

		MAPA_CO.P_INIT_GP_BATCH_GRP(:NEW.CO_CD) ;

		MAPA_NUM.P_INIT_NUM_PTN(:NEW.CO_CD) ;

		MAPA_CO.P_INIT_STK_ANLY_CTL(:NEW.CO_CD) ;

		MAPA_CO.P_INIT_NON_MOV_SCHD_CTL(:NEW.CO_CD) ;

	ELSIF UPDATING THEN
		IF :NEW.CO_CD <> :OLD.CO_CD THEN
			MAPA_CO.P_INIT_SYS_PARM(:NEW.CO_CD) ;

			MAPA_CO.P_INIT_GP_BATCH_GRP(:NEW.CO_CD) ;

			MAPA_NUM.P_INIT_NUM_PTN(:NEW.CO_CD) ;

			MAPA_CO.P_INIT_STK_ANLY_CTL(:NEW.CO_CD) ;

			MAPA_CO.P_INIT_NON_MOV_SCHD_CTL(:NEW.CO_CD) ;
		END IF ;

	ELSIF DELETING THEN
		MAPA_CO.P_DEL_SYS_PARM(:OLD.CO_CD) ;

		MAPA_CO.P_DEL_GP_BATCH_GRP(:OLD.CO_CD) ;

		MAPA_NUM.P_DEL_NUM_PTN(:OLD.CO_CD) ;

		MAPA_CO.P_DEL_STK_ANLY_CTL(:OLD.CO_CD) ;

		MAPA_CO.P_DEL_NON_MOV_SCHD_CTL(:OLD.CO_CD) ;

	END IF ;
END ;
/
