CREATE OR REPLACE VIEW MAM_ALT_GRP(
	ALT_GRP_CD,
	WG_CD,
	ALT_GRP_NM,
	ALT_ITM_TYP,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT 
	ORG.ALT_GRP_CD,
	ORG.WG_CD,
	ORG.ALT_GRP_NM,
	ORG.ALT_ITM_TYP,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM 
	MAM_ALT_GRP_ALL ORG
WHERE 
	0 = 0
AND (MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR ORG.DEL_FLG = '0')
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD <> MAC_STR.NULL_VAL
UNION ALL
SELECT 
	ORG.ALT_GRP_CD,
	WG.WG_CD,
	ORG.ALT_GRP_NM,
	ORG.ALT_ITM_TYP,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM 
	MAM_WG WG,
	MAM_ALT_GRP_ALL ORG
WHERE 
	0 = 0
AND (MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR ORG.DEL_FLG = '0')
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD = MAC_STR.NULL_VAL
	AND (WG.LG_FLG = '1' OR WG.MFG_FLG = '1')
	AND NOT EXISTS (
		SELECT	'X'
		FROM	MAM_ALT_GRP_ALL x
		WHERE	0=0
		AND	x.CO_CD = ORG.CO_CD
		AND	x.ALT_GRP_CD = ORG.ALT_GRP_CD
		AND	x.WG_CD = WG.WG_CD
		AND 	(MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR x.DEL_FLG = '0')
		)
/
