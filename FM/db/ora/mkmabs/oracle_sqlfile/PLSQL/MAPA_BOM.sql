		I_BASE_UNIT_QTY	IN MAPA_META.QTY%TYPE DEFAULT NULL,
		I_ALL_SNO_FLG	IN MAPA_META.FLG%TYPE DEFAULT NULL
	)
	/*********************************************************
	<SYNOPSIS>
		ＢＯＭ正展開結果を一時表（MAW_BOM_EX）に格納する
	<REMARKS>
		I_WG_CDがNULLの場合はWG共通のＢＯＭのみで展開する
	<ARGUMENTS>
	<IN>	I_ITM_CD
			品目ＣＤ
	<IN>	I_ITM_SUB1
			枝番１
	<IN>	I_ITM_SUB2
			枝番２
	<IN>	I_ITM_SUB3
			枝番３
	<IN>	I_BOM_PTN
			構成パタン
	<IN>	I_WG_CD
			ワーキンググループＣＤ
	<IN>	I_BASE_DT
			マスタ適用日
