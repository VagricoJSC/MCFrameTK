			DELETE	MAW_BOM_EX w
			WHERE	0=0
			AND	w.PH_FLG = '1'
			AND	w.BOTTOM_FLG = '1'
			;

			UPDATE	MAW_BOM_EX w
			SET	w.PH_FLG = '0'
			WHERE	0=0
			AND	w.PH_FLG = '1'
			;
		END IF ;

		UPDATE	MAW_BOM_EX w
		SET	w.WG_CD = I_WG_CD
		WHERE	0=0
		AND	w.WG_CD = G_NULL_VAL
		;

		G_BOM.DELETE ;
	END P_INS_BOM_EX_REV ;

END MAPA_BOM ;

