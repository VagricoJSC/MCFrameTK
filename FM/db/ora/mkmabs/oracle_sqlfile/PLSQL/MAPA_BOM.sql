	)
	/*********************************************************
	<SYNOPSIS>
		MAW_BOM_EXのLOOP_FLGを更新する
		MAW_BOM_EXのCHD_RQMT_QTY,CHD_INPT_QTY,FXD_CHD_RQMT_QTY
		がマイナスの場合は０とする
	<REMARKS>
	<ARGUMENTS>
	<IN>	I_LVL
			チェック対象のレベル
	<HISTORY>
	**********************************************************/
	IS
	BEGIN
		FOR x IN (
			SELECT	t.ROWID	row_id
			FROM	MAW_BOM_EX t
			WHERE	0=0
			AND	t.BOM_LVL = I_LVL
			AND	EXISTS (
					SELECT	'X'
					FROM	MAW_BOM_EX w
					WHERE	0=0
					AND	w.BOM_LVL < t.BOM_LVL
					AND	w.ITM_CD = t.ITM_CD
					AND	w.ITM_SUB1 = t.ITM_SUB1
					AND	w.ITM_SUB2 = t.ITM_SUB2
					AND	w.ITM_SUB3 = t.ITM_SUB3
					AND	SUBSTR(w.SORT_NO, 1, (w.BOM_LVL + 1) * G_MAX_ITM) = SUBSTR(t.SORT_NO, 1, (w.BOM_LVL + 1) * G_MAX_ITM)
				)
			)
		LOOP
			UPDATE	MAW_BOM_EX t
			SET	t.LOOP_FLG = '1'
			WHERE	0=0
			AND	t.ROWID = x.row_id
			;
		END LOOP ;

		UPDATE	MAW_BOM_EX t
		SET	t.CHD_RQMT_QTY = 0
		WHERE	0=0
		AND	t.BOM_LVL = I_LVL
		AND	t.CHD_RQMT_QTY < 0
		;

		UPDATE	MAW_BOM_EX t
		SET	t.CHD_INPT_QTY = 0
		WHERE	0=0
		AND	t.BOM_LVL = I_LVL
		AND	t.CHD_INPT_QTY < 0
		;

		UPDATE	MAW_BOM_EX t
		SET	t.FXD_CHD_RQMT_QTY = 0
		WHERE	0=0
		AND	t.BOM_LVL = I_LVL
		AND	t.FXD_CHD_RQMT_QTY < 0
		;
	END P_UPD_LOOP ;

	PROCEDURE P_INS_BOM_EX (
		I_ITM_CD	IN MAPA_META.ITM_CD%TYPE,
		I_ITM_SUB1	IN MAPA_META.ITM_SUB1%TYPE,
		I_ITM_SUB2	IN MAPA_META.ITM_SUB2%TYPE,
		I_ITM_SUB3	IN MAPA_META.ITM_SUB3%TYPE,
		I_BOM_PTN	IN MAPA_META.BOM_PTN%TYPE,
		I_WG_CD		IN MAPA_META.WG_CD%TYPE,
