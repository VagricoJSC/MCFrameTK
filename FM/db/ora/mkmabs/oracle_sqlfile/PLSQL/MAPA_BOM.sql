				G_BOM(i).SORT_NO := RPAD(SUBSTR(I_PH_BOM.SORT_NO, 1, I_PH_BOM.BOM_LVL  * G_MAX_ITM) || LPAD(TO_CHAR(IO_SEQ), G_MAX_ITM, '0'), 
								G_SORT_DIGIT, '0') ;

				IF L_TMP_SEQ <> IO_SEQ - 1 THEN
					G_BOM(i).PH_FLG := '1' ;
				END IF ;

			END LOOP ;

			<<NEXT_X1>>
				NULL ;

		END LOOP ;
	END P_EX_PH_REV ;

