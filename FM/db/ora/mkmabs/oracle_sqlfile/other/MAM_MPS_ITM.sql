CREATE OR REPLACE VIEW MAM_MPS_ITM(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	WG_CD,
	MPS_GRP_CD,
	STRG_LOC_CD,
	MFG_LOC_CD,
	SPPL_CD,
	MAKER_CD,
	RQST_LOC_CD,
	PROD_RATE,
	PROD_BEGIN_DAY,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT 
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.WG_CD,
	ORG.MPS_GRP_CD,
	ORG.STRG_LOC_CD,
	ORG.MFG_LOC_CD,
	ORG.SPPL_CD,
	ORG.MAKER_CD,
	ORG.RQST_LOC_CD,
	ORG.PROD_RATE,
	ORG.PROD_BEGIN_DAY,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM 
	MAM_MPS_ITM_ALL ORG
WHERE 
	0 = 0
AND ORG.DEL_FLG = '0'
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD <> MAC_STR.NULL_VAL
UNION ALL
SELECT 
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	WG.WG_CD,
	ORG.MPS_GRP_CD,
	ORG.STRG_LOC_CD,
	ORG.MFG_LOC_CD,
	ORG.SPPL_CD,
	ORG.MAKER_CD,
	ORG.RQST_LOC_CD,
	ORG.PROD_RATE,
	ORG.PROD_BEGIN_DAY,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM 
	MAM_WG WG,
	MAM_MPS_ITM_ALL ORG
WHERE 
	0 = 0
AND ORG.DEL_FLG = '0'
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
	AND ORG.WG_CD = MAC_STR.NULL_VAL
	AND (WG.LG_FLG = '1' OR WG.MFG_FLG = '1')
	AND EXISTS (
		SELECT	'X'
		FROM	MAM_LOC STRG
		WHERE	0=0
		AND	ORG.STRG_LOC_CD = STRG.LOC_CD
		AND	STRG.WG_CD = WG.WG_CD
		)
	AND (ORG.MFG_LOC_CD = MAC_STR.NULL_VAL 
		OR
		EXISTS (
			SELECT	'X'
			FROM	MAM_LOC MFG
			WHERE	0=0
			AND	ORG.MFG_LOC_CD = MFG.LOC_CD
			AND	MFG.WG_CD = WG.WG_CD
			)
		)
 	AND (ORG.RQST_LOC_CD = MAC_STR.NULL_VAL 
		OR
		EXISTS (
			SELECT	'X'
			FROM	MAM_LOC RQST
			WHERE	0=0
			AND	ORG.RQST_LOC_CD = RQST.LOC_CD
			AND	RQST.WG_CD <> WG.WG_CD
			)
		)
	AND NOT EXISTS (
		SELECT	'X'
		FROM	MAM_MPS_ITM_ALL x
		WHERE	0=0
		AND	x.CO_CD = ORG.CO_CD
		AND	x.ITM_CD = ORG.ITM_CD
		AND	x.ITM_SUB1 = ORG.ITM_SUB1
		AND	x.ITM_SUB2 = ORG.ITM_SUB2
		AND	x.ITM_SUB3 = ORG.ITM_SUB3
		AND	x.WG_CD = WG.WG_CD
		AND 	x.DEL_FLG = '0'
		)

/
show errors;


