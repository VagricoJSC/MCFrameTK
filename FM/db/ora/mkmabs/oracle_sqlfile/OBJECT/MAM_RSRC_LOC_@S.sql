SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_RSRC_LOC_$S(
	MFG_LOC_CD,
	RSRC_CD,
	ST_DT,
	END_DT,
	RSRC_BASE_QTY,
	VAR_PER,
	ALERT_PER,
	DISP_SEQ,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.MFG_LOC_CD,
	ORG.RSRC_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.RSRC_BASE_QTY,
	ORG.VAR_PER,
	ORG.ALERT_PER,
	ORG.DISP_SEQ,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_RSRC_LOC_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_rsrc_loc'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

