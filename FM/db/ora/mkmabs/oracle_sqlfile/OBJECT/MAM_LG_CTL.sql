CREATE OR REPLACE VIEW MAM_LG_CTL(
	FR_LG_GRP_CD,
	TO_LG_GRP_CD,
	SHIP_TERM_CD,
	XFR_LT,
	FIN_CL_TIME,
	ALLOC_DAYS,
	IV_TRD_FLG,
	DEF_TDLV_CD,
	SHIP_WK_GRP_CD,
	NON_DMND_LT_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	EARLY_SHIP_DT_ADD_DAYS
	)
AS
SELECT
	ORG.FR_LG_GRP_CD,
	ORG.TO_LG_GRP_CD,
	ORG.SHIP_TERM_CD,
	ORG.XFR_LT,
	ORG.FIN_CL_TIME,
	ORG.ALLOC_DAYS,
	ORG.IV_TRD_FLG,
	ORG.DEF_TDLV_CD,
	ORG.SHIP_WK_GRP_CD,
	ORG.NON_DMND_LT_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ORG.EARLY_SHIP_DT_ADD_DAYS
FROM
	MAM_LG_CTL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_lg_ctl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

