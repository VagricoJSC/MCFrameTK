SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_LOT_INH_DEST(
	PAR_ITM_CD,
	PAR_ITM_SUB1,
	PAR_ITM_SUB2,
	PAR_ITM_SUB3,
	BOM_PTN,
	LOT_INH_COL_TYP,
	WG_CD,
	LOT_INH_TYP,
	ADD_CONCAT_COL,
	OVERFLOW_ERR_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PAR_ITM_CD,
	ORG.PAR_ITM_SUB1,
	ORG.PAR_ITM_SUB2,
	ORG.PAR_ITM_SUB3,
	ORG.BOM_PTN,
	ORG.LOT_INH_COL_TYP,
	ORG.WG_CD,
	ORG.LOT_INH_TYP,
	ORG.ADD_CONCAT_COL,
	ORG.OVERFLOW_ERR_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_LOT_INH_DEST_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_lot_inh_dest'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

