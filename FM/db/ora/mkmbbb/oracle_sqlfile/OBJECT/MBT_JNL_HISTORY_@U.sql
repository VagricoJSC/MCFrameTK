SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MBT_JNL_HISTORY_$U(
	JNL_GRP_NO,
	AC_YM,
	ST_DT,
	END_DT,
	AC_SLIP_DT,
	JNL_ACT_CD,
	DATA_TYP,
	RERUN_FLG,
	JNL_RMRKS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.JNL_GRP_NO,
	ORG.AC_YM,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.AC_SLIP_DT,
	ORG.JNL_ACT_CD,
	ORG.DATA_TYP,
	ORG.RERUN_FLG,
	ORG.JNL_RMRKS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MBT_JNL_HISTORY_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

