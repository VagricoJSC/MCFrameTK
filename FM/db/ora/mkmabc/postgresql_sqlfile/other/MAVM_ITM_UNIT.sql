	mavm_itm_unit_mam_itm_unit_$u_m2.itm_cd,
	mavm_itm_unit_mam_itm_unit_$u_m2.itm_sub1,
	mavm_itm_unit_mam_itm_unit_$u_m2.itm_sub2,
