SELECT
	T1.RSRC_CD,
	T1.RSRC_NM,
	T1.RSRC_UNIT_NM,
	T1.DEC_PLACE,
	T1.RND_TYP,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--資源名（ロケール１）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_ALL T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	RSRC_NM_LCL1,
	--資源名（ロケール２）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_ALL T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	RSRC_NM_LCL2,
	--資源名（ロケール３）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_ALL T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	RSRC_NM_LCL3,
	--資源名（ロケール４）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_ALL T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	RSRC_NM_LCL4,
	--資源名（ロケール５）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_ALL T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	RSRC_NM_LCL5
	FROM MAM_RSRC_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_RSRC
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_RSRC
			)
		)
	)
UNION ALL
SELECT
	T1.RSRC_CD,
	T1.RSRC_NM,
	T1.RSRC_UNIT_NM,
	T1.DEC_PLACE,
	T1.RND_TYP,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	MAC_STR.NULL_VAL CO_CD,
	--資源名（ロケール１）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_CMN T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.LCL_CD = 'ja_JP'
	)	RSRC_NM_LCL1,
	--資源名（ロケール２）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_CMN T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.LCL_CD = 'en_US'
	)	RSRC_NM_LCL2,
	--資源名（ロケール３）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_CMN T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.LCL_CD = 'TBD3'
	)	RSRC_NM_LCL3,
	--資源名（ロケール４）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_CMN T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.LCL_CD = 'TBD4'
	)	RSRC_NM_LCL4,
	--資源名（ロケール５）
	(SELECT T.RSRC_NM
		FROM MAM_RSRC_LCL_CMN T
		WHERE 0 = 0
		AND T.RSRC_CD = T1.RSRC_CD
		AND T.LCL_CD = 'TBD5'
	)	RSRC_NM_LCL5
	FROM MAM_RSRC_CMN T1
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_RSRC
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
/
