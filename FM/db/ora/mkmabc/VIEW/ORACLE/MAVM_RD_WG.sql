SELECT	m.*
FROM	MAT_DA_WG t , MAM_WG m
WHERE	0 = 0
AND	t.WG_CD = m.WG_CD
AND	t.RD_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.*
FROM	MAM_WG m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	w.FULL_DA_FLG = '1'
/
