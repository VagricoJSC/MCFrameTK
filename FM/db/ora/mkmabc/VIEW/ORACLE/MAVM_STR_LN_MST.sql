SELECT
	T1.LOC_CD,
	T1.STR_LN_CD,
	T1.STR_LN_NM,
	T1.LN_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--棚・ライン名（ロケール１）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	STR_LN_NM_LCL1,
	--棚・ライン名（ロケール２）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	STR_LN_NM_LCL2,
	--棚・ライン名（ロケール３）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	STR_LN_NM_LCL3,
	--棚・ライン名（ロケール４）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	STR_LN_NM_LCL4,
	--棚・ライン名（ロケール５）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	STR_LN_NM_LCL5
	FROM MAM_STR_LN_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_STR_LN
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_STR_LN
			)
		)
	)
UNION ALL
SELECT
	T1.LOC_CD,
	T1.STR_LN_CD,
	T1.STR_LN_NM,
	T1.LN_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--棚・ライン名（ロケール１）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.LCL_CD = 'ja_JP'
	)	STR_LN_NM_LCL1,
	--棚・ライン名（ロケール２）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.LCL_CD = 'en_US'
	)	STR_LN_NM_LCL2,
	--棚・ライン名（ロケール３）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.LCL_CD = 'TBD3'
	)	STR_LN_NM_LCL3,
	--棚・ライン名（ロケール４）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.LCL_CD = 'TBD4'
	)	STR_LN_NM_LCL4,
	--棚・ライン名（ロケール５）
	(SELECT T.STR_LN_NM
		FROM MAM_STR_LN_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.STR_LN_CD = T1.STR_LN_CD
		AND T.LCL_CD = 'TBD5'
	)	STR_LN_NM_LCL5
	FROM MAM_STR_LN_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_STR_LN
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
