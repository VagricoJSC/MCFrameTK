SELECT	m.*
FROM	MAT_DA_ALLOC_GRP t , MAM_ALLOC_GRP m
WHERE	0 = 0
AND	t.ALLOC_GRP_CD = m.ALLOC_GRP_CD
AND	t.WR_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.*
FROM	MAM_ALLOC_GRP m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	w.FULL_DA_FLG = '1'
/
