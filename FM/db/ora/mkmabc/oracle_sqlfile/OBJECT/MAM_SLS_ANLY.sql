SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_SLS_ANLY(
	SLS_ANLY_TYP,
	SLS_ANLY_CD,
	SLS_ANLY_NM,
	BASE_SLS_ANLY_NM,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLS_ANLY_TYP,
	ORG.SLS_ANLY_CD,
	LCL.SLS_ANLY_NM,
	ORG.SLS_ANLY_NM AS BASE_SLS_ANLY_NM,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SLS_ANLY_ALL ORG,
	mam_sls_anly_lcl_all LCL
WHERE
	0 = 0
	AND ORG.SLS_ANLY_TYP = LCL.SLS_ANLY_TYP(+)
	AND ORG.SLS_ANLY_CD = LCL.SLS_ANLY_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_sls_anly'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

