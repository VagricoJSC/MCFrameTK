	EXT_SYS_CD,
	EXT_SYS_NM,
	EXT_SYS_TYP,
	WEB_API_FLG,
	CMD_EXEC_FLG,
	REAL_IMP_FLG,
	NOT_SEND_UPD_FLG,
	NOT_DUP_IMP_FLG,
	IF_UPD_TYP,
	DLV_SLIP_SPLIT_FLG,
	NULL_VAL_IF_FLG,
	UPRI_NOT_CHK_FLG,
	AMT_NOT_CHK_FLG,
	TAX_NOT_CHK_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.EXT_SYS_CD,
	ORG.EXT_SYS_NM,
	ORG.EXT_SYS_TYP,
	ORG.WEB_API_FLG,
	ORG.CMD_EXEC_FLG,
	ORG.REAL_IMP_FLG,
	ORG.NOT_SEND_UPD_FLG,
	ORG.NOT_DUP_IMP_FLG,
	ORG.IF_UPD_TYP,
	ORG.DLV_SLIP_SPLIT_FLG,
	ORG.NULL_VAL_IF_FLG,
