CREATE OR REPLACE VIEW MAM_SCHD_PAY_$S(
	PAY_AP_TYP,
	SEQ,
	PRIO,
	CUR_CD,
	FOREIGN_TYP,
	ASPPL_CD,
	DPT_ID_FLG,
	SLIP_CNT_ID,
	AC_CD,
	SUB_AC_CD,
	ABS_TYP,
	ABSTRACT1,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PAY_AP_TYP,
	ORG.SEQ,
	ORG.PRIO,
	ORG.CUR_CD,
	ORG.FOREIGN_TYP,
	ORG.ASPPL_CD,
	ORG.DPT_ID_FLG,
	ORG.SLIP_CNT_ID,
	ORG.AC_CD,
	ORG.SUB_AC_CD,
	ORG.ABS_TYP,
	ORG.ABSTRACT1,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SCHD_PAY_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_schd_pay'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

