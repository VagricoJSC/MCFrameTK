SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_ATTACH_INFO_$S(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	WG_CD,
	ATTACH_INFO_KEY1,
	ATTACH_INFO_KEY2,
	ATTACH_INFO_KEY3,
	ATTACH_INFO_KEY4,
	ATTACH_INFO_KEY5,
	ATTACH_INFO_ID,
	ATTACH_INFO_TYP,
	ATTACH_INFO_RMRKS,
	ATTACH_INFO_PATH,
	ATTACH_INFO_BIN,
	ATTACH_INFO_BIN_NM,
	EXT_SYS_NO_ATTACH,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.WG_CD,
	ORG.ATTACH_INFO_KEY1,
	ORG.ATTACH_INFO_KEY2,
	ORG.ATTACH_INFO_KEY3,
	ORG.ATTACH_INFO_KEY4,
	ORG.ATTACH_INFO_KEY5,
	ORG.ATTACH_INFO_ID,
	ORG.ATTACH_INFO_TYP,
	ORG.ATTACH_INFO_RMRKS,
	ORG.ATTACH_INFO_PATH,
	ORG.ATTACH_INFO_BIN,
	ORG.ATTACH_INFO_BIN_NM,
	ORG.EXT_SYS_NO_ATTACH,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ATTACH_INFO_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_attach_info'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

