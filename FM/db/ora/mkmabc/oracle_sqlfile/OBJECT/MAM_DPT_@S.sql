CREATE OR REPLACE VIEW MAM_DPT_$S(
	DPT_CD,
	ST_DT,
	END_DT,
	BASE_END_DT,
	DPT_NM,
	BASE_DPT_NM,
	DPT_LVL_CD,
	UP_LV_DPT_CD,
	AC_DPT_CD,
	COST_DPT_CD,
	NEW_DPT_CD,
	ZIP_CD,
	BASE_ZIP_CD,
	ADDR1,
	BASE_ADDR1,
	ADDR2,
	BASE_ADDR2,
	ADDR3,
	BASE_ADDR3,
	ADDR4,
	BASE_ADDR4,
	TEL,
	BASE_TEL,
	FAX,
	BASE_FAX,
	WG_CD,
	RCV_BANK_AC_CD,
	PAY_BANK_AC_CD,
	CAL_CD,
	ASST_DPT_FLG,
	AR_DPT_FLG,
	AP_DPT_FLG,
	SLS_DPT_FLG,
	PURC_DPT_FLG,
	SHIP_DPT_FLG,
	ARR_DPT_FLG,
	MFG_DPT_FLG,
	SD_DPT_FLG,
	INSP_DPT_FLG,
	BD_DPT_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.DPT_CD,
	ORG.ST_DT,
	LCL.END_DT,
	ORG.END_DT AS BASE_END_DT,
	LCL.DPT_NM,
	ORG.DPT_NM AS BASE_DPT_NM,
	ORG.DPT_LVL_CD,
	ORG.UP_LV_DPT_CD,
	ORG.AC_DPT_CD,
	ORG.COST_DPT_CD,
	ORG.NEW_DPT_CD,
	LCL.ZIP_CD,
	ORG.ZIP_CD AS BASE_ZIP_CD,
	LCL.ADDR1,
	ORG.ADDR1 AS BASE_ADDR1,
	LCL.ADDR2,
	ORG.ADDR2 AS BASE_ADDR2,
	LCL.ADDR3,
	ORG.ADDR3 AS BASE_ADDR3,
	LCL.ADDR4,
	ORG.ADDR4 AS BASE_ADDR4,
	LCL.TEL,
	ORG.TEL AS BASE_TEL,
	LCL.FAX,
	ORG.FAX AS BASE_FAX,
	ORG.WG_CD,
	ORG.RCV_BANK_AC_CD,
	ORG.PAY_BANK_AC_CD,
	ORG.CAL_CD,
	ORG.ASST_DPT_FLG,
	ORG.AR_DPT_FLG,
	ORG.AP_DPT_FLG,
	ORG.SLS_DPT_FLG,
	ORG.PURC_DPT_FLG,
	ORG.SHIP_DPT_FLG,
	ORG.ARR_DPT_FLG,
	ORG.MFG_DPT_FLG,
	ORG.SD_DPT_FLG,
	ORG.INSP_DPT_FLG,
	ORG.BD_DPT_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_DPT_ALL ORG,
	mam_dpt_lcl_all LCL
WHERE
	0 = 0
	AND ORG.DPT_CD = LCL.DPT_CD(+)
	AND ORG.ST_DT = LCL.ST_DT(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_dpt'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

