SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_COST_DPT_$S(
	DPT_CD,
	TERM,
	DPT_NM,
	BASE_DPT_NM,
	DPT_LVL_CD,
	DPT_ALC_GRP,
	DPT_CONFIG_TYP,
	LG_GRP_CD,
	LOC_GRP_CD,
	WG_CD,
	SITE_CD,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.DPT_CD,
	ORG.TERM,
	LCL.DPT_NM,
	ORG.DPT_NM AS BASE_DPT_NM,
	ORG.DPT_LVL_CD,
	ORG.DPT_ALC_GRP,
	ORG.DPT_CONFIG_TYP,
	ORG.LG_GRP_CD,
	ORG.LOC_GRP_CD,
	ORG.WG_CD,
	ORG.SITE_CD,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_COST_DPT_ALL ORG,
	mam_cost_dpt_lcl_all LCL
WHERE
	0 = 0
	AND ORG.DPT_CD = LCL.DPT_CD(+)
	AND ORG.TERM = LCL.TERM(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_cost_dpt'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

