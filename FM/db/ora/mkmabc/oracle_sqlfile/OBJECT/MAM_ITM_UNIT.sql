SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_ITM_UNIT(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	UNIT_CD,
	CONV_BASE_QTY,
	CONV_QTY,
	DEC_PLACE,
	RND_TYP,
	PACK_FLG,
	PCKG_FLG,
	UNIT_DIM,
	UNIT_WT,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.UNIT_CD,
	ORG.CONV_BASE_QTY,
	ORG.CONV_QTY,
	ORG.DEC_PLACE,
	ORG.RND_TYP,
	ORG.PACK_FLG,
	ORG.PCKG_FLG,
	ORG.UNIT_DIM,
	ORG.UNIT_WT,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ITM_UNIT_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_itm_unit'))
	AND (1=MAPA_CONTEXT.F_ITM_UNIT) --MAVM_ITM_UNITを使用する
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

