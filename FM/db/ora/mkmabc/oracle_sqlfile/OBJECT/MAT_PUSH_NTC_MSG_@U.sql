CREATE OR REPLACE VIEW MAT_PUSH_NTC_MSG_$U(
	PUSH_NTC_NO,
	BIND_SEQ,
	BIND_VAL,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PUSH_NTC_NO,
	ORG.BIND_SEQ,
	ORG.BIND_VAL,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAT_PUSH_NTC_MSG_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

