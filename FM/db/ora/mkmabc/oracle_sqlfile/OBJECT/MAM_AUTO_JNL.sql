SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_AUTO_JNL(
	AC_SLIP_TYP,
	AUTO_JNL_KEY_CD,
	AUTO_JNL_GRP,
	JNL_PTN_CD,
	PRIO,
	AC_IF_TYP,
	ID_TYP,
	SLIP_CNT_ID,
	STD_RND_TYP,
	CLS_JNL_TYP,
	COMPOUND_JNL_TYP,
	ALLOC_JNL_FLG,
	MINUS_FLG,
	REV_FLG,
	MINUS_REV_FLG,
	DEFAULT_FLG,
	ABS_TYP,
	ABSTRACT1,
	ST_DT,
	END_DT,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.AC_SLIP_TYP,
	ORG.AUTO_JNL_KEY_CD,
	ORG.AUTO_JNL_GRP,
	ORG.JNL_PTN_CD,
	ORG.PRIO,
	ORG.AC_IF_TYP,
	ORG.ID_TYP,
	ORG.SLIP_CNT_ID,
	ORG.STD_RND_TYP,
	ORG.CLS_JNL_TYP,
	ORG.COMPOUND_JNL_TYP,
	ORG.ALLOC_JNL_FLG,
	ORG.MINUS_FLG,
	ORG.REV_FLG,
	ORG.MINUS_REV_FLG,
	ORG.DEFAULT_FLG,
	ORG.ABS_TYP,
	ORG.ABSTRACT1,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_AUTO_JNL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_auto_jnl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

