CREATE OR REPLACE VIEW MAM_TRD_$U(
	TRD_CD,
	TRD_NM,
	TRD_PTN_TYP,
	AC_RSN_CD,
	SLIP_EACH_LOT_TYP,
	SLIP_FORM_CD,
	AUTO_ADOPT_FLG,
	NOT_SLS_SLIP_SND_FLG,
	NOT_PURC_SLIP_SND_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.TRD_CD,
	ORG.TRD_NM,
	ORG.TRD_PTN_TYP,
	ORG.AC_RSN_CD,
	ORG.SLIP_EACH_LOT_TYP,
	ORG.SLIP_FORM_CD,
	ORG.AUTO_ADOPT_FLG,
	ORG.NOT_SLS_SLIP_SND_FLG,
	ORG.NOT_PURC_SLIP_SND_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_TRD_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

