CREATE OR REPLACE VIEW MAM_WG(
	WG_CD,
	WG_NM,
	BASE_WG_NM,
	SLS_FLG,
	LG_FLG,
	MFG_FLG,
	PURC_FLG,
	AR_FLG,
	AP_FLG,
	SD_FLG,
	MRP_PREFIX,
	MFG_INST_UNIT_TYP,
	MRP_PROC_TYP,
	ALLOC_MARGIN_DAYS,
	NOT_XFR_FLG,
	MRP_ALLOC_MARGIN_DAYS,
	MRP_OPN_XFR_DAYS,
	RQMT_TYP,
	PROD_PLN_TYP,
	DMND_DATE_DIV_MONS,
	PLM_FLG,
	CALC_SEQ,
	CMN_UPRI_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WG_CD,
	LCL.WG_NM,
	ORG.WG_NM AS BASE_WG_NM,
	ORG.SLS_FLG,
	ORG.LG_FLG,
	ORG.MFG_FLG,
	ORG.PURC_FLG,
	ORG.AR_FLG,
	ORG.AP_FLG,
	ORG.SD_FLG,
	ORG.MRP_PREFIX,
	ORG.MFG_INST_UNIT_TYP,
	ORG.MRP_PROC_TYP,
	ORG.ALLOC_MARGIN_DAYS,
	ORG.NOT_XFR_FLG,
	ORG.MRP_ALLOC_MARGIN_DAYS,
	ORG.MRP_OPN_XFR_DAYS,
	ORG.RQMT_TYP,
	ORG.PROD_PLN_TYP,
	ORG.DMND_DATE_DIV_MONS,
	ORG.PLM_FLG,
	ORG.CALC_SEQ,
	ORG.CMN_UPRI_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_WG_ALL ORG,
	mam_wg_lcl_all LCL
WHERE
	0 = 0
	AND ORG.WG_CD = LCL.WG_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_wg'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

