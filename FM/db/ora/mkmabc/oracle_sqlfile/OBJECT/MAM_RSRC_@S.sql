SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_RSRC_$S(
	RSRC_CD,
	RSRC_NM,
	BASE_RSRC_NM,
	RSRC_UNIT_NM,
	BASE_RSRC_UNIT_NM,
	DEC_PLACE,
	RND_TYP,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.RSRC_CD,
	LCL.RSRC_NM,
	ORG.RSRC_NM AS BASE_RSRC_NM,
	LCL.RSRC_UNIT_NM,
	ORG.RSRC_UNIT_NM AS BASE_RSRC_UNIT_NM,
	ORG.DEC_PLACE,
	ORG.RND_TYP,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_RSRC_ALL ORG,
	mam_rsrc_lcl_all LCL
WHERE
	0 = 0
	AND ORG.RSRC_CD = LCL.RSRC_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_rsrc'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

