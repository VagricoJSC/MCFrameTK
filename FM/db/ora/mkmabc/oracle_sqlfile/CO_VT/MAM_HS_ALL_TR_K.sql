SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_HS_ALL_TR_K
BEFORE INSERT ON MAM_HS_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
 T$KEY2 VARCHAR2(50 char);
BEGIN
 T$KEY2 := FCPA_CONTEXT.F_GET_CO_CD;
 IF T$KEY2 IS NOT NULL AND :NEW.CO_CD IS NULL THEN
  :NEW.CO_CD := T$KEY2 ;
 END IF ;
END;

/
show errors;


