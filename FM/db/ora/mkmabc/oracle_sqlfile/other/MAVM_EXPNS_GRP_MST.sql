SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_EXPNS_GRP_MST(
	EXPNS_GRP_CD,
	EXPNS_GRP_NM,
	EXPNS_GRP_SEQ,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	EXPNS_GRP_NM_LCL1,
	EXPNS_GRP_NM_LCL2,
	EXPNS_GRP_NM_LCL3,
	EXPNS_GRP_NM_LCL4,
	EXPNS_GRP_NM_LCL5
)
AS
SELECT
	T1.EXPNS_GRP_CD,
	T1.EXPNS_GRP_NM,
	T1.EXPNS_GRP_SEQ,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--費目グループ名（ロケール１）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	EXPNS_GRP_NM_LCL1,
	--費目グループ名（ロケール２）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	EXPNS_GRP_NM_LCL2,
	--費目グループ名（ロケール３）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	EXPNS_GRP_NM_LCL3,
	--費目グループ名（ロケール４）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	EXPNS_GRP_NM_LCL4,
	--費目グループ名（ロケール５）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	EXPNS_GRP_NM_LCL5
	FROM MAM_EXPNS_GRP_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_EXPNS_GRP
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_EXPNS_GRP
			)
		)
	)
UNION ALL
SELECT
	T1.EXPNS_GRP_CD,
	T1.EXPNS_GRP_NM,
	T1.EXPNS_GRP_SEQ,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	MAC_STR.NULL_VAL CO_CD,
	--費目グループ名（ロケール１）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.LCL_CD = 'ja_JP'
	)	EXPNS_GRP_NM_LCL1,
	--費目グループ名（ロケール２）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.LCL_CD = 'en_US'
	)	EXPNS_GRP_NM_LCL2,
	--費目グループ名（ロケール３）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.LCL_CD = 'TBD3'
	)	EXPNS_GRP_NM_LCL3,
	--費目グループ名（ロケール４）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.LCL_CD = 'TBD4'
	)	EXPNS_GRP_NM_LCL4,
	--費目グループ名（ロケール５）
	(SELECT T.EXPNS_GRP_NM
		FROM MAM_EXPNS_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.EXPNS_GRP_CD = T1.EXPNS_GRP_CD
		AND T.LCL_CD = 'TBD5'
	)	EXPNS_GRP_NM_LCL5
	FROM MAM_EXPNS_GRP_CMN T1
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_EXPNS_GRP
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

