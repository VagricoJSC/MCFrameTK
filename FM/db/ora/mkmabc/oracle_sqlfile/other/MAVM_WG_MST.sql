SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_WG_MST(
	WG_CD,
	WG_NM,
	SLS_FLG,
	LG_FLG,
	MFG_FLG,
	PURC_FLG,
	AR_FLG,
	AP_FLG,
	SD_FLG,
	MRP_PREFIX,
	MFG_INST_UNIT_TYP,
	MRP_PROC_TYP,
	ALLOC_MARGIN_DAYS,
	NOT_XFR_FLG,
	MRP_ALLOC_MARGIN_DAYS,
	MRP_OPN_XFR_DAYS,
	RQMT_TYP,
	PROD_PLN_TYP,
	DMND_DATE_DIV_MONS,
	PLM_FLG,
	CALC_SEQ,
	CMN_UPRI_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	WG_NM_LCL1,
	WG_NM_LCL2,
	WG_NM_LCL3,
	WG_NM_LCL4,
	WG_NM_LCL5
)
AS
SELECT
	T1.WG_CD,
	T1.WG_NM,
	T1.SLS_FLG,
	T1.LG_FLG,
	T1.MFG_FLG,
	T1.PURC_FLG,
	T1.AR_FLG,
	T1.AP_FLG,
	T1.SD_FLG,
	T1.MRP_PREFIX,
	T1.MFG_INST_UNIT_TYP,
	T1.MRP_PROC_TYP,
	T1.ALLOC_MARGIN_DAYS,
	T1.NOT_XFR_FLG,
	T1.MRP_ALLOC_MARGIN_DAYS,
	T1.MRP_OPN_XFR_DAYS,
	T1.RQMT_TYP,
	T1.PROD_PLN_TYP,
	T1.DMND_DATE_DIV_MONS,
	T1.PLM_FLG,
	T1.CALC_SEQ,
	T1.CMN_UPRI_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--ワーキンググループ名（ロケール１）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_ALL T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	WG_NM_LCL1,
	--ワーキンググループ名（ロケール２）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_ALL T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	WG_NM_LCL2,
	--ワーキンググループ名（ロケール３）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_ALL T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	WG_NM_LCL3,
	--ワーキンググループ名（ロケール４）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_ALL T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	WG_NM_LCL4,
	--ワーキンググループ名（ロケール５）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_ALL T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	WG_NM_LCL5
	FROM MAM_WG_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_WG
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_WG
			)
		)
	)
UNION ALL
SELECT
	T1.WG_CD,
	T1.WG_NM,
	T1.SLS_FLG,
	T1.LG_FLG,
	T1.MFG_FLG,
	T1.PURC_FLG,
	T1.AR_FLG,
	T1.AP_FLG,
	T1.SD_FLG,
	T1.MRP_PREFIX,
	T1.MFG_INST_UNIT_TYP,
	T1.MRP_PROC_TYP,
	T1.ALLOC_MARGIN_DAYS,
	T1.NOT_XFR_FLG,
	T1.MRP_ALLOC_MARGIN_DAYS,
	T1.MRP_OPN_XFR_DAYS,
	T1.RQMT_TYP,
	T1.PROD_PLN_TYP,
	T1.DMND_DATE_DIV_MONS,
	T1.PLM_FLG,
	T1.CALC_SEQ,
	T1.CMN_UPRI_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--ワーキンググループ名（ロケール１）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_CMN T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.LCL_CD = 'ja_JP'
	)	WG_NM_LCL1,
	--ワーキンググループ名（ロケール２）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_CMN T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.LCL_CD = 'en_US'
	)	WG_NM_LCL2,
	--ワーキンググループ名（ロケール３）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_CMN T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.LCL_CD = 'TBD3'
	)	WG_NM_LCL3,
	--ワーキンググループ名（ロケール４）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_CMN T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.LCL_CD = 'TBD4'
	)	WG_NM_LCL4,
	--ワーキンググループ名（ロケール５）
	(SELECT T.WG_NM
		FROM MAM_WG_LCL_CMN T
		WHERE 0 = 0
		AND T.WG_CD = T1.WG_CD
		AND T.LCL_CD = 'TBD5'
	)	WG_NM_LCL5
	FROM MAM_WG_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_WG
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

