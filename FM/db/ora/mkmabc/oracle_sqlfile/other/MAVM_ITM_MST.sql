	(SELECT ITM_NM 
		FROM MAM_ITM_LCL_CMN T
		WHERE 0=0
		AND	T.ITM_CD = T1.ITM_CD
		AND T.ITM_SUB1 = T1.ITM_SUB1
		AND T.ITM_SUB2 = T1.ITM_SUB2
		AND T.ITM_SUB3 = T1.ITM_SUB3
		AND T.LCL_CD = 'en_US'
	)	ITM_NM_LCL2,
	--品目名（ロケール３） 
	(SELECT ITM_NM 
		FROM MAM_ITM_LCL_CMN T
		WHERE 0=0
		AND	T.ITM_CD = T1.ITM_CD
		AND T.ITM_SUB1 = T1.ITM_SUB1
		AND T.ITM_SUB2 = T1.ITM_SUB2
		AND T.ITM_SUB3 = T1.ITM_SUB3
		AND T.LCL_CD = 'TBD3'
	)	ITM_NM_LCL3,	
	--品目名（ロケール４） 
	(SELECT ITM_NM 
		FROM MAM_ITM_LCL_CMN T
		WHERE 0=0
		AND	T.ITM_CD = T1.ITM_CD
		AND T.ITM_SUB1 = T1.ITM_SUB1
		AND T.ITM_SUB2 = T1.ITM_SUB2
		AND T.ITM_SUB3 = T1.ITM_SUB3
		AND T.LCL_CD = 'TBD4'
	)	ITM_NM_LCL4,	
	--品目名（ロケール５） 
	(SELECT ITM_NM 
		FROM MAM_ITM_LCL_CMN T
		WHERE 0=0
		AND	T.ITM_CD = T1.ITM_CD
		AND T.ITM_SUB1 = T1.ITM_SUB1
		AND T.ITM_SUB2 = T1.ITM_SUB2
		AND T.ITM_SUB3 = T1.ITM_SUB3
		AND T.LCL_CD = 'TBD5'
	)	ITM_NM_LCL5
	FROM MAM_ITM_COM T1
	LEFT OUTER JOIN MAM_ITM_CMN T2 ON (
			T1.ITM_CD = T2.ITM_CD
		AND	T1.ITM_SUB1 = T2.ITM_SUB1
		AND T1.ITM_SUB2 = T2.ITM_SUB2
		AND T1.ITM_SUB3 = T2.ITM_SUB3
	)
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_ITM
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
