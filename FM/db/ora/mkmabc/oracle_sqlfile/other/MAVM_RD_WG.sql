CREATE OR REPLACE VIEW MAVM_RD_WG(
	WG_CD,
	WG_NM,
	BASE_WG_NM,
	SLS_FLG,
	LG_FLG,
	MFG_FLG,
	PURC_FLG,
	AR_FLG,
	AP_FLG,
	SD_FLG,
	MRP_PREFIX,
	MFG_INST_UNIT_TYP,
	MRP_PROC_TYP,
	ALLOC_MARGIN_DAYS,
	NOT_XFR_FLG,
	MRP_ALLOC_MARGIN_DAYS,
	MRP_OPN_XFR_DAYS,
	RQMT_TYP,
	PROD_PLN_TYP,
	DMND_DATE_DIV_MONS,
	PLM_FLG,
	CALC_SEQ,
	CMN_UPRI_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT	m.*
FROM	MAT_DA_WG t , MAM_WG m
WHERE	0 = 0
AND	t.WG_CD = m.WG_CD
AND	t.RD_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.*
FROM	MAM_WG m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	w.FULL_DA_FLG = '1'
;

