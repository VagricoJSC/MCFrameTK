CREATE OR REPLACE VIEW MAVM_DPT_CONFIG_IF_ALL(
	CO_CD,
	DPT_CD,
	TERM,
	LV01_DPT_CD,
	LV02_DPT_CD,
	LV03_DPT_CD,
	LV04_DPT_CD,
	LV05_DPT_CD,
	LV06_DPT_CD,
	LV07_DPT_CD,
	LV08_DPT_CD,
	LV09_DPT_CD,
	LV10_DPT_CD,
	MEMO1,
	MEMO2,
	MEMO3
)
AS
WITH T1 AS (
	SELECT M1.CO_CD, M1.TERM, M1.PAR_DPT_CD, M1.DPT_CD, M1.MEMO1, M1.MEMO2, M1.MEMO3
	FROM MAM_DPT_CONFIG_ALL M1
	WHERE 0=0
	AND M1.DEL_FLG = '0'
	AND M1.DPT_CD IS NOT NULL
	AND (
		EXISTS (
			SELECT 'X'
			FROM MAM_MST_CTL x
			WHERE 0=0
			AND x.MST_NM = MAC_MST_NM.MAM_DPT_CONFIG
			AND x.MST_SET_TYP = MAC_MST_SET_TYP.COM
		)
		OR
		NOT EXISTS (
			SELECT 'X'
			FROM MAM_MST_CTL x
			WHERE 0=0
			AND x.MST_NM = MAC_MST_NM.MAM_DPT_CONFIG
		)
	)
-- 1番上の階層のレコード
UNION ALL
	SELECT DISTINCT M2.CO_CD, M2.TERM, NULL AS PAR_DPT_CD, M2.PAR_DPT_CD AS DPT_CD, M2.MEMO1, M2.MEMO2, M2.MEMO3
	FROM MAM_DPT_CONFIG_ALL M2
	WHERE 0=0
	AND M2.DEL_FLG = '0'
	AND NOT EXISTS (
		SELECT *
		FROM MAM_DPT_CONFIG_ALL M3
		WHERE 0=0
		AND M2.PAR_DPT_CD = M3.DPT_CD
		AND M2.TERM = M3.TERM
		AND M2.CO_CD = M3.CO_CD 
		AND M3.DEL_FLG = '0'
	)
	AND M2.DPT_CD IS NOT NULL
	AND (
		EXISTS (
			SELECT 'X'
			FROM MAM_MST_CTL x
			WHERE 0=0
			AND x.MST_NM = MAC_MST_NM.MAM_DPT_CONFIG
			AND x.MST_SET_TYP = MAC_MST_SET_TYP.COM
		)
		OR
		NOT EXISTS (
			SELECT 'X'
			FROM MAM_MST_CTL x
			WHERE 0=0
			AND x.MST_NM = MAC_MST_NM.MAM_DPT_CONFIG
		)
	)

-- CMN結合
UNION ALL
	SELECT M5.CO_CD, M4.TERM, M4.PAR_DPT_CD, M4.DPT_CD, M4.MEMO1, M4.MEMO2, M4.MEMO3
	FROM MAM_DPT_CONFIG_CMN M4, MAM_CO_ALL M5
	WHERE 0=0
	AND M4.DEL_FLG = '0'
	AND M4.DPT_CD IS NOT NULL
	AND (
		EXISTS (
			SELECT 'X'
			FROM MAM_MST_CTL x
			WHERE 0=0
			AND x.MST_NM = MAC_MST_NM.MAM_DPT_CONFIG
			AND x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
		)
	)
-- 1番上の階層のレコード
UNION ALL
	SELECT DISTINCT M7.CO_CD, M6.TERM, NULL AS PAR_DPT_CD, M6.PAR_DPT_CD AS DPT_CD, M6.MEMO1, M6.MEMO2, M6.MEMO3
	FROM MAM_DPT_CONFIG_CMN M6, MAM_CO_ALL M7
	WHERE 0=0
	AND M6.DEL_FLG = '0'
	AND NOT EXISTS (
		SELECT *
		FROM MAM_DPT_CONFIG_CMN M8
		WHERE 0=0
		AND M6.PAR_DPT_CD = M8.DPT_CD
		AND M6.TERM = M8.TERM
		AND M8.DEL_FLG = '0'
	)
	AND M6.DPT_CD IS NOT NULL
	AND (
		EXISTS (
			SELECT 'X'
			FROM MAM_MST_CTL x
			WHERE 0=0
			AND x.MST_NM = MAC_MST_NM.MAM_DPT_CONFIG
			AND x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
		)
	)
)
SELECT CO_CD, DPT_CD, TERM, 
	CASE WHEN INSTR(PATH, ',', 1, 1) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 2) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 1) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 1) + 1, INSTR(PATH, ',', 1, 2) - INSTR(PATH, ',', 1, 1) - 1) END Lv01_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 2) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 3) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 2) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 2) + 1, INSTR(PATH, ',', 1, 3) - INSTR(PATH, ',', 1, 2) - 1) END Lv02_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 3) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 4) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 3) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 3) + 1, INSTR(PATH, ',', 1, 4) - INSTR(PATH, ',', 1, 3) - 1) END Lv03_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 4) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 5) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 4) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 4) + 1, INSTR(PATH, ',', 1, 5) - INSTR(PATH, ',', 1, 4) - 1) END Lv04_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 5) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 6) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 5) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 5) + 1, INSTR(PATH, ',', 1, 6) - INSTR(PATH, ',', 1, 5) - 1) END Lv05_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 6) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 7) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 6) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 6) + 1, INSTR(PATH, ',', 1, 7) - INSTR(PATH, ',', 1, 6) - 1) END Lv06_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 7) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 8) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 7) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 7) + 1, INSTR(PATH, ',', 1, 8) - INSTR(PATH, ',', 1, 7) - 1) END Lv07_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 8) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 9) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 8) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 8) + 1, INSTR(PATH, ',', 1, 9) - INSTR(PATH, ',', 1, 8) - 1) END Lv08_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 9) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 10) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 9) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 9) + 1, INSTR(PATH, ',', 1, 10) - INSTR(PATH, ',', 1, 9) - 1) END Lv09_DPT_CD,
	CASE WHEN INSTR(PATH, ',', 1, 10) = 0 THEN NULL
		WHEN INSTR(PATH, ',', 1, 11) = 0 THEN SUBSTR(PATH, INSTR(PATH, ',', 1, 10) + 1)
		ELSE SUBSTR(PATH, INSTR(PATH, ',', 1, 10) + 1, INSTR(PATH, ',', 1, 11) - INSTR(PATH, ',', 1, 10) - 1) END Lv10_DPT_CD,
	MEMO1, MEMO2, MEMO3
FROM (
	SELECT T1.CO_CD, T1.DPT_CD, T1.TERM, SYS_CONNECT_BY_PATH(T1.DPT_CD, ',') AS PATH, T1.MEMO1, T1.MEMO2, T1.MEMO3
	FROM T1
	START WITH T1.PAR_DPT_CD IS NULL
	CONNECT BY NOCYCLE PRIOR T1.DPT_CD = T1.PAR_DPT_CD
	AND PRIOR T1.CO_CD = T1.CO_CD
	AND PRIOR T1.TERM = T1.TERM
)
;

