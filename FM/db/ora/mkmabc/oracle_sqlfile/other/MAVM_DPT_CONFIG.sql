SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_DPT_CONFIG(
	PAR_DPT_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	OPER_NULL_FLG,
	TERM
)
AS
SELECT
	M1.PAR_DPT_CD,
	M1.DPT_CD,
	M1.LOC_CD,
	M1.OPER_CD,
	M1.OPER_NULL_FLG,
	M1.TERM
FROM	MAM_DPT_CONFIG M1, MAM_COST_DPT M2
WHERE	0=0
AND	M1.PAR_DPT_CD = M2.DPT_CD
AND	M1.TERM = M2.TERM
AND	M2.DPT_CONFIG_TYP = MAC_DPT_CONFIG_TYP.CONFIG
AND	M1.DEL_FLG = '0'
AND	M2.DEL_FLG = '0'
UNION ALL
SELECT
	M1.DPT_CD PAR_DPT_CD,
	NULL	DPT_CD,
	M2.LOC_CD,
	NULL	OPER_CD,
	'0'	OPER_NULL_FLG,
	M1.TERM
FROM	MAM_COST_DPT M1, MAM_LOC M2
WHERE	0=0
AND	M1.LG_GRP_CD = M2.LG_GRP_CD
AND	M1.DPT_CONFIG_TYP = MAC_DPT_CONFIG_TYP.LG_GRP
AND	M1.DEL_FLG = '0'
AND	M2.DEL_FLG = '0'
UNION ALL
SELECT
	M1.DPT_CD PAR_DPT_CD,
	NULL	DPT_CD,
	M2.LOC_CD,
	NULL	OPER_CD,
	'0'	OPER_NULL_FLG,
	M1.TERM
FROM	MAM_COST_DPT M1, MAM_LOC M2
WHERE	0=0
AND	M1.LOC_GRP_CD = M2.LOC_GRP_CD
AND	M1.DPT_CONFIG_TYP = MAC_DPT_CONFIG_TYP.LOC_GRP
AND	M1.DEL_FLG = '0'
AND	M2.DEL_FLG = '0'
UNION ALL
SELECT
	M1.DPT_CD PAR_DPT_CD,
	NULL	DPT_CD,
	M2.LOC_CD,
	NULL	OPER_CD,
	'0'	OPER_NULL_FLG,
	M1.TERM
FROM	MAM_COST_DPT M1, MAM_LOC M2
WHERE	0=0
AND	M1.WG_CD = M2.WG_CD
AND	M1.DPT_CONFIG_TYP = MAC_DPT_CONFIG_TYP.WG
AND	M1.DEL_FLG = '0'
AND	M2.DEL_FLG = '0'
UNION ALL
SELECT
	M1.DPT_CD PAR_DPT_CD,
	NULL	DPT_CD,
	M2.LOC_CD,
	NULL	OPER_CD,
	'0'	OPER_NULL_FLG,
	M1.TERM
FROM	MAM_COST_DPT M1, MAM_LOC M2
WHERE	0=0
AND	M1.SITE_CD = M2.SITE_CD
AND	M1.DPT_CONFIG_TYP = MAC_DPT_CONFIG_TYP.SITE
AND	M1.DEL_FLG = '0'
AND	M2.DEL_FLG = '0'
;

