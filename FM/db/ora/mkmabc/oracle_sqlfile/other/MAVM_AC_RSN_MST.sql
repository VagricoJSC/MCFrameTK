SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_AC_RSN_MST(
	AC_RSN_CD,
	AC_RSN_NM,
	AR_TYP,
	AP_TYP,
	AC_INVALID_FLG,
	COST_INVALID_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	AC_RSN_NM_LCL1,
	AC_RSN_NM_LCL2,
	AC_RSN_NM_LCL3,
	AC_RSN_NM_LCL4,
	AC_RSN_NM_LCL5
)
AS
SELECT
	T1.AC_RSN_CD,
	T1.AC_RSN_NM,
	T1.AR_TYP,
	T1.AP_TYP,
	T1.AC_INVALID_FLG,
	T1.COST_INVALID_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--会計理由名（ロケール１）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_ALL T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	AC_RSN_NM_LCL1,
	--会計理由名（ロケール２）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_ALL T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	AC_RSN_NM_LCL2,
	--会計理由名（ロケール３）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_ALL T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	AC_RSN_NM_LCL3,
	--会計理由名（ロケール４）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_ALL T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	AC_RSN_NM_LCL4,
	--会計理由名（ロケール５）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_ALL T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	AC_RSN_NM_LCL5
	FROM MAM_AC_RSN_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_AC_RSN
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_AC_RSN
			)
		)
	)
UNION ALL
SELECT
	T1.AC_RSN_CD,
	T1.AC_RSN_NM,
	T1.AR_TYP,
	T1.AP_TYP,
	T1.AC_INVALID_FLG,
	T1.COST_INVALID_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--会計理由名（ロケール１）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_CMN T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.LCL_CD = 'ja_JP'
	)	AC_RSN_NM_LCL1,
	--会計理由名（ロケール２）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_CMN T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.LCL_CD = 'en_US'
	)	AC_RSN_NM_LCL2,
	--会計理由名（ロケール３）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_CMN T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.LCL_CD = 'TBD3'
	)	AC_RSN_NM_LCL3,
	--会計理由名（ロケール４）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_CMN T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.LCL_CD = 'TBD4'
	)	AC_RSN_NM_LCL4,
	--会計理由名（ロケール５）
	(SELECT T.AC_RSN_NM
		FROM MAM_AC_RSN_LCL_CMN T
		WHERE 0 = 0
		AND T.AC_RSN_CD = T1.AC_RSN_CD
		AND T.LCL_CD = 'TBD5'
	)	AC_RSN_NM_LCL5
	FROM MAM_AC_RSN_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_AC_RSN
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

