CREATE OR REPLACE VIEW MAVM_LOC_MST(
	LOC_CD,
	LOC_NM,
	ASST_DPT_CD,
	SLS_DPT_CD,
	WG_CD,
	SITE_CD,
	LG_GRP_CD,
	LG_DEF_FLG,
	LOC_GRP_CD,
	ALLOC_GRP_CD,
	SPPL_CD,
	MAKER_CD,
	PRE_OUTSRC_ACT_FLG,
	DDLV_PROV_INSP_FLG,
	CAL_CD,
	LOC_MNG_TYP,
	PRNT_LCL_CD,
	CNTRY_CD,
	NUM_ID,
	STKTK_TGT_FLG,
	STKTK_TOR_DISP_FLG,
	STKTK_TOR_EX_ZERO_FLG,
	STKTK_ACT_EX_ZERO_FLG,
	STKTK_AMT_FLG,
	STR_LN_TGT_FLG,
	ALLOC_LMT_FLG,
	GI_PACK_XFER_FLG,
	GI_VMI_FLG,
	RSRC_CD1,
	RSRC_CD2,
	EXT_SYS_LOC_TYP,
	LOC_ALC_GRP,
	ADDR_FLG,
	ZIP_CD,
	ADDR1,
	ADDR2,
	ADDR3,
	ADDR4,
	TEL,
	FAX,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	LOC_NM_LCL1,
	LOC_NM_LCL2,
	LOC_NM_LCL3,
	LOC_NM_LCL4,
	LOC_NM_LCL5
)
AS
SELECT
	T1.LOC_CD,
	T1.LOC_NM,
	T1.ASST_DPT_CD,
	T1.SLS_DPT_CD,
	T1.WG_CD,
	T1.SITE_CD,
	T1.LG_GRP_CD,
	T1.LG_DEF_FLG,
	T1.LOC_GRP_CD,
	T1.ALLOC_GRP_CD,
	T1.SPPL_CD,
	T1.MAKER_CD,
	T1.PRE_OUTSRC_ACT_FLG,
	T1.DDLV_PROV_INSP_FLG,
	T1.CAL_CD,
	T1.LOC_MNG_TYP,
	T1.PRNT_LCL_CD,
	T1.CNTRY_CD,
	T1.NUM_ID,
	T1.STKTK_TGT_FLG,
	T1.STKTK_TOR_DISP_FLG,
	T1.STKTK_TOR_EX_ZERO_FLG,
	T1.STKTK_ACT_EX_ZERO_FLG,
	T1.STKTK_AMT_FLG,
	T1.STR_LN_TGT_FLG,
	T1.ALLOC_LMT_FLG,
	T1.GI_PACK_XFER_FLG,
	T1.GI_VMI_FLG,
	T1.RSRC_CD1,
	T1.RSRC_CD2,
	T1.EXT_SYS_LOC_TYP,
	T1.LOC_ALC_GRP,
	T1.ADDR_FLG,
	T1.ZIP_CD,
	T1.ADDR1,
	T1.ADDR2,
	T1.ADDR3,
	T1.ADDR4,
	T1.TEL,
	T1.FAX,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--場所名（ロケール１）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	LOC_NM_LCL1,
	--場所名（ロケール２）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	LOC_NM_LCL2,
	--場所名（ロケール３）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	LOC_NM_LCL3,
	--場所名（ロケール４）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	LOC_NM_LCL4,
	--場所名（ロケール５）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_ALL T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	LOC_NM_LCL5
	FROM MAM_LOC_ALL T1
	WHERE 0 = 0
	AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_LOC
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
		)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_LOC
			)
		)
	)
UNION ALL
SELECT
	T1.LOC_CD,
	T1.LOC_NM,
	T1.ASST_DPT_CD,
	T1.SLS_DPT_CD,
	T1.WG_CD,
	T1.SITE_CD,
	T1.LG_GRP_CD,
	T1.LG_DEF_FLG,
	T1.LOC_GRP_CD,
	T1.ALLOC_GRP_CD,
	T1.SPPL_CD,
	T1.MAKER_CD,
	T1.PRE_OUTSRC_ACT_FLG,
	T1.DDLV_PROV_INSP_FLG,
	T1.CAL_CD,
	T1.LOC_MNG_TYP,
	T1.PRNT_LCL_CD,
	T1.CNTRY_CD,
	T1.NUM_ID,
	T1.STKTK_TGT_FLG,
	T1.STKTK_TOR_DISP_FLG,
	T1.STKTK_TOR_EX_ZERO_FLG,
	T1.STKTK_ACT_EX_ZERO_FLG,
	T1.STKTK_AMT_FLG,
	T1.STR_LN_TGT_FLG,
	T1.ALLOC_LMT_FLG,
	T1.GI_PACK_XFER_FLG,
	T1.GI_VMI_FLG,
	T1.RSRC_CD1,
	T1.RSRC_CD2,
	T1.EXT_SYS_LOC_TYP,
	T1.LOC_ALC_GRP,
	T1.ADDR_FLG,
	T1.ZIP_CD,
	T1.ADDR1,
	T1.ADDR2,
	T1.ADDR3,
	T1.ADDR4,
	T1.TEL,
	T1.FAX,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--場所名（ロケール１）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.LCL_CD = 'ja_JP'
	)	LOC_NM_LCL1,
	--場所名（ロケール２）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.LCL_CD = 'en_US'
	)	LOC_NM_LCL2,
	--場所名（ロケール３）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.LCL_CD = 'TBD3'
	)	LOC_NM_LCL3,
	--場所名（ロケール４）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.LCL_CD = 'TBD4'
	)	LOC_NM_LCL4,
	--場所名（ロケール５）
	(SELECT T.LOC_NM
		FROM MAM_LOC_LCL_CMN T
		WHERE 0 = 0
		AND T.LOC_CD = T1.LOC_CD
		AND T.LCL_CD = 'TBD5'
	)	LOC_NM_LCL5
	FROM MAM_LOC_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_LOC
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

