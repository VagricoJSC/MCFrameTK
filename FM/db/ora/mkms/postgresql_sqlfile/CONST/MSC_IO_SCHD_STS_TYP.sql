	OR I_VALUE = MSC_IO_SCHD_STS_TYP$DLV_INST()
	OR I_VALUE = MSC_IO_SCHD_STS_TYP$ORD()
	OR I_VALUE = MSC_IO_SCHD_STS_TYP$STT()
	OR I_VALUE = MSC_IO_SCHD_STS_TYP$YET()
	OR I_VALUE = MSC_IO_SCHD_STS_TYP$ING()
