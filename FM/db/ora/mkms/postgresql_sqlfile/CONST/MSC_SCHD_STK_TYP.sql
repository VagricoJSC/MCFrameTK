	OR I_VALUE = MSC_SCHD_STK_TYP$LOC_GI_SCHD()
	OR I_VALUE = MSC_SCHD_STK_TYP$GRS_GI_SCHD()
	OR I_VALUE = MSC_SCHD_STK_TYP$LOC_WAIT_GI_SCHD()
	OR I_VALUE = MSC_SCHD_STK_TYP$GRS_WAIT_GI_SCHD()
	OR I_VALUE = MSC_SCHD_STK_TYP$STK()
	OR I_VALUE = MSC_SCHD_STK_TYP$MINUS_STK()
	OR I_VALUE = MSC_SCHD_STK_TYP$GR_SCHD()
	OR I_VALUE = MSC_SCHD_STK_TYP$GR_ACT()
	OR I_VALUE = MSC_SCHD_STK_TYP$GI_SCHD()
	OR I_VALUE = MSC_SCHD_STK_TYP$GI_ACT() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE MSC_SCHD_STK_TYP$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF MSC_SCHD_STK_TYP$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
