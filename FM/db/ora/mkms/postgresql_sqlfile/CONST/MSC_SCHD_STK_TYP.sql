CREATE OR REPLACE FUNCTION MSC_SCHD_STK_TYP$SCHD_STK_PRIO(
		IN I_SCHD_STK_TYP VARCHAR
)RETURNS NUMERIC
 AS
$BODY$ BEGIN
	IF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$TGT_GR_SCHD()) THEN
		RETURN 1;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$NOTGT_GR_SCHD()) THEN
		RETURN 2;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$LOC_GI_SCHD()) THEN
		RETURN 2;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$GRS_GI_SCHD()) THEN
		RETURN 3;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$LOC_WAIT_GI_SCHD()) THEN
		RETURN 4;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$GRS_WAIT_GI_SCHD()) THEN
		RETURN 5;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$STK()) THEN
		RETURN 3;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$MINUS_STK()) THEN
		RETURN 1;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$GR_SCHD()) THEN
		RETURN NULL;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$GR_ACT()) THEN
		RETURN NULL;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$GI_SCHD()) THEN
		RETURN NULL;
	ELSIF (I_SCHD_STK_TYP = MSC_SCHD_STK_TYP$GI_ACT()) THEN
		RETURN NULL;
	ELSE
		RETURN NULL;
	END IF;
	END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;

