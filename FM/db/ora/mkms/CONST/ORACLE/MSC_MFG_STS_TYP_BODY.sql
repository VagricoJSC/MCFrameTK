CREATE OR REPLACE PACKAGE BODY MSC_MFG_STS_TYP
/*****************************
製造状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION YET RETURN VARCHAR2 DETERMINISTIC IS -- 未指図
	BEGIN RETURN '1'; END YET;
	FUNCTION SAV RETURN VARCHAR2 DETERMINISTIC IS -- 指図保存
	BEGIN RETURN '2'; END SAV;
	FUNCTION ORD RETURN VARCHAR2 DETERMINISTIC IS -- 指図済
	BEGIN RETURN '3'; END ORD;
	FUNCTION STT RETURN VARCHAR2 DETERMINISTIC IS -- 着手中
	BEGIN RETURN '4'; END STT;
	FUNCTION CMPL RETURN VARCHAR2 DETERMINISTIC IS -- 完了
	BEGIN RETURN '5'; END CMPL;

	FUNCTION IS_YET(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未指図かどうか
	BEGIN
		IF I_VALUE = YET THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_YET;

	FUNCTION IS_SAV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指図保存かどうか
	BEGIN
		IF I_VALUE = SAV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SAV;

	FUNCTION IS_ORD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指図済かどうか
	BEGIN
		IF I_VALUE = ORD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ORD;

	FUNCTION IS_STT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 着手中かどうか
	BEGIN
		IF I_VALUE = STT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STT;

	FUNCTION IS_CMPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 完了かどうか
	BEGIN
		IF I_VALUE = CMPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CMPL;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = YET
		OR I_VALUE = SAV
		OR I_VALUE = ORD
		OR I_VALUE = STT
		OR I_VALUE = CMPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_MFG_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_MFG_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_MFG_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_MFG_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_MFG_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_MFG_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_MFG_STS_TYP;
