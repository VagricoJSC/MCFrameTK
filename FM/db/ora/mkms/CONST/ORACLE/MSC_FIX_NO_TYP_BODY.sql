CREATE OR REPLACE PACKAGE BODY MSC_FIX_NO_TYP
/*****************************
確定ＮＯ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- なし
	BEGIN RETURN '1'; END NON;
	FUNCTION DLV_SLIP_NO RETURN VARCHAR2 DETERMINISTIC IS -- 納品書ＮＯ
	BEGIN RETURN '2'; END DLV_SLIP_NO;
	FUNCTION IV_NO RETURN VARCHAR2 DETERMINISTIC IS -- インボイスＮＯ
	BEGIN RETURN '3'; END IV_NO;
	FUNCTION YIELD_ACT_NO RETURN VARCHAR2 DETERMINISTIC IS -- 出来高実績ＮＯ
	BEGIN RETURN '4'; END YIELD_ACT_NO;
	FUNCTION ARR_ACT_NO RETURN VARCHAR2 DETERMINISTIC IS -- 入荷実績ＮＯ
	BEGIN RETURN '5'; END ARR_ACT_NO;
	FUNCTION PURC_ACT_IO_NO RETURN VARCHAR2 DETERMINISTIC IS -- 仕入実績受払ＮＯ
	BEGIN RETURN '6'; END PURC_ACT_IO_NO;
	FUNCTION INSP_SCHD_NO RETURN VARCHAR2 DETERMINISTIC IS -- 検査予定ＮＯ
	BEGIN RETURN '7'; END INSP_SCHD_NO;

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- なしかどうか
	BEGIN
		IF I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON;

	FUNCTION IS_DLV_SLIP_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 納品書ＮＯかどうか
	BEGIN
		IF I_VALUE = DLV_SLIP_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DLV_SLIP_NO;

	FUNCTION IS_IV_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- インボイスＮＯかどうか
	BEGIN
		IF I_VALUE = IV_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IV_NO;

	FUNCTION IS_YIELD_ACT_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出来高実績ＮＯかどうか
	BEGIN
		IF I_VALUE = YIELD_ACT_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_YIELD_ACT_NO;

	FUNCTION IS_ARR_ACT_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入荷実績ＮＯかどうか
	BEGIN
		IF I_VALUE = ARR_ACT_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ARR_ACT_NO;

	FUNCTION IS_PURC_ACT_IO_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 仕入実績受払ＮＯかどうか
	BEGIN
		IF I_VALUE = PURC_ACT_IO_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC_ACT_IO_NO;

	FUNCTION IS_INSP_SCHD_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 検査予定ＮＯかどうか
	BEGIN
		IF I_VALUE = INSP_SCHD_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INSP_SCHD_NO;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NON
		OR I_VALUE = DLV_SLIP_NO
		OR I_VALUE = IV_NO
		OR I_VALUE = YIELD_ACT_NO
		OR I_VALUE = ARR_ACT_NO
		OR I_VALUE = PURC_ACT_IO_NO
		OR I_VALUE = INSP_SCHD_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_STK_OTH_GI(
		I_FIX_NO_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_FIX_NO_TYP = NON) THEN
			RETURN '1';
		ELSIF (I_FIX_NO_TYP = DLV_SLIP_NO) THEN
			RETURN '1';
		ELSIF (I_FIX_NO_TYP = IV_NO) THEN
			RETURN '1';
		ELSIF (I_FIX_NO_TYP = YIELD_ACT_NO) THEN
			RETURN '0';
		ELSIF (I_FIX_NO_TYP = ARR_ACT_NO) THEN
			RETURN '0';
		ELSIF (I_FIX_NO_TYP = PURC_ACT_IO_NO) THEN
			RETURN '0';
		ELSIF (I_FIX_NO_TYP = INSP_SCHD_NO) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_STK_OTH_GI;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_FIX_NO_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_FIX_NO_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_FIX_NO_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_FIX_NO_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_FIX_NO_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_FIX_NO_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_FIX_NO_TYP;
