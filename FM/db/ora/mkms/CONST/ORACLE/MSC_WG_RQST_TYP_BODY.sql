CREATE OR REPLACE PACKAGE BODY MSC_WG_RQST_TYP
/*****************************
ＷＧ間依頼種類区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION XFR RETURN VARCHAR2 DETERMINISTIC IS -- 移送依頼
	BEGIN RETURN '1'; END XFR;
	FUNCTION PURC RETURN VARCHAR2 DETERMINISTIC IS -- 購買依頼
	BEGIN RETURN '2'; END PURC;
	FUNCTION SHIP RETURN VARCHAR2 DETERMINISTIC IS -- 出荷依頼
	BEGIN RETURN '3'; END SHIP;

	FUNCTION IS_XFR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 移送依頼かどうか
	BEGIN
		IF I_VALUE = XFR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_XFR;

	FUNCTION IS_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買依頼かどうか
	BEGIN
		IF I_VALUE = PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC;

	FUNCTION IS_SHIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出荷依頼かどうか
	BEGIN
		IF I_VALUE = SHIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SHIP;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = XFR
		OR I_VALUE = PURC
		OR I_VALUE = SHIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_WG_RQST_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_WG_RQST_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_WG_RQST_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_WG_RQST_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_WG_RQST_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_WG_RQST_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_WG_RQST_TYP;
