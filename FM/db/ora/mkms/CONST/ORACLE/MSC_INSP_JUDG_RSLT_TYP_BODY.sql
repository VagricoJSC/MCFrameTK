CREATE OR REPLACE PACKAGE BODY MSC_INSP_JUDG_RSLT_TYP
/*****************************
検査判定結果区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION OK RETURN VARCHAR2 DETERMINISTIC IS -- 合格
	BEGIN RETURN '1'; END OK;
	FUNCTION NG RETURN VARCHAR2 DETERMINISTIC IS -- 不合格
	BEGIN RETURN '2'; END NG;
	FUNCTION SP RETURN VARCHAR2 DETERMINISTIC IS -- 特採
	BEGIN RETURN '3'; END SP;
	FUNCTION RE RETURN VARCHAR2 DETERMINISTIC IS -- 再検査
	BEGIN RETURN '4'; END RE;

	FUNCTION IS_OK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 合格かどうか
	BEGIN
		IF I_VALUE = OK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OK;

	FUNCTION IS_NG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 不合格かどうか
	BEGIN
		IF I_VALUE = NG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NG;

	FUNCTION IS_SP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 特採かどうか
	BEGIN
		IF I_VALUE = SP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SP;

	FUNCTION IS_RE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 再検査かどうか
	BEGIN
		IF I_VALUE = RE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RE;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = OK
		OR I_VALUE = NG
		OR I_VALUE = SP
		OR I_VALUE = RE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_STK_GOOD(
		I_INSP_JUDG_RSLT_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_INSP_JUDG_RSLT_TYP = OK) THEN
			RETURN '1';
		ELSIF (I_INSP_JUDG_RSLT_TYP = NG) THEN
			RETURN '0';
		ELSIF (I_INSP_JUDG_RSLT_TYP = SP) THEN
			RETURN '1';
		ELSIF (I_INSP_JUDG_RSLT_TYP = RE) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_STK_GOOD;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_INSP_JUDG_RSLT_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_INSP_JUDG_RSLT_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_INSP_JUDG_RSLT_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_INSP_JUDG_RSLT_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_INSP_JUDG_RSLT_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_INSP_JUDG_RSLT_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_INSP_JUDG_RSLT_TYP;
