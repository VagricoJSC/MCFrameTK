CREATE OR REPLACE PACKAGE BODY MSC_SHIP_RQST_ID_TYP
/*****************************
出荷依頼先識別区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION CST RETURN VARCHAR2 DETERMINISTIC IS -- 得意先
	BEGIN RETURN '1'; END CST;
	FUNCTION SPPL RETURN VARCHAR2 DETERMINISTIC IS -- 発注先
	BEGIN RETURN '2'; END SPPL;
	FUNCTION LOC RETURN VARCHAR2 DETERMINISTIC IS -- 場所
	BEGIN RETURN '3'; END LOC;

	FUNCTION IS_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 得意先かどうか
	BEGIN
		IF I_VALUE = CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CST;

	FUNCTION IS_SPPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 発注先かどうか
	BEGIN
		IF I_VALUE = SPPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SPPL;

	FUNCTION IS_LOC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 場所かどうか
	BEGIN
		IF I_VALUE = LOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LOC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = CST
		OR I_VALUE = SPPL
		OR I_VALUE = LOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_SHIP_RQST_ID_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_SHIP_RQST_ID_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_SHIP_RQST_ID_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_SHIP_RQST_ID_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_SHIP_RQST_ID_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_SHIP_RQST_ID_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_SHIP_RQST_ID_TYP;
