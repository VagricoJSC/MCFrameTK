	OR I_VALUE = MSC_PR_STS_TYP$SHIP()
	OR I_VALUE = MSC_PR_STS_TYP$NOT_ARR()
	OR I_VALUE = MSC_PR_STS_TYP$PART_ARR()
	OR I_VALUE = MSC_PR_STS_TYP$PART_EXT_ARR()
	OR I_VALUE = MSC_PR_STS_TYP$ARR()
	OR I_VALUE = MSC_PR_STS_TYP$EXT_ARR()
	OR I_VALUE = MSC_PR_STS_TYP$PART_COMP()
	OR I_VALUE = MSC_PR_STS_TYP$COMP() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE MSC_PR_STS_TYP$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF MSC_PR_STS_TYP$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
