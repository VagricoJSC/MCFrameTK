SELECT
	mst_pay_note_mst_pay_note_all_org.pay_note_mng_no,
	mst_pay_note_mst_pay_note_all_org.pay_note_mng_seq,
	mst_pay_note_mst_pay_note_all_org.slip_sts_typ,
	mst_pay_note_mst_pay_note_all_org.note_no,
