	mst_pay_note_mst_pay_note_all_org.upd_usr_nm,
	mst_pay_note_mst_pay_note_all_org.upd_ts,
	mst_pay_note_mst_pay_note_all_org.upd_func_id,
	mst_pay_note_mst_pay_note_all_org.upd_srv_req_no
FROM
	mst_pay_note_all mst_pay_note_mst_pay_note_all_org
WHERE
	0 = 0
	AND mst_pay_note_mst_pay_note_all_org.co_cd = (SELECT co_cd FROM fct_context mst_pay_note_fct_context WHERE pid = pg_backend_pid())
