CREATE OR REPLACE VIEW MST_PAY_SCHD_LOCK_$S(
	BSPPL_CD,
	BSPPL_DPT_CD,
	PURC_ACT_NO,
	RCPT_IV_MNG_NO,
	RCPT_IV_NO,
	WRK_NO,
	TRD_CUR_CD,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BSPPL_CD,
	ORG.BSPPL_DPT_CD,
	ORG.PURC_ACT_NO,
	ORG.RCPT_IV_MNG_NO,
	ORG.RCPT_IV_NO,
	ORG.WRK_NO,
	ORG.TRD_CUR_CD,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PAY_SCHD_LOCK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

