CREATE OR REPLACE VIEW MSVT_PAY_ACT_BR(
	BATCH_DATA_NO,
	PAY_CHK_NO,
	PAY_SCHD_NO,
	PSPPL_CD,
	BSPPL_CD,
	BSPPL_DPT_CD,
	BSPPL_DPT_NM,
	AP_STTL_CD,
	AP_STTL_TYP,
	PAY_SCHD_DT,
	REG_DT,
	BSPPL_CL_DT,
	EXE_STS_TYP,
	BATCH_LOG_NO,
	LOG_SUB_KEY1,
	LOG_SUB_KEY2,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT
	T1.BATCH_DATA_NO,
	T1.PAY_CHK_NO,
	T1.PAY_SCHD_NO,
	T1.PSPPL_CD,
	T1.BSPPL_CD,
	T1.BSPPL_DPT_CD,
	M1.DPT_NM BSPPL_DPT_NM,
	T1.AP_STTL_CD,
	T1.AP_STTL_TYP,
	T1.PAY_SCHD_DT,
	T1.REG_DT,
	T1.BSPPL_CL_DT,
	T1.EXE_STS_TYP,
	T1.BATCH_LOG_NO,
	T1.LOG_SUB_KEY1,
	T1.LOG_SUB_KEY2,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO
FROM
	MST_PAY_ACT_BR T1
	LEFT OUTER JOIN MAM_DPT M1 ON (T1.BSPPL_DPT_CD = M1.DPT_CD AND NVL(T1.BSPPL_CL_DT, T1.REG_DT) BETWEEN M1.ST_DT AND M1.END_DT)
WHERE
	0 = 0
;

