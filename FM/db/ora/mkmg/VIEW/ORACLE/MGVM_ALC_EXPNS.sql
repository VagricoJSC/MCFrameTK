SELECT	m1.ALC_PTN_CD,
	m1.EXPNS_CD,
	m1.SELF_OPER_FLG,
	m1.INPT_ITM_TYP,
	m1.CTG_CD,
	m1.ITM_CD,
	m1.ITM_SUB1,
	m1.ITM_SUB2,
	m1.ITM_SUB3
FROM	MGW_ARG w1, MAM_ALC_EXPNS m1
WHERE	0=0
AND	w1.TERM = m1.TERM
AND	EXISTS (
		SELECT	'X'
		FROM	MGVM_ALC_RULE x
		WHERE	0=0
		AND	x.ALC_PTN_CD = m1.ALC_PTN_CD
		AND	x.ALC_RULE_TYP IN (MAC_ALC_RULE_TYP.EXPNS_COST, MAC_ALC_RULE_TYP.PROFIT)
	)
/
