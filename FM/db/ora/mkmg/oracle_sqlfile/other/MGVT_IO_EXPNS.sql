SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVT_IO_EXPNS(
	ACT_IO_ID,
	ACT_IO_ID_SUB,
	EXPNS_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	WG_CD,
	AMT
)
AS
SELECT	t1.ACT_IO_ID,
	t1.ACT_IO_ID_SUB,
	t1.EXPNS_CD,
	t2.ITM_CD,
	t2.ITM_SUB1,
	t2.ITM_SUB2,
	t2.ITM_SUB3,
	t2.ITM_EXT,
	t2.WG_CD,
	t1.AMT
FROM	MGW_ARG w1, MGT_ACT_IO_EXPNS t1, MGVT_IO t2
WHERE	0=0
AND	w1.SA_TYP = MAC_SA_TYP.ACT
AND	t1.ACT_IO_ID = t2.ACT_IO_ID
AND	t1.ACT_IO_ID_SUB = t2.ACT_IO_ID_SUB
AND	t2.REC_EVAL_TYP = MGC_REC_EVAL_TYP.EXPNS
AND	t1.AMT <> 0
AND	NOT EXISTS (
		SELECT	'X'
		FROM	MGT_CALC_IO_EXPNS_AMT x
		WHERE	0=0
		AND	x.CALC_NO = w1.CALC_NO
		AND	x.CALC_GRP_CD = w1.CALC_GRP_CD
		AND	x.ITM_CD = t2.ITM_CD
		AND	x.ITM_SUB1 = t2.ITM_SUB1
		AND	x.ITM_SUB2 = t2.ITM_SUB2
		AND	x.ITM_SUB3 = t2.ITM_SUB3
		AND	x.ITM_EXT = t2.ITM_EXT
		AND	x.ACT_IO_ID = t2.ACT_IO_ID
		AND	x.ACT_IO_ID_SUB = t2.ACT_IO_ID_SUB
	)
UNION ALL
SELECT	t1.ACT_IO_ID,
	t1.ACT_IO_ID_SUB,
	t1.EXPNS_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.WG_CD,
	t1.AMT
FROM	MGW_ARG w1, MGT_CALC_IO_EXPNS_AMT t1
WHERE	0=0
AND	w1.SA_TYP = MAC_SA_TYP.ACT
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
AND	t1.AMT <> 0
;

