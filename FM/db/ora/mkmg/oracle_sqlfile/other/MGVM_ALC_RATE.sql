SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVM_ALC_RATE(
	ALC_AC_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	BP_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	WG_CD,
	ALC_PTN_CD,
	EXPNS_CD,
	ALC_RATE
)
AS
SELECT	t1.ALC_AC_CD,
	t1.DPT_CD,
	t1.LOC_CD,
	t1.OPER_CD,
	t1.BP_CD,
	t1.CTG_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.WG_CD,
	t1.ALC_PTN_CD,
	t1.EXPNS_CD,
	t1.ALC_RATE
FROM	MGW_ARG w1, MGT_CALC_STD_ALC_RATE t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

