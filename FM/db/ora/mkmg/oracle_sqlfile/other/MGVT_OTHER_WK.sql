CREATE OR REPLACE VIEW MGVT_OTHER_WK(
	WG_CD,
	YM,
	AC_DT,
	DPT_CD,
	CTG_CD,
	LOC_CD,
	OPER_CD,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	WK_COST_CD,
	WK_RSN_CD,
	WK_COST,
	ALC_PTN_CD
)
AS
SELECT	t1.WG_CD,
	t1.YM,
	t1.AC_DT,
	t1.DPT_CD,
	t1.CTG_CD,
	t1.LOC_CD,
	t1.OPER_CD,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.WK_COST_CD,
	t1.WK_RSN_CD,
	t1.WK_COST,
	NULL	ALC_PTN_CD
FROM	MGW_ARG w1, MGT_CALC_OTHER_WK t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

