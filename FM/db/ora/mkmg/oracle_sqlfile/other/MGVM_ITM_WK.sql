SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVM_ITM_WK(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	WK_COST_CD,
	WG_CD,
	BASE_QTY,
	FXD_WK_COST,
	WK_COST,
	MIN_WK_COST,
	BATCH_WK_COST
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.LOC_CD,
	t1.OPER_PTN,
	t1.OPER_CD,
	t1.OPER_SEQ,
	t1.WK_COST_CD,
	t1.WG_CD,
	t1.BASE_QTY,
	t1.FXD_WK_COST,
	t1.WK_COST,
	t1.MIN_WK_COST,
	t1.BATCH_WK_COST
FROM	MGW_ARG w1, MGT_CALC_ITM_WK t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

