SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVM_CTG_CONFIG(
	PAR_CTG_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3
)
AS
SELECT	m1.PAR_CTG_CD,
	m1.CTG_CD,
	m1.ITM_CD,
	m1.ITM_SUB1,
	m1.ITM_SUB2,
	m1.ITM_SUB3
FROM	MGW_ARG w1, MAVM_CTG_CONFIG m1
WHERE	0=0
AND	w1.TERM = m1.TERM
AND	(
	m1.ITM_CD IS NULL 
	OR 
	EXISTS (
		SELECT	'X'
		FROM	MGT_CALC_ITM x
		WHERE	0=0
		AND	x.CALC_NO = w1.CALC_NO
		AND	x.CALC_GRP_CD = w1.CALC_GRP_CD
		AND	x.ITM_CD = m1.ITM_CD
		AND	x.ITM_SUB1 = m1.ITM_SUB1
		AND	x.ITM_SUB2 = m1.ITM_SUB2
		AND	x.ITM_SUB3 = m1.ITM_SUB3
		)
	)
;

