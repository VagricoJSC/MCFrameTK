CREATE OR REPLACE VIEW MGVT_ALC_AMT(
	INPT_ALC_TYP,
	WG_CD,
	YM,
	ALC_AC_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	BP_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ITM_MFG_INST_NO,
	IV_NO,
	PO_NO,
	SLO_NO,
	AMT,
	ALC_RATE,
	ALC_PTN_CD,
	EXPNS_CD
)
AS
SELECT	t1.INPT_ALC_TYP,
	t1.WG_CD,
	t1.YM,
	t1.ALC_AC_CD,
	t1.DPT_CD,
	t1.LOC_CD,
	t1.OPER_CD,
	t1.BP_CD,
	t1.CTG_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.ITM_MFG_INST_NO,
	t1.IV_NO,
	t1.PO_NO,
	t1.SLO_NO,
	t1.AMT,
	t1.ALC_RATE,
	t1.ALC_PTN_CD,
	t1.EXPNS_CD
FROM	MGW_ARG w1, MGT_CALC_ALC_AMT t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
AND	t1.YM BETWEEN w1.ST_YM AND w1.END_YM
;

