CREATE OR REPLACE VIEW MGVM_ITM_PROC(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SPPL_CD,
	WG_CD,
	BASE_QTY,
	CUR_CD,
	OUTSRC_UPRI_TYP,
	UPRI,
	BASE_CUR_UPRI,
	COST_RATIO
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.SPPL_CD,
	t1.WG_CD,
	t1.BASE_QTY,
	t1.CUR_CD,
	DECODE(m1.ONR_PRSPPL_FLG, '0', MAC_OUTSRC_UPRI_TYP.PROC, NVL(m1.OUTSRC_UPRI_TYP, m2.OUTSRC_UPRI_TYP)) OUTSRC_UPRI_TYP,
	t1.UPRI,
	t1.BASE_CUR_UPRI,
	t1.COST_RATIO
FROM	MGW_ARG w1, MGT_CALC_ITM_PROC t1, MAM_BP m1, MAM_CO m2
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
AND t1.SPPL_CD = m1.BP_CD(+)
;

