SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVM_ALC_INPT(
	ALC_PTN_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3
)
AS
SELECT	m1.ALC_PTN_CD,
	m1.CTG_CD,
	m1.ITM_CD,
	m1.ITM_SUB1,
	m1.ITM_SUB2,
	m1.ITM_SUB3
FROM	MGW_ARG w1, MAM_ALC_INPT m1
WHERE	0=0
AND	w1.TERM = m1.TERM
AND	EXISTS (
		SELECT	'X'
		FROM	MGVM_ALC_RULE x
		WHERE	0=0
		AND	x.ALC_PTN_CD = m1.ALC_PTN_CD
		AND	x.ALC_RULE_TYP = MAC_ALC_RULE_TYP.INPT_QTY
	)
;

