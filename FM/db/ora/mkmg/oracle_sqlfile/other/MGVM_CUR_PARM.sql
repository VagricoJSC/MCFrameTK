CREATE OR REPLACE VIEW MGVM_CUR_PARM(
	CUR_CD,
	AMT_RND_TYP,
	AMT_DEC_PLACE,
	AVE_RND_TYP,
	AVE_DEC_PLACE
)
AS
SELECT	t1.CUR_CD,
	t1.AMT_RND_TYP,
	t1.AMT_DEC_PLACE,
	t1.AVE_RND_TYP,
	t1.AVE_DEC_PLACE
FROM	MGW_ARG w1, MGT_CALC_CUR_PARM t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

