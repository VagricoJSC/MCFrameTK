				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO4),
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP)
			)
		LOOP
			FOR y IN (
				SELECT	t1.QTY,
					t1.AMT
				FROM	MGW_CALC_CTG w1, MAW_WG_KEY w2, MGT_ACT_PURC_IF t1
				WHERE	0=0
				AND	w1.CALC_CTG_CD = t1.CALC_CTG_CD
				AND	w2.WG_CD = t1.WG_CD
				AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
				AND	t1.NO_EVAL_FLG = '0'
				AND	t1.QTY > 0
				AND	t1.AMT > 0
				AND	t1.AC_DT = x.AC_DT
				AND	t1.ITM_CD = x.ITM_CD
				AND	t1.ITM_SUB1 = x.ITM_SUB1
				AND	t1.ITM_SUB2 = x.ITM_SUB2
				AND	t1.ITM_SUB3 = x.ITM_SUB3
				AND	DECODE(x.MNG_DPT_CD, NULL, t1.MNG_DPT_CD, x.MNG_DPT_CD) = t1.MNG_DPT_CD
				AND	DECODE(x.LOT_NO, NULL, t1.LOT_NO, x.LOT_NO) = t1.LOT_NO
