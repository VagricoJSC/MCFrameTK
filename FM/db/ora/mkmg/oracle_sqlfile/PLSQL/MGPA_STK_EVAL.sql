		BP_CD,
		ASST_TYP,
		QTY,
		FIRST_GR_DT,
		VLD_DT,
		LMT_DT,
		NON_MOV_BASE_DT
		)
	SELECT	NVL(L_CALC_GRP.RUNTIME_WG_CD, t.WG_CD),
