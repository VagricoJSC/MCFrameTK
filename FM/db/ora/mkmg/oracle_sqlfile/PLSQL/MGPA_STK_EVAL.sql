CREATE OR REPLACE PACKAGE BODY MGPA_STK_EVAL
IS
	G_MSG		FCPA_ERR.MSG_BINDER ;
	G_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;

	G_RNDOFF	CONSTANT MAPA_META.RND_TYP%TYPE := MAC_RND_TYP.RNDOFF ;

	G_EVAL_NON	CONSTANT MAPA_META.LOSS_EVAL_TYP%TYPE := MAC_LOSS_EVAL_TYP.NON ;
	G_EVAL_TGT	CONSTANT MAPA_META.LOSS_EVAL_TYP%TYPE := MAC_LOSS_EVAL_TYP.TGT ;

	G_UPRI_SET_STD		CONSTANT MAPA_META.UPRI_SET_TYP%TYPE := MAC_UPRI_SET_TYP.STD ;
	G_UPRI_SET_AVG_PURC	CONSTANT MAPA_META.UPRI_SET_TYP%TYPE := MAC_UPRI_SET_TYP.AVG_PURC ;
	G_UPRI_SET_AVG_SLS	CONSTANT MAPA_META.UPRI_SET_TYP%TYPE := MAC_UPRI_SET_TYP.AVG_SLS ;
	G_UPRI_SET_PREV_PURC	CONSTANT MAPA_META.UPRI_SET_TYP%TYPE := MAC_UPRI_SET_TYP.PREV_PURC ;
	G_UPRI_SET_PREV_SLS	CONSTANT MAPA_META.UPRI_SET_TYP%TYPE := MAC_UPRI_SET_TYP.PREV_SLS ;

	G_ENPNS_PRD		CONSTANT MAPA_META.EXPNS_TYP%TYPE := MAC_EXPNS_TYP.PROD ;

	G_ASSET_MNG_MNG		CONSTANT MAPA_META.ASSET_MNG_TYP%TYPE := MAC_ASSET_MNG_TYP.MNG ;

FUNCTION F_GET_EVAL (
	I_STK_EVAL_CD	IN MAPA_META.STK_EVAL_CD%TYPE
)
RETURN MAM_STK_EVAL%ROWTYPE
/*********************************************************
<SYNOPSIS>
	MAM_STK_EVALのレコードを返す
<REMARKS>
	存在しないときはエラーとする
<ARGUMENTS>
<IN>	I_STK_EVAL_CD
		在庫評価ＣＤ
<RETURNVALUE>
	対象となるMAM_STK_EVALのレコード
<HISTORY>
**********************************************************/
AS
	L_REC	MAM_STK_EVAL%ROWTYPE ;
BEGIN
	BEGIN
		SELECT	m.*
		INTO	L_REC
		FROM	MAM_STK_EVAL m
		WHERE	0=0
		AND	m.STK_EVAL_CD = I_STK_EVAL_CD
		;
	EXCEPTION
	WHEN NO_DATA_FOUND THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_STK_EVAL_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBBD0005', G_MSG) ;
	END ;

	RETURN L_REC ;

END F_GET_EVAL ;

PROCEDURE P_MAIN (
	I_CALC_CTG_CD	IN MAPA_META.CALC_CTG_CD%TYPE,
	I_WG_CD	IN MAPA_META.WG_CD%TYPE,
	I_YM		IN MAPA_META.YM%TYPE,
	I_STK_EVAL_CD	IN MAPA_META.STK_EVAL_CD%TYPE,
	I_CALC_GRP_CD	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN MAPA_META.CALC_NO%TYPE,
	I_YM_FROM	IN MAPA_META.YM%TYPE,
	I_YM_TO		IN MAPA_META.YM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	月末在庫評価データ作成メイン処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_CTG_CD
		計算カテゴリＣＤ
<IN>	I_WG_CD
		ワーキンググループＣＤ
<IN>	I_YM
		年月
<IN>	I_STK_EVAL_CD
		在庫評価ＣＤ
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<IN>	I_YM_FROM
		取得先年月ＦＲＯＭ
<IN>	I_YM_TO
		取得先年月ＴＯ
<HISTORY>
**************************************************************************/
AS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	CURSOR LOCK_STK_EVAL IS
		SELECT	t.ITM_CD
		FROM	MGT_STK_EVAL t
		WHERE	0=0
		AND	t.CALC_CTG_CD = I_CALC_CTG_CD
		AND	t.STK_EVAL_CD = I_STK_EVAL_CD
		AND	t.WG_CD = I_WG_CD
		AND	t.YM = I_YM
		FOR UPDATE NOWAIT
	;

	L_EVAL	MAM_STK_EVAL%ROWTYPE ;

	L_ARG	MGT_ARG%ROWTYPE ;
	L_CO	MAM_CO%ROWTYPE ;
	L_CUR	MAM_CUR%ROWTYPE ;
	L_CALC_GRP	MAM_CALC_GRP%ROWTYPE ;

	TYPE LIST_STK_EVAL IS TABLE OF MGT_STK_EVAL%ROWTYPE INDEX BY BINARY_INTEGER ;
	rec	LIST_STK_EVAL ;
	i	INTEGER ;

	C_MAX_CNT	CONSTANT INTEGER := 20000 ; --バルクインサートでの最大レコード数

/*************************************************************************/
PROCEDURE P_STK_EVAL_INSERT
AS
BEGIN
	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MGT_STK_EVAL VALUES rec(t) ;
		rec.DELETE ;
		i := 0 ;
	END IF ;
END ;
/*************************************************************************/
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0028',
		I_CALC_CTG_CD,
		I_WG_CD,
		FCPA_DATE_UTIL.F_TO_CHAR(I_YM, FCPA_DATE_UTIL.Y4M),
		I_STK_EVAL_CD,
		I_CALC_GRP_CD,
		I_CALC_NO,
		FCPA_DATE_UTIL.F_TO_CHAR(I_YM_FROM, FCPA_DATE_UTIL.Y4M),
		FCPA_DATE_UTIL.F_TO_CHAR(I_YM_TO, FCPA_DATE_UTIL.Y4M)
		) ;

	L_CO := MAPA_CO.F_GET_CO_REC() ;

	L_CUR := MGPA_XCHNG.F_GET_CUR(L_CO.BASE_CUR_CD) ;

	L_EVAL := F_GET_EVAL(I_STK_EVAL_CD) ;

	IF L_EVAL.LUMP_RATE_FLG = '1' THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_STK_EVAL_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBBD0006', G_MSG) ;

	ELSIF L_EVAL.UPRI_SET_TYP IS NULL THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_STK_EVAL_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBBD0007', G_MSG) ;
	END IF ;

	DELETE MAW_WG_KEY ;
	L_CALC_GRP := MGPA_CALC_GRP.F_GET_REC(I_CALC_GRP_CD) ;
	IF L_CALC_GRP.RUNTIME_WG_CD IS NOT NULL AND L_CALC_GRP.RUNTIME_WG_CD = I_WG_CD THEN
		INSERT INTO MAW_WG_KEY
		SELECT m.WG_CD FROM MAM_GRP_WG m WHERE m.CALC_GRP_CD = I_CALC_GRP_CD ;
	ELSE
		INSERT INTO MAW_WG_KEY VALUES (I_WG_CD) ;
	END IF ;

	/***ロック***/
	BEGIN
		OPEN LOCK_STK_EVAL ;
		CLOSE LOCK_STK_EVAL ;
	EXCEPTION
	WHEN LOCK_ERROR THEN
		FCPA_ERR.RAISE_APP_ERR('MGBXD0029') ;
	END ;

	DELETE	MGT_STK_EVAL t
	WHERE	0=0
	AND	t.CALC_CTG_CD = I_CALC_CTG_CD
	AND	t.STK_EVAL_CD = I_STK_EVAL_CD
	AND	t.WG_CD = I_WG_CD
	AND	t.YM = I_YM
	;

	CASE L_EVAL.UPRI_SET_TYP
	WHEN G_UPRI_SET_STD THEN
		L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

		INSERT INTO MGT_STK_EVAL (
			CALC_CTG_CD,
			STK_EVAL_CD,
			WG_CD,
			YM,
			MNG_DPT_CD,
			ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
			LOT_NO, SUBLOT_NO,
			SNO1, SNO2, SNO3, SNO4,
			ASST_TYP,
			BASE_QTY,
			UPRI
			)
		SELECT	I_CALC_CTG_CD,
			I_STK_EVAL_CD,
			I_WG_CD,
			I_YM,
			NULL,
			x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3,
			G_NULL_VAL, G_NULL_VAL,
			G_NULL_VAL, G_NULL_VAL, G_NULL_VAL, G_NULL_VAL,
			NULL,
			SUM(x.QTY),
			SUM(x.STD_COST)
		FROM	(
			SELECT	t1.ITM_CD,
				t1.ITM_SUB1,
				t1.ITM_SUB2,
				t1.ITM_SUB3,
				t1.TOP_REC_NO,
				NVL(t1.QTY, 0)	QTY,
				NVL(SUM(t2.STD_COST), 0)	STD_COST
			FROM	MGT_STD_TOP t1, MGT_STD_SML_COST t2, MAM_ITM m1
			WHERE	0=0
			AND	t1.CALC_NO = I_CALC_NO
			AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t1.WG_CD = I_WG_CD
			AND	t1.SLS_FLG = '0'
			AND	t1.CALC_NO = t2.CALC_NO(+)
			AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD(+)
			AND	t1.TOP_REC_NO = t2.TOP_REC_NO(+)
			AND	t2.EXPNS_TYP(+) = G_ENPNS_PRD
			AND	t1.ITM_CD = m1.ITM_CD
			AND	t1.ITM_SUB1 = m1.ITM_SUB1
			AND	t1.ITM_SUB2 = m1.ITM_SUB2
			AND	t1.ITM_SUB3 = m1.ITM_SUB3
			AND	m1.ASSET_MNG_TYP = G_ASSET_MNG_MNG
			GROUP BY t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3, t1.TOP_REC_NO, t1.QTY
			) x
		WHERE	0=0
		AND	x.STD_COST <> 0
		GROUP BY x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3
		;

	WHEN G_UPRI_SET_AVG_PURC THEN
		MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP_CD, MAC_CALC_CTG_TYP.PURC) ;

		INSERT INTO MGT_STK_EVAL (
			CALC_CTG_CD,
			STK_EVAL_CD,
			WG_CD,
			YM,
			MNG_DPT_CD,
			ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
			LOT_NO, SUBLOT_NO,
			SNO1, SNO2, SNO3, SNO4,
			ASST_TYP,
			BASE_QTY,
			UPRI
			)
		SELECT	I_CALC_CTG_CD,
			I_STK_EVAL_CD,
			I_WG_CD,
			I_YM,
			t.MNG_DPT_CD,
			t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
			t.LOT_NO, t.SUBLOT_NO,
			t.SNO1, t.SNO2, t.SNO3, t.SNO4,
			t.ASST_TYP,
			t.BASE_QTY,
			MAPA_CALC.F_RND(t.AMT / t.QTY * t.BASE_QTY, L_CUR.UPRI_DEC_PLACE, G_RNDOFF)
		FROM	(
			SELECT	DECODE(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.MNG_DPT_CD) MNG_DPT_CD,
				t1.ITM_CD,
				t1.ITM_SUB1,
				t1.ITM_SUB2,
				t1.ITM_SUB3,
				NVL(m1.COST_STD_QTY, 1)	BASE_QTY,
				DECODE(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.LOT_NO) LOT_NO,
				DECODE(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SUBLOT_NO) SUBLOT_NO,
				DECODE(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO1) SNO1,
				DECODE(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO2) SNO2,
				DECODE(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO3) SNO3,
				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO4) SNO4,
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP) ASST_TYP,
				SUM(t1.QTY)	QTY,
				SUM(t1.AMT)	AMT
			FROM	MGW_CALC_CTG w1, MAW_WG_KEY w2, MGT_ACT_PURC_IF t1, MAM_ITM m1, MAM_CALC_PTN m2
			WHERE	0=0
			AND	w1.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	w2.WG_CD = t1.WG_CD
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	t1.NO_EVAL_FLG = '0'
			AND	t1.ITM_CD = m1.ITM_CD
			AND	t1.ITM_SUB1 = m1.ITM_SUB1
			AND	t1.ITM_SUB2 = m1.ITM_SUB2
			AND	t1.ITM_SUB3 = m1.ITM_SUB3
			AND	m1.ASSET_MNG_TYP = G_ASSET_MNG_MNG
			AND	m1.CALC_PTN_CD = m2.CALC_PTN_CD(+)
			AND	m2.DEL_FLG(+) = '0'
			GROUP BY DECODE(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.MNG_DPT_CD),
				t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
				NVL(m1.COST_STD_QTY, 1),
				DECODE(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.LOT_NO),
				DECODE(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SUBLOT_NO),
				DECODE(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO1),
				DECODE(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO2),
				DECODE(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO3),
				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO4),
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP)
			) t
		WHERE	0=0
		AND	(t.QTY > 0 AND t.AMT > 0 OR t.QTY < 0 AND t.AMT < 0)
		AND	t.BASE_QTY > 0
		;
	WHEN G_UPRI_SET_AVG_SLS THEN
		MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP_CD, MAC_CALC_CTG_TYP.SLS) ;

		INSERT INTO MGT_STK_EVAL (
			CALC_CTG_CD,
			STK_EVAL_CD,
			WG_CD,
			YM,
			MNG_DPT_CD,
			ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
			LOT_NO, SUBLOT_NO,
			SNO1, SNO2, SNO3, SNO4,
			ASST_TYP,
			BASE_QTY,
			UPRI
			)
		SELECT	I_CALC_CTG_CD,
			I_STK_EVAL_CD,
			I_WG_CD,
			I_YM,
			t.MNG_DPT_CD,
			t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
			t.LOT_NO, t.SUBLOT_NO,
			t.SNO1, t.SNO2, t.SNO3, t.SNO4,
			t.ASST_TYP,
			t.BASE_QTY,
			MAPA_CALC.F_RND(t.AMT / t.QTY * t.BASE_QTY, L_CUR.UPRI_DEC_PLACE, G_RNDOFF)
		FROM	(
			SELECT	DECODE(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.MNG_DPT_CD) MNG_DPT_CD,
				t1.ITM_CD,
				t1.ITM_SUB1,
				t1.ITM_SUB2,
				t1.ITM_SUB3,
				NVL(m1.COST_STD_QTY, 1)	BASE_QTY,
				DECODE(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.LOT_NO) LOT_NO,
				DECODE(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SUBLOT_NO) SUBLOT_NO,
				DECODE(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO1) SNO1,
				DECODE(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO2) SNO2,
				DECODE(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO3) SNO3,
				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO4) SNO4,
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP) ASST_TYP,
				SUM(t1.QTY)	QTY,
				SUM(t1.AMT)	AMT
			FROM	MGW_CALC_CTG w1, MAW_WG_KEY w2, MGT_ACT_SLS_IF t1, MAM_ITM m1, MAM_CALC_PTN m2
			WHERE	0=0
			AND	w1.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	w2.WG_CD = t1.WG_CD
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	t1.NO_EVAL_FLG = '0'
			AND	t1.ITM_CD = m1.ITM_CD
			AND	t1.ITM_SUB1 = m1.ITM_SUB1
			AND	t1.ITM_SUB2 = m1.ITM_SUB2
			AND	t1.ITM_SUB3 = m1.ITM_SUB3
			AND	m1.ASSET_MNG_TYP = G_ASSET_MNG_MNG
			AND	m1.CALC_PTN_CD = m2.CALC_PTN_CD(+)
			AND	m2.DEL_FLG(+) = '0'
			GROUP BY DECODE(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.MNG_DPT_CD),
				t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
				NVL(m1.COST_STD_QTY, 1),
				DECODE(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.LOT_NO),
				DECODE(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SUBLOT_NO),
				DECODE(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO1),
				DECODE(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO2),
				DECODE(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO3),
				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, G_NULL_VAL, t1.SNO4),
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP)
			) t
		WHERE	0=0
		AND	(t.QTY > 0 AND t.AMT > 0 OR t.QTY < 0 AND t.AMT < 0)
		AND	t.BASE_QTY > 0
		;
	WHEN G_UPRI_SET_PREV_PURC THEN
		MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP_CD, MAC_CALC_CTG_TYP.PURC) ;

		i := 0 ;
