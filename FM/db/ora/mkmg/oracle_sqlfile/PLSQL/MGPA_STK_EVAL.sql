				EXIT ;
			END LOOP ;

			IF i > C_MAX_CNT THEN
				P_STK_EVAL_INSERT() ;
			END IF ;
		END LOOP ;

		P_STK_EVAL_INSERT() ;

	WHEN G_UPRI_SET_PREV_SLS THEN
		MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP_CD, MAC_CALC_CTG_TYP.SLS) ;

		i := 0 ;
		FOR x IN (
			SELECT	DECODE(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.MNG_DPT_CD) MNG_DPT_CD,
				t1.ITM_CD,
				t1.ITM_SUB1,
				t1.ITM_SUB2,
				t1.ITM_SUB3,
				NVL(m1.COST_STD_QTY, 1)	COST_STD_QTY,
				DECODE(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.LOT_NO) LOT_NO,
				DECODE(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SUBLOT_NO) SUBLOT_NO,
				DECODE(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO1) SNO1,
				DECODE(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO2) SNO2,
				DECODE(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO3) SNO3,
				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO4) SNO4,
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP) ASST_TYP,
				MAX(t1.AC_DT)	AC_DT
			FROM	MGW_CALC_CTG w1, MAW_WG_KEY w2, MGT_ACT_SLS_IF t1, MAM_ITM m1, MAM_CALC_PTN m2
			WHERE	0=0
			AND	w1.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	w2.WG_CD = t1.WG_CD
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	t1.NO_EVAL_FLG = '0'
			AND	t1.QTY > 0
			AND	t1.AMT > 0
			AND	t1.ITM_CD = m1.ITM_CD
			AND	t1.ITM_SUB1 = m1.ITM_SUB1
			AND	t1.ITM_SUB2 = m1.ITM_SUB2
			AND	t1.ITM_SUB3 = m1.ITM_SUB3
			AND	m1.ASSET_MNG_TYP = G_ASSET_MNG_MNG
			AND	m1.CALC_PTN_CD = m2.CALC_PTN_CD(+)
			AND	m2.DEL_FLG(+) = '0'
			GROUP BY DECODE(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.MNG_DPT_CD),
				t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
				NVL(m1.COST_STD_QTY, 1),
				DECODE(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.LOT_NO),
				DECODE(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SUBLOT_NO),
				DECODE(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO1),
				DECODE(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO2),
				DECODE(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO3),
				DECODE(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.SNO4),
				DECODE(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON), G_EVAL_NON, NULL, t1.ASST_TYP)
			)
		LOOP
			FOR y IN (
				SELECT	t1.QTY,
					t1.AMT
				FROM	MGW_CALC_CTG w1, MAW_WG_KEY w2, MGT_ACT_SLS_IF t1
				WHERE	0=0
				AND	w1.CALC_CTG_CD = t1.CALC_CTG_CD
				AND	w2.WG_CD = t1.WG_CD
				AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
				AND	t1.NO_EVAL_FLG = '0'
				AND	t1.QTY > 0
				AND	t1.AMT > 0
				AND	t1.AC_DT = x.AC_DT
				AND	t1.ITM_CD = x.ITM_CD
				AND	t1.ITM_SUB1 = x.ITM_SUB1
				AND	t1.ITM_SUB2 = x.ITM_SUB2
				AND	t1.ITM_SUB3 = x.ITM_SUB3
				AND	DECODE(x.MNG_DPT_CD, NULL, t1.MNG_DPT_CD, x.MNG_DPT_CD) = t1.MNG_DPT_CD
				AND	DECODE(x.LOT_NO, NULL, t1.LOT_NO, x.LOT_NO) = t1.LOT_NO
				AND	DECODE(x.SUBLOT_NO, NULL, t1.SUBLOT_NO, x.SUBLOT_NO) = t1.SUBLOT_NO
				AND	DECODE(x.SNO1, NULL, t1.SNO1, x.SNO1) = t1.SNO1
				AND	DECODE(x.SNO2, NULL, t1.SNO2, x.SNO2) = t1.SNO2
				AND	DECODE(x.SNO3, NULL, t1.SNO3, x.SNO3) = t1.SNO3
				AND	DECODE(x.SNO4, NULL, t1.SNO4, x.SNO4) = t1.SNO4
				AND	DECODE(x.ASST_TYP, NULL, t1.ASST_TYP, x.ASST_TYP) = t1.ASST_TYP
				ORDER BY t1.DATA_LNO DESC
				)
			LOOP
				i := i + 1 ;

				rec(i).CALC_CTG_CD := I_CALC_CTG_CD ;
				rec(i).STK_EVAL_CD := I_STK_EVAL_CD ;
				rec(i).WG_CD := I_WG_CD ;
				rec(i).YM := I_YM ;
				rec(i).MNG_DPT_CD := x.MNG_DPT_CD ;
				rec(i).ITM_CD := x.ITM_CD ;
				rec(i).ITM_SUB1 := x.ITM_SUB1 ;
				rec(i).ITM_SUB2 := x.ITM_SUB2 ;
				rec(i).ITM_SUB3 := x.ITM_SUB3 ;
				rec(i).LOT_NO := NVL(x.LOT_NO, G_NULL_VAL) ;
				rec(i).SUBLOT_NO := NVL(x.SUBLOT_NO, G_NULL_VAL) ;
				rec(i).SNO1 := NVL(x.SNO1, G_NULL_VAL) ;
				rec(i).SNO2 := NVL(x.SNO2, G_NULL_VAL) ;
				rec(i).SNO3 := NVL(x.SNO3, G_NULL_VAL) ;
