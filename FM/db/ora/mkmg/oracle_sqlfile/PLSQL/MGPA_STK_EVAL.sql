				rec(i).UPRI := MAPA_CALC.F_RND(y.AMT / y.QTY * x.COST_STD_QTY, L_CUR.UPRI_DEC_PLACE, G_RNDOFF) ;

				EXIT ;
			END LOOP ;

			IF i > C_MAX_CNT THEN
				P_STK_EVAL_INSERT() ;
			END IF ;
		END LOOP ;

		P_STK_EVAL_INSERT() ;
	ELSE
		NULL ;
	END CASE ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_STK_EVAL.P_MAIN') ;
END P_MAIN ;

PROCEDURE P_SET_WORK (
	I_CALC_GRP_CD	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_STK_EVAL_CD	IN MAPA_META.STK_EVAL_CD%TYPE,
	I_YM		IN MAPA_META.YM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	評価損登録時に使用するワークテーブルを作成する
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_STK_EVAL_CD
		在庫評価ＣＤ
<IN>	I_YM
		年月
<HISTORY>
**************************************************************************/
AS
	CURSOR CTG_LIST
	IS
		SELECT	w.CALC_CTG_CD
		FROM	MGW_CALC_CTG w
		WHERE	0=0
		ORDER BY w.CTG_PRIO, w.CALC_CTG_CD
	;

	L_EVAL	MAM_STK_EVAL%ROWTYPE ;
	L_CALC_GRP	MAM_CALC_GRP%ROWTYPE ;
BEGIN
	DELETE MGW_STK_EVAL ;
	DELETE MGW_ACT_STK ;

	MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP_CD, MAC_CALC_CTG_TYP.END_STK) ;

	L_EVAL := F_GET_EVAL(I_STK_EVAL_CD) ;

	IF L_EVAL.LUMP_RATE_FLG = '1' THEN
		GOTO SKIP_STK_EVAL ;
	END IF ;

	FOR x IN CTG_LIST LOOP
		INSERT INTO MGW_STK_EVAL (
			WG_CD,
			MNG_DPT_CD,
			ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
			LOT_NO, SUBLOT_NO,
			SNO1, SNO2, SNO3, SNO4,
			ASST_TYP,
			BASE_QTY,
			UPRI
			)
		SELECT	t1.WG_CD,
			NVL(t1.MNG_DPT_CD, G_NULL_VAL),
			t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
			t1.LOT_NO, t1.SUBLOT_NO,
			t1.SNO1, t1.SNO2, t1.SNO3, t1.SNO4,
			NVL(t1.ASST_TYP, G_NULL_VAL),
			t1.BASE_QTY,
			t1.UPRI
		FROM	MGT_STK_EVAL t1, MAM_ITM m1, MAM_CALC_PTN m2
		WHERE	0=0
		AND	t1.YM = I_YM
		AND	t1.STK_EVAL_CD = I_STK_EVAL_CD
		AND	t1.CALC_CTG_CD = x.CALC_CTG_CD
		AND	t1.ITM_CD = m1.ITM_CD(+)
		AND	t1.ITM_SUB1 = m1.ITM_SUB1(+)
		AND	t1.ITM_SUB2 = m1.ITM_SUB2(+)
		AND	t1.ITM_SUB3 = m1.ITM_SUB3(+)
		AND	m1.CALC_PTN_CD = m2.CALC_PTN_CD(+)
		AND	m2.DEL_FLG(+) = '0'
		AND	(
			(NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.MNG_DPT_CD IS NULL
			OR
			NVL(m2.DPT_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.MNG_DPT_CD IS NOT NULL
			)
		AND	(
			(NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.LOT_NO = G_NULL_VAL
			OR
			NVL(m2.LOT_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.LOT_NO IS NOT NULL
			)
		AND	(
			(NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.SUBLOT_NO = G_NULL_VAL
			OR
			NVL(m2.SUBLOT_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.SUBLOT_NO IS NOT NULL
			)
		AND	(
			(NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.SNO1 = G_NULL_VAL
			OR
			NVL(m2.SNO1_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.SNO1 IS NOT NULL
			)
		AND	(
			(NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.SNO2 = G_NULL_VAL
			OR
			NVL(m2.SNO2_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.SNO2 IS NOT NULL
			)
		AND	(
			(NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.SNO3 = G_NULL_VAL
			OR
			NVL(m2.SNO3_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.SNO3 IS NOT NULL
			)
		AND	(
			(NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.SNO4 = G_NULL_VAL
			OR
			NVL(m2.SNO4_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.SNO4 IS NOT NULL
			)
		AND	(
			(NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_NON OR L_EVAL.UPRI_SET_TYP = G_UPRI_SET_STD)
				AND t1.ASST_TYP IS NULL
			OR
			NVL(m2.ASST_LOSS_EVAL_TYP, G_EVAL_NON) = G_EVAL_TGT AND t1.ASST_TYP IS NOT NULL
			)
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_STK_EVAL w
				WHERE	0=0
				AND	w.WG_CD = t1.WG_CD
				AND	w.MNG_DPT_CD = NVL(t1.MNG_DPT_CD, G_NULL_VAL)
				AND	w.ITM_CD = t1.ITM_CD
				AND	w.ITM_SUB1 = t1.ITM_SUB1
				AND	w.ITM_SUB2 = t1.ITM_SUB2
				AND	w.ITM_SUB3 = t1.ITM_SUB3
				AND	w.LOT_NO = t1.LOT_NO
				AND	w.SUBLOT_NO = t1.SUBLOT_NO
				AND	w.SNO1 = t1.SNO1
				AND	w.SNO2 = t1.SNO2
				AND	w.SNO3 = t1.SNO3
				AND	w.SNO4 = t1.SNO4
				AND	w.ASST_TYP = NVL(t1.ASST_TYP, G_NULL_VAL)
			)
		;
	END LOOP ;

	<<SKIP_STK_EVAL>>
		NULL ;

	L_CALC_GRP := MGPA_CALC_GRP.F_GET_REC(I_CALC_GRP_CD) ;

	DELETE MAW_WG_KEY ;
