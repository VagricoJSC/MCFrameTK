CREATE OR REPLACE PACKAGE BODY MGPA_WIP_LOC
IS

PROCEDURE P_MAIN (
	I_CALC_GRP_CD	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN MAPA_META.CALC_NO%TYPE,
	I_WG_CD	IN	MAPA_META.WG_CD%TYPE DEFAULT NULL
)
/**************************************************************************
<SYNOPSIS>
	場所別仕掛原価データの作成メイン処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<HISTORY>
**************************************************************************/
AS
	L_ARG		MGT_ARG%ROWTYPE ;
	C_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;

	C_CALC_REC_ST_WIP	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.ST_WIP ;
	C_CALC_REC_COMP		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.COMP ;
	C_CALC_REC_END_WIP	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.END_WIP ;
	C_CALC_REC_INST		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.INST ;
BEGIN
	IF I_WG_CD IS NULL THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_WIP_LOC.P_MAIN') ;
	ELSE
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_WIP_LOC.P_MAIN - ' || I_WG_CD) ;
	END IF ;

	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	DELETE MGT_WIP_LOC t
	WHERE t.CALC_NO = I_CALC_NO AND t.CALC_GRP_CD = I_CALC_GRP_CD
	AND (I_WG_CD IS NULL OR t.WG_CD = I_WG_CD) ;

	INSERT INTO MGT_WIP_LOC (
		CALC_NO,
		CALC_GRP_CD,
		WG_CD, 
		YM,
		MNG_DPT_CD, 
		LOC_CD, 
		STR_LN_CD,
		OPER_CD,
		OPER_SEQ,
		EXPNS_CD,
		ST_WIP_AMT,
		PROD_AMT,
		INPT_AMT,
		COMP_AMT,
		END_WIP_AMT
		)
	SELECT	I_CALC_NO,
		I_CALC_GRP_CD,
		x.WG_CD,
		x.YM,
		x.MNG_DPT_CD,
		x.LOC_CD,
		NVL(x.STR_LN_CD, C_NULL_VAL),
		x.OPER_CD,
		x.OPER_SEQ,
		x.EXPNS_CD,
		SUM(x.ST_WIP_AMT),
		SUM(x.PROD_AMT),
		SUM(x.INPT_AMT),
		SUM(x.COMP_AMT),
		SUM(x.END_WIP_AMT)
	FROM	(
		-- 月初仕掛・完成・月末仕掛データの取得
		SELECT /*+USE_NL(t1 t2) INDEX(t1 MGT_ACC_TOP_ALL_IE01) INDEX(t2 MGT_ACC_SML_COST_ALL_IE01)*/
			t1.WG_CD,
			t1.YM,
			t1.MNG_DPT_CD,
			t1.LOC_CD,
			t1.STR_LN_CD,
			t1.OPER_CD,
			t1.OPER_SEQ,
			t2.EXPNS_CD,
			DECODE(t1.CALC_REC_TYP, C_CALC_REC_ST_WIP, SUM(t2.ACT_COST), 0)		ST_WIP_AMT,
			0	PROD_AMT,
			0	INPT_AMT,
			DECODE(t1.CALC_REC_TYP, C_CALC_REC_COMP, SUM(t2.ACT_COST), 0)		COMP_AMT,
			DECODE(t1.CALC_REC_TYP, C_CALC_REC_END_WIP, SUM(t2.ACT_COST), 0)	END_WIP_AMT
		FROM	MGT_ACC_TOP t1, MGT_ACC_SML_COST t2
		WHERE	0=0
		AND	t1.CALC_NO = I_CALC_NO
		AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
		AND	(I_WG_CD IS NULL OR t1.WG_CD = I_WG_CD)
		AND	t1.CALC_REC_TYP IN (
				C_CALC_REC_ST_WIP,
				C_CALC_REC_COMP,
				C_CALC_REC_END_WIP
				)
		AND	t1.CALC_NO = t2.CALC_NO
		AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
		AND	t1.TOP_REC_NO = t2.TOP_REC_NO
		GROUP BY t1.WG_CD, t1.YM, t1.MNG_DPT_CD, 
			t1.LOC_CD, t1.STR_LN_CD,
			t1.OPER_CD, t1.OPER_SEQ,
			t1.CALC_REC_TYP,
			t2.EXPNS_CD
		UNION ALL
		-- 月初仕掛データの取得（複数年月での計算時）
		SELECT /*+USE_NL(t1 t2) INDEX(t1 MGT_ACC_TOP_ALL_IE01) INDEX(t2 MGT_ACC_SML_COST_ALL_IE01)*/
			t1.WG_CD,
			ADD_MONTHS(t1.YM, 1) YM,
			t1.MNG_DPT_CD,
			t1.LOC_CD,
			t1.STR_LN_CD,
			t1.OPER_CD,
			t1.OPER_SEQ,
			t2.EXPNS_CD,
			SUM(t2.ACT_COST)	ST_WIP_AMT,
			0	PROD_AMT,
			0	INPT_AMT,
			0	COMP_AMT,
			0	END_WIP_AMT
		FROM	MGT_ACC_TOP t1, MGT_ACC_SML_COST t2
		WHERE	0=0
		AND	t1.CALC_NO = I_CALC_NO
		AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
		AND	(I_WG_CD IS NULL OR t1.WG_CD = I_WG_CD)
		AND	t1.CALC_REC_TYP = C_CALC_REC_END_WIP
		AND	t1.YM <= ADD_MONTHS(L_ARG.END_YM, -1)
		AND	t1.CALC_NO = t2.CALC_NO
		AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
		AND	t1.TOP_REC_NO = t2.TOP_REC_NO
		GROUP BY t1.WG_CD, ADD_MONTHS(t1.YM, 1), t1.MNG_DPT_CD,
			t1.LOC_CD, t1.STR_LN_CD,
			t1.OPER_CD, t1.OPER_SEQ,
			t2.EXPNS_CD
		UNION ALL
		-- 発生原価・製造品投入原価データの取得
		SELECT /*+USE_NL(t1 t2) INDEX(t1 MGT_ACC_TOP_ALL_IE01) INDEX(t2 MGT_ACC_COST_ALL_IE06)*/
			t1.WG_CD,
			t1.YM,
			t1.MNG_DPT_CD,
			t1.LOC_CD,
			t1.STR_LN_CD,
			t2.OPER_CD,
			t2.OPER_SEQ,
			t2.EXPNS_CD,
			0	ST_WIP_AMT,
			DECODE(t2.OPER_COST_FLG, '1', SUM(t2.ACT_COST), 0)	PROD_AMT,
			DECODE(t2.OPER_COST_FLG, '0', SUM(t2.ACT_COST), 0)	INPT_AMT,
			0	COMP_AMT,
			0	END_WIP_AMT
		FROM	MGT_ACC_TOP t1, MGT_ACC_COST t2
		WHERE	0=0
		AND	t1.CALC_NO = I_CALC_NO
		AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
		AND	(I_WG_CD IS NULL OR t1.WG_CD = I_WG_CD)
		AND	t1.CALC_REC_TYP = C_CALC_REC_INST
		AND	t1.CALC_NO = t2.CALC_NO
		AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
		AND	t1.TOP_REC_NO = t2.TOP_REC_NO
		GROUP BY t1.WG_CD, t1.YM, t1.MNG_DPT_CD,
			t1.LOC_CD, t1.STR_LN_CD,
			t2.OPER_CD, t2.OPER_SEQ,
			t2.OPER_COST_FLG,
			t2.EXPNS_CD
		) x
	WHERE	0=0
	GROUP BY x.WG_CD, x.YM, x.MNG_DPT_CD,
		x.LOC_CD, NVL(x.STR_LN_CD, C_NULL_VAL),
		x.OPER_CD, x.OPER_SEQ,
		x.EXPNS_CD
	;

	IF I_WG_CD IS NULL THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_WIP_LOC.P_MAIN') ;
	ELSE
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_WIP_LOC.P_MAIN - ' || I_WG_CD) ;
	END IF ;
END P_MAIN ;

END MGPA_WIP_LOC ;

/
show errors;


