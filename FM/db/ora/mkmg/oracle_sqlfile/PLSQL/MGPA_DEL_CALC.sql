PROCEDURE P_CHK_DEL
/*********************************************************
<SYNOPSIS>
	削除前チェック
<REMARKS>
	削除不可の場合はエラーを返す
<ARGUMENTS>

<HISTORY>
**********************************************************/
AS
BEGIN
	FOR x1 IN (
		SELECT	w.CALC_GRP_CD,
			w.CALC_NO
		FROM	MGW_DEL_CALC w
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_ACT_ALC_AMT x
				WHERE	0=0
				AND	x.TRD_CALC_GRP_CD = w.CALC_GRP_CD
				AND	x.TRD_CALC_NO = w.CALC_NO
			)
		)
	LOOP
		G_MSG := FCPA_ERR.MSG_BINDER(x1.CALC_GRP_CD, x1.CALC_NO) ;
		FCPA_ERR.RAISE_APP_ERR('MGBDD0010', G_MSG) ;
	END LOOP ;

	FOR x2 IN (
		SELECT	w.CALC_GRP_CD,
			w.CALC_NO
		FROM	MGW_DEL_CALC w
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_PLN_ALC_AMT x
				WHERE	0=0
				AND	x.TRD_CALC_GRP_CD = w.CALC_GRP_CD
				AND	x.TRD_CALC_NO = w.CALC_NO
			)
		)
	LOOP
		G_MSG := FCPA_ERR.MSG_BINDER(x2.CALC_GRP_CD, x2.CALC_NO) ;
		FCPA_ERR.RAISE_APP_ERR('MGBDD0010', G_MSG) ;
	END LOOP ;

	FOR x3 IN (
		SELECT	w.CALC_GRP_CD,
			w.CALC_NO
		FROM	MGW_DEL_CALC w
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_STD_ALC_RATE x
				WHERE	0=0
				AND	x.CALC_GRP_CD = w.CALC_GRP_CD
				AND	x.CALC_NO = w.CALC_NO
			)
		)
	LOOP
		G_MSG := FCPA_ERR.MSG_BINDER(x3.CALC_GRP_CD, x3.CALC_NO) ;
		FCPA_ERR.RAISE_APP_ERR('MGBDD0011', G_MSG) ;
	END LOOP ;

END P_CHK_DEL ;

PROCEDURE P_DEL_YM_NO
/*********************************************************
<SYNOPSIS>
	MGT_YM_NOの削除処理
<REMARKS>
	
<ARGUMENTS>

<HISTORY>
**********************************************************/
AS
BEGIN
	-- 削除対象のレコードにMGT_YM_NOが存在する場合はMGT_YM_NOを再作成する必要がある
	FOR x IN (
		SELECT	w.CALC_GRP_CD,
			w.CALC_NO,
			ADD_MONTHS(t.END_YM, -1)	YM
		FROM	MGW_DEL_CALC w, MGT_ARG t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGT_YM_NO x
				WHERE	0=0
				AND	x.CALC_GRP_CD = w.CALC_GRP_CD
				AND	x.CALC_NO = w.CALC_NO
				)
		AND	w.CALC_GRP_CD = t.CALC_GRP_CD
		AND	w.CALC_NO = t.CALC_NO
		ORDER BY w.CALC_GRP_CD, t.END_YM DESC, w.CALC_NO DESC
		)
	LOOP
		MGPA_CALC_FIX.P_REMAKE_YM_NO(x.CALC_GRP_CD, x.CALC_NO, x.YM) ;
	END LOOP ;

	DELETE MGT_YM_NO	t WHERE EXISTS (SELECT 'X' FROM MGW_DEL_CALC w WHERE w.CALC_GRP_CD = t.CALC_GRP_CD AND w.CALC_NO = t.CALC_NO) ;

END P_DEL_YM_NO ;

