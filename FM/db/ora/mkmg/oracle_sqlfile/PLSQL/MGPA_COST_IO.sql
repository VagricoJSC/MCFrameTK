		L_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, I_COST_IO_ID) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0023', L_MSG) ;
	END IF ;

	/*** 同一計算グループＣＤ、原価計算ＮＯ、受払表ＩＤのデータがあれば削除 ***/
	L_SQL := 'DELETE MGT_COST_IO' || I_COST_IO_ID || ' t WHERE t.CALC_NO = :data1 AND t.CALC_GRP_CD = :deta2' ;
	EXECUTE IMMEDIATE L_SQL USING I_CALC_NO, I_CALC_GRP_CD ;

	/*** 計算情報の取得 ***/
	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	IF L_ARG.COST_CALC_TYP NOT IN (MAC_COST_CALC_TYP.CALC_STK, MAC_COST_CALC_TYP.NOT_STK) THEN
		GOTO PROC_END ;
	END IF ;

	BEGIN
		SELECT	m.*
		INTO	L_IO_MST
		FROM	MAM_COST_IO m
		WHERE	0=0
		AND	m.COST_IO_ID = I_COST_IO_ID
		;
	EXCEPTION
	WHEN NO_DATA_FOUND THEN
		L_MSG := FCPA_ERR.MSG_BINDER(I_COST_IO_ID) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0021', L_MSG) ;
	END ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_COST_IO_CONF m
	WHERE	0=0
	AND	m.COST_IO_ID = I_COST_IO_ID
	;

