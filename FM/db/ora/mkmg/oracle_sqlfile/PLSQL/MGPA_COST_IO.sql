						)
					AND	(L_COST_IO_TYP = C_COST_IO_ONR_PROV OR L_ASST_TYP = C_ASST_OTH OR t1.REPURC_OBLI_FLG = '1')
					GROUP BY t1.TOP_REC_NO, t1.QTY
					) w
				WHERE	0=0
				;

				L_PROV_AMT_FLG := '0' ;
