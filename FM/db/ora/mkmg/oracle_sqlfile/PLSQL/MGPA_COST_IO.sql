			SELECT	NVL(SUM(w.QTY), 0)	QTY,
				NVL(SUM(w.ACT_AMT), 0)	ACT_AMT,
				NVL(SUM(w.STD_AMT), 0)	STD_AMT
			INTO	L_QTY, L_ACT, L_STD
			FROM	(
				SELECT	/*+USE_NL(t1 t2) INDEX(t1 MGT_ACC_TOP_ALL_IE02) INDEX(t2 MGT_ACC_SML_COST_ALL_IE01)*/
					t1.TOP_REC_NO,
					t1.QTY,
					NVL(SUM(DECODE(t2.EXPNS_TYP, C_EXPNS_PROD, t2.ACT_COST, L_EXPNS, t2.ACT_COST, 0)), 0) ACT_AMT,
					NVL(SUM(DECODE(t2.EXPNS_TYP, C_EXPNS_PROD, t2.STD_COST, L_EXPNS, t2.STD_COST, 0)), 0) STD_AMT
				FROM	MGT_ACC_TOP t1, MGT_ACC_SML_COST t2
				WHERE	0=0
