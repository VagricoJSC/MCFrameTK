		EXCEPTION
		WHEN LOCK_ERROR THEN
			L_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, I_CALC_NO) ;
			FCPA_ERR.RAISE_APP_ERR('MGBXD0009', L_MSG) ;
		END ;
	END IF ;

