			FROM	MAM_CALC_COST_IO m
			WHERE	0=0
			AND	m.CALC_GRP_CD = I_CALC_GRP_CD
			AND	m.COST_IO_ID = I_COST_IO_ID
			)
		LOOP
			L_CNT := 1 ;
		END LOOP ;
	ELSE
		BEGIN
			FOR x IN (
				SELECT	m.CALC_GRP_CD
				FROM	MAM_CALC_COST_IO m
				WHERE	0=0
				AND	m.CALC_GRP_CD = I_CALC_GRP_CD
				AND	m.COST_IO_ID = I_COST_IO_ID
				FOR UPDATE NOWAIT
				)
			LOOP
				L_CNT := 1 ;
