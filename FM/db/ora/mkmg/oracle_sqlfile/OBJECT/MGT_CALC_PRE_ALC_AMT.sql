CREATE OR REPLACE VIEW MGT_CALC_PRE_ALC_AMT(
	CALC_NO,
	CALC_GRP_CD,
	ALC_AMT_KEY,
	WG_CD,
	YM,
	ALC_AC_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	BP_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ITM_MFG_INST_NO,
	IV_NO,
	PO_NO,
	SLO_NO,
	AMT
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ALC_AMT_KEY,
	ORG.WG_CD,
	ORG.YM,
	ORG.ALC_AC_CD,
	ORG.DPT_CD,
	ORG.LOC_CD,
	ORG.OPER_CD,
	ORG.BP_CD,
	ORG.CTG_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.ITM_MFG_INST_NO,
	ORG.IV_NO,
	ORG.PO_NO,
	ORG.SLO_NO,
	ORG.AMT
FROM
	MGT_CALC_PRE_ALC_AMT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

