SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGT_USR_ITM(
	USR_CD,
	CALC_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3
	)
AS
SELECT
	ORG.USR_CD,
	ORG.CALC_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3
FROM
	MGT_USR_ITM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

