CREATE OR REPLACE VIEW MGT_CALC_ITM_PROC(
	CALC_NO,
	CALC_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SPPL_CD,
	WG_CD,
	BASE_QTY,
	CUR_CD,
	UPRI,
	BASE_CUR_UPRI,
	COST_RATIO,
	CALC_CTG_CD,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.SPPL_CD,
	ORG.WG_CD,
	ORG.BASE_QTY,
	ORG.CUR_CD,
	ORG.UPRI,
	ORG.BASE_CUR_UPRI,
	ORG.COST_RATIO,
	ORG.CALC_CTG_CD,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3
FROM
	MGT_CALC_ITM_PROC_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

