CREATE OR REPLACE VIEW MGT_CALC_RQMT_$S(
	CALC_NO,
	CALC_GRP_CD,
	WG_CD,
	YM,
	MNG_DPT_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ASST_TYP,
	QTY
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.WG_CD,
	ORG.YM,
	ORG.MNG_DPT_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.ASST_TYP,
	ORG.QTY
FROM
	MGT_CALC_RQMT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

