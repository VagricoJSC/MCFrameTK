CREATE OR REPLACE VIEW MGT_ITM_PROV_$U(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	PRSPPL_CD,
	TERM,
	CALC_CTG_CD,
	WG_CD,
	PROV_TYP,
	BASE_QTY,
	CUR_CD,
	UPRI,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	NON_CALC_FLG,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.PRSPPL_CD,
	ORG.TERM,
	ORG.CALC_CTG_CD,
	ORG.WG_CD,
	ORG.PROV_TYP,
	ORG.BASE_QTY,
	ORG.CUR_CD,
	ORG.UPRI,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.NON_CALC_FLG,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_ITM_PROV_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

