CREATE OR REPLACE VIEW MGT_ACT_PTN_CONFIG(
	ACT_PTN_CD,
	CALC_ACT_SEQ,
	TERM,
	CALC_GRP_CD,
	ST_YM,
	END_YM,
	XRATE_CD,
	CARRY_FLG,
	ERR_PROCEED_FLG,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ACT_PTN_CD,
	ORG.CALC_ACT_SEQ,
	ORG.TERM,
	ORG.CALC_GRP_CD,
	ORG.ST_YM,
	ORG.END_YM,
	ORG.XRATE_CD,
	ORG.CARRY_FLG,
	ORG.ERR_PROCEED_FLG,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_ACT_PTN_CONFIG_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

