CREATE OR REPLACE VIEW MGT_CALC_OTHER_WK(
	CALC_NO,
	CALC_GRP_CD,
	WG_CD,
	YM,
	AC_DT,
	DPT_CD,
	CTG_CD,
	LOC_CD,
	OPER_CD,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	WK_COST_CD,
	WK_RSN_CD,
	WK_COST
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.WG_CD,
	ORG.YM,
	ORG.AC_DT,
	ORG.DPT_CD,
	ORG.CTG_CD,
	ORG.LOC_CD,
	ORG.OPER_CD,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.WK_COST_CD,
	ORG.WK_RSN_CD,
	ORG.WK_COST
FROM
	MGT_CALC_OTHER_WK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

