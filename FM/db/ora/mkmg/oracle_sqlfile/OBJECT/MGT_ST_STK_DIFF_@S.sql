CREATE OR REPLACE VIEW MGT_ST_STK_DIFF_$S(
	ST_STK_KEY,
	EXPNS_CD,
	DIFF_AMT,
	BF_AMT,
	AF_AMT,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ST_STK_KEY,
	ORG.EXPNS_CD,
	ORG.DIFF_AMT,
	ORG.BF_AMT,
	ORG.AF_AMT,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_ST_STK_DIFF_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

