SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.INPT_ALC_TYP,
	ORG.WG_CD,
	ORG.YM,
	ORG.ALC_AC_CD,
	ORG.DPT_CD,
	ORG.LOC_CD,
	ORG.OPER_CD,
	ORG.BP_CD,
	ORG.CTG_CD,
