	CALC_NO,
	CALC_GRP_CD,
	INPT_ALC_TYP,
	WG_CD,
	YM,
	ALC_AC_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	BP_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ITM_MFG_INST_NO,
	IV_NO,
	PO_NO,
	SLO_NO,
	AMT,
	EXPNS_CD,
	ALC_PTN_CD,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
