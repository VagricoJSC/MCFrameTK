	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.ITM_MFG_INST_NO,
