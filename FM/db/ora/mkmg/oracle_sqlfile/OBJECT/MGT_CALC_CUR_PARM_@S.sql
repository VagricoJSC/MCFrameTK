CREATE OR REPLACE VIEW MGT_CALC_CUR_PARM_$S(
	CALC_NO,
	CALC_GRP_CD,
	CUR_CD,
	AMT_RND_TYP,
	AMT_DEC_PLACE,
	AVE_RND_TYP,
	AVE_DEC_PLACE
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.CUR_CD,
	ORG.AMT_RND_TYP,
	ORG.AMT_DEC_PLACE,
	ORG.AVE_RND_TYP,
	ORG.AVE_DEC_PLACE
FROM
	MGT_CALC_CUR_PARM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

