CREATE OR REPLACE VIEW MGT_CALC_INST_WIP_$U(
	CALC_NO,
	CALC_GRP_CD,
	WG_CD,
	YM,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	ITM_MFG_INST_NO,
	MFG_ACT_NO,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	LOC_CD,
	STR_LN_CD,
	AC_RSN_CD,
	WIP_QTY,
	WIP_PER
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.WG_CD,
	ORG.YM,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_EXT,
	ORG.ITM_MFG_INST_NO,
	ORG.MFG_ACT_NO,
	ORG.OPER_ACT_NO,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.LOC_CD,
	ORG.STR_LN_CD,
	ORG.AC_RSN_CD,
	ORG.WIP_QTY,
	ORG.WIP_PER
FROM
	MGT_CALC_INST_WIP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

