CREATE OR REPLACE VIEW MGT_CALC_MFG(
	CALC_NO,
	CALC_GRP_CD,
	WG_CD,
	YM,
	AC_DT,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	ITM_MFG_INST_NO,
	MFG_ACT_NO,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	LOC_CD,
	STR_LN_CD,
	AC_SLIP_TYP,
	AC_RSN_CD,
	EXPNS_CD,
	ASST_TYP,
	MNG_DPT_CD,
	CUR_CD,
	XRATE,
	QTY,
	AMT,
	CUR_AMT,
	MFG_PER,
	MFG_COST_RATIO,
	ALC_VAL1,
	ALC_VAL2,
	ALC_VAL3,
	ALC_VAL4,
	ALC_VAL5
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.WG_CD,
	ORG.YM,
	ORG.AC_DT,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_EXT,
	ORG.ITM_MFG_INST_NO,
	ORG.MFG_ACT_NO,
	ORG.OPER_ACT_NO,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.LOC_CD,
	ORG.STR_LN_CD,
	ORG.AC_SLIP_TYP,
	ORG.AC_RSN_CD,
	ORG.EXPNS_CD,
	ORG.ASST_TYP,
	ORG.MNG_DPT_CD,
	ORG.CUR_CD,
	ORG.XRATE,
	ORG.QTY,
	ORG.AMT,
	ORG.CUR_AMT,
	ORG.MFG_PER,
	ORG.MFG_COST_RATIO,
	ORG.ALC_VAL1,
	ORG.ALC_VAL2,
	ORG.ALC_VAL3,
	ORG.ALC_VAL4,
	ORG.ALC_VAL5
FROM
	MGT_CALC_MFG_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

