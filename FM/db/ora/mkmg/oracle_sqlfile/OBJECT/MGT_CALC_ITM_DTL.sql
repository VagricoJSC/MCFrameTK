CREATE OR REPLACE VIEW MGT_CALC_ITM_DTL(
	CALC_NO,
	CALC_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	SPPL_CD,
	RQST_WG_CD,
	WG_CD,
	COST_RATIO,
	OPER_PTN,
	BOM_PTN,
	MIN_LOT_QTY,
	BATCH_LOT_QTY,
	FXD_LOT_QTY,
	FXD_YIELD_QTY,
	NMR_QTY,
	DNM_QTY,
	ALC_DPT_CD,
	EXP_DPT_CD,
	EXP_PRIO,
	MAX_QTY,
	ALC_VAL1,
	ALC_VAL2,
	ALC_VAL3,
	ALC_VAL4,
	ALC_VAL5,
	CALC_CTG_CD,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOC_CD,
	ORG.SPPL_CD,
	ORG.RQST_WG_CD,
	ORG.WG_CD,
	ORG.COST_RATIO,
	ORG.OPER_PTN,
	ORG.BOM_PTN,
	ORG.MIN_LOT_QTY,
	ORG.BATCH_LOT_QTY,
	ORG.FXD_LOT_QTY,
	ORG.FXD_YIELD_QTY,
	ORG.NMR_QTY,
	ORG.DNM_QTY,
	ORG.ALC_DPT_CD,
	ORG.EXP_DPT_CD,
	ORG.EXP_PRIO,
	ORG.MAX_QTY,
	ORG.ALC_VAL1,
	ORG.ALC_VAL2,
	ORG.ALC_VAL3,
	ORG.ALC_VAL4,
	ORG.ALC_VAL5,
	ORG.CALC_CTG_CD,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3
FROM
	MGT_CALC_ITM_DTL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

