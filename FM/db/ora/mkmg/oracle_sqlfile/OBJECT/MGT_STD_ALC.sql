CREATE OR REPLACE VIEW MGT_STD_ALC(
	CALC_NO,
	CALC_GRP_CD,
	TOP_REC_NO,
	ALC_AC_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	BP_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	WG_CD,
	ALC_TGT_VAL,
	ALC_RATE,
	ALC_AMT,
	COEF_VAL,
	ALC_ORG_TGT_VAL,
	EXPNS_CD,
	ALC_PTN_CD,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.TOP_REC_NO,
	ORG.ALC_AC_CD,
	ORG.DPT_CD,
	ORG.LOC_CD,
	ORG.OPER_CD,
	ORG.BP_CD,
	ORG.CTG_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.WG_CD,
	ORG.ALC_TGT_VAL,
	ORG.ALC_RATE,
	ORG.ALC_AMT,
	ORG.COEF_VAL,
	ORG.ALC_ORG_TGT_VAL,
	ORG.EXPNS_CD,
	ORG.ALC_PTN_CD,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_STD_ALC_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

