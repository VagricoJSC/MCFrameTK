CREATE OR REPLACE VIEW MGT_STD_INPT_$U(
	CALC_NO,
	CALC_GRP_CD,
	INPT_REC_NO,
	TOP_REC_NO,
	LVL,
	WG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	MFG_PURC_TYP,
	OPER_CD,
	OPER_SEQ,
	DISP_SEQ,
	LOC_CD,
	SPPL_CD,
	PROV_TYP,
	STD_QTY,
	THE_QTY,
	REQ_QTY,
	BOTTOM_FLG,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.INPT_REC_NO,
	ORG.TOP_REC_NO,
	ORG.LVL,
	ORG.WG_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.MFG_PURC_TYP,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.DISP_SEQ,
	ORG.LOC_CD,
	ORG.SPPL_CD,
	ORG.PROV_TYP,
	ORG.STD_QTY,
	ORG.THE_QTY,
	ORG.REQ_QTY,
	ORG.BOTTOM_FLG,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_STD_INPT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

