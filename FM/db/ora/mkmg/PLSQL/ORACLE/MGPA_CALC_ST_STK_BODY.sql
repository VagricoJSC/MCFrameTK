CREATE OR REPLACE PACKAGE BODY MGPA_CALC_ST_STK
IS
	G_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;
	G_MSG		FCPA_ERR.MSG_BINDER ;
	G_LOG_NO	MAPA_META.BATCH_LOG_NO%TYPE ;
	G_LOG_SUB_KEY1	MAPA_META.BATCH_LOG_SUB_KEY1%TYPE ;
	G_LOG_SUB_KEY2	MAPA_META.BATCH_LOG_SUB_KEY2%TYPE ;

	C_RND_TYP	CONSTANT MAPA_META.RND_TYP%TYPE := MAC_RND_TYP.RNDOFF ; -- 四捨五入

	C_EXPNS_PROD	CONSTANT MAPA_META.EXPNS_TYP%TYPE := MAC_EXPNS_TYP.PROD ;
	C_EXPNS_SGA	CONSTANT MAPA_META.EXPNS_TYP%TYPE := MAC_EXPNS_TYP.SGA ;
	C_EXPNS_SPPL	CONSTANT MAPA_META.EXPNS_TYP%TYPE := MAC_EXPNS_TYP.SPPL ;

	C_ASST_OTH	CONSTANT MAPA_META.ASST_TYP%TYPE := MAC_ASST_TYP.OTH ;

PROCEDURE P_SET_ITM (
	I_CALC_GRP	MAPA_META.CALC_GRP_CD%TYPE,
	I_TERM		MAPA_META.YM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	対象品目設定処理
<REMARKS>
	対象となる確定されている品目をMGW_FIX_ITMに書き込む
<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_TERM
		期
<HISTORY>
**************************************************************************/
IS
	L_CNT		NUMBER ;
	L_PARM	MAPA_META.PARM_VAL%TYPE ;
	L_CALC_GRP	MAM_CALC_GRP%ROWTYPE ;

	CURSOR CTG_LIST
	IS
		SELECT	w.CALC_CTG_CD
		FROM	MGW_CALC_CTG w
		WHERE	0=0
		ORDER BY w.CTG_PRIO, w.CALC_CTG_CD
	;
BEGIN
	DELETE MAW_GRP_WG_KEY ;
	L_CALC_GRP := MGPA_CALC_GRP.F_GET_REC(I_CALC_GRP) ;
	IF L_CALC_GRP.RUNTIME_WG_CD IS NULL THEN
		INSERT INTO MAW_GRP_WG_KEY
		SELECT m.CALC_GRP_CD, m.WG_CD FROM MAM_GRP_WG m WHERE m.CALC_GRP_CD = I_CALC_GRP ;
	ELSE
		INSERT INTO MAW_GRP_WG_KEY VALUES (I_CALC_GRP, L_CALC_GRP.RUNTIME_WG_CD) ;
	END IF ;

	DELETE MGW_FIX_ITM ;
	MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP, MAC_CALC_CTG_TYP.CALC_ITM) ;
	FOR x IN CTG_LIST LOOP
		INSERT INTO MGW_FIX_ITM (
			ITM_CD,
			ITM_SUB1,
			ITM_SUB2,
			ITM_SUB3,
			WG_CD,
			CALC_CTG_CD,
			STD_QTY
			)
		SELECT	t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.WG_CD,
			t.CALC_CTG_CD,
			t.STD_QTY
		FROM	MGT_STD_FIX t, MAW_GRP_WG_KEY m
		WHERE	0=0
		AND	t.TERM = I_TERM
		AND	t.CALC_CTG_CD = x.CALC_CTG_CD
		AND	m.CALC_GRP_CD = I_CALC_GRP
		AND	m.WG_CD = t.WG_CD
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_FIX_ITM w
				WHERE	0=0
				AND	w.ITM_CD = t.ITM_CD
				AND	w.ITM_SUB1 = t.ITM_SUB1
				AND	w.ITM_SUB2 = t.ITM_SUB2
				AND	w.ITM_SUB3 = t.ITM_SUB3
				AND	w.WG_CD = t.WG_CD
			)
		;
	END LOOP ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGW_FIX_ITM w
	;

	IF L_CNT = 0 THEN
		FCPA_ERR.RAISE_APP_ERR('MGBBD0002') ;
	END IF ;

	L_PARM := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;

	/*** 確定品目のチェック ***/
	L_CNT := 0 ;
	FOR y IN (
		SELECT	t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.WG_CD
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ST_STK_KEY w
				WHERE	0=0
				AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_FIX_ITM w
				WHERE	0=0
				AND	t.ITM_CD = w.ITM_CD
				AND	t.ITM_SUB1 = w.ITM_SUB1
				AND	t.ITM_SUB2 = w.ITM_SUB2
				AND	t.ITM_SUB3 = w.ITM_SUB3
				AND	t.WG_CD = w.WG_CD
			)
		)
	LOOP
		L_CNT := L_CNT + 1 ;
		FCPA_BATCH_LOG.P_DATA_LOG('MGBXD0015',
				G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2,
				FCPA_DATE_UTIL.F_TO_CHAR(I_TERM, FCPA_DATE_UTIL.Y4M),
				MAPA_COMM.F_TO_DISP_ITM(y.ITM_CD, y.ITM_SUB1, y.ITM_SUB2, y.ITM_SUB3, L_PARM),
				y.WG_CD
				) ;
	END LOOP ;

	IF L_CNT > 0 THEN
		FCPA_ERR.RAISE_APP_ERR('MGBBD0003') ;
	END IF ;

END P_SET_ITM ;

PROCEDURE P_MAIN
/**************************************************************************
<SYNOPSIS>
	月初在庫評価替メイン処理
<REMARKS>
	MGW_ST_STK_KEYに対象となるデータを設定しておく必要がある
	評価替差異はMGT_ST_STK_DIFFに書き込む
<ARGUMENTS>

<HISTORY>
**************************************************************************/
IS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	L_CALC_GRP	MAPA_META.CALC_GRP_CD%TYPE ;
	L_YM		MAPA_META.YM%TYPE ;
	L_TERM		MAPA_META.YM%TYPE ;

	L_DIGIT		NUMBER ;
	L_CNT		NUMBER ;

	L_CO_PARM	MAM_CO_PARM%ROWTYPE ;

	L_AF_AMT	MAPA_META.MONEY%TYPE ;

	TYPE LIST_DIFF IS TABLE OF MGT_ST_STK_DIFF%ROWTYPE INDEX BY BINARY_INTEGER ;
	rec 	LIST_DIFF ;
	i	INTEGER := 0 ;

	CURSOR LOCK_STK IS
		SELECT	t.ITM_CD
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ST_STK_KEY w
				WHERE	0=0
				AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
		FOR UPDATE NOWAIT
	;

	L_TQA		MAPA_META.FLG%TYPE ;
	L_SUM_AMT	MAPA_META.MONEY%TYPE ;
	L_STD_AMT	MAPA_META.MONEY%TYPE ;

BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_CALC_ST_STK.P_MAIN') ;

	/***他社資産は除く***/
	DELETE	MGW_ST_STK_KEY w
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGT_ST_STK t
			WHERE	0=0
			AND	t.ST_STK_KEY = w.ST_STK_KEY
			AND	(t.ASST_TYP = C_ASST_OTH OR t.REPURC_OBLI_FLG = '1')
		)
	;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_ST_STK t
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_ST_STK_KEY w
			WHERE	0=0
			AND	w.ST_STK_KEY = t.ST_STK_KEY
		)
	;

	IF L_CNT = 0 THEN
		GOTO PROC_END ;
	END IF ;

	BEGIN
		SELECT	DISTINCT
			t.CALC_GRP_CD, t.YM
		INTO	L_CALC_GRP, L_YM
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ST_STK_KEY w
				WHERE	0=0
				AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
		;
	EXCEPTION
	WHEN TOO_MANY_ROWS THEN
		FCPA_ERR.RAISE_APP_ERR('MGBBD0001') ;
	END ;

	/***ロック***/
	BEGIN
		OPEN LOCK_STK ;
		CLOSE LOCK_STK ;
	EXCEPTION
	WHEN LOCK_ERROR THEN
		G_MSG := FCPA_ERR.MSG_BINDER(L_CALC_GRP, FCPA_DATE_UTIL.F_TO_CHAR(L_YM, FCPA_DATE_UTIL.Y4M)) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0010', G_MSG) ;
	END ;

	/*** 対象年月に対する確定状況の確認 ***/
	MGPA_CALC_FIX.P_CHK_FIX(L_CALC_GRP, L_YM) ;

	L_TERM := MAPA_TERM.F_GET_TERM(L_YM) ;

	/*** 対象となる確定品目のセット ***/
	P_SET_ITM(L_CALC_GRP, L_TERM) ;

	/*** 原価計算と同じ桁数で端数処理を行う ***/
	SELECT	NVL(MIN(m.PARM_VAL), 8)
	INTO	L_DIGIT
	FROM	MGT_PARM m
	WHERE	0=0
	AND	m.CALC_GRP_CD = L_CALC_GRP
	AND	m.PARM_KEY = 'SCA_PREC_COST'
	;

	L_TQA := '0' ;
	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_PARM m
	WHERE	0=0
	AND	m.CALC_GRP_CD = L_CALC_GRP
	AND	m.PARM_KEY = 'SCA_TQA'
	AND	m.PARM_VAL IS NOT NULL
	AND	m.PARM_VAL != '0'
	AND	m.PARM_VAL != 'NO'
	;

	IF L_CNT > 0 THEN
		L_TQA := '1' ;
	END IF ;

	L_CO_PARM := MGPA_CO_PARM.F_GET_REC() ;

	/*** 評価替前のデータを作成する ***/
	DELETE MGW_ST_STK_DIFF ;
	INSERT INTO MGW_ST_STK_DIFF (
		ST_STK_KEY,
		EXPNS_CD,
		DIFF_AMT,
		BF_AMT,
		AF_AMT
		)
	SELECT	t.ST_STK_KEY,
		t.EXPNS_CD,
		0,
		t.AMT,
		0
	FROM	MGT_ST_STK_EXPNS t
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_ST_STK_KEY w
			WHERE	0=0
			AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
	AND	t.AMT != 0
	;

	--製造・売上原価費目以外のデータは削除
	DELETE	MGW_ST_STK_DIFF w
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MAM_EXPNS x
			WHERE	0=0
			AND	x.EXPNS_CD = w.EXPNS_CD
			AND	x.EXPNS_TYP IN (C_EXPNS_SGA, C_EXPNS_SPPL)
		)
	;

	FOR x IN (
		SELECT	t.ST_STK_KEY,
			t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.WG_CD,
			t.QTY
		FROM	MGT_ST_STK t
		WHERE	0=0
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ST_STK_KEY w
				WHERE	0=0
				AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
		)
	LOOP

		FOR y IN (
			SELECT	w.CALC_CTG_CD,
					w.STD_QTY
			FROM	MGW_FIX_ITM w
			WHERE	0=0
			AND	w.ITM_CD = x.ITM_CD
			AND	w.ITM_SUB1 = x.ITM_SUB1
			AND	w.ITM_SUB2 = x.ITM_SUB2
			AND	w.ITM_SUB3 = x.ITM_SUB3
			AND	w.WG_CD = x.WG_CD
			)
		LOOP
			MERGE INTO MGW_ST_STK_DIFF t
			USING	(
				SELECT	t3.EXPNS_CD,
					SUM(t3.STD_COST)	AMT
				FROM	MGT_STD_FIX t1, MGT_STD_TOP t2, MGT_STD_SML_COST t3
				WHERE	0=0
				AND	t1.ITM_CD = x.ITM_CD
				AND	t1.ITM_SUB1 = x.ITM_SUB1
				AND	t1.ITM_SUB2 = x.ITM_SUB2
				AND	t1.ITM_SUB3 = x.ITM_SUB3
				AND	t1.CALC_CTG_CD = y.CALC_CTG_CD
				AND	t1.TERM = L_TERM
				AND	t1.WG_CD = x.WG_CD
				AND	t1.ITM_CD = t2.ITM_CD
				AND	t1.ITM_SUB1 = t2.ITM_SUB1
				AND	t1.ITM_SUB2 = t2.ITM_SUB2
				AND	t1.ITM_SUB3 = t2.ITM_SUB3
				AND	t1.WG_CD = t2.WG_CD
				AND	t1.CALC_NO = t2.CALC_NO
				AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
				AND	t2.SLS_FLG = '0'
				AND	t2.CALC_NO = t3.CALC_NO
				AND	t2.CALC_GRP_CD = t3.CALC_GRP_CD
				AND	t2.TOP_REC_NO = t3.TOP_REC_NO
				AND	t3.EXPNS_TYP = C_EXPNS_PROD
				AND	t3.STD_COST != 0
				GROUP BY t3.EXPNS_CD
				) w
			ON	(0=0
				AND	t.ST_STK_KEY = x.ST_STK_KEY
				AND	t.EXPNS_CD = w.EXPNS_CD
				)
			WHEN MATCHED THEN
				UPDATE
				SET	t.AF_AMT = t.AF_AMT +
						MAPA_CALC.F_RND(
							MAPA_CALC.F_RND(x.QTY * w.AMT / y.STD_QTY, L_DIGIT, C_RND_TYP),
							L_CO_PARM.AMT_DEC_PLACE,
							L_CO_PARM.AMT_RND_TYP)
			WHEN NOT MATCHED THEN
				INSERT (
					ST_STK_KEY,
					EXPNS_CD,
					DIFF_AMT,
					BF_AMT,
					AF_AMT
					)
				VALUES	(
					x.ST_STK_KEY,
					w.EXPNS_CD,
					0,
					0,
					MAPA_CALC.F_RND(
						MAPA_CALC.F_RND(x.QTY * w.AMT / y.STD_QTY, L_DIGIT, C_RND_TYP),
						L_CO_PARM.AMT_DEC_PLACE,
						L_CO_PARM.AMT_RND_TYP)
					)
			;

			IF L_TQA = '1' THEN
				SELECT	NVL(SUM(w.AF_AMT), 0)
				INTO	L_SUM_AMT
				FROM	MGW_ST_STK_DIFF w
				WHERE	0=0
				AND	ST_STK_KEY = x.ST_STK_KEY
				;

				SELECT	MAPA_CALC.F_RND(
						SUM(t3.STD_COST) * x.QTY / y.STD_QTY,
						L_CO_PARM.AMT_DEC_PLACE,
						L_CO_PARM.AMT_RND_TYP
						)
				INTO	L_STD_AMT
				FROM	MGT_STD_FIX t1, MGT_STD_TOP t2, MGT_STD_SML_COST t3
				WHERE	0=0
				AND	t1.ITM_CD = x.ITM_CD
				AND	t1.ITM_SUB1 = x.ITM_SUB1
				AND	t1.ITM_SUB2 = x.ITM_SUB2
				AND	t1.ITM_SUB3 = x.ITM_SUB3
				AND	t1.CALC_CTG_CD = y.CALC_CTG_CD
				AND	t1.WG_CD = x.WG_CD
				AND	t1.TERM = L_TERM
				AND	t1.ITM_CD = t2.ITM_CD
				AND	t1.ITM_SUB1 = t2.ITM_SUB1
				AND	t1.ITM_SUB2 = t2.ITM_SUB2
				AND	t1.ITM_SUB3 = t2.ITM_SUB3
				AND	t1.WG_CD = t2.WG_CD
				AND	t1.CALC_NO = t2.CALC_NO
				AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
				AND	t2.SLS_FLG = '0'
				AND	t2.CALC_NO = t3.CALC_NO
				AND	t2.CALC_GRP_CD = t3.CALC_GRP_CD
				AND	t2.TOP_REC_NO = t3.TOP_REC_NO
				AND	t3.EXPNS_TYP = C_EXPNS_PROD
				AND	t3.STD_COST != 0
				;

				IF L_STD_AMT != L_SUM_AMT THEN
					MERGE INTO MGW_ST_STK_DIFF t
					USING	(
						SELECT	L_CO_PARM.MRGN_EXPNS_CD	EXPNS_CD
						FROM	DUAL
						) w
					ON	(0=0
						AND	t.ST_STK_KEY = x.ST_STK_KEY
						AND	t.EXPNS_CD = w.EXPNS_CD
						)
					WHEN MATCHED THEN
						UPDATE
						SET	t.AF_AMT = t.AF_AMT + L_STD_AMT - L_SUM_AMT
					WHEN NOT MATCHED THEN
						INSERT (
							ST_STK_KEY,
							EXPNS_CD,
							DIFF_AMT,
							BF_AMT,
							AF_AMT
							)
						VALUES	(
							x.ST_STK_KEY,
							w.EXPNS_CD,
							0,
							0,
							L_STD_AMT - L_SUM_AMT
							)
					;
				END IF ;
			END IF ;
		END LOOP ;
	END LOOP ;

	DELETE	MGW_ST_STK_DIFF w
	WHERE	0=0
	AND	w.AF_AMT = 0
	AND	w.BF_AMT = 0
	;

	MERGE INTO MGT_ST_STK_DIFF t
	USING	(
		SELECT	w.*
		FROM	MGW_ST_STK_DIFF w
		WHERE	0=0
		) x
	ON	(0=0
		AND	t.ST_STK_KEY = x.ST_STK_KEY
		AND	t.EXPNS_CD = x.EXPNS_CD
		)
	WHEN MATCHED THEN
		UPDATE
		SET	t.DIFF_AMT = x.AF_AMT - t.BF_AMT,
			t.AF_AMT = x.AF_AMT
	WHEN NOT MATCHED THEN
		INSERT (
			ST_STK_KEY,
			EXPNS_CD,
			DIFF_AMT,
			BF_AMT,
			AF_AMT
			)
		VALUES	(
			x.ST_STK_KEY,
			x.EXPNS_CD,
			x.AF_AMT - x.BF_AMT,
			x.BF_AMT,
			x.AF_AMT
			)
	;

	/*** 月初在庫費目情報の再作成 ***/
	DELETE	MGT_ST_STK_EXPNS t
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_ST_STK_KEY w
			WHERE	0=0
			AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
	;

	INSERT INTO MGT_ST_STK_EXPNS (
		ST_STK_KEY,
		EXPNS_CD,
		AMT
		)
	SELECT	w.ST_STK_KEY,
		w.EXPNS_CD,
		w.AF_AMT
	FROM	MGW_ST_STK_DIFF w
	WHERE	0=0
	AND	w.AF_AMT != 0
	;

	/*** 標準評価後ＦＬＧの更新 ***/
	UPDATE	MGT_ST_STK t
	SET	t.STD_FLG = '1'
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_ST_STK_KEY w
			WHERE	0=0
			AND	w.ST_STK_KEY = t.ST_STK_KEY
			)
	;

	<<PROC_END>>
		NULL ;

	DELETE MGW_ST_STK_KEY ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_CALC_ST_STK.P_MAIN') ;

END P_MAIN ;

END MGPA_CALC_ST_STK ;
