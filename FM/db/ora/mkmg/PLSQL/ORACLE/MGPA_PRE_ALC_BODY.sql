			AND	m.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
			)
		LOOP
			RATE_MST(I_PRE_ALC_RATE_CD) := x ;
			RETURN x ;
		END LOOP ;
	END IF ;

	G_MSG := FCPA_ERR.MSG_BINDER(I_PRE_ALC_RATE_CD) ;
	FCPA_ERR.RAISE_APP_ERR('MGBXD0045', G_MSG) ;

END F_GET_PRE_ALC_RATE ;


