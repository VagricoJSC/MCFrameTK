FUNCTION F_GET_PRE_ALC_RATE (
	I_PRE_ALC_RATE_CD	IN MAPA_META.PRE_ALC_RATE_CD%TYPE
)
RETURN MAM_PRE_ALC_RATE%ROWTYPE
/**************************************************************************
<SYNOPSIS>
	対象となる一次配賦基準マスタのレコードを返す
<REMARKS>

<ARGUMENTS>
<IN>	I_PRE_ALC_RATE_CD
		一次配賦基準ＣＤ
<RETURNVALUE>
	対象となるMAM_PRE_ALC_RATEのレコード
<HISTORY>
**************************************************************************/
AS
BEGIN
	IF RATE_MST.EXISTS(I_PRE_ALC_RATE_CD) THEN
		RETURN RATE_MST(I_PRE_ALC_RATE_CD) ;
	ELSE
