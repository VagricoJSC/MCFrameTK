	G_PRE_ALC_NON	CONSTANT MAPA_META.PRE_ALC_CALC_TYP%TYPE := MAC_PRE_ALC_CALC_TYP.NON ;
	G_PRE_ALC_CALC	CONSTANT MAPA_META.PRE_ALC_CALC_TYP%TYPE := MAC_PRE_ALC_CALC_TYP.CALC ;

	G_ALC_NON	CONSTANT MAPA_META.ALC_CALC_TYP%TYPE := MAC_ALC_CALC_TYP.NON ;
