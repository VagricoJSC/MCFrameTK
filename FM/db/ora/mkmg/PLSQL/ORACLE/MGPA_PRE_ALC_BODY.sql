	;

	CURSOR SEL_LIST (
		CI_WG_CD	IN MAPA_META.WG_CD%TYPE,
		CI_ALC_AC_CD	IN MAPA_META.ALC_AC_CD%TYPE,
		CI_DPT_CD	IN MAPA_META.COST_DPT_CD%TYPE
		)
	IS
		SELECT	m.PRE_ALC_RATE_CD,
			m.TRD_ALC_AC_CD,
			m.TRD_WG_CD,
			m.PRE_ALC_DPT_PTN,
			m.FIN_FLG
		FROM	MGW_PRE_ALC_RATE_SEL m
		WHERE	0=0
		AND	m.WG_CD = CI_WG_CD
		AND	m.ALC_AC_CD = CI_ALC_AC_CD
		AND	m.DPT_CD = CI_DPT_CD
	;

	G_ALC_DEF	SEL_LIST%ROWTYPE ;

	TYPE ITM_ALC_LIST IS TABLE OF MGW_ALC_AMT%ROWTYPE INDEX BY BINARY_INTEGER ;
	ITM_ALC 	ITM_ALC_LIST ;
	w1		BINARY_INTEGER ;

	TYPE PRE_ALC_LIST IS TABLE OF MGT_CALC_PRE_ALC_AMT%ROWTYPE INDEX BY BINARY_INTEGER ;
	PRE_ALC		PRE_ALC_LIST ;
	w2		BINARY_INTEGER ;

	TYPE PRE_ALC_RATE_LIST IS TABLE OF MAM_PRE_ALC_RATE%ROWTYPE INDEX BY MAPA_META.PRE_ALC_RATE_CD%TYPE ;
	RATE_MST	PRE_ALC_RATE_LIST ;

	TYPE PRE_ALC_PTN_LIST IS TABLE OF MAM_PRE_ALC_PTN%ROWTYPE INDEX BY MAPA_META.PRE_ALC_PTN_CD%TYPE ;
	PTN_MST		PRE_ALC_PTN_LIST ;

	TYPE PATH_LIST IS TABLE OF MGT_PRE_ALC_PATH%ROWTYPE INDEX BY BINARY_INTEGER ;
	ALC_TGT		PATH_LIST ;
	TYPE LIST_G_ALC_DEF IS TABLE OF SEL_LIST%ROWTYPE INDEX BY MAPA_META.WG_CD%TYPE ;
	G_ALC_DEF_REC	LIST_G_ALC_DEF ;

FUNCTION F_GET_ALC_RATE_SEL (
	I_WG_CD		IN MAPA_META.WG_CD%TYPE,
	I_ALC_AC_CD	IN MAPA_META.ALC_AC_CD%TYPE,
	I_DPT_CD	IN MAPA_META.COST_DPT_CD%TYPE
)
RETURN SEL_LIST%ROWTYPE
/**************************************************************************
<SYNOPSIS>
	対象となる一次配賦基準選択マスタのレコードを返す
<REMARKS>
	対象となるレコードが存在しないときは一次配賦基準ＣＤに
	ＮＵＬＬ文字をセットしたレコードを返す
<ARGUMENTS>
<IN>	I_WG_CD
		ワーキンググループＣＤ
<IN>	I_ALC_AC_CD
		配賦科目ＣＤ
<IN>	I_DPT_CD
		部門ＣＤ
<RETURNVALUE>
	対象となるMAM_PRE_ALC_RATE_SELのレコード
<HISTORY>
**************************************************************************/
AS
	L_NULL_ALC_AC	CONSTANT MAPA_META.ALC_AC_CD%TYPE := MAC_STR.NULL_VAL ;
	L_NULL_DPT	CONSTANT MAPA_META.COST_DPT_CD%TYPE := MAC_STR.NULL_VAL ;
BEGIN

	FOR x1 IN SEL_LIST(I_WG_CD, I_ALC_AC_CD, I_DPT_CD) LOOP
		RETURN x1 ;
	END LOOP ;

	FOR x2 IN SEL_LIST(I_WG_CD, I_ALC_AC_CD, L_NULL_DPT) LOOP
		RETURN x2 ;
	END LOOP ;

	FOR x3 IN SEL_LIST(I_WG_CD, L_NULL_ALC_AC, I_DPT_CD) LOOP
		RETURN x3 ;
	END LOOP ;

	IF G_ALC_DEF_REC.EXISTS(I_WG_CD) THEN
		RETURN G_ALC_DEF_REC(I_WG_CD) ;
	ELSE
		G_ALC_DEF.PRE_ALC_RATE_CD := NULL ;
		FOR x4 IN SEL_LIST(I_WG_CD, L_NULL_ALC_AC, L_NULL_DPT) LOOP
			G_ALC_DEF := x4 ;
		END LOOP ;
		IF G_ALC_DEF.PRE_ALC_RATE_CD IS NULL THEN
			G_ALC_DEF.PRE_ALC_RATE_CD := G_NULL_VAL ;
		END IF ;
	END IF ;
	G_ALC_DEF_REC(I_WG_CD) := G_ALC_DEF ;

	RETURN G_ALC_DEF ;

END F_GET_ALC_RATE_SEL ;


