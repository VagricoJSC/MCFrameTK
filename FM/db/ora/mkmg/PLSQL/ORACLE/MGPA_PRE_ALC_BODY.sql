PROCEDURE P_CALC_PRE_ALC (
	I_ALC_REC	IN MGT_PRE_ALC_PATH%ROWTYPE,
	O_SEQ		IN OUT NUMBER
)
/**************************************************************************
<SYNOPSIS>
	一次配賦計算処理
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
AS
	C_ALC_OVER	CONSTANT MAPA_META.PRE_ALC_TYP%TYPE := MAC_PRE_ALC_TYP.NON_OVER ;
	C_ALC_NULL	CONSTANT MAPA_META.PRE_ALC_TYP%TYPE := MAC_PRE_ALC_TYP.NON_NULL ;
	C_ALC_TGT	CONSTANT MAPA_META.PRE_ALC_TYP%TYPE := MAC_PRE_ALC_TYP.TARGET ;

	L_SEL_REC	SEL_LIST%ROWTYPE ;
	L_RATE_REC	MAM_PRE_ALC_RATE%ROWTYPE ;
	L_PTN_REC	MAM_PRE_ALC_PTN%ROWTYPE ;

	L_AMT		MAPA_META.MONEY%TYPE ;
	L_TOTAL		MGPA_META.PRE_ALC_TOTAL%TYPE ;
	L_CALC_RATE	MGPA_META.PRE_ALC_CALC_RATE%TYPE ;

	TYPE ALC_DPT_LIST IS TABLE OF MAPA_META.FLG%TYPE INDEX BY MAPA_META.COST_DPT_CD%TYPE ;
	ALC_DPT_MST	ALC_DPT_LIST ;

	CURSOR CUR_RATE (
		CI_PRE_ALC_RATE_CD IN MAPA_META.PRE_ALC_RATE_CD%TYPE,
		CI_YM IN MAPA_META.YM%TYPE,
		CI_WG_CD IN MAPA_META.WG_CD%TYPE
		)
	IS
		SELECT	t.*
		FROM	(
			SELECT	w.DPT_CD, w.LOC_CD, w.OPER_CD, w.BP_CD,
				w.CTG_CD, w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3,
				w.LOT_NO, w.SUBLOT_NO, w.SNO1, w.SNO2, w.SNO3, w.SNO4,
				w.ITM_MFG_INST_NO, w.IV_NO, w.PO_NO, w.SLO_NO,
				w.ALC_AC_CD,
				w.TRD_WG_CD,
				w.PRE_ALC_RATE,
				w.ADJ_FLG
			FROM	MGW_PRE_RATE_TERM w
			WHERE	0=0
			AND	w.PRE_ALC_RATE_CD = CI_PRE_ALC_RATE_CD
			AND	w.WG_CD = CI_WG_CD
			AND	w.PRE_ALC_RATE != 0
			AND	CI_YM IS NULL
			UNION ALL
			SELECT	w.DPT_CD, w.LOC_CD, w.OPER_CD, w.BP_CD,
				w.CTG_CD, w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3,
				w.LOT_NO, w.SUBLOT_NO, w.SNO1, w.SNO2, w.SNO3, w.SNO4,
				w.ITM_MFG_INST_NO, w.IV_NO, w.PO_NO, w.SLO_NO,
				w.ALC_AC_CD,
				w.TRD_WG_CD,
				w.PRE_ALC_RATE,
				w.ADJ_FLG
			FROM	MGW_PRE_RATE_MLY w
			WHERE	0=0
			AND	w.PRE_ALC_RATE_CD = CI_PRE_ALC_RATE_CD
			AND	w.PRE_ALC_RATE != 0
			AND	w.YM = CI_YM
			AND	w.WG_CD = CI_WG_CD
			AND	CI_YM IS NOT NULL
			) t
		WHERE	0=0
		ORDER BY t.ADJ_FLG, t.PRE_ALC_RATE,
			t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
			t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
			t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
			t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
			t.ALC_AC_CD,
			t.TRD_WG_CD
	;

	TYPE RATE_LIST IS TABLE OF CUR_RATE%ROWTYPE INDEX BY BINARY_INTEGER ;
	RATE	RATE_LIST ;

	j	BINARY_INTEGER ;
	k	BINARY_INTEGER ;
BEGIN
	L_SEL_REC := F_GET_ALC_RATE_SEL(I_ALC_REC.WG_CD, I_ALC_REC.ALC_AC_CD, I_ALC_REC.DPT_CD) ;

	IF L_SEL_REC.PRE_ALC_RATE_CD = G_NULL_VAL THEN
		IF I_ALC_REC.PRE_ALC_LVL = 0 THEN
			G_MSG := FCPA_ERR.MSG_BINDER(I_ALC_REC.WG_CD, I_ALC_REC.DPT_CD, I_ALC_REC.ALC_AC_CD) ;
			FCPA_ERR.RAISE_APP_ERR('MGBDD0003', G_MSG) ;
		END IF ;

		UPDATE	MGT_PRE_ALC_PATH t
		SET	t.FIN_FLG = '1'
		WHERE	0=0
		AND	t.CALC_NO = I_ALC_REC.CALC_NO
		AND	t.CALC_GRP_CD = I_ALC_REC.CALC_GRP_CD
		AND	t.PRE_ALC_SEQ = I_ALC_REC.PRE_ALC_SEQ
		;

		IF G_LVL_SUM = '1' THEN
			UPDATE	MGT_PRE_ALC_PATH t
			SET	t.FIN_FLG = '1'
			WHERE	0=0
			AND	t.CALC_NO = I_ALC_REC.CALC_NO
			AND	t.CALC_GRP_CD = I_ALC_REC.CALC_GRP_CD
			AND	t.YM = I_ALC_REC.YM
			AND	t.WG_CD = I_ALC_REC.WG_CD
			AND	t.ALC_AC_CD = I_ALC_REC.ALC_AC_CD
			AND	NVL(t.DPT_CD, G_NULL_VAL) = NVL(I_ALC_REC.DPT_CD, G_NULL_VAL)
			AND	NVL(t.LOC_CD, G_NULL_VAL) = NVL(I_ALC_REC.LOC_CD, G_NULL_VAL)
			AND	NVL(t.OPER_CD, G_NULL_VAL) = NVL(I_ALC_REC.OPER_CD, G_NULL_VAL)
			AND	NVL(t.BP_CD, G_NULL_VAL) = NVL(I_ALC_REC.BP_CD, G_NULL_VAL)
			AND	NVL(t.CTG_CD, G_NULL_VAL) = NVL(I_ALC_REC.CTG_CD, G_NULL_VAL)
			AND	NVL(t.ITM_CD, G_NULL_VAL) = NVL(I_ALC_REC.ITM_CD, G_NULL_VAL)
			AND	NVL(t.ITM_SUB1, G_NULL_VAL) = NVL(I_ALC_REC.ITM_SUB1, G_NULL_VAL)
			AND	NVL(t.ITM_SUB2, G_NULL_VAL) = NVL(I_ALC_REC.ITM_SUB2, G_NULL_VAL)
			AND	NVL(t.ITM_SUB3, G_NULL_VAL) = NVL(I_ALC_REC.ITM_SUB3, G_NULL_VAL)
			AND	NVL(t.LOT_NO, G_NULL_VAL) = NVL(I_ALC_REC.LOT_NO, G_NULL_VAL)
			AND	NVL(t.SUBLOT_NO, G_NULL_VAL) = NVL(I_ALC_REC.SUBLOT_NO, G_NULL_VAL)
			AND	NVL(t.SNO1, G_NULL_VAL) = NVL(I_ALC_REC.SNO1, G_NULL_VAL)
			AND	NVL(t.SNO2, G_NULL_VAL) = NVL(I_ALC_REC.SNO2, G_NULL_VAL)
			AND	NVL(t.SNO3, G_NULL_VAL) = NVL(I_ALC_REC.SNO3, G_NULL_VAL)
			AND	NVL(t.SNO4, G_NULL_VAL) = NVL(I_ALC_REC.SNO4, G_NULL_VAL)
			AND	NVL(t.ITM_MFG_INST_NO, G_NULL_VAL) = NVL(I_ALC_REC.ITM_MFG_INST_NO, G_NULL_VAL)
			AND	NVL(t.IV_NO, G_NULL_VAL) = NVL(I_ALC_REC.IV_NO, G_NULL_VAL)
			AND	NVL(t.PO_NO, G_NULL_VAL) = NVL(I_ALC_REC.PO_NO, G_NULL_VAL)
			AND	NVL(t.SLO_NO, G_NULL_VAL) = NVL(I_ALC_REC.SLO_NO, G_NULL_VAL)
			AND	t.SRC_WG_CD = I_ALC_REC.SRC_WG_CD
			AND	t.PRE_ALC_LVL = I_ALC_REC.PRE_ALC_LVL
			AND	t.FIN_FLG = '0'
			;
		END IF ;

		RETURN ;
	END IF ;

	L_RATE_REC := F_GET_PRE_ALC_RATE(L_SEL_REC.PRE_ALC_RATE_CD) ;

	L_PTN_REC := F_GET_PRE_ALC_PTN(L_RATE_REC.PRE_ALC_PTN_CD) ;

	/*** 配賦先部門の取得 ***/
	ALC_DPT_MST.DELETE ;
	IF L_SEL_REC.PRE_ALC_DPT_PTN IS NOT NULL AND I_ALC_REC.DPT_CD IS NOT NULL THEN
		FOR x IN (
			SELECT	m.DST_DPT_CD
			FROM	MAM_PRE_ALC_DPT m
			WHERE	0=0
			AND	m.PRE_ALC_DPT_PTN = L_SEL_REC.PRE_ALC_DPT_PTN
			AND	m.SRC_DPT_CD = I_ALC_REC.DPT_CD
			AND	m.TERM = G_ARG.TERM
			)
		LOOP
			ALC_DPT_MST(x.DST_DPT_CD) := '1' ;
		END LOOP ;
	END IF ;

	/*** 配賦比率の取得 ***/
	RATE.DELETE ;
	L_TOTAL := 0 ;
	k := 0 ;
	IF G_ARG.SA_TYP = G_PLN AND L_RATE_REC.PLN_MLY_FLG = '0'
	OR G_ARG.SA_TYP = G_ACT AND L_RATE_REC.ACT_MLY_FLG = '0' AND L_RATE_REC.PLN_RULE_FLG = '0'
	THEN
		--期間比率から取得
		FOR x IN CUR_RATE(L_RATE_REC.PRE_ALC_RATE_CD, NULL, I_ALC_REC.WG_CD)
		LOOP
			IF ALC_DPT_MST.COUNT = 0 OR ALC_DPT_MST.EXISTS(x.DPT_CD) THEN
				k := k + 1 ;
				RATE(k) := x ;
				L_TOTAL := L_TOTAL + x.PRE_ALC_RATE ;
			END IF ;
		END LOOP ;

		IF k = 0 OR L_TOTAL = 0 THEN
			G_MSG := FCPA_ERR.MSG_BINDER(
					FCPA_DATE_UTIL.F_TO_CHAR(G_ARG.TERM, FCPA_DATE_UTIL.Y4M),
					L_RATE_REC.PRE_ALC_RATE_CD,
					I_ALC_REC.WG_CD,
					I_ALC_REC.DPT_CD,
					L_SEL_REC.PRE_ALC_DPT_PTN
				) ;
			IF k = 0 THEN
				FCPA_ERR.RAISE_APP_ERR('MGBDD0004', G_MSG) ;
			ELSE
				FCPA_ERR.RAISE_APP_ERR('MGBDD0005', G_MSG) ;
			END IF ;
		END IF ;
	ELSE
		--月次比率から取得
		FOR x IN CUR_RATE(L_RATE_REC.PRE_ALC_RATE_CD, I_ALC_REC.YM, I_ALC_REC.WG_CD)
		LOOP
			IF ALC_DPT_MST.COUNT = 0 OR ALC_DPT_MST.EXISTS(x.DPT_CD) THEN
				k := k + 1 ;
				RATE(k) := x ;
				L_TOTAL := L_TOTAL + x.PRE_ALC_RATE ;
			END IF ;
		END LOOP ;

		IF k = 0 OR L_TOTAL = 0 THEN
			G_MSG := FCPA_ERR.MSG_BINDER(
					FCPA_DATE_UTIL.F_TO_CHAR(I_ALC_REC.YM, FCPA_DATE_UTIL.Y4M),
					L_RATE_REC.PRE_ALC_RATE_CD,
					I_ALC_REC.WG_CD,
					I_ALC_REC.DPT_CD,
					L_SEL_REC.PRE_ALC_DPT_PTN
				) ;
			IF k = 0 THEN
				FCPA_ERR.RAISE_APP_ERR('MGBDD0006', G_MSG) ;
			ELSE
				FCPA_ERR.RAISE_APP_ERR('MGBDD0007', G_MSG) ;
			END IF ;
		END IF ;
	END IF ;
	ALC_DPT_MST.DELETE ;

	/*** 配賦元レコードに配賦関連の情報を設定 ***/
	L_AMT := I_ALC_REC.AMT ;
	L_CALC_RATE := L_AMT / L_TOTAL ;

	UPDATE	MGT_PRE_ALC_PATH t
	SET	t.PRE_ALC_RATE_CD = L_RATE_REC.PRE_ALC_RATE_CD,
		t.PRE_ALC_TOTAL = L_TOTAL,
		t.PRE_ALC_CALC_RATE = L_CALC_RATE
	WHERE	0=0
	AND	t.CALC_NO = I_ALC_REC.CALC_NO
	AND	t.CALC_GRP_CD = I_ALC_REC.CALC_GRP_CD
	AND	t.PRE_ALC_SEQ = I_ALC_REC.PRE_ALC_SEQ
	;

	/*** 配賦処理 ***/
	j := ALC_TGT.COUNT ;
	FOR i IN 1..k LOOP
		j := j + 1 ;
		O_SEQ := O_SEQ + 1 ;

		ALC_TGT(j).CALC_NO	:= G_ARG.CALC_NO ;
		ALC_TGT(j).CALC_GRP_CD	:= G_ARG.CALC_GRP_CD ;
		ALC_TGT(j).PRE_ALC_SEQ	:= O_SEQ ;
		ALC_TGT(j).YM		:= I_ALC_REC.YM ;

		CASE L_PTN_REC.WG_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).WG_CD := NVL(L_SEL_REC.TRD_WG_CD, I_ALC_REC.WG_CD) ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).WG_CD := NVL(RATE(i).TRD_WG_CD,
							NVL(L_SEL_REC.TRD_WG_CD, I_ALC_REC.WG_CD)) ;
		ELSE
			ALC_TGT(j).WG_CD := NVL(L_SEL_REC.TRD_WG_CD, I_ALC_REC.WG_CD) ;
		END CASE ;

		CASE L_PTN_REC.ALC_AC_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).ALC_AC_CD := NVL(L_SEL_REC.TRD_ALC_AC_CD, I_ALC_REC.ALC_AC_CD) ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).ALC_AC_CD := NVL(RATE(i).ALC_AC_CD,
							NVL(L_SEL_REC.TRD_ALC_AC_CD, I_ALC_REC.ALC_AC_CD)) ;
		ELSE
			ALC_TGT(j).ALC_AC_CD := NVL(L_SEL_REC.TRD_ALC_AC_CD, I_ALC_REC.ALC_AC_CD) ;
		END CASE ;

		CASE L_PTN_REC.DPT_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).DPT_CD := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).DPT_CD := RATE(i).DPT_CD ;
		ELSE
			ALC_TGT(j).DPT_CD := I_ALC_REC.DPT_CD ;
		END CASE ;

		CASE L_PTN_REC.LOC_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).LOC_CD := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).LOC_CD := RATE(i).LOC_CD ;
		ELSE
			ALC_TGT(j).LOC_CD := I_ALC_REC.LOC_CD ;
		END CASE ;

		CASE L_PTN_REC.OPER_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).OPER_CD := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).OPER_CD := RATE(i).OPER_CD ;
		ELSE
			ALC_TGT(j).OPER_CD := I_ALC_REC.OPER_CD ;
		END CASE ;

		CASE L_PTN_REC.BP_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).BP_CD := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).BP_CD := RATE(i).BP_CD ;
		ELSE
			ALC_TGT(j).BP_CD := I_ALC_REC.BP_CD ;
		END CASE ;

		CASE L_PTN_REC.CTG_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).CTG_CD := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).CTG_CD := RATE(i).CTG_CD ;
		ELSE
			ALC_TGT(j).CTG_CD := I_ALC_REC.CTG_CD ;
		END CASE ;

		CASE L_PTN_REC.ITM_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).ITM_CD := NULL ;
			ALC_TGT(j).ITM_SUB1 := NULL ;
			ALC_TGT(j).ITM_SUB2 := NULL ;
			ALC_TGT(j).ITM_SUB3 := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).ITM_CD := RATE(i).ITM_CD ;
			ALC_TGT(j).ITM_SUB1 := RATE(i).ITM_SUB1 ;
			ALC_TGT(j).ITM_SUB2 := RATE(i).ITM_SUB2 ;
			ALC_TGT(j).ITM_SUB3 := RATE(i).ITM_SUB3 ;
		ELSE
			ALC_TGT(j).ITM_CD := I_ALC_REC.ITM_CD ;
			ALC_TGT(j).ITM_SUB1 := I_ALC_REC.ITM_SUB1 ;
			ALC_TGT(j).ITM_SUB2 := I_ALC_REC.ITM_SUB2 ;
			ALC_TGT(j).ITM_SUB3 := I_ALC_REC.ITM_SUB3 ;
		END CASE ;

		CASE L_PTN_REC.LOT_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).LOT_NO := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).LOT_NO := RATE(i).LOT_NO ;
		ELSE
			ALC_TGT(j).LOT_NO := I_ALC_REC.LOT_NO ;
		END CASE ;

		CASE L_PTN_REC.SUBLOT_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).SUBLOT_NO := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).SUBLOT_NO := RATE(i).SUBLOT_NO ;
		ELSE
			ALC_TGT(j).SUBLOT_NO := I_ALC_REC.SUBLOT_NO ;
		END CASE ;

		CASE L_PTN_REC.SNO1_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).SNO1 := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).SNO1 := RATE(i).SNO1 ;
		ELSE
			ALC_TGT(j).SNO1 := I_ALC_REC.SNO1 ;
		END CASE ;

		CASE L_PTN_REC.SNO2_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).SNO2 := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).SNO2 := RATE(i).SNO2 ;
		ELSE
			ALC_TGT(j).SNO2 := I_ALC_REC.SNO2 ;
		END CASE ;

		CASE L_PTN_REC.SNO3_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).SNO3 := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).SNO3 := RATE(i).SNO3 ;
		ELSE
			ALC_TGT(j).SNO3 := I_ALC_REC.SNO3 ;
		END CASE ;

		CASE L_PTN_REC.SNO4_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).SNO4 := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).SNO4 := RATE(i).SNO4 ;
		ELSE
			ALC_TGT(j).SNO4 := I_ALC_REC.SNO4 ;
		END CASE ;

		CASE L_PTN_REC.INST_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).ITM_MFG_INST_NO := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).ITM_MFG_INST_NO := RATE(i).ITM_MFG_INST_NO ;
		ELSE
			ALC_TGT(j).ITM_MFG_INST_NO := I_ALC_REC.ITM_MFG_INST_NO ;
		END CASE ;

		CASE L_PTN_REC.IV_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).IV_NO := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).IV_NO := RATE(i).IV_NO ;
		ELSE
			ALC_TGT(j).IV_NO := I_ALC_REC.IV_NO ;
		END CASE ;

		CASE L_PTN_REC.PO_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).PO_NO := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).PO_NO := RATE(i).PO_NO ;
		ELSE
			ALC_TGT(j).PO_NO := I_ALC_REC.PO_NO ;
		END CASE ;

		CASE L_PTN_REC.SLO_ALC_TYP
		WHEN C_ALC_NULL THEN
			ALC_TGT(j).SLO_NO := NULL ;
		WHEN C_ALC_TGT THEN
			ALC_TGT(j).SLO_NO := RATE(i).SLO_NO ;
		ELSE
			ALC_TGT(j).SLO_NO := I_ALC_REC.SLO_NO ;
		END CASE ;

		ALC_TGT(j).PRE_ALC_RATE := RATE(i).PRE_ALC_RATE ;

		ALC_TGT(j).SRC_WG_CD := I_ALC_REC.SRC_WG_CD ;
		ALC_TGT(j).SRC_PRE_ALC_SEQ := I_ALC_REC.PRE_ALC_SEQ ;
		ALC_TGT(j).TOP_PRE_ALC_SEQ := I_ALC_REC.TOP_PRE_ALC_SEQ ;
		ALC_TGT(j).PRE_ALC_LVL	   := I_ALC_REC.PRE_ALC_LVL + 1 ;

		ALC_TGT(j).FIN_FLG := L_SEL_REC.FIN_FLG ;
		IF ALC_TGT(j).PRE_ALC_LVL = G_CO_PARM.PRE_ALC_MAX_LVL THEN
			ALC_TGT(j).FIN_FLG := '1' ;
		END IF ;

		IF i = k THEN
			ALC_TGT(j).AMT := L_AMT ;
		ELSE
			ALC_TGT(j).AMT := MAPA_CALC.F_RND(
						L_CALC_RATE * ALC_TGT(j).PRE_ALC_RATE,
						G_CO_PARM.AMT_DEC_PLACE,
						G_CO_PARM.AMT_RND_TYP
						)
					;
			L_AMT := L_AMT - ALC_TGT(j).AMT ;
		END IF ;

		IF G_LOOP_ERR = '1' AND ALC_TGT(j).FIN_FLG = '0' THEN
			FOR x IN (
				SELECT	t.*
				FROM	MGT_PRE_ALC_PATH t
				WHERE	0=0
				AND	t.CALC_NO = G_ARG.CALC_NO
				AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				START WITH 0=0
				AND	t.CALC_NO = G_ARG.CALC_NO
				AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	t.PRE_ALC_SEQ = ALC_TGT(j).SRC_PRE_ALC_SEQ
				CONNECT BY NOCYCLE 0=0
				AND	PRIOR t.SRC_PRE_ALC_SEQ = t.PRE_ALC_SEQ
				AND	PRIOR t.CALC_NO = G_ARG.CALC_NO
				AND	PRIOR t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				)
			LOOP
				IF  x.WG_CD = ALC_TGT(j).WG_CD
				AND x.ALC_AC_CD = ALC_TGT(j).ALC_AC_CD
				AND NVL(x.DPT_CD, G_NULL_VAL) = NVL(ALC_TGT(j).DPT_CD, G_NULL_VAL)
				AND NVL(x.LOC_CD, G_NULL_VAL) = NVL(ALC_TGT(j).LOC_CD, G_NULL_VAL)
				AND NVL(x.OPER_CD, G_NULL_VAL) = NVL(ALC_TGT(j).OPER_CD, G_NULL_VAL)
				AND NVL(x.BP_CD, G_NULL_VAL) = NVL(ALC_TGT(j).BP_CD, G_NULL_VAL)
				AND NVL(x.CTG_CD, G_NULL_VAL) = NVL(ALC_TGT(j).CTG_CD, G_NULL_VAL)
				AND NVL(x.ITM_CD, G_NULL_VAL) = NVL(ALC_TGT(j).ITM_CD, G_NULL_VAL)
				AND NVL(x.ITM_SUB1, G_NULL_VAL) = NVL(ALC_TGT(j).ITM_SUB1, G_NULL_VAL)
				AND NVL(x.ITM_SUB2, G_NULL_VAL) = NVL(ALC_TGT(j).ITM_SUB2, G_NULL_VAL)
				AND NVL(x.ITM_SUB3, G_NULL_VAL) = NVL(ALC_TGT(j).ITM_SUB3, G_NULL_VAL)
				AND NVL(x.LOT_NO, G_NULL_VAL) = NVL(ALC_TGT(j).LOT_NO, G_NULL_VAL)
				AND NVL(x.SUBLOT_NO, G_NULL_VAL) = NVL(ALC_TGT(j).SUBLOT_NO, G_NULL_VAL)
				AND NVL(x.SNO1, G_NULL_VAL) = NVL(ALC_TGT(j).SNO1, G_NULL_VAL)
				AND NVL(x.SNO2, G_NULL_VAL) = NVL(ALC_TGT(j).SNO2, G_NULL_VAL)
				AND NVL(x.SNO3, G_NULL_VAL) = NVL(ALC_TGT(j).SNO3, G_NULL_VAL)
				AND NVL(x.SNO4, G_NULL_VAL) = NVL(ALC_TGT(j).SNO4, G_NULL_VAL)
				AND NVL(x.ITM_MFG_INST_NO, G_NULL_VAL) = NVL(ALC_TGT(j).ITM_MFG_INST_NO, G_NULL_VAL)
				AND NVL(x.IV_NO, G_NULL_VAL) = NVL(ALC_TGT(j).IV_NO, G_NULL_VAL)
				AND NVL(x.PO_NO, G_NULL_VAL) = NVL(ALC_TGT(j).PO_NO, G_NULL_VAL)
				AND NVL(x.SLO_NO, G_NULL_VAL) = NVL(ALC_TGT(j).SLO_NO, G_NULL_VAL)
				THEN
					O_SEQ := G_LOOP_ERR_NUM ;
					G_MSG := FCPA_ERR.MSG_BINDER(ALC_TGT(j).TOP_PRE_ALC_SEQ, x.PRE_ALC_SEQ, ALC_TGT(j).PRE_ALC_SEQ) ;
					RETURN ;
				END IF ;
			END LOOP ;
		END IF ;

	END LOOP ;

END P_CALC_PRE_ALC ;


PROCEDURE P_MAIN (
	I_ARG	IN MGT_ARG%ROWTYPE
)
/**************************************************************************
<SYNOPSIS>
	一次配賦計算のメイン処理
<REMARKS>

<ARGUMENTS>
<IN>	I_ARG
		原価計算設定情報レコード
<HISTORY>
**************************************************************************/
AS
	C_IO_STK_OUT	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_OUT ;

	C_AMT_ADD_ALC	CONSTANT MGPA_META.AMT_ADD_TYP%TYPE := MGC_AMT_ADD_TYP.ALC ;

	L_LVL		MAPA_META.PRE_ALC_MAX_LVL%TYPE ;

	ALC_REC		PATH_LIST ;

	L_REC_CNT	NUMBER ;
	L_CNT		NUMBER ;

	i		BINARY_INTEGER ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_PRE_ALC.P_MAIN') ;

	G_ARG := I_ARG ;

	IF G_ARG.PRE_ALC_CALC_TYP = G_PRE_ALC_NON THEN
		GOTO PROC_FIN ;
	END IF ;

	G_CO_PARM := MGPA_CO_PARM.F_GET_REC() ;
	IF G_CO_PARM.PRE_ALC_MAX_LVL IS NULL THEN
		G_CO_PARM.PRE_ALC_MAX_LVL := 10 ;
	END IF ;

	IF G_CO_PARM.PRE_ALC_MAX_REC IS NULL THEN
		G_CO_PARM.PRE_ALC_MAX_REC := 10000 ;
	END IF ;

	G_MAX_LVL_ERR := '0' ;
	G_MAX_REC_ERR := '0' ;
	G_LOOP_ERR := '0' ;
	G_LVL_SUM := '0' ;
	FOR z IN (
		SELECT	t.PARM_KEY,
			t.PARM_VAL
		FROM	MGT_CALC_PARM t
		WHERE	0=0
		AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
		AND	t.CALC_NO = G_ARG.CALC_NO
		AND	t.PARM_KEY LIKE 'PRE%'
		)
	LOOP
		IF z.PARM_KEY = 'PRE_MAX_LVL' AND z.PARM_VAL IS NOT NULL THEN
			G_CO_PARM.PRE_ALC_MAX_LVL := z.PARM_VAL ;
		END IF ;

		IF z.PARM_KEY = 'PRE_MAX_REC' AND z.PARM_VAL IS NOT NULL THEN
			G_CO_PARM.PRE_ALC_MAX_REC := z.PARM_VAL ;
		END IF ;

		IF z.PARM_KEY = 'PRE_MAX_LVL_ERR' AND z.PARM_VAL = '1' THEN
			G_MAX_LVL_ERR := z.PARM_VAL ;
		END IF ;

		IF z.PARM_KEY = 'PRE_MAX_REC_ERR' AND z.PARM_VAL = '1' THEN
			G_MAX_REC_ERR := z.PARM_VAL ;
		END IF ;

		IF z.PARM_KEY = 'PRE_LOOP_ERR' AND z.PARM_VAL = '1' THEN
			G_LOOP_ERR := z.PARM_VAL ;
		END IF ;

		IF z.PARM_KEY = 'PRE_LVL_SUM' AND z.PARM_VAL = '1' THEN
			G_LVL_SUM := z.PARM_VAL ;
		END IF ;
	END LOOP ;

	DELETE MGT_PRE_ALC_PATH t WHERE t.CALC_NO = G_ARG.CALC_NO AND t.CALC_GRP_CD = G_ARG.CALC_GRP_CD ;

	INSERT INTO MGT_PRE_ALC_PATH (
		CALC_NO, CALC_GRP_CD,
		YM, INPT_ALC_TYP,
		WG_CD, ALC_AC_CD,
		DPT_CD, LOC_CD, OPER_CD, BP_CD,
		CTG_CD, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		LOT_NO, SUBLOT_NO, SNO1, SNO2, SNO3, SNO4,
		ITM_MFG_INST_NO, IV_NO, PO_NO, SLO_NO,
		AMT,
		SRC_WG_CD,
		PRE_ALC_SEQ,
		SRC_PRE_ALC_SEQ,
		TOP_PRE_ALC_SEQ,
		PRE_ALC_LVL
		)
	SELECT	G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
		t.YM, t.INPT_ALC_TYP,
		t.WG_CD, t.ALC_AC_CD,
		t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
		t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
		t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
		t.AMT,
		t.WG_CD,
		ROWNUM,
		NULL,
		ROWNUM,
		0
	FROM	(
		SELECT	x.*
		FROM	(
			SELECT	G_INPT_ALC_AMT	INPT_ALC_TYP,
				t1.YM, t1.WG_CD, t1.ALC_AC_CD,
				t1.DPT_CD, t1.LOC_CD, t1.OPER_CD, t1.BP_CD,
				t1.CTG_CD, t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
				t1.LOT_NO, t1.SUBLOT_NO, t1.SNO1, t1.SNO2, t1.SNO3, t1.SNO4,
				t1.ITM_MFG_INST_NO,
				t1.IV_NO, t1.PO_NO, t1.SLO_NO,
				SUM(t1.AMT)	AMT
			FROM	MGT_CALC_PRE_ALC_AMT t1
			WHERE	0=0
			AND	t1.CALC_NO = G_ARG.CALC_NO
			AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
			AND	t1.AMT != 0
			GROUP BY t1.YM, t1.WG_CD, t1.ALC_AC_CD,
				t1.DPT_CD, t1.LOC_CD, t1.OPER_CD, t1.BP_CD,
				t1.CTG_CD, t1.ITM_CD, t1.ITM_SUB1, t1.ITM_SUB2, t1.ITM_SUB3,
				t1.LOT_NO, t1.SUBLOT_NO, t1.SNO1, t1.SNO2, t1.SNO3, t1.SNO4,
				t1.ITM_MFG_INST_NO, t1.IV_NO, t1.PO_NO, t1.SLO_NO
			UNION ALL
			SELECT	G_INPT_SO_ALC	INPT_ALC_TYP,
				t1.YM,
				t1.ALC_WG_CD	WG_CD,
				t1.ALC_AC_CD	ALC_AC_CD,
				t1.ALC_DPT_CD	DPT_CD,
				t1.ALC_LOC_CD	LOC_CD,
				t1.ALC_OPER_CD	OPER_CD,
				t1.ALC_BP_CD	BP_CD,
				t1.ALC_CTG_CD	CTG_CD,
				t1.ALC_ITM_CD	ITM_CD,
				t1.ALC_ITM_SUB1	ITM_SUB1,
				t1.ALC_ITM_SUB2	ITM_SUB2,
				t1.ALC_ITM_SUB3	ITM_SUB3,
				t1.ALC_LOT_NO	LOT_NO,
				t1.ALC_SUBLOT_NO	SUBLOT_NO,
				t1.ALC_SNO1	SNO1,
				t1.ALC_SNO2	SNO2,
				t1.ALC_SNO3	SNO3,
				t1.ALC_SNO4	SNO4,
				t1.ALC_ITM_MFG_INST_NO	ITM_MFG_INST_NO,
				NULL	IV_NO,
				NULL	PO_NO,
				NULL	SLO_NO,
				SUM(t2.AMT)	AMT
			FROM	MGT_CALC_IO t1, MGT_CALC_IO_EXPNS_AMT t2
			WHERE	0=0
			AND	t1.CALC_NO = G_ARG.CALC_NO
			AND	t1.CALC_GRP_CD = G_ARG.CALC_GRP_CD
			AND	t1.ALC_AC_CD IS NOT NULL
			AND	t1.ALC_AMT_FLG = '1'
			AND	t1.COST_IO_TYP = C_IO_STK_OUT
			AND	t1.CALC_NO = t2.CALC_NO
			AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
			AND	t1.ITM_CD = t2.ITM_CD
			AND	t1.ITM_SUB1 = t2.ITM_SUB1
			AND	t1.ITM_SUB2 = t2.ITM_SUB2
			AND	t1.ITM_SUB3 = t2.ITM_SUB3
			AND	t1.WG_CD = t2.WG_CD
			AND	t1.ACT_IO_ID = t2.ACT_IO_ID
			AND	t1.ACT_IO_ID_SUB = t2.ACT_IO_ID_SUB
			AND	t2.AMT_ADD_TYP = C_AMT_ADD_ALC
			AND	G_ARG.CALC_EXEC_CNT > 1
			GROUP BY t1.YM, t1.ALC_WG_CD, t1.ALC_AC_CD,
				t1.ALC_DPT_CD, t1.ALC_LOC_CD, t1.ALC_OPER_CD,
				t1.ALC_BP_CD, t1.ALC_CTG_CD, t1.ALC_ITM_CD,
				t1.ALC_ITM_SUB1, t1.ALC_ITM_SUB2, t1.ALC_ITM_SUB3,
				t1.ALC_LOT_NO, t1.ALC_SUBLOT_NO, t1.ALC_SNO1, t1.ALC_SNO2, t1.ALC_SNO3, t1.ALC_SNO4,
				t1.ALC_ITM_MFG_INST_NO
			) x
		WHERE	0=0
		ORDER BY x.YM, x.INPT_ALC_TYP,
			x.WG_CD, x.ALC_AC_CD,
			x.DPT_CD, x.LOC_CD, x.OPER_CD, x.BP_CD,
			x.CTG_CD, x.ITM_CD, x.ITM_SUB1, x.ITM_SUB2, x.ITM_SUB3,
			x.LOT_NO, x.SUBLOT_NO, x.SNO1, x.SNO2, x.SNO3, x.SNO4,
			x.ITM_MFG_INST_NO, x.IV_NO, x.PO_NO, x.SLO_NO
		) t
	WHERE	0=0
	;

	SELECT	COUNT(*)
	INTO	L_REC_CNT
	FROM	MGT_PRE_ALC_PATH t
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	;

	IF L_REC_CNT > G_CO_PARM.PRE_ALC_MAX_REC THEN
		RATE_MST.DELETE ;
		PTN_MST.DELETE ;
		ALC_REC.DELETE ;
		ALC_TGT.DELETE ;
		IF G_MAX_REC_ERR = '1' THEN
			COMMIT ;
		END IF ;

		G_MSG := FCPA_ERR.MSG_BINDER(L_REC_CNT, G_CO_PARM.PRE_ALC_MAX_REC) ;
		FCPA_ERR.RAISE_APP_ERR('MGBDD0001', G_MSG) ;
	END IF ;

	RATE_MST.DELETE ;
	PTN_MST.DELETE ;
	ALC_REC.DELETE ;
	ALC_TGT.DELETE ;

	L_LVL := 0 ;
	i := 0 ;
	WHILE L_LVL < G_CO_PARM.PRE_ALC_MAX_LVL LOOP

		IF G_LVL_SUM = '1' THEN
			FOR x IN (
				SELECT	t.YM,
					t.WG_CD, t.ALC_AC_CD,
					t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
					t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
					t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
					t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
					t.SRC_WG_CD,
					SUM(t.AMT)	AMT,
					MIN(t.PRE_ALC_SEQ)	PRE_ALC_SEQ,
					MIN(t.TOP_PRE_ALC_SEQ)	TOP_PRE_ALC_SEQ
				FROM	MGT_PRE_ALC_PATH t
				WHERE	0=0
				AND	t.CALC_NO = G_ARG.CALC_NO
				AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	t.PRE_ALC_LVL = L_LVL
				AND	t.AMT != 0
				AND	t.FIN_FLG = '0'
				GROUP BY t.YM,
					t.WG_CD, t.ALC_AC_CD,
					t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
					t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
					t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
					t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
					t.SRC_WG_CD
				HAVING SUM(t.AMT) != 0
				ORDER BY MIN(t.PRE_ALC_SEQ)
				)
			LOOP
				i := i + 1 ;
				ALC_REC(i).CALC_NO := G_ARG.CALC_NO ;
				ALC_REC(i).CALC_GRP_CD := G_ARG.CALC_GRP_CD ;
				ALC_REC(i).PRE_ALC_SEQ := x.PRE_ALC_SEQ ;
				ALC_REC(i).YM := x.YM ;
				ALC_REC(i).WG_CD := x.WG_CD ;
				ALC_REC(i).ALC_AC_CD := x.ALC_AC_CD ;
				ALC_REC(i).DPT_CD := x.DPT_CD ;
				ALC_REC(i).LOC_CD := x.LOC_CD ;
				ALC_REC(i).OPER_CD := x.OPER_CD ;
				ALC_REC(i).BP_CD := x.BP_CD ;
				ALC_REC(i).CTG_CD := x.CTG_CD ;
				ALC_REC(i).ITM_CD := x.ITM_CD ;
				ALC_REC(i).ITM_SUB1 := x.ITM_SUB1 ;
				ALC_REC(i).ITM_SUB2 := x.ITM_SUB2 ;
				ALC_REC(i).ITM_SUB3 := x.ITM_SUB3 ;
				ALC_REC(i).LOT_NO := x.LOT_NO ;
				ALC_REC(i).SUBLOT_NO := x.SUBLOT_NO ;
				ALC_REC(i).SNO1 := x.SNO1 ;
				ALC_REC(i).SNO2 := x.SNO2 ;
				ALC_REC(i).SNO3 := x.SNO3 ;
				ALC_REC(i).SNO4 := x.SNO4 ;
				ALC_REC(i).ITM_MFG_INST_NO := x.ITM_MFG_INST_NO ;
				ALC_REC(i).IV_NO := x.IV_NO ;
				ALC_REC(i).PO_NO := x.PO_NO ;
				ALC_REC(i).SLO_NO := x.SLO_NO ;
				ALC_REC(i).AMT := x.AMT ;
				ALC_REC(i).SRC_WG_CD := x.SRC_WG_CD ;
				ALC_REC(i).TOP_PRE_ALC_SEQ := x.TOP_PRE_ALC_SEQ ;
				ALC_REC(i).PRE_ALC_LVL := L_LVL ;
				ALC_REC(i).FIN_FLG := '0' ;
			END LOOP ;
		ELSE
			FOR x IN (
				SELECT	t.*
				FROM	MGT_PRE_ALC_PATH t
				WHERE	0=0
				AND	t.CALC_NO = G_ARG.CALC_NO
				AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	t.PRE_ALC_LVL = L_LVL
				AND	t.AMT != 0
				AND	t.FIN_FLG = '0'
				ORDER BY t.PRE_ALC_SEQ
				)
			LOOP
				i := i + 1 ;
				ALC_REC(i) := x ;
			END LOOP ;
		END IF ;

		IF i > 0 THEN
			FOR j IN 1..i LOOP
				P_CALC_PRE_ALC(ALC_REC(j), L_REC_CNT) ;

				IF G_LOOP_ERR = '1' AND L_REC_CNT = G_LOOP_ERR_NUM THEN

					ALC_REC.DELETE ;
					RATE_MST.DELETE ;
					PTN_MST.DELETE ;

					P_INS_PRE_ALC_PATH('1') ;
					COMMIT ;
					FCPA_ERR.RAISE_APP_ERR('MGBDD0020', G_MSG) ;
				END IF ;

				P_INS_PRE_ALC_PATH('0') ;

				IF L_REC_CNT > G_CO_PARM.PRE_ALC_MAX_REC THEN

					ALC_REC.DELETE ;
					RATE_MST.DELETE ;
					PTN_MST.DELETE ;

					IF G_MAX_REC_ERR = '1' THEN
						P_INS_PRE_ALC_PATH('1') ;
						COMMIT ;
					ELSE
						ALC_TGT.DELETE ;
					END IF ;

					G_MSG := FCPA_ERR.MSG_BINDER(L_REC_CNT, G_CO_PARM.PRE_ALC_MAX_REC) ;
					FCPA_ERR.RAISE_APP_ERR('MGBDD0001', G_MSG) ;
				END IF ;

			END LOOP ;
		END IF ;

		P_INS_PRE_ALC_PATH('1') ;

		IF i = 0 THEN
			EXIT ;
		END IF ;

		ALC_REC.DELETE ;
		i := 0 ;
		L_LVL := L_LVL + 1 ;
	END LOOP ;

	ALC_REC.DELETE ;
	RATE_MST.DELETE ;
	PTN_MST.DELETE ;

	IF L_LVL >= G_CO_PARM.PRE_ALC_MAX_LVL THEN
		IF G_MAX_LVL_ERR = '0' THEN
			FCPA_BATCH_LOG.P_DATA_LOG('MGBDD0002', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2, G_CO_PARM.PRE_ALC_MAX_LVL) ;
		ELSE
			COMMIT ;
			G_MSG := FCPA_ERR.MSG_BINDER(G_CO_PARM.PRE_ALC_MAX_LVL) ;
			FCPA_ERR.RAISE_APP_ERR('MGBDD0021', G_MSG) ;
		END IF ;
	END IF ;

	DELETE MGT_PRE_ALC t WHERE t.CALC_NO = G_ARG.CALC_NO AND t.CALC_GRP_CD = G_ARG.CALC_GRP_CD ;
	INSERT INTO MGT_PRE_ALC (
		CALC_NO, CALC_GRP_CD,
		WG_CD, YM, ALC_AC_CD,
		DPT_CD, LOC_CD, OPER_CD, BP_CD,
		CTG_CD, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		LOT_NO, SUBLOT_NO, SNO1, SNO2, SNO3, SNO4,
		ITM_MFG_INST_NO, IV_NO, PO_NO, SLO_NO,
		SRC_WG_CD,
		AMT
		)
	SELECT	G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
		t.WG_CD, t.YM, t.ALC_AC_CD,
		t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
		t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
		t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
		t.SRC_WG_CD,
		SUM(t.AMT)
	FROM	MGT_PRE_ALC_PATH t
	WHERE	0=0
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.FIN_FLG = '1'
	AND	t.AMT != 0
	GROUP BY t.WG_CD, t.YM, t.ALC_AC_CD,
		t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
		t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
		t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
		t.SRC_WG_CD
	;

	L_CNT := 0 ;
	INSERT INTO MGT_CALC_ALC_AMT (
		CALC_NO, CALC_GRP_CD,
		INPT_ALC_TYP, WG_CD,
		YM, ALC_AC_CD,
		DPT_CD, LOC_CD, OPER_CD, BP_CD,
		CTG_CD, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3,
		LOT_NO, SUBLOT_NO, SNO1, SNO2, SNO3, SNO4,
		ITM_MFG_INST_NO, IV_NO, PO_NO, SLO_NO,
		AMT
		)
	SELECT	G_ARG.CALC_NO, G_ARG.CALC_GRP_CD,
		G_INPT_PRE_ALC, NVL(G_ARG.RUNTIME_WG_CD, t.WG_CD),
		DECODE(G_ARG.ALC_CALC_TYP, G_ALC_MONTH, t.YM, G_ARG.END_YM),
		t.ALC_AC_CD,
		t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
		t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
		t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO,
		SUM(t.AMT)
	FROM	MGT_PRE_ALC t
	WHERE	0=0
	AND	(
		t.WG_CD = G_ARG.RUNTIME_WG_CD
		OR 
		G_ARG.RUNTIME_WG_CD IS NULL
			AND	EXISTS (
				SELECT	'X'
				FROM	MAM_GRP_WG w
				WHERE	0=0
				AND	w.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	w.WG_CD = t.WG_CD
			)
	)
	AND	t.CALC_NO = G_ARG.CALC_NO
	AND	t.CALC_GRP_CD = G_ARG.CALC_GRP_CD
	AND	t.AMT != 0
	GROUP BY NVL(G_ARG.RUNTIME_WG_CD, t.WG_CD),
		DECODE(G_ARG.ALC_CALC_TYP, G_ALC_MONTH, t.YM, G_ARG.END_YM),
		t.ALC_AC_CD,
		t.DPT_CD, t.LOC_CD, t.OPER_CD, t.BP_CD,
		t.CTG_CD, t.ITM_CD, t.ITM_SUB1, t.ITM_SUB2, t.ITM_SUB3,
		t.LOT_NO, t.SUBLOT_NO, t.SNO1, t.SNO2, t.SNO3, t.SNO4,
		t.ITM_MFG_INST_NO, t.IV_NO, t.PO_NO, t.SLO_NO
	;
	L_CNT := L_CNT + SQL%ROWCOUNT ;
	FCPA_BATCH_LOG.P_PROC_LOG('MGBDD0008', 'MGT_CALC_ALC_AMT', L_CNT) ;

	<<PROC_FIN>>
		NULL ;

	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_PRE_ALC.P_MAIN') ;

END P_MAIN ;

END MGPA_PRE_ALC ;
