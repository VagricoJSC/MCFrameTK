PROCEDURE P_SET_INPUT_AMT (
	I_CALC_CTG_CD	IN MAPA_META.CALC_CTG_CD%TYPE
)
/**************************************************************************
<SYNOPSIS>
	計算対象となる一次配賦計算用及び品目配賦用の費用データを作成する
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_CTG_CD
		計算カテゴリＣＤ
<HISTORY>
**************************************************************************/
AS
	C_MY_WG	CONSTANT MGPA_META.ALC_REC_TYP%TYPE := MGC_ALC_REC_TYP.MY_WG ;

	L_SEL_REC	SEL_LIST%ROWTYPE ;
	L_CNT		NUMBER ;
BEGIN
	IF G_ARG.SA_TYP = G_PLN AND G_ARG.PRE_ALC_CALC_TYP = G_PRE_ALC_CALC THEN

		FOR x IN (
			SELECT	t.*
			FROM	MGT_PLN_ALC_AMT t
			WHERE	0=0
			AND	t.CALC_CTG_CD = I_CALC_CTG_CD
			AND	t.YM BETWEEN G_ARG.ST_YM AND G_ARG.END_YM
			AND	t.ALC_REC_TYP != C_MY_WG
			AND	(
				t.WG_CD = G_ARG.RUNTIME_WG_CD
				OR EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG m
					WHERE	0=0
					AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	m.WG_CD = t.WG_CD
					)
				)
			)
		LOOP
			x.WG_CD := NVL(G_ARG.RUNTIME_WG_CD, x.WG_CD) ;

			IF x.TRD_WG_CD IS NOT NULL
			AND x.TRD_CALC_GRP_CD IS NOT NULL
			AND x.TRD_CALC_NO IS NOT NULL
			AND x.ALC_REC_TYP != MGC_ALC_REC_TYP.CARRY THEN
				SELECT	COUNT(*)
				INTO	L_CNT
				FROM	MAM_GRP_WG w
				WHERE	0=0
				AND	w.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	w.WG_CD = x.TRD_WG_CD
				;

				IF L_CNT > 0 THEN
					GOTO NEXT_LOOP1 ;
				END IF ;
			END IF ;
			L_SEL_REC := F_GET_ALC_RATE_SEL(x.WG_CD, x.ALC_AC_CD, x.DPT_CD) ;
			IF L_SEL_REC.PRE_ALC_RATE_CD != G_NULL_VAL THEN
				P_SET_WORK_PRE_ALC(x) ;
			ELSIF G_NOT_AMT_FLG = '0' THEN
				P_SET_WORK_ITM_ALC(x) ;
			END IF ;

			<<NEXT_LOOP1>>
				NULL ;
		END LOOP ;

	ELSIF G_ARG.SA_TYP = G_PLN AND G_ARG.PRE_ALC_CALC_TYP = G_PRE_ALC_NON AND G_NOT_AMT_FLG = '0' THEN

		FOR x IN (
			SELECT	t.*
			FROM	MGT_PLN_ALC_AMT t
			WHERE	0=0
			AND	t.CALC_CTG_CD = I_CALC_CTG_CD
			AND	t.YM BETWEEN G_ARG.ST_YM AND G_ARG.END_YM
			AND	t.PRE_ALC_FIN_FLG = '0'
			AND	(
				t.WG_CD = G_ARG.RUNTIME_WG_CD
				OR EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG m
					WHERE	0=0
					AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	m.WG_CD = t.WG_CD
					)
				)
			)
		LOOP
			x.WG_CD := NVL(G_ARG.RUNTIME_WG_CD, x.WG_CD) ;

			IF x.ALC_REC_TYP = C_MY_WG THEN
				P_SET_WORK_ITM_ALC(x) ;
			ELSE
				L_SEL_REC := F_GET_ALC_RATE_SEL(x.WG_CD, x.ALC_AC_CD, x.DPT_CD) ;
				IF L_SEL_REC.PRE_ALC_RATE_CD = G_NULL_VAL THEN
					P_SET_WORK_ITM_ALC(x) ;
				END IF ;
			END IF ;
		END LOOP ;

	ELSIF G_ARG.SA_TYP = G_ACT AND G_ARG.PRE_ALC_CALC_TYP = G_PRE_ALC_CALC THEN

		FOR x IN (
			SELECT	t.*
			FROM	MGT_ACT_ALC_AMT t
			WHERE	0=0
			AND	t.CALC_CTG_CD = I_CALC_CTG_CD
			AND	t.YM BETWEEN G_ARG.ST_YM AND G_ARG.END_YM
			AND	t.ALC_REC_TYP != C_MY_WG
			AND	(
				t.WG_CD = G_ARG.RUNTIME_WG_CD
				OR EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG m
					WHERE	0=0
					AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	m.WG_CD = t.WG_CD
					)
				)
			)
		LOOP
			x.WG_CD := NVL(G_ARG.RUNTIME_WG_CD, x.WG_CD) ;

			IF x.TRD_WG_CD IS NOT NULL
			AND x.TRD_CALC_GRP_CD IS NOT NULL
			AND x.TRD_CALC_NO IS NOT NULL
			AND x.ALC_REC_TYP != MGC_ALC_REC_TYP.CARRY THEN
				SELECT	COUNT(*)
				INTO	L_CNT
				FROM	MAM_GRP_WG w
				WHERE	0=0
				AND	w.CALC_GRP_CD = G_ARG.CALC_GRP_CD
				AND	w.WG_CD = x.TRD_WG_CD
				;

				IF L_CNT > 0 THEN
					GOTO NEXT_LOOP3 ;
				END IF ;
			END IF ;

			L_SEL_REC := F_GET_ALC_RATE_SEL(x.WG_CD, x.ALC_AC_CD, x.DPT_CD) ;
			IF L_SEL_REC.PRE_ALC_RATE_CD != G_NULL_VAL THEN
				P_SET_WORK_PRE_ALC(x) ;
			ELSIF G_NOT_AMT_FLG = '0' THEN
				P_SET_WORK_ITM_ALC(x) ;
			END IF ;

			<<NEXT_LOOP3>>
				NULL ;
		END LOOP ;

	ELSIF G_ARG.SA_TYP = G_ACT AND G_ARG.PRE_ALC_CALC_TYP = G_PRE_ALC_NON AND G_NOT_AMT_FLG = '0' THEN

		FOR x IN (
			SELECT	t.*
			FROM	MGT_ACT_ALC_AMT t
			WHERE	0=0
			AND	t.CALC_CTG_CD = I_CALC_CTG_CD
			AND	t.YM BETWEEN G_ARG.ST_YM AND G_ARG.END_YM
			AND	t.PRE_ALC_FIN_FLG = '0'
			AND	(
				t.WG_CD = G_ARG.RUNTIME_WG_CD
				OR EXISTS (
					SELECT	'X'
					FROM	MAM_GRP_WG m
					WHERE	0=0
					AND	m.CALC_GRP_CD = G_ARG.CALC_GRP_CD
					AND	m.WG_CD = t.WG_CD
					)
				)
			)
		LOOP
			x.WG_CD := NVL(G_ARG.RUNTIME_WG_CD, x.WG_CD) ;

			IF x.ALC_REC_TYP = C_MY_WG THEN
				P_SET_WORK_ITM_ALC(x) ;
			ELSE
				L_SEL_REC := F_GET_ALC_RATE_SEL(x.WG_CD, x.ALC_AC_CD, x.DPT_CD) ;
				IF L_SEL_REC.PRE_ALC_RATE_CD = G_NULL_VAL THEN
					P_SET_WORK_ITM_ALC(x) ;
				END IF ;
			END IF ;
		END LOOP ;
	END IF ;

END P_SET_INPUT_AMT ;


