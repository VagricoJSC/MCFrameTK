CREATE OR REPLACE PACKAGE BODY MGPA_PRE_RATE
IS
	G_MSG	FCPA_ERR.MSG_BINDER ;

	G_TERM	MAPA_META.YM%TYPE ;

	G_CO		MAM_CO%ROWTYPE ;
	G_CUR		MAM_CUR%ROWTYPE ;
	G_ALC_RATE	MAM_PRE_ALC_RATE%ROWTYPE ;
	G_ALC_CTG	MAM_PRE_ALC_CTG%ROWTYPE ;

	TYPE RATE_LIST IS TABLE OF MGT_PRE_RATE_MLY%ROWTYPE INDEX BY BINARY_INTEGER ;
	RATE 	RATE_LIST ;
	i	INTEGER ;

PROCEDURE P_WK (
	I_SA_TYP	IN MAPA_META.SA_TYP%TYPE,
	I_YM_FROM	IN MAPA_META.YM%TYPE,
	I_YM_TO		IN MAPA_META.YM%TYPE,
	I_WG_CD		IN MAPA_META.WG_CD%TYPE,
	I_CALC_CTG_CD	IN MAPA_META.CALC_CTG_CD%TYPE
)
/**************************************************************************
<SYNOPSIS>
	工数データからの比率作成処理
<REMARKS>

<ARGUMENTS>
<IN>	I_SA_TYP
		予実区分
<IN>	I_YM_FROM
		取得先年月ＦＲＯＭ
<IN>	I_YM_TO
		取得先年月ＴＯ
<IN>	I_WG_CD
		ワーキンググループＣＤ
<IN>	I_CALC_CTG_CD
		計算カテゴリＣＤ
<HISTORY>
**************************************************************************/
AS
	L_CNT	NUMBER ;
	L_VAL	MGT_PRE_RATE_MLY.PRE_ALC_RATE%TYPE ;
	L_TMP1	MGT_PRE_RATE_MLY.PRE_ALC_RATE%TYPE ;
	L_TMP2	MGT_PRE_RATE_MLY.PRE_ALC_RATE%TYPE ;
BEGIN
	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_PRE_ALC_WK m
	WHERE	0=0
	AND	m.TERM = G_TERM
	AND	m.CALC_CTG_CD = I_CALC_CTG_CD
	AND	m.WG_CD = I_WG_CD
	AND	m.PRE_ALC_RATE_CD = G_ALC_RATE.PRE_ALC_RATE_CD
	;

	IF L_CNT = 0 THEN
		G_MSG := FCPA_ERR.MSG_BINDER(
				FCPA_DATE_UTIL.F_TO_CHAR(G_TERM, FCPA_DATE_UTIL.Y4M),
				I_WG_CD,
				I_CALC_CTG_CD,
				G_ALC_RATE.PRE_ALC_RATE_CD
				) ;
		FCPA_ERR.RAISE_APP_ERR('MGBGD0005', G_MSG) ;
	END IF ;

	IF I_SA_TYP = MAC_SA_TYP.PLN THEN
		--工数計画データから作成
		FOR t IN 1..i LOOP
			IF RATE(t).DPT_CD IS NOT NULL THEN
				MAPA_DPT_LOC.P_SET_DPT_LOC(G_TERM, RATE(t).DPT_CD) ; --品目工数用
				MAPA_DPT_LOC.P_SET_DPT_DPT(G_TERM, RATE(t).DPT_CD) ; --品目外工数用
			END IF ;
			IF RATE(t).CTG_CD IS NOT NULL THEN
				MAPA_CTG_ITM.P_SET_CTG_ITM(G_TERM, RATE(t).CTG_CD) ; --品目工数用
				MAPA_CTG_ITM.P_SET_CTG_CTG(G_TERM, RATE(t).CTG_CD) ; --品目外工数用
			END IF ;

			SELECT	SUM(t1.WK_COST * NVL(m1.COEF_VAL, 1))
			INTO	L_VAL
			FROM	MGW_CALC_CTG_WG x,
				MGT_PLN_ITM_WK t1,
				MAM_PRE_ALC_WK m1, MAM_LOC m2
			WHERE	0=0
			AND	x.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	x.WG_CD = t1.WG_CD
			AND	t1.WK_COST_CD = m1.WK_COST_CD
			AND	t1.LOC_CD = m2.LOC_CD(+)
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	m1.TERM = G_TERM
			AND	m1.CALC_CTG_CD = I_CALC_CTG_CD
			AND	m1.WG_CD = I_WG_CD
			AND	m1.PRE_ALC_RATE_CD = G_ALC_RATE.PRE_ALC_RATE_CD
			AND	(RATE(t).DPT_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_DPT_LOC w
						WHERE	0=0
						AND	w.LOC_CD = t1.LOC_CD
						AND	(
							w.OPER_CD = t1.OPER_CD
							OR
							w.OPER_CD IS NULL AND w.OPER_NULL_FLG = '0'
							OR
							w.OPER_CD IS NULL AND w.OPER_NULL_FLG = '1' AND t1.OPER_CD IS NULL
							)
						)
				)
			AND	(RATE(t).LOC_CD IS NULL OR RATE(t).LOC_CD = t1.LOC_CD)
			AND	(RATE(t).OPER_CD IS NULL OR RATE(t).OPER_CD = t1.OPER_CD)
			AND	(RATE(t).BP_CD IS NULL OR RATE(t).BP_CD = m2.SPPL_CD)
			AND	(RATE(t).CTG_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_CTG_ITM w
						WHERE	0=0
						AND	w.ITM_CD = t1.ITM_CD
						AND	w.ITM_SUB1 = t1.ITM_SUB1
						AND	w.ITM_SUB2 = t1.ITM_SUB2
						AND	w.ITM_SUB3 = t1.ITM_SUB3
						)
				)
			AND	(RATE(t).ITM_CD IS NULL OR RATE(t).ITM_CD = t1.ITM_CD)
			AND	(RATE(t).ITM_SUB1 IS NULL OR RATE(t).ITM_SUB1 = t1.ITM_SUB1)
			AND	(RATE(t).ITM_SUB2 IS NULL OR RATE(t).ITM_SUB2 = t1.ITM_SUB2)
			AND	(RATE(t).ITM_SUB3 IS NULL OR RATE(t).ITM_SUB3 = t1.ITM_SUB3)
			AND	(RATE(t).LOT_NO IS NULL OR RATE(t).LOT_NO = t1.LOT_NO)
			AND	(RATE(t).SUBLOT_NO IS NULL OR RATE(t).SUBLOT_NO = t1.SUBLOT_NO)
			AND	(RATE(t).SNO1 IS NULL OR RATE(t).SNO1 = t1.SNO1)
			AND	(RATE(t).SNO2 IS NULL OR RATE(t).SNO2 = t1.SNO2)
			AND	(RATE(t).SNO3 IS NULL OR RATE(t).SNO3 = t1.SNO3)
			AND	(RATE(t).SNO4 IS NULL OR RATE(t).SNO4 = t1.SNO4)
			AND	(RATE(t).TRD_WG_CD IS NULL OR RATE(t).TRD_WG_CD = t1.WG_CD)
			AND	RATE(t).ITM_MFG_INST_NO IS NULL
			AND	RATE(t).IV_NO IS NULL
			AND	RATE(t).PO_NO IS NULL
			AND	RATE(t).SLO_NO IS NULL
			;

			L_TMP1 := NVL(L_VAL, 0) * RATE(t).PRE_ALC_RATE ;

			SELECT	SUM(t1.WK_COST * NVL(m1.COEF_VAL, 1))
			INTO	L_VAL
			FROM	MGW_CALC_CTG_WG x,
				MGT_PLN_OTHER_WK t1,
				MAM_PRE_ALC_WK m1, MAM_LOC m2
			WHERE	0=0
			AND	x.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	x.WG_CD = t1.WG_CD
			AND	t1.WK_COST_CD = m1.WK_COST_CD
			AND	t1.LOC_CD = m2.LOC_CD(+)
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	m1.TERM = G_TERM
			AND	m1.CALC_CTG_CD = I_CALC_CTG_CD
			AND	m1.WG_CD = I_WG_CD
			AND	m1.PRE_ALC_RATE_CD = G_ALC_RATE.PRE_ALC_RATE_CD
			AND	(RATE(t).DPT_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_DPT_DPT w
						WHERE	0=0
						AND	w.DPT_CD = t1.DPT_CD
						)
				)
			AND	(RATE(t).LOC_CD IS NULL OR RATE(t).LOC_CD = t1.LOC_CD)
			AND	(RATE(t).OPER_CD IS NULL OR RATE(t).OPER_CD = t1.OPER_CD)
			AND	(RATE(t).BP_CD IS NULL OR RATE(t).BP_CD = m2.SPPL_CD)
			AND	(RATE(t).CTG_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_CTG_CTG w
						WHERE	0=0
						AND	w.CTG_CD = t1.CTG_CD
						)
				)

			AND	RATE(t).ITM_CD IS NULL
			AND	(RATE(t).LOT_NO IS NULL OR RATE(t).LOT_NO = t1.LOT_NO)
			AND	(RATE(t).SUBLOT_NO IS NULL OR RATE(t).SUBLOT_NO = t1.SUBLOT_NO)
			AND	(RATE(t).SNO1 IS NULL OR RATE(t).SNO1 = t1.SNO1)
			AND	(RATE(t).SNO2 IS NULL OR RATE(t).SNO2 = t1.SNO2)
			AND	(RATE(t).SNO3 IS NULL OR RATE(t).SNO3 = t1.SNO3)
			AND	(RATE(t).SNO4 IS NULL OR RATE(t).SNO4 = t1.SNO4)
			AND	(RATE(t).TRD_WG_CD IS NULL OR RATE(t).TRD_WG_CD = t1.WG_CD)
			AND	RATE(t).ITM_MFG_INST_NO IS NULL
			AND	RATE(t).IV_NO IS NULL
			AND	RATE(t).PO_NO IS NULL
			AND	RATE(t).SLO_NO IS NULL
			;

			L_TMP2 := NVL(L_VAL, 0) * RATE(t).PRE_ALC_RATE ;

			RATE(t).PRE_ALC_RATE := L_TMP1 + L_TMP2 ;
		END LOOP ;
	ELSE
		--工数実績データから作成
		FOR t IN 1..i LOOP
			IF RATE(t).DPT_CD IS NOT NULL THEN
				MAPA_DPT_LOC.P_SET_DPT_LOC(G_TERM, RATE(t).DPT_CD) ; --指図工数用
				MAPA_DPT_LOC.P_SET_DPT_DPT(G_TERM, RATE(t).DPT_CD) ; --指図外工数用
			END IF ;
			IF RATE(t).CTG_CD IS NOT NULL THEN
				MAPA_CTG_ITM.P_SET_CTG_ITM(G_TERM, RATE(t).CTG_CD) ; --指図工数用
				MAPA_CTG_ITM.P_SET_CTG_CTG(G_TERM, RATE(t).CTG_CD) ; --指図外工数用
			END IF ;

			SELECT	SUM(t1.WK_COST * NVL(m1.COEF_VAL, 1))
			INTO	L_VAL
			FROM	MGW_CALC_CTG_WG x,
				MGT_ACT_INST_WK t1, MGT_ITM_MFG_INST t2, MGT_INST_OPER t3,
				MAM_PRE_ALC_WK m1
			WHERE	0=0
			AND	x.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	x.WG_CD = t1.WG_CD
			AND	t1.ITM_CD = t2.ITM_CD
			AND	t1.ITM_SUB1 = t2.ITM_SUB1
			AND	t1.ITM_SUB2 = t2.ITM_SUB2
			AND	t1.ITM_SUB3 = t2.ITM_SUB3
			AND	t1.CALC_CTG_CD = t2.CALC_CTG_CD
			AND	t1.WG_CD = t2.WG_CD
			AND	t1.ITM_MFG_INST_NO = t2.ITM_MFG_INST_NO
			AND	t1.MFG_ACT_NO = t2.MFG_ACT_NO
			AND	t1.ITM_CD = t3.ITM_CD(+)
			AND	t1.ITM_SUB1 = t3.ITM_SUB1(+)
			AND	t1.ITM_SUB2 = t3.ITM_SUB2(+)
			AND	t1.ITM_SUB3 = t3.ITM_SUB3(+)
			AND	t1.CALC_CTG_CD = t3.CALC_CTG_CD(+)
			AND	t1.WG_CD = t3.WG_CD(+)
			AND	t1.ITM_MFG_INST_NO = t3.ITM_MFG_INST_NO(+)
			AND	t1.OPER_ACT_NO = t3.OPER_ACT_NO(+)
			AND	t1.MFG_ACT_NO = t3.MFG_ACT_NO(+)
			AND	t1.WK_COST_CD = m1.WK_COST_CD
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	m1.TERM = G_TERM
			AND	m1.CALC_CTG_CD = I_CALC_CTG_CD
			AND	m1.WG_CD = I_WG_CD
			AND	m1.PRE_ALC_RATE_CD = G_ALC_RATE.PRE_ALC_RATE_CD
			AND	(RATE(t).DPT_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_DPT_LOC w
						WHERE	0=0
						AND	w.LOC_CD = t1.LOC_CD
						AND	(
							w.OPER_CD = t3.OPER_CD
							OR
							w.OPER_CD IS NULL AND w.OPER_NULL_FLG = '0'
							OR
							w.OPER_CD IS NULL AND w.OPER_NULL_FLG = '1' AND t3.OPER_CD IS NULL
							)
						)
				)
			AND	(RATE(t).LOC_CD IS NULL OR RATE(t).LOC_CD = t1.LOC_CD)
			AND	(RATE(t).OPER_CD IS NULL OR RATE(t).OPER_CD = t3.OPER_CD)
			AND	(RATE(t).BP_CD IS NULL OR RATE(t).BP_CD = t2.SPPL_CD)
			AND	(RATE(t).CTG_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_CTG_ITM w
						WHERE	0=0
						AND	w.ITM_CD = t1.ITM_CD
						AND	w.ITM_SUB1 = t1.ITM_SUB1
						AND	w.ITM_SUB2 = t1.ITM_SUB2
						AND	w.ITM_SUB3 = t1.ITM_SUB3
						)
				)
			AND	(RATE(t).ITM_CD IS NULL OR RATE(t).ITM_CD = t1.ITM_CD)
			AND	(RATE(t).ITM_SUB1 IS NULL OR RATE(t).ITM_SUB1 = t1.ITM_SUB1)
			AND	(RATE(t).ITM_SUB2 IS NULL OR RATE(t).ITM_SUB2 = t1.ITM_SUB2)
			AND	(RATE(t).ITM_SUB3 IS NULL OR RATE(t).ITM_SUB3 = t1.ITM_SUB3)
			AND	(RATE(t).LOT_NO IS NULL OR RATE(t).LOT_NO = t2.LOT_NO)
			AND	(RATE(t).SUBLOT_NO IS NULL OR RATE(t).SUBLOT_NO = t2.SUBLOT_NO)
			AND	(RATE(t).SNO1 IS NULL OR RATE(t).SNO1 = t2.SNO1)
			AND	(RATE(t).SNO2 IS NULL OR RATE(t).SNO2 = t2.SNO2)
			AND	(RATE(t).SNO3 IS NULL OR RATE(t).SNO3 = t2.SNO3)
			AND	(RATE(t).SNO4 IS NULL OR RATE(t).SNO4 = t2.SNO4)
			AND	(RATE(t).TRD_WG_CD IS NULL OR RATE(t).TRD_WG_CD = t1.WG_CD)
			AND	(RATE(t).ITM_MFG_INST_NO IS NULL OR RATE(t).ITM_MFG_INST_NO = t1.ITM_MFG_INST_NO)
			AND	(RATE(t).IV_NO IS NULL OR RATE(t).IV_NO = t2.IV_NO)
			AND	(RATE(t).PO_NO IS NULL OR RATE(t).PO_NO = t2.PO_NO)
			AND	(RATE(t).SLO_NO IS NULL OR RATE(t).SLO_NO = t2.SLO_NO)
			;

			L_TMP1 := NVL(L_VAL, 0) * RATE(t).PRE_ALC_RATE ;

			SELECT	SUM(t1.WK_COST * NVL(m1.COEF_VAL, 1))
			INTO	L_VAL
			FROM	MGW_CALC_CTG_WG x,
				MGT_ACT_OTHER_WK t1,
				MAM_PRE_ALC_WK m1, MAM_LOC m2
			WHERE	0=0
			AND	x.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	x.WG_CD = t1.WG_CD
			AND	t1.WK_COST_CD = m1.WK_COST_CD
			AND	t1.LOC_CD = m2.LOC_CD(+)
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	m1.TERM = G_TERM
			AND	m1.CALC_CTG_CD = I_CALC_CTG_CD
			AND	m1.WG_CD = I_WG_CD
			AND	m1.PRE_ALC_RATE_CD = G_ALC_RATE.PRE_ALC_RATE_CD
			AND	(RATE(t).DPT_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_DPT_DPT w
						WHERE	0=0
						AND	w.DPT_CD = t1.DPT_CD
						)
				)
			AND	(RATE(t).LOC_CD IS NULL OR RATE(t).LOC_CD = t1.LOC_CD)
			AND	(RATE(t).OPER_CD IS NULL OR RATE(t).OPER_CD = t1.OPER_CD)
			AND	(RATE(t).BP_CD IS NULL OR RATE(t).BP_CD = m2.SPPL_CD)
			AND	(RATE(t).CTG_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_CTG_CTG w
						WHERE	0=0
						AND	w.CTG_CD = t1.CTG_CD
						)
				)
			AND	RATE(t).ITM_CD IS NULL
			AND	(RATE(t).LOT_NO IS NULL OR RATE(t).LOT_NO = t1.LOT_NO)
			AND	(RATE(t).SUBLOT_NO IS NULL OR RATE(t).SUBLOT_NO = t1.SUBLOT_NO)
			AND	(RATE(t).SNO1 IS NULL OR RATE(t).SNO1 = t1.SNO1)
			AND	(RATE(t).SNO2 IS NULL OR RATE(t).SNO2 = t1.SNO2)
			AND	(RATE(t).SNO3 IS NULL OR RATE(t).SNO3 = t1.SNO3)
			AND	(RATE(t).SNO4 IS NULL OR RATE(t).SNO4 = t1.SNO4)
			AND	(RATE(t).TRD_WG_CD IS NULL OR RATE(t).TRD_WG_CD = t1.WG_CD)
			AND	RATE(t).ITM_MFG_INST_NO IS NULL
			AND	RATE(t).IV_NO IS NULL
			AND	RATE(t).PO_NO IS NULL
			AND	RATE(t).SLO_NO IS NULL
			;

			L_TMP2 := NVL(L_VAL, 0) * RATE(t).PRE_ALC_RATE ;

			RATE(t).PRE_ALC_RATE := L_TMP1 + L_TMP2 ;
		END LOOP ;
	END IF ;

END P_WK ;

PROCEDURE P_MFG (
	I_SA_TYP	IN MAPA_META.SA_TYP%TYPE,
	I_YM_FROM	IN MAPA_META.YM%TYPE,
	I_YM_TO		IN MAPA_META.YM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	製造データからの比率作成処理
<REMARKS>

<ARGUMENTS>
<IN>	I_SA_TYP
		予実区分
<IN>	I_YM_FROM
		取得先年月ＦＲＯＭ
<IN>	I_YM_TO
		取得先年月ＴＯ
<HISTORY>
**************************************************************************/
AS
	L_VAL		MGT_PRE_RATE_MLY.PRE_ALC_RATE%TYPE ;
	L_QTY_FLG	MAPA_META.FLG%TYPE ;
BEGIN
	IF G_ALC_RATE.PRE_ALC_SET_TYP = MAC_PRE_ALC_SET_TYP.MFG_QTY THEN
		L_QTY_FLG := '1' ;
	ELSE
		L_QTY_FLG := '0' ;
	END IF ;

	IF I_SA_TYP = MAC_SA_TYP.PLN THEN
		IF L_QTY_FLG = '0' THEN
			MGPA_XCHNG.P_INI(G_TERM, G_CO.PURC_XRATE_CD) ;
		END IF ;

		--製造計画データから作成
		FOR t IN 1..i LOOP
			IF RATE(t).DPT_CD IS NOT NULL THEN
				MAPA_DPT_LOC.P_SET_DPT_LOC(G_TERM, RATE(t).DPT_CD) ;
			END IF ;
			IF RATE(t).CTG_CD IS NOT NULL THEN
				MAPA_CTG_ITM.P_SET_CTG_ITM(G_TERM, RATE(t).CTG_CD) ;
			END IF ;

			SELECT	DECODE(L_QTY_FLG, '1',
					SUM(MGPA_UNIT.F_GET_CONV_QTY(
						t1.QTY,
						m2.CONV_BASE_QTY,
						m2.CONV_QTY,
						m3.DEC_PLACE,
						m3.RND_TYP)
					),
					SUM(MGPA_XCHNG.F_XCHNG(t1.CUR_CD, G_CO.BASE_CUR_CD,
						G_CUR.AMT_DEC_PLACE, G_CO.XRATE_RND_TYP, t1.AMT, 'MGT_PLN_MFG')
					)
				)
			INTO	L_VAL
			FROM	MGW_CALC_CTG_WG x,
				MGT_PLN_MFG t1,
				MAM_LOC m1,
				MAVM_ITM_UNIT m2,
				MAM_ITM_CMN_ m3
			WHERE	0=0
			AND	x.CALC_CTG_CD = t1.CALC_CTG_CD
			AND	x.WG_CD = t1.WG_CD
			AND	t1.LOC_CD = m1.LOC_CD(+)
			AND	t1.ITM_CD = m2.ITM_CD(+)
			AND	t1.ITM_SUB1 = m2.ITM_SUB1(+)
			AND	t1.ITM_SUB2 = m2.ITM_SUB2(+)
			AND	t1.ITM_SUB3 = m2.ITM_SUB3(+)
			AND	t1.UNIT_CD = m2.UNIT_CD(+)
			AND	t1.ITM_CD = m3.ITM_CD(+)
			AND	t1.ITM_SUB1 = m3.ITM_SUB1(+)
			AND	t1.ITM_SUB2 = m3.ITM_SUB2(+)
			AND	t1.ITM_SUB3 = m3.ITM_SUB3(+)
			AND	t1.YM BETWEEN I_YM_FROM AND I_YM_TO
			AND	(RATE(t).DPT_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_DPT_LOC w
						WHERE	0=0
						AND	w.LOC_CD = t1.LOC_CD
						AND	w.OPER_CD IS NULL
						)
				)
			AND	(RATE(t).LOC_CD IS NULL OR RATE(t).LOC_CD = t1.LOC_CD)
			AND	RATE(t).OPER_CD IS NULL
			AND	(RATE(t).BP_CD IS NULL OR RATE(t).BP_CD = m1.SPPL_CD)
			AND	(RATE(t).CTG_CD IS NULL
					OR EXISTS (
						SELECT	'X'
						FROM	MAW_CTG_ITM w
						WHERE	0=0
						AND	w.ITM_CD = t1.ITM_CD
						AND	w.ITM_SUB1 = t1.ITM_SUB1
						AND	w.ITM_SUB2 = t1.ITM_SUB2
						AND	w.ITM_SUB3 = t1.ITM_SUB3
						)
				)
			AND	(RATE(t).ITM_CD IS NULL OR RATE(t).ITM_CD = t1.ITM_CD)
			AND	(RATE(t).ITM_SUB1 IS NULL OR RATE(t).ITM_SUB1 = t1.ITM_SUB1)
			AND	(RATE(t).ITM_SUB2 IS NULL OR RATE(t).ITM_SUB2 = t1.ITM_SUB2)
			AND	(RATE(t).ITM_SUB3 IS NULL OR RATE(t).ITM_SUB3 = t1.ITM_SUB3)
			AND	(RATE(t).LOT_NO IS NULL OR RATE(t).LOT_NO = t1.LOT_NO)
			AND	(RATE(t).SUBLOT_NO IS NULL OR RATE(t).SUBLOT_NO = t1.SUBLOT_NO)
