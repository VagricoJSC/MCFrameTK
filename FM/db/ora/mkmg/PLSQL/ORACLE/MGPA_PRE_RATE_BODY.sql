			AND	(RATE(t).LOT_NO IS NULL OR RATE(t).LOT_NO = t1.LOT_NO)
			AND	(RATE(t).SUBLOT_NO IS NULL OR RATE(t).SUBLOT_NO = t1.SUBLOT_NO)
			AND	(RATE(t).SNO1 IS NULL OR RATE(t).SNO1 = t1.SNO1)
			AND	(RATE(t).SNO2 IS NULL OR RATE(t).SNO2 = t1.SNO2)
			AND	(RATE(t).SNO3 IS NULL OR RATE(t).SNO3 = t1.SNO3)
			AND	(RATE(t).SNO4 IS NULL OR RATE(t).SNO4 = t1.SNO4)
			AND	(RATE(t).TRD_WG_CD IS NULL OR RATE(t).TRD_WG_CD = t1.WG_CD)
			AND	RATE(t).ITM_MFG_INST_NO IS NULL
			AND	(RATE(t).IV_NO IS NULL OR RATE(t).IV_NO = t1.IV_NO)
			AND	RATE(t).PO_NO IS NULL
			AND	(RATE(t).SLO_NO IS NULL OR RATE(t).SLO_NO = t1.SLO_NO)
			;

			RATE(t).PRE_ALC_RATE := NVL(L_VAL, 0) * RATE(t).PRE_ALC_RATE ;
		END LOOP ;
	END IF ;
END P_SLS ;

PROCEDURE P_MAIN (
	I_SA_TYP		IN MAPA_META.SA_TYP%TYPE,
	I_YM			IN MAPA_META.YM%TYPE,
	I_YM_FROM		IN MAPA_META.YM%TYPE,
	I_YM_TO			IN MAPA_META.YM%TYPE,
	I_WG_CD			IN MAPA_META.WG_CD%TYPE,
	I_CALC_CTG_CD		IN MAPA_META.CALC_CTG_CD%TYPE,
	I_PRE_ALC_RATE_CD	IN MAPA_META.PRE_ALC_RATE_CD%TYPE
)
/**************************************************************************
<SYNOPSIS>
	一次配賦比率作成メイン処理
<REMARKS>

<ARGUMENTS>
<IN>	I_SA_TYP
		予実区分
<IN>	I_YM
		作成対象年月
<IN>	I_YM_FROM
		取得先年月ＦＲＯＭ
<IN>	I_YM_TO
		取得先年月ＴＯ
<IN>	I_WG_CD
		ワーキンググループＣＤ
<IN>	I_CALC_CTG_CD
		計算カテゴリＣＤ
<IN>	I_PRE_ALC_RATE_CD
		一次配賦基準ＣＤ
<HISTORY>
**************************************************************************/
AS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	C_ALC_OVER	CONSTANT MAPA_META.PRE_ALC_TYP%TYPE := MAC_PRE_ALC_TYP.NON_OVER ;
	C_ALC_NULL	CONSTANT MAPA_META.PRE_ALC_TYP%TYPE := MAC_PRE_ALC_TYP.NON_NULL ;
	C_ALC_TGT	CONSTANT MAPA_META.PRE_ALC_TYP%TYPE := MAC_PRE_ALC_TYP.TARGET ;

	L_CNT		NUMBER ;
	L_DATA_SA_TYP	MAPA_META.SA_TYP%TYPE ;
	L_KEY_SA_TYP	MAPA_META.SA_TYP%TYPE ;
	L_KEY_YM	MAPA_META.YM%TYPE ;

	L_PTN_REC	MAM_PRE_ALC_PTN%ROWTYPE ;
BEGIN
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0018',
		I_SA_TYP,
		FCPA_DATE_UTIL.F_TO_CHAR(I_YM, FCPA_DATE_UTIL.Y4M),
		I_WG_CD,
		I_CALC_CTG_CD,
		I_PRE_ALC_RATE_CD) ;

	G_CO := MAPA_CO.F_GET_CO_REC() ;
	G_CUR := MGPA_XCHNG.F_GET_CUR(G_CO.BASE_CUR_CD) ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_PRE_ALC_RATE m
	WHERE	0=0
	AND	m.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
	AND	m.PRE_ALC_SET_TYP IS NOT NULL
	;

	IF L_CNT = 0 THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_PRE_ALC_RATE_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBGD0001', G_MSG) ;
	END IF ;

	SELECT	m.*
	INTO	G_ALC_RATE
	FROM	MAM_PRE_ALC_RATE m
	WHERE	0=0
	AND	m.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
	;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_PRE_ALC_PTN m
	WHERE	0=0
	AND	m.PRE_ALC_PTN_CD = G_ALC_RATE.PRE_ALC_PTN_CD
	;

	IF L_CNT = 0 THEN
		G_MSG := FCPA_ERR.MSG_BINDER(G_ALC_RATE.PRE_ALC_PTN_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0046', G_MSG) ;
	END IF ;

	SELECT	m.*
	INTO	L_PTN_REC
	FROM	MAM_PRE_ALC_PTN m
	WHERE	0=0
	AND	m.PRE_ALC_PTN_CD = G_ALC_RATE.PRE_ALC_PTN_CD
	;

	IF I_SA_TYP = MAC_SA_TYP.PLN AND G_ALC_RATE.PLN_MLY_FLG = '0' THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_PRE_ALC_RATE_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBGD0002', G_MSG) ;
	END IF ;
	IF I_SA_TYP = MAC_SA_TYP.ACT AND G_ALC_RATE.ACT_MLY_FLG = '0' THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_PRE_ALC_RATE_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBGD0003', G_MSG) ;
	END IF ;

	G_TERM := MAPA_TERM.F_GET_TERM(I_YM) ;
	BEGIN
		SELECT	m.*
		INTO	G_ALC_CTG
		FROM	MAM_PRE_ALC_CTG m
		WHERE	0=0
		AND	m.TERM = G_TERM
		AND	m.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
		AND	m.CALC_CTG_CD = I_CALC_CTG_CD
		AND	m.WG_CD = I_WG_CD
		;
	EXCEPTION
	WHEN NO_DATA_FOUND THEN
		G_MSG := FCPA_ERR.MSG_BINDER(
				FCPA_DATE_UTIL.F_TO_CHAR(G_TERM, FCPA_DATE_UTIL.Y4M),
				I_WG_CD,
				I_CALC_CTG_CD,
				I_PRE_ALC_RATE_CD
				) ;
		FCPA_ERR.RAISE_APP_ERR('MGBGD0004', G_MSG) ;
	END ;

	DELETE MGW_CALC_CTG_WG w ;
	IF I_SA_TYP = MAC_SA_TYP.PLN THEN
		L_DATA_SA_TYP := NVL(G_ALC_CTG.DATA_PLN_SA_TYP, I_SA_TYP) ;
		L_KEY_SA_TYP := NVL(G_ALC_CTG.KEY_PLN_SA_TYP, I_SA_TYP) ;
		L_KEY_YM := NVL(G_ALC_CTG.KEY_PLN_YM, G_TERM) ;
	ELSE
		L_DATA_SA_TYP := NVL(G_ALC_CTG.DATA_ACT_SA_TYP, I_SA_TYP) ;
		L_KEY_SA_TYP := NVL(G_ALC_CTG.KEY_ACT_SA_TYP, I_SA_TYP) ;
		L_KEY_YM := NVL(G_ALC_CTG.KEY_ACT_YM, G_TERM) ;
	END IF ;

	INSERT INTO MGW_CALC_CTG_WG (CALC_CTG_CD, WG_CD)
	SELECT	m.DATA_CALC_CTG_CD, m.DATA_WG_CD
	FROM	MAM_PRE_RATE_TGT m
	WHERE	0=0
	AND	m.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
	AND	m.CALC_CTG_CD = I_CALC_CTG_CD
	AND	m.TERM = G_TERM
	AND	m.SA_TYP = I_SA_TYP
	AND	m.WG_CD = I_WG_CD
	;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGW_CALC_CTG_WG w
	;

	IF L_CNT = 0 THEN
		INSERT INTO MGW_CALC_CTG_WG (CALC_CTG_CD, WG_CD) VALUES (I_CALC_CTG_CD, I_WG_CD) ;
	END IF ;

	i := 0 ;
	RATE.DELETE ;
	FOR x IN (
		SELECT
			t.PRE_ALC_RATE_CD,
			t.SA_TYP,
			t.YM,
			t.CALC_CTG_CD,
			t.WG_CD,
			t.DPT_CD,
			t.LOC_CD,
			t.OPER_CD,
			t.BP_CD,
			t.CTG_CD,
			t.ITM_CD,
			t.ITM_SUB1,
			t.ITM_SUB2,
			t.ITM_SUB3,
			t.LOT_NO,
			t.SUBLOT_NO,
			t.SNO1,
			t.SNO2,
			t.SNO3,
			t.SNO4,
			t.ITM_MFG_INST_NO,
			t.IV_NO,
			t.PO_NO,
			t.SLO_NO,
			t.ALC_AC_CD,
			t.TRD_WG_CD,
			t.PRE_ALC_RATE,
			t.ADJ_FLG,
			t.RMRKS,
			t.SUB_CHAR1,
			t.SUB_CHAR2,
			t.SUB_CHAR3
		FROM	MGT_PRE_RATE_MLY t
		WHERE	0=0
		AND	t.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
		AND	t.SA_TYP = L_KEY_SA_TYP
		AND	t.YM = L_KEY_YM
		AND	t.CALC_CTG_CD = I_CALC_CTG_CD
		AND	t.WG_CD = I_WG_CD
		FOR UPDATE NOWAIT
		)
	LOOP
		IF x.DPT_CD IS NOT NULL AND NVL(L_PTN_REC.DPT_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.LOC_CD IS NOT NULL AND NVL(L_PTN_REC.LOC_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.OPER_CD IS NOT NULL AND NVL(L_PTN_REC.OPER_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.BP_CD IS NOT NULL AND NVL(L_PTN_REC.BP_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.CTG_CD IS NOT NULL AND NVL(L_PTN_REC.CTG_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.ITM_CD IS NOT NULL AND NVL(L_PTN_REC.ITM_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.LOT_NO IS NOT NULL AND NVL(L_PTN_REC.LOT_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.SUBLOT_NO IS NOT NULL AND NVL(L_PTN_REC.SUBLOT_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.SNO1 IS NOT NULL AND NVL(L_PTN_REC.SNO1_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.SNO2 IS NOT NULL AND NVL(L_PTN_REC.SNO2_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.SNO3 IS NOT NULL AND NVL(L_PTN_REC.SNO3_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.SNO4 IS NOT NULL AND NVL(L_PTN_REC.SNO4_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.ITM_MFG_INST_NO IS NOT NULL AND NVL(L_PTN_REC.INST_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.IV_NO IS NOT NULL AND NVL(L_PTN_REC.IV_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.PO_NO IS NOT NULL AND NVL(L_PTN_REC.PO_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.SLO_NO IS NOT NULL AND NVL(L_PTN_REC.SLO_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.ALC_AC_CD IS NOT NULL AND NVL(L_PTN_REC.ALC_AC_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		OR x.TRD_WG_CD IS NOT NULL AND NVL(L_PTN_REC.WG_ALC_TYP, C_ALC_OVER) != C_ALC_TGT
		THEN
			G_MSG := FCPA_ERR.MSG_BINDER(
					L_KEY_SA_TYP,
					FCPA_DATE_UTIL.F_TO_CHAR(L_KEY_YM, FCPA_DATE_UTIL.Y4M),
					I_WG_CD,
					I_CALC_CTG_CD,
					I_PRE_ALC_RATE_CD
					) ;
			FCPA_ERR.RAISE_APP_ERR('MGBGD0007', G_MSG) ;
		END IF ;

		i := i + 1 ;
		RATE(i).YM := I_YM ;
		RATE(i).SA_TYP := I_SA_TYP ;
		RATE(i).PRE_ALC_RATE_CD := x.PRE_ALC_RATE_CD ;
		RATE(i).CALC_CTG_CD := x.CALC_CTG_CD ;
		RATE(i).WG_CD := x.WG_CD ;
		RATE(i).DPT_CD := x.DPT_CD ;
		RATE(i).LOC_CD := x.LOC_CD ;
		RATE(i).OPER_CD := x.OPER_CD ;
		RATE(i).BP_CD := x.BP_CD ;
		RATE(i).CTG_CD := x.CTG_CD ;
		RATE(i).ITM_CD := x.ITM_CD ;
		RATE(i).ITM_SUB1 := x.ITM_SUB1 ;
		RATE(i).ITM_SUB2 := x.ITM_SUB2 ;
		RATE(i).ITM_SUB3 := x.ITM_SUB3 ;
		RATE(i).LOT_NO := x.LOT_NO ;
		RATE(i).SUBLOT_NO := x.SUBLOT_NO ;
		RATE(i).SNO1 := x.SNO1 ;
		RATE(i).SNO2 := x.SNO2 ;
		RATE(i).SNO3 := x.SNO3 ;
		RATE(i).SNO4 := x.SNO4 ;
		RATE(i).ITM_MFG_INST_NO := x.ITM_MFG_INST_NO ;
		RATE(i).IV_NO := x.IV_NO ;
		RATE(i).PO_NO := x.PO_NO ;
		RATE(i).SLO_NO := x.SLO_NO ;
		RATE(i).ALC_AC_CD := x.ALC_AC_CD ;
		RATE(i).TRD_WG_CD := x.TRD_WG_CD ;
		RATE(i).PRE_ALC_RATE := x.PRE_ALC_RATE ;
		RATE(i).ADJ_FLG := x.ADJ_FLG ;
		RATE(i).RMRKS := x.RMRKS ;
		RATE(i).SUB_CHAR1 := x.SUB_CHAR1 ;
		RATE(i).SUB_CHAR2 := x.SUB_CHAR2 ;
		RATE(i).SUB_CHAR3 := x.SUB_CHAR3 ;
		IF G_ALC_CTG.RATE_COEFF_FLG = '0' THEN
			RATE(i).PRE_ALC_RATE := 1 ;
		END IF ;
	END LOOP ;

	IF i = 0 THEN
		G_MSG := FCPA_ERR.MSG_BINDER(
				L_KEY_SA_TYP,
				FCPA_DATE_UTIL.F_TO_CHAR(L_KEY_YM, FCPA_DATE_UTIL.Y4M),
				I_WG_CD,
				I_CALC_CTG_CD,
				I_PRE_ALC_RATE_CD
				) ;
		FCPA_ERR.RAISE_APP_ERR('MGBGD0006', G_MSG) ;
	END IF ;
	-- キー情報に対する比率データを設定する
	IF G_ALC_RATE.PRE_ALC_SET_TYP = MAC_PRE_ALC_SET_TYP.WK THEN
		P_WK(L_DATA_SA_TYP, I_YM_FROM, I_YM_TO, I_WG_CD, I_CALC_CTG_CD) ;

	ELSIF G_ALC_RATE.PRE_ALC_SET_TYP IN (MAC_PRE_ALC_SET_TYP.MFG_QTY, MAC_PRE_ALC_SET_TYP.MFG_AMT) THEN
		P_MFG(L_DATA_SA_TYP, I_YM_FROM, I_YM_TO) ;

	ELSIF G_ALC_RATE.PRE_ALC_SET_TYP IN (MAC_PRE_ALC_SET_TYP.PURC_QTY, MAC_PRE_ALC_SET_TYP.PURC_AMT) THEN
		P_PURC(L_DATA_SA_TYP, I_YM_FROM, I_YM_TO) ;

	ELSIF G_ALC_RATE.PRE_ALC_SET_TYP IN (MAC_PRE_ALC_SET_TYP.SLS_QTY, MAC_PRE_ALC_SET_TYP.SLS_AMT) THEN
		P_SLS(L_DATA_SA_TYP, I_YM_FROM, I_YM_TO) ;

	END IF ;

	DELETE	MGT_PRE_RATE_MLY t
	WHERE	0=0
	AND	t.PRE_ALC_RATE_CD = I_PRE_ALC_RATE_CD
	AND	t.SA_TYP = I_SA_TYP
	AND	t.YM = I_YM
	AND	t.CALC_CTG_CD = I_CALC_CTG_CD
	AND	t.WG_CD = I_WG_CD
	;

	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MGT_PRE_RATE_MLY VALUES RATE(t) ;
	END IF ;

	COMMIT ;
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_PRE_RATE.P_MAIN') ;

EXCEPTION
WHEN LOCK_ERROR THEN
	FCPA_ERR.RAISE_APP_ERR('MGBXD0029') ;
END P_MAIN ;

END MGPA_PRE_RATE ;
