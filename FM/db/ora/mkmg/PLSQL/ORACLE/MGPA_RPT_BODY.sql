FUNCTION F_CHECK_ROW_CD (
	I_RPT_ROW_CD	IN MAPA_META.RPT_ROW_CD%TYPE
)
RETURN INTEGER
/*********************************************************
<SYNOPSIS>
	指定された行番号を持つrecxに対しての格納番号を返す
<REMARKS>
	まだ未作成のときは0を返す
<ARGUMENTS>
<IN>	I_RPT_ROW_CD
		レポート行ＣＤ
<RETURNVALUE>
	対象となる格納番号
<HISTORY>
**********************************************************/
AS
BEGIN
	IF xi > 0 THEN
		FOR i IN 1..xi LOOP
			IF recx(i).RPT_ROW_CD = I_RPT_ROW_CD THEN
				RETURN i ;
			END IF ;
		END LOOP ;
	END IF ;

	RETURN 0 ;

END F_CHECK_ROW_CD ;

FUNCTION F_GET_VAL (
	I_RPT_KEY	IN CUR_RPT_KEY_CONFIG%ROWTYPE,
	I_RPT_PTN_CD	IN MAPA_META.RPT_PTN_CD%TYPE,
	I_RPT_ROW_CD	IN MAPA_META.RPT_ROW_CD%TYPE,
	I_WG_CD	IN MAPA_META.WG_CD%TYPE
)
RETURN MGPA_META.RPT_VAL%TYPE
/*********************************************************
<SYNOPSIS>
	指定された行番号を持つrecxに対するレポート値を返す
	まだ未作成のときは対象となる値を作成したのちにその値を返す
<REMARKS>
<ARGUMENTS>
<IN>	I_RPT_KEY
		レポートキー
<IN>	I_RPT_PTN_CD
		レポートパタンＣＤ
<IN>	I_RPT_ROW_CD
		レポート行ＣＤ
<IN>	I_WG_CD
		ワーキンググループＣＤ
<RETURNVALUE>
	対象となるレポート値
<HISTORY>
**********************************************************/
AS
	L_ROW	MAM_RPT_CONF%ROWTYPE ;

	L_VAL	MGPA_META.RPT_VAL%TYPE := 0 ;
	L_TMP	MGPA_META.RPT_VAL%TYPE := 0 ;

	L_YM	MAPA_META.YM%TYPE ;

	L_CALC_REC_TYP	MGPA_META.CALC_REC_TYP%TYPE ;
	L_CALC_REC_TYP1	MGPA_META.CALC_REC_TYP%TYPE ;
	L_CALC_REC_TYP2	MGPA_META.CALC_REC_TYP%TYPE ;

	L_COST_IO_TYP	MAPA_META.COST_IO_TYP%TYPE ;

	idx	INTEGER := 0 ;
	L_ITM_FLG 	MAPA_META.FLG%TYPE ;
	L_ALC_FLG 	MAPA_META.FLG%TYPE ;
	L_STK_CALC_GRP_CD	MAPA_META.CALC_GRP_CD%TYPE ;
BEGIN
	L_VAL := 0 ;
	BEGIN
		SELECT	m.*
		INTO	L_ROW
		FROM	MAM_RPT_CONF m
		WHERE	0=0
		AND	m.RPT_PTN_CD = I_RPT_PTN_CD
		AND	m.RPT_ROW_CD = I_RPT_ROW_CD
		AND	m.DEL_FLG = '0'
		;
	EXCEPTION
	WHEN OTHERS THEN
		RETURN L_VAL ;
	END ;

	IF L_ROW.SML_FLG = '1' THEN
		FOR x IN (
			SELECT	m.TGT_RPT_ROW_CD,
				m.MINUS_FLG
			FROM	MAM_RPT_ROW_SML m
			WHERE	0=0
			AND	m.RPT_PTN_CD = L_ROW.RPT_PTN_CD
			AND	m.SML_RPT_ROW_CD = L_ROW.RPT_ROW_CD
			)
		LOOP
			idx := F_CHECK_ROW_CD(x.TGT_RPT_ROW_CD) ;
			IF idx = 0 THEN
				IF RPT_ROW_LOOP.EXISTS(x.TGT_RPT_ROW_CD) THEN
					G_MSG := FCPA_ERR.MSG_BINDER(L_ROW.RPT_PTN_CD, L_ROW.RPT_ROW_CD, x.TGT_RPT_ROW_CD) ;
					FCPA_ERR.RAISE_APP_ERR('MGBXD0024', G_MSG) ;
				ELSE
					RPT_ROW_LOOP(x.TGT_RPT_ROW_CD) := '1' ;
				END IF ;

				L_TMP := F_GET_VAL(I_RPT_KEY, I_RPT_PTN_CD, x.TGT_RPT_ROW_CD, I_WG_CD) ;

				RPT_ROW_LOOP.DELETE(x.TGT_RPT_ROW_CD) ;
			ELSE
				L_TMP := recx(idx).RPT_VAL ;
			END IF ;

			IF x.MINUS_FLG = '0' THEN
				L_VAL := L_VAL + L_TMP ;
			ELSE
				L_VAL := L_VAL - L_TMP ;
			END IF ;
		END LOOP ;

		GOTO FUNC_FIN ;
	END IF ;

	IF  L_ROW.ITM_JNL_CD IS NULL
	AND L_ROW.ITM_GRP_CD1 IS NULL
	AND L_ROW.ITM_GRP_CD2 IS NULL
	AND L_ROW.ITM_GRP_CD3 IS NULL
	AND L_ROW.ITM_GRP_CD4 IS NULL
	AND L_ROW.ITM_GRP_CD5 IS NULL
	AND L_ROW.ITM_GRP_CD6 IS NULL
	AND L_ROW.ITM_GRP_CD7 IS NULL
	AND L_ROW.ITM_GRP_CD8 IS NULL
	AND L_ROW.ITM_GRP_CD9 IS NULL
	AND L_ROW.ITM_GRP_CD10 IS NULL
	AND I_RPT_KEY.ITM_JNL_CD IS NULL
	AND I_RPT_KEY.ITM_GRP_TYP IS NULL
	THEN
		L_ITM_FLG := '0' ;
	ELSE
		L_ITM_FLG := '1' ;
	END IF ;

	IF  L_ROW.ALC_AC_GRP_CD1 IS NULL
	AND L_ROW.ALC_AC_GRP_CD2 IS NULL
	AND L_ROW.ALC_AC_GRP_CD3 IS NULL
	THEN
		L_ALC_FLG := '0' ;
	ELSE
		L_ALC_FLG := '1' ;
	END IF ;

	IF L_ROW.RPT_TGT_TYP = G_RPT_TGT_ALC THEN
		IF L_ROW.QTY_UNIT_TYP IS NOT NULL THEN
			GOTO FUNC_FIN ;
		END IF ;

		IF L_ITM_FLG = '0' THEN

			IF L_ALC_FLG = '0' THEN
				SELECT
					DECODE(L_ROW.STD_FLG, '1',
						SUM(t1.STD_ALC_AMT),
						SUM(t1.ALC_AMT + t1.ADJ_AMT)
						)
				INTO	L_VAL
				FROM	MGT_ALC_CALC_DTL t1, MGT_ALC_CALC_RATE t2,
					MAM_EXPNS m2
				WHERE	0=0
				AND	t1.CALC_NO	= G_ARG.CALC_NO
				AND	t1.CALC_GRP_CD	= G_ARG.CALC_GRP_CD
				AND	t1.WG_CD	= I_WG_CD
				AND	t2.CALC_NO	= G_ARG.CALC_NO
				AND	t2.CALC_GRP_CD	= G_ARG.CALC_GRP_CD
				AND	t1.CALC_NO	= t2.CALC_NO
				AND	t1.CALC_GRP_CD	= t2.CALC_GRP_CD
				AND	t1.ALC_GRP_ID	= t2.ALC_GRP_ID
				AND	t2.EXPNS_CD	= m2.EXPNS_CD
				AND	m2.DEL_FLG	= '0'
				AND	(L_ROW.AC_SLIP_TYP IS NULL OR L_ROW.AC_SLIP_TYP = t1.AC_SLIP_TYP)
				AND	(L_ROW.AC_RSN_CD IS NULL OR L_ROW.AC_RSN_CD = t1.AC_RSN_CD)
				AND	(L_ROW.EXPNS_TYP IS NULL OR L_ROW.EXPNS_TYP = m2.EXPNS_TYP)
				AND	(L_ROW.DIRECT_TYP IS NULL OR L_ROW.DIRECT_TYP = m2.DIRECT_TYP)
				AND	(L_ROW.VAR_TYP IS NULL OR L_ROW.VAR_TYP = m2.VAR_TYP)
				AND	(L_ROW.EXPNS_GRP_CD IS NULL OR L_ROW.EXPNS_GRP_CD = m2.EXPNS_GRP_CD)
				AND	(L_ROW.EXPNS_CD IS NULL OR L_ROW.EXPNS_CD = t2.EXPNS_CD)
				AND	(L_ROW.ALC_AC_CD IS NULL OR L_ROW.ALC_AC_CD = t2.ALC_AC_CD)
				AND	(L_ROW.ASST_TYP IS NULL OR L_ROW.ASST_TYP = t1.ASST_TYP)
				AND	(I_RPT_KEY.DPT_CD IS NULL OR I_RPT_KEY.DPT_CD = t1.MNG_DPT_CD)
				AND	(I_RPT_KEY.ITM_CD IS NULL OR I_RPT_KEY.ITM_CD = t1.ITM_CD)
				AND	(I_RPT_KEY.ITM_SUB1 IS NULL OR I_RPT_KEY.ITM_SUB1 = t1.ITM_SUB1)
				AND	(I_RPT_KEY.ITM_SUB2 IS NULL OR I_RPT_KEY.ITM_SUB2 = t1.ITM_SUB2)
				AND	(I_RPT_KEY.ITM_SUB3 IS NULL OR I_RPT_KEY.ITM_SUB3 = t1.ITM_SUB3)
				;
			ELSE
				SELECT	/*+LEADING(m3 t2) INDEX(t2 MGT_ALC_CALC_RATE_ALL_IE01)*/
					DECODE(L_ROW.STD_FLG, '1',
						SUM(t1.STD_ALC_AMT),
						SUM(t1.ALC_AMT + t1.ADJ_AMT)
						)
				INTO	L_VAL
				FROM	MGT_ALC_CALC_DTL t1, MGT_ALC_CALC_RATE t2,
					MAM_EXPNS m2, MAM_ALC_AC m3
				WHERE	0=0
				AND	t1.CALC_NO	= G_ARG.CALC_NO
				AND	t1.CALC_GRP_CD	= G_ARG.CALC_GRP_CD
				AND	t1.WG_CD	= I_WG_CD
				AND	t2.CALC_NO	= G_ARG.CALC_NO
				AND	t2.CALC_GRP_CD	= G_ARG.CALC_GRP_CD
				AND	t1.CALC_NO	= t2.CALC_NO
				AND	t1.CALC_GRP_CD	= t2.CALC_GRP_CD
				AND	t1.ALC_GRP_ID	= t2.ALC_GRP_ID
				AND	t2.EXPNS_CD	= m2.EXPNS_CD
				AND	m2.DEL_FLG	= '0'
				AND	t2.ALC_AC_CD	= m3.ALC_AC_CD
				AND	m3.DEL_FLG	= '0'
				AND	(L_ROW.AC_SLIP_TYP IS NULL OR L_ROW.AC_SLIP_TYP = t1.AC_SLIP_TYP)
				AND	(L_ROW.AC_RSN_CD IS NULL OR L_ROW.AC_RSN_CD = t1.AC_RSN_CD)
				AND	(L_ROW.EXPNS_TYP IS NULL OR L_ROW.EXPNS_TYP = m2.EXPNS_TYP)
				AND	(L_ROW.DIRECT_TYP IS NULL OR L_ROW.DIRECT_TYP = m2.DIRECT_TYP)
				AND	(L_ROW.VAR_TYP IS NULL OR L_ROW.VAR_TYP = m2.VAR_TYP)
				AND	(L_ROW.EXPNS_GRP_CD IS NULL OR L_ROW.EXPNS_GRP_CD = m2.EXPNS_GRP_CD)
				AND	(L_ROW.EXPNS_CD IS NULL OR L_ROW.EXPNS_CD = t2.EXPNS_CD)
				AND	(L_ROW.ALC_AC_GRP_CD1 IS NULL OR L_ROW.ALC_AC_GRP_CD1 = m3.ALC_AC_GRP_CD1)
				AND	(L_ROW.ALC_AC_GRP_CD2 IS NULL OR L_ROW.ALC_AC_GRP_CD2 = m3.ALC_AC_GRP_CD2)
				AND	(L_ROW.ALC_AC_GRP_CD3 IS NULL OR L_ROW.ALC_AC_GRP_CD3 = m3.ALC_AC_GRP_CD3)
				AND	(L_ROW.ALC_AC_CD IS NULL OR L_ROW.ALC_AC_CD = t2.ALC_AC_CD)
				AND	(L_ROW.ASST_TYP IS NULL OR L_ROW.ASST_TYP = t1.ASST_TYP)
				AND	(I_RPT_KEY.DPT_CD IS NULL OR I_RPT_KEY.DPT_CD = t1.MNG_DPT_CD)
				AND	(I_RPT_KEY.ITM_CD IS NULL OR I_RPT_KEY.ITM_CD = t1.ITM_CD)
				AND	(I_RPT_KEY.ITM_SUB1 IS NULL OR I_RPT_KEY.ITM_SUB1 = t1.ITM_SUB1)
				AND	(I_RPT_KEY.ITM_SUB2 IS NULL OR I_RPT_KEY.ITM_SUB2 = t1.ITM_SUB2)
				AND	(I_RPT_KEY.ITM_SUB3 IS NULL OR I_RPT_KEY.ITM_SUB3 = t1.ITM_SUB3)
				;
			END IF ;
		ELSE
			IF L_ALC_FLG = '0' THEN
				SELECT
					DECODE(L_ROW.STD_FLG, '1',
						SUM(t1.STD_ALC_AMT),
						SUM(t1.ALC_AMT + t1.ADJ_AMT)
						)
