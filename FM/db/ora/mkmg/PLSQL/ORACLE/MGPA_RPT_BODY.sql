		AND	(L_ROW.ITM_JNL_CD IS NULL OR L_ROW.ITM_JNL_CD = m1.ITM_JNL_CD)
		AND	(L_ROW.ITM_GRP_CD1 IS NULL OR L_ROW.ITM_GRP_CD1 = m1.ITM_GRP_CD1)
		AND	(L_ROW.ITM_GRP_CD2 IS NULL OR L_ROW.ITM_GRP_CD2 = m1.ITM_GRP_CD2)
		AND	(L_ROW.ITM_GRP_CD3 IS NULL OR L_ROW.ITM_GRP_CD3 = m1.ITM_GRP_CD3)
		AND	(L_ROW.ITM_GRP_CD4 IS NULL OR L_ROW.ITM_GRP_CD4 = m1.ITM_GRP_CD4)
		AND	(L_ROW.ITM_GRP_CD5 IS NULL OR L_ROW.ITM_GRP_CD5 = m1.ITM_GRP_CD5)
		AND	(L_ROW.ITM_GRP_CD6 IS NULL OR L_ROW.ITM_GRP_CD6 = m1.ITM_GRP_CD6)
		AND	(L_ROW.ITM_GRP_CD7 IS NULL OR L_ROW.ITM_GRP_CD7 = m1.ITM_GRP_CD7)
		AND	(L_ROW.ITM_GRP_CD8 IS NULL OR L_ROW.ITM_GRP_CD8 = m1.ITM_GRP_CD8)
		AND	(L_ROW.ITM_GRP_CD9 IS NULL OR L_ROW.ITM_GRP_CD9 = m1.ITM_GRP_CD9)
		AND	(L_ROW.ITM_GRP_CD10 IS NULL OR L_ROW.ITM_GRP_CD10 = m1.ITM_GRP_CD10)
		AND	(L_ROW.COST_IO_TYP IS NULL OR L_ROW.COST_IO_TYP = t1.COST_IO_TYP)
		AND	(L_ROW.AC_SLIP_TYP IS NULL OR L_ROW.AC_SLIP_TYP = t1.AC_SLIP_TYP)
		AND	(L_ROW.AC_RSN_CD IS NULL OR L_ROW.AC_RSN_CD = t1.AC_RSN_CD)
		AND	(L_ROW.EXPNS_TYP IS NULL OR L_ROW.EXPNS_TYP = m2.EXPNS_TYP)
		AND	(L_ROW.DIRECT_TYP IS NULL OR L_ROW.DIRECT_TYP = m2.DIRECT_TYP)
		AND	(L_ROW.VAR_TYP IS NULL OR L_ROW.VAR_TYP = m2.VAR_TYP)
		AND	(L_ROW.EXPNS_GRP_CD IS NULL OR L_ROW.EXPNS_GRP_CD = m2.EXPNS_GRP_CD)
		AND	(L_ROW.EXPNS_CD IS NULL OR L_ROW.EXPNS_CD = t2.EXPNS_CD)
		AND	(L_ROW.ASST_TYP IS NULL AND t1.ASST_TYP IN (G_ASST_PROD, G_ASST_SLS) OR L_ROW.ASST_TYP = t1.ASST_TYP)
		AND	(I_RPT_KEY.DPT_CD IS NULL OR I_RPT_KEY.DPT_CD = t1.MNG_DPT_CD)
		AND	(I_RPT_KEY.ITM_CD IS NULL OR I_RPT_KEY.ITM_CD = t1.ITM_CD)
		AND	(I_RPT_KEY.ITM_SUB1 IS NULL OR I_RPT_KEY.ITM_SUB1 = t1.ITM_SUB1)
		AND	(I_RPT_KEY.ITM_SUB2 IS NULL OR I_RPT_KEY.ITM_SUB2 = t1.ITM_SUB2)
		AND	(I_RPT_KEY.ITM_SUB3 IS NULL OR I_RPT_KEY.ITM_SUB3 = t1.ITM_SUB3)
		AND	(I_RPT_KEY.ITM_JNL_CD IS NULL OR I_RPT_KEY.ITM_JNL_CD = m1.ITM_JNL_CD)
		AND	(I_RPT_KEY.ITM_GRP_TYP IS NULL OR
				I_RPT_KEY.ITM_GRP_CD =
					DECODE(I_RPT_KEY.ITM_GRP_TYP,
						G_ITM_GRP1, m1.ITM_GRP_CD1,
						G_ITM_GRP2, m1.ITM_GRP_CD2,
						G_ITM_GRP3, m1.ITM_GRP_CD3,
						G_ITM_GRP4, m1.ITM_GRP_CD4,
						G_ITM_GRP5, m1.ITM_GRP_CD5,
						G_ITM_GRP6, m1.ITM_GRP_CD6,
						G_ITM_GRP7, m1.ITM_GRP_CD7,
						G_ITM_GRP8, m1.ITM_GRP_CD8,
						G_ITM_GRP9, m1.ITM_GRP_CD9,
						G_ITM_GRP10, m1.ITM_GRP_CD10,
						NULL)
			)
		;
	END IF ;

	<<FUNC_FIN>>
		NULL ;

	xi := xi + 1 ;

	recx(xi).CALC_NO	:= G_ARG.CALC_NO ;
	recx(xi).CALC_GRP_CD	:= G_ARG.CALC_GRP_CD ;
	recx(xi).YM		:= G_ARG.END_YM ;
	recx(xi).RPT_PTN_CD	:= I_RPT_PTN_CD ;
	recx(xi).RPT_KEY_CD	:= I_RPT_KEY.RPT_KEY_CD ;
	recx(xi).RPT_ROW_CD	:= I_RPT_ROW_CD ;
	recx(xi).WG_CD	:= I_WG_CD ;
	recx(xi).DPT_CD		:= I_RPT_KEY.DPT_CD ;
	recx(xi).ITM_CD		:= I_RPT_KEY.ITM_CD ;
	recx(xi).ITM_SUB1		:= I_RPT_KEY.ITM_SUB1 ;
	recx(xi).ITM_SUB2		:= I_RPT_KEY.ITM_SUB2 ;
	recx(xi).ITM_SUB3		:= I_RPT_KEY.ITM_SUB3 ;
	recx(xi).ITM_JNL_CD	:= I_RPT_KEY.ITM_JNL_CD ;
	recx(xi).ITM_GRP_TYP	:= I_RPT_KEY.ITM_GRP_TYP ;
	recx(xi).ITM_GRP_CD	:= I_RPT_KEY.ITM_GRP_CD ;

	recx(xi).RPT_VAL	:= NVL(L_VAL, 0) ;

	RETURN L_VAL ;

END F_GET_VAL ;

PROCEDURE P_MAIN (
	I_CALC_GRP_CD	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN MAPA_META.CALC_NO%TYPE,
	I_RPT_PTN_CD	IN MAPA_META.RPT_PTN_CD%TYPE,
	I_RPT_KEY_CD	IN MAPA_META.RPT_KEY_CD%TYPE,
	I_LOCK_FLG 	IN MAPA_META.FLG%TYPE DEFAULT '1'
	, I_DPT_CD	IN	MAPA_META.COST_DPT_CD%TYPE DEFAULT NULL
	, I_WG_CD	IN	MAPA_META.WG_CD%TYPE DEFAULT NULL
	, I_ITM_CD	IN	MAPA_META.ITM_CD%TYPE DEFAULT NULL
	, I_ITM_SUB1	IN	MAPA_META.ITM_SUB1%TYPE DEFAULT NULL
	, I_ITM_SUB2	IN	MAPA_META.ITM_SUB2%TYPE DEFAULT NULL
	, I_ITM_SUB3	IN	MAPA_META.ITM_SUB3%TYPE DEFAULT NULL
	, I_ITM_JNL_CD	IN	MAPA_META.ITM_JNL_CD%TYPE DEFAULT NULL
	, I_ITM_GRP_TYP	IN	MAPA_META.ITM_GRP_TYP%TYPE DEFAULT NULL
	, I_ITM_GRP_CD	IN	MAPA_META.ITM_GRP_CD%TYPE DEFAULT NULL
)
/*********************************************************
<SYNOPSIS>
	原価レポート作成処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<IN>	I_RPT_PTN_CD
		レポートパタンＣＤ
<IN>	I_RPT_KEY_CD
		レポートキーＣＤ
<IN>	I_LOCK_FLG
		ロックＦＬＧ
<HISTORY>
**********************************************************/
AS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	L_CNT	NUMBER ;

	L_TMP	MGPA_META.RPT_VAL%TYPE := 0 ;

	L_RPT_KEY	CUR_RPT_KEY_CONFIG%ROWTYPE ;
	L_MSG	VARCHAR(1000) ;
BEGIN
	IF I_DPT_CD IS NOT NULL THEN
		L_MSG := I_DPT_CD ;
	ELSIF I_WG_CD IS NOT NULL THEN
		L_MSG := I_WG_CD ;
	ELSIF I_ITM_CD IS NOT NULL THEN
 		L_MSG := MAPA_COMM.F_TO_DISP_ITM(I_ITM_CD, I_ITM_SUB1, I_ITM_SUB2, I_ITM_SUB3, MAPA_COMM.F_GET_PARM('ITM_SUB_TYP')) ;
	ELSIF I_ITM_JNL_CD IS NOT NULL THEN
		L_MSG := I_ITM_JNL_CD ;
	ELSIF I_ITM_GRP_TYP IS NOT NULL THEN
		L_MSG := I_ITM_GRP_TYP || ' - ' || I_ITM_GRP_CD ;
	END IF ;
	IF L_MSG IS NULL THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0012', I_CALC_GRP_CD, I_CALC_NO, I_RPT_PTN_CD, I_RPT_KEY_CD) ;
	ELSE
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0012', I_CALC_GRP_CD, I_CALC_NO, I_RPT_PTN_CD, I_RPT_KEY_CD || ' - ' || L_MSG) ;
	END IF ;

	L_CNT := 0 ;
	IF I_LOCK_FLG = '0' THEN
		FOR x IN (
			SELECT	m.CALC_GRP_CD
			FROM	MAM_CALC_RPT_PTN m
			WHERE	0=0
			AND	m.CALC_GRP_CD= I_CALC_GRP_CD
			AND	m.RPT_PTN_CD = I_RPT_PTN_CD
			AND	m.RPT_KEY_CD = I_RPT_KEY_CD
			)
		LOOP
			L_CNT := 1 ;
		END LOOP ;
	ELSE
		BEGIN
			FOR x IN (
				SELECT	m.CALC_GRP_CD
				FROM	MAM_CALC_RPT_PTN m
				WHERE	0=0
				AND	m.CALC_GRP_CD= I_CALC_GRP_CD
				AND	m.RPT_PTN_CD = I_RPT_PTN_CD
				AND	m.RPT_KEY_CD = I_RPT_KEY_CD
				FOR UPDATE NOWAIT
				)
			LOOP
				L_CNT := 1 ;
			END LOOP ;
		EXCEPTION
		WHEN LOCK_ERROR THEN
			G_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, I_CALC_NO) ;
			FCPA_ERR.RAISE_APP_ERR('MGBXD0009', G_MSG) ;
		END ;
	END IF ;

	IF L_CNT = 0 THEN
		G_MSG := FCPA_ERR.MSG_BINDER(I_CALC_GRP_CD, I_RPT_PTN_CD, I_RPT_KEY_CD) ;
		FCPA_ERR.RAISE_APP_ERR('MGBXD0017', G_MSG) ;
	END IF ;

	/*** 同一のデータがあれば削除 ***/
	DELETE	MGT_RPT t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	t.RPT_PTN_CD = I_RPT_PTN_CD
	AND	t.RPT_KEY_CD = I_RPT_KEY_CD
	AND	(I_DPT_CD IS NULL OR t.DPT_CD = I_DPT_CD)
	AND	(I_WG_CD IS NULL OR t.WG_CD = I_WG_CD)
	AND	(I_ITM_CD IS NULL OR t.ITM_CD = I_ITM_CD)
	AND	(I_ITM_SUB1 IS NULL OR t.ITM_SUB1 = I_ITM_SUB1)
	AND	(I_ITM_SUB2 IS NULL OR t.ITM_SUB2 = I_ITM_SUB2)
	AND	(I_ITM_SUB3 IS NULL OR t.ITM_SUB3 = I_ITM_SUB3)
	AND	(I_ITM_JNL_CD IS NULL OR t.ITM_JNL_CD = I_ITM_JNL_CD)
	AND	(I_ITM_GRP_TYP IS NULL OR t.ITM_GRP_TYP = I_ITM_GRP_TYP)
	AND	(I_ITM_GRP_CD IS NULL OR t.ITM_GRP_CD = I_ITM_GRP_CD)
	;

	/*** 計算情報の取得 ***/
	G_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	DELETE MAW_WG_KEY ;
	IF G_ARG.RUNTIME_WG_CD IS NULL THEN
		INSERT INTO MAW_WG_KEY
		SELECT m.WG_CD
		FROM	MAM_GRP_WG m
		WHERE	0=0
		AND	m.CALC_GRP_CD = I_CALC_GRP_CD
		AND	m.DEL_FLG = '0'
		AND	(I_WG_CD IS NULL OR m.WG_CD = I_WG_CD) ;
	ELSE
		INSERT INTO MAW_WG_KEY VALUES (G_ARG.RUNTIME_WG_CD) ;
	END IF ;

	FOR z IN (
		SELECT m.WG_CD FROM MAW_WG_KEY m
		)
	LOOP
		FOR x IN CUR_RPT_KEY_CONFIG(I_RPT_KEY_CD) LOOP
			L_RPT_KEY := x ;

			IF L_RPT_KEY.WG_CD IS NOT NULL AND L_RPT_KEY.WG_CD <> z.WG_CD THEN
				CONTINUE ;
			END IF;
			IF (I_DPT_CD IS NOT NULL AND I_DPT_CD <> L_RPT_KEY.DPT_CD)
				OR (I_WG_CD IS NOT NULL AND I_WG_CD <> L_RPT_KEY.WG_CD)
				OR (I_ITM_CD IS NOT NULL AND I_ITM_CD <> L_RPT_KEY.ITM_CD)
				OR (I_ITM_SUB1 IS NOT NULL AND I_ITM_SUB1 <> L_RPT_KEY.ITM_SUB1)
				OR (I_ITM_SUB2 IS NOT NULL AND I_ITM_SUB2 <> L_RPT_KEY.ITM_SUB2)
				OR (I_ITM_SUB3 IS NOT NULL AND I_ITM_SUB3 <> L_RPT_KEY.ITM_SUB3)
				OR (I_ITM_JNL_CD IS NOT NULL AND I_ITM_JNL_CD <> L_RPT_KEY.ITM_JNL_CD)
				OR (I_ITM_GRP_TYP IS NOT NULL AND I_ITM_GRP_TYP <> L_RPT_KEY.ITM_GRP_TYP)
				OR (I_ITM_GRP_CD IS NOT NULL AND I_ITM_GRP_CD <> L_RPT_KEY.ITM_GRP_CD)
			THEN
				CONTINUE ;
			END IF;

			recx.DELETE ;
			xi := 0 ;

			FOR y IN (
				SELECT	m.RPT_ROW_CD,
					m.SML_FLG
				FROM	MAM_RPT_CONF m
				WHERE	0=0
				AND	m.RPT_PTN_CD = I_RPT_PTN_CD
				AND	m.DEL_FLG = '0'
				ORDER BY m.SML_FLG
				)
			LOOP
				RPT_ROW_LOOP.DELETE ;
				IF y.SML_FLG = '0' OR F_CHECK_ROW_CD(y.RPT_ROW_CD) = 0 THEN
					L_TMP := F_GET_VAL(L_RPT_KEY, I_RPT_PTN_CD, y.RPT_ROW_CD, z.WG_CD) ;
				END IF ;
				RPT_ROW_LOOP.DELETE ;
			END LOOP ;

			IF xi > 0 THEN
				FORALL i IN 1..xi
					INSERT INTO MGT_RPT VALUES recx(i) ;
			END IF ;

		END LOOP ;

		recx.DELETE ;
	
	END LOOP ;

	COMMIT ;

	IF L_MSG IS NULL THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_RPT.P_MAIN - ' || I_RPT_PTN_CD || ' - ' || I_RPT_KEY_CD) ;
	ELSE
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_RPT.P_MAIN - ' || I_RPT_PTN_CD || ' - ' || I_RPT_KEY_CD || ' - ' || L_MSG) ;
	END IF ;
END P_MAIN ;

END MGPA_RPT ;
