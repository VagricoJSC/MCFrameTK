	OR I_VALUE = MGC_CALC_REC_TYP$IO()
	OR I_VALUE = MGC_CALC_REC_TYP$INPT()
	OR I_VALUE = MGC_CALC_REC_TYP$SLS()
	OR I_VALUE = MGC_CALC_REC_TYP$END_STK()
