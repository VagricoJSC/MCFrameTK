	OR I_VALUE = MGC_CALC_REC_TYP$INST()
	OR I_VALUE = MGC_CALC_REC_TYP$GP_ALC()
	OR I_VALUE = MGC_CALC_REC_TYP$AVE()
	OR I_VALUE = MGC_CALC_REC_TYP$ADJ() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE MGC_CALC_REC_TYP$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF MGC_CALC_REC_TYP$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
