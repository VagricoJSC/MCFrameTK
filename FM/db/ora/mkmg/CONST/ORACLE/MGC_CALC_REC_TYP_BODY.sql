CREATE OR REPLACE PACKAGE BODY MGC_CALC_REC_TYP
/*****************************
計算レコード区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ST_STK RETURN VARCHAR2 DETERMINISTIC IS -- 月初在庫
	BEGIN RETURN '1'; END ST_STK;
	FUNCTION ST_WIP RETURN VARCHAR2 DETERMINISTIC IS -- 月初仕掛
	BEGIN RETURN '2'; END ST_WIP;
	FUNCTION PURC RETURN VARCHAR2 DETERMINISTIC IS -- 購買
	BEGIN RETURN '3'; END PURC;
	FUNCTION COMP RETURN VARCHAR2 DETERMINISTIC IS -- 完成
	BEGIN RETURN '4'; END COMP;
	FUNCTION IO RETURN VARCHAR2 DETERMINISTIC IS -- 入出庫
	BEGIN RETURN '5'; END IO;
	FUNCTION INPT RETURN VARCHAR2 DETERMINISTIC IS -- 投入
	BEGIN RETURN '6'; END INPT;
	FUNCTION SLS RETURN VARCHAR2 DETERMINISTIC IS -- 売上
	BEGIN RETURN '7'; END SLS;
	FUNCTION END_STK RETURN VARCHAR2 DETERMINISTIC IS -- 月末在庫
	BEGIN RETURN '8'; END END_STK;
	FUNCTION END_WIP RETURN VARCHAR2 DETERMINISTIC IS -- 月末仕掛
	BEGIN RETURN '9'; END END_WIP;
	FUNCTION INST RETURN VARCHAR2 DETERMINISTIC IS -- 発生
	BEGIN RETURN 'A'; END INST;
	FUNCTION GP_ALC RETURN VARCHAR2 DETERMINISTIC IS -- 汎用配賦
	BEGIN RETURN 'L'; END GP_ALC;
	FUNCTION AVE RETURN VARCHAR2 DETERMINISTIC IS -- 総平均単価
	BEGIN RETURN 'T'; END AVE;
	FUNCTION ADJ RETURN VARCHAR2 DETERMINISTIC IS -- 受払差額
	BEGIN RETURN 'X'; END ADJ;

	FUNCTION IS_ST_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月初在庫かどうか
	BEGIN
		IF I_VALUE = ST_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ST_STK;

	FUNCTION IS_ST_WIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月初仕掛かどうか
	BEGIN
		IF I_VALUE = ST_WIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ST_WIP;

	FUNCTION IS_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買かどうか
	BEGIN
		IF I_VALUE = PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC;

	FUNCTION IS_COMP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 完成かどうか
	BEGIN
		IF I_VALUE = COMP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_COMP;

	FUNCTION IS_IO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入出庫かどうか
	BEGIN
		IF I_VALUE = IO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IO;

	FUNCTION IS_INPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 投入かどうか
	BEGIN
		IF I_VALUE = INPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INPT;

	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上かどうか
	BEGIN
		IF I_VALUE = SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS;

	FUNCTION IS_END_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月末在庫かどうか
	BEGIN
		IF I_VALUE = END_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_END_STK;

	FUNCTION IS_END_WIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月末仕掛かどうか
	BEGIN
		IF I_VALUE = END_WIP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_END_WIP;

	FUNCTION IS_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 発生かどうか
	BEGIN
		IF I_VALUE = INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INST;

	FUNCTION IS_GP_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 汎用配賦かどうか
	BEGIN
		IF I_VALUE = GP_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GP_ALC;

	FUNCTION IS_AVE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 総平均単価かどうか
	BEGIN
		IF I_VALUE = AVE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AVE;

	FUNCTION IS_ADJ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受払差額かどうか
	BEGIN
		IF I_VALUE = ADJ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ADJ;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ST_STK
		OR I_VALUE = ST_WIP
		OR I_VALUE = PURC
		OR I_VALUE = COMP
		OR I_VALUE = IO
		OR I_VALUE = INPT
		OR I_VALUE = SLS
		OR I_VALUE = END_STK
		OR I_VALUE = END_WIP
		OR I_VALUE = INST
		OR I_VALUE = GP_ALC
		OR I_VALUE = AVE
		OR I_VALUE = ADJ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MGC_CALC_REC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MGC_CALC_REC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MGC_CALC_REC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MGC_CALC_REC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MGC_CALC_REC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MGC_CALC_REC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MGC_CALC_REC_TYP;
