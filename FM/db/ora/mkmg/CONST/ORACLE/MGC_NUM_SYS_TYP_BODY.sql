	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ST_STK_KEY
		OR I_VALUE = ST_WIP_KEY
		OR I_VALUE = PLN_RQMT_KEY
		OR I_VALUE = PLN_MFG_KEY
		OR I_VALUE = PLN_PURC_KEY
		OR I_VALUE = PLN_SLS_KEY
		OR I_VALUE = PLN_ITM_WK_KEY
		OR I_VALUE = PLN_OTHER_WK_KEY
		OR I_VALUE = PLN_INPT_KEY
		OR I_VALUE = PLN_ALC_AMT_KEY
		OR I_VALUE = ACT_ALC_AMT_KEY
		OR I_VALUE = PLN_ALC_IF_DATA_LNO
		OR I_VALUE = ACT_ALC_IF_DATA_LNO
		OR I_VALUE = ITM_MFG_INST
		OR I_VALUE = ACT_MFG_ID
		OR I_VALUE = ACT_PURC_ID
		OR I_VALUE = ACT_INPT_ID
		OR I_VALUE = ACT_INST_WK_ID
		OR I_VALUE = ACT_OTHER_WK_ID
		OR I_VALUE = ACT_IO_ID
		OR I_VALUE = ACT_SLS_ID
		OR I_VALUE = ACT_MFG_IF_DATA_LNO
		OR I_VALUE = ACT_PURC_IF_DATA_LNO
		OR I_VALUE = ACT_INPT_IF_DATA_LNO
		OR I_VALUE = ACT_INST_WK_IF_DATA_LNO
		OR I_VALUE = ACT_OTHER_WK_IF_DATA_LNO
		OR I_VALUE = ACT_IO_IF_DATA_LNO
		OR I_VALUE = ACT_SLS_IF_DATA_LNO
		OR I_VALUE = ACT_INST_WIP_IF_DATA_LNO
		OR I_VALUE = ACT_STK_IF_DATA_LNO
		OR I_VALUE = IO_ACT_RCV_DATA_LNO
		OR I_VALUE = ACT_WK_RCV_DATA_LNO
		OR I_VALUE = ACT_INST_WIP_RCV_DATA_LNO
		OR I_VALUE = ACT_STK_RCV_DATA_LNO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

