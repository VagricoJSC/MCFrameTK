CREATE OR REPLACE VIEW MAM_COST_SLIP_JNL(
	CALC_GRP_CD,
	AC_SLIP_TYP,
	SUMMARY_TYP,
	SLO_NO_FLG,
	PO_NO_FLG,
	IV_NO_FLG,
	JNL_ACT_CD,
	AUTO_JNL_KEY_CD,
	ITM_SUM_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_GRP_CD,
	ORG.AC_SLIP_TYP,
	ORG.SUMMARY_TYP,
	ORG.SLO_NO_FLG,
	ORG.PO_NO_FLG,
	ORG.IV_NO_FLG,
	ORG.JNL_ACT_CD,
	ORG.AUTO_JNL_KEY_CD,
	ORG.ITM_SUM_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_COST_SLIP_JNL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_cost_slip_jnl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

