SELECT
	ORG.PRE_ALC_RATE_CD,
	ORG.PRE_ALC_RATE_NM,
	ORG.PRE_ALC_PTN_CD,
	ORG.PLN_MLY_FLG,
	ORG.ACT_MLY_FLG,
	ORG.PLN_RULE_FLG,
	ORG.PRE_ALC_SET_TYP,
