	PRE_ALC_RATE_CD,
	PRE_ALC_RATE_NM,
	PRE_ALC_PTN_CD,
	PLN_MLY_FLG,
	ACT_MLY_FLG,
	PLN_RULE_FLG,
	PRE_ALC_SET_TYP,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
