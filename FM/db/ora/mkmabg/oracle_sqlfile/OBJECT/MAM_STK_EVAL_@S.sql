SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_STK_EVAL_$S(
	STK_EVAL_CD,
	STK_EVAL_NM,
	BASE_STK_EVAL_NM,
	AC_RSN_CD,
	CUT_FLG,
	EXPNS_CD,
	LUMP_RATE_FLG,
	EVAL_RATE,
	UPRI_SET_TYP,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.STK_EVAL_CD,
	LCL.STK_EVAL_NM,
	ORG.STK_EVAL_NM AS BASE_STK_EVAL_NM,
	ORG.AC_RSN_CD,
	ORG.CUT_FLG,
	ORG.EXPNS_CD,
	ORG.LUMP_RATE_FLG,
	ORG.EVAL_RATE,
	ORG.UPRI_SET_TYP,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_STK_EVAL_ALL ORG,
	mam_stk_eval_lcl_all LCL
WHERE
	0 = 0
	AND ORG.STK_EVAL_CD = LCL.STK_EVAL_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_stk_eval'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

