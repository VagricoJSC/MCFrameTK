CREATE OR REPLACE VIEW MAM_PRE_ALC_RATE_SEL_$S(
	ALC_AC_CD,
	DPT_CD,
	CALC_CTG_CD,
	WG_CD,
	TERM,
	PRE_ALC_RATE_CD,
	TRD_ALC_AC_CD,
	TRD_WG_CD,
	PRE_ALC_DPT_PTN,
	FIN_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ALC_AC_CD,
	ORG.DPT_CD,
	ORG.CALC_CTG_CD,
	ORG.WG_CD,
	ORG.TERM,
	ORG.PRE_ALC_RATE_CD,
	ORG.TRD_ALC_AC_CD,
	ORG.TRD_WG_CD,
	ORG.PRE_ALC_DPT_PTN,
	ORG.FIN_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_PRE_ALC_RATE_SEL_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_pre_alc_rate_sel'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

