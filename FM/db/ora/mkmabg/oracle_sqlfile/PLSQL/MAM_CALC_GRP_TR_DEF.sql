SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_CALC_GRP_TR_DEF
BEFORE INSERT OR DELETE OR UPDATE OF CALC_GRP_CD
ON MAM_CALC_GRP_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW 
BEGIN
	IF INSERTING THEN
		MAPA_COST_SYS.P_INIT_CALC_PARM(:NEW.CALC_GRP_CD, :NEW.CO_CD) ;
	ELSIF UPDATING THEN
		IF :OLD.CALC_GRP_CD <> :NEW.CALC_GRP_CD THEN
			MAPA_COST_SYS.P_DEL_CALC_PARM(:OLD.CALC_GRP_CD, :OLD.CO_CD) ;
			MAPA_COST_SYS.P_INIT_CALC_PARM(:NEW.CALC_GRP_CD, :NEW.CO_CD) ;
		END IF ;
	ELSIF DELETING THEN
		MAPA_COST_SYS.P_DEL_CALC_PARM(:OLD.CALC_GRP_CD, :OLD.CO_CD) ;
	END IF ;
END ;

/
show errors;


