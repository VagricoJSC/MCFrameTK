SELECT
	--会社ＣＤ
	T1.CO_CD,
	--計算グループＣＤ
	T1.CALC_GRP_CD,
	--計算グループ名
	T1.CALC_GRP_NM,
	--計算グループ名（ロケール１）
	(SELECT T.CALC_GRP_NM
		FROM MAM_CALC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.CALC_GRP_CD = T1.CALC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	CALC_GRP_NM_LCL1,
	--計算グループ名（ロケール２）
	(SELECT T.CALC_GRP_NM
		FROM MAM_CALC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.CALC_GRP_CD = T1.CALC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	CALC_GRP_NM_LCL2,
	--計算グループ名（ロケール３）
	(SELECT T.CALC_GRP_NM
		FROM MAM_CALC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.CALC_GRP_CD = T1.CALC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	CALC_GRP_NM_LCL3,
	--計算グループ名（ロケール４）
	(SELECT T.CALC_GRP_NM
		FROM MAM_CALC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.CALC_GRP_CD = T1.CALC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	CALC_GRP_NM_LCL4,
	--計算グループ名（ロケール５）
	(SELECT T.CALC_GRP_NM
		FROM MAM_CALC_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.CALC_GRP_CD = T1.CALC_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	CALC_GRP_NM_LCL5,
	--計算区分
	T1.COST_CALC_TYP,
	--金額評価区分
	T1.EVAL_TYP,
	--最大計算月数
	T1.MAX_MONS,
	--計算回数
	T1.CALC_CNT,
	--予実区分
	T1.SA_TYP,
	--展開計算区分
	T1.EXP_CALC_TYP,
	--一次配賦計算区分
	T1.PRE_ALC_CALC_TYP,
	--配賦率計算区分
	T1.ALC_CALC_TYP,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3
FROM MAM_CALC_GRP_ALL T1
