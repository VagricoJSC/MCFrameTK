-- 納品先
SELECT
	MSC_SHIP_TO_ID_TYP.DLV,
	M1.BP_CD,
	M1.BP_NM,
	M1.BP_ALT_NM1,
	M1.BP_ALT_NM2,
	M1.BP_ALT_NM3,
	M1.BP_ALT_NM4,
	M1.DLV_SUNDRY_FLG,
	M1.CNTRY_CD,
	M2.CNTRY_NM,
	NULL,
	NULL,
	M1.LG_GRP_CD,
	M3.LG_GRP_NM,
	NULL,
	NULL,
	NULL,
	M1.PRNT_LCL_CD,
	M1.PRI_PRNT_FLG,
	M1.DEL_FLG,
	M1.DEL_USR_ID,
	M1.DEL_USR_NM,
	M1.DEL_TS
FROM
	MAM_BP M1
	LEFT JOIN MAM_CNTRY M2 ON (M2.CNTRY_CD = M1.CNTRY_CD)
	LEFT JOIN MAM_LG_GRP M3 ON (M3.LG_GRP_CD = M1.LG_GRP_CD)
WHERE
	M1.DLV_FLG = '1'
UNION ALL
-- 場所
SELECT
	MSC_SHIP_TO_ID_TYP.LOC,
	M1.LOC_CD,
	M1.LOC_NM,
	NULL,
	NULL,
	NULL,
	NULL,
	NULL,
	NULL,
	NULL,
	M1.SITE_CD,
	M2.SITE_NM,
	M1.LG_GRP_CD,
	M3.LG_GRP_NM,
	M1.SPPL_CD,
	M4.BP_NM,
	M1.STR_LN_TGT_FLG,
	M1.PRNT_LCL_CD,
	NULL,
	M1.DEL_FLG,
	M1.DEL_USR_ID,
	M1.DEL_USR_NM,
	M1.DEL_TS
FROM
	MAM_LOC M1
	LEFT JOIN MAM_SITE M2 ON (M2.SITE_CD = M1.SITE_CD)
	LEFT JOIN MAM_LG_GRP M3 ON (M3.LG_GRP_CD = M1.LG_GRP_CD)
	LEFT JOIN MAM_BP M4 ON (M4.BP_CD = M1.SPPL_CD)
/

