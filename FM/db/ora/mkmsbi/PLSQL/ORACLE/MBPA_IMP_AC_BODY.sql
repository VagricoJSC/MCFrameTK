		REC(i).XRATE_CD		:= x.XRATE_CD ;
		REC(i).XRATE		:= x.XRATE ;
		REC(i).NOTE_NO		:= x.NOTE_NO ;
		REC(i).NOTE_TYP		:= x.NOTE_TYP ;
		REC(i).DRAW_DT		:= x.DRAW_DT ;
		REC(i).DUE_DT		:= x.DUE_DT ;
		REC(i).BANK_CD		:= x.BANK_CD ;
