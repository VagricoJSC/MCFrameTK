	I_DT		IN	MAPA_META.DT%TYPE,
	O_AC_TAX_CD	OUT	MAPA_META.TAX_CD%TYPE
	)
/**************************************************************************
<SYNOPSIS>
	会計税変換処理
<REMARKS>

<ARGUMENTS>
<IN>	I_AC_SLIP_TYP
		会計伝票区分
<IN>	I_TAX_CD
		税ＣＤ
<IN>	I_DT
		対象日
<OUT>	O_AC_TAX_CD
		会計税ＣＤ
<HISTORY>
**************************************************************************/
IS
	L_CNT		NUMBER ;
BEGIN
	IF I_TAX_CD IS NULL THEN
		O_AC_TAX_CD := I_TAX_CD ;
		RETURN ;
	END IF ;

	IF TAX_MAP_REC.EXISTS(I_TAX_CD) THEN
		O_AC_TAX_CD := TAX_MAP_REC(I_TAX_CD) ;
		RETURN ;
	END IF ;

	O_AC_TAX_CD := NULL ;
	IF G_TMAP = C_ON THEN
		SELECT	MIN(m.AC_TAX_CD)
		INTO	O_AC_TAX_CD
		FROM	MAM_AC_TAX_MAP m
		WHERE	0=0
		AND	m.AC_SLIP_TYP = I_AC_SLIP_TYP
		AND	m.TAX_CD = I_TAX_CD
		AND	m.ST_DT <= I_DT
		AND	m.END_DT >= I_DT
		AND	m.DEL_FLG = C_OFF
		AND	EXISTS (
				SELECT	'X'
				FROM	MAM_AC_TAX w
				WHERE	0=0
				AND	w.AC_TAX_CD = m.AC_TAX_CD
				AND	w.ST_DT	 <= I_DT
				AND	w.END_DT >= I_DT
				AND	w.DEL_FLG = C_OFF
				)
	 	;

		IF O_AC_TAX_CD IS NULL THEN
			-- 会計税対応マスタに有効なレコードが登録されていません。会計伝票区分：{1} 税ＣＤ：{2}
			FCPA_BATCH_LOG.P_DATA_LOG('MBBBD0028', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2, I_AC_SLIP_TYP, I_TAX_CD) ;
		END IF ;
	ELSE
		SELECT	COUNT(*)
		INTO	L_CNT
		FROM	MAM_AC_TAX m
		WHERE	0=0
		AND	m.AC_TAX_CD = I_TAX_CD
		AND	m.ST_DT	 <= I_DT
		AND	m.END_DT >= I_DT
		AND	m.DEL_FLG = C_OFF
		;

		IF L_CNT > 0 THEN
			O_AC_TAX_CD := I_TAX_CD ;
		ELSE
			-- 会計税マスタに有効なレコードが登録されていません。税ＣＤ：{1}
			FCPA_BATCH_LOG.P_DATA_LOG('MBBBD0029', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2, I_TAX_CD) ;
		END IF ;
	END IF ;

	TAX_MAP_REC(I_TAX_CD) := O_AC_TAX_CD ;
END ;
