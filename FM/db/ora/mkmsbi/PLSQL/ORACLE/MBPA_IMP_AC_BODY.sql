PROCEDURE P_SET_AC_DPT (
	I_DPT_CD	IN	MAPA_META.DPT_CD%TYPE,
	I_DT		IN	MAPA_META.DT%TYPE,
	O_AC_DPT_CD	OUT	MAPA_META.AC_DPT_CD%TYPE
	)
/**************************************************************************
<SYNOPSIS>
	会計部門変換処理
<REMARKS>

<ARGUMENTS>
<IN>	I_DPT_CD
		部門ＣＤ
<IN>	I_DT
		対象日
<OUT>	O_AC_DPT_CD
		会計部門ＣＤ
<HISTORY>
**************************************************************************/
IS
BEGIN
	IF I_DPT_CD IS NULL THEN
		O_AC_DPT_CD := I_DPT_CD ;
		RETURN ;
	END IF ;

	IF DPT_REC.EXISTS(I_DPT_CD) THEN
		O_AC_DPT_CD := DPT_REC(I_DPT_CD) ;
		RETURN ;
	END IF ;

	SELECT	MIN(m.AC_DPT_CD)
	INTO	O_AC_DPT_CD
	FROM	MAM_DPT m
	WHERE	0=0
	AND	m.DPT_CD = I_DPT_CD
	AND	m.ST_DT	 <= I_DT
	AND	m.END_DT >= I_DT
	AND	m.DEL_FLG = C_OFF
	AND	EXISTS (
			SELECT	'X'
			FROM	MAM_AC_DPT w
			WHERE	0=0
			AND	w.AC_DPT_CD = m.AC_DPT_CD
			AND	w.ST_DT	 <= I_DT
			AND	w.END_DT >= I_DT
			AND	w.DEL_FLG = C_OFF
			)
	;

	IF O_AC_DPT_CD IS NULL THEN
		-- 対象の部門を会計部門に変換できませんでした。部門ＣＤ：{1}
		FCPA_BATCH_LOG.P_DATA_LOG('MBBBD0027', G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2, I_DPT_CD) ;
	END IF ;

	DPT_REC(I_DPT_CD) := O_AC_DPT_CD ;

END P_SET_AC_DPT ;

