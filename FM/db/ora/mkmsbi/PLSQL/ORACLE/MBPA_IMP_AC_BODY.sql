			GOTO NEXT_LOOP ;
		END IF ;

		IF L_TMP_DT IS NULL OR L_TMP_DT <> x.AC_DT THEN
			DPT_REC.DELETE ;
			TAX_MAP_REC.DELETE ;
			L_TMP_DT := x.AC_DT ;
