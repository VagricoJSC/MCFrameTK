PROCEDURE P_NOTE
/**************************************************************************
<SYNOPSIS>
	手形情報取込処理
<REMARKS>

<ARGUMENTS>

<HISTORY>
**************************************************************************/
IS
	C_PROC_NM	CONSTANT VARCHAR2(30) := 'MBPA_IMP_AC.P_NOTE' ;

	C_AC_NOTE_SEQ	CONSTANT MAPA_META.ORA_OBJ_NM%TYPE := MAC_NUM_SYS_TYP.AC_NOTE ;
	C_IT_DAT_NO_L	CONSTANT NUMBER := MAPA_META.IT_DAT_NO_L() ;

	TYPE LIST_NOTE IS TABLE OF MBT_AC_NOTE%ROWTYPE INDEX BY BINARY_INTEGER ;
	REC 	LIST_NOTE ;
	i	BINARY_INTEGER ;

	TYPE LIST_ROWID IS TABLE OF ROWID INDEX BY BINARY_INTEGER ;
	REC_ID	LIST_ROWID ;
	d1	BINARY_INTEGER ;

	L_CNT		NUMBER ;
	L_REC_CNT	NUMBER ;
	L_CHK_ERR	MAPA_META.FLG%TYPE ;
	L_MAX_TS	MAPA_META.SYS_TS%TYPE ;

	L_TMP_DT	MAPA_META.DT%TYPE ;

	L_DPT		MAPA_META.AC_DPT_CD%TYPE ;
/************************************************************************/
PROCEDURE INS_NOTE
IS
BEGIN
	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MBT_AC_NOTE VALUES REC(t) ;

		FORALL t IN 1..d1
			UPDATE	MST_NOTE_IF t
			SET	t.A_IMP_FLG = C_ON
			WHERE	0=0
			AND	t.ROWID = REC_ID(t)
			AND	t.A_IMP_FLG = '0'
			;
	END IF ;

	REC.DELETE ;
	REC_ID.DELETE ;
	i := 0 ;
	d1 := 0 ;
END ;
/************************************************************************/
BEGIN
	-- 処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MBBBD0001', C_PROC_NM) ;

	-- ロック後に追加されたレコードは取込対象外にする
	L_MAX_TS := NULL ;
	FOR y IN (
		SELECT	t.INS_TS
		FROM	MST_NOTE_IF t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	(t.A_IMP_FLG = C_OFF OR G_RERUN = C_ON)
		ORDER BY t.INS_TS DESC, NOTE_IF_NO
		FOR UPDATE NOWAIT
		)
	LOOP
		L_MAX_TS := y.INS_TS ;
		EXIT ;
	END LOOP ;

	IF G_RERUN = C_ON THEN
		-- 再取込チェック
		SELECT	COUNT(*)
		INTO	L_CNT
		FROM	MBT_AC_NOTE t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT BETWEEN G_DT_FR AND G_DT_TO
		AND	t.FIN_FLG = C_ON
		;

		IF L_CNT > 0 THEN
			-- 対象の手形データで処理済みのレコードがあるため再取込できません。
			FCPA_ERR.RAISE_APP_ERR('MBBBD0034') ;
		ELSE
			DELETE	MBT_AC_NOTE t
			WHERE	0=0
			AND	t.AC_YM = G_YM
			AND	t.AC_DT BETWEEN G_DT_FR AND G_DT_TO
			;
		END IF ;

		UPDATE	MST_NOTE_IF t
		SET	t.A_IMP_FLG = C_OFF
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	t.A_IMP_FLG = C_ON
		AND	t.INS_TS <= L_MAX_TS
		;

	END IF ;

	FOR z1 IN (
		SELECT	t.*,
			t.ROWID		ROW_ID
		FROM	MST_NOTE_IF t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	t.A_IMP_FLG = C_OFF
		AND	t.INS_TS <= L_MAX_TS
		AND	t.BASE_CUR_AMT < 0
		ORDER BY t.NOTE_IF_NO
		)
	LOOP
		FOR z2 IN (
			SELECT	t.*,
				t.ROWID		ROW_ID
			FROM	MST_NOTE_IF t
			WHERE	0=0
			AND	t.AC_YM = z1.AC_YM
			AND	t.AC_DT = z1.AC_DT
			AND	(t.NOTE_RSN_CD = z1.NOTE_RSN_CD OR t.NOTE_RSN_CD IS NULL AND z1.NOTE_RSN_CD IS NULL)
			AND	t.DPT_CD = z1.DPT_CD
			AND	t.RCST_CD = z1.RCST_CD
			AND	t.NOTE_NO = z1.NOTE_NO
			AND	t.NOTE_TYP = z1.NOTE_TYP
			AND	t.BANK_CD = z1.BANK_CD
			AND	t.BRANCH_CD = z1.BRANCH_CD
			AND	t.BASE_CUR_AMT > 0
			AND	ABS(t.BASE_CUR_AMT) = ABS(z1.BASE_CUR_AMT)
			AND	t.NOTE_IF_NO < z1.NOTE_IF_NO
			AND	t.A_IMP_FLG = C_OFF
			AND	t.INS_TS <= L_MAX_TS
			ORDER BY t.NOTE_IF_NO
			)
		LOOP

			UPDATE	MST_NOTE_IF t
			SET	t.A_IMP_FLG = C_ON
			WHERE	0=0
			AND	t.ROWID = z2.ROW_ID
			;

			UPDATE	MST_NOTE_IF t
			SET	t.A_IMP_FLG = C_ON
			WHERE	0=0
			AND	t.ROWID = z1.ROW_ID
			;

			EXIT ;
		END LOOP ;
	END LOOP ;

	i := 0 ;
	d1 := 0 ;
	L_REC_CNT := 0 ;
	L_CHK_ERR := C_OFF ;
	L_TMP_DT := NULL ;
	DPT_REC.DELETE ;
	FOR x IN (
		SELECT	t.ROWID		ROW_ID,
			t.NOTE_IF_NO,
			m1.WG_CD,
			t.AC_YM,
			TRUNC(t.AC_DT, 'DD')	AC_DT,
			t.NOTE_RSN_CD,
			t.DPT_CD,
			t.RCST_CD,
			t.FOREIGN_FLG,
			t.BASE_CUR_CD,
			t.BASE_CUR_AMT,
			t.BASE_CUR_TAX_AMT,
			t.TRD_CUR_CD,
			t.TRD_CUR_AMT,
			t.TRD_CUR_TAX_AMT,
			t.XRATE_CD,
			t.XRATE,
			t.NOTE_NO,
			t.NOTE_TYP,
			t.DRAW_DT,
			t.DUE_DT,
			t.BANK_CD,
			t.BRANCH_CD,
			t.DRAWER_NM,
			t.ENDRSR1,
			t.ENDRSR2,
			t.ENDRSR3,
			t.ENDRSR4,
			t.ENDRSR5,
			t.ACCPTR,
			t.SUB_CHAR1,
			t.SUB_CHAR2,
			t.SUB_CHAR3,
			t.SUB_CHAR4,
			t.SUB_CHAR5,
			t.SUB_CHAR6,
			t.SUB_CHAR7,
			t.SUB_CHAR8,
			t.SUB_CHAR9,
			t.SUB_CHAR10,
			t.SUB_NUM1,
			t.SUB_NUM2,
			t.SUB_NUM3,
			t.SUB_DT1,
			t.SUB_DT2,
			t.SUB_DT3
		FROM	MST_NOTE_IF t, MAM_DPT m1
		WHERE	0=0
		AND	m1.DPT_CD = t.DPT_CD
		AND	m1.ST_DT  <= t.AC_DT
		AND	m1.END_DT >= t.AC_DT
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	t.A_IMP_FLG = C_OFF
		AND	t.INS_TS <= L_MAX_TS
		ORDER BY t.AC_DT, t.NOTE_IF_NO
		)
	LOOP
		IF x.BASE_CUR_AMT = 0 AND x.BASE_CUR_TAX_AMT = 0 THEN
			UPDATE	MST_NOTE_IF t
			SET	t.A_IMP_FLG = C_ON
			WHERE	0=0
			AND	t.ROWID = x.ROW_ID
			AND	t.A_IMP_FLG = C_OFF
			;

			GOTO NEXT_LOOP ;
		END IF ;

		IF L_TMP_DT IS NULL OR L_TMP_DT <> x.AC_DT THEN
			DPT_REC.DELETE ;
			L_TMP_DT := x.AC_DT ;
		END IF ;

		-- 受入部門
		P_SET_AC_DPT(x.DPT_CD, x.AC_DT, L_DPT) ;
		IF x.DPT_CD IS NOT NULL AND L_DPT IS NULL THEN
			L_CHK_ERR := C_ON ;
			GOTO NEXT_LOOP ;
		END IF ;

		i := i + 1 ;

		REC(i).DATA_NO		:= LPAD(MAPA_NUM.F_GET_SEQ(C_AC_NOTE_SEQ), C_IT_DAT_NO_L, '0') ;
		REC(i).WG_CD		:= x.WG_CD ;
		REC(i).AC_YM		:= x.AC_YM ;
		REC(i).AC_DT		:= x.AC_DT ;
		REC(i).NOTE_RSN_CD	:= x.NOTE_RSN_CD ;
		REC(i).DPT_CD		:= L_DPT ;
		REC(i).RCST_CD		:= x.RCST_CD ;
		REC(i).FOREIGN_FLG	:= x.FOREIGN_FLG ;
		REC(i).BASE_CUR_CD	:= x.BASE_CUR_CD ;
		REC(i).BASE_CUR_AMT	:= x.BASE_CUR_AMT ;
		REC(i).BASE_CUR_TAX_AMT	:= x.BASE_CUR_TAX_AMT ;
		REC(i).TRD_CUR_CD	:= x.TRD_CUR_CD ;
		REC(i).TRD_CUR_AMT	:= x.TRD_CUR_AMT ;
