PROCEDURE P_MAIN (
	I_AC_YM		IN	MAPA_META.YM%TYPE,
	I_DT_FR		IN	MAPA_META.DT%TYPE,
	I_DT_TO		IN	MAPA_META.DT%TYPE,
	I_IO		IN	MAPA_META.FLG%TYPE,
	I_STK		IN	MAPA_META.FLG%TYPE,
	I_RCV		IN	MAPA_META.FLG%TYPE,
	I_PAY		IN	MAPA_META.FLG%TYPE,
	I_SCHDPAY	IN	MAPA_META.FLG%TYPE,
	I_NOTE		IN	MAPA_META.FLG%TYPE,
	I_RERUN		IN	MAPA_META.FLG%TYPE,
	I_REGET		IN	MAPA_META.FLG%TYPE
)
/**************************************************************************
<SYNOPSIS>
	取込のメイン処理
<REMARKS>
	ＳＣＭから会計ＩＦ用テーブル(MBT_AC_***)への取込処理。
<ARGUMENTS>
<IN>	I_AC_YM
		取込対象月
<IN>	I_ST_DT
		取込対象開始日 (NULLのときは指定月の開始日）
<IN>	I_END_DT
		取込対象終了日（指定日も含む)(NULLのときは指定月の最終日）
<IN>	I_IO
		受払情報取込ＦＬＧ
<IN>	I_STK
		在庫情報取込ＦＬＧ
<IN>	I_RCV
		入金情報ＦＬＧ
<IN>	I_PAY
		支払情報ＦＬＧ
<IN>	I_NOTE
		手形情報ＦＬＧ
<IN>	I_RERUN
		再取込ＦＬＧ 0:未取込のレコードが対象 1:取込済みのレコードも対象
<IN>	I_REGET
		マスタ再取得ＦＬＧ 0:取り込み時にトランザクションの品目情報を使用する 1:取り込み時に共通品目マスタの情報を使用する
<HISTORY>
**************************************************************************/
IS
	LOCK_ERROR     EXCEPTION ;
	PRAGMA EXCEPTION_INIT(LOCK_ERROR, -54) ;

	C_PROC_NM	CONSTANT VARCHAR2(30) := 'MBPA_IMP_AC.P_MAIN' ;

	L_CNT		NUMBER ;

BEGIN
	-- 処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MBBBD0001', C_PROC_NM) ;

	G_YM := I_AC_YM ;
	G_RERUN := I_RERUN ;
	G_REGET := I_REGET ;

	-- 自社情報の取得
	G_CO := MAPA_CO.F_GET_CO_REC() ;

	-- 対象期間の設定
	-- 対象開始日がNULLのときはすべて有効(1000/01/01をセット)
	IF I_DT_FR IS NULL THEN
		G_DT_FR := TO_DATE('10000101', 'YYYYMMDD') ;
	ELSE
		G_DT_FR := I_DT_FR ;
	END IF ;
	-- 対象終了日がNULLのときはすべて有効(2999/12/31をセット)
	IF I_DT_TO IS NULL THEN
		G_DT_TO := TO_DATE('29991231', 'YYYYMMDD') ;
	ELSE
		G_DT_TO := I_DT_TO ;
	END IF ;

	G_DT_FR := TRUNC(G_DT_FR, 'DD') ;
	G_DT_TO := TRUNC(G_DT_TO, 'DD') ;

	-- 月度初／末日の計算
	G_ST_DT := MAPA_DT.F_GET_YM_ST_DT_NE(G_YM, G_CO.AC_CL_DAY, G_CO.AC_CL_MON_BASE) ;
	G_END_DT := MAPA_DT.F_GET_YM_END_DT_NE(G_YM, G_CO.AC_CL_DAY, G_CO.AC_CL_MON_BASE) ;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_SLIP_JNL m
	WHERE	0=0
	AND	m.DEL_FLG = C_OFF
	;

	IF L_CNT = 0 THEN
		-- 仕訳対象の会計伝票区分が存在していません。会計伝票区分仕訳マスタを確認してください。
		FCPA_ERR.RAISE_APP_ERR('MBBBD0035') ;
	END IF ;

	-- 対象年月の月初日に対して有効な会計税対応マスタが１件でも登録されていたら会計税対応マスタを使用する
	G_TMAP	:= C_OFF ;
	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_AC_TAX_MAP m
	WHERE	0=0
	AND	m.ST_DT <= G_ST_DT
	AND	m.END_DT >= G_ST_DT
	AND	m.DEL_FLG = C_OFF
	AND	EXISTS (
			SELECT	'X'
			FROM	MAM_AC_TAX y
			WHERE	0=0
			AND	y.AC_TAX_CD = m.AC_TAX_CD
			AND	y.ST_DT	 <= G_ST_DT
			AND	y.END_DT >= G_ST_DT
			AND	y.DEL_FLG = C_OFF
		)
	AND	ROWNUM = 1
	;

	IF L_CNT = 1 THEN
		G_TMAP := C_ON ;
	END IF ;

	-- 会計理由マスタの取得
	INVALID_RSN_REC.DELETE ;
	FOR z IN (
		SELECT	m.AC_RSN_CD,
			m.AC_INVALID_FLG
		FROM	MAM_AC_RSN m
		WHERE	0=0
		AND	m.AC_INVALID_FLG = C_ON
		AND	m.DEL_FLG = C_OFF
		)
	LOOP
		INVALID_RSN_REC(z.AC_RSN_CD) := z.AC_INVALID_FLG ;
	END LOOP ;
	-- 仕訳キー対応マスタの取得
	L_CNT := 0 ;
	JNL_KEY_MAP_REC.DELETE ;
	FOR r IN (
		SELECT	*
		FROM	MAM_JNL_KEY_MAP m
		WHERE	0=0
		AND	m.COST_FLG = C_OFF
		ORDER BY m.AC_SLIP_TYP, m.JNL_KEY_COL_TYP
		)
	LOOP
		L_CNT := L_CNT + 1 ;
		JNL_KEY_MAP_REC(L_CNT) := r ;
	END LOOP ;


	IF I_IO = C_ON THEN
		P_IO() ;
	END IF ;

	IF I_STK = C_ON THEN
		P_STK() ;
	END IF ;

	IF I_RCV = C_ON THEN
		P_RCV() ;
	END IF ;

	IF I_PAY = C_ON THEN
		P_PAY() ;
	END IF ;

	IF I_SCHDPAY = C_ON THEN
		P_SCHDPAY() ;
	END IF ;

	IF I_NOTE = C_ON THEN
		P_NOTE() ;
	END IF ;

	DPT_REC.DELETE ;
	TAX_MAP_REC.DELETE ;
	INVALID_RSN_REC.DELETE ;
	JNL_KEY_MAP_REC.DELETE ;
	BP_GRP_REC.DELETE ;

	-- 処理が終了しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MBBBD0002', C_PROC_NM) ;

EXCEPTION
WHEN LOCK_ERROR THEN
	FCPA_ERR.RAISE_APP_ERR('MBBBD0003') ;

END P_MAIN ;

END MBPA_IMP_AC ;
