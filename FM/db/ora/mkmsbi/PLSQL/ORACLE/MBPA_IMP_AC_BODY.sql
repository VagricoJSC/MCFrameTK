		P_SET_AC_DPT(x.AP_DPT_CD, x.AC_DT, L_AP_DPT) ;
		IF x.AP_DPT_CD IS NOT NULL AND L_AP_DPT IS NULL THEN
			L_CHK_ERR := C_ON ;
			GOTO NEXT_LOOP ;
