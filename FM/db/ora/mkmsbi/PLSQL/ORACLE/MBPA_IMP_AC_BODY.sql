		P_SET_AC_DPT(x.SLS_DPT_CD, x.AC_DT, L_SLS_DPT) ;
		IF x.SLS_DPT_CD IS NOT NULL AND L_SLS_DPT IS NULL THEN
			L_CHK_ERR := C_ON ;
			GOTO NEXT_LOOP ;
