		P_SET_AC_DPT(x.BD_DPT_CD, x.AC_DT, L_BD_DPT) ;
		IF x.BD_DPT_CD IS NOT NULL AND L_BD_DPT IS NULL THEN
			L_CHK_ERR := C_ON ;
			GOTO NEXT_LOOP ;
		END IF ;

		-- 予備部門1
		P_SET_AC_DPT(x.SUB_DPT_CD1, x.AC_DT, L_SUB_DPT1) ;
