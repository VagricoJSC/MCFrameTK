PROCEDURE INS_IO
IS
BEGIN
	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MBT_AC_IO VALUES REC(t) ;

		FORALL t IN 1..d1
			UPDATE	MST_IO_ACT t
			SET	t.A_IMP_FLG = C_ON
			WHERE	0=0
			AND	t.ROWID = REC_ID(t)
			AND	t.A_IMP_FLG = C_OFF
			;
	END IF ;

	REC.DELETE ;
	REC_ID.DELETE ;
	i := 0 ;
	d1 := 0 ;
END ;
/************************************************************************/
BEGIN
	-- 処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MBBBD0001', C_PROC_NM) ;

	-- ロック後に追加されたレコードは取込対象外にする
	L_MAX_TS := NULL ;
	FOR y IN (
		SELECT	t.INS_TS
		FROM	MST_IO_ACT t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	(t.A_IMP_FLG = C_OFF OR G_RERUN = C_ON)
		AND	EXISTS (
				SELECT	'X'
				FROM	MAM_SLIP_JNL x
				WHERE	0=0
				AND	DECODE(x.AC_SLIP_TYP, C_PURC_IN_TRANSIT, C_PURC, x.AC_SLIP_TYP) = t.AC_SLIP_TYP
				AND	x.DEL_FLG = C_OFF
				)
		ORDER BY t.INS_TS DESC, t.SLIP_NO, t.SLIP_SEQ_NO
		FOR UPDATE NOWAIT
		)
	LOOP
		L_MAX_TS := y.INS_TS ;
		EXIT ;
	END LOOP ;
	-- 会計伝票区分仕訳マスタに「未着品仕入」が登録されているか
	L_PURC_IN_TRANSIT_FLG := C_OFF;
	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_SLIP_JNL t
	WHERE	0=0
	AND	t.AC_SLIP_TYP = C_PURC_IN_TRANSIT
	AND	t.DEL_FLG = C_OFF
	;
	IF L_CNT > 0 THEN
		L_PURC_IN_TRANSIT_FLG := C_ON;
	END IF ;
	-- 会計伝票区分仕訳マスタに「仕入」が登録されているか
	L_PURC_FLG := C_OFF;
	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MAM_SLIP_JNL t
	WHERE	0=0
	AND	t.AC_SLIP_TYP = C_PURC
	AND	t.DEL_FLG = C_OFF
	;
	IF L_CNT > 0 THEN
