PROCEDURE INS_PAY
IS
BEGIN
	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MBT_AC_PAY VALUES REC(t) ;

		FORALL t IN 1..d1
			UPDATE	MST_PAY_ACT_IF t
			SET	t.A_IMP_FLG = C_ON
			WHERE	0=0
			AND	t.ROWID = REC_ID(t)
			AND	t.A_IMP_FLG = C_OFF
			;
	END IF ;

	REC.DELETE ;
	REC_ID.DELETE ;
	i := 0 ;
	d1 := 0 ;
END ;
/************************************************************************/
BEGIN
	-- 処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MBBBD0001', C_PROC_NM) ;

	-- ロック後に追加されたレコードは取込対象外にする
	L_MAX_TS := NULL ;
	FOR y IN (
		SELECT	t.INS_TS
		FROM	MST_PAY_ACT_IF t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	(t.A_IMP_FLG = C_OFF OR G_RERUN = C_ON)
		AND	EXISTS (
				SELECT	'X'
				FROM	MAM_SLIP_JNL x
				WHERE	0=0
				AND	x.AC_SLIP_TYP = t.AC_SLIP_TYP
				AND	x.DEL_FLG = C_OFF
				)
		ORDER BY t.INS_TS DESC, t.PAY_ACT_IF_NO
		FOR UPDATE NOWAIT
		)
	LOOP
		L_MAX_TS := y.INS_TS ;
		EXIT ;
	END LOOP ;

	IF G_RERUN = C_ON THEN
		-- 再取込チェック
		SELECT	MAX(t.JNL_FIN_CNT)
		INTO	L_CNT
		FROM	MBT_AC_PAY t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT BETWEEN G_DT_FR AND G_DT_TO
		;

		IF L_CNT > 0 THEN
			-- 対象の支払データで仕訳済みのレコードがあるため再取込できません。
			FCPA_ERR.RAISE_APP_ERR('MBBBD0037') ;
		ELSE
			DELETE	MBT_AC_PAY t
			WHERE	0=0
			AND	t.AC_YM = G_YM
			AND	t.AC_DT BETWEEN G_DT_FR AND G_DT_TO
			;
		END IF ;

		UPDATE	MST_PAY_ACT_IF t
		SET	t.A_IMP_FLG = C_OFF
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT >= G_DT_FR
		AND	t.AC_DT < G_DT_TO + 1
		AND	t.A_IMP_FLG = C_ON
		AND	t.INS_TS <= L_MAX_TS
		;
	END IF ;

	UPDATE	MST_PAY_ACT_IF t
	SET	t.A_IMP_FLG = C_ON
	WHERE	0=0
	AND	t.AC_YM = G_YM
	AND	t.PAY_ACT_NO != C_NULL_VAL --締処理為替評価替レコードは対象外
	AND	t.AC_DT >= G_DT_FR
	AND	t.AC_DT < G_DT_TO + 1
	AND	t.A_IMP_FLG = C_OFF
	AND	t.INS_TS <= L_MAX_TS
	AND	EXISTS (
			SELECT	'X'
			FROM	MAM_SLIP_JNL w
			WHERE	0=0
			AND	w.AC_SLIP_TYP = t.AC_SLIP_TYP
			AND	w.RED_INPUT_FLG = C_OFF
			AND	w.DEL_FLG = C_OFF
			)
	AND	EXISTS (
			SELECT	/*+INDEX(w MST_PAY_ACT_IF_ALL_IE02)*/
					'X'
			FROM	MST_PAY_ACT_IF w
			WHERE	0=0
			AND	w.PAY_ACT_NO = t.PAY_ACT_NO
			AND	w.PAY_ACT_REV = t.PAY_ACT_REV
			AND	w.AC_SLIP_TYP = t.AC_SLIP_TYP
			AND	w.AC_YM = G_YM
			AND	w.AC_DT >= G_DT_FR
			AND	w.AC_DT < G_DT_TO + 1
			AND	w.A_IMP_FLG = C_OFF
			AND	w.INS_TS <= L_MAX_TS
			GROUP BY w.PAY_ACT_NO, w.PAY_ACT_REV, w.AC_SLIP_TYP
			HAVING	SUM(DECODE(w.CAN_FLG, C_OFF, 1, 0))
				= SUM(DECODE(w.CAN_FLG, C_ON, 1, 0))
			)
	;

	i := 0 ;
	d1 := 0 ;
	L_REC_CNT := 0 ;
	L_CHK_ERR := C_OFF ;
	L_TMP_DT := NULL ;
	DPT_REC.DELETE ;
	TAX_MAP_REC.DELETE ;
	FOR x IN (
		SELECT	t.ROWID	ROW_ID,
