	FCPA_BATCH_LOG.P_PROC_LOG('MBBBD0001', C_PROC_NM) ;

	-- ロック後に追加されたレコードは取込対象外にする
	L_MAX_TS := NULL ;
	FOR y IN (
		SELECT	t.INS_TS
		FROM	MST_PAY_SCHD_IF t
		WHERE	0=0
		AND	t.AC_YM = G_YM
		AND	t.AC_DT BETWEEN G_DT_FR AND G_DT_TO
		AND	(t.A_IMP_FLG = C_OFF OR G_RERUN = C_ON)
		AND	t.AP_STTL_TYP IS NOT NULL
		AND	t.AP_STTL_TYP <> C_SETOFF
		AND	t.AP_STTL_TYP <> C_WTAX
		ORDER BY t.INS_TS DESC, t.PAY_SCHD_IF_NO
		FOR UPDATE NOWAIT
		)
