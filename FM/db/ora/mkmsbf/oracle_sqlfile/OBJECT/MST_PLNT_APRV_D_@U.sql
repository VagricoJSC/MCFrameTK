CREATE OR REPLACE VIEW MST_PLNT_APRV_D_$U(
	PLNT_APRV_D_NO,
	PLNT_APRV_NO,
	INSP_TYP,
	INSP_NO,
	SRC_NO1,
	SRC_NO2,
	SRC_NO3,
	SRC_NO4,
	BASE_UNIT_QTY,
	BASE_UNIT_CD,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PLNT_APRV_D_NO,
	ORG.PLNT_APRV_NO,
	ORG.INSP_TYP,
	ORG.INSP_NO,
	ORG.SRC_NO1,
	ORG.SRC_NO2,
	ORG.SRC_NO3,
	ORG.SRC_NO4,
	ORG.BASE_UNIT_QTY,
	ORG.BASE_UNIT_CD,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PLNT_APRV_D_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

