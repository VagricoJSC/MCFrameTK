CREATE OR REPLACE VIEW MST_STD_INSP_ACT(
	STD_INSP_ACT_NO,
	STD_INSP_INST_NO,
	INSP_NO,
	QN_INSP_VAL,
	QL_INSP_VAL,
	ST_TM,
	END_TM,
	DPT_CD,
	USR_CD,
	STD_INSP_RSLT_TYP,
	CNF_FLG,
	CNF_DT,
	CNF_DPT_CD,
	CNF_USR_CD,
	ACT_INTR_RMRKS,
	CNF_INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.STD_INSP_ACT_NO,
	ORG.STD_INSP_INST_NO,
	ORG.INSP_NO,
	ORG.QN_INSP_VAL,
	ORG.QL_INSP_VAL,
	ORG.ST_TM,
	ORG.END_TM,
	ORG.DPT_CD,
	ORG.USR_CD,
	ORG.STD_INSP_RSLT_TYP,
	ORG.CNF_FLG,
	ORG.CNF_DT,
	ORG.CNF_DPT_CD,
	ORG.CNF_USR_CD,
	ORG.ACT_INTR_RMRKS,
	ORG.CNF_INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_STD_INSP_ACT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

