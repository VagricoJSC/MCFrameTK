SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_LOT_LIST(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SCHD_FLG,
	VER_NO,
	FIRST_GR_DT,
	BASE_GR_DT,
	UNREG_LMT_FLG,
	VLD_DT,
	LMT_DT,
	LOT_MNG_TYP,
	SUBLOT_MNG_TYP,
	BP_LOT_NO,
	STK_INSP_TYP,
	QUALITY_TYP,
	MFG_APRV_STS_TYP,
	INSP_APRV_STS_TYP,
	PLNT_APRV_STS_TYP,
	MRKT_JUDG_STS_TYP,
	FIRST_GR_DT_SAVE_FLG,
	ACT_CONT_FCTR,
	LMT_DT_FRM_TYP,
	LMT_DT_FRM,
	LOT_SEQ,
	LOT_RMRKS,
	LOT_SUB_CHAR1,
	LOT_SUB_CHAR2,
	LOT_SUB_CHAR3,
	LOT_SUB_CHAR4,
	LOT_SUB_CHAR5,
	LOT_SUB_NUM1,
	LOT_SUB_NUM2,
	LOT_SUB_NUM3,
	LOT_SUB_NUM4,
	LOT_SUB_NUM5,
	LOT_SUB_DT1,
	LOT_SUB_DT2,
	LOT_SUB_DT3,
	LOT_SUB_DT4,
	LOT_SUB_DT5,
	LOT_SUB_FLG1,
	LOT_SUB_FLG2,
	LOT_SUB_FLG3,
	LOT_SUB_FLG4,
	LOT_SUB_FLG5
)
AS
SELECT 
	T1.ITM_CD,
	T1.ITM_SUB1,
	T1.ITM_SUB2,
	T1.ITM_SUB3,
	T1.LOT_NO,
	T1.SUBLOT_NO,
	T2.SCHD_FLG,
	T2.VER_NO,
	T2.FIRST_GR_DT,
	T2.BASE_GR_DT,
	T2.UNREG_LMT_FLG,
	T2.VLD_DT,
	T2.LMT_DT,
	T2.LOT_MNG_TYP,
	T2.SUBLOT_MNG_TYP,
	T2.BP_LOT_NO,
	T2.STK_INSP_TYP,
	T2.QUALITY_TYP,
	T2.MFG_APRV_STS_TYP,
	T2.INSP_APRV_STS_TYP,
	T2.PLNT_APRV_STS_TYP,
	T2.MRKT_JUDG_STS_TYP,
	T2.FIRST_GR_DT_SAVE_FLG,
	T2.ACT_CONT_FCTR,
	T2.LMT_DT_FRM_TYP,
	T2.LMT_DT_FRM,
	T2.LOT_SEQ,
	T2.LOT_RMRKS,
	T2.LOT_SUB_CHAR1,
	T2.LOT_SUB_CHAR2,
	T2.LOT_SUB_CHAR3,
	T2.LOT_SUB_CHAR4,
	T2.LOT_SUB_CHAR5,
	T2.LOT_SUB_NUM1,
	T2.LOT_SUB_NUM2,
	T2.LOT_SUB_NUM3,
	T2.LOT_SUB_NUM4,
	T2.LOT_SUB_NUM5,
	T2.LOT_SUB_DT1,
	T2.LOT_SUB_DT2,
	T2.LOT_SUB_DT3,
	T2.LOT_SUB_DT4,
	T2.LOT_SUB_DT5,
	T2.LOT_SUB_FLG1,
	T2.LOT_SUB_FLG2,
	T2.LOT_SUB_FLG3,
	T2.LOT_SUB_FLG4,
	T2.LOT_SUB_FLG5
FROM
	MST_LOT_LIST T1
	LEFT OUTER JOIN MST_LOT T2 ON 
		(T2.ITM_CD = T1.ITM_CD
		AND T2.ITM_SUB1 = T1.ITM_SUB1
		AND T2.ITM_SUB2 = T1.ITM_SUB2
		AND T2.ITM_SUB3 = T1.ITM_SUB3
		AND T2.LOT_NO = T1.LOT_NO
		AND T2.SUBLOT_NO = T1.LOT_TBL_SUBLOT_NO
		)
;

