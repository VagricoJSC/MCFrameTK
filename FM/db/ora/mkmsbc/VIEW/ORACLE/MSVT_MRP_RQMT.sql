SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY - NVL(T2.YIELD_SCHD_QTY,0) AS RQMT_QTY
	,T1.SNO1
	,CAST(DECODE(T1.SNO1, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO1_TYP
	,T1.SNO2
	,CAST(DECODE(T1.SNO2, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO2_TYP
	,T1.SNO3
	,CAST(DECODE(T1.SNO3, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO3_TYP
	,T1.SNO4
	,CAST(DECODE(T1.SNO4, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
FROM
	MST_RQMT T1,
	(
		SELECT T3.RQMT_NO, SUM(T3.YIELD_SCHD_QTY) AS YIELD_SCHD_QTY
		FROM MST_ITM_ORDER T3
		WHERE T3.ITM_ORD_STS_TYP IN (MSC_ITM_ORD_STS_TYP.FIX,MSC_ITM_ORD_STS_TYP.INST,MSC_ITM_ORD_STS_TYP.CMPL)
		AND T3.RQMT_NO IS NOT NULL
		GROUP BY RQMT_NO
	) T2
WHERE 0=0
AND T1.FIX_FLG = '0'
AND T1.RQMT_NO = T2.RQMT_NO(+)
AND T1.RQMT_QTY - NVL(T2.YIELD_SCHD_QTY,0) > 0
UNION ALL
SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY - NVL(T2.YIELD_SCHD_QTY,0) AS RQMT_QTY
	,T1.SNO1
	,T1.SNO1_TYP
	,T1.SNO2
	,T1.SNO2_TYP
	,T1.SNO3
	,T1.SNO3_TYP
	,T1.SNO4
	,T1.SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
FROM
	MSVT_MRP_DLY_RQMT T1,
	(
		SELECT T3.RQMT_NO, SUM(T3.YIELD_SCHD_QTY) AS YIELD_SCHD_QTY
		FROM MST_ITM_ORDER T3
		WHERE T3.ITM_ORD_STS_TYP IN (MSC_ITM_ORD_STS_TYP.FIX,MSC_ITM_ORD_STS_TYP.INST,MSC_ITM_ORD_STS_TYP.CMPL)
		AND T3.RQMT_NO IS NOT NULL
		GROUP BY RQMT_NO
	) T2
WHERE 0=0
AND T1.RQMT_NO = T2.RQMT_NO(+)
AND T1.RQMT_QTY - NVL(T2.YIELD_SCHD_QTY,0) > 0
/
