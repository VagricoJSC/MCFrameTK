SELECT
	T1.PURC_ACT_D_NO,
	T1.PURC_ACT_D_SEQ,
	T4.ITM_MFG_INST_NO,
	T5.BASE_UNIT_INST_QTY AS ITM_INST_QTY,
	T1.MFG_INST_NO,
	T4.MFG_ACT_NO,
	T6.BASE_UNIT_MFG_QTY AS MFG_ST_QTY,
	T5.MFG_LOC_CD AS OUTSRC_MFG_LOC_CD,
	T5.WG_CD AS OUTSRC_MFG_LOC_WG_CD,
	T5.LOT_NO AS PAR_LOT_NO,
	T5.SUBLOT_NO AS PAR_SUBLOT_NO
FROM
	MST_PURC_ACT_D T1
	JOIN MST_PURC_SCHD T2 ON (T1.PURC_SCHD_NO = T2.PURC_SCHD_NO)
	JOIN MST_ARR_SCHD T3 ON (T2.ARR_SCHD_NO = T3.ARR_SCHD_NO)
	JOIN MST_MFG_ACT T4 ON (T1.MFG_INST_NO = T4.MFG_INST_NO)
	JOIN MST_ITM_MFG_INST T5 ON (T4.ITM_MFG_INST_NO = T5.ITM_MFG_INST_NO)
	JOIN MST_MFG_ACT_REM T6 ON (T4.MFG_INST_NO = T6.MFG_INST_NO AND T4.DIV_SEQ = T6.DIV_SEQ)
	JOIN MST_PURC_ACT T7 ON (T1.PURC_ACT_NO = T7.PURC_ACT_NO AND T1.PURC_ACT_SEQ = T7.PURC_ACT_SEQ)
WHERE 0=0
AND T7.SLIP_STS_TYP = MAC_SLIP_STS_TYP.CRT
/
