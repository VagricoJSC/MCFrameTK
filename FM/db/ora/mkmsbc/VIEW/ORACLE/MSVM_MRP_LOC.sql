SELECT
	 T1.LOC_CD
	,T1.LOC_GRP_CD
	,NVL(T1.CAL_CD, T4.STD_CAL_CD) AS CAL_CD
	,T1.SITE_CD
	,T1.LG_GRP_CD
	,NVL(T2.CAL_CD, T4.STD_CAL_CD) AS LG_CAL_CD
	,T1.SPPL_CD
	,T3.SPPL_CAL_CD
	,T1.LOC_MNG_TYP
	,T1.ALLOC_LMT_FLG
	,T1.WG_CD
FROM MAM_LOC T1, MAM_LG_GRP T2, MAM_BP T3, MAM_CO T4
WHERE 0=0
AND T1.LG_GRP_CD = T2.LG_GRP_CD(+)
AND T1.SPPL_CD = T3.BP_CD(+)
AND T1.DEL_FLG = '0'
/
