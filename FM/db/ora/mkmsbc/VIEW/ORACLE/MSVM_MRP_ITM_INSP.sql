SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.MAKER_CD
	,T1.FROM_SITE_CD
	,T1.TO_SITE_CD
	,T2.INSP_LT
	,T1.INSP_OFFST
	,GREATEST(T1.ST_DT,NVL(T2.ST_DT,T1.ST_DT)) AS ST_DT
	,LEAST(T1.END_DT,NVL(T2.END_DT,T1.END_DT)) AS END_DT
	,T3.WG_CD
FROM MAM_ITM_INSP T1, MAM_ITM_INSP_PTN T2, MAM_LOC T3
WHERE 0=0
AND T1.ITM_CD = T2.ITM_CD
AND T1.ITM_SUB1 = T2.ITM_SUB1
AND T1.ITM_SUB2 = T2.ITM_SUB2
AND T1.ITM_SUB3 = T2.ITM_SUB3
AND T1.INSP_PTN_CD = T2.INSP_PTN_CD
AND GREATEST(T1.ST_DT,NVL(T2.ST_DT,T1.ST_DT)) <= LEAST(T1.END_DT,NVL(T2.END_DT,T1.END_DT))
AND T1.MFG_LOC_CD = T3.LOC_CD(+)
AND T1.DEL_FLG = '0'
AND T2.DEL_FLG = '0'
/
