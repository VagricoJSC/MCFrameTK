CREATE OR REPLACE VIEW MSVT_LITEMES_WK_STS(
	CO_CD,
	WK_SCHD_NO,
	OPER_INST_NO,
	MFG_INST_NO,
	WK_COST,
	FXD_WK_COST,
	MFG_STS_TYP,
	MFG_STS_TYP_NM,
	MFG_STS_TYP_NM_LCL1,
	MFG_STS_TYP_NM_LCL2,
	MFG_STS_TYP_NM_LCL3,
	MFG_STS_TYP_NM_LCL4,
	MFG_STS_TYP_NM_LCL5,
	INST_MFG_STS_TYP,
	WK_ACT_COST,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	WG_NM,
	WG_NM_LCL1,
	WG_NM_LCL2,
	WG_NM_LCL3,
	WG_NM_LCL4,
    WG_NM_LCL5,
    WK_COST_CD,
    OPER_CD,
    ST_SCHD_TM,
    END_SCHD_TM,
    ST_TM,
    END_TM,
    BRK_PD,
    ST_ACT_TM,
    END_ACT_TM
    )
AS
SELECT
	T1.CO_CD,
	T1.WK_SCHD_NO, -- 工数予定NO
	T1.OPER_INST_NO, -- 工程指図NO
	T1.MFG_INST_NO, -- 製造指図NO
	T1.WK_COST, -- 予定工数（数量依存）
	T1.FXD_WK_COST, -- 予定工数（固定）
	T2.MFG_STS_TYP, -- 製造状況区分[工数状況]
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,'ja_JP'),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,'en_US'),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,'zh_CN'),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,''),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,''),
	T7.MFG_STS_TYP AS INST_MFG_STS_TYP,
	NVL(T3.WK_ACT_COST, 0), -- 工数実績
	T5.ITM_CD, -- 製造品目CD
	T5.ITM_SUB1,
	T5.ITM_SUB2,
	T5.ITM_SUB3,
	M1.WG_NM,
    M1.WG_NM_LCL1,
	M1.WG_NM_LCL2,
	M1.WG_NM_LCL3,
	M1.WG_NM_LCL4,
	M1.WG_NM_LCL5,
	T1.WK_COST_CD, -- 工数管理CD
	T4.OPER_CD, -- 工程CD
	T4.ST_SCHD_TM, -- 着手予定日時[工程着手予定日]
	T4.END_SCHD_TM, -- 終了予定日時[工程終了予定日]
	TO_DATE(TO_CHAR(NVL(T3.ST_TM, T3.AC_DT_MIN), 'YYYY/MM/DD HH24:MI:SS'), 'YYYY/MM/DD HH24:MI:SS') AS ST_TM, -- [工数着手日時] NULLの場合「計上日MIN ＋ 00:00:00」
	TO_DATE(REPLACE(TO_CHAR(GREATEST(NVL(T3.END_TM, T3.AC_DT_MAX), T3.AC_DT_MAX), 'YYYY/MM/DD HH24:MI:SS'), '00:00:00', '23:59:00'), 'YYYY/MM/DD HH24:MI:SS') AS END_TM, -- [工数終了日時] NULLの場合「計上日MAX + 23:59:00」
	NVL(T3.BRK_PD, 0),
	T6.ST_ACT_TM,
    T6.END_ACT_TM
FROM
	MST_WK_SCHD_ALL T1 -- 工数予定
	JOIN (SELECT
			TA1.WK_SCHD_NO,
			TA1.CO_CD,
			TA1.MFG_STS_TYP
		FROM
			MST_WK_ACT_REM_ALL TA1 -- 工数実績残
		WHERE 0=0
		AND TA1.DIV_SEQ = 0
		AND TA1.MFG_STS_TYP IN (MSC_MFG_STS_TYP.ORD, MSC_MFG_STS_TYP.STT, MSC_MFG_STS_TYP.CMPL) --製造状況区分が指図済・着手中・完了と一致(SAV:指図保存、YET:未指図)
		) T2 ON (T1.WK_SCHD_NO = T2.WK_SCHD_NO AND T1.CO_CD = T2.CO_CD)
	LEFT OUTER JOIN (SELECT
						TA2.WK_SCHD_NO,
						TA2.CO_CD,
						SUM(TA2.WK_COST) WK_ACT_COST, -- 工数実績
						MIN(TA2.AC_DT) AC_DT_MIN, -- 最小計上日
						MAX(TA2.AC_DT) AC_DT_MAX, -- 最大計上日
						MIN(TA2.ST_TM) ST_TM, -- 着手時刻
						MAX(TA2.END_TM) END_TM, -- 終了時刻
						SUM(BRK_PD) BRK_PD -- 中断時間
					FROM
						MST_WK_ACT_ALL TA2 -- 工数実績
					GROUP BY
						TA2.WK_SCHD_NO,
						TA2.CO_CD
	) T3 ON (T1.WK_SCHD_NO = T3.WK_SCHD_NO AND T1.CO_CD = T3.CO_CD)
	LEFT OUTER JOIN MST_OPER_INST_ALL T4 ON (T1.OPER_INST_NO = T4.OPER_INST_NO AND T1.CO_CD = T4.CO_CD) -- 工程指図
	LEFT OUTER JOIN MST_ITM_MFG_INST_ALL T5 ON (T1.ITM_MFG_INST_NO = T5.ITM_MFG_INST_NO AND T1.CO_CD = T5.CO_CD) -- 品目製造指図
	LEFT OUTER JOIN MAVM_LOC_IF_ALL M1 ON (T5.MFG_LOC_CD = M1.LOC_CD AND T5.CO_CD = M1.CO_CD)
	LEFT OUTER JOIN MST_MFG_ACT_ALL T6 ON (T1.MFG_INST_NO = T6.MFG_INST_NO AND T1.CO_CD = T6.CO_CD) --製造実績
	JOIN (SELECT
			TA7.MFG_INST_NO,
			TA7.CO_CD,
            TA7.MFG_STS_TYP
		FROM
			MST_MFG_ACT_REM_ALL TA7 -- 製造実績残
		WHERE 0=0
		AND TA7.DIV_SEQ = 0 -- 分割連番
		) T7 ON (T1.MFG_INST_NO = T7.MFG_INST_NO AND T1.CO_CD = T7.CO_CD)
WHERE 0=0
AND T1.CAN_FLG = '0'
/
