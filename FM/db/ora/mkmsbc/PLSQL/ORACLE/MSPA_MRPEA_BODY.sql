	FUNCTION F_GET_USRNM (
		I_WG_CD		IN	VARCHAR2,
		I_PROC_TYP	IN	VARCHAR2,
		I_SIM_MRP_NO	IN	MAPA_META.SIM_MRP_NO%TYPE
	)
	RETURN VARCHAR2
	/*********************************************************
	<SYNOPSIS>

	<REMARKS>

	<ARGUMENTS>

	<RETURNVALUE>

	<HISTORY>
	**********************************************************/
	AS
		V_RTN MAPA_META.FCM_USR_NM%TYPE ;
	BEGIN
		BEGIN
			IF I_PROC_TYP = MSC_MRP_TYP.SIM THEN
				SELECT	t.UPD_USR_NM
				INTO	V_RTN
				FROM	MST_SIM_MRP t
				WHERE	0=0
				AND	t.SIM_MRP_NO = I_SIM_MRP_NO
				;
			ELSE
				SELECT	t.UPD_USR_NM
				INTO	V_RTN
				FROM	MST_MRP_LOCK t
				WHERE	0=0
				AND	t.WG_CD = I_WG_CD
				AND	t.MRP_TYP = I_PROC_TYP
				;
			END IF ;
		EXCEPTION
		WHEN OTHERS THEN
			V_RTN := NULL ;
		END ;
		RETURN V_RTN ;
	END F_GET_USRNM ;

	FUNCTION F_GET_SIM_MRP (
