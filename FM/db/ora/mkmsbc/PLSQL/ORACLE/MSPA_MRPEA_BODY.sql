	PROCEDURE P_VALID_ITM_SUB (
		I_WG_CD		IN VARCHAR2
	)
	/**************************************************************************
	<SYNOPSIS>
			品目絞込み処理
	<REMARKS>

	<ARGUMENTS>

	<ITEM>
		I_WG_CD		: ＷＧＣＤ
	<HISTORY>
	**************************************************************************/
	IS
		L_CNT NUMBER ;
		TYPE ITM_TYPE IS TABLE OF MSW_MRP_ITM_TMP%ROWTYPE ;
		L_LIST ITM_TYPE ;
	BEGIN
		SELECT DISTINCT
			 T.CHD_ITM_CD AS ITM_CD
			,T.CHD_ITM_SUB1 AS ITM_SUB1
			,T.CHD_ITM_SUB2 AS ITM_SUB2
			,T.CHD_ITM_SUB3 AS ITM_SUB3
		BULK COLLECT INTO L_LIST
		FROM MSVM_MRP_BOM T, MSW_MRP_ITM_TMP T1
		WHERE 0=0
		AND T.PAR_ITM_CD = T1.ITM_CD
		AND T.PAR_ITM_SUB1 = T1.ITM_SUB1
		AND T.PAR_ITM_SUB2 = T1.ITM_SUB2
		AND T.PAR_ITM_SUB3 = T1.ITM_SUB3
		AND T.CHD_ITM_CD IS NOT NULL
		AND NOT EXISTS
			(SELECT 'x' FROM MSW_MRP_ITM T2
			WHERE 0=0
			AND T.CHD_ITM_CD = T2.ITM_CD
			AND T.CHD_ITM_SUB1 = T2.ITM_SUB1
			AND T.CHD_ITM_SUB2 = T2.ITM_SUB2
			AND T.CHD_ITM_SUB3 = T2.ITM_SUB3
			)
		;

		IF L_LIST.count() = 0 THEN
			RETURN ;
		END IF ;

		DELETE FROM MSW_MRP_ITM_TMP ;
		FOR I IN L_LIST.FIRST..L_LIST.LAST LOOP
			INSERT INTO MSW_MRP_ITM_TMP VALUES L_LIST(I) ;
			INSERT INTO MSW_MRP_ITM VALUES L_LIST(I) ;
		END LOOP ;

		P_VALID_ITM_SUB(I_WG_CD) ;

	END P_VALID_ITM_SUB ;

	PROCEDURE P_VALID_ITM (
		I_WG_CD		IN VARCHAR2,
		I_PROC_TYP	IN	VARCHAR2,
		I_SIM_MRP	IN	MST_SIM_MRP%ROWTYPE
	/**************************************************************************
	<SYNOPSIS>
			ＭＲＰ前処理
	<REMARKS>

	<ARGUMENTS>

	<ITEM>
		I_WG_CD				: ＷＧＣＤ
		I_PROC_TYP	: ＭＲＰ実行区分
		I_SIM_MRP_TYP		: シミュレーションＭＲＰ区分
	<HISTORY>
	**************************************************************************/
	)
	AS
		L_CNT NUMBER ;
	BEGIN
		DELETE FROM MSW_MRP_ITM_TMP ;
		DELETE FROM MSW_MRP_ITM ;

		IF I_PROC_TYP = MSC_MRP_TYP.MRP THEN
			INSERT INTO MSW_MRP_ITM_TMP
			SELECT DISTINCT
				ITM_CD,
				ITM_SUB1,
				ITM_SUB2,
				ITM_SUB3
			FROM (
				-- 通常ＭＲＰのケース
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3  FROM MSVT_MRP_RQMT WHERE WG_CD = I_WG_CD
				UNION ALL
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_IO_SCHD_GI WHERE WG_CD = I_WG_CD
				UNION ALL
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_ITM_ORDERZ WHERE WG_CD = I_WG_CD
				UNION ALL
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_STK WHERE WG_CD = I_WG_CD
			)
			;
		ELSIF I_PROC_TYP = MSC_MRP_TYP.PRCD THEN
			-- 先行手配のケース
			INSERT INTO MSW_MRP_ITM_TMP
			SELECT DISTINCT
				ITM_CD,
				ITM_SUB1,
				ITM_SUB2,
				ITM_SUB3
			FROM (
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3  FROM MSVT_MRP_PRCD_RQMT WHERE WG_CD = I_WG_CD
				UNION ALL
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_IO_SCHD_GI WHERE WG_CD = I_WG_CD
				UNION ALL
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_ITM_ORDERZ WHERE WG_CD = I_WG_CD
				UNION ALL
				SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_STK WHERE WG_CD = I_WG_CD
			)
			;
		ELSIF I_PROC_TYP = MSC_MRP_TYP.SIM THEN
			-- シミュレーションのケース
			IF I_SIM_MRP.SIM_MRP_TYP = MSC_SIM_MRP_TYP.GP_SIM THEN
				-- 汎用シミュレーション
				INSERT INTO MSW_MRP_ITM_TMP
				SELECT DISTINCT
					ITM_CD,
					ITM_SUB1,
					ITM_SUB2,
					ITM_SUB3
				FROM (
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3  FROM MSVT_MRP_SIM_RQMT_FULL
							WHERE WG_CD = I_WG_CD AND (I_SIM_MRP.DLY_RQMT_FLG = '1' AND SIM_MRP_NO IS NULL OR SIM_MRP_NO = I_SIM_MRP.SIM_MRP_NO )
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_IO_SCHD_GI_NOSHIP WHERE WG_CD = I_WG_CD AND I_SIM_MRP.GI_FLG = '1' --出庫予定（出荷をのぞく）
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_IO_SCHD_GI_SHIP WHERE WG_CD = I_WG_CD AND I_SIM_MRP.SHIP_FLG = '1' --出荷予定
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_ITM_ORDERZ WHERE WG_CD = I_WG_CD AND I_SIM_MRP.GR_FLG = '1' --入庫予定
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_STK WHERE WG_CD = I_WG_CD AND I_SIM_MRP.STK_FLG = '1'
				)
				;
			ELSIF I_SIM_MRP.SIM_MRP_TYP = MSC_SIM_MRP_TYP.MST_CHK THEN
				-- リリース前マスタチェック用
				INSERT INTO MSW_MRP_ITM_TMP
				SELECT DISTINCT
					ITM_CD,
					ITM_SUB1,
					ITM_SUB2,
					ITM_SUB3
				FROM (
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3  FROM MSVT_MRP_SIM_RQMT WHERE WG_CD = I_WG_CD AND SIM_MRP_NO = I_SIM_MRP.SIM_MRP_NO
				)
				;
			ELSIF I_SIM_MRP.SIM_MRP_TYP = MSC_SIM_MRP_TYP.SD_ADJST THEN
				-- 需給調整用
				INSERT INTO MSW_MRP_ITM_TMP
				SELECT DISTINCT
					ITM_CD,
					ITM_SUB1,
					ITM_SUB2,
					ITM_SUB3
				FROM (
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3  FROM MSVT_MRP_SIM_RQMT_SD WHERE WG_CD = I_WG_CD
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_IO_SCHD_GI_SD WHERE WG_CD = I_WG_CD
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_ITM_ORDERZ WHERE WG_CD = I_WG_CD
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_STK WHERE WG_CD = I_WG_CD
				)
				;
			ELSIF I_SIM_MRP.SIM_MRP_TYP = MSC_SIM_MRP_TYP.PRMS THEN
				-- 納期回答用
				INSERT INTO MSW_MRP_ITM_TMP
				SELECT DISTINCT
					ITM_CD,
					ITM_SUB1,
					ITM_SUB2,
					ITM_SUB3
				FROM (
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3  FROM MSVT_MRP_SIM_RQMT_PRMS WHERE WG_CD = I_WG_CD
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_IO_SCHD_GI WHERE WG_CD = I_WG_CD
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_ITM_ORDERZ WHERE WG_CD = I_WG_CD
					UNION ALL
					SELECT DISTINCT ITM_CD,ITM_SUB1,ITM_SUB2,ITM_SUB3 FROM MSVT_MRP_STK WHERE WG_CD = I_WG_CD
				)
				;
			END IF ;
		END IF ;

		SELECT COUNT(ITM_CD) INTO L_CNT FROM MSW_MRP_ITM_TMP ;

		IF L_CNT = 0 THEN
			RETURN ;
		END IF ;

		INSERT INTO MSW_MRP_ITM
		SELECT * FROM MSW_MRP_ITM_TMP
		;

		P_VALID_ITM_SUB(I_WG_CD) ;

	END P_VALID_ITM ;

