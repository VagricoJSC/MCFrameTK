CREATE OR REPLACE VIEW MSVT_LITEMES_INPT_STS(
	CO_CD,
	INPT_SCHD_NO,
	OPER_INST_NO,
	MFG_INST_NO,
	MFG_STS_TYP,
	MFG_STS_TYP_NM,
	MFG_STS_TYP_NM_LCL1,
	MFG_STS_TYP_NM_LCL2,
	MFG_STS_TYP_NM_LCL3,
	MFG_STS_TYP_NM_LCL4,
	MFG_STS_TYP_NM_LCL5,
	INST_MFG_STS_TYP,
	BASE_UNIT_INPT_QTY,
	BASE_UNIT_RQMT_QTY,
	BASE_UNIT_FXD_RQMT_QTY,
	BASE_UNIT_INPT_ACT_QTY,
	BASE_UNIT_LOSS_ACT_QTY,
	BASE_UNIT_FXD_LOSS_QTY,
	OPER_CD,
	MFG_ITM_CD,
	MFG_ITM_SUB1,
	MFG_ITM_SUB2,
	MFG_ITM_SUB3,
	WG_CD,
	WG_NM,
    WG_NM_LCL1,
    WG_NM_LCL2,
    WG_NM_LCL3,
    WG_NM_LCL4,
    WG_NM_LCL5,
    ALT_GRP_CD,
    ALT_GRP_NM,
    INPT_ITM_CD,
	INPT_ITM_SUB1,
	INPT_ITM_SUB2,
	INPT_ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	INPT_LOC_CD,
	INPT_STR_LN_CD,
	SCHD_TM,
	ACT_TM,
	ST_ACT_TM,
	END_ACT_TM
	)
AS
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.OPER_INST_NO, -- 工程指図NO
	T1.MFG_INST_NO, -- 製造指図NO
	T2.MFG_STS_TYP, -- 製造状況区分[投入状況]
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,'ja_JP'),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,'en_US'),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,'zh_CN'),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,''),
	MSC_MFG_STS_TYP.V2NAME(T2.MFG_STS_TYP,''),
	T7.MFG_STS_TYP AS INST_MFG_STS_TYP, -- 製造状況区分[製造指図]
	T1.BASE_UNIT_INPT_QTY, -- 基準単位投入数量[予定投入数量]
	T1.BASE_UNIT_RQMT_QTY,-- 基準単位必要数量
	T1.BASE_UNIT_FXD_RQMT_QTY, -- 基準単位固定必要数量[予定固定ロス数量]
	NVL(T3.BASE_UNIT_INPT_ACT_QTY, 0), -- 基準単位投入数量[投入数量]
	NVL(T3.BASE_UNIT_LOSS_ACT_QTY, 0), -- 基準単位ロス数量[ロス数量]
	NVL(T3.BASE_UNIT_FXD_LOSS_QTY, 0), -- 基準単位固定ロス数量[固定ロス数量]
	T4.OPER_CD, -- 工程CD
	T5.ITM_CD AS MFG_ITM_CD, -- 製造品目CD
	T5.ITM_SUB1 AS MFG_ITM_SUB1,
	T5.ITM_SUB2 AS MFG_ITM_SUB2,
	T5.ITM_SUB3 AS MFG_ITM_SUB3,
	T5.WG_CD,
	M2.WG_NM,
    M2.WG_NM_LCL1,
	M2.WG_NM_LCL2,
	M2.WG_NM_LCL3,
	M2.WG_NM_LCL4,
	M2.WG_NM_LCL5,
	T1.ALT_GRP_CD, -- 代替グループCD
	M1.ALT_GRP_NM,
	T1.ITM_CD AS INPT_ITM_CD, -- 投入品目CD
	T1.ITM_SUB1 AS INPT_ITM_SUB1,
	T1.ITM_SUB2 AS INPT_ITM_SUB2,
	T1.ITM_SUB3 AS INPT_ITM_SUB3,
	T1.LOT_NO,
	T1.SUBLOT_NO,
	T1.INPT_LOC_CD, -- 投入場所
	T1.INPT_STR_LN_CD, -- 投入棚・ライン
	T1.SCHD_TM, -- 投入予定日時
	T3.ACT_TM, -- 投入実績日時
	T6.ST_ACT_TM,
    T6.END_ACT_TM
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
	JOIN (SELECT
			TA1.INPT_SCHD_NO,
			TA1.CO_CD,
			TA1.MFG_STS_TYP
		FROM
			MST_INPT_ACT_REM_ALL TA1 -- 投入実績残
		WHERE 0=0
		AND TA1.DIV_SEQ = 0 -- 分割連番
		AND TA1.MFG_STS_TYP IN (MSC_MFG_STS_TYP.ORD, MSC_MFG_STS_TYP.STT, MSC_MFG_STS_TYP.CMPL) --製造状況区分が指図済・着手中・完了と一致(SAV:指図保存、YET:未指図)
		) T2 ON (T1.INPT_SCHD_NO = T2.INPT_SCHD_NO AND T1.CO_CD = T2.CO_CD) -- 投入実績残
	LEFT OUTER JOIN (SELECT 
						TA2.INPT_SCHD_NO,
						TA2.CO_CD,
						SUM(TA2.BASE_UNIT_INPT_QTY) BASE_UNIT_INPT_ACT_QTY, -- 基準単位投入数量
						SUM(TA2.BASE_UNIT_LOSS_QTY) BASE_UNIT_LOSS_ACT_QTY, -- 基準単位ロス数量
						SUM(TA2.BASE_UNIT_FXD_LOSS_QTY) BASE_UNIT_FXD_LOSS_QTY, -- 基準単位固定ロス数量
						MAX(TA2.ACT_TM) ACT_TM -- 投入実績日時
					FROM
						MST_INPT_ACT_ALL TA2
					GROUP BY
						TA2.INPT_SCHD_NO,
						TA2.CO_CD
	) T3 ON (T1.INPT_SCHD_NO = T3.INPT_SCHD_NO AND T1.CO_CD = T3.CO_CD) -- 投入実績
	LEFT OUTER JOIN MST_OPER_INST_ALL T4 ON (T1.OPER_INST_NO = T4.OPER_INST_NO AND T1.CO_CD = T4.CO_CD) -- 工程指図
	LEFT OUTER JOIN MST_ITM_MFG_INST_ALL T5 ON (T1.ITM_MFG_INST_NO = T5.ITM_MFG_INST_NO AND T1.CO_CD = T5.CO_CD) -- 品目製造指図
	LEFT OUTER JOIN MAM_ALT_GRP_ALL M1 ON (T1.ALT_GRP_CD = M1.ALT_GRP_CD AND T5.WG_CD = M1.WG_CD AND T1.CO_CD = M1.CO_CD) -- 代替グループマスタ
	LEFT OUTER JOIN MAVM_LOC_IF_ALL M2 ON (T5.MFG_LOC_CD = M2.LOC_CD AND T5.CO_CD = M2.CO_CD)
	LEFT OUTER JOIN MST_MFG_ACT_ALL T6 ON (T1.MFG_INST_NO = T6.MFG_INST_NO AND T1.CO_CD = T6.CO_CD) --製造実績
	JOIN (SELECT
			TA7.MFG_INST_NO,
			TA7.CO_CD,
            TA7.MFG_STS_TYP
		FROM
			MST_MFG_ACT_REM_ALL TA7 -- 製造実績残
		WHERE 0=0
        AND TA7.DIV_SEQ = 0 -- 分割連番
		) T7 ON (T1.MFG_INST_NO = T7.MFG_INST_NO AND T1.CO_CD = T7.CO_CD)
WHERE 0=0
AND T1.CAN_FLG = '0'
/
