CREATE OR REPLACE VIEW MST_WK_ACT_REM(
	WK_SCHD_NO,
	DIV_SEQ,
	MFG_STS_TYP,
	MFG_INST_NO,
	ITM_MFG_INST_NO,
	OPER_INST_NO,
	FXD_WK_COST,
	WK_COST,
	REM_WK_COST,
	ABORT_WK_COST,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WK_SCHD_NO,
	ORG.DIV_SEQ,
	ORG.MFG_STS_TYP,
	ORG.MFG_INST_NO,
	ORG.ITM_MFG_INST_NO,
	ORG.OPER_INST_NO,
	ORG.FXD_WK_COST,
	ORG.WK_COST,
	ORG.REM_WK_COST,
	ORG.ABORT_WK_COST,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_WK_ACT_REM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

