CREATE OR REPLACE VIEW MST_OPER_ACT(
	OPER_ACT_NO,
	MFG_ACT_NO,
	ITM_MFG_INST_NO,
	OPER_INST_NO,
	DIV_SEQ,
	ARR_ACT_NO,
	PURC_ACT_IO_NO,
	DISP_SEQ,
	ST_ACT_TM,
	END_ACT_TM,
	BASE_UNIT_QTY,
	BASE_UNIT_CD,
	OPER_UNIT_QTY,
	OPER_UNIT_CD,
	BKF_CTL_FLG,
	WK_COST_CALC_CTL_FLG,
	OPER_YIELD,
	BKF_NOT_REF_FLG,
	DATA_NO,
	MES_ID,
	MES_FLG,
	EXT_SYS_CD,
	EXT_OPER_ACT_NO,
	IF_AUTO_REG_FLG,
	INTR_RMRKS,
	ACT_RPT_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.OPER_ACT_NO,
	ORG.MFG_ACT_NO,
	ORG.ITM_MFG_INST_NO,
	ORG.OPER_INST_NO,
	ORG.DIV_SEQ,
	ORG.ARR_ACT_NO,
	ORG.PURC_ACT_IO_NO,
	ORG.DISP_SEQ,
	ORG.ST_ACT_TM,
	ORG.END_ACT_TM,
	ORG.BASE_UNIT_QTY,
	ORG.BASE_UNIT_CD,
	ORG.OPER_UNIT_QTY,
	ORG.OPER_UNIT_CD,
	ORG.BKF_CTL_FLG,
	ORG.WK_COST_CALC_CTL_FLG,
	ORG.OPER_YIELD,
	ORG.BKF_NOT_REF_FLG,
	ORG.DATA_NO,
	ORG.MES_ID,
	ORG.MES_FLG,
	ORG.EXT_SYS_CD,
	ORG.EXT_OPER_ACT_NO,
	ORG.IF_AUTO_REG_FLG,
	ORG.INTR_RMRKS,
	ORG.ACT_RPT_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_OPER_ACT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

