SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_WK_SCHD_$S(
	WK_SCHD_NO,
	MFG_INST_NO,
	ITM_MFG_INST_NO,
	OPER_INST_NO,
	WK_COST_CD,
	WK_COST_CALC_FLG,
	FXD_WK_COST,
	WK_COST,
	MST_FXD_WK_COST,
	MST_WK_COST,
	DISP_SEQ,
	CAN_FLG,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WK_SCHD_NO,
	ORG.MFG_INST_NO,
	ORG.ITM_MFG_INST_NO,
	ORG.OPER_INST_NO,
	ORG.WK_COST_CD,
	ORG.WK_COST_CALC_FLG,
	ORG.FXD_WK_COST,
	ORG.WK_COST,
	ORG.MST_FXD_WK_COST,
	ORG.MST_WK_COST,
	ORG.DISP_SEQ,
	ORG.CAN_FLG,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_WK_SCHD_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

