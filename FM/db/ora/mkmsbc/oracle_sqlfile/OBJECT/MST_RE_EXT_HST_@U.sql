CREATE OR REPLACE VIEW MST_RE_EXT_HST_$U(
	MFG_INST_NO,
	REF_ORD,
	MFG_INST_REV,
	RE_EXT_TYP,
	CHNG_NO,
	OPER_CHNG_FLG,
	INTR_RMRKS,
	PLM_CNT_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.MFG_INST_NO,
	ORG.REF_ORD,
	ORG.MFG_INST_REV,
	ORG.RE_EXT_TYP,
	ORG.CHNG_NO,
	ORG.OPER_CHNG_FLG,
	ORG.INTR_RMRKS,
	ORG.PLM_CNT_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_RE_EXT_HST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

