CREATE OR REPLACE VIEW MST_BF_BR(
	BATCH_DATA_NO,
	BATCH_LOG_NO,
	LOG_SUB_KEY1,
	LOG_SUB_KEY2,
	EXE_STS_TYP,
	MFG_INST_NO,
	DIV_SEQ,
	MFG_ACT_NO,
	OPER_ACT_NO,
	PAR_ITM_CD,
	PAR_ITM_SUB1,
	PAR_ITM_SUB2,
	PAR_ITM_SUB3,
	MFG_LOC_CD,
	OPER_CD,
	ST_ACT_TM,
	END_ACT_TM,
	BF_TGT_CNT,
	BF_SUCCESS_CNT,
	BF_FAILURE_CNT,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BATCH_DATA_NO,
	ORG.BATCH_LOG_NO,
	ORG.LOG_SUB_KEY1,
	ORG.LOG_SUB_KEY2,
	ORG.EXE_STS_TYP,
	ORG.MFG_INST_NO,
	ORG.DIV_SEQ,
	ORG.MFG_ACT_NO,
	ORG.OPER_ACT_NO,
	ORG.PAR_ITM_CD,
	ORG.PAR_ITM_SUB1,
	ORG.PAR_ITM_SUB2,
	ORG.PAR_ITM_SUB3,
	ORG.MFG_LOC_CD,
	ORG.OPER_CD,
	ORG.ST_ACT_TM,
	ORG.END_ACT_TM,
	ORG.BF_TGT_CNT,
	ORG.BF_SUCCESS_CNT,
	ORG.BF_FAILURE_CNT,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_BF_BR_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

