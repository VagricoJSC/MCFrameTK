CREATE OR REPLACE VIEW MSVT_MRPRQMT_ALLOC_PLN(
	RQMT_NO,
	MRP_RQMT_TYP,
	ITM_ORD_NO,
	OPER_ORD_NO,
	IO_SCHD_TYP,
	IO_SCHD_STS_TYP,
	IO_SCHD_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	VER_NO,
	LOC_CD,
	DUE_DT,
	NET_RQMT_QTY,
	ALT_GRP_CD,
	ALT_GRP_SEQ,
	ALT_ITM_TYP,
	ALT_ITM_RATIO,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	CHD_ITM_CD,
	CHD_ITM_SUB1,
	CHD_ITM_SUB2,
	CHD_ITM_SUB3,
	CHD_VER_NO,
	CHD_LOT_NO,
	CHD_SUBLOT_NO,
	CHD_LOC_CD,
	CHD_IO_SCHD_PR_NO,
	CHD_SCHD_ALLOC_QTY,
	CHD_GI_SCHD_DT,
	CHD_SNO1,
	CHD_SNO2,
	CHD_SNO3,
	CHD_SNO4,
	CHD_ALLOC_AVL_DT,
	CHD_AVL_QTY,
	CHD_LMT_DT,
	WG_CD
)
AS
SELECT
	T1.RQMT_NO RQMT_NO,
	T1.MRP_RQMT_TYP MRP_RQMT_TYP,
	T1.ITM_ORD_NO ITM_ORD_NO,
	T1.OPER_ORD_NO OPER_ORD_NO,
	T1.IO_SCHD_TYP IO_SCHD_TYP,
	T1.IO_SCHD_STS_TYP,
	T1.IO_SCHD_NO IO_SCHD_NO,
	T1.ITM_CD ITM_CD,
	T1.ITM_SUB1 ITM_SUB1,
	T1.ITM_SUB2 ITM_SUB2,
	T1.ITM_SUB3 ITM_SUB3,
	T1.VER_NO VER_NO,
	T1.LOC_CD LOC_CD,
	T1.DUE_DT DUE_DT,
	T1.NET_RQMT_QTY NET_RQMT_QTY,
	T1.ALT_GRP_CD ALT_GRP_CD,
	T1.ALT_GRP_SEQ ALT_GRP_SEQ,
	T1.ALT_ITM_TYP ALT_ITM_TYP,
	T1.ALT_ITM_RATIO ALT_ITM_RATIO,
	T1.OPER_PTN OPER_PTN,
	T1.OPER_CD OPER_CD,
	T1.OPER_SEQ OPER_SEQ,
	T2.ITM_CD CHD_ITM_CD,
	T2.ITM_SUB1 CHD_ITM_SUB1,
	T2.ITM_SUB2 CHD_ITM_SUB2,
	T2.ITM_SUB3 CHD_ITM_SUB3,
	T2.VER_NO CHD_VER_NO,
	T2.LOT_NO CHD_LOT_NO,
	T2.SUBLOT_NO CHD_SUBLOT_NO,
	T2.LOC_CD CHD_LOC_CD,
	T2.IO_SCHD_PR_NO CHD_IO_SCHD_PR_NO,
	T2.SCHD_ALLOC_QTY CHD_SCHD_ALLOC_QTY,
	T2.GI_SCHD_DT CHD_GI_SCHD_DT,
	T2.SNO1 CHD_SNO1,
	T2.SNO2 CHD_SNO2,
	T2.SNO3 CHD_SNO3,
	T2.SNO4 CHD_SNO4,
	T2.ALLOC_AVL_DT CHD_ALLOC_AVL_DT,
	T2.AVL_QTY CHD_AVL_QTY,
	T2.LMT_DT CHD_LMT_DT,
	T2.WG_CD
FROM
	MST_MRPRQMT T1,
	MST_ALLOC_PLN T2
WHERE 0=0
AND T1.RQMT_NO = T2.RQMT_NO
;

