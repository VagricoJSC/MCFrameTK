CREATE OR REPLACE VIEW MSVT_LITEMES_INPT_PRO(
	CO_CD,
	INPT_SCHD_NO,
	MFG_INST_NO,
	SA,
	SA_LCL,
	QTY_TYP,
	QTY_TYP_LCL,
	QTY
	)
AS
-- 予定の投入
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.MFG_INST_NO, -- 製造指図NO
	'予定' AS SA,
	'SCHD' AS SA_LCL,
	'投入' AS QTY_TYP,
	'INPT' AS QTY_TYP_LCL,
	T1.BASE_UNIT_INPT_QTY AS QTY -- 基準単位投入数量[予定投入数量]
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
WHERE 0=0
AND T1.CAN_FLG = '0'
-- 予定のロス
UNION ALL
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.MFG_INST_NO, -- 製造指図NO
	'予定' AS SA,
	'SCHD' AS SA_LCL,
	'ロス' AS QTY_TYP,
	'LOSS' AS QTY_TYP_LCL,
	T1.BASE_UNIT_RQMT_QTY - T1.BASE_UNIT_INPT_QTY AS QTY -- 基準単位必要数量 - 基準単位投入数量[予定ロス数量]
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
WHERE 0=0
AND T1.CAN_FLG = '0'
-- 予定の固定ロス
UNION ALL
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.MFG_INST_NO, -- 製造指図NO
	'予定' AS SA,
	'SCHD' AS SA_LCL,
	'固定ロス' AS QTY_TYP,
	'FXD_LOSS' AS QTY_TYP_LCL,
	T1.BASE_UNIT_FXD_RQMT_QTY AS QTY -- 基準単位固定必要数量[予定固定ロス数量]
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
WHERE 0=0
AND T1.CAN_FLG = '0'
-- 実績の投入
UNION ALL
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.MFG_INST_NO, -- 製造指図NO
	'実績' AS SA,
	'ACT' AS SA_LCL,
	'投入' AS QTY_TYP,
	'INPT' AS QTY_TYP_LCL,
	NVL(T3.BASE_UNIT_INPT_ACT_QTY, 0) AS QTY -- 基準単位投入数量[投入数量]
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
	LEFT OUTER JOIN (SELECT 
						TA2.INPT_SCHD_NO,
						TA2.CO_CD,
						SUM(TA2.BASE_UNIT_INPT_QTY) BASE_UNIT_INPT_ACT_QTY -- 基準単位投入数量
					FROM
						MST_INPT_ACT_ALL TA2
					GROUP BY
						TA2.INPT_SCHD_NO,
						TA2.CO_CD
	) T3 ON (T1.INPT_SCHD_NO = T3.INPT_SCHD_NO AND T1.CO_CD = T3.CO_CD) -- 投入実績
WHERE 0=0
AND T1.CAN_FLG = '0'
-- 実績のロス
UNION ALL
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.MFG_INST_NO, -- 製造指図NO
	'実績' AS SA,
	'ACT' AS SA_LCL,
	'ロス' AS QTY_TYP,
	'LOSS' AS QTY_TYP_LCL,
	NVL(T3.BASE_UNIT_LOSS_ACT_QTY, 0) AS QTY -- 基準単位ロス数量[ロス数量]
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
	LEFT OUTER JOIN (SELECT 
						TA2.INPT_SCHD_NO,
						TA2.CO_CD,
						SUM(TA2.BASE_UNIT_LOSS_QTY) BASE_UNIT_LOSS_ACT_QTY -- 基準単位ロス数量
					FROM
						MST_INPT_ACT_ALL TA2
					GROUP BY
						TA2.INPT_SCHD_NO,
						TA2.CO_CD
	) T3 ON (T1.INPT_SCHD_NO = T3.INPT_SCHD_NO AND T1.CO_CD = T3.CO_CD) -- 投入実績
WHERE 0=0
AND T1.CAN_FLG = '0'
-- 実績の固定ロス
UNION ALL
SELECT
	T1.CO_CD,
	T1.INPT_SCHD_NO, -- 投入予定NO
	T1.MFG_INST_NO, -- 製造指図NO
	'実績' AS SA,
	'ACT' AS SA_LCL,
	'固定ロス' AS QTY_TYP,
	'FXD_LOSS' AS QTY_TYP_LCL,
	NVL(T3.BASE_UNIT_FXD_LOSS_QTY, 0) AS QTY -- 基準単位固定ロス数量[固定ロス数量]
FROM
	MST_INPT_SCHD_ALL T1 -- 投入予定
	LEFT OUTER JOIN (SELECT 
						TA2.INPT_SCHD_NO,
						TA2.CO_CD,
						SUM(TA2.BASE_UNIT_FXD_LOSS_QTY) BASE_UNIT_FXD_LOSS_QTY -- 基準単位固定ロス数量
					FROM
						MST_INPT_ACT_ALL TA2
					GROUP BY
						TA2.INPT_SCHD_NO,
						TA2.CO_CD
	) T3 ON (T1.INPT_SCHD_NO = T3.INPT_SCHD_NO AND T1.CO_CD = T3.CO_CD) -- 投入実績
WHERE 0=0
AND T1.CAN_FLG = '0'

/
show errors;


