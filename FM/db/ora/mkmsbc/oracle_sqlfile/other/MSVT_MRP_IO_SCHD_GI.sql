CREATE OR REPLACE VIEW MSVT_MRP_IO_SCHD_GI(
	IO_SCHD_NO,
	IO_SCHD_TYP,
	IO_SCHD_STS_TYP,
	ITM_ORD_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	VER_NO,
	LOC_CD,
	BASE_UNIT_QTY,
	SCHD_DT,
	ALT_GRP_CD,
	ALT_GRP_SEQ,
	OPER_INST_NO,
	OPER_ORD_NO,
	ALT_ITM_TYP,
	ALT_ITM_RATIO,
	ALT_ALLOC_PRIO,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO_TYP1,
	SNO2,
	SNO_TYP2,
	SNO3,
	SNO_TYP3,
	SNO4,
	SNO_TYP4,
	EX_SNO1,
	EX_SNO2,
	EX_SNO3,
	EX_SNO4,
	GD_CD,
	INPT_CTL_TYP,
	ALLOC_FLG,
	WG_CD
)
AS
SELECT
	 T1.IO_SCHD_NO
	,T1.IO_SCHD_TYP
	,T1.IO_SCHD_STS_TYP
	,T1.IO_SCHD_PR_NO AS ITM_ORD_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOC_CD
	,DECODE(T1.ALT_GRP_CD,NULL,T1.BASE_UNIT_QTY,
		DECODE(T6.INST_BASE_UNIT_QTY,NULL,T4.ORD_BASE_UNIT_QTY,T6.INST_BASE_UNIT_QTY)) AS BASE_UNIT_QTY
	,T1.SCHD_DT
	,T1.ALT_GRP_CD
	,T1.ALT_GRP_SEQ
	,T1.OPER_INST_NO
	,T1.OPER_ORD_NO
	,T1.ALT_ITM_TYP
	,T1.ALT_ITM_RATIO
	,T1.ALT_ALLOC_PRIO
	,T2.OPER_PTN
	,T2.OPER_CD
	,T2.OPER_SEQ
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.SNO1
	,CAST(DECODE(T1.SNO1_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP1
	,T1.SNO2
	,CAST(DECODE(T1.SNO2_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP2
	,T1.SNO3
	,CAST(DECODE(T1.SNO3_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP3
	,T1.SNO4
	,CAST(DECODE(T1.SNO4_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP4
	,T1.EX_SNO1
	,T1.EX_SNO2
	,T1.EX_SNO3
	,T1.EX_SNO4
	,T1.GD_CD
	,T1.INPT_CTL_TYP
	,T1.ALLOC_FLG
	,T1.WG_CD
FROM
	MSVT_AVL_IO_SCHD T1
	,MST_OPER_ORDER T2
	,(SELECT
		 T3.ALT_GRP_CD
		,T3.ALT_GRP_SEQ
		,T3.OPER_ORD_NO
		,SUM(T3.BASE_UNIT_QTY) AS ORD_BASE_UNIT_QTY
	FROM
		MSVT_AVL_IO_SCHD T3
	WHERE 0 = 0
	AND T3.ALT_GRP_CD IS NOT NULL
	AND T3.OPER_ORD_NO IS NOT NULL
	GROUP BY
		 T3.ALT_GRP_CD
		,T3.ALT_GRP_SEQ
		,T3.OPER_ORD_NO
	) T4
	,(SELECT
		 T5.ALT_GRP_CD
		,T5.ALT_GRP_SEQ
		,T5.OPER_INST_NO
		,SUM(T5.BASE_UNIT_QTY) AS INST_BASE_UNIT_QTY
	FROM
		MSVT_AVL_IO_SCHD T5
	WHERE 0 = 0
	AND T5.ALT_GRP_CD IS NOT NULL
	AND T5.OPER_INST_NO IS NOT NULL
	GROUP BY
		 T5.ALT_GRP_CD
		,T5.ALT_GRP_SEQ
		,T5.OPER_INST_NO
	) T6
WHERE 0=0
AND T1.QUALITY_TYP = MAC_QUALITY_TYP.GOOD
AND T1.IO_TYP = MSC_IO_TYP.GI
-- 以下の受払予定からオーダ生成されないようにマイナス在庫としてIFするため、対象外
AND	T1.IO_SCHD_TYP NOT IN
	(
	MSC_IO_SCHD_TYP.ARR_RTN, --入荷返品
	MSC_IO_SCHD_TYP.ARR_RTN_PROV, --入荷返品（支給）
	MSC_IO_SCHD_TYP.SCRP -- 廃棄
	)
-- 仕入直送の受払予定は出庫、入庫とも対象外とする
AND	T1.IO_SCHD_STS_TYP NOT IN
	(
	MSC_IO_SCHD_STS_TYP.DDLV_SLO -- 直送受注
	)
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
AND T1.OPER_ORD_NO = T2.OPER_ORD_NO(+)
-- システムパラメータの値が'0'なら、依頼のデータを除外する
AND T1.IO_SCHD_STS_TYP <> NVL(
	(CASE (SELECT PARM_VAL AS SYS_PARM FROM MAM_SYS_PARM WHERE PARM_KEY = 'INCLD_SCHD_STS_FIX_FLG')
		WHEN '0' THEN
			MSC_IO_SCHD_STS_TYP.FIX -- 依頼
	END),'*')
AND T1.ALT_GRP_CD = T4.ALT_GRP_CD(+)
AND T1.ALT_GRP_SEQ = T4.ALT_GRP_SEQ(+)
AND T1.OPER_ORD_NO = T4.OPER_ORD_NO(+)
AND T1.ALT_GRP_CD = T6.ALT_GRP_CD(+)
AND T1.ALT_GRP_SEQ = T6.ALT_GRP_SEQ(+)
AND T1.OPER_INST_NO = T6.OPER_INST_NO(+)
UNION ALL
SELECT
	 T1.IO_SCHD_NO
	,T1.IO_SCHD_TYP
	,T1.IO_SCHD_STS_TYP
	,T1.IO_SCHD_PR_NO AS ITM_ORD_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOC_CD
	,DECODE(T1.ALT_GRP_CD,NULL,T1.BASE_UNIT_QTY,
		DECODE(T7.INST_BASE_UNIT_QTY,NULL,T5.ORD_BASE_UNIT_QTY,T7.INST_BASE_UNIT_QTY)) AS BASE_UNIT_QTY
	,T1.SCHD_DT
	,T1.ALT_GRP_CD
	,T1.ALT_GRP_SEQ
	,T1.OPER_INST_NO
	,T1.OPER_ORD_NO
	,T1.ALT_ITM_TYP
	,T1.ALT_ITM_RATIO
	,T1.ALT_ALLOC_PRIO
	,NULL AS OPER_PTN
	,NULL AS OPER_CD
	,NULL AS OPER_SEQ
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.SNO1
	,CAST(DECODE(T1.SNO1_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP1
	,T1.SNO2
	,CAST(DECODE(T1.SNO2_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP2
	,T1.SNO3
	,CAST(DECODE(T1.SNO3_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP3
	,T1.SNO4
	,CAST(DECODE(T1.SNO4_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP4
	,T1.EX_SNO1
	,T1.EX_SNO2
	,T1.EX_SNO3
	,T1.EX_SNO4
	,T1.GD_CD
	,T1.INPT_CTL_TYP
	,T1.ALLOC_FLG
	,T1.WG_CD
FROM
	MST_ORD_IO_SCHD T1
	,MAVM_ITM_WG T2
	,(SELECT FCPA_DATE_UTIL.F_GET_TODAY AS CO_TODAY FROM DUAL) T3
	,(SELECT
		 T4.ALT_GRP_CD
		,T4.ALT_GRP_SEQ
		,T4.OPER_ORD_NO
		,SUM(T4.BASE_UNIT_QTY) AS ORD_BASE_UNIT_QTY
	FROM
		MST_ORD_IO_SCHD T4
	WHERE 0 = 0
	AND T4.ALT_GRP_CD IS NOT NULL
	AND T4.OPER_ORD_NO IS NOT NULL
	GROUP BY
		 T4.ALT_GRP_CD
		,T4.ALT_GRP_SEQ
		,T4.OPER_ORD_NO
	) T5
	,(SELECT
		 T6.ALT_GRP_CD
		,T6.ALT_GRP_SEQ
		,T6.OPER_INST_NO
		,SUM(T6.BASE_UNIT_QTY) AS INST_BASE_UNIT_QTY
	FROM
		MST_ORD_IO_SCHD T6
	WHERE 0 = 0
	AND T6.ALT_GRP_CD IS NOT NULL
	AND T6.OPER_INST_NO IS NOT NULL
	GROUP BY
		 T6.ALT_GRP_CD
		,T6.ALT_GRP_SEQ
		,T6.OPER_INST_NO
	) T7
WHERE 0=0
AND T1.IO_TYP = MSC_IO_TYP.GI
AND T1.IO_SCHD_TYP = MSC_IO_SCHD_TYP.XFR_GI_PLN
AND T1.IN_XFR_TYP = MSC_IN_XFR_TYP.IN_LOC
AND T1.STK_INSP_TYP = MSC_STK_INSP_TYP.FIN
AND	T1.ITM_CD = T2.ITM_CD(+)
AND	T1.ITM_SUB1 = T2.ITM_SUB1(+)
AND	T1.ITM_SUB2 = T2.ITM_SUB2(+)
AND	T1.ITM_SUB3 = T2.ITM_SUB3(+)
AND	T1.WG_CD = T2.WG_CD(+)
AND T1.SCHD_DT <= TO_DATE(T3.CO_TODAY) + T2.MRP_OPN_XFR_DAYS -- T2.MRP_OPN_XFR_DAYSがnullの場合はfalseとなり抽出されない
AND T1.ALT_GRP_CD = T5.ALT_GRP_CD(+)
AND T1.ALT_GRP_SEQ = T5.ALT_GRP_SEQ(+)
AND T1.OPER_ORD_NO = T5.OPER_ORD_NO(+)
AND T1.ALT_GRP_CD = T7.ALT_GRP_CD(+)
AND T1.ALT_GRP_SEQ = T7.ALT_GRP_SEQ(+)
AND T1.OPER_INST_NO = T7.OPER_INST_NO(+)
AND T1.WG_CD <> T1.ORG_WG_CD
UNION ALL
SELECT
	 T1.RQMT_NO AS IO_SCHD_NO
	,CAST(MSC_IO_SCHD_TYP.SHIP_OUT AS VARCHAR2(5 CHAR)) AS IO_SCHD_TYP
	,CAST(MSC_IO_SCHD_STS_TYP.SCHD AS VARCHAR2(2 CHAR)) AS IO_SCHD_STS_TYP
	,NULL AS ITM_ORD_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,NULL AS VER_NO
	,T1.STRG_LOC_CD AS LOC_CD
	,T1.RQMT_QTY AS BASE_UNIT_QTY
	,T1.DUE_DT AS SCHD_DT
	,NULL AS ALT_GRP_CD
	,NULL AS ALT_GRP_SEQ
	,NULL AS OPER_INST_NO
	,NULL AS OPER_ORD_NO
	,NULL AS ALT_ITM_TYP
	,0 AS ALT_ITM_RATIO
	,0 AS ALT_ALLOC_PRIO
	,NULL AS OPER_PTN
	,NULL AS OPER_CD
	,NULL AS OPER_SEQ
	,NULL AS LOT_NO
	,NULL AS SUBLOT_NO
	,DECODE(T2.SNO1_MNG_TYP, MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_STR.NULL_VAL, T1.SNO1) AS SNO1
	,CAST(MAC_SNO_TYP.EXTND AS VARCHAR2(1 CHAR)) AS SNO_TYP1
	,DECODE(T2.SNO2_MNG_TYP, MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_STR.NULL_VAL, T1.SNO2) AS SNO2
	,CAST(MAC_SNO_TYP.EXTND AS VARCHAR2(1 CHAR)) AS SNO_TYP2
	,DECODE(T2.SNO3_MNG_TYP, MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_STR.NULL_VAL, T1.SNO3) AS SNO3
	,CAST(MAC_SNO_TYP.EXTND AS VARCHAR2(1 CHAR)) AS SNO_TYP3
	,DECODE(T2.SNO4_MNG_TYP, MAC_SNO_MNG_TYP.MNG_NOT_STK, MAC_STR.NULL_VAL, T1.SNO4) AS SNO4
	,CAST(MAC_SNO_TYP.EXTND AS VARCHAR2(1 CHAR)) AS SNO_TYP4
	,T1.SNO1 AS EX_SNO1
	,T1.SNO2 AS EX_SNO2
	,T1.SNO3 AS EX_SNO3
	,T1.SNO4 AS EX_SNO4
	,T3.GD_CD
	,CAST(MAC_INPT_CTL_TYP.MRP_INPT AS VARCHAR2(1 CHAR)) AS INPT_CTL_TYP
	,'0' AS ALLOC_FLG
	,T1.WG_CD
FROM
	MSVT_MRP_DLY_DMND T1
	,MAVM_ITM_WG T2
	,(SELECT MAPA_UTIL.F_GET_DEF_GD_CD AS GD_CD FROM DUAL) T3
WHERE 0=0
	AND T1.ITM_CD = T2.ITM_CD(+)
	AND T1.ITM_SUB1 = T2.ITM_SUB1(+)
	AND T1.ITM_SUB2 = T2.ITM_SUB2(+)
	AND T1.ITM_SUB3 = T2.ITM_SUB3(+)
	AND T1.WG_CD = T2.WG_CD(+)
	AND T2.PROD_PLN_TYP = MAC_PROD_PLN_TYP.DMND_USE
	AND T2.RQMT_TYP = MAC_RQMT_TYP.ALLOC
	AND T1.DMND_TYP IN (MSC_DMND_TYP.CST_FRCST, MSC_DMND_TYP.PLN_SLS)
UNION ALL
-- システムパラメータの値が'0'の時のみ、「MRP未確定移送依頼考慮日数」を考慮して、受払い状況区分が「依頼」のデータを追加する
SELECT
	 T1.IO_SCHD_NO
	,T1.IO_SCHD_TYP
	,T1.IO_SCHD_STS_TYP
	,T1.IO_SCHD_PR_NO AS ITM_ORD_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.VER_NO
	,T1.LOC_CD
	,DECODE(T1.ALT_GRP_CD,NULL,T1.BASE_UNIT_QTY,
		DECODE(T8.INST_BASE_UNIT_QTY,NULL,T6.ORD_BASE_UNIT_QTY,T8.INST_BASE_UNIT_QTY)) AS BASE_UNIT_QTY
	,T1.SCHD_DT
	,T1.ALT_GRP_CD
	,T1.ALT_GRP_SEQ
	,T1.OPER_INST_NO
	,T1.OPER_ORD_NO
	,T1.ALT_ITM_TYP
	,T1.ALT_ITM_RATIO
	,T1.ALT_ALLOC_PRIO
	,T2.OPER_PTN
	,T2.OPER_CD
	,T2.OPER_SEQ
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.SNO1
	,CAST(DECODE(T1.SNO1_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP1
	,T1.SNO2
	,CAST(DECODE(T1.SNO2_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP2
	,T1.SNO3
	,CAST(DECODE(T1.SNO3_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP3
	,T1.SNO4
	,CAST(DECODE(T1.SNO4_NULL_FLG, '1', MAC_SNO_TYP.EXTND_NULL, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) AS SNO_TYP4
	,T1.EX_SNO1
	,T1.EX_SNO2
	,T1.EX_SNO3
	,T1.EX_SNO4
	,T1.GD_CD
	,T1.INPT_CTL_TYP
	,T1.ALLOC_FLG
	,T1.WG_CD
FROM
	MSVT_AVL_IO_SCHD T1
	,MST_OPER_ORDER T2
	,MAVM_ITM_WG T3
	,(SELECT FCPA_DATE_UTIL.F_GET_TODAY AS CO_TODAY FROM DUAL) T4
	,(SELECT
		 T5.ALT_GRP_CD
		,T5.ALT_GRP_SEQ
		,T5.OPER_ORD_NO
		,SUM(T5.BASE_UNIT_QTY) AS ORD_BASE_UNIT_QTY
	FROM
		MSVT_AVL_IO_SCHD T5
	WHERE 0 = 0
	AND T5.ALT_GRP_CD IS NOT NULL
	AND T5.OPER_ORD_NO IS NOT NULL
	GROUP BY
		 T5.ALT_GRP_CD
		,T5.ALT_GRP_SEQ
		,T5.OPER_ORD_NO
	) T6
	,(SELECT
		 T7.ALT_GRP_CD
		,T7.ALT_GRP_SEQ
		,T7.OPER_INST_NO
		,SUM(T7.BASE_UNIT_QTY) AS INST_BASE_UNIT_QTY
	FROM
		MSVT_AVL_IO_SCHD T7
	WHERE 0 = 0
	AND T7.ALT_GRP_CD IS NOT NULL
	AND T7.OPER_INST_NO IS NOT NULL
	GROUP BY
		 T7.ALT_GRP_CD
		,T7.ALT_GRP_SEQ
		,T7.OPER_INST_NO
	) T8
WHERE 0=0
AND T1.QUALITY_TYP = MAC_QUALITY_TYP.GOOD
AND T1.IO_SCHD_STS_TYP = NVL(
	(CASE (SELECT PARM_VAL AS SYS_PARM FROM MAM_SYS_PARM WHERE PARM_KEY = 'INCLD_SCHD_STS_FIX_FLG')
		WHEN '0' THEN
			MSC_IO_SCHD_STS_TYP.FIX -- 依頼
	END),'*')
AND T1.IO_TYP = MSC_IO_TYP.GI
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
AND T1.OPER_ORD_NO = T2.OPER_ORD_NO(+)
AND	T1.ITM_CD = T3.ITM_CD(+)
AND	T1.ITM_SUB1 = T3.ITM_SUB1(+)
AND	T1.ITM_SUB2 = T3.ITM_SUB2(+)
AND	T1.ITM_SUB3 = T3.ITM_SUB3(+)
AND	T1.WG_CD = T3.WG_CD(+)
AND	T1.SCHD_DT <= TO_DATE(T4.CO_TODAY) + T3.MRP_OPN_XFR_DAYS -- T2.MRP_OPN_XFR_DAYSがnullの場合はfalseとなり抽出されない
AND T1.ALT_GRP_CD = T6.ALT_GRP_CD(+)
AND T1.ALT_GRP_SEQ = T6.ALT_GRP_SEQ(+)
AND T1.OPER_ORD_NO = T6.OPER_ORD_NO(+)
AND T1.ALT_GRP_CD = T8.ALT_GRP_CD(+)
AND T1.ALT_GRP_SEQ = T8.ALT_GRP_SEQ(+)
AND T1.OPER_INST_NO = T8.OPER_INST_NO(+)

;

