CREATE OR REPLACE VIEW MSVT_MRP_SIM_RQMT_FULL(
	RQMT_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STRG_LOC_CD,
	MFG_LOC_CD,
	SPPL_CD,
	RQST_LOC_CD,
	DUE_DT,
	RQMT_QTY,
	SNO1,
	SNO1_TYP,
	SNO2,
	SNO2_TYP,
	SNO3,
	SNO3_TYP,
	SNO4,
	SNO4_TYP,
	WG_CD,
	RQMT_TYP,
	SIM_MRP_NO
)
AS
SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY
	,T1.SNO1
	,T1.SNO1_TYP
	,T1.SNO2
	,T1.SNO2_TYP
	,T1.SNO3
	,T1.SNO3_TYP
	,T1.SNO4
	,T1.SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
	,T1.SIM_MRP_NO
FROM
	MSVT_MRP_SIM_RQMT T1
UNION ALL
SELECT
	 T1.RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.STRG_LOC_CD
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.RQST_LOC_CD
	,T1.DUE_DT
	,T1.RQMT_QTY
	,T1.SNO1
	,T1.SNO1_TYP
	,T1.SNO2
	,T1.SNO2_TYP
	,T1.SNO3
	,T1.SNO3_TYP
	,T1.SNO4
	,T1.SNO4_TYP
	,T1.WG_CD
	,T1.RQMT_TYP
	,NULL AS SIM_MRP_NO
FROM
	MSVT_MRP_RQMT T1
;

