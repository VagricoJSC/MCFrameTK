SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MRP_VALID_STK(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	LOC_CD,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	GD_CD,
	BASE_UNIT_QTY,
	VER_NO,
	FIRST_GR_DT,
	LOT_SEQ,
	AVL_SCHD_DT,
	LMT_DT,
	WG_CD
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.LOC_CD
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,SUM(T1.BASE_UNIT_QTY) AS BASE_UNIT_QTY
	,T2.VER_NO
	,T2.FIRST_GR_DT
	,T2.LOT_SEQ
	,TO_DATE(NULL) AS AVL_SCHD_DT
	,T2.LMT_DT
	,T3.WG_CD
FROM
	MSVT_AVL_STK T1
	,MSVT_LOT_LIST T2
	,MAM_LOC T3
WHERE 0=0
AND NVL(T2.QUALITY_TYP, T1.QUALITY_TYP) = MAC_QUALITY_TYP.GOOD
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
AND T1.ITM_CD = T2.ITM_CD(+)
AND T1.ITM_SUB1 = T2.ITM_SUB1(+)
AND T1.ITM_SUB2 = T2.ITM_SUB2(+)
AND T1.ITM_SUB3 = T2.ITM_SUB3(+)
AND T1.LOT_NO = T2.LOT_NO(+)
AND T1.SUBLOT_NO = T2.SUBLOT_NO(+)
AND T1.LOC_CD = T3.LOC_CD(+)
GROUP BY
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.LOC_CD
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,T2.VER_NO
	,T2.FIRST_GR_DT
	,T2.LOT_SEQ
	,T2.LMT_DT
	,T3.WG_CD
;

