SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVM_MRP_ALLOC_CTL(
	TO_LOC_CD,
	FR_LOC_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	PRIO,
	XFR_LOT_UNIT_QTY,
	IN_LOC_FLG,
	WG_CD
)
AS
SELECT
	 T1.TO_LOC_CD
	,T1.FR_LOC_CD
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.PRIO
	,T1.XFR_LOT_UNIT_QTY
	,T1.IN_LOC_FLG
	,T2.WG_CD
FROM
	 MAM_ALLOC_CTL T1
	,MAM_LOC T2
	,MAM_LOC T3
WHERE 0=0
AND T1.TO_LOC_CD = T2.LOC_CD
AND T1.FR_LOC_CD = T3.LOC_CD
AND T2.WG_CD = T3.WG_CD
AND T1.DEL_FLG = '0'
;

