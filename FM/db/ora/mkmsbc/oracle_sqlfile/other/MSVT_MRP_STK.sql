SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MRP_STK(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	LOC_CD,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	GD_CD,
	BASE_UNIT_QTY,
	VER_NO,
	FIRST_GR_DT,
	LOT_SEQ,
	AVL_SCHD_DT,
	LMT_DT,
	WG_CD
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.LOT_NO
	,T1.SUBLOT_NO
	,T1.LOC_CD
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.GD_CD
	,T1.BASE_UNIT_QTY
	,T1.VER_NO
	,T1.FIRST_GR_DT
	,T1.LOT_SEQ
	,T1.AVL_SCHD_DT
	,T1.LMT_DT
	,T1.WG_CD
FROM
	MSVT_MRP_VALID_STK T1
UNION ALL
SELECT
	 T2.ITM_CD
	,T2.ITM_SUB1
	,T2.ITM_SUB2
	,T2.ITM_SUB3
	,T2.LOT_NO
	,T2.SUBLOT_NO
	,T2.LOC_CD
	,T2.SNO1
	,T2.SNO2
	,T2.SNO3
	,T2.SNO4
	,T2.GD_CD
	,T2.BASE_UNIT_QTY
	,T2.VER_NO
	,T2.FIRST_GR_DT
	,T2.LOT_SEQ
	,T2.AVL_SCHD_DT
	,T2.LMT_DT
	,T2.WG_CD
FROM
	MSVT_MRP_MINUS_STK_GI T2
;

