SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MRP_DLY_DMND(
	RQMT_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STRG_LOC_CD,
	MFG_LOC_CD,
	SPPL_CD,
	RQST_LOC_CD,
	DUE_DT,
	RQMT_QTY,
	SNO1,
	SNO1_TYP,
	SNO2,
	SNO2_TYP,
	SNO3,
	SNO3_TYP,
	SNO4,
	SNO4_TYP,
	WG_CD,
	RQMT_TYP,
	DMND_TYP
)
AS
SELECT
	 T1.DLY_DMND_NO AS RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.DMND_LOC_CD AS STRG_LOC_CD
	,CAST(MAC_STR.NULL_VAL AS VARCHAR2(1 CHAR)) AS MFG_LOC_CD
	,CAST(MAC_STR.NULL_VAL AS VARCHAR2(1 CHAR)) AS SPPL_CD
	,CAST(MAC_STR.NULL_VAL AS VARCHAR2(1 CHAR)) AS RQST_LOC_CD
	,T1.DMND_DT AS DUE_DT
	,T1.DMND_QTY AS RQMT_QTY
	,T1.SNO1
	,CAST(DECODE(T1.SNO1, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO1_TYP
	,T1.SNO2
	,CAST(DECODE(T1.SNO2, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO2_TYP
	,T1.SNO3
	,CAST(DECODE(T1.SNO3, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO3_TYP
	,T1.SNO4
	,CAST(DECODE(T1.SNO4, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO4_TYP
	,T1.WG_CD
	,CAST(MAC_RQMT_TYP.ALLOC AS VARCHAR2(1 CHAR)) AS RQMT_TYP
	,T1.DMND_TYP
FROM
	MST_DLY_DMND T1
WHERE 0=0
AND T1.DMND_DT >= FCPA_DATE_UTIL.F_GET_TODAY
AND T1.DMND_TYP IN (
	MSC_DMND_TYP.CST_FRCST
	, MSC_DMND_TYP.PLN_SLS
	, MSC_DMND_TYP.MISC
)
;

