CREATE OR REPLACE VIEW MSVM_MRP_ITM_OPER(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	ST_DT,
	END_DT,
	DISP_SEQ,
	OPER_LT,
	OPER_LT_ADD_QTY,
	OPER_OFFST_TYP,
	OPER_OFFST,
	OPER_OFFST_ADD_QTY,
	YIELD_OPER_FLG,
	OPER_LOC_CD,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	WG_CD
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.LOC_CD
	,T1.OPER_PTN
	,T1.OPER_CD
	,T1.OPER_SEQ
	,T1.ST_DT
	,T1.END_DT
	,T1.DISP_SEQ
	,T1.OPER_LT
	,T1.OPER_LT_ADD_QTY
	,T1.OPER_OFFST_TYP
	,T1.OPER_OFFST
	,T1.OPER_OFFST_ADD_QTY
	,T1.YIELD_OPER_FLG
	,T1.OPER_LOC_CD
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T2.WG_CD
FROM MAM_ITM_OPER T1, MAM_LOC T2
WHERE 0=0
AND T1.LOC_CD = T2.LOC_CD(+)
AND T1.DEL_FLG = '0'
;

