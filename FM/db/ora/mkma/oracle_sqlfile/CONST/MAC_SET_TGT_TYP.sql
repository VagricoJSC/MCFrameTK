CREATE OR REPLACE PACKAGE BODY MAC_SET_TGT_TYP
/*****************************
設定対象区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION INPT RETURN VARCHAR2 DETERMINISTIC IS -- 投入
	BEGIN RETURN '1'; END INPT;
	FUNCTION IO RETURN VARCHAR2 DETERMINISTIC IS -- 入出庫
	BEGIN RETURN '2'; END IO;
	FUNCTION SLS RETURN VARCHAR2 DETERMINISTIC IS -- 売上
	BEGIN RETURN '3'; END SLS;
	FUNCTION IO_IN RETURN VARCHAR2 DETERMINISTIC IS -- 入出庫（入庫）
	BEGIN RETURN '4'; END IO_IN;
	FUNCTION IO_OUT RETURN VARCHAR2 DETERMINISTIC IS -- 入出庫（出庫）
	BEGIN RETURN '5'; END IO_OUT;

	FUNCTION IS_INPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 投入かどうか
	BEGIN
		IF I_VALUE = INPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INPT;

	FUNCTION IS_IO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入出庫かどうか
	BEGIN
		IF I_VALUE = IO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IO;

	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上かどうか
	BEGIN
		IF I_VALUE = SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS;

	FUNCTION IS_IO_IN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入出庫（入庫）かどうか
	BEGIN
		IF I_VALUE = IO_IN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IO_IN;

	FUNCTION IS_IO_OUT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入出庫（出庫）かどうか
	BEGIN
		IF I_VALUE = IO_OUT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IO_OUT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = INPT
		OR I_VALUE = IO
		OR I_VALUE = SLS
		OR I_VALUE = IO_IN
		OR I_VALUE = IO_OUT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SET_TGT_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SET_TGT_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SET_TGT_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SET_TGT_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SET_TGT_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SET_TGT_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SET_TGT_TYP;

/
