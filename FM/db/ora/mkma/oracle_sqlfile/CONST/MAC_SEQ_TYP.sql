CREATE OR REPLACE PACKAGE BODY MAC_SEQ_TYP
/*****************************
シーケンス区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION SAME_TRAN RETURN VARCHAR2 DETERMINISTIC IS -- カウンタテーブル（自動発番時の飛び番：なし　パフォーマンス：低）
	BEGIN RETURN '0'; END SAME_TRAN;
	FUNCTION ATNMS_TRAN RETURN VARCHAR2 DETERMINISTIC IS -- カウンタテーブル（自動発番時の飛び番：あり　パフォーマンス：中）
	BEGIN RETURN '1'; END ATNMS_TRAN;
	FUNCTION ORA_SEQ RETURN VARCHAR2 DETERMINISTIC IS -- シーケンス（自動発番時の飛び番：あり　パフォーマンス：高）
	BEGIN RETURN '2'; END ORA_SEQ;

	FUNCTION IS_SAME_TRAN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- カウンタテーブル（自動発番時の飛び番：なし　パフォーマンス：低）かどうか
	BEGIN
		IF I_VALUE = SAME_TRAN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SAME_TRAN;

	FUNCTION IS_ATNMS_TRAN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- カウンタテーブル（自動発番時の飛び番：あり　パフォーマンス：中）かどうか
	BEGIN
		IF I_VALUE = ATNMS_TRAN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ATNMS_TRAN;

	FUNCTION IS_ORA_SEQ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- シーケンス（自動発番時の飛び番：あり　パフォーマンス：高）かどうか
	BEGIN
		IF I_VALUE = ORA_SEQ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ORA_SEQ;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SAME_TRAN
		OR I_VALUE = ATNMS_TRAN
		OR I_VALUE = ORA_SEQ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_TBL_SEQ(
		I_SEQ_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_SEQ_TYP = SAME_TRAN) THEN
			RETURN '1';
		ELSIF (I_SEQ_TYP = ATNMS_TRAN) THEN
			RETURN '1';
		ELSIF (I_SEQ_TYP = ORA_SEQ) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_TBL_SEQ;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SEQ_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SEQ_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SEQ_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SEQ_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SEQ_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SEQ_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SEQ_TYP;

/
show errors;


