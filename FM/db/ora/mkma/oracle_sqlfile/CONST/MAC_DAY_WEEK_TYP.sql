CREATE OR REPLACE PACKAGE BODY MAC_DAY_WEEK_TYP
/*****************************
曜日区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION SUN RETURN VARCHAR2 DETERMINISTIC IS -- Sun.
	BEGIN RETURN '1'; END SUN;
	FUNCTION MON RETURN VARCHAR2 DETERMINISTIC IS -- Mon.
	BEGIN RETURN '2'; END MON;
	FUNCTION TUE RETURN VARCHAR2 DETERMINISTIC IS -- Tue.
	BEGIN RETURN '3'; END TUE;
	FUNCTION WED RETURN VARCHAR2 DETERMINISTIC IS -- Wed.
	BEGIN RETURN '4'; END WED;
	FUNCTION THU RETURN VARCHAR2 DETERMINISTIC IS -- Thu.
	BEGIN RETURN '5'; END THU;
	FUNCTION FRI RETURN VARCHAR2 DETERMINISTIC IS -- Fri.
	BEGIN RETURN '6'; END FRI;
	FUNCTION SAT RETURN VARCHAR2 DETERMINISTIC IS -- Sat.
	BEGIN RETURN '7'; END SAT;

	FUNCTION IS_SUN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Sun.かどうか
	BEGIN
		IF I_VALUE = SUN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUN;

	FUNCTION IS_MON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Mon.かどうか
	BEGIN
		IF I_VALUE = MON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MON;

	FUNCTION IS_TUE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Tue.かどうか
	BEGIN
		IF I_VALUE = TUE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TUE;

	FUNCTION IS_WED(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Wed.かどうか
	BEGIN
		IF I_VALUE = WED THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WED;

	FUNCTION IS_THU(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Thu.かどうか
	BEGIN
		IF I_VALUE = THU THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_THU;

	FUNCTION IS_FRI(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Fri.かどうか
	BEGIN
		IF I_VALUE = FRI THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FRI;

	FUNCTION IS_SAT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- Sat.かどうか
	BEGIN
		IF I_VALUE = SAT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SAT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SUN
		OR I_VALUE = MON
		OR I_VALUE = TUE
		OR I_VALUE = WED
		OR I_VALUE = THU
		OR I_VALUE = FRI
		OR I_VALUE = SAT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_DAY_WEEK_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_DAY_WEEK_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_DAY_WEEK_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_DAY_WEEK_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_DAY_WEEK_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_DAY_WEEK_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_DAY_WEEK_TYP;

/
show errors;


