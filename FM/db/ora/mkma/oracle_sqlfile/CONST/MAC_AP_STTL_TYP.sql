CREATE OR REPLACE PACKAGE BODY MAC_AP_STTL_TYP
/*****************************
債務決済区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ACNT RETURN VARCHAR2 DETERMINISTIC IS -- 預金
	BEGIN RETURN '1'; END ACNT;
	FUNCTION ACNT_COM_PAID RETURN VARCHAR2 DETERMINISTIC IS -- 預金（手数料）
	BEGIN RETURN '2'; END ACNT_COM_PAID;
	FUNCTION CASH RETURN VARCHAR2 DETERMINISTIC IS -- 現金
	BEGIN RETURN '3'; END CASH;
	FUNCTION CASH_COM_PAID RETURN VARCHAR2 DETERMINISTIC IS -- 現金（手数料）
	BEGIN RETURN '4'; END CASH_COM_PAID;
	FUNCTION NOTE RETURN VARCHAR2 DETERMINISTIC IS -- 手形
	BEGIN RETURN '5'; END NOTE;
	FUNCTION SETOFF RETURN VARCHAR2 DETERMINISTIC IS -- 相殺
	BEGIN RETURN '6'; END SETOFF;
	FUNCTION WTAX RETURN VARCHAR2 DETERMINISTIC IS -- 源泉税
	BEGIN RETURN '7'; END WTAX;
	FUNCTION APSW_OUT_CHK RETURN VARCHAR2 DETERMINISTIC IS -- 照合済残高振替払出
	BEGIN RETURN 'A'; END APSW_OUT_CHK;
	FUNCTION APSW_IN_CHK RETURN VARCHAR2 DETERMINISTIC IS -- 照合済残高振替受入
	BEGIN RETURN 'B'; END APSW_IN_CHK;
	FUNCTION APSW_OUT_NOT_CHK RETURN VARCHAR2 DETERMINISTIC IS -- 未照合残高振替払出
	BEGIN RETURN 'C'; END APSW_OUT_NOT_CHK;
	FUNCTION APSW_IN_NOT_CHK RETURN VARCHAR2 DETERMINISTIC IS -- 未照合残高振替受入
	BEGIN RETURN 'D'; END APSW_IN_NOT_CHK;

	FUNCTION IS_ACNT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 預金かどうか
	BEGIN
		IF I_VALUE = ACNT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACNT;

	FUNCTION IS_ACNT_COM_PAID(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 預金（手数料）かどうか
	BEGIN
		IF I_VALUE = ACNT_COM_PAID THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACNT_COM_PAID;

	FUNCTION IS_CASH(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 現金かどうか
	BEGIN
		IF I_VALUE = CASH THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CASH;

	FUNCTION IS_CASH_COM_PAID(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 現金（手数料）かどうか
	BEGIN
		IF I_VALUE = CASH_COM_PAID THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CASH_COM_PAID;

	FUNCTION IS_NOTE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 手形かどうか
	BEGIN
		IF I_VALUE = NOTE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOTE;

	FUNCTION IS_SETOFF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 相殺かどうか
	BEGIN
		IF I_VALUE = SETOFF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SETOFF;

	FUNCTION IS_WTAX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 源泉税かどうか
	BEGIN
		IF I_VALUE = WTAX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WTAX;

	FUNCTION IS_APSW_OUT_CHK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 照合済残高振替払出かどうか
	BEGIN
		IF I_VALUE = APSW_OUT_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_APSW_OUT_CHK;

	FUNCTION IS_APSW_IN_CHK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 照合済残高振替受入かどうか
	BEGIN
		IF I_VALUE = APSW_IN_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_APSW_IN_CHK;

	FUNCTION IS_APSW_OUT_NOT_CHK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未照合残高振替払出かどうか
	BEGIN
		IF I_VALUE = APSW_OUT_NOT_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_APSW_OUT_NOT_CHK;

	FUNCTION IS_APSW_IN_NOT_CHK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未照合残高振替受入かどうか
	BEGIN
		IF I_VALUE = APSW_IN_NOT_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_APSW_IN_NOT_CHK;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ACNT
		OR I_VALUE = ACNT_COM_PAID
		OR I_VALUE = CASH
		OR I_VALUE = CASH_COM_PAID
		OR I_VALUE = NOTE
		OR I_VALUE = SETOFF
		OR I_VALUE = WTAX
		OR I_VALUE = APSW_OUT_CHK
		OR I_VALUE = APSW_IN_CHK
		OR I_VALUE = APSW_OUT_NOT_CHK
		OR I_VALUE = APSW_IN_NOT_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_COM_PAID(
		I_AP_STTL_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_AP_STTL_TYP = ACNT) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = ACNT_COM_PAID) THEN
			RETURN '1';
		ELSIF (I_AP_STTL_TYP = CASH) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = CASH_COM_PAID) THEN
			RETURN '1';
		ELSIF (I_AP_STTL_TYP = NOTE) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = SETOFF) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = WTAX) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_OUT_CHK) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_IN_CHK) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_OUT_NOT_CHK) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_IN_NOT_CHK) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_COM_PAID;

	FUNCTION IS_REQ_BANK_AC(
		I_AP_STTL_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_AP_STTL_TYP = ACNT) THEN
			RETURN '1';
		ELSIF (I_AP_STTL_TYP = ACNT_COM_PAID) THEN
			RETURN '1';
		ELSIF (I_AP_STTL_TYP = CASH) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = CASH_COM_PAID) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = NOTE) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = SETOFF) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = WTAX) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_OUT_CHK) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_IN_CHK) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_OUT_NOT_CHK) THEN
			RETURN '0';
		ELSIF (I_AP_STTL_TYP = APSW_IN_NOT_CHK) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_REQ_BANK_AC;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_AP_STTL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_AP_STTL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_AP_STTL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_AP_STTL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_AP_STTL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_AP_STTL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_AP_STTL_TYP;

/
show errors;


