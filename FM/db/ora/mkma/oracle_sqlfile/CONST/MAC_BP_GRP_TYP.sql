CREATE OR REPLACE PACKAGE BODY MAC_BP_GRP_TYP
/*****************************
取引先分類区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION GRP1 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類１
	BEGIN RETURN '01'; END GRP1;
	FUNCTION GRP2 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類２
	BEGIN RETURN '02'; END GRP2;
	FUNCTION GRP3 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類３
	BEGIN RETURN '03'; END GRP3;
	FUNCTION GRP4 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類４
	BEGIN RETURN '04'; END GRP4;
	FUNCTION GRP5 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類５
	BEGIN RETURN '05'; END GRP5;
	FUNCTION GRP6 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類６
	BEGIN RETURN '06'; END GRP6;
	FUNCTION GRP7 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類７
	BEGIN RETURN '07'; END GRP7;
	FUNCTION GRP8 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類８
	BEGIN RETURN '08'; END GRP8;
	FUNCTION GRP9 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類９
	BEGIN RETURN '09'; END GRP9;
	FUNCTION GRP10 RETURN VARCHAR2 DETERMINISTIC IS -- 取引先分類１０
	BEGIN RETURN '10'; END GRP10;

	FUNCTION IS_GRP1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類１かどうか
	BEGIN
		IF I_VALUE = GRP1 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP1;

	FUNCTION IS_GRP2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類２かどうか
	BEGIN
		IF I_VALUE = GRP2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP2;

	FUNCTION IS_GRP3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類３かどうか
	BEGIN
		IF I_VALUE = GRP3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP3;

	FUNCTION IS_GRP4(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類４かどうか
	BEGIN
		IF I_VALUE = GRP4 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP4;

	FUNCTION IS_GRP5(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類５かどうか
	BEGIN
		IF I_VALUE = GRP5 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP5;

	FUNCTION IS_GRP6(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類６かどうか
	BEGIN
		IF I_VALUE = GRP6 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP6;

	FUNCTION IS_GRP7(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類７かどうか
	BEGIN
		IF I_VALUE = GRP7 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP7;

	FUNCTION IS_GRP8(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類８かどうか
	BEGIN
		IF I_VALUE = GRP8 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP8;

	FUNCTION IS_GRP9(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類９かどうか
	BEGIN
		IF I_VALUE = GRP9 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP9;

	FUNCTION IS_GRP10(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 取引先分類１０かどうか
	BEGIN
		IF I_VALUE = GRP10 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GRP10;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = GRP1
		OR I_VALUE = GRP2
		OR I_VALUE = GRP3
		OR I_VALUE = GRP4
		OR I_VALUE = GRP5
		OR I_VALUE = GRP6
		OR I_VALUE = GRP7
		OR I_VALUE = GRP8
		OR I_VALUE = GRP9
		OR I_VALUE = GRP10 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_BP_GRP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_BP_GRP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_BP_GRP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_BP_GRP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_BP_GRP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_BP_GRP_TYP', I_LCL_CD);
	END GRP_RMRKS;
