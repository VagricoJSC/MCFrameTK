CREATE OR REPLACE PACKAGE BODY MAC_QUALITY_TYP
/*****************************
在庫良品区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION GOOD RETURN VARCHAR2 DETERMINISTIC IS -- 良品
	BEGIN RETURN '1'; END GOOD;
	FUNCTION DFCT_OPER RETURN VARCHAR2 DETERMINISTIC IS -- 工程不良品
	BEGIN RETURN '2'; END DFCT_OPER;
	FUNCTION DFCT_INSP RETURN VARCHAR2 DETERMINISTIC IS -- 検査不良品
	BEGIN RETURN '3'; END DFCT_INSP;
	FUNCTION SSPND RETURN VARCHAR2 DETERMINISTIC IS -- 保留
	BEGIN RETURN '4'; END SSPND;

	FUNCTION IS_GOOD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 良品かどうか
	BEGIN
		IF I_VALUE = GOOD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GOOD;

	FUNCTION IS_DFCT_OPER(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工程不良品かどうか
	BEGIN
		IF I_VALUE = DFCT_OPER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DFCT_OPER;

	FUNCTION IS_DFCT_INSP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 検査不良品かどうか
	BEGIN
		IF I_VALUE = DFCT_INSP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DFCT_INSP;

	FUNCTION IS_SSPND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 保留かどうか
	BEGIN
		IF I_VALUE = SSPND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SSPND;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = GOOD
		OR I_VALUE = DFCT_OPER
		OR I_VALUE = DFCT_INSP
		OR I_VALUE = SSPND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_INSP_TYP(
		I_QUALITY_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_QUALITY_TYP = GOOD) THEN
			RETURN '1';
		ELSIF (I_QUALITY_TYP = DFCT_OPER) THEN
			RETURN '0';
		ELSIF (I_QUALITY_TYP = DFCT_INSP) THEN
			RETURN '1';
		ELSIF (I_QUALITY_TYP = SSPND) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_INSP_TYP;

	FUNCTION IS_OTH(
		I_QUALITY_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_QUALITY_TYP = GOOD) THEN
			RETURN '1';
		ELSIF (I_QUALITY_TYP = DFCT_OPER) THEN
			RETURN '0';
		ELSIF (I_QUALITY_TYP = DFCT_INSP) THEN
			RETURN '0';
		ELSIF (I_QUALITY_TYP = SSPND) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END IS_OTH;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_QUALITY_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_QUALITY_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_QUALITY_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_QUALITY_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_QUALITY_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_QUALITY_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_QUALITY_TYP;

/
show errors;


