		OR I_VALUE = SLS_XTRA
		OR I_VALUE = MFG
		OR I_VALUE = PURC
		OR I_VALUE = PURC_VMI
		OR I_VALUE = PURC_XPNS
		OR I_VALUE = PURC_RTN
		OR I_VALUE = PURC_RTN_XPNS
		OR I_VALUE = PURC_DSCNT
		OR I_VALUE = PURC_DSCNT_XPNS
		OR I_VALUE = PURC_XTRA
		OR I_VALUE = PURC_XTRA_XPNS
		OR I_VALUE = SHIP
		OR I_VALUE = SHIP_RTN
		OR I_VALUE = XFR
		OR I_VALUE = XFR_RTN
		OR I_VALUE = PROV
		OR I_VALUE = PROV_RTN
		OR I_VALUE = ARR
		OR I_VALUE = ARR_RTN
		OR I_VALUE = STK_OTH_GR
		OR I_VALUE = STK_OTH_GI
		OR I_VALUE = SCRP
		OR I_VALUE = XFR_ITM
		OR I_VALUE = XFR_LOT_SNO
		OR I_VALUE = XFR_GRD
		OR I_VALUE = XFR_PACK
		OR I_VALUE = STK_ADJST
		OR I_VALUE = INSP
		OR I_VALUE = REINSP
		OR I_VALUE = INSP_SMPL
		OR I_VALUE = RCV_AR
		OR I_VALUE = RCV_ADV
		OR I_VALUE = RCV_SUSP
		OR I_VALUE = SETOFF_ADV_AR
		OR I_VALUE = SETOFF_ADV_OTH
		OR I_VALUE = SETOFF_SUSP_AR
		OR I_VALUE = SETOFF_SUSP_ADV
		OR I_VALUE = SETOFF_SUSP_OTH
		OR I_VALUE = SETOFF_OTR_AR
		OR I_VALUE = ARSW_OUT_BILL_BAL
		OR I_VALUE = ARSW_OUT_NOT_BILL_BAL
		OR I_VALUE = ARSW_IN_BILL_BAL
		OR I_VALUE = ARSW_IN_NOT_BILL_BAL
		OR I_VALUE = TAX_DIFF_BILL_CL
		OR I_VALUE = TAX_DIFF_PAY_SCHD_CL
		OR I_VALUE = APSW_IN_CHK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

