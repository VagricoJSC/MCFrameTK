CREATE OR REPLACE PACKAGE BODY MAC_COST_CALC_TYP
/*****************************
原価計算区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION COST_STD RETURN VARCHAR2 DETERMINISTIC IS -- 標準単価
	BEGIN RETURN '1'; END COST_STD;
	FUNCTION NOT_STK RETURN VARCHAR2 DETERMINISTIC IS -- 原価計算（在庫対象外）
	BEGIN RETURN '2'; END NOT_STK;
	FUNCTION CALC_STK RETURN VARCHAR2 DETERMINISTIC IS -- 原価計算（在庫計算）
	BEGIN RETURN '3'; END CALC_STK;
	FUNCTION OTHER RETURN VARCHAR2 DETERMINISTIC IS -- その他
	BEGIN RETURN '4'; END OTHER;

	FUNCTION IS_COST_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準単価かどうか
	BEGIN
		IF I_VALUE = COST_STD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_COST_STD;

	FUNCTION IS_NOT_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 原価計算（在庫対象外）かどうか
	BEGIN
		IF I_VALUE = NOT_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_STK;

	FUNCTION IS_CALC_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 原価計算（在庫計算）かどうか
	BEGIN
		IF I_VALUE = CALC_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CALC_STK;

	FUNCTION IS_OTHER(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- その他かどうか
	BEGIN
		IF I_VALUE = OTHER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OTHER;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = COST_STD
		OR I_VALUE = NOT_STK
		OR I_VALUE = CALC_STK
		OR I_VALUE = OTHER THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_COST_CALC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_COST_CALC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_COST_CALC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_COST_CALC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_COST_CALC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_COST_CALC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_COST_CALC_TYP;

/
show errors;


