CREATE OR REPLACE PACKAGE BODY MAC_PERIOD_TYP
/*****************************
期間区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION DAILY RETURN VARCHAR2 DETERMINISTIC IS -- 日次
	BEGIN RETURN '1'; END DAILY;
	FUNCTION WEEKLY RETURN VARCHAR2 DETERMINISTIC IS -- 週次
	BEGIN RETURN '2'; END WEEKLY;
	FUNCTION TENDAYS RETURN VARCHAR2 DETERMINISTIC IS -- 旬次
	BEGIN RETURN '3'; END TENDAYS;
	FUNCTION MONTHLY RETURN VARCHAR2 DETERMINISTIC IS -- 月次
	BEGIN RETURN '4'; END MONTHLY;

	FUNCTION IS_DAILY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 日次かどうか
	BEGIN
		IF I_VALUE = DAILY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_DAILY;

	FUNCTION IS_WEEKLY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 週次かどうか
	BEGIN
		IF I_VALUE = WEEKLY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WEEKLY;

	FUNCTION IS_TENDAYS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 旬次かどうか
	BEGIN
		IF I_VALUE = TENDAYS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TENDAYS;

	FUNCTION IS_MONTHLY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月次かどうか
	BEGIN
		IF I_VALUE = MONTHLY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MONTHLY;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = DAILY
		OR I_VALUE = WEEKLY
		OR I_VALUE = TENDAYS
		OR I_VALUE = MONTHLY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_CST_FRCST(
		I_PERIOD_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_PERIOD_TYP = DAILY) THEN
			RETURN '0';
		ELSIF (I_PERIOD_TYP = WEEKLY) THEN
			RETURN '1';
		ELSIF (I_PERIOD_TYP = TENDAYS) THEN
			RETURN '1';
		ELSIF (I_PERIOD_TYP = MONTHLY) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_CST_FRCST;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_PERIOD_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_PERIOD_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_PERIOD_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_PERIOD_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_PERIOD_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_PERIOD_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_PERIOD_TYP;

/
show errors;


