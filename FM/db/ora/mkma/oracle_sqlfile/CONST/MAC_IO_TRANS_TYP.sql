CREATE OR REPLACE PACKAGE BODY MAC_IO_TRANS_TYP
/*****************************
入出庫振替区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ALC RETURN VARCHAR2 DETERMINISTIC IS -- 費用振替
	BEGIN RETURN '1'; END ALC;
	FUNCTION INPT RETURN VARCHAR2 DETERMINISTIC IS -- 投入振替
	BEGIN RETURN '2'; END INPT;
	FUNCTION GR RETURN VARCHAR2 DETERMINISTIC IS -- 入庫振替
	BEGIN RETURN '3'; END GR;
	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- 対象外
	BEGIN RETURN 'X'; END NON;

	FUNCTION IS_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 費用振替かどうか
	BEGIN
		IF I_VALUE = ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALC;

	FUNCTION IS_INPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 投入振替かどうか
	BEGIN
		IF I_VALUE = INPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INPT;

	FUNCTION IS_GR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入庫振替かどうか
	BEGIN
		IF I_VALUE = GR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_GR;

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 対象外かどうか
	BEGIN
		IF I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ALC
		OR I_VALUE = INPT
		OR I_VALUE = GR
		OR I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_IO_TRANS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_IO_TRANS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_IO_TRANS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_IO_TRANS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_IO_TRANS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_IO_TRANS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_IO_TRANS_TYP;

/
show errors;


