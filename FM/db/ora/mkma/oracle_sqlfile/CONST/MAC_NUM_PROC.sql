CREATE OR REPLACE PACKAGE BODY MAC_NUM_PROC
/*****************************
発番処理用定数の定数定義パッケージ本体
******************************/
IS

	FUNCTION SEQ_MIN_VAL_DEF RETURN VARCHAR2 DETERMINISTIC IS -- 最小値の初期設定値
	BEGIN RETURN '0'; END SEQ_MIN_VAL_DEF;
	FUNCTION SEQ_MAX_VAL_DEF RETURN VARCHAR2 DETERMINISTIC IS -- 最大値の初期設定値
	BEGIN RETURN '99999999999999999999'; END SEQ_MAX_VAL_DEF;
	FUNCTION SEQ_INC_DEF RETURN VARCHAR2 DETERMINISTIC IS -- 増加量の初期設定値
	BEGIN RETURN '1'; END SEQ_INC_DEF;
	FUNCTION SEQ_CYCL_FLG_DEF RETURN VARCHAR2 DETERMINISTIC IS -- 自動リセット許可フラグの初期設定値
	BEGIN RETURN '0'; END SEQ_CYCL_FLG_DEF;
	FUNCTION LAST_VAL_DEF RETURN VARCHAR2 DETERMINISTIC IS -- 現在値の初期値
	BEGIN RETURN '0'; END LAST_VAL_DEF;
	FUNCTION ORA_SEQ_OPT RETURN VARCHAR2 DETERMINISTIC IS -- シーケンスのオプションを指定用文字列
	BEGIN RETURN 'NOCACHE'; END ORA_SEQ_OPT;
	FUNCTION PAD_STR RETURN VARCHAR2 DETERMINISTIC IS -- 埋める文字（文字列用）
	BEGIN RETURN 'X'; END PAD_STR;
	FUNCTION PAD_NUM RETURN VARCHAR2 DETERMINISTIC IS -- 埋める文字（数字用）
	BEGIN RETURN '0'; END PAD_NUM;
	FUNCTION MFG_CHD_LOT_NO RETURN VARCHAR2 DETERMINISTIC IS -- 引継対象子品目ロットＮＯ
	BEGIN RETURN 'MFG_CHD_LOT_NO'; END MFG_CHD_LOT_NO;
	FUNCTION MFG_CHD_SUBLOT_NO RETURN VARCHAR2 DETERMINISTIC IS -- 引継対象子品目サブロットＮＯ
	BEGIN RETURN 'MFG_CHD_SUBLOT_NO'; END MFG_CHD_SUBLOT_NO;
	FUNCTION MFG_YIELD_SCHD_DT RETURN VARCHAR2 DETERMINISTIC IS -- 出来高予定日
	BEGIN RETURN 'MFG_YIELD_SCHD_DT'; END MFG_YIELD_SCHD_DT;

	FUNCTION IS_SEQ_MIN_VAL_DEF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 最小値の初期設定値かどうか
	BEGIN
		IF I_VALUE = SEQ_MIN_VAL_DEF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SEQ_MIN_VAL_DEF;

	FUNCTION IS_SEQ_MAX_VAL_DEF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 最大値の初期設定値かどうか
	BEGIN
		IF I_VALUE = SEQ_MAX_VAL_DEF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SEQ_MAX_VAL_DEF;

	FUNCTION IS_SEQ_INC_DEF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 増加量の初期設定値かどうか
	BEGIN
		IF I_VALUE = SEQ_INC_DEF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SEQ_INC_DEF;

	FUNCTION IS_SEQ_CYCL_FLG_DEF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 自動リセット許可フラグの初期設定値かどうか
	BEGIN
		IF I_VALUE = SEQ_CYCL_FLG_DEF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SEQ_CYCL_FLG_DEF;

	FUNCTION IS_LAST_VAL_DEF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 現在値の初期値かどうか
	BEGIN
		IF I_VALUE = LAST_VAL_DEF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LAST_VAL_DEF;

	FUNCTION IS_ORA_SEQ_OPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- シーケンスのオプションを指定用文字列かどうか
	BEGIN
		IF I_VALUE = ORA_SEQ_OPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ORA_SEQ_OPT;

	FUNCTION IS_PAD_STR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 埋める文字（文字列用）かどうか
	BEGIN
		IF I_VALUE = PAD_STR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PAD_STR;

	FUNCTION IS_PAD_NUM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 埋める文字（数字用）かどうか
	BEGIN
		IF I_VALUE = PAD_NUM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PAD_NUM;

	FUNCTION IS_MFG_CHD_LOT_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 引継対象子品目ロットＮＯかどうか
	BEGIN
		IF I_VALUE = MFG_CHD_LOT_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG_CHD_LOT_NO;

	FUNCTION IS_MFG_CHD_SUBLOT_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 引継対象子品目サブロットＮＯかどうか
	BEGIN
		IF I_VALUE = MFG_CHD_SUBLOT_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG_CHD_SUBLOT_NO;

	FUNCTION IS_MFG_YIELD_SCHD_DT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 出来高予定日かどうか
	BEGIN
		IF I_VALUE = MFG_YIELD_SCHD_DT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG_YIELD_SCHD_DT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SEQ_MIN_VAL_DEF
		OR I_VALUE = SEQ_MAX_VAL_DEF
		OR I_VALUE = SEQ_INC_DEF
		OR I_VALUE = SEQ_CYCL_FLG_DEF
		OR I_VALUE = LAST_VAL_DEF
		OR I_VALUE = ORA_SEQ_OPT
		OR I_VALUE = PAD_STR
		OR I_VALUE = PAD_NUM
		OR I_VALUE = MFG_CHD_LOT_NO
		OR I_VALUE = MFG_CHD_SUBLOT_NO
		OR I_VALUE = MFG_YIELD_SCHD_DT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_NUM_PROC', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_NUM_PROC', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_NUM_PROC', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_NUM_PROC', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_NUM_PROC', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_NUM_PROC', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_NUM_PROC;

