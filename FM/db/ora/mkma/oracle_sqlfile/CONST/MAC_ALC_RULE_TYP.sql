CREATE OR REPLACE PACKAGE BODY MAC_ALC_RULE_TYP
/*****************************
配賦方法区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION WK RETURN VARCHAR2 DETERMINISTIC IS -- 工数
	BEGIN RETURN '1'; END WK;
	FUNCTION QTY RETURN VARCHAR2 DETERMINISTIC IS -- 数量
	BEGIN RETURN '2'; END QTY;
	FUNCTION AMT RETURN VARCHAR2 DETERMINISTIC IS -- 金額
	BEGIN RETURN '3'; END AMT;
	FUNCTION EXPNS_COST RETURN VARCHAR2 DETERMINISTIC IS -- 費目別原価
	BEGIN RETURN '4'; END EXPNS_COST;
	FUNCTION PROFIT RETURN VARCHAR2 DETERMINISTIC IS -- 利益
	BEGIN RETURN '5'; END PROFIT;
	FUNCTION INPT_QTY RETURN VARCHAR2 DETERMINISTIC IS -- 投入数量
	BEGIN RETURN '6'; END INPT_QTY;
	FUNCTION OTHER_VAL RETURN VARCHAR2 DETERMINISTIC IS -- 任意配賦基準値
	BEGIN RETURN '7'; END OTHER_VAL;

	FUNCTION IS_WK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工数かどうか
	BEGIN
		IF I_VALUE = WK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WK;

	FUNCTION IS_QTY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 数量かどうか
	BEGIN
		IF I_VALUE = QTY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_QTY;

	FUNCTION IS_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 金額かどうか
	BEGIN
		IF I_VALUE = AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AMT;

	FUNCTION IS_EXPNS_COST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 費目別原価かどうか
	BEGIN
		IF I_VALUE = EXPNS_COST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_EXPNS_COST;

	FUNCTION IS_PROFIT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 利益かどうか
	BEGIN
		IF I_VALUE = PROFIT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROFIT;

	FUNCTION IS_INPT_QTY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 投入数量かどうか
	BEGIN
		IF I_VALUE = INPT_QTY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INPT_QTY;

	FUNCTION IS_OTHER_VAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 任意配賦基準値かどうか
	BEGIN
		IF I_VALUE = OTHER_VAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OTHER_VAL;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = WK
		OR I_VALUE = QTY
		OR I_VALUE = AMT
		OR I_VALUE = EXPNS_COST
		OR I_VALUE = PROFIT
		OR I_VALUE = INPT_QTY
		OR I_VALUE = OTHER_VAL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION IS_MFG(
		I_ALC_RULE_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_ALC_RULE_TYP = WK) THEN
			RETURN '1';
		ELSIF (I_ALC_RULE_TYP = QTY) THEN
			RETURN '1';
		ELSIF (I_ALC_RULE_TYP = AMT) THEN
			RETURN '1';
		ELSIF (I_ALC_RULE_TYP = EXPNS_COST) THEN
			RETURN '1';
		ELSIF (I_ALC_RULE_TYP = PROFIT) THEN
			RETURN '0';
		ELSIF (I_ALC_RULE_TYP = INPT_QTY) THEN
			RETURN '1';
		ELSIF (I_ALC_RULE_TYP = OTHER_VAL) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_MFG;

	FUNCTION IS_PURC(
		I_ALC_RULE_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_ALC_RULE_TYP = WK) THEN
