	FUNCTION IS_PURC_DDLV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 仕入直送であるか
	FUNCTION IS_PROC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 手配依頼であるか
