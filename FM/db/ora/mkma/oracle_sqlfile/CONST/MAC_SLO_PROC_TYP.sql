CREATE OR REPLACE PACKAGE BODY MAC_SLO_PROC_TYP
/*****************************
受注手配区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ALLOC RETURN VARCHAR2 DETERMINISTIC IS -- 在庫引当
	BEGIN RETURN '1'; END ALLOC;
	FUNCTION PURC_DDLV RETURN VARCHAR2 DETERMINISTIC IS -- 仕入直送
	BEGIN RETURN '2'; END PURC_DDLV;
	FUNCTION PROC RETURN VARCHAR2 DETERMINISTIC IS -- 手配依頼
	BEGIN RETURN '3'; END PROC;
	FUNCTION ALLOC_PROC RETURN VARCHAR2 DETERMINISTIC IS -- 引当後手配
	BEGIN RETURN '4'; END ALLOC_PROC;

	FUNCTION IS_ALLOC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 在庫引当かどうか
	BEGIN
		IF I_VALUE = ALLOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALLOC;

	FUNCTION IS_PURC_DDLV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 仕入直送かどうか
	BEGIN
		IF I_VALUE = PURC_DDLV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC_DDLV;

	FUNCTION IS_PROC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 手配依頼かどうか
	BEGIN
		IF I_VALUE = PROC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROC;

	FUNCTION IS_ALLOC_PROC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 引当後手配かどうか
	BEGIN
		IF I_VALUE = ALLOC_PROC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALLOC_PROC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ALLOC
		OR I_VALUE = PURC_DDLV
		OR I_VALUE = PROC
		OR I_VALUE = ALLOC_PROC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SLO_PROC_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SLO_PROC_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SLO_PROC_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SLO_PROC_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SLO_PROC_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SLO_PROC_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SLO_PROC_TYP;

/
show errors;


