CREATE OR REPLACE FUNCTION MAC_STR$CONTAINS(IN I_VALUE VARCHAR) RETURNS CHAR(1) AS -- 定数に含まれるかどうか
$BODY$ BEGIN
	IF I_VALUE = MAC_STR$NULL_VAL()
	OR I_VALUE = MAC_STR$REAL_NULL_VAL()
	OR I_VALUE = MAC_STR$CD_NM_DLM()
	OR I_VALUE = MAC_STR$DEF_NUM_PTN_CD()
	OR I_VALUE = MAC_STR$BTN_GRP_NM_DLM()
	OR I_VALUE = MAC_STR$PRNT_CHK_TRUE()
	OR I_VALUE = MAC_STR$PRNT_CHK_FALSE()
	OR I_VALUE = MAC_STR$PRNT_NOTE_MARK()
	OR I_VALUE = MAC_STR$PRNT_INC_TAX()
	OR I_VALUE = MAC_STR$PRNT_INTERIM()
	OR I_VALUE = MAC_STR$MSG_FLG_ON()
	OR I_VALUE = MAC_STR$MSG_FLG_OFF()
	OR I_VALUE = MAC_STR$PRNT_SNO1()
	OR I_VALUE = MAC_STR$PRNT_SNO2()
	OR I_VALUE = MAC_STR$PRNT_SNO3()
	OR I_VALUE = MAC_STR$PRNT_SNO4()
	OR I_VALUE = MAC_STR$DISP_SNO_DLM1()
	OR I_VALUE = MAC_STR$DISP_SNO_DLM2()
	OR I_VALUE = MAC_STR$DISP_SNO_DLM3()
	OR I_VALUE = MAC_STR$DISP_SNO_PREFIX()
	OR I_VALUE = MAC_STR$DISP_SNO1_PREFIX()
	OR I_VALUE = MAC_STR$DISP_SNO2_PREFIX()
	OR I_VALUE = MAC_STR$DISP_SNO3_PREFIX()
	OR I_VALUE = MAC_STR$DISP_SNO4_PREFIX()
	OR I_VALUE = MAC_STR$DISP_ITM_DLM1()
	OR I_VALUE = MAC_STR$DISP_ITM_DLM2()
	OR I_VALUE = MAC_STR$DISP_ITM_DLM3()
	OR I_VALUE = MAC_STR$DISP_ITM_PREFIX() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE MAC_STR$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF MAC_STR$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
