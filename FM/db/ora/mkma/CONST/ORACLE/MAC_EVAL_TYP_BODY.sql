CREATE OR REPLACE PACKAGE BODY MAC_EVAL_TYP
/*****************************
金額評価区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MONTH_AVE RETURN VARCHAR2 DETERMINISTIC IS -- 月次平均
	BEGIN RETURN '1'; END MONTH_AVE;
	FUNCTION TERM_AVE RETURN VARCHAR2 DETERMINISTIC IS -- 期間平均
	BEGIN RETURN '2'; END TERM_AVE;
	FUNCTION STD_UNIT RETURN VARCHAR2 DETERMINISTIC IS -- 標準単価
	BEGIN RETURN 'A'; END STD_UNIT;

	FUNCTION IS_MONTH_AVE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 月次平均かどうか
	BEGIN
		IF I_VALUE = MONTH_AVE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MONTH_AVE;

	FUNCTION IS_TERM_AVE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 期間平均かどうか
	BEGIN
		IF I_VALUE = TERM_AVE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TERM_AVE;

	FUNCTION IS_STD_UNIT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準単価かどうか
	BEGIN
		IF I_VALUE = STD_UNIT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD_UNIT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MONTH_AVE
		OR I_VALUE = TERM_AVE
		OR I_VALUE = STD_UNIT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_EVAL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_EVAL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_EVAL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_EVAL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_EVAL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_EVAL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_EVAL_TYP;
