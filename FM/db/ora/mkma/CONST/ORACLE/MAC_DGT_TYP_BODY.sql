CREATE OR REPLACE PACKAGE BODY MAC_DGT_TYP
/*****************************
桁数処理法の定数定義パッケージ本体
******************************/
IS

	FUNCTION CHAR_CNT RETURN VARCHAR2 DETERMINISTIC IS -- 文字数
	BEGIN RETURN 'A'; END CHAR_CNT;
	FUNCTION FIX_DGT RETURN VARCHAR2 DETERMINISTIC IS -- 固定値
	BEGIN RETURN 'B'; END FIX_DGT;
	FUNCTION ELM_DGT RETURN VARCHAR2 DETERMINISTIC IS -- 設定桁数
	BEGIN RETURN 'C'; END ELM_DGT;

	FUNCTION IS_CHAR_CNT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 文字数かどうか
	BEGIN
		IF I_VALUE = CHAR_CNT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CHAR_CNT;

	FUNCTION IS_FIX_DGT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 固定値かどうか
	BEGIN
		IF I_VALUE = FIX_DGT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FIX_DGT;

	FUNCTION IS_ELM_DGT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 設定桁数かどうか
	BEGIN
		IF I_VALUE = ELM_DGT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ELM_DGT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = CHAR_CNT
		OR I_VALUE = FIX_DGT
		OR I_VALUE = ELM_DGT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_DGT_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_DGT_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_DGT_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_DGT_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_DGT_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_DGT_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_DGT_TYP;
