CREATE OR REPLACE PACKAGE BODY MAC_ALC_TGT_TYP
/*****************************
配賦対象区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MFG RETURN VARCHAR2 DETERMINISTIC IS -- 製造
	BEGIN RETURN '1'; END MFG;
	FUNCTION PURC RETURN VARCHAR2 DETERMINISTIC IS -- 購買
	BEGIN RETURN '2'; END PURC;
	FUNCTION MFG_PURC RETURN VARCHAR2 DETERMINISTIC IS -- 製造・購買
	BEGIN RETURN '3'; END MFG_PURC;
	FUNCTION SLS RETURN VARCHAR2 DETERMINISTIC IS -- 売上
	BEGIN RETURN '4'; END SLS;
	FUNCTION ALC RETURN VARCHAR2 DETERMINISTIC IS -- 汎用配賦
	BEGIN RETURN '5'; END ALC;

	FUNCTION IS_MFG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製造かどうか
	BEGIN
		IF I_VALUE = MFG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG;

	FUNCTION IS_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買かどうか
	BEGIN
		IF I_VALUE = PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC;

	FUNCTION IS_MFG_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製造・購買かどうか
	BEGIN
		IF I_VALUE = MFG_PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG_PURC;

	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上かどうか
	BEGIN
		IF I_VALUE = SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS;

	FUNCTION IS_ALC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 汎用配賦かどうか
	BEGIN
		IF I_VALUE = ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ALC;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MFG
		OR I_VALUE = PURC
		OR I_VALUE = MFG_PURC
		OR I_VALUE = SLS
		OR I_VALUE = ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_ALC_TGT_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_ALC_TGT_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_ALC_TGT_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_ALC_TGT_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_ALC_TGT_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_ALC_TGT_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_ALC_TGT_TYP;
