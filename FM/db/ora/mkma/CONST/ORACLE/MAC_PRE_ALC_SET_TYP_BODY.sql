CREATE OR REPLACE PACKAGE BODY MAC_PRE_ALC_SET_TYP
/*****************************
一次配賦設定区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION WK RETURN VARCHAR2 DETERMINISTIC IS -- 工数
	BEGIN RETURN '1'; END WK;
	FUNCTION MFG_QTY RETURN VARCHAR2 DETERMINISTIC IS -- 製造数量
	BEGIN RETURN '2'; END MFG_QTY;
	FUNCTION MFG_AMT RETURN VARCHAR2 DETERMINISTIC IS -- 製造金額
	BEGIN RETURN '3'; END MFG_AMT;
	FUNCTION PURC_QTY RETURN VARCHAR2 DETERMINISTIC IS -- 購買数量
	BEGIN RETURN '4'; END PURC_QTY;
	FUNCTION PURC_AMT RETURN VARCHAR2 DETERMINISTIC IS -- 購買金額
	BEGIN RETURN '5'; END PURC_AMT;
	FUNCTION SLS_QTY RETURN VARCHAR2 DETERMINISTIC IS -- 売上数量
	BEGIN RETURN '6'; END SLS_QTY;
	FUNCTION SLS_AMT RETURN VARCHAR2 DETERMINISTIC IS -- 売上金額
	BEGIN RETURN '7'; END SLS_AMT;

	FUNCTION IS_WK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 工数かどうか
	BEGIN
		IF I_VALUE = WK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WK;

	FUNCTION IS_MFG_QTY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製造数量かどうか
	BEGIN
		IF I_VALUE = MFG_QTY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG_QTY;

	FUNCTION IS_MFG_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 製造金額かどうか
	BEGIN
		IF I_VALUE = MFG_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MFG_AMT;

	FUNCTION IS_PURC_QTY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買数量かどうか
	BEGIN
		IF I_VALUE = PURC_QTY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC_QTY;

	FUNCTION IS_PURC_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買金額かどうか
	BEGIN
		IF I_VALUE = PURC_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC_AMT;

	FUNCTION IS_SLS_QTY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上数量かどうか
	BEGIN
		IF I_VALUE = SLS_QTY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_QTY;

	FUNCTION IS_SLS_AMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上金額かどうか
	BEGIN
		IF I_VALUE = SLS_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_AMT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = WK
		OR I_VALUE = MFG_QTY
		OR I_VALUE = MFG_AMT
		OR I_VALUE = PURC_QTY
		OR I_VALUE = PURC_AMT
		OR I_VALUE = SLS_QTY
		OR I_VALUE = SLS_AMT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_PRE_ALC_SET_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_PRE_ALC_SET_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_PRE_ALC_SET_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_PRE_ALC_SET_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_PRE_ALC_SET_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_PRE_ALC_SET_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_PRE_ALC_SET_TYP;
