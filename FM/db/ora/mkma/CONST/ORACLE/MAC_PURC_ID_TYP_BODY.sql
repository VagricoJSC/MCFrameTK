CREATE OR REPLACE PACKAGE BODY MAC_PURC_ID_TYP
/*****************************
購買識別区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION PURC RETURN VARCHAR2 DETERMINISTIC IS -- 通常購買
	BEGIN RETURN '1'; END PURC;
	FUNCTION FFR_RCV RETURN VARCHAR2 DETERMINISTIC IS -- 無償受給
	BEGIN RETURN '2'; END FFR_RCV;
	FUNCTION ONR_RCV RETURN VARCHAR2 DETERMINISTIC IS -- 有償受給
	BEGIN RETURN '3'; END ONR_RCV;
	FUNCTION VMI RETURN VARCHAR2 DETERMINISTIC IS -- ＶＭＩ
	BEGIN RETURN '4'; END VMI;

	FUNCTION IS_PURC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 通常購買かどうか
	BEGIN
		IF I_VALUE = PURC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PURC;

	FUNCTION IS_FFR_RCV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 無償受給かどうか
	BEGIN
		IF I_VALUE = FFR_RCV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FFR_RCV;

	FUNCTION IS_ONR_RCV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 有償受給かどうか
	BEGIN
		IF I_VALUE = ONR_RCV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ONR_RCV;

	FUNCTION IS_VMI(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＶＭＩかどうか
	BEGIN
		IF I_VALUE = VMI THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_VMI;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = PURC
		OR I_VALUE = FFR_RCV
		OR I_VALUE = ONR_RCV
		OR I_VALUE = VMI THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_PURC_ID_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_PURC_ID_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_PURC_ID_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_PURC_ID_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_PURC_ID_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_PURC_ID_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_PURC_ID_TYP;
