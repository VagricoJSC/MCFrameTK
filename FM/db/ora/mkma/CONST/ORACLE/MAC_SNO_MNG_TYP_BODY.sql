CREATE OR REPLACE PACKAGE BODY MAC_SNO_MNG_TYP
/*****************************
手配ＮＯ管理区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NOT_MNG RETURN VARCHAR2 DETERMINISTIC IS -- 管理しない
	BEGIN RETURN '1'; END NOT_MNG;
	FUNCTION MNG_REQ RETURN VARCHAR2 DETERMINISTIC IS -- 管理する（必須）
	BEGIN RETURN '2'; END MNG_REQ;
	FUNCTION MNG_ARB RETURN VARCHAR2 DETERMINISTIC IS -- 管理する（任意）
	BEGIN RETURN '3'; END MNG_ARB;
	FUNCTION MNG_NOT_STK RETURN VARCHAR2 DETERMINISTIC IS -- 管理する（任意：在庫対象外）
	BEGIN RETURN '4'; END MNG_NOT_STK;

	FUNCTION IS_NOT_MNG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 管理しないかどうか
	BEGIN
		IF I_VALUE = NOT_MNG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NOT_MNG;

	FUNCTION IS_MNG_REQ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 管理する（必須）かどうか
	BEGIN
		IF I_VALUE = MNG_REQ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MNG_REQ;

	FUNCTION IS_MNG_ARB(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 管理する（任意）かどうか
	BEGIN
		IF I_VALUE = MNG_ARB THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MNG_ARB;

	FUNCTION IS_MNG_NOT_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 管理する（任意：在庫対象外）かどうか
	BEGIN
		IF I_VALUE = MNG_NOT_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MNG_NOT_STK;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NOT_MNG
		OR I_VALUE = MNG_REQ
		OR I_VALUE = MNG_ARB
		OR I_VALUE = MNG_NOT_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SNO_MNG_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SNO_MNG_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SNO_MNG_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SNO_MNG_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SNO_MNG_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SNO_MNG_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SNO_MNG_TYP;
