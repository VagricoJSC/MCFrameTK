CREATE OR REPLACE PACKAGE BODY MAC_AC_TABLE_TYP
/*****************************
会計ＩＦテーブル区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION AC_IO RETURN VARCHAR2 DETERMINISTIC IS -- 会計ＩＦ用受払データ
	BEGIN RETURN '1'; END AC_IO;
	FUNCTION AC_STK RETURN VARCHAR2 DETERMINISTIC IS -- 会計ＩＦ用在庫データ
	BEGIN RETURN '2'; END AC_STK;
	FUNCTION AC_COST RETURN VARCHAR2 DETERMINISTIC IS -- 会計ＩＦ用原価データ
	BEGIN RETURN '3'; END AC_COST;
	FUNCTION AC_RCV RETURN VARCHAR2 DETERMINISTIC IS -- 会計ＩＦ用入金データ
	BEGIN RETURN '4'; END AC_RCV;
	FUNCTION AC_PAY RETURN VARCHAR2 DETERMINISTIC IS -- 会計ＩＦ用支払データ
	BEGIN RETURN '5'; END AC_PAY;
	FUNCTION AC_NOTE RETURN VARCHAR2 DETERMINISTIC IS -- 会計ＩＦ用手形データ
	BEGIN RETURN '6'; END AC_NOTE;

	FUNCTION IS_AC_IO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計ＩＦ用受払データかどうか
	BEGIN
		IF I_VALUE = AC_IO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_IO;

	FUNCTION IS_AC_STK(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計ＩＦ用在庫データかどうか
	BEGIN
		IF I_VALUE = AC_STK THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_STK;

	FUNCTION IS_AC_COST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計ＩＦ用原価データかどうか
	BEGIN
		IF I_VALUE = AC_COST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_COST;

	FUNCTION IS_AC_RCV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計ＩＦ用入金データかどうか
	BEGIN
		IF I_VALUE = AC_RCV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_RCV;

	FUNCTION IS_AC_PAY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計ＩＦ用支払データかどうか
	BEGIN
		IF I_VALUE = AC_PAY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_PAY;

	FUNCTION IS_AC_NOTE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 会計ＩＦ用手形データかどうか
	BEGIN
		IF I_VALUE = AC_NOTE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AC_NOTE;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = AC_IO
		OR I_VALUE = AC_STK
		OR I_VALUE = AC_COST
		OR I_VALUE = AC_RCV
		OR I_VALUE = AC_PAY
		OR I_VALUE = AC_NOTE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_AC_TABLE_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_AC_TABLE_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_AC_TABLE_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_AC_TABLE_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_AC_TABLE_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_AC_TABLE_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_AC_TABLE_TYP;
