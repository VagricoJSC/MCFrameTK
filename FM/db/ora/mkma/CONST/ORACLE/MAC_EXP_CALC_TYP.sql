/*****************************
展開計算区分の定数定義パッケージ
*****************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC ; -- 計算対象外
	FUNCTION RQMT RETURN VARCHAR2 DETERMINISTIC ; -- 計算（月次計画）
	FUNCTION MFG RETURN VARCHAR2 DETERMINISTIC ; -- 計算（製造データ）

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 計算対象外であるか
	FUNCTION IS_RQMT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 計算（月次計画）であるか
	FUNCTION IS_MFG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 計算（製造データ）であるか

