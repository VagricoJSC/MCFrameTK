*****************************/
IS

	FUNCTION MNG RETURN VARCHAR2 DETERMINISTIC ; -- 在庫管理する
	FUNCTION NOT_MNG RETURN VARCHAR2 DETERMINISTIC ; -- 在庫管理しない
	FUNCTION PHANTOM RETURN VARCHAR2 DETERMINISTIC ; -- 架空品

	FUNCTION IS_MNG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 在庫管理するであるか
	FUNCTION IS_NOT_MNG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 在庫管理しないであるか
