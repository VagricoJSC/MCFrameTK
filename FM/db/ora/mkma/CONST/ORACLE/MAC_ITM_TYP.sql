	FUNCTION PROD RETURN VARCHAR2 DETERMINISTIC ; -- 製品
	FUNCTION INT_PROD RETURN VARCHAR2 DETERMINISTIC ; -- 中間品
	FUNCTION PART RETURN VARCHAR2 DETERMINISTIC ; -- 部品
	FUNCTION MATERIAL RETURN VARCHAR2 DETERMINISTIC ; -- 資材
	FUNCTION RM RETURN VARCHAR2 DETERMINISTIC ; -- 原料
	FUNCTION PHANTOM RETURN VARCHAR2 DETERMINISTIC ; -- 架空品
	FUNCTION OTHER RETURN VARCHAR2 DETERMINISTIC ; -- その他

