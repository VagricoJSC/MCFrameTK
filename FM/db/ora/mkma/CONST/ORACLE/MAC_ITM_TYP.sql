	FUNCTION IS_PROD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 製品であるか
	FUNCTION IS_INT_PROD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 中間品であるか
	FUNCTION IS_PART(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 部品であるか
	FUNCTION IS_MATERIAL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 資材であるか
	FUNCTION IS_RM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 原料であるか
