CREATE OR REPLACE PACKAGE MAC_DPT_CONFIG_TYP
/*****************************
部門構成区分の定数定義パッケージ
*****************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC ; -- 部門構成対象外
	FUNCTION CONFIG RETURN VARCHAR2 DETERMINISTIC ; -- 部門構成マスタ
	FUNCTION LG_GRP RETURN VARCHAR2 DETERMINISTIC ; -- 物流Ｇ
	FUNCTION LOC_GRP RETURN VARCHAR2 DETERMINISTIC ; -- 製造場所Ｇ
	FUNCTION WG RETURN VARCHAR2 DETERMINISTIC ; -- ＷＧ
	FUNCTION SITE RETURN VARCHAR2 DETERMINISTIC ; -- 工場・物流倉庫

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 部門構成対象外であるか
	FUNCTION IS_CONFIG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 部門構成マスタであるか
	FUNCTION IS_LG_GRP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 物流Ｇであるか
	FUNCTION IS_LOC_GRP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 製造場所Ｇであるか
	FUNCTION IS_WG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- ＷＧであるか
	FUNCTION IS_SITE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 工場・物流倉庫であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) ; -- 定数に含まれるかどうか


	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数名を取得する

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数名を取得する

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- キーから定数備考を取得する

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 値から定数備考を取得する

	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ名を取得する

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2; -- 定数グループ備考を取得する

	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END;
