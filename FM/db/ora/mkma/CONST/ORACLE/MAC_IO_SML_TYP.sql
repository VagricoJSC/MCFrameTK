/*****************************
受払集計単位区分の定数定義パッケージ
*****************************/
IS

	FUNCTION IO_TGT RETURN VARCHAR2 DETERMINISTIC ; -- 受払対象単位
	FUNCTION AC_SLIP RETURN VARCHAR2 DETERMINISTIC ; -- 受払対象・会計伝票単位
	FUNCTION AC_RSN RETURN VARCHAR2 DETERMINISTIC ; -- 受払対象・会計伝票・会計理由単位

	FUNCTION IS_IO_TGT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 受払対象単位であるか
	FUNCTION IS_AC_SLIP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 受払対象・会計伝票単位であるか
