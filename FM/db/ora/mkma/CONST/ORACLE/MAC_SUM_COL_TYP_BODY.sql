CREATE OR REPLACE PACKAGE BODY MAC_SUM_COL_TYP
/*****************************
集計項目区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION SUM0 RETURN VARCHAR2 DETERMINISTIC IS -- 集計ＣＤ０
	BEGIN RETURN '110'; END SUM0;
	FUNCTION SUM1 RETURN VARCHAR2 DETERMINISTIC IS -- 集計ＣＤ１
	BEGIN RETURN '111'; END SUM1;
	FUNCTION SUM2 RETURN VARCHAR2 DETERMINISTIC IS -- 集計ＣＤ２
	BEGIN RETURN '112'; END SUM2;
	FUNCTION SUM3 RETURN VARCHAR2 DETERMINISTIC IS -- 集計ＣＤ３
	BEGIN RETURN '113'; END SUM3;
	FUNCTION SUM4 RETURN VARCHAR2 DETERMINISTIC IS -- 集計ＣＤ４
	BEGIN RETURN '114'; END SUM4;
	FUNCTION SUM5 RETURN VARCHAR2 DETERMINISTIC IS -- 集計ＣＤ５
	BEGIN RETURN '115'; END SUM5;
	FUNCTION PROJ RETURN VARCHAR2 DETERMINISTIC IS -- プロジェクトＣＤ
	BEGIN RETURN '120'; END PROJ;

	FUNCTION IS_SUM0(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計ＣＤ０かどうか
	BEGIN
		IF I_VALUE = SUM0 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUM0;

	FUNCTION IS_SUM1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計ＣＤ１かどうか
	BEGIN
		IF I_VALUE = SUM1 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUM1;

	FUNCTION IS_SUM2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計ＣＤ２かどうか
	BEGIN
		IF I_VALUE = SUM2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUM2;

	FUNCTION IS_SUM3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計ＣＤ３かどうか
	BEGIN
		IF I_VALUE = SUM3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUM3;

	FUNCTION IS_SUM4(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計ＣＤ４かどうか
	BEGIN
		IF I_VALUE = SUM4 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUM4;

	FUNCTION IS_SUM5(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 集計ＣＤ５かどうか
	BEGIN
		IF I_VALUE = SUM5 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SUM5;

	FUNCTION IS_PROJ(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- プロジェクトＣＤかどうか
	BEGIN
		IF I_VALUE = PROJ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PROJ;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SUM0
		OR I_VALUE = SUM1
		OR I_VALUE = SUM2
		OR I_VALUE = SUM3
		OR I_VALUE = SUM4
		OR I_VALUE = SUM5
		OR I_VALUE = PROJ THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SUM_COL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SUM_COL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SUM_COL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SUM_COL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SUM_COL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SUM_COL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SUM_COL_TYP;
