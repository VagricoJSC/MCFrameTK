CREATE OR REPLACE PACKAGE BODY MAC_APRV_STS_TYP
/*****************************
承認状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION OPN RETURN VARCHAR2 DETERMINISTIC IS -- 未承認
	BEGIN RETURN '1'; END OPN;
	FUNCTION FIX RETURN VARCHAR2 DETERMINISTIC IS -- 一次承認済
	BEGIN RETURN '2'; END FIX;
	FUNCTION ACPT RETURN VARCHAR2 DETERMINISTIC IS -- 最終承認済
	BEGIN RETURN '9'; END ACPT;
	FUNCTION RJCT RETURN VARCHAR2 DETERMINISTIC IS -- 却下
	BEGIN RETURN 'C'; END RJCT;
	FUNCTION LAST_RJCT RETURN VARCHAR2 DETERMINISTIC IS -- 否認
	BEGIN RETURN 'X'; END LAST_RJCT;

	FUNCTION IS_OPN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 未承認かどうか
	BEGIN
		IF I_VALUE = OPN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_OPN;

	FUNCTION IS_FIX(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 一次承認済かどうか
	BEGIN
		IF I_VALUE = FIX THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FIX;

	FUNCTION IS_ACPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 最終承認済かどうか
	BEGIN
		IF I_VALUE = ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACPT;

	FUNCTION IS_RJCT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 却下かどうか
	BEGIN
		IF I_VALUE = RJCT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RJCT;

	FUNCTION IS_LAST_RJCT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 否認かどうか
	BEGIN
		IF I_VALUE = LAST_RJCT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_LAST_RJCT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = OPN
		OR I_VALUE = FIX
		OR I_VALUE = ACPT
		OR I_VALUE = RJCT
		OR I_VALUE = LAST_RJCT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_APRV_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_APRV_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_APRV_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_APRV_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_APRV_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_APRV_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_APRV_STS_TYP;
