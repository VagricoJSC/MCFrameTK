	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = CALC_ITM
		OR I_VALUE = ITM_DTL
		OR I_VALUE = ITM_OPER
		OR I_VALUE = BOM
		OR I_VALUE = ITM_WK
		OR I_VALUE = ITM_PURC
		OR I_VALUE = ITM_PROC
		OR I_VALUE = ITM_PROV
		OR I_VALUE = ITM_SLS
		OR I_VALUE = ITM_FIX
		OR I_VALUE = ALC_RATE_M
		OR I_VALUE = ALC_PTN_SEL
		OR I_VALUE = PRE_ALC_RATE_SEL
		OR I_VALUE = ALC_AMT
		OR I_VALUE = ALC_RATE_T
		OR I_VALUE = PRE_RATE_TERM
		OR I_VALUE = PRE_RATE_MLY
		OR I_VALUE = RQMT
		OR I_VALUE = MFG
		OR I_VALUE = PURC
		OR I_VALUE = SLS
		OR I_VALUE = INPT
		OR I_VALUE = WK
		OR I_VALUE = OTHER_WK
		OR I_VALUE = IO
		OR I_VALUE = INST_WIP
		OR I_VALUE = END_STK
		OR I_VALUE = GP_ALC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

