Declare
	TYPE tab IS TABLE OF VARCHAR2(20)
	INDEX BY PLS_INTEGER;
	
	submodule	tab;
	submodule2	tab;
	submodule3	tab;
	T_MODULE	VARCHAR2(20);
	T_SUB_RID	VARCHAR2(50);
	T_SEQ		NUMBER;
	T_CNT		NUMBER;
	
	FUNCTION F_GET_OR_CRT_ROLE(I_ROLE_ID IN VARCHAR2)
	RETURN VARCHAR2
	IS
		T_CNT_R		NUMBER;
	BEGIN
		SELECT COUNT(*) INTO T_CNT_R FROM FCM_ROLE_ALL WHERE RID = I_ROLE_ID;
		IF T_CNT_R = 0 THEN
			INSERT INTO FCM_ROLE_ALL (RID,RNM,HISTORY) VALUES (I_ROLE_ID,I_ROLE_ID,'0');
		END IF;
		RETURN I_ROLE_ID;
	END;
BEGIN
	--モジュールID定義
	T_MODULE := 'FS';
	T_CNT := 1;
	
	-- サブモジュールIDのコレクションを定義
	submodule(1) := 'FSBAP';
	submodule(2) := 'FSBCP';
	submodule(3) := 'FSBDP';
	submodule(4) := 'FSBFP';
	submodule(5) := 'FSBGP';
	submodule(6) := 'FSBIP';
	submodule(7) := 'FSBEP';
	submodule(8) := 'FSBHP';
	submodule(9) := 'FSUCP';
	
	-- 最初にモジュールに紐付くロールアイテムを削除する
	DELETE FCM_ROLEITEM WHERE ACTYPE LIKE T_MODULE || '.FS__P%' OR ACTYPE LIKE T_MODULE || '.FS__L%';
	
	WHILE(T_CNT <= submodule.count) LOOP
		
		-- 参照権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule(T_CNT) || '_SHOW' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.show','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.srch*','0');
		IF submodule(T_CNT) = 'FSBFP' THEN
			SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
			-- ロール管理(管理者)
			INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
				VALUES (T_SEQ,T_SUB_RID,'3','FS.FSBFP0030.*','0');
			SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
			-- ユーザ管理(管理者)
			INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
				VALUES (T_SEQ,T_SUB_RID,'3','FS.FSBFP0250.*','0');
		END IF;
		
		--更新権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule(T_CNT) || '_REG' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.show','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.srch*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.upd*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.ins*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.del*','0');
		IF submodule(T_CNT) = 'FSBFP' THEN
			SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
			-- ロール管理(管理者)
			INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
				VALUES (T_SEQ,T_SUB_RID,'3','FS.FSBFP0030.*','0');
			SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
			-- ユーザ管理(管理者)
			INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
				VALUES (T_SEQ,T_SUB_RID,'3','FS.FSBFP0250.*','0');
		END IF;
		
		-- 出力権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule(T_CNT) || '_OUT' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.prnt*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.popup_out*','0');
		IF submodule(T_CNT) = 'FSBFP' THEN
			SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
			-- ロール管理(管理者)
			INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
				VALUES (T_SEQ,T_SUB_RID,'3','FS.FSBFP0030.*','0');
			SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
			-- ユーザ管理(管理者)
			INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
				VALUES (T_SEQ,T_SUB_RID,'3','FS.FSBFP0250.*','0');
		END IF;
		
		T_CNT := T_CNT + 1;
	END LOOP;
	
	-- 出力権限のみ設定
	submodule2(1) := 'FSBBP';
	submodule2(2) := 'FSUAP';
	
	T_CNT := 1;
	WHILE(T_CNT <= submodule2.count) LOOP
		-- 出力権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule2(T_CNT) || '_OUT' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW)
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule2(T_CNT) || '*.prnt*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW)
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule2(T_CNT) || '*.popup_out*','0');
		
		T_CNT := T_CNT + 1;
	END LOOP;
	
	-- 最初にモジュールに紐付くロールアイテムを削除する
	T_MODULE := 'FX';
	DELETE FCM_ROLEITEM WHERE ACTYPE LIKE T_MODULE || '.FX__P%' OR ACTYPE LIKE T_MODULE || '.FX__L%';
	
	-- 出力権限のみ設定
	submodule3(1) := 'FXUCP';
	
	T_CNT := 1;
	
	WHILE(T_CNT <= submodule3.count) LOOP
		-- 出力権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule3(T_CNT) || '_OUT' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW)
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule3(T_CNT) || '*.prnt*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW)
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule3(T_CNT) || '*.popup_out*','0');
		
		T_CNT := T_CNT + 1;
	END LOOP;
	
END;
