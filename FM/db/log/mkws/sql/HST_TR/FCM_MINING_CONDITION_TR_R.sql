			COL_ID,
			COL_NM,
			LIST_ORDER,
			SCR_ITM_ID,
			MD_ITM_ID,
			DATA_TYP,
			REQUIRE_FLG,
			INIT_VAL,
			EDITABLE_FLG,
			INS_USR_ID,
			INS_USR_NM,
			INS_TS,
			INS_FUNC_ID,
			UPD_CNTR,
			UPD_USR_ID,
			UPD_USR_NM,
			UPD_TS,
