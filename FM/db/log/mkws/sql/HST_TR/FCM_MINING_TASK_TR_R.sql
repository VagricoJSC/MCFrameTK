SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER FCM_MINING_TASK_TR_R
AFTER INSERT OR DELETE OR UPDATE
ON FCM_MINING_TASK
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
BEGIN
DECLARE
	H_ID FCT_HST_HEADER.HST_ID%TYPE;
	A_ID FCT_OPRHISTORY.ACTION_ID%TYPE;
	H_TYP FCT_HST_HEADER.HST_TYPE%TYPE;
	H_TAB FCT_HST_HEADER.TABLE_NAME%TYPE;
	U_ID FCM_USER.USER_ID%TYPE;
	COCD FCT_HST_HEADER.CO_CD%TYPE;
	EX_1 FCT_HST_HEADER.EXT_ATTR1%TYPE ;
	EX_2 FCT_HST_HEADER.EXT_ATTR2%TYPE ;
	EX_3 FCT_HST_HEADER.EXT_ATTR3%TYPE ;
	RDATE DATE;
BEGIN
	H_TAB := 'FCM_MINING_TASK_R';
	A_ID := FCPA_CONTEXT.F_GET_ACTION_ID;
	U_ID := NVL(FCPA_CONTEXT.F_GET_USERID, FCPA_CONTEXT.F_GET_OS_USR);
	COCD := FCPA_CONTEXT.F_GET_CO_CD;
	EX_1 := FCPA_CONTEXT.F_GET_EXT_ATTR1;
	EX_2 := FCPA_CONTEXT.F_GET_EXT_ATTR2;
	EX_3 := FCPA_CONTEXT.F_GET_EXT_ATTR3;
	RDATE := FCPA_DATE_UTIL.F_MCSYSDATE;
	IF INSERTING THEN
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		H_TYP := 'I';
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCM_MINING_TASK_R (
			HST_ID,
			HST_TYPE,
			TASK_ID,
			TASK_NM,
			TASK_TYP,
			MINING_ID,
			USER_ID,
			CO_CD,
			INV_FLG,
			INS_USR_ID,
			INS_USR_NM,
			INS_TS,
			INS_FUNC_ID,
			UPD_CNTR,
			UPD_USR_ID,
			UPD_USR_NM,
			UPD_TS,
			UPD_FUNC_ID,
			UPD_SRV_REQ_NO
		)
			VALUES (
				H_ID,
				H_TYP,
				:NEW.TASK_ID,
				:NEW.TASK_NM,
				:NEW.TASK_TYP,
				:NEW.MINING_ID,
				:NEW.USER_ID,
				:NEW.CO_CD,
				:NEW.INV_FLG,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_TS,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_CNTR,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_TS,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
		);
	ELSIF UPDATING THEN
--keyに変更があるかどうかの判定
--keyに変更がある場合
		IF :OLD.TASK_ID <> :NEW.TASK_ID THEN
			SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
			H_TYP := 'D';
			INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
				VALUES (
					H_ID,
					H_TAB,
					H_ID,
					A_ID,
					H_TYP,
					RDATE,
					U_ID,
					COCD,
					EX_1,
					EX_2,
					EX_3
			);
			INSERT INTO FCM_MINING_TASK_R (
				HST_ID,
				HST_TYPE,
				TASK_ID,
				TASK_NM,
				TASK_TYP,
				MINING_ID,
				USER_ID,
				CO_CD,
				INV_FLG,
				INS_USR_ID,
				INS_USR_NM,
				INS_TS,
				INS_FUNC_ID,
				UPD_CNTR,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_TS,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)
				VALUES (
					H_ID,
					H_TYP,
					:OLD.TASK_ID,
					:OLD.TASK_NM,
					:OLD.TASK_TYP,
					:OLD.MINING_ID,
					:OLD.USER_ID,
					:OLD.CO_CD,
					:OLD.INV_FLG,
					:OLD.INS_USR_ID,
					:OLD.INS_USR_NM,
					:OLD.INS_TS,
					:OLD.INS_FUNC_ID,
					:OLD.UPD_CNTR,
					:OLD.UPD_USR_ID,
					:OLD.UPD_USR_NM,
					:OLD.UPD_TS,
					:OLD.UPD_FUNC_ID,
					:OLD.UPD_SRV_REQ_NO
			);
			H_TYP := 'I';
		ELSE
			H_TYP := 'U';
		END IF;
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCM_MINING_TASK_R (
			HST_ID,
			HST_TYPE,
			TASK_ID,
			TASK_NM,
			TASK_TYP,
			MINING_ID,
			USER_ID,
			CO_CD,
			INV_FLG,
			INS_USR_ID,
			INS_USR_NM,
			INS_TS,
			INS_FUNC_ID,
			UPD_CNTR,
			UPD_USR_ID,
			UPD_USR_NM,
			UPD_TS,
			UPD_FUNC_ID,
			UPD_SRV_REQ_NO
		)
			VALUES (
				H_ID,
				H_TYP,
				:NEW.TASK_ID,
				:NEW.TASK_NM,
				:NEW.TASK_TYP,
				:NEW.MINING_ID,
				:NEW.USER_ID,
				:NEW.CO_CD,
				:NEW.INV_FLG,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_TS,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_CNTR,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_TS,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
		);
	ELSIF DELETING THEN
		H_TYP := 'D';
		SELECT FCS_HISTORY.NEXTVAL INTO H_ID FROM DUAL;
		INSERT INTO FCT_HST_HEADER (HST_ID,TABLE_NAME,KEY_ID,ACTION_ID,HST_TYPE,HST_TIME,HST_USER_ID,CO_CD,EXT_ATTR1,EXT_ATTR2,EXT_ATTR3)
			VALUES (
				H_ID,
				H_TAB,
				H_ID,
				A_ID,
				H_TYP,
				RDATE,
				U_ID,
				COCD,
				EX_1,
				EX_2,
				EX_3
		);
		INSERT INTO FCM_MINING_TASK_R (
			HST_ID,
			HST_TYPE,
			TASK_ID,
			TASK_NM,
			TASK_TYP,
			MINING_ID,
			USER_ID,
			CO_CD,
			INV_FLG,
			INS_USR_ID,
			INS_USR_NM,
			INS_TS,
			INS_FUNC_ID,
			UPD_CNTR,
			UPD_USR_ID,
			UPD_USR_NM,
			UPD_TS,
			UPD_FUNC_ID,
			UPD_SRV_REQ_NO
		)
			VALUES (
				H_ID,
				H_TYP,
				:OLD.TASK_ID,
				:OLD.TASK_NM,
				:OLD.TASK_TYP,
				:OLD.MINING_ID,
				:OLD.USER_ID,
				:OLD.CO_CD,
				:OLD.INV_FLG,
				:OLD.INS_USR_ID,
				:OLD.INS_USR_NM,
				:OLD.INS_TS,
				:OLD.INS_FUNC_ID,
				:OLD.UPD_CNTR,
				:OLD.UPD_USR_ID,
				:OLD.UPD_USR_NM,
				:OLD.UPD_TS,
				:OLD.UPD_FUNC_ID,
				:OLD.UPD_SRV_REQ_NO
		);
	END IF;
END;
END;

/
show errors;



ALTER TRIGGER FCM_MINING_TASK_TR_R DISABLE
/
