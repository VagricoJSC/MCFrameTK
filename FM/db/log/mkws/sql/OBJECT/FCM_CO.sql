SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW FCM_CO(
	CO_CD,
	CO_NM,
	DEF_LOCALE_CD,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CO_CD,
	LCL.CO_NM,
	ORG.DEF_LOCALE_CD,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	FCM_CO_ALL ORG,
	fcm_co_lcl_all LCL
WHERE
	0 = 0
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)

;

