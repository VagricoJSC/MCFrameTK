	FUNCTION IS_Client(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- クライアント印刷であるか
	FUNCTION IS_Retry(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- クライアント再印刷であるか
	FUNCTION IS_File_Donwload(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- ファイルダウンロードであるか
	FUNCTION IS_Unknown(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 不明であるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) ; -- 定数に含まれるかどうか
