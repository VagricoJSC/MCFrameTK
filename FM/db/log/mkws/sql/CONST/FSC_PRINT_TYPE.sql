CREATE OR REPLACE PACKAGE BODY FSC_PRINT_TYPE
/*****************************
印刷タイプの定数定義パッケージ本体
******************************/
IS

	FUNCTION Client_Server RETURN VARCHAR2 DETERMINISTIC IS -- クライアント－サーバ印刷
	BEGIN RETURN '1'; END Client_Server;
	FUNCTION Server RETURN VARCHAR2 DETERMINISTIC IS -- サーバ印刷
	BEGIN RETURN '3'; END Server;
	FUNCTION Client RETURN VARCHAR2 DETERMINISTIC IS -- クライアント印刷
	BEGIN RETURN '4'; END Client;
	FUNCTION Retry RETURN VARCHAR2 DETERMINISTIC IS -- クライアント再印刷
	BEGIN RETURN '5'; END Retry;
	FUNCTION File_Donwload RETURN VARCHAR2 DETERMINISTIC IS -- ファイルダウンロード
	BEGIN RETURN '6'; END File_Donwload;
	FUNCTION Unknown RETURN VARCHAR2 DETERMINISTIC IS -- 不明
	BEGIN RETURN '99'; END Unknown;

	FUNCTION IS_Client_Server(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- クライアント－サーバ印刷かどうか
	BEGIN
		IF I_VALUE = Client_Server THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Client_Server;

	FUNCTION IS_Server(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- サーバ印刷かどうか
	BEGIN
		IF I_VALUE = Server THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Server;

	FUNCTION IS_Client(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- クライアント印刷かどうか
	BEGIN
		IF I_VALUE = Client THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Client;

	FUNCTION IS_Retry(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- クライアント再印刷かどうか
	BEGIN
		IF I_VALUE = Retry THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Retry;

	FUNCTION IS_File_Donwload(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ファイルダウンロードかどうか
	BEGIN
		IF I_VALUE = File_Donwload THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_File_Donwload;

	FUNCTION IS_Unknown(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 不明かどうか
	BEGIN
		IF I_VALUE = Unknown THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_Unknown;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = Client_Server
		OR I_VALUE = Server
		OR I_VALUE = Client
		OR I_VALUE = Retry
		OR I_VALUE = File_Donwload
		OR I_VALUE = Unknown THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_PRINT_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_PRINT_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_PRINT_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_PRINT_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_PRINT_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_PRINT_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_PRINT_TYPE;

/
show errors;


