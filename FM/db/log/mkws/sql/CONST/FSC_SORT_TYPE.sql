CREATE OR REPLACE PACKAGE BODY FSC_SORT_TYPE
/*****************************
ソートタイプの定数定義パッケージ本体
******************************/
IS

	FUNCTION TYPE_ASC RETURN VARCHAR2 DETERMINISTIC IS -- 昇順
	BEGIN RETURN 'ASC'; END TYPE_ASC;
	FUNCTION TYPE_DESC RETURN VARCHAR2 DETERMINISTIC IS -- 降順
	BEGIN RETURN 'DESC'; END TYPE_DESC;
	FUNCTION TYPE_ASC_NULL_AHEAD RETURN VARCHAR2 DETERMINISTIC IS -- 昇順（空白優先）
	BEGIN RETURN 'ASC_NULL_AHEAD'; END TYPE_ASC_NULL_AHEAD;
	FUNCTION TYPE_DESC_NULL_AHEAD RETURN VARCHAR2 DETERMINISTIC IS -- 降順（空白優先）
	BEGIN RETURN 'DESC_NULL_AHEAD'; END TYPE_DESC_NULL_AHEAD;

	FUNCTION IS_TYPE_ASC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 昇順かどうか
	BEGIN
		IF I_VALUE = TYPE_ASC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_ASC;

	FUNCTION IS_TYPE_DESC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 降順かどうか
	BEGIN
		IF I_VALUE = TYPE_DESC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_DESC;

	FUNCTION IS_TYPE_ASC_NULL_AHEAD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 昇順（空白優先）かどうか
	BEGIN
		IF I_VALUE = TYPE_ASC_NULL_AHEAD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_ASC_NULL_AHEAD;

	FUNCTION IS_TYPE_DESC_NULL_AHEAD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 降順（空白優先）かどうか
	BEGIN
		IF I_VALUE = TYPE_DESC_NULL_AHEAD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TYPE_DESC_NULL_AHEAD;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = TYPE_ASC
		OR I_VALUE = TYPE_DESC
		OR I_VALUE = TYPE_ASC_NULL_AHEAD
		OR I_VALUE = TYPE_DESC_NULL_AHEAD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('FSC_SORT_TYPE', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('FSC_SORT_TYPE', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('FSC_SORT_TYPE', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('FSC_SORT_TYPE', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('FSC_SORT_TYPE', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('FSC_SORT_TYPE', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END FSC_SORT_TYPE;

/
show errors;


