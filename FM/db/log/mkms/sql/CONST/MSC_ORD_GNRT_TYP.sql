CREATE OR REPLACE PACKAGE BODY MSC_ORD_GNRT_TYP
/*****************************
オーダ生成区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION MRP RETURN VARCHAR2 DETERMINISTIC IS -- ＭＲＰ
	BEGIN RETURN '1'; END MRP;
	FUNCTION MNL RETURN VARCHAR2 DETERMINISTIC IS -- マニュアル計画
	BEGIN RETURN '2'; END MNL;
	FUNCTION PRCD RETURN VARCHAR2 DETERMINISTIC IS -- 先行手配
	BEGIN RETURN '3'; END PRCD;
	FUNCTION SIM RETURN VARCHAR2 DETERMINISTIC IS -- シミュレーション
	BEGIN RETURN '4'; END SIM;
	FUNCTION UPLND RETURN VARCHAR2 DETERMINISTIC IS -- 計画外
	BEGIN RETURN '5'; END UPLND;

	FUNCTION IS_MRP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- ＭＲＰかどうか
	BEGIN
		IF I_VALUE = MRP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MRP;

	FUNCTION IS_MNL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- マニュアル計画かどうか
	BEGIN
		IF I_VALUE = MNL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_MNL;

	FUNCTION IS_PRCD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 先行手配かどうか
	BEGIN
		IF I_VALUE = PRCD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PRCD;

	FUNCTION IS_SIM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- シミュレーションかどうか
	BEGIN
		IF I_VALUE = SIM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SIM;

	FUNCTION IS_UPLND(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 計画外かどうか
	BEGIN
		IF I_VALUE = UPLND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_UPLND;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = MRP
		OR I_VALUE = MNL
		OR I_VALUE = PRCD
		OR I_VALUE = SIM
		OR I_VALUE = UPLND THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_ORD_GNRT_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_ORD_GNRT_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_ORD_GNRT_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_ORD_GNRT_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_ORD_GNRT_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_ORD_GNRT_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_ORD_GNRT_TYP;

/
show errors;


