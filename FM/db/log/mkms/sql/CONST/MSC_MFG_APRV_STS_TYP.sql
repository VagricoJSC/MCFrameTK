CREATE OR REPLACE PACKAGE BODY MSC_MFG_APRV_STS_TYP
/*****************************
製造承認状況区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION INST_OPN RETURN VARCHAR2 DETERMINISTIC IS -- 指図未承認
	BEGIN RETURN '1'; END INST_OPN;
	FUNCTION INST_ACPT RETURN VARCHAR2 DETERMINISTIC IS -- 指図承認済
	BEGIN RETURN '2'; END INST_ACPT;
	FUNCTION ACT_OPN RETURN VARCHAR2 DETERMINISTIC IS -- 記録未承認
	BEGIN RETURN '3'; END ACT_OPN;
	FUNCTION ACT_ACPT RETURN VARCHAR2 DETERMINISTIC IS -- 記録承認済
	BEGIN RETURN '4'; END ACT_ACPT;

	FUNCTION IS_INST_OPN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指図未承認かどうか
	BEGIN
		IF I_VALUE = INST_OPN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INST_OPN;

	FUNCTION IS_INST_ACPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 指図承認済かどうか
	BEGIN
		IF I_VALUE = INST_ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_INST_ACPT;

	FUNCTION IS_ACT_OPN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 記録未承認かどうか
	BEGIN
		IF I_VALUE = ACT_OPN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACT_OPN;

	FUNCTION IS_ACT_ACPT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 記録承認済かどうか
	BEGIN
		IF I_VALUE = ACT_ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACT_ACPT;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = INST_OPN
		OR I_VALUE = INST_ACPT
		OR I_VALUE = ACT_OPN
		OR I_VALUE = ACT_ACPT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION STATE_ORDER(
		I_MFG_APRV_STS_TYP IN VARCHAR2
	)RETURN NUMBER
	 DETERMINISTIC IS
	BEGIN
		IF (I_MFG_APRV_STS_TYP = INST_OPN) THEN
			RETURN 1;
		ELSIF (I_MFG_APRV_STS_TYP = INST_ACPT) THEN
			RETURN 2;
		ELSIF (I_MFG_APRV_STS_TYP = ACT_OPN) THEN
			RETURN 3;
		ELSIF (I_MFG_APRV_STS_TYP = ACT_ACPT) THEN
			RETURN 4;
		ELSE
			RETURN NULL;
		END IF;
	END STATE_ORDER;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MSC_MFG_APRV_STS_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MSC_MFG_APRV_STS_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MSC_MFG_APRV_STS_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MSC_MFG_APRV_STS_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MSC_MFG_APRV_STS_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MSC_MFG_APRV_STS_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MSC_MFG_APRV_STS_TYP;

/
