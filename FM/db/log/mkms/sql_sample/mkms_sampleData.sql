SET DEFINE OFF
SET SQLBLANKLINES ON

Declare
	TYPE tab IS TABLE OF VARCHAR2(20)
	INDEX BY PLS_INTEGER;
	
	submodule	tab;
	submodule2	tab;
	T_MODULE	VARCHAR2(20);
	T_FULL_RID	VARCHAR2(50);
	T_SUB_RID	VARCHAR2(50);
	T_SEQ		NUMBER;
	T_CNT		NUMBER;
	
	FUNCTION F_GET_OR_CRT_ROLE(I_ROLE_ID IN VARCHAR2)
	RETURN VARCHAR2
	IS
		T_CNT_R		NUMBER;
	BEGIN
		SELECT COUNT(*) INTO T_CNT_R FROM FCM_ROLE_ALL WHERE RID = I_ROLE_ID;
		IF T_CNT_R = 0 THEN
			IF I_ROLE_ID = 'FULL' THEN
				INSERT INTO FCM_ROLE_ALL (RID,RNM,HISTORY,ADMIN_FLG) VALUES (I_ROLE_ID,I_ROLE_ID,'0','1');
			ELSE
				INSERT INTO FCM_ROLE_ALL (RID,RNM,HISTORY) VALUES (I_ROLE_ID,I_ROLE_ID,'0');
			END IF;
		END IF;
		RETURN I_ROLE_ID;
	END;
BEGIN
	--モジュールID定義
	T_MODULE := 'MS';
	T_CNT := 1;
	
	-- サブモジュールIDのコレクションを定義
	submodule(1) := 'MSBA';
	submodule(2) := 'MSBB';
	submodule(3) := 'MSBC';
	submodule(4) := 'MSBD';
	submodule(5) := 'MSBE';
	submodule(6) := 'MSBF';
	submodule(7) := 'MSBG';
	submodule(8) := 'MSBH';
	submodule(9) := 'MSBI';
	submodule(10) := 'MSLA';
	submodule(11) := 'MSLC';
	
	-- 最初にモジュールに紐付くロールアイテムを削除する
	delete FCM_ROLEITEM where ACTYPE like T_MODULE || '.MS__P%' OR ACTYPE like T_MODULE || '.MS__L%';
	
	WHILE(T_CNT <= submodule.count) LOOP
		
		-- 参照権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule(T_CNT) || '_SHOW' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.show','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.srch*','0');
		
		--更新権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule(T_CNT) || '_REG' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.show','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.srch*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.upd*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.ins*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.del*','0');
			
		-- 出力権限データ追加
		T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || submodule(T_CNT) || '_OUT' );
		DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.prnt*','0');
		SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
		INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
			VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || submodule(T_CNT) || '*.popup_out*','0');
		
		T_CNT := T_CNT + 1;
	END LOOP;
	
	-- MSUA（参照権限と出力権限のみ設定）
	-- 参照権限データ追加
	T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || 'MSUAP' || '_SHOW' );
	DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
	SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
	INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
		VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || 'MSUAP' || '*.show','0');
	SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
	INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
		VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || 'MSUAP' || '*.srch*','0');
	
	-- 出力権限データ追加
	T_SUB_RID := F_GET_OR_CRT_ROLE(T_MODULE || '_' || 'MSUAP' || '_OUT' );
	DELETE FCM_ROLEITEM WHERE RID = T_SUB_RID;
	SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
	INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
		VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || 'MSUAP' || '*.prnt*','0');
	SELECT FCS_ROLEITEM.NEXTVAL INTO T_SEQ FROM DUAL;
	INSERT INTO FCM_ROLEITEM (IID,RID,TYPE_CD,ACTYPE,CHK_PW) 
		VALUES (T_SEQ,T_SUB_RID,'0',T_MODULE || '.' || 'MSUAP' || '*.popup_out*','0');
	
END;

/
show errors;


SET DEFINE ON
