CREATE OR REPLACE PACKAGE BODY MSPA_BOM
IS
	G_ALT_GRP_SEQ	NUMBER ;
	TYPE G_ALT_GRP_SEQ_INNER_ARRAY_TYPE IS TABLE OF NUMBER INDEX BY VARCHAR2(55 CHAR) ;
	TYPE G_ALT_GRP_SEQ_ARRAY_TYPE IS TABLE OF G_ALT_GRP_SEQ_INNER_ARRAY_TYPE INDEX BY MSW_BOM_EXP_RSLT.ALT_GRP_CD%TYPE ;
	G_ALT_GRP_SEQ_ARRAY G_ALT_GRP_SEQ_ARRAY_TYPE;
	TYPE G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY_TYPE IS TABLE OF NUMBER INDEX BY MSW_BOM_EXP_RSLT.ALT_GRP_CD%TYPE ;
	G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY_TYPE ;

	PROCEDURE P_EX_PH (
		I_PH_BOM 	IN MSW_BOM_EXP_RSLT%ROWTYPE,
		I_BOM_PTN	IN MAPA_META.BOM_PTN%TYPE,
		I_BASE_DT	IN MAPA_META.DT%TYPE,
		I_ALL_OPER_NULL_FLG	IN MAPA_META.FLG%TYPE -- これまでの全ての階層において工程がNULLであったかどうか
	)
	/*********************************************************
	<SYNOPSIS>
		ファントム品の展開処理
	<REMARKS>
	<ARGUMENTS>
	<HISTORY>
	**********************************************************/
	IS
		L_REC_BOM MSW_BOM_EXP_RSLT%ROWTYPE;
		L_ALT_GRP_CD	MSW_BOM_EXP_RSLT.ALT_GRP_CD%TYPE ;
		L_ALT_ITM_FLG	MSW_BOM_EXP_RSLT.ALT_ITM_FLG%TYPE ;
		L_ALL_OPER_NULL_FLG	MAPA_META.FLG%TYPE;
		L_ALT_GRP_SEQ	NUMBER ;
		L_ALT_GRP_SEQ_ARRAY_KEY VARCHAR2(128);
		L_PREVIOUS_LEVEL_ALT_GRP_SEQ_ARRAY	G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY_TYPE;
	BEGIN
		-- これまでの階層において採番した代替G連番
		L_PREVIOUS_LEVEL_ALT_GRP_SEQ_ARRAY := G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY;
		FOR x IN (
			SELECT
				I_PH_BOM.PEG_NO,
				DECODE(T2.ALT_ITM_FLG, '0', T2.BOM_KEY, NULL) AS BOM_KEY,
				I_PH_BOM.ITM_ORD_NO,
				T2.PAR_ITM_CD,
				T2.PAR_ITM_SUB1,
				T2.PAR_ITM_SUB2,
				T2.PAR_ITM_SUB3,
				T2.CHD_ITM_CD AS ITM_CD,
				T2.CHD_ITM_SUB1 AS ITM_SUB1,
				T2.CHD_ITM_SUB2 AS ITM_SUB2,
				T2.CHD_ITM_SUB3 AS ITM_SUB3,
				T2.VER_NO,
				T2.PAR_INST_QTY,
				DECODE(T2.PAR_INST_QTY, 0, 0, I_PH_BOM.CHD_RQMT_QTY * T2.CHD_RQMT_QTY / T2.PAR_INST_QTY) AS CHD_RQMT_QTY,
				DECODE(T2.PAR_INST_QTY, 0, 0, I_PH_BOM.CHD_INPT_QTY * T2.CHD_INPT_QTY / T2.PAR_INST_QTY) AS CHD_INPT_QTY,
				DECODE(T2.PAR_INST_QTY, 0, T2.FXD_CHD_RQMT_QTY, I_PH_BOM.FXD_CHD_RQMT_QTY * T2.CHD_RQMT_QTY / T2.PAR_INST_QTY + T2.FXD_CHD_RQMT_QTY) AS FXD_CHD_RQMT_QTY,
				T2.CHD_RQMT_RATIO,
				T2.CHD_INPT_RATIO,
				I_PH_BOM.RQMT_QTY * T2.CHD_RQMT_QTY / T2.PAR_INST_QTY + T2.FXD_CHD_RQMT_QTY AS RQMT_QTY,
				I_PH_BOM.RQMT_QTY * T2.CHD_RQMT_QTY / T2.PAR_INST_QTY AS LOSS_RQMT_QTY,
				I_PH_BOM.RQMT_QTY * T2.CHD_INPT_QTY / T2.PAR_INST_QTY AS INPT_QTY,
				T2.FXD_CHD_RQMT_QTY AS FXD_RQMT_QTY,
				T2.ALT_ITM_FLG,
				T2.ALT_GRP_CD,
				T2.ALT_ITM_TYP,
				T2.ALT_ITM_RATIO,
				T2.ALT_ALLOC_PRIO,
				DECODE(T2.PH_FLG, '1', I_PH_BOM.SNO1,
					DECODE(T2.SNO_TYP1, MAC_SNO_TYP.EXTND, I_PH_BOM.SNO1, MAC_SNO_TYP.EXTND_NULL, I_PH_BOM.SNO1, MAC_STR.NULL_VAL)
				) AS SNO1,
				T2.SNO_TYP1,
				DECODE(T2.PH_FLG, '1', I_PH_BOM.SNO2,
					DECODE(T2.SNO_TYP2, MAC_SNO_TYP.EXTND, I_PH_BOM.SNO2, MAC_SNO_TYP.EXTND_NULL, I_PH_BOM.SNO2, MAC_STR.NULL_VAL)
				) AS SNO2,
				T2.SNO_TYP2,
				DECODE(T2.PH_FLG, '1', I_PH_BOM.SNO3,
					DECODE(T2.SNO_TYP3, MAC_SNO_TYP.EXTND, I_PH_BOM.SNO3, MAC_SNO_TYP.EXTND_NULL, I_PH_BOM.SNO3, MAC_STR.NULL_VAL)
				) AS SNO3,
				T2.SNO_TYP3,
				DECODE(T2.PH_FLG, '1', I_PH_BOM.SNO4,
					DECODE(T2.SNO_TYP4, MAC_SNO_TYP.EXTND, I_PH_BOM.SNO4, MAC_SNO_TYP.EXTND_NULL, I_PH_BOM.SNO4, MAC_STR.NULL_VAL)
				) AS SNO4,
				T2.SNO_TYP4,
				T2.BYPROD_FLG,
				T2.IN_OFFST_TYP,
				T2.IN_OFFST,
				T2.BKF_TYP,
				T2.INST_LOT_FIX_FLG,
				T2.LOT_MIX_FLG,
				T2.SUBLOT_MIX_FLG,
				T2.ALLOC_CTL_TYP,
				T2.MAIN_ITM_FLG,
				T2.YIELD_CALC_FLG,
				T2.INPT_CTL_TYP,
				T2.DISP_SEQ,
				T2.MEMO1,
				T2.MEMO2,
				T2.MEMO3,
				I_PH_BOM.CUR_CD AS CUR_CD,
				T2.PH_FLG,
				T2.PH_BOM_PTN,
				T2.OPER_CD,
				T2.OPER_SEQ
			FROM (
				SELECT
					T.PEG_NO,
					T.ITM_ORD_NO,
					T.OPER_ORD_NO,
					T.OPER_CD,
					T.OPER_SEQ,
					T.MST_WG_CD AS WG_CD
				FROM
					MSW_BOM_EXP T
				WHERE 0=0
				AND T.PEG_NO = I_PH_BOM.PEG_NO
				) T1,
				MAVM_BOM T2,
				MAM_ITM T3
			WHERE 0=0
			AND T2.PAR_ITM_CD = I_PH_BOM.ITM_CD
			AND T2.PAR_ITM_SUB1 = I_PH_BOM.ITM_SUB1
			AND T2.PAR_ITM_SUB2 = I_PH_BOM.ITM_SUB2
			AND T2.PAR_ITM_SUB3 = I_PH_BOM.ITM_SUB3
			AND T2.BOM_PTN = I_BOM_PTN
			AND T2.CHD_ITM_CD = T3.ITM_CD
			AND T2.CHD_ITM_SUB1 = T3.ITM_SUB1
			AND T2.CHD_ITM_SUB2 = T3.ITM_SUB2
			AND T2.CHD_ITM_SUB3 = T3.ITM_SUB3
			AND (MAC_STR.IS_NULL_VAL(T1.OPER_CD)='1'
				OR (T1.OPER_CD = T2.OPER_CD AND T1.OPER_SEQ = T2.OPER_SEQ)
				OR (T2.OPER_CD IS NULL AND T2.PH_FLG = '1')--まだ下に架空品が存在する場合は、NULLも展開対象
				OR (T2.OPER_CD IS NULL AND T2.PH_FLG = '0' AND I_ALL_OPER_NULL_FLG = '0') -- 最下層（T2.PH_FLG='0'）の場合、これまでの階層で工程が指定されていなければならない
			)
			AND I_BASE_DT BETWEEN T2.ST_DT AND T2.END_DT
			AND (
				T2.MIN_SNO1 IS NULL AND T2.MAX_SNO1 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(I_PH_BOM.SNO1)='0'
					AND (T2.MIN_SNO1 <= I_PH_BOM.SNO1 OR T2.MIN_SNO1 IS NULL)
					AND (T2.MAX_SNO1 >= I_PH_BOM.SNO1 OR T2.MAX_SNO1 IS NULL)
				)
			)
			AND (
				T2.MIN_SNO2 IS NULL AND T2.MAX_SNO2 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(I_PH_BOM.SNO2)='0'
					AND (T2.MIN_SNO2 <= I_PH_BOM.SNO2 OR T2.MIN_SNO2 IS NULL)
					AND (T2.MAX_SNO2 >= I_PH_BOM.SNO2 OR T2.MAX_SNO2 IS NULL)
				)
			)
			AND (
				T2.MIN_SNO3 IS NULL AND T2.MAX_SNO3 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(I_PH_BOM.SNO3)='0'
					AND (T2.MIN_SNO3 <= I_PH_BOM.SNO3 OR T2.MIN_SNO3 IS NULL)
					AND (T2.MAX_SNO3 >= I_PH_BOM.SNO3 OR T2.MAX_SNO3 IS NULL)
				)
			)
			AND (
				T2.MIN_SNO4 IS NULL AND T2.MAX_SNO4 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(I_PH_BOM.SNO4)='0'
					AND (T2.MIN_SNO4 <= I_PH_BOM.SNO4 OR T2.MIN_SNO4 IS NULL)
					AND (T2.MAX_SNO4 >= I_PH_BOM.SNO4 OR T2.MAX_SNO4 IS NULL)
				)
			)
			AND T1.WG_CD = T2.WG_CD
			AND T2.DEL_FLG = '0'
			-- 代替品目フラグがオンのレコードから先に処理して、架空品は最後に処理する
			ORDER BY T1.PEG_NO, T2.ALT_GRP_CD, T2.ALT_ITM_FLG DESC, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, T2.DISP_SEQ, T2.PH_FLG
			)
		LOOP
			IF x.ALT_GRP_CD IS NULL THEN
				L_REC_BOM.ALT_GRP_SEQ := NULL ;
			ELSE
				L_ALT_GRP_SEQ := 1 ;

				IF x.ALT_ITM_FLG = '1' THEN
					-- これまでの階層で同じ代替Ｇがあれば連番を増やして初期値にする
					IF L_PREVIOUS_LEVEL_ALT_GRP_SEQ_ARRAY.EXISTS(x.ALT_GRP_CD) THEN
						L_ALT_GRP_SEQ := L_PREVIOUS_LEVEL_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD) + 1 ;
					END IF ;
					-- 同じ代替品目があれば同じ品目が登場する度に連番を増やす
					L_ALT_GRP_SEQ_ARRAY_KEY := CONCAT(x.ITM_CD, CONCAT(x.ITM_SUB1, CONCAT(x.ITM_SUB2, CONCAT(x.ITM_SUB3, x.VER_NO))));
					IF G_ALT_GRP_SEQ_ARRAY.EXISTS(x.ALT_GRP_CD) AND G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD).EXISTS(L_ALT_GRP_SEQ_ARRAY_KEY) THEN
						IF L_ALT_GRP_SEQ <=  G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD)(L_ALT_GRP_SEQ_ARRAY_KEY) THEN
							L_ALT_GRP_SEQ := G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD)(L_ALT_GRP_SEQ_ARRAY_KEY) + 1 ;
						END IF ;
					END IF ;

					G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD)(L_ALT_GRP_SEQ_ARRAY_KEY) := L_ALT_GRP_SEQ;
					G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) := L_ALT_GRP_SEQ ;

				ELSE
					IF G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY.EXISTS(x.ALT_GRP_CD) THEN
						-- 各代替Ｇで１度だけ連番を増やす
						IF L_ALT_ITM_FLG = '1' OR L_ALT_GRP_CD <> x.ALT_GRP_CD OR L_ALT_GRP_CD IS NULL THEN
							L_ALT_GRP_SEQ := G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) + 1 ;
						ELSE
							L_ALT_GRP_SEQ := G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) ;
						END IF ;
					END IF ;

					G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) := L_ALT_GRP_SEQ ;
				END IF ;

				L_REC_BOM.ALT_GRP_SEQ := L_ALT_GRP_SEQ ;
				L_ALT_GRP_CD := x.ALT_GRP_CD ;
				L_ALT_ITM_FLG := x.ALT_ITM_FLG ;
			END IF ;
			L_REC_BOM.PEG_NO := x.PEG_NO ;
			L_REC_BOM.BOM_KEY := x.BOM_KEY ;
			L_REC_BOM.ITM_ORD_NO := x.ITM_ORD_NO ;
			L_REC_BOM.ITM_CD := x.ITM_CD ;
			L_REC_BOM.ITM_SUB1 := x.ITM_SUB1 ;
			L_REC_BOM.ITM_SUB2 := x.ITM_SUB2 ;
			L_REC_BOM.ITM_SUB3 := x.ITM_SUB3 ;
			L_REC_BOM.VER_NO := x.VER_NO ;
			L_REC_BOM.RQMT_QTY := x.RQMT_QTY ;
			L_REC_BOM.LOSS_RQMT_QTY := x.LOSS_RQMT_QTY ;
			L_REC_BOM.INPT_QTY := x.INPT_QTY ;
			L_REC_BOM.FXD_RQMT_QTY := x.FXD_RQMT_QTY ;
			L_REC_BOM.ALT_ITM_FLG := x.ALT_ITM_FLG ;
			L_REC_BOM.ALT_GRP_CD := x.ALT_GRP_CD ;

			L_REC_BOM.ALT_ITM_TYP := x.ALT_ITM_TYP ;
			L_REC_BOM.ALT_ITM_RATIO := x.ALT_ITM_RATIO ;
			L_REC_BOM.ALT_ALLOC_PRIO := x.ALT_ALLOC_PRIO ;
			L_REC_BOM.SNO1 := x.SNO1 ;
			L_REC_BOM.SNO_TYP1 := x.SNO_TYP1 ;
			L_REC_BOM.SNO2 := x.SNO2 ;
			L_REC_BOM.SNO_TYP2 := x.SNO_TYP2 ;
			L_REC_BOM.SNO3 := x.SNO3 ;
			L_REC_BOM.SNO_TYP3 := x.SNO_TYP3 ;
			L_REC_BOM.SNO4 := x.SNO4 ;
			L_REC_BOM.SNO_TYP4 := x.SNO_TYP4 ;
			L_REC_BOM.PAR_INST_QTY := x.PAR_INST_QTY ;
			L_REC_BOM.CHD_RQMT_QTY := x.CHD_RQMT_QTY ;
			L_REC_BOM.CHD_INPT_QTY := x.CHD_INPT_QTY ;
			L_REC_BOM.FXD_CHD_RQMT_QTY := x.FXD_CHD_RQMT_QTY ;
			L_REC_BOM.CHD_RQMT_RATIO := x.CHD_RQMT_RATIO ;
			L_REC_BOM.CHD_INPT_RATIO := x.CHD_INPT_RATIO ;
			L_REC_BOM.BYPROD_FLG := x.BYPROD_FLG ;
			L_REC_BOM.IN_OFFST_TYP := x.IN_OFFST_TYP ;
			L_REC_BOM.IN_OFFST := I_PH_BOM.IN_OFFST + x.IN_OFFST ;
			L_REC_BOM.BKF_TYP := x.BKF_TYP ;
			L_REC_BOM.INST_LOT_FIX_FLG := x.INST_LOT_FIX_FLG ;
			L_REC_BOM.LOT_MIX_FLG := x.LOT_MIX_FLG ;
			L_REC_BOM.SUBLOT_MIX_FLG := x.SUBLOT_MIX_FLG ;
			L_REC_BOM.ALLOC_CTL_TYP := x.ALLOC_CTL_TYP ;
			L_REC_BOM.MAIN_ITM_FLG := x.MAIN_ITM_FLG ;
			L_REC_BOM.YIELD_CALC_FLG := x.YIELD_CALC_FLG ;
			L_REC_BOM.INPT_CTL_TYP := x.INPT_CTL_TYP ;
			L_REC_BOM.DISP_SEQ := x.DISP_SEQ ;
			L_REC_BOM.MEMO1 := x.MEMO1 ;
			L_REC_BOM.MEMO2 := x.MEMO2 ;
			L_REC_BOM.MEMO3 := x.MEMO3 ;
			L_REC_BOM.CUR_CD := x.CUR_CD ;

			IF x.PH_FLG ='1' AND x.PH_BOM_PTN IS NOT NULL THEN
				IF I_ALL_OPER_NULL_FLG = '1' AND x.OPER_CD IS NULL THEN
					L_ALL_OPER_NULL_FLG := '1';
				ELSE
					L_ALL_OPER_NULL_FLG := '0';
				END IF;
				P_EX_PH(L_REC_BOM, x.PH_BOM_PTN, I_BASE_DT, L_ALL_OPER_NULL_FLG) ;

			ELSE
				INSERT INTO MSW_BOM_EXP_RSLT VALUES L_REC_BOM ;

			END IF ;

		END LOOP ;

	END P_EX_PH ;

	PROCEDURE P_BOM_EXP
	/*********************************************************
	<SYNOPSIS>
		品目オーダの構成展開処理
	<REMARKS>
	<ARGUMENTS>
	<HISTORY>
	**********************************************************/
	IS
		L_REC_BOM MSW_BOM_EXP_RSLT%ROWTYPE ;
		L_PEG_NO MAPA_META.INT%TYPE ;
		L_ALT_GRP_CD	MSW_BOM_EXP_RSLT.ALT_GRP_CD%TYPE ;
		L_ALT_ITM_FLG	MSW_BOM_EXP_RSLT.ALT_ITM_FLG%TYPE ;
		L_ALL_OPER_NULL_FLG	MAPA_META.FLG%TYPE;
		L_ALT_GRP_SEQ	NUMBER ;
		L_ALT_GRP_SEQ_ARRAY_KEY VARCHAR2(128);
    BEGIN

		G_ALT_GRP_SEQ := 0 ;

		DELETE MSW_BOM_EXP_RSLT;

		FOR x IN(
			SELECT
				/*+ORDERED INDEX(T2.M1 MAM_BOM_ALL_IE01) USE_NL(T2.M1) */
				T1.PEG_NO,
				DECODE(T2.ALT_ITM_FLG, '0', T2.BOM_KEY, NULL) BOM_KEY,
				T1.ITM_ORD_NO,
				T2.PAR_ITM_CD,
				T2.PAR_ITM_SUB1,
				T2.PAR_ITM_SUB2,
				T2.PAR_ITM_SUB3,
				T2.CHD_ITM_CD ITM_CD,
				T2.CHD_ITM_SUB1 ITM_SUB1,
				T2.CHD_ITM_SUB2 ITM_SUB2,
				T2.CHD_ITM_SUB3 ITM_SUB3,
				T2.VER_NO,
				T2.PAR_INST_QTY,
				T2.CHD_RQMT_QTY,
				T2.CHD_INPT_QTY,
				T2.FXD_CHD_RQMT_QTY AS FXD_RQMT_QTY,
				T2.CHD_RQMT_RATIO,
				T2.CHD_INPT_RATIO,
				T1.OPER_SCHD_QTY * T2.CHD_RQMT_QTY / T2.PAR_INST_QTY + T2.FXD_CHD_RQMT_QTY AS RQMT_QTY,
				T1.OPER_SCHD_QTY * T2.CHD_RQMT_QTY / T2.PAR_INST_QTY AS LOSS_RQMT_QTY,
				T1.OPER_SCHD_QTY * T2.CHD_INPT_QTY / T2.PAR_INST_QTY AS INPT_QTY,
				T2.FXD_CHD_RQMT_QTY,
				T2.ALT_ITM_FLG,
				T2.ALT_GRP_CD,
				T2.ALT_ITM_TYP,
				T2.ALT_ITM_RATIO,
				T2.ALT_ALLOC_PRIO,
				DECODE(T2.PH_FLG, '1', T1.SNO1,
					DECODE(T2.SNO_TYP1, MAC_SNO_TYP.EXTND, T1.SNO1, MAC_SNO_TYP.EXTND_NULL, T1.SNO1, MAC_STR.NULL_VAL)
				) AS SNO1,
				T2.SNO_TYP1,
				DECODE(T2.PH_FLG, '1', T1.SNO2,
					DECODE(T2.SNO_TYP2, MAC_SNO_TYP.EXTND, T1.SNO2, MAC_SNO_TYP.EXTND_NULL, T1.SNO2, MAC_STR.NULL_VAL)
				) AS SNO2,
				T2.SNO_TYP2,
				DECODE(T2.PH_FLG, '1', T1.SNO3,
					DECODE(T2.SNO_TYP3, MAC_SNO_TYP.EXTND, T1.SNO3, MAC_SNO_TYP.EXTND_NULL, T1.SNO3, MAC_STR.NULL_VAL)
				) AS SNO3,
				T2.SNO_TYP3,
				DECODE(T2.PH_FLG, '1', T1.SNO4,
					DECODE(T2.SNO_TYP4, MAC_SNO_TYP.EXTND, T1.SNO4, MAC_SNO_TYP.EXTND_NULL, T1.SNO4, MAC_STR.NULL_VAL)
				) AS SNO4,
				T2.SNO_TYP4,
				T2.BYPROD_FLG,
				T2.IN_OFFST_TYP,
				T2.IN_OFFST,
				T2.BKF_TYP,
				T2.INST_LOT_FIX_FLG,
				T2.LOT_MIX_FLG,
				T2.SUBLOT_MIX_FLG,
				T2.ALLOC_CTL_TYP,
				T2.MAIN_ITM_FLG,
				T2.YIELD_CALC_FLG,
				T2.INPT_CTL_TYP,
				T2.DISP_SEQ,
				T2.MEMO1,
				T2.MEMO2,
				T2.MEMO3,
				T1.CUR_CD,
				T2.PH_FLG,
				T2.PH_BOM_PTN,
				T2.OPER_CD BOM_OPER_CD,
				T1.OPER_LOC_CD,
				T1.OPER_CD,
				T1.OPER_SEQ,
				T1.OPER_SCHD_QTY,
				T1.MFG_ST_SCHD_DT,
				T1.ST_SCHD_DT,
				T1.END_SCHD_DT
			FROM	MSW_BOM_EXP T1,
				MAVM_BOM T2,
				MAM_ITM T3
			WHERE 0=0
			AND T1.ITM_CD = T2.PAR_ITM_CD
			AND T1.ITM_SUB1 = T2.PAR_ITM_SUB1
			AND T1.ITM_SUB2 = T2.PAR_ITM_SUB2
			AND T1.ITM_SUB3 = T2.PAR_ITM_SUB3
			AND T1.BOM_PTN = T2.BOM_PTN
			AND T2.CHD_ITM_CD = T3.ITM_CD
			AND T2.CHD_ITM_SUB1 = T3.ITM_SUB1
			AND T2.CHD_ITM_SUB2 = T3.ITM_SUB2
			AND T2.CHD_ITM_SUB3 = T3.ITM_SUB3
			AND (MAC_STR.IS_NULL_VAL(T1.OPER_CD)='1'
				OR (T1.OPER_CD = T2.OPER_CD AND T1.OPER_SEQ = T2.OPER_SEQ)
				OR (T2.OPER_CD IS NULL AND T2.PH_FLG = '1')
			)
			AND T1.MFG_ST_SCHD_DT BETWEEN T2.ST_DT AND T2.END_DT
			AND (
				T2.MIN_SNO1 IS NULL AND T2.MAX_SNO1 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(T1.SNO1)='0'
					AND (T2.MIN_SNO1 <= T1.SNO1 OR T2.MIN_SNO1 IS NULL)
					AND (T2.MAX_SNO1 >= T1.SNO1 OR T2.MAX_SNO1 IS NULL)
				)
			)
			AND (
				T2.MIN_SNO2 IS NULL AND T2.MAX_SNO2 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(T1.SNO2)='0'
					AND (T2.MIN_SNO2 <= T1.SNO2 OR T2.MIN_SNO2 IS NULL)
					AND (T2.MAX_SNO2 >= T1.SNO2 OR T2.MAX_SNO2 IS NULL)
				)
			)
			AND (
				T2.MIN_SNO3 IS NULL AND T2.MAX_SNO3 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(T1.SNO3)='0'
					AND (T2.MIN_SNO3 <= T1.SNO3 OR T2.MIN_SNO3 IS NULL)
					AND (T2.MAX_SNO3 >= T1.SNO3 OR T2.MAX_SNO3 IS NULL)
				)
			)
			AND (
				T2.MIN_SNO4 IS NULL AND T2.MAX_SNO4 IS NULL
				OR
				(MAC_STR.IS_NULL_VAL(T1.SNO4)='0'
					AND (T2.MIN_SNO4 <= T1.SNO4 OR T2.MIN_SNO4 IS NULL)
					AND (T2.MAX_SNO4 >= T1.SNO4 OR T2.MAX_SNO4 IS NULL)
				)
			)
			AND T1.MST_WG_CD = T2.WG_CD
			AND T2.DEL_FLG = '0'
			-- 代替品目フラグがオンのレコードから先に処理して、架空品は最後に処理する
			ORDER BY T1.PEG_NO, T2.ALT_GRP_CD, T2.ALT_ITM_FLG DESC, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, T2.DISP_SEQ, T2.PH_FLG
			)
		LOOP
			IF x.ALT_GRP_CD IS NULL THEN
				L_REC_BOM.ALT_GRP_SEQ := NULL ;
			ELSE
				L_ALT_GRP_SEQ := 1 ;

				IF x.ALT_ITM_FLG = '1' THEN
					-- 同じ代替品目があれば同じ品目が登場する度に連番を増やす
					L_ALT_GRP_SEQ_ARRAY_KEY := CONCAT(x.ITM_CD, CONCAT(x.ITM_SUB1, CONCAT(x.ITM_SUB2, CONCAT(x.ITM_SUB3, x.VER_NO))));
					IF G_ALT_GRP_SEQ_ARRAY.EXISTS(x.ALT_GRP_CD) AND G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD).EXISTS(L_ALT_GRP_SEQ_ARRAY_KEY) THEN
						L_ALT_GRP_SEQ := G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD)(L_ALT_GRP_SEQ_ARRAY_KEY) + 1 ;
					END IF ;

					G_ALT_GRP_SEQ_ARRAY(x.ALT_GRP_CD)(L_ALT_GRP_SEQ_ARRAY_KEY) := L_ALT_GRP_SEQ;
					G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) := L_ALT_GRP_SEQ ;

				ELSE
					IF G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY.EXISTS(x.ALT_GRP_CD) THEN
						-- 各代替Ｇで１度だけ連番を増やす
						IF L_ALT_ITM_FLG = '1' OR L_ALT_GRP_CD <> x.ALT_GRP_CD OR L_PEG_NO <> x.PEG_NO THEN
							L_ALT_GRP_SEQ := G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) + 1 ;
						ELSE
							L_ALT_GRP_SEQ := G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) ;
						END IF ;
					END IF ;

					G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY(x.ALT_GRP_CD) := L_ALT_GRP_SEQ ;
				END IF ;

				L_REC_BOM.ALT_GRP_SEQ := L_ALT_GRP_SEQ ;
				L_ALT_GRP_CD := x.ALT_GRP_CD ;
				L_ALT_ITM_FLG := x.ALT_ITM_FLG ;
				L_PEG_NO := x.PEG_NO ;
			END IF ;
			L_REC_BOM.PEG_NO := x.PEG_NO ;
			L_REC_BOM.BOM_KEY := x.BOM_KEY ;
			L_REC_BOM.ITM_ORD_NO := x.ITM_ORD_NO ;
			L_REC_BOM.ITM_CD := x.ITM_CD ;
			L_REC_BOM.ITM_SUB1 := x.ITM_SUB1 ;
			L_REC_BOM.ITM_SUB2 := x.ITM_SUB2 ;
			L_REC_BOM.ITM_SUB3 := x.ITM_SUB3 ;
			L_REC_BOM.VER_NO := x.VER_NO ;
			L_REC_BOM.RQMT_QTY := x.RQMT_QTY ;
			L_REC_BOM.LOSS_RQMT_QTY := x.LOSS_RQMT_QTY ;
			L_REC_BOM.INPT_QTY := x.INPT_QTY ;
			L_REC_BOM.FXD_RQMT_QTY := x.FXD_RQMT_QTY ;
			L_REC_BOM.ALT_ITM_FLG := x.ALT_ITM_FLG ;
			L_REC_BOM.ALT_GRP_CD := x.ALT_GRP_CD ;

			L_REC_BOM.ALT_ITM_TYP := x.ALT_ITM_TYP ;
			L_REC_BOM.ALT_ITM_RATIO := x.ALT_ITM_RATIO ;
			L_REC_BOM.ALT_ALLOC_PRIO := x.ALT_ALLOC_PRIO ;
			L_REC_BOM.SNO1 := x.SNO1 ;
			L_REC_BOM.SNO_TYP1 := x.SNO_TYP1 ;
			L_REC_BOM.SNO2 := x.SNO2 ;
			L_REC_BOM.SNO_TYP2 := x.SNO_TYP2 ;
			L_REC_BOM.SNO3 := x.SNO3 ;
			L_REC_BOM.SNO_TYP3 := x.SNO_TYP3 ;
			L_REC_BOM.SNO4 := x.SNO4 ;
			L_REC_BOM.SNO_TYP4 := x.SNO_TYP4 ;
			L_REC_BOM.PAR_INST_QTY := x.PAR_INST_QTY ;
			L_REC_BOM.CHD_RQMT_QTY := x.CHD_RQMT_QTY ;
			L_REC_BOM.CHD_INPT_QTY := x.CHD_INPT_QTY ;
			L_REC_BOM.FXD_CHD_RQMT_QTY := x.FXD_CHD_RQMT_QTY ;
			L_REC_BOM.ALT_ITM_RATIO := x.ALT_ITM_RATIO ;
			L_REC_BOM.ALT_ALLOC_PRIO := x.ALT_ALLOC_PRIO ;
			L_REC_BOM.BYPROD_FLG := x.BYPROD_FLG ;
			L_REC_BOM.IN_OFFST_TYP := x.IN_OFFST_TYP ;
			L_REC_BOM.IN_OFFST := x.IN_OFFST ;
			L_REC_BOM.BKF_TYP := x.BKF_TYP ;
			L_REC_BOM.INST_LOT_FIX_FLG := x.INST_LOT_FIX_FLG ;
			L_REC_BOM.LOT_MIX_FLG := x.LOT_MIX_FLG ;
			L_REC_BOM.SUBLOT_MIX_FLG := x.SUBLOT_MIX_FLG ;
			L_REC_BOM.ALLOC_CTL_TYP := x.ALLOC_CTL_TYP ;
			L_REC_BOM.MAIN_ITM_FLG := x.MAIN_ITM_FLG ;
			L_REC_BOM.YIELD_CALC_FLG := x.YIELD_CALC_FLG ;
			L_REC_BOM.INPT_CTL_TYP := x.INPT_CTL_TYP ;
			L_REC_BOM.DISP_SEQ := x.DISP_SEQ ;
			L_REC_BOM.MEMO1 := x.MEMO1 ;
			L_REC_BOM.MEMO2 := x.MEMO2 ;
			L_REC_BOM.MEMO3 := x.MEMO3 ;
			L_REC_BOM.CUR_CD := x.CUR_CD ;

			IF x.PH_FLG ='1' AND x.PH_BOM_PTN IS NOT NULL THEN
				IF x.BOM_OPER_CD IS NULL THEN
					L_ALL_OPER_NULL_FLG := '1';
				ELSE
					L_ALL_OPER_NULL_FLG := '0';
				END IF;
				P_EX_PH(L_REC_BOM, x.PH_BOM_PTN, x.MFG_ST_SCHD_DT, L_ALL_OPER_NULL_FLG) ;

			ELSE
				INSERT INTO MSW_BOM_EXP_RSLT VALUES L_REC_BOM ;

			END IF ;

		END LOOP ;
		G_ALT_GRP_SEQ_ARRAY.DELETE;
		G_ALT_GRP_SEQ_EACH_ALT_GRP_ARRAY.DELETE;
	END P_BOM_EXP ;

	PROCEDURE P_BOM_EXP_NO_RECURSIVE
	/*********************************************************
	<SYNOPSIS>
		品目オーダの非再帰的な構成展開処理
	<REMARKS>
	<ARGUMENTS>
	<HISTORY>
	**********************************************************/
	IS

	-- 変数定義
	L_ALT_GRP_SEQ MSW_BOM_EXP_RSLT.ALT_GRP_SEQ%TYPE;
	L_REC_BOM MSW_BOM_EXP_RSLT%ROWTYPE;
	L_PEG_NO MSW_BOM_EXP.PEG_NO%TYPE;
	L_ALT_GRP_CD MAM_ALT_GRP.ALT_GRP_CD%TYPE;
	L_ALT_ITM_FLG CHAR(1);
	L_ALL_OPER_NULL_FLG CHAR(1);
	
	-- ORACLE PL/SQLコレクション (POSTGRESQL配列の代替)
	TYPE T_MSW_BOM_EXP_RSLT_TBL IS TABLE OF MSW_BOM_EXP_RSLT%ROWTYPE INDEX BY PLS_INTEGER;
	L_ALT_GRP_SEQ_ARRAY T_MSW_BOM_EXP_RSLT_TBL;
	L_LOOPCOUNT PLS_INTEGER;
	L_EXIST_FLG CHAR(1);

	-- カーソル定義 (POSTGRESQLのFOR INの代替)
	CURSOR C_BOM_EXP IS
		WITH BOM_RECURSION (
			MASTER_PAR_ITM_CD, PAR_ITM_CD, PAR_ITM_SUB1, PAR_ITM_SUB2, PAR_ITM_SUB3,
			CHD_ITM_CD, BOM_PTN, PH_BOM_PTN, PH_FLG, SNO1, SNO2, SNO3, SNO4,
			CHD_ITM_SUB1, CHD_ITM_SUB2, CHD_ITM_SUB3, SNO_TYP1, SNO_TYP2, SNO_TYP3, SNO_TYP4,
			BOM_KEY, PAR_INST_QTY, FXD_CHD_RQMT_QTY, FXD_RQMT_QTY, RQMT_QTY, LOSS_RQMT_QTY, INPT_QTY,
			CHD_RQMT_QTY, CHD_INPT_QTY, MASTER_PEG_NO, MASTER_OPER_CD, MASTER_OPER_SEQ,
			OPER_CD, OPER_SEQ, MST_WG_CD, MFG_ST_SCHD_DT, ALL_OPER_NULL_FLG, VER_NO,
			CHD_RQMT_RATIO, CHD_INPT_RATIO, ALT_ITM_FLG, ALT_GRP_CD, ALT_ITM_TYP,
			ALT_ITM_RATIO, ALT_ALLOC_PRIO, BYPROD_FLG, IN_OFFST_TYP, IN_OFFST, BKF_TYP,
			INST_LOT_FIX_FLG, LOT_MIX_FLG, SUBLOT_MIX_FLG, ALLOC_CTL_TYP, MAIN_ITM_FLG,
			YIELD_CALC_FLG, INPT_CTL_TYP, DISP_SEQ, MEMO1, MEMO2, MEMO3, BOM_OPER_CD
		) AS (
			-- アンカーメンバー
			SELECT
				M.PAR_ITM_CD AS MASTER_PAR_ITM_CD,
				M.PAR_ITM_CD,
				M.PAR_ITM_SUB1,
				M.PAR_ITM_SUB2,
				M.PAR_ITM_SUB3,
				M.CHD_ITM_CD,
				P.BOM_PTN,
				M.PH_BOM_PTN,
				M.PH_FLG,
				CASE M.PH_FLG
					WHEN '1' THEN P.SNO1
					ELSE
						CASE M.SNO_TYP1
							WHEN MAC_SNO_TYP.EXTND THEN P.SNO1
							WHEN MAC_SNO_TYP.EXTND_NULL THEN P.SNO1
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO1,
				CASE M.PH_FLG
					WHEN '1' THEN P.SNO2
					ELSE
						CASE M.SNO_TYP2
							WHEN MAC_SNO_TYP.EXTND THEN P.SNO2
							WHEN MAC_SNO_TYP.EXTND_NULL THEN P.SNO2
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO2,
				CASE M.PH_FLG
					WHEN '1' THEN P.SNO3
					ELSE
						CASE M.SNO_TYP3
							WHEN MAC_SNO_TYP.EXTND THEN P.SNO3
							WHEN MAC_SNO_TYP.EXTND_NULL THEN P.SNO3
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO3,
				CASE M.PH_FLG
					WHEN '1' THEN P.SNO4
					ELSE
						CASE M.SNO_TYP4
							WHEN MAC_SNO_TYP.EXTND THEN P.SNO4
							WHEN MAC_SNO_TYP.EXTND_NULL THEN P.SNO4
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO4,
				M.CHD_ITM_SUB1, M.CHD_ITM_SUB2, M.CHD_ITM_SUB3,
				M.SNO_TYP1, M.SNO_TYP2, M.SNO_TYP3, M.SNO_TYP4,
				M.BOM_KEY,
				M.PAR_INST_QTY,
				M.FXD_CHD_RQMT_QTY,
				M.FXD_CHD_RQMT_QTY AS FXD_RQMT_QTY,
				P.OPER_SCHD_QTY * M.CHD_RQMT_QTY / M.PAR_INST_QTY + M.FXD_CHD_RQMT_QTY AS RQMT_QTY,
				P.OPER_SCHD_QTY * M.CHD_RQMT_QTY / M.PAR_INST_QTY AS LOSS_RQMT_QTY,
				P.OPER_SCHD_QTY * M.CHD_INPT_QTY / M.PAR_INST_QTY AS INPT_QTY,
				CAST(M.CHD_RQMT_QTY AS NUMBER(21,8)) AS CHD_RQMT_QTY,
				CAST(M.CHD_INPT_QTY AS NUMBER(21,8)) AS CHD_INPT_QTY,
				P.PEG_NO AS MASTER_PEG_NO,
				P.OPER_CD AS MASTER_OPER_CD,
				P.OPER_SEQ AS MASTER_OPER_SEQ,
				P.OPER_CD,
				P.OPER_SEQ,
				P.MST_WG_CD,
				P.MFG_ST_SCHD_DT,
				CASE
					WHEN M.OPER_CD IS NULL THEN '1'
					ELSE '0'
				END AS ALL_OPER_NULL_FLG,
				M.VER_NO,
				M.CHD_RQMT_RATIO,
				M.CHD_INPT_RATIO,
				M.ALT_ITM_FLG,
				M.ALT_GRP_CD,
				M.ALT_ITM_TYP,
				M.ALT_ITM_RATIO,
				M.ALT_ALLOC_PRIO,
				M.BYPROD_FLG,
				M.IN_OFFST_TYP,
				M.IN_OFFST,
				M.BKF_TYP,
				M.INST_LOT_FIX_FLG,
				M.LOT_MIX_FLG,
				M.SUBLOT_MIX_FLG,
				M.ALLOC_CTL_TYP,
				M.MAIN_ITM_FLG,
				M.YIELD_CALC_FLG,
				M.INPT_CTL_TYP,
				M.DISP_SEQ,
				M.MEMO1,
				M.MEMO2,
				M.MEMO3,
				M.OPER_CD AS BOM_OPER_CD
			FROM
				MAVM_BOM M
			JOIN
				MSW_BOM_EXP P
			ON
				P.ITM_CD = M.PAR_ITM_CD
				AND P.ITM_SUB1 = M.PAR_ITM_SUB1
				AND P.ITM_SUB2 = M.PAR_ITM_SUB2
				AND P.ITM_SUB3 = M.PAR_ITM_SUB3
				AND P.BOM_PTN = M.BOM_PTN
			INNER JOIN
				MAM_ITM MI
			ON
				M.CHD_ITM_CD = MI.ITM_CD
				AND M.CHD_ITM_SUB1 = MI.ITM_SUB1
				AND M.CHD_ITM_SUB2 = MI.ITM_SUB2
				AND M.CHD_ITM_SUB3 = MI.ITM_SUB3
			WHERE
				1 = 1
				AND (MAC_SNO_TYP.EXTND = P.OPER_CD OR (P.OPER_CD = M.OPER_CD AND P.OPER_SEQ = M.OPER_SEQ) OR (M.OPER_CD IS NULL AND M.PH_FLG = '1'))
				AND P.MFG_ST_SCHD_DT BETWEEN M.ST_DT AND M.END_DT
				AND (
					M.MIN_SNO1 IS NULL AND M.MAX_SNO1 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> P.SNO1 AND (M.MIN_SNO1 <= P.SNO1 OR M.MIN_SNO1 IS NULL) AND (M.MAX_SNO1 >= P.SNO1 OR M.MAX_SNO1 IS NULL))
				)
				AND (
					M.MIN_SNO2 IS NULL AND M.MAX_SNO2 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> P.SNO2 AND (M.MIN_SNO2 <= P.SNO2 OR M.MIN_SNO2 IS NULL) AND (M.MAX_SNO2 >= P.SNO2 OR M.MAX_SNO2 IS NULL))
				)
				AND (
					M.MIN_SNO3 IS NULL AND M.MAX_SNO3 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> P.SNO3 AND (M.MIN_SNO3 <= P.SNO3 OR M.MIN_SNO3 IS NULL) AND (M.MAX_SNO3 >= P.SNO3 OR M.MAX_SNO3 IS NULL))
				)
				AND (
					M.MIN_SNO4 IS NULL AND M.MAX_SNO4 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> P.SNO4 AND (M.MIN_SNO4 <= P.SNO4 OR M.MIN_SNO4 IS NULL) AND (M.MAX_SNO4 >= P.SNO4 OR M.MAX_SNO4 IS NULL))
				)
				AND P.MST_WG_CD = M.WG_CD
				AND M.DEL_FLG = '0'
			UNION ALL
			-- 再帰メンバー
			SELECT
				R.MASTER_PAR_ITM_CD,
				B.PAR_ITM_CD,
				B.PAR_ITM_SUB1,
				B.PAR_ITM_SUB2,
				B.PAR_ITM_SUB3,
				B.CHD_ITM_CD,
				R.BOM_PTN,
				B.PH_BOM_PTN,
				B.PH_FLG,
				CASE B.PH_FLG
					WHEN '1' THEN R.SNO1
					ELSE
						CASE B.SNO_TYP1
							WHEN MAC_SNO_TYP.EXTND THEN R.SNO1
							WHEN MAC_SNO_TYP.EXTND_NULL THEN R.SNO1
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO1,
				CASE B.PH_FLG
					WHEN '1' THEN R.SNO2
					ELSE
						CASE B.SNO_TYP2
							WHEN MAC_SNO_TYP.EXTND THEN R.SNO2
							WHEN MAC_SNO_TYP.EXTND_NULL THEN R.SNO2
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO2,
				CASE B.PH_FLG
					WHEN '1' THEN R.SNO3
					ELSE
						CASE B.SNO_TYP3
							WHEN MAC_SNO_TYP.EXTND THEN R.SNO3
							WHEN MAC_SNO_TYP.EXTND_NULL THEN R.SNO3
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO3,
				CASE B.PH_FLG
					WHEN '1' THEN R.SNO4
					ELSE
						CASE B.SNO_TYP4
							WHEN MAC_SNO_TYP.EXTND THEN R.SNO4
							WHEN MAC_SNO_TYP.EXTND_NULL THEN R.SNO4
							ELSE MAC_SNO_TYP.EXTND
						END
				END AS SNO4,
				B.CHD_ITM_SUB1, B.CHD_ITM_SUB2, B.CHD_ITM_SUB3,
				B.SNO_TYP1, B.SNO_TYP2, B.SNO_TYP3, B.SNO_TYP4,
				B.BOM_KEY,
				B.PAR_INST_QTY,
				B.FXD_CHD_RQMT_QTY,
				R.FXD_RQMT_QTY AS FXD_RQMT_QTY,
				R.RQMT_QTY * B.CHD_RQMT_QTY / B.PAR_INST_QTY + B.FXD_CHD_RQMT_QTY AS RQMT_QTY,
				R.RQMT_QTY * B.CHD_RQMT_QTY / B.PAR_INST_QTY AS LOSS_RQMT_QTY,
				R.RQMT_QTY * B.CHD_INPT_QTY / B.PAR_INST_QTY AS INPT_QTY,
				CAST(
					CASE B.PAR_INST_QTY
						WHEN 0 THEN 0
						ELSE R.CHD_RQMT_QTY * B.CHD_RQMT_QTY / B.PAR_INST_QTY
					END AS NUMBER(21,8)
				) AS CHD_RQMT_QTY,
				CAST(
					CASE B.PAR_INST_QTY
						WHEN 0 THEN 0
						ELSE R.CHD_INPT_QTY * B.CHD_INPT_QTY / B.PAR_INST_QTY
					END AS NUMBER(21,8)
				) AS CHD_INPT_QTY,
				R.MASTER_PEG_NO,
				R.MASTER_OPER_CD,
				R.MASTER_OPER_SEQ,
				B.OPER_CD,
				B.OPER_SEQ,
				R.MST_WG_CD,
				R.MFG_ST_SCHD_DT,
				CASE
					WHEN R.ALL_OPER_NULL_FLG = '1' AND B.OPER_CD IS NULL THEN '1'
					ELSE '0'
				END AS ALL_OPER_NULL_FLG,
				B.VER_NO,
				B.CHD_RQMT_RATIO,
				B.CHD_INPT_RATIO,
				B.ALT_ITM_FLG,
				B.ALT_GRP_CD,
				B.ALT_ITM_TYP,
				B.ALT_ITM_RATIO,
				B.ALT_ALLOC_PRIO,
				B.BYPROD_FLG,
				B.IN_OFFST_TYP,
				B.IN_OFFST,
				B.BKF_TYP,
				B.INST_LOT_FIX_FLG,
				B.LOT_MIX_FLG,
				B.SUBLOT_MIX_FLG,
				B.ALLOC_CTL_TYP,
				B.MAIN_ITM_FLG,
				B.YIELD_CALC_FLG,
				B.INPT_CTL_TYP,
				B.DISP_SEQ,
				B.MEMO1,
				B.MEMO2,
				B.MEMO3,
				B.OPER_CD AS BOM_OPER_CD
			FROM
				MAVM_BOM B
			INNER JOIN
				BOM_RECURSION R
			ON
				B.PAR_ITM_CD = R.CHD_ITM_CD
				AND B.PAR_ITM_SUB1 = R.CHD_ITM_SUB1
				AND B.PAR_ITM_SUB2 = R.CHD_ITM_SUB2
				AND B.PAR_ITM_SUB3 = R.CHD_ITM_SUB3
				AND B.BOM_PTN = R.PH_BOM_PTN
			INNER JOIN
				MAM_ITM MI
			ON
				B.CHD_ITM_CD = MI.ITM_CD
				AND B.CHD_ITM_SUB1 = MI.ITM_SUB1
				AND B.CHD_ITM_SUB2 = MI.ITM_SUB2
				AND B.CHD_ITM_SUB3 = MI.ITM_SUB3
			WHERE
				1 = 1
				AND R.MST_WG_CD = B.WG_CD
				AND (MAC_SNO_TYP.EXTND = R.MASTER_OPER_CD OR (R.MASTER_OPER_CD = B.OPER_CD AND R.MASTER_OPER_SEQ = B.OPER_SEQ)
					OR (B.OPER_CD IS NULL AND B.PH_FLG = '1')
					OR (B.OPER_CD IS NULL AND B.PH_FLG = '0' AND R.ALL_OPER_NULL_FLG = '0'))
				AND R.MFG_ST_SCHD_DT BETWEEN B.ST_DT AND B.END_DT
				AND (
					B.MIN_SNO1 IS NULL AND B.MAX_SNO1 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> R.SNO1 AND (B.MIN_SNO1 <= R.SNO1 OR B.MIN_SNO1 IS NULL) AND (B.MAX_SNO1 >= R.SNO1 OR B.MAX_SNO1 IS NULL))
				)
				AND (
					B.MIN_SNO2 IS NULL AND B.MAX_SNO2 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> R.SNO2 AND (B.MIN_SNO2 <= R.SNO2 OR B.MIN_SNO2 IS NULL) AND (B.MAX_SNO2 >= R.SNO2 OR B.MAX_SNO2 IS NULL))
				)
				AND (
					B.MIN_SNO3 IS NULL AND B.MAX_SNO3 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> R.SNO3 AND (B.MIN_SNO3 <= R.SNO3 OR B.MIN_SNO3 IS NULL) AND (B.MAX_SNO3 >= R.SNO3 OR B.MAX_SNO3 IS NULL))
				)
				AND (
					B.MIN_SNO4 IS NULL AND B.MAX_SNO4 IS NULL
					OR
					(MAC_SNO_TYP.EXTND <> R.SNO4 AND (B.MIN_SNO4 <= R.SNO4 OR B.MIN_SNO4 IS NULL) AND (B.MAX_SNO4 >= R.SNO4 OR B.MAX_SNO4 IS NULL))
				)
				AND R.PH_FLG = '1'
		)
		SELECT
			T1.PEG_NO,
			CASE
				WHEN BR.ALT_ITM_FLG = '0' THEN BR.BOM_KEY
				ELSE NULL
			END AS BOM_KEY,
			T1.ITM_ORD_NO,
			BR.PAR_ITM_CD,
			BR.PAR_ITM_SUB1,
			BR.PAR_ITM_SUB2,
			BR.PAR_ITM_SUB3,
			BR.CHD_ITM_CD AS ITM_CD,
			BR.CHD_ITM_SUB1 AS ITM_SUB1,
			BR.CHD_ITM_SUB2 AS ITM_SUB2,
			BR.CHD_ITM_SUB3 AS ITM_SUB3,
			BR.VER_NO,
			BR.PAR_INST_QTY,
			BR.CHD_RQMT_QTY,
			BR.CHD_INPT_QTY,
			BR.FXD_CHD_RQMT_QTY AS FXD_RQMT_QTY,
			BR.FXD_RQMT_QTY AS FXD_CHD_RQMT_QTY,
			BR.CHD_RQMT_RATIO,
			BR.CHD_INPT_RATIO,
			BR.RQMT_QTY,
			BR.LOSS_RQMT_QTY,
			BR.INPT_QTY,
			BR.ALT_ITM_FLG,
			BR.ALT_GRP_CD,
			BR.ALT_ITM_TYP,
			BR.ALT_ITM_RATIO,
			BR.ALT_ALLOC_PRIO,
			CASE BR.PH_FLG
				WHEN '1' THEN T1.SNO1
				ELSE
					CASE BR.SNO_TYP1
						WHEN MAC_SNO_TYP.EXTND THEN T1.SNO1
						WHEN MAC_SNO_TYP.EXTND_NULL THEN T1.SNO1
						ELSE MAC_SNO_TYP.EXTND
					END
			END AS SNO1,
			BR.SNO_TYP1,
			CASE BR.PH_FLG
				WHEN '1' THEN T1.SNO2
				ELSE
					CASE BR.SNO_TYP2
						WHEN MAC_SNO_TYP.EXTND THEN T1.SNO2
						WHEN MAC_SNO_TYP.EXTND_NULL THEN T1.SNO2
						ELSE MAC_SNO_TYP.EXTND
					END
			END AS SNO2,
			BR.SNO_TYP2,
			CASE BR.PH_FLG
				WHEN '1' THEN T1.SNO3
				ELSE
					CASE BR.SNO_TYP3
						WHEN MAC_SNO_TYP.EXTND THEN T1.SNO3
						WHEN MAC_SNO_TYP.EXTND_NULL THEN T1.SNO3
						ELSE MAC_SNO_TYP.EXTND
					END
			END AS SNO3,
			BR.SNO_TYP3,
			CASE BR.PH_FLG
				WHEN '1' THEN T1.SNO4
				ELSE
					CASE BR.SNO_TYP4
						WHEN MAC_SNO_TYP.EXTND THEN T1.SNO4
						WHEN MAC_SNO_TYP.EXTND_NULL THEN T1.SNO4
						ELSE MAC_SNO_TYP.EXTND
					END
			END AS SNO4,
			BR.SNO_TYP4,
			BR.BYPROD_FLG,
			BR.IN_OFFST_TYP,
			BR.IN_OFFST,
			BR.BKF_TYP,
			BR.INST_LOT_FIX_FLG,
			BR.LOT_MIX_FLG,
			BR.SUBLOT_MIX_FLG,
			BR.ALLOC_CTL_TYP,
			BR.MAIN_ITM_FLG,
			BR.YIELD_CALC_FLG,
			BR.INPT_CTL_TYP,
			BR.DISP_SEQ,
			BR.MEMO1,
			BR.MEMO2,
			BR.MEMO3,
			T1.CUR_CD,
			BR.PH_FLG,
			BR.PH_BOM_PTN,
			BR.OPER_CD AS BOM_OPER_CD,
			T1.OPER_LOC_CD,
			T1.OPER_CD,
			T1.OPER_SEQ,
			T1.OPER_SCHD_QTY,
			T1.MFG_ST_SCHD_DT,
			T1.ST_SCHD_DT,
			T1.END_SCHD_DT
		FROM
			BOM_RECURSION BR
		INNER JOIN
			MSW_BOM_EXP T1
		ON
			T1.ITM_CD = BR.MASTER_PAR_ITM_CD
			AND T1.ITM_SUB1 = BR.CHD_ITM_SUB1
			AND T1.ITM_SUB2 = BR.CHD_ITM_SUB2
			AND T1.ITM_SUB3 = BR.CHD_ITM_SUB3
			AND T1.PEG_NO = BR.MASTER_PEG_NO
			AND T1.BOM_PTN = BR.BOM_PTN
		WHERE
			BR.PH_FLG = '0'
		ORDER BY
			T1.PEG_NO, BR.ALT_GRP_CD, ITM_CD, ITM_SUB1, ITM_SUB2, ITM_SUB3, BR.DISP_SEQ, BR.ALT_ITM_FLG, BR.PH_FLG;

	-- カーソルレコード
	REC_BOM_EXP C_BOM_EXP%ROWTYPE;

	BEGIN
		-- 初期化
		L_ALT_GRP_SEQ := 0;
		L_EXIST_FLG := '0';
		L_ALT_GRP_SEQ_ARRAY.DELETE;
		L_PEG_NO := NULL;
		L_ALT_GRP_CD := NULL;
		L_ALT_ITM_FLG := NULL;

		-- 作業テーブルのTRUNCATE
		DELETE MSW_BOM_EXP_RSLT;

		OPEN C_BOM_EXP;
		LOOP
		  FETCH C_BOM_EXP INTO REC_BOM_EXP;
		  EXIT WHEN C_BOM_EXP%NOTFOUND;

		  IF (L_PEG_NO IS NULL OR L_PEG_NO != REC_BOM_EXP.PEG_NO) THEN
			  L_ALT_GRP_SEQ_ARRAY.DELETE;
			  L_PEG_NO := REC_BOM_EXP.PEG_NO;
			  L_ALT_GRP_SEQ := 0;
		  END IF;

		  -- レコードのコピー
		  L_REC_BOM.PEG_NO := REC_BOM_EXP.PEG_NO;
		  L_REC_BOM.BOM_KEY := REC_BOM_EXP.BOM_KEY;
		  L_REC_BOM.ITM_ORD_NO := REC_BOM_EXP.ITM_ORD_NO;
		  L_REC_BOM.ITM_CD := REC_BOM_EXP.ITM_CD;
		  L_REC_BOM.ITM_SUB1 := REC_BOM_EXP.ITM_SUB1;
		  L_REC_BOM.ITM_SUB2 := REC_BOM_EXP.ITM_SUB2;
		  L_REC_BOM.ITM_SUB3 := REC_BOM_EXP.ITM_SUB3;
		  L_REC_BOM.VER_NO := REC_BOM_EXP.VER_NO;
		  L_REC_BOM.RQMT_QTY := REC_BOM_EXP.RQMT_QTY;
		  L_REC_BOM.LOSS_RQMT_QTY := REC_BOM_EXP.LOSS_RQMT_QTY;
		  L_REC_BOM.INPT_QTY := REC_BOM_EXP.INPT_QTY;
		  L_REC_BOM.FXD_RQMT_QTY := REC_BOM_EXP.FXD_RQMT_QTY;
		  L_REC_BOM.ALT_ITM_FLG := REC_BOM_EXP.ALT_ITM_FLG;
		  L_REC_BOM.ALT_GRP_CD := REC_BOM_EXP.ALT_GRP_CD;

		  L_REC_BOM.ALT_ITM_TYP := REC_BOM_EXP.ALT_ITM_TYP;
		  L_REC_BOM.ALT_ITM_RATIO := REC_BOM_EXP.ALT_ITM_RATIO;
		  L_REC_BOM.ALT_ALLOC_PRIO := REC_BOM_EXP.ALT_ALLOC_PRIO;
		  L_REC_BOM.SNO1 := REC_BOM_EXP.SNO1;
		  L_REC_BOM.SNO_TYP1 := REC_BOM_EXP.SNO_TYP1;
		  L_REC_BOM.SNO2 := REC_BOM_EXP.SNO2;
		  L_REC_BOM.SNO_TYP2 := REC_BOM_EXP.SNO_TYP2;
		  L_REC_BOM.SNO3 := REC_BOM_EXP.SNO3;
		  L_REC_BOM.SNO_TYP3 := REC_BOM_EXP.SNO_TYP3;
		  L_REC_BOM.SNO4 := REC_BOM_EXP.SNO4;
		  L_REC_BOM.SNO_TYP4 := REC_BOM_EXP.SNO_TYP4;
		  L_REC_BOM.PAR_INST_QTY := REC_BOM_EXP.PAR_INST_QTY;
		  L_REC_BOM.CHD_RQMT_QTY := REC_BOM_EXP.CHD_RQMT_QTY;
		  L_REC_BOM.CHD_INPT_QTY := REC_BOM_EXP.CHD_INPT_QTY;
		  L_REC_BOM.FXD_CHD_RQMT_QTY := REC_BOM_EXP.FXD_CHD_RQMT_QTY;
		  L_REC_BOM.ALT_ITM_RATIO := REC_BOM_EXP.ALT_ITM_RATIO;
		  L_REC_BOM.ALT_ALLOC_PRIO := REC_BOM_EXP.ALT_ALLOC_PRIO;
		  L_REC_BOM.BYPROD_FLG := REC_BOM_EXP.BYPROD_FLG;
		  L_REC_BOM.IN_OFFST_TYP := REC_BOM_EXP.IN_OFFST_TYP;
		  L_REC_BOM.IN_OFFST := REC_BOM_EXP.IN_OFFST;
		  L_REC_BOM.BKF_TYP := REC_BOM_EXP.BKF_TYP;
		  L_REC_BOM.INST_LOT_FIX_FLG := REC_BOM_EXP.INST_LOT_FIX_FLG;
		  L_REC_BOM.LOT_MIX_FLG := REC_BOM_EXP.LOT_MIX_FLG;
		  L_REC_BOM.SUBLOT_MIX_FLG := REC_BOM_EXP.SUBLOT_MIX_FLG;
		  L_REC_BOM.ALLOC_CTL_TYP := REC_BOM_EXP.ALLOC_CTL_TYP;
		  L_REC_BOM.MAIN_ITM_FLG := REC_BOM_EXP.MAIN_ITM_FLG;
		  L_REC_BOM.YIELD_CALC_FLG := REC_BOM_EXP.YIELD_CALC_FLG;
		  L_REC_BOM.INPT_CTL_TYP := REC_BOM_EXP.INPT_CTL_TYP;
		  L_REC_BOM.DISP_SEQ := REC_BOM_EXP.DISP_SEQ;
		  L_REC_BOM.MEMO1 := REC_BOM_EXP.MEMO1;
		  L_REC_BOM.MEMO2 := REC_BOM_EXP.MEMO2;
		  L_REC_BOM.MEMO3 := REC_BOM_EXP.MEMO3;
		  L_REC_BOM.CUR_CD := REC_BOM_EXP.CUR_CD;

		  IF REC_BOM_EXP.ALT_GRP_CD IS NULL THEN
			  L_REC_BOM.ALT_GRP_SEQ := NULL;
		  ELSE
			  IF (L_ALT_GRP_CD IS NULL OR L_ALT_GRP_CD <> REC_BOM_EXP.ALT_GRP_CD OR L_ALT_ITM_FLG <> REC_BOM_EXP.ALT_ITM_FLG) THEN
				  L_ALT_GRP_CD := REC_BOM_EXP.ALT_GRP_CD;
				  L_ALT_ITM_FLG := REC_BOM_EXP.ALT_ITM_FLG;
				  L_EXIST_FLG := '0';
			  END IF;

			  L_EXIST_FLG := '0';
			  IF L_ALT_GRP_SEQ_ARRAY.COUNT > 0 THEN
				  FOR I IN L_ALT_GRP_SEQ_ARRAY.FIRST .. L_ALT_GRP_SEQ_ARRAY.LAST LOOP
					  IF L_ALT_GRP_SEQ_ARRAY(I).ALT_GRP_CD = REC_BOM_EXP.ALT_GRP_CD AND L_ALT_GRP_SEQ_ARRAY(I).ITM_CD = REC_BOM_EXP.ITM_CD
						  AND L_ALT_GRP_SEQ_ARRAY(I).ITM_SUB1 = REC_BOM_EXP.ITM_SUB1 AND L_ALT_GRP_SEQ_ARRAY(I).ITM_SUB2 = REC_BOM_EXP.ITM_SUB2
						  AND L_ALT_GRP_SEQ_ARRAY(I).ITM_SUB3 = REC_BOM_EXP.ITM_SUB3
						  AND (L_ALT_GRP_SEQ_ARRAY(I).VER_NO = REC_BOM_EXP.VER_NO OR (L_ALT_GRP_SEQ_ARRAY(I).VER_NO IS NULL AND REC_BOM_EXP.VER_NO IS NULL))
					  THEN
						  L_ALT_GRP_SEQ_ARRAY(I).ALT_GRP_SEQ := L_ALT_GRP_SEQ_ARRAY(I).ALT_GRP_SEQ + 1;
						  L_REC_BOM.ALT_GRP_SEQ := L_ALT_GRP_SEQ_ARRAY(I).ALT_GRP_SEQ;
						  L_EXIST_FLG := '1';
						  EXIT;
					  END IF;
				  END LOOP;
			  END IF;

			  IF L_EXIST_FLG = '0' THEN
				  L_REC_BOM.ALT_GRP_SEQ := 1;
				  -- 新しいエントリをコレクションに追加
				  L_ALT_GRP_SEQ_ARRAY(NVL(L_ALT_GRP_SEQ_ARRAY.LAST, 0) + 1) := L_REC_BOM;
			  END IF;
		  END IF;

		  -- レコードをテーブルに挿入
		INSERT INTO MSW_BOM_EXP_RSLT VALUES L_REC_BOM ;

		END LOOP;
	CLOSE C_BOM_EXP;
  END P_BOM_EXP_NO_RECURSIVE;

END;

