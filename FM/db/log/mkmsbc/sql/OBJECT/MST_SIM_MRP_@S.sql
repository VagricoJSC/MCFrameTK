CREATE OR REPLACE VIEW MST_SIM_MRP_$S(
	SIM_MRP_NO,
	WG_CD,
	SIM_MRP_TYP,
	SIM_USR_CD,
	DLY_RQMT_FLG,
	STK_FLG,
	GR_FLG,
	GI_FLG,
	SHIP_FLG,
	TREE_LVL,
	MRP_PROC_DT,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SIM_MRP_NO,
	ORG.WG_CD,
	ORG.SIM_MRP_TYP,
	ORG.SIM_USR_CD,
	ORG.DLY_RQMT_FLG,
	ORG.STK_FLG,
	ORG.GR_FLG,
	ORG.GI_FLG,
	ORG.SHIP_FLG,
	ORG.TREE_LVL,
	ORG.MRP_PROC_DT,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SIM_MRP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

