SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVM_MRP_ITM_DTL(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	MFG_LOC_CD,
	SPPL_CD,
	MAKER_CD,
	RQST_LOC_CD,
	WG_CD,
	BOM_PTN,
	ST_DT,
	SPPL_CAL_CD,
	RQST_SPPL_CD,
	RQST_SITE_CD,
	RQST_LG_GRP_CD,
	RQST_LG_CAL_CD,
	RQST_WG_CD,
	END_DT,
	OPER_PTN,
	ORDER_RATIO,
	MFG_LT,
	MFG_LT_ADD_QTY,
	PURC_LT,
	PURC_LT_ADD_QTY,
	ACCPT_INSP_LT,
	BUF_LT,
	SZ_DAY_WEEK_TYP,
	SZ_WEEK,
	LOT_SZ_PD,
	MIN_LOT_QTY,
	BATCH_LOT_QTY,
	MAX_LOT_QTY,
	YIELD_SCHD_QTY,
	MFG_INST_QTY,
	FXD_RQMT_QTY,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	PRIO,
	MAX_ORDER,
	ORD_FIX_PD,
	ORDER_STOP_DT
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.MFG_LOC_CD
	,T1.SPPL_CD
	,T1.MAKER_CD
	,T1.RQST_LOC_CD
	,T1.WG_CD
	,T1.BOM_PTN
	,T1.ST_DT
	,T3.SPPL_CAL_CD
	,T4.SPPL_CD AS RQST_SPPL_CD
	,T4.SITE_CD AS RQST_SITE_CD
	,T4.LG_GRP_CD AS RQST_LG_GRP_CD
	,DECODE(T7.LG_GRP_CD, NULL, NULL, NVL(T7.CAL_CD, T8.STD_CAL_CD)) AS RQST_LG_CAL_CD
	,NVL(T4.WG_CD, T1.RQST_WG_CD) AS RQST_WG_CD
	,T1.END_DT
	,T1.OPER_PTN
	,T1.ORDER_RATIO
	,T1.MFG_LT
	,T1.MFG_LT_ADD_QTY
	,T1.PURC_LT
	,T1.PURC_LT_ADD_QTY
	,T1.ACCPT_INSP_LT
	,T1.BUF_LT
	,T1.SZ_DAY_WEEK_TYP
	,T1.SZ_WEEK
	,T1.LOT_SZ_PD
	,T1.MIN_LOT_QTY
	,T1.BATCH_LOT_QTY
	,T1.MAX_LOT_QTY
	,T1.YIELD_SCHD_QTY
	,T1.MFG_INST_QTY
	,T1.FXD_RQMT_QTY
	,T1.SNO1
	,T1.SNO2
	,T1.SNO3
	,T1.SNO4
	,T1.PRIO
	,T1.MAX_ORDER
	,T1.ORD_FIX_PD
	,NVL(T5.ORDER_STOP_DT, T6.ORDER_STOP_DT) AS ORDER_STOP_DT
FROM MAM_ITM_DTL T1, MAM_LOC T2, MAM_BP T3, MAM_LOC T4, MAM_BP_STOP T5, MAM_BP_STOP T6, MAM_LG_GRP T7, MAM_CO T8
WHERE 0=0
AND T1.MFG_LOC_CD = T2.LOC_CD(+)
AND T1.SPPL_CD = T3.BP_CD(+)
AND T1.RQST_LOC_CD = T4.LOC_CD(+)
AND T1.SPPL_CD = T5.BP_CD(+)
AND T2.SPPL_CD = T6.BP_CD(+)
AND T4.LG_GRP_CD = T7.LG_GRP_CD(+)
AND T1.NOT_MRP_FLG = '0'
AND T5.DEL_FLG(+) = '0'
AND T6.DEL_FLG(+) = '0'
;

