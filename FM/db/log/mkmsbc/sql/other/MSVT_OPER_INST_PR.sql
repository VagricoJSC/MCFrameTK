SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_OPER_INST_PR(
	OPER_INST_NO,
	MFG_STS_TYP,
	MFG_INST_NO,
	ITM_MFG_INST_NO,
	BASE_UNIT_QTY,
	BASE_UNIT_REM_QTY,
	BASE_UNIT_ABORT_QTY,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
)
AS
SELECT
	T1.OPER_INST_NO,
	T1.MFG_STS_TYP,
	T1.MFG_INST_NO,
	T1.ITM_MFG_INST_NO,
	T1.BASE_UNIT_QTY,
	T1.BASE_UNIT_REM_QTY,
	T1.BASE_UNIT_ABORT_QTY,
	T1.SUB_CHAR1,
	T1.SUB_CHAR2,
	T1.SUB_CHAR3
FROM
	MST_OPER_ACT_REM T1
WHERE 0=0
AND	T1.DIV_SEQ = 0
;

