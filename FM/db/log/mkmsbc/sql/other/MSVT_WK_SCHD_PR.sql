SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_WK_SCHD_PR(
	WK_SCHD_NO,
	MFG_STS_TYP,
	MFG_INST_NO,
	ITM_MFG_INST_NO,
	OPER_INST_NO,
	FXD_WK_COST,
	WK_COST,
	REM_WK_COST,
	ABORT_WK_COST,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
)
AS
SELECT
	T1.WK_SCHD_NO,
	T1.MFG_STS_TYP,
	T1.MFG_INST_NO,
	T1.ITM_MFG_INST_NO,
	T1.OPER_INST_NO,
	T1.FXD_WK_COST,
	T1.WK_COST,
	T1.REM_WK_COST,
	T1.ABORT_WK_COST,
	T1.SUB_CHAR1,
	T1.SUB_CHAR2,
	T1.SUB_CHAR3
FROM
	MST_WK_ACT_REM T1
WHERE 0=0
AND	T1.DIV_SEQ = 0
;

