SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVM_MRP_ITM_SITE(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SITE_CD,
	IN_PRMT_INSP_FLG
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.SITE_CD
	,T1.IN_PRMT_INSP_FLG
FROM MAM_ITM_SITE T1
WHERE 0=0
AND T1.IN_PRMT_INSP_FLG = '1'
AND T1.DEL_FLG = '0'
;

