CREATE OR REPLACE VIEW MSVT_YIELD_SCHD_PR(
	YIELD_SCHD_NO,
	MFG_STS_TYP,
	MFG_INST_NO,
	ITM_MFG_INST_NO,
	OPER_INST_NO,
	YIELD_TYP,
	TRD_UNIT_YIELD_QTY,
	TRD_UNIT_YIELD_REM_QTY,
	TRD_UNIT_YIELD_ABORT_QTY,
	BASE_UNIT_YIELD_QTY,
	BASE_UNIT_YIELD_REM_QTY,
	BASE_UNIT_YIELD_ABORT_QTY,
	STK_LST_PRNT_FLG,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
)
AS
SELECT
	T1.YIELD_SCHD_NO,
	T1.MFG_STS_TYP,
	T1.MFG_INST_NO,
	T1.ITM_MFG_INST_NO,
	T1.OPER_INST_NO,
	T1.YIELD_TYP,
	T1.TRD_UNIT_YIELD_QTY,
	T1.TRD_UNIT_YIELD_REM_QTY,
	T1.TRD_UNIT_YIELD_ABORT_QTY,
	T1.BASE_UNIT_YIELD_QTY,
	T1.BASE_UNIT_YIELD_REM_QTY,
	T1.BASE_UNIT_YIELD_ABORT_QTY,
	T1.STK_LST_PRNT_FLG,
	T1.SUB_CHAR1,
	T1.SUB_CHAR2,
	T1.SUB_CHAR3
FROM
	MST_YIELD_ACT_REM T1
WHERE 0=0
AND	T1.DIV_SEQ = 0
;

