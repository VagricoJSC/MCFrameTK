CREATE OR REPLACE VIEW MSVM_MRP_STK_RPL(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	ST_DT,
	END_DT,
	BUF_QTY,
	WG_CD
)
AS
SELECT
	 T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.LOC_CD
	,T1.ST_DT
	,T1.END_DT
	,T1.BUF_QTY
	,T2.WG_CD
FROM MAM_STK_RPL T1, MAM_LOC T2
WHERE 0=0
AND T1.BUF_QTY > 0
AND T1.LOC_CD = T2.LOC_CD
AND T1.DEL_FLG = '0'
;

