CREATE OR REPLACE VIEW MSVM_MRP_PURC_DDLV_LT(
	SPPL_CD,
	LG_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ST_DT,
	END_DT,
	PURC_LT,
	PURC_LT_ADD_QTY
)
AS
SELECT
	 T1.SPPL_CD
	,T1.LG_GRP_CD
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.ST_DT
	,T1.END_DT
	,T1.PURC_LT
	,T1.PURC_LT_ADD_QTY
FROM MAM_PURC_DDLV_LT T1
WHERE 0=0
AND T1.DEL_FLG = '0'
;

