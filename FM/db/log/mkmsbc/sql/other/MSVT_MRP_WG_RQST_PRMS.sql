CREATE OR REPLACE VIEW MSVT_MRP_WG_RQST_PRMS(
	RQMT_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STRG_LOC_CD,
	MFG_LOC_CD,
	SPPL_CD,
	RQST_LOC_CD,
	DUE_DT,
	RQMT_QTY,
	SNO1,
	SNO1_TYP,
	SNO2,
	SNO2_TYP,
	SNO3,
	SNO3_TYP,
	SNO4,
	SNO4_TYP,
	WG_CD,
	RQMT_TYP
)
AS
SELECT
	 T1.WG_RQST_NO AS RQMT_NO
	,T1.ITM_CD
	,T1.ITM_SUB1
	,T1.ITM_SUB2
	,T1.ITM_SUB3
	,T1.GR_LOC_CD AS STRG_LOC_CD
	,CAST(MAC_STR.NULL_VAL AS VARCHAR2(1 CHAR)) AS MFG_LOC_CD
	,T1.SPPL_CD
	,T1.GI_LOC_CD AS RQST_LOC_CD
	,TRUNC(T1.GR_RQST_TM) AS DUE_DT
	,T1.NOT_CMPL_QTY AS RQMT_QTY
	,T1.SNO1
	,CAST(DECODE(T1.SNO1, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO1_TYP
	,T1.SNO2
	,CAST(DECODE(T1.SNO2, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO2_TYP
	,T1.SNO3
	,CAST(DECODE(T1.SNO3, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO3_TYP
	,T1.SNO4
	,CAST(DECODE(T1.SNO4, MAC_STR.NULL_VAL, MAC_SNO_TYP.NO_EXTND, MAC_SNO_TYP.EXTND) AS VARCHAR2(1 CHAR)) SNO4_TYP
	,T1.RQST_TO_WG_CD AS WG_CD
	,CAST(MAC_RQMT_TYP.ALLOC AS VARCHAR2(1 CHAR)) AS RQMT_TYP
FROM
	MST_WG_RQST T1
WHERE 0=0
AND WG_RQST_STS_TYP IN (MSC_WG_RQST_STS_TYP.RQST, MSC_WG_RQST_STS_TYP.PRMS, MSC_WG_RQST_STS_TYP.INST)
AND T1.CAN_FLG = '0'
AND T1.NOT_CMPL_QTY <> 0
AND T1.WG_RQST_TYP = MSC_WG_RQST_TYP.PURC
;

