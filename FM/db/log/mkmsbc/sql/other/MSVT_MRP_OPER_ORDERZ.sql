SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVT_MRP_OPER_ORDERZ(
	OPER_ORD_NO,
	OPER_ORD_STS_TYP,
	ITM_ORD_NO,
	LOC_CD,
	OPER_SCHD_QTY,
	ST_SCHD_TM,
	END_SCHD_TM,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	DISP_SEQ,
	WG_CD
)
AS
SELECT
	  T1.OPER_ORD_NO
	 ,T1.OPER_ORD_STS_TYP
	 ,T1.ITM_ORD_NO
	 ,T1.LOC_CD
	 ,T1.OPER_SCHD_QTY
	 ,T1.ST_SCHD_TM
	 ,T1.END_SCHD_TM
	 ,T1.OPER_PTN
	 ,T1.OPER_CD
	 ,T1.OPER_SEQ
	 ,T1.DISP_SEQ
	 ,T1.WG_CD
FROM
	 MST_OPER_ORDER T1
	,MST_ITM_ORDER T2
WHERE 0=0
AND T1.ITM_ORD_NO = T2.ITM_ORD_NO
AND T1.ITM_ORD_STS_TYP in (MSC_ITM_ORD_STS_TYP.SAV, MSC_ITM_ORD_STS_TYP.OPN)
;

