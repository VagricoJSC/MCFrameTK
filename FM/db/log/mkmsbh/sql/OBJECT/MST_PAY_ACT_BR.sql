CREATE OR REPLACE VIEW MST_PAY_ACT_BR(
	BATCH_DATA_NO,
	PAY_CHK_NO,
	PAY_SCHD_NO,
	PSPPL_CD,
	BSPPL_CD,
	BSPPL_DPT_CD,
	AP_STTL_CD,
	AP_STTL_TYP,
	PAY_SCHD_DT,
	REG_DT,
	BSPPL_CL_DT,
	EXE_STS_TYP,
	BATCH_LOG_NO,
	LOG_SUB_KEY1,
	LOG_SUB_KEY2,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BATCH_DATA_NO,
	ORG.PAY_CHK_NO,
	ORG.PAY_SCHD_NO,
	ORG.PSPPL_CD,
	ORG.BSPPL_CD,
	ORG.BSPPL_DPT_CD,
	ORG.AP_STTL_CD,
	ORG.AP_STTL_TYP,
	ORG.PAY_SCHD_DT,
	ORG.REG_DT,
	ORG.BSPPL_CL_DT,
	ORG.EXE_STS_TYP,
	ORG.BATCH_LOG_NO,
	ORG.LOG_SUB_KEY1,
	ORG.LOG_SUB_KEY2,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PAY_ACT_BR_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

