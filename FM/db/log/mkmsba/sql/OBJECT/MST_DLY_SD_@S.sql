	DLY_SD_NO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STRG_LOC_CD,
	DUE_DT,
	RQMT_QTY,
	MFG_LOC_CD,
	SPPL_CD,
	RQST_LOC_CD,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	WG_CD,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
