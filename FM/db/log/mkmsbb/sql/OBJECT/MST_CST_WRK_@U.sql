CREATE OR REPLACE VIEW MST_CST_WRK_$U(
	WRK_NO,
	CST_CD,
	CST_SUNDRY_FLG,
	CST_NM,
	CST_CNTCT_DPT,
	CST_CNTCT_PSN,
	ZIP_CD,
	ADDR1,
	ADDR2,
	ADDR3,
	ADDR4,
	TEL,
	FAX,
	CAPITAL,
	EMP_NUM,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.WRK_NO,
	ORG.CST_CD,
	ORG.CST_SUNDRY_FLG,
	ORG.CST_NM,
	ORG.CST_CNTCT_DPT,
	ORG.CST_CNTCT_PSN,
	ORG.ZIP_CD,
	ORG.ADDR1,
	ORG.ADDR2,
	ORG.ADDR3,
	ORG.ADDR4,
	ORG.TEL,
	ORG.FAX,
	ORG.CAPITAL,
	ORG.EMP_NUM,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_CST_WRK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

