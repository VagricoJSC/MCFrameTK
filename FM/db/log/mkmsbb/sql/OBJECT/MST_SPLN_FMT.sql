SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_SPLN_FMT(
	SPLN_FMT_NO,
	DPT_CD,
	CST_CD,
	WRK_NO,
	SPLN_ITM_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	CUR_CD,
	SPLN_SET_TYP,
	CST_CD_UNIT_FLG,
	WRK_NO_UNIT_FLG,
	DISP_SEQ,
	ST_YM,
	END_YM,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SPLN_FMT_NO,
	ORG.DPT_CD,
	ORG.CST_CD,
	ORG.WRK_NO,
	ORG.SPLN_ITM_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.CUR_CD,
	ORG.SPLN_SET_TYP,
	ORG.CST_CD_UNIT_FLG,
	ORG.WRK_NO_UNIT_FLG,
	ORG.DISP_SEQ,
	ORG.ST_YM,
	ORG.END_YM,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SPLN_FMT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

