CREATE OR REPLACE VIEW MST_SLS_BDG_$S(
	YM,
	SLS_DPT_CD,
	WG_CD,
	SLS_ITM_GRP_CD,
	CST_CD,
	SLS_USR_CD,
	TRD_CUR_CD,
	WRK_NO,
	SLS_BDG_GRP,
	BDG_SLS_AMT,
	BDG_SLS_PROF_RATE,
	BDG_SLS_PROF_AMT,
	NOT_SUM_FLG,
	SLS_ITM_GRP_NOT_SUM_FLG,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.YM,
	ORG.SLS_DPT_CD,
	ORG.WG_CD,
	ORG.SLS_ITM_GRP_CD,
	ORG.CST_CD,
	ORG.SLS_USR_CD,
	ORG.TRD_CUR_CD,
	ORG.WRK_NO,
	ORG.SLS_BDG_GRP,
	ORG.BDG_SLS_AMT,
	ORG.BDG_SLS_PROF_RATE,
	ORG.BDG_SLS_PROF_AMT,
	ORG.NOT_SUM_FLG,
	ORG.SLS_ITM_GRP_NOT_SUM_FLG,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SLS_BDG_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

