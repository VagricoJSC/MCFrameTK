SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_SLO_PRMS_H(
	SLO_PRMS_H_NO,
	SLO_PRMS_REV,
	LAST_PRMS_REV,
	SLO_D_NO,
	EDI_PRMS_FLG,
	PRMS_PRNT_TM,
	SLO_PRMS_PRNT_FLG,
	CAN_FLG,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLO_PRMS_H_NO,
	ORG.SLO_PRMS_REV,
	ORG.LAST_PRMS_REV,
	ORG.SLO_D_NO,
	ORG.EDI_PRMS_FLG,
	ORG.PRMS_PRNT_TM,
	ORG.SLO_PRMS_PRNT_FLG,
	ORG.CAN_FLG,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SLO_PRMS_H_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

