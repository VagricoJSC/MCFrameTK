CREATE OR REPLACE VIEW MST_SLS_ITM_COMP(
	SLS_ITM_COMP_NO,
	SLS_ITM_NO,
	SLS_ITM_COMP_LNO,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_NM,
	SUNDRY_ITM_FLG,
	CORE_ITM_FLG,
	TRD_UNIT_CD,
	TRD_UNIT_QTY,
	BASE_UNIT_CD,
	BASE_UNIT_QTY,
	COST_UPRI,
	COST_AMT,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	MST_FLG,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLS_ITM_COMP_NO,
	ORG.SLS_ITM_NO,
	ORG.SLS_ITM_COMP_LNO,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_NM,
	ORG.SUNDRY_ITM_FLG,
	ORG.CORE_ITM_FLG,
	ORG.TRD_UNIT_CD,
	ORG.TRD_UNIT_QTY,
	ORG.BASE_UNIT_CD,
	ORG.BASE_UNIT_QTY,
	ORG.COST_UPRI,
	ORG.COST_AMT,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.MST_FLG,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_SLS_ITM_COMP_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

