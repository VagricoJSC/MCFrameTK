SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_AC_DPT(
	AC_DPT_CD,
	ST_DT,
	END_DT,
	AC_DPT_NM,
	BASE_AC_DPT_NM,
	SLIP_CNT_ID,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	COST_CENTER
	)
AS
SELECT
	ORG.AC_DPT_CD,
	ORG.ST_DT,
	ORG.END_DT,
	LCL.AC_DPT_NM,
	ORG.AC_DPT_NM AS BASE_AC_DPT_NM,
	ORG.SLIP_CNT_ID,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ORG.COST_CENTER
FROM
	MAM_AC_DPT_ALL ORG,
	mam_ac_dpt_lcl_all LCL
WHERE
	0 = 0
	AND ORG.AC_DPT_CD = LCL.AC_DPT_CD(+)
	AND ORG.ST_DT = LCL.ST_DT(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_ac_dpt'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

