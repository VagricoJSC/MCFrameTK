SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_SLIP_FORM_$S(
	SLIP_FORM_CD,
	SLIP_FORM_NM,
	BASE_SLIP_FORM_NM,
	SLIP_FORM_ID,
	COPY_SLIP_FORM_ID,
	LINE_NUM,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SLIP_FORM_CD,
	LCL.SLIP_FORM_NM,
	ORG.SLIP_FORM_NM AS BASE_SLIP_FORM_NM,
	ORG.SLIP_FORM_ID,
	ORG.COPY_SLIP_FORM_ID,
	ORG.LINE_NUM,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SLIP_FORM_ALL ORG,
	mam_slip_form_lcl_all LCL
WHERE
	0 = 0
	AND ORG.SLIP_FORM_CD = LCL.SLIP_FORM_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_slip_form'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

