SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_BP_CMN_TR_L
AFTER INSERT OR UPDATE ON MAM_BP_CMN
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
	SME BOOLEAN;
BEGIN
	IF (:OLD.BP_NM IS NOT NULL AND :NEW.BP_NM IS NOT NULL) THEN
		SME := (:OLD.BP_NM = :NEW.BP_NM);
	ELSE
		SME := (:OLD.BP_NM IS NULL AND :NEW.BP_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.BP_ALT_NM1 IS NOT NULL AND :NEW.BP_ALT_NM1 IS NOT NULL) THEN
		SME := (:OLD.BP_ALT_NM1 = :NEW.BP_ALT_NM1);
	ELSE
		SME := (:OLD.BP_ALT_NM1 IS NULL AND :NEW.BP_ALT_NM1 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.BP_ALT_NM2 IS NOT NULL AND :NEW.BP_ALT_NM2 IS NOT NULL) THEN
		SME := (:OLD.BP_ALT_NM2 = :NEW.BP_ALT_NM2);
	ELSE
		SME := (:OLD.BP_ALT_NM2 IS NULL AND :NEW.BP_ALT_NM2 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.BP_ALT_NM3 IS NOT NULL AND :NEW.BP_ALT_NM3 IS NOT NULL) THEN
		SME := (:OLD.BP_ALT_NM3 = :NEW.BP_ALT_NM3);
	ELSE
		SME := (:OLD.BP_ALT_NM3 IS NULL AND :NEW.BP_ALT_NM3 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.BP_ALT_NM4 IS NOT NULL AND :NEW.BP_ALT_NM4 IS NOT NULL) THEN
		SME := (:OLD.BP_ALT_NM4 = :NEW.BP_ALT_NM4);
	ELSE
		SME := (:OLD.BP_ALT_NM4 IS NULL AND :NEW.BP_ALT_NM4 IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	<<MDIFF>>
	IF INSERTING OR (UPDATING AND NOT SME) THEN
	MERGE INTO MAM_BP_LCL_CMN LCL
		USING  DUAL
		ON (0=0
			AND LCL.LCL_CD = FCPA_CONTEXT.F_GET_DEF_LOCALE_CD
			AND LCL.BP_CD = :NEW.BP_CD
		)
		WHEN MATCHED THEN
			UPDATE
			SET
				LCL.BP_NM=:NEW.BP_NM,
				LCL.BP_ALT_NM1=:NEW.BP_ALT_NM1,
				LCL.BP_ALT_NM2=:NEW.BP_ALT_NM2,
				LCL.BP_ALT_NM3=:NEW.BP_ALT_NM3,
				LCL.BP_ALT_NM4=:NEW.BP_ALT_NM4,
				LCL.INS_USR_ID=:NEW.INS_USR_ID,
				LCL.INS_USR_NM=:NEW.INS_USR_NM,
				LCL.INS_FUNC_ID=:NEW.INS_FUNC_ID,
				LCL.UPD_USR_ID=:NEW.UPD_USR_ID,
				LCL.UPD_USR_NM=:NEW.UPD_USR_NM,
				LCL.UPD_FUNC_ID=:NEW.UPD_FUNC_ID,
				LCL.UPD_SRV_REQ_NO=:NEW.UPD_SRV_REQ_NO
		WHEN NOT MATCHED THEN
			INSERT(
				LCL_CD,
				BP_CD,
				BP_NM,
				BP_ALT_NM1,
				BP_ALT_NM2,
				BP_ALT_NM3,
				BP_ALT_NM4,
				INS_USR_ID,
				INS_USR_NM,
				INS_FUNC_ID,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)VALUES(
				FCPA_CONTEXT.F_GET_DEF_LOCALE_CD,
				:NEW.BP_CD,
				:NEW.BP_NM,
				:NEW.BP_ALT_NM1,
				:NEW.BP_ALT_NM2,
				:NEW.BP_ALT_NM3,
				:NEW.BP_ALT_NM4,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
			)
		;
	END IF;
END;

/
show errors;


