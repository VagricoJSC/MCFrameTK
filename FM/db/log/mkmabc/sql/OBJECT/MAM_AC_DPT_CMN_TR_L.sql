SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_AC_DPT_CMN_TR_L
AFTER INSERT OR UPDATE ON MAM_AC_DPT_CMN
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
	SME BOOLEAN;
BEGIN
	IF (:OLD.AC_DPT_NM IS NOT NULL AND :NEW.AC_DPT_NM IS NOT NULL) THEN
		SME := (:OLD.AC_DPT_NM = :NEW.AC_DPT_NM);
	ELSE
		SME := (:OLD.AC_DPT_NM IS NULL AND :NEW.AC_DPT_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	<<MDIFF>>
	IF INSERTING OR (UPDATING AND NOT SME) THEN
	MERGE INTO MAM_AC_DPT_LCL_CMN LCL
		USING  DUAL
		ON (0=0
			AND LCL.LCL_CD = FCPA_CONTEXT.F_GET_DEF_LOCALE_CD
			AND LCL.AC_DPT_CD = :NEW.AC_DPT_CD
			AND LCL.ST_DT = :NEW.ST_DT
		)
		WHEN MATCHED THEN
			UPDATE
			SET
				LCL.AC_DPT_NM=:NEW.AC_DPT_NM,
				LCL.INS_USR_ID=:NEW.INS_USR_ID,
				LCL.INS_USR_NM=:NEW.INS_USR_NM,
				LCL.INS_FUNC_ID=:NEW.INS_FUNC_ID,
				LCL.UPD_USR_ID=:NEW.UPD_USR_ID,
				LCL.UPD_USR_NM=:NEW.UPD_USR_NM,
				LCL.UPD_FUNC_ID=:NEW.UPD_FUNC_ID,
				LCL.UPD_SRV_REQ_NO=:NEW.UPD_SRV_REQ_NO
		WHEN NOT MATCHED THEN
			INSERT(
				LCL_CD,
				AC_DPT_CD,
				ST_DT,
				AC_DPT_NM,
				INS_USR_ID,
				INS_USR_NM,
				INS_FUNC_ID,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)VALUES(
				FCPA_CONTEXT.F_GET_DEF_LOCALE_CD,
				:NEW.AC_DPT_CD,
				:NEW.ST_DT,
				:NEW.AC_DPT_NM,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
			)
		;
	END IF;
END;

/
show errors;


