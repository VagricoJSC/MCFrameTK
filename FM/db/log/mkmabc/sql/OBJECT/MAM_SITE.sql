SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_SITE(
	SITE_CD,
	SITE_NM,
	BASE_SITE_NM,
	ARR_FLG,
	ZIP_CD,
	BASE_ZIP_CD,
	ADDR1,
	BASE_ADDR1,
	ADDR2,
	BASE_ADDR2,
	ADDR3,
	BASE_ADDR3,
	ADDR4,
	BASE_ADDR4,
	TEL,
	BASE_TEL,
	FAX,
	BASE_FAX,
	DEF_LOC_GRP_CD,
	DEF_ALLOC_GRP_CD,
	DEF_LG_GRP_CD,
	DEF_CAL_CD,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SITE_CD,
	LCL.SITE_NM,
	ORG.SITE_NM AS BASE_SITE_NM,
	ORG.ARR_FLG,
	LCL.ZIP_CD,
	ORG.ZIP_CD AS BASE_ZIP_CD,
	LCL.ADDR1,
	ORG.ADDR1 AS BASE_ADDR1,
	LCL.ADDR2,
	ORG.ADDR2 AS BASE_ADDR2,
	LCL.ADDR3,
	ORG.ADDR3 AS BASE_ADDR3,
	LCL.ADDR4,
	ORG.ADDR4 AS BASE_ADDR4,
	LCL.TEL,
	ORG.TEL AS BASE_TEL,
	LCL.FAX,
	ORG.FAX AS BASE_FAX,
	ORG.DEF_LOC_GRP_CD,
	ORG.DEF_ALLOC_GRP_CD,
	ORG.DEF_LG_GRP_CD,
	ORG.DEF_CAL_CD,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SITE_ALL ORG,
	mam_site_lcl_all LCL
WHERE
	0 = 0
	AND ORG.SITE_CD = LCL.SITE_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_site'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

