SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_ACCOUNT_$S(
	AC_CD,
	AC_NM,
	BASE_AC_NM,
	AC_NM2,
	BASE_AC_NM2,
	DC_TYP,
	SUB_FLG,
	AC_TYP,
	AC_TAX_CD,
	AC_TAX_TYP,
	FOREIGN_FLG,
	SUM0_FLG,
	SUM1_FLG,
	SUM2_FLG,
	SUM3_FLG,
	SUM4_FLG,
	SUM5_FLG,
	PROJECT_FLG,
	BP_FLG,
	USR_FLG,
	BANK_AC_FLG,
	AP_TYP,
	AR_TYP,
	AC_TYP1,
	AC_TYP2,
	AC_TYP3,
	AC_TYP4,
	AC_TYP5,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.AC_CD,
	LCL.AC_NM,
	ORG.AC_NM AS BASE_AC_NM,
	LCL.AC_NM2,
	ORG.AC_NM2 AS BASE_AC_NM2,
	ORG.DC_TYP,
	ORG.SUB_FLG,
	ORG.AC_TYP,
	ORG.AC_TAX_CD,
	ORG.AC_TAX_TYP,
	ORG.FOREIGN_FLG,
	ORG.SUM0_FLG,
	ORG.SUM1_FLG,
	ORG.SUM2_FLG,
	ORG.SUM3_FLG,
	ORG.SUM4_FLG,
	ORG.SUM5_FLG,
	ORG.PROJECT_FLG,
	ORG.BP_FLG,
	ORG.USR_FLG,
	ORG.BANK_AC_FLG,
	ORG.AP_TYP,
	ORG.AR_TYP,
	ORG.AC_TYP1,
	ORG.AC_TYP2,
	ORG.AC_TYP3,
	ORG.AC_TYP4,
	ORG.AC_TYP5,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ACCOUNT_ALL ORG,
	mam_account_lcl_all LCL
WHERE
	0 = 0
	AND ORG.AC_CD = LCL.AC_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_account'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

