SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_STTL(
	STTL_CD,
	STTL_NM,
	BASE_STTL_NM,
	AR_STTL_FLG,
	AP_STTL_FLG,
	AR_STTL_TYP,
	RCV_REG_TYP,
	SLS_PURC_TYP,
	CALC_COM_PAID_FLG,
	AR_SETOFF_CD,
	DEBT_CRED_ID_TYP,
	AP_STTL_TYP,
	AP_SETOFF_TYP,
	AP_SETOFF_ACT_FLG,
	BILL_TAX_DISP_FLG,
	AC_RSN_CD,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.STTL_CD,
	LCL.STTL_NM,
	ORG.STTL_NM AS BASE_STTL_NM,
	ORG.AR_STTL_FLG,
	ORG.AP_STTL_FLG,
	ORG.AR_STTL_TYP,
	ORG.RCV_REG_TYP,
	ORG.SLS_PURC_TYP,
	ORG.CALC_COM_PAID_FLG,
	ORG.AR_SETOFF_CD,
	ORG.DEBT_CRED_ID_TYP,
	ORG.AP_STTL_TYP,
	ORG.AP_SETOFF_TYP,
	ORG.AP_SETOFF_ACT_FLG,
	ORG.BILL_TAX_DISP_FLG,
	ORG.AC_RSN_CD,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_STTL_ALL ORG,
	mam_sttl_lcl_all LCL
WHERE
	0 = 0
	AND ORG.STTL_CD = LCL.STTL_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_sttl'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

