SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_IF_ADAPTER(
	EXT_SYS_CD,
	IF_PROC_TYP,
	ST_DT,
	END_DT,
	CONV_OPE,
	FILE_IO_OPE,
	WEB_API_OPE,
	CMD_EXEC_OPE,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.EXT_SYS_CD,
	ORG.IF_PROC_TYP,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.CONV_OPE,
	ORG.FILE_IO_OPE,
	ORG.WEB_API_OPE,
	ORG.CMD_EXEC_OPE,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_IF_ADAPTER_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_if_adapter'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

