CREATE OR REPLACE VIEW MAM_LOC_LCL_$S(
	LOC_CD,
	LOC_NM,
	ZIP_CD,
	ADDR1,
	ADDR2,
	ADDR3,
	ADDR4,
	TEL,
	FAX,
	MEMO1,
	MEMO2,
	MEMO3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	LCL_CD
	)
AS
SELECT
	ORG.LOC_CD,
	ORG.LOC_NM,
	ORG.ZIP_CD,
	ORG.ADDR1,
	ORG.ADDR2,
	ORG.ADDR3,
	ORG.ADDR4,
	ORG.TEL,
	ORG.FAX,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ORG.LCL_CD
FROM
	MAM_LOC_LCL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

