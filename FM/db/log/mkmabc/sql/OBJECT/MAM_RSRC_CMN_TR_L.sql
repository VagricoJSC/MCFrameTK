SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_RSRC_CMN_TR_L
AFTER INSERT OR UPDATE ON MAM_RSRC_CMN
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
	SME BOOLEAN;
BEGIN
	IF (:OLD.RSRC_NM IS NOT NULL AND :NEW.RSRC_NM IS NOT NULL) THEN
		SME := (:OLD.RSRC_NM = :NEW.RSRC_NM);
	ELSE
		SME := (:OLD.RSRC_NM IS NULL AND :NEW.RSRC_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	IF (:OLD.RSRC_UNIT_NM IS NOT NULL AND :NEW.RSRC_UNIT_NM IS NOT NULL) THEN
		SME := (:OLD.RSRC_UNIT_NM = :NEW.RSRC_UNIT_NM);
	ELSE
		SME := (:OLD.RSRC_UNIT_NM IS NULL AND :NEW.RSRC_UNIT_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	<<MDIFF>>
	IF INSERTING OR (UPDATING AND NOT SME) THEN
	MERGE INTO MAM_RSRC_LCL_CMN LCL
		USING  DUAL
		ON (0=0
			AND LCL.LCL_CD = FCPA_CONTEXT.F_GET_DEF_LOCALE_CD
			AND LCL.RSRC_CD = :NEW.RSRC_CD
		)
		WHEN MATCHED THEN
			UPDATE
			SET
				LCL.RSRC_NM=:NEW.RSRC_NM,
				LCL.RSRC_UNIT_NM=:NEW.RSRC_UNIT_NM,
				LCL.INS_USR_ID=:NEW.INS_USR_ID,
				LCL.INS_USR_NM=:NEW.INS_USR_NM,
				LCL.INS_FUNC_ID=:NEW.INS_FUNC_ID,
				LCL.UPD_USR_ID=:NEW.UPD_USR_ID,
				LCL.UPD_USR_NM=:NEW.UPD_USR_NM,
				LCL.UPD_FUNC_ID=:NEW.UPD_FUNC_ID,
				LCL.UPD_SRV_REQ_NO=:NEW.UPD_SRV_REQ_NO
		WHEN NOT MATCHED THEN
			INSERT(
				LCL_CD,
				RSRC_CD,
				RSRC_NM,
				RSRC_UNIT_NM,
				INS_USR_ID,
				INS_USR_NM,
				INS_FUNC_ID,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)VALUES(
				FCPA_CONTEXT.F_GET_DEF_LOCALE_CD,
				:NEW.RSRC_CD,
				:NEW.RSRC_NM,
				:NEW.RSRC_UNIT_NM,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
			)
		;
	END IF;
END;

/
show errors;


