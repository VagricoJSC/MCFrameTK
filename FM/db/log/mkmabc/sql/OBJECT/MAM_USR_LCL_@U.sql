CREATE OR REPLACE VIEW MAM_USR_LCL_$U(
	USR_CD,
	USR_NM,
	USR_ALT_NM1,
	USR_ALT_NM2,
	USR_ALT_NM3,
	USR_ALT_NM4,
	MEMO1,
	MEMO2,
	MEMO3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	LCL_CD
	)
AS
SELECT
	ORG.USR_CD,
	ORG.USR_NM,
	ORG.USR_ALT_NM1,
	ORG.USR_ALT_NM2,
	ORG.USR_ALT_NM3,
	ORG.USR_ALT_NM4,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO,
	ORG.LCL_CD
FROM
	MAM_USR_LCL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

