SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_JNL_ACT(
	JNL_ACT_CD,
	JNL_ACT_NM,
	BASE_JNL_ACT_NM,
	JNL_DEL_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.JNL_ACT_CD,
	LCL.JNL_ACT_NM,
	ORG.JNL_ACT_NM AS BASE_JNL_ACT_NM,
	ORG.JNL_DEL_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_JNL_ACT_ALL ORG,
	mam_jnl_act_lcl_all LCL
WHERE
	0 = 0
	AND ORG.JNL_ACT_CD = LCL.JNL_ACT_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_jnl_act'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

