CREATE OR REPLACE VIEW MAM_BANK_AC_$U(
	BANK_AC_CD,
	BANK_AC_NM,
	EXT_FLG,
	BANK_CD,
	BRANCH_CD,
	BANK_AC_NO,
	BANK_AC_TYP,
	BANK_AC_HOLDER,
	BANK_AC_HOLDER_SUB,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BANK_AC_CD,
	ORG.BANK_AC_NM,
	ORG.EXT_FLG,
	ORG.BANK_CD,
	ORG.BRANCH_CD,
	ORG.BANK_AC_NO,
	ORG.BANK_AC_TYP,
	ORG.BANK_AC_HOLDER,
	ORG.BANK_AC_HOLDER_SUB,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_BANK_AC_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

