CREATE OR REPLACE VIEW MAM_LG_GRP(
	LG_GRP_CD,
	LG_GRP_NM,
	BASE_LG_GRP_NM,
	LOC_FLG,
	WG_CD,
	SHIP_SLIP_FLG,
	PICK_LIST_FLG,
	SHIP_INST_FLG,
	SHIP_SLIP_ACT_FLG,
	CAL_CD,
	SITE_CO_CD,
	GI_MINUS_STK_CHK_FLG,
	SHIP_LOC_PRIO_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.LG_GRP_CD,
	LCL.LG_GRP_NM,
	ORG.LG_GRP_NM AS BASE_LG_GRP_NM,
	ORG.LOC_FLG,
	ORG.WG_CD,
	ORG.SHIP_SLIP_FLG,
	ORG.PICK_LIST_FLG,
	ORG.SHIP_INST_FLG,
	ORG.SHIP_SLIP_ACT_FLG,
	ORG.CAL_CD,
	ORG.SITE_CO_CD,
	ORG.GI_MINUS_STK_CHK_FLG,
	ORG.SHIP_LOC_PRIO_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_LG_GRP_ALL ORG,
	mam_lg_grp_lcl_all LCL
WHERE
	0 = 0
	AND ORG.LG_GRP_CD = LCL.LG_GRP_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_lg_grp'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

