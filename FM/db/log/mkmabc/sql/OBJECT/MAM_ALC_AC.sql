SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_ALC_AC(
	ALC_AC_CD,
	ALC_AC_NM,
	BASE_ALC_AC_NM,
	ALC_PTN_CD,
	EXPNS_CD,
	ALC_AC_GRP_CD1,
	ALC_AC_GRP_CD2,
	ALC_AC_GRP_CD3,
	CO_ALC_AC_CD,
	NOT_ITM_ALC_AC_FLG,
	NOT_ALC_RATE_AC_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ALC_AC_CD,
	LCL.ALC_AC_NM,
	ORG.ALC_AC_NM AS BASE_ALC_AC_NM,
	ORG.ALC_PTN_CD,
	ORG.EXPNS_CD,
	ORG.ALC_AC_GRP_CD1,
	ORG.ALC_AC_GRP_CD2,
	ORG.ALC_AC_GRP_CD3,
	ORG.CO_ALC_AC_CD,
	ORG.NOT_ITM_ALC_AC_FLG,
	ORG.NOT_ALC_RATE_AC_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ALC_AC_ALL ORG,
	mam_alc_ac_lcl_all LCL
WHERE
	0 = 0
	AND ORG.ALC_AC_CD = LCL.ALC_AC_CD(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_alc_ac'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

