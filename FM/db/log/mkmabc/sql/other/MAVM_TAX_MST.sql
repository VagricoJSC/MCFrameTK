SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_TAX_MST(
	TAX_CD,
	TAX_NM,
	TAX_TYP,
	INC_TAX_FLG,
	TAX_RATE,
	SLS_FLG,
	PURC_FLG,
	PROV_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	TAX_NM_LCL1,
	TAX_NM_LCL2,
	TAX_NM_LCL3,
	TAX_NM_LCL4,
	TAX_NM_LCL5
)
AS
SELECT
	T1.TAX_CD,
	T1.TAX_NM,
	T1.TAX_TYP,
	T1.INC_TAX_FLG,
	T1.TAX_RATE,
	T1.SLS_FLG,
	T1.PURC_FLG,
	T1.PROV_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--税名（ロケール１）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_ALL T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	TAX_NM_LCL1,
	--税名（ロケール２）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_ALL T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	TAX_NM_LCL2,
	--税名（ロケール３）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_ALL T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	TAX_NM_LCL3,
	--税名（ロケール４）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_ALL T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	TAX_NM_LCL4,
	--税名（ロケール５）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_ALL T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	TAX_NM_LCL5
	FROM MAM_TAX_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_TAX
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_TAX
			)
		)
	)
UNION ALL
SELECT
	T1.TAX_CD,
	T1.TAX_NM,
	T1.TAX_TYP,
	T1.INC_TAX_FLG,
	T1.TAX_RATE,
	T1.SLS_FLG,
	T1.PURC_FLG,
	T1.PROV_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--税名（ロケール１）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_CMN T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.LCL_CD = 'ja_JP'
	)	TAX_NM_LCL1,
	--税名（ロケール２）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_CMN T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.LCL_CD = 'en_US'
	)	TAX_NM_LCL2,
	--税名（ロケール３）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_CMN T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.LCL_CD = 'TBD3'
	)	TAX_NM_LCL3,
	--税名（ロケール４）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_CMN T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.LCL_CD = 'TBD4'
	)	TAX_NM_LCL4,
	--税名（ロケール５）
	(SELECT T.TAX_NM
		FROM MAM_TAX_LCL_CMN T
		WHERE 0 = 0
		AND T.TAX_CD = T1.TAX_CD
		AND T.LCL_CD = 'TBD5'
	)	TAX_NM_LCL5
	FROM MAM_TAX_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_TAX
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

