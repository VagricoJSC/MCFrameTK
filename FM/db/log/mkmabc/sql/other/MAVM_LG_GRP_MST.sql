SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_LG_GRP_MST(
	LG_GRP_CD,
	LG_GRP_NM,
	LOC_FLG,
	WG_CD,
	SHIP_SLIP_FLG,
	PICK_LIST_FLG,
	SHIP_INST_FLG,
	SHIP_SLIP_ACT_FLG,
	CAL_CD,
	SITE_CO_CD,
	GI_MINUS_STK_CHK_FLG,
	SHIP_LOC_PRIO_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	LG_GRP_NM_LCL1,
	LG_GRP_NM_LCL2,
	LG_GRP_NM_LCL3,
	LG_GRP_NM_LCL4,
	LG_GRP_NM_LCL5
)
AS
SELECT
	T1.LG_GRP_CD,
	T1.LG_GRP_NM,
	T1.LOC_FLG,
	T1.WG_CD,
	T1.SHIP_SLIP_FLG,
	T1.PICK_LIST_FLG,
	T1.SHIP_INST_FLG,
	T1.SHIP_SLIP_ACT_FLG,
	T1.CAL_CD,
	T1.SITE_CO_CD,
	T1.GI_MINUS_STK_CHK_FLG,
	T1.SHIP_LOC_PRIO_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--物流グループ名（ロケール１）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	LG_GRP_NM_LCL1,
	--物流グループ名（ロケール２）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	LG_GRP_NM_LCL2,
	--物流グループ名（ロケール３）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	LG_GRP_NM_LCL3,
	--物流グループ名（ロケール４）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	LG_GRP_NM_LCL4,
	--物流グループ名（ロケール５）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_ALL T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	LG_GRP_NM_LCL5
	FROM MAM_LG_GRP_ALL T1
	WHERE 0 = 0
		AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_LG_GRP
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
			)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_LG_GRP
			)
		)
	)
UNION ALL
SELECT
	T1.LG_GRP_CD,
	T1.LG_GRP_NM,
	T1.LOC_FLG,
	T1.WG_CD,
	T1.SHIP_SLIP_FLG,
	T1.PICK_LIST_FLG,
	T1.SHIP_INST_FLG,
	T1.SHIP_SLIP_ACT_FLG,
	T1.CAL_CD,
	T1.SITE_CO_CD,
	T1.GI_MINUS_STK_CHK_FLG,
	T1.SHIP_LOC_PRIO_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--物流グループ名（ロケール１）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.LCL_CD = 'ja_JP'
	)	LG_GRP_NM_LCL1,
	--物流グループ名（ロケール２）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.LCL_CD = 'en_US'
	)	LG_GRP_NM_LCL2,
	--物流グループ名（ロケール３）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.LCL_CD = 'TBD3'
	)	LG_GRP_NM_LCL3,
	--物流グループ名（ロケール４）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.LCL_CD = 'TBD4'
	)	LG_GRP_NM_LCL4,
	--物流グループ名（ロケール５）
	(SELECT T.LG_GRP_NM
		FROM MAM_LG_GRP_LCL_CMN T
		WHERE 0 = 0
		AND T.LG_GRP_CD = T1.LG_GRP_CD
		AND T.LCL_CD = 'TBD5'
	)	LG_GRP_NM_LCL5
	FROM MAM_LG_GRP_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_LG_GRP
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

