SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAVM_ALC_AC_MST(
	ALC_AC_CD,
	ALC_AC_NM,
	ALC_PTN_CD,
	EXPNS_CD,
	ALC_AC_GRP_CD1,
	ALC_AC_GRP_CD2,
	ALC_AC_GRP_CD3,
	CO_ALC_AC_CD,
	NOT_ITM_ALC_AC_FLG,
	NOT_ALC_RATE_AC_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO,
	CO_CD,
	ALC_AC_NM_LCL1,
	ALC_AC_NM_LCL2,
	ALC_AC_NM_LCL3,
	ALC_AC_NM_LCL4,
	ALC_AC_NM_LCL5
)
AS
SELECT
	T1.ALC_AC_CD,
	T1.ALC_AC_NM,
	T1.ALC_PTN_CD,
	T1.EXPNS_CD,
	T1.ALC_AC_GRP_CD1,
	T1.ALC_AC_GRP_CD2,
	T1.ALC_AC_GRP_CD3,
	T1.CO_ALC_AC_CD,
	T1.NOT_ITM_ALC_AC_FLG,
	T1.NOT_ALC_RATE_AC_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T1.CO_CD,
	--配賦科目名（ロケール１）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_ALL T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'ja_JP'
	)	ALC_AC_NM_LCL1,
	--配賦科目名（ロケール２）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_ALL T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'en_US'
	)	ALC_AC_NM_LCL2,
	--配賦科目名（ロケール３）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_ALL T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD3'
	)	ALC_AC_NM_LCL3,
	--配賦科目名（ロケール４）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_ALL T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD4'
	)	ALC_AC_NM_LCL4,
	--配賦科目名（ロケール５）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_ALL T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.CO_CD = T1.CO_CD
		AND T.LCL_CD = 'TBD5'
	)	ALC_AC_NM_LCL5
	FROM MAM_ALC_AC_ALL T1
	WHERE 0 = 0
	AND	(
	(
		EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_ALC_AC
			AND	x.MST_SET_TYP = MAC_MST_SET_TYP.COM
		)
		OR
		NOT EXISTS (
			SELECT	'X'
			FROM	MAM_MST_CTL x
			WHERE	0=0
			AND	x.MST_NM = MAC_MST_NM.MAM_ALC_AC
			)
		)
	)
UNION ALL
SELECT
	T1.ALC_AC_CD,
	T1.ALC_AC_NM,
	T1.ALC_PTN_CD,
	T1.EXPNS_CD,
	T1.ALC_AC_GRP_CD1,
	T1.ALC_AC_GRP_CD2,
	T1.ALC_AC_GRP_CD3,
	T1.CO_ALC_AC_CD,
	T1.NOT_ITM_ALC_AC_FLG,
	T1.NOT_ALC_RATE_AC_FLG,
	T1.MEMO1,
	T1.MEMO2,
	T1.MEMO3,
	T1.DEL_FLG,
	T1.DEL_USR_ID,
	T1.DEL_USR_NM,
	T1.DEL_TS,
	T1.INS_USR_ID,
	T1.INS_USR_NM,
	T1.INS_TS,
	T1.INS_FUNC_ID,
	T1.UPD_CNTR,
	T1.UPD_USR_ID,
	T1.UPD_USR_NM,
	T1.UPD_TS,
	T1.UPD_FUNC_ID,
	T1.UPD_SRV_REQ_NO,
	T2.CO_CD,
	--配賦科目名（ロケール１）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_CMN T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.LCL_CD = 'ja_JP'
	)	ALC_AC_NM_LCL1,
	--配賦科目名（ロケール２）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_CMN T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.LCL_CD = 'en_US'
	)	ALC_AC_NM_LCL2,
	--配賦科目名（ロケール３）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_CMN T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.LCL_CD = 'TBD3'
	)	ALC_AC_NM_LCL3,
	--配賦科目名（ロケール４）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_CMN T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.LCL_CD = 'TBD4'
	)	ALC_AC_NM_LCL4,
	--配賦科目名（ロケール５）
	(SELECT T.ALC_AC_NM
		FROM MAM_ALC_AC_LCL_CMN T
		WHERE 0 = 0
		AND T.ALC_AC_CD = T1.ALC_AC_CD
		AND T.LCL_CD = 'TBD5'
	)	ALC_AC_NM_LCL5
	FROM MAM_ALC_AC_CMN T1, MAM_CO_ALL T2
	WHERE 0 = 0
	AND	EXISTS (
		SELECT	'X'
		FROM	MAM_MST_CTL x
		WHERE	0=0
		AND	x.MST_NM = MAC_MST_NM.MAM_ALC_AC
		AND	x.MST_SET_TYP = MAC_MST_SET_TYP.ALL_COM
	)
;

