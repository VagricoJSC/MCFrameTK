CREATE OR REPLACE VIEW MAVM_RD_LOC(
	LOC_CD,
	LOC_NM,
	BASE_LOC_NM,
	ASST_DPT_CD,
	SLS_DPT_CD,
	WG_CD,
	SITE_CD,
	LG_GRP_CD,
	LG_DEF_FLG,
	LOC_GRP_CD,
	ALLOC_GRP_CD,
	SPPL_CD,
	MAKER_CD,
	PRE_OUTSRC_ACT_FLG,
	DDLV_PROV_INSP_FLG,
	CAL_CD,
	LOC_MNG_TYP,
	PRNT_LCL_CD,
	CNTRY_CD,
	NUM_ID,
	STKTK_TGT_FLG,
	STKTK_TOR_DISP_FLG,
	STKTK_TOR_EX_ZERO_FLG,
	STKTK_ACT_EX_ZERO_FLG,
	STKTK_AMT_FLG,
	STR_LN_TGT_FLG,
	ALLOC_LMT_FLG,
	GI_PACK_XFER_FLG,
	GI_VMI_FLG,
	RSRC_CD1,
	RSRC_CD2,
	EXT_SYS_LOC_TYP,
	LOC_ALC_GRP,
	ADDR_FLG,
	ZIP_CD,
	BASE_ZIP_CD,
	ADDR1,
	BASE_ADDR1,
	ADDR2,
	BASE_ADDR2,
	ADDR3,
	BASE_ADDR3,
	ADDR4,
	BASE_ADDR4,
	TEL,
	BASE_TEL,
	FAX,
	BASE_FAX,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT	m.*
FROM	MAT_DA_LOC t , MAM_LOC m
WHERE	0 = 0
AND	t.LOC_CD = m.LOC_CD
AND	t.RD_FLG = '1'
AND	t.LOGIN_SEQ = FCPA_CONTEXT.F_GET_LOGIN_SEQ
UNION ALL
SELECT	m.*
FROM	MAM_LOC m
	, (SELECT x.FULL_DA_FLG FROM MAM_USR x WHERE 0=0 AND FCPA_CONTEXT.F_GET_USERID = x.USR_CD) w
WHERE	0=0
AND	w.FULL_DA_FLG = '1'
;

