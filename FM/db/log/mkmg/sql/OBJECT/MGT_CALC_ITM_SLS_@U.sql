CREATE OR REPLACE VIEW MGT_CALC_ITM_SLS_$U(
	CALC_NO,
	CALC_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	DPT_CD,
	CST_CD,
	DLV_CD,
	DEST_CD1,
	DEST_CD2,
	DEST_CD3,
	WG_CD,
	BASE_QTY,
	CUR_CD,
	UPRI,
	BASE_CUR_UPRI,
	PRIO,
	ALC_VAL1,
	ALC_VAL2,
	ALC_VAL3,
	ALC_VAL4,
	ALC_VAL5,
	CALC_CTG_CD,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.DPT_CD,
	ORG.CST_CD,
	ORG.DLV_CD,
	ORG.DEST_CD1,
	ORG.DEST_CD2,
	ORG.DEST_CD3,
	ORG.WG_CD,
	ORG.BASE_QTY,
	ORG.CUR_CD,
	ORG.UPRI,
	ORG.BASE_CUR_UPRI,
	ORG.PRIO,
	ORG.ALC_VAL1,
	ORG.ALC_VAL2,
	ORG.ALC_VAL3,
	ORG.ALC_VAL4,
	ORG.ALC_VAL5,
	ORG.CALC_CTG_CD,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3
FROM
	MGT_CALC_ITM_SLS_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

