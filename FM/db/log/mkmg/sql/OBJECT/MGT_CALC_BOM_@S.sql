CREATE OR REPLACE VIEW MGT_CALC_BOM_$S(
	CALC_NO,
	CALC_GRP_CD,
	PAR_ITM_CD,
	PAR_ITM_SUB1,
	PAR_ITM_SUB2,
	PAR_ITM_SUB3,
	BOM_PTN,
	OPER_CD,
	OPER_SEQ,
	CHD_ITM_CD,
	CHD_ITM_SUB1,
	CHD_ITM_SUB2,
	CHD_ITM_SUB3,
	ALT_GRP_CD,
	EXPNS_CD,
	WG_CD,
	DISP_SEQ,
	PAR_RQMT_QTY,
	CHD_RQMT_QTY,
	CHD_BASE_QTY,
	FXD_CHD_RQMT_QTY,
	CHD_MIN_QTY,
	CHD_BATCH_QTY,
	ALT_ITM_RATIO,
	CALC_CTG_CD,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.PAR_ITM_CD,
	ORG.PAR_ITM_SUB1,
	ORG.PAR_ITM_SUB2,
	ORG.PAR_ITM_SUB3,
	ORG.BOM_PTN,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.CHD_ITM_CD,
	ORG.CHD_ITM_SUB1,
	ORG.CHD_ITM_SUB2,
	ORG.CHD_ITM_SUB3,
	ORG.ALT_GRP_CD,
	ORG.EXPNS_CD,
	ORG.WG_CD,
	ORG.DISP_SEQ,
	ORG.PAR_RQMT_QTY,
	ORG.CHD_RQMT_QTY,
	ORG.CHD_BASE_QTY,
	ORG.FXD_CHD_RQMT_QTY,
	ORG.CHD_MIN_QTY,
	ORG.CHD_BATCH_QTY,
	ORG.ALT_ITM_RATIO,
	ORG.CALC_CTG_CD,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3
FROM
	MGT_CALC_BOM_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

