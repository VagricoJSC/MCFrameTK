CREATE OR REPLACE VIEW MGT_ACC_WK_$S(
	CALC_NO,
	CALC_GRP_CD,
	WK_REC_NO,
	INPT_REC_NO,
	LOC_CD,
	STR_LN_CD,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	WK_COST_CD,
	WK_RSN_CD,
	ACT_WK_COST,
	STD_WK_COST,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.WK_REC_NO,
	ORG.INPT_REC_NO,
	ORG.LOC_CD,
	ORG.STR_LN_CD,
	ORG.OPER_ACT_NO,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.WK_COST_CD,
	ORG.WK_RSN_CD,
	ORG.ACT_WK_COST,
	ORG.STD_WK_COST,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_ACC_WK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

