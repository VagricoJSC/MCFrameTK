CREATE OR REPLACE VIEW MGT_CALC_TRD_CALC_NO(
	CALC_NO,
	CALC_GRP_CD,
	YM,
	TRD_CALC_NO,
	TRD_CALC_GRP_CD
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.YM,
	ORG.TRD_CALC_NO,
	ORG.TRD_CALC_GRP_CD
FROM
	MGT_CALC_TRD_CALC_NO_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

