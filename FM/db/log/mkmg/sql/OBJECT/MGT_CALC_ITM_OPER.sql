SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGT_CALC_ITM_OPER(
	CALC_NO,
	CALC_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	WG_CD,
	DISP_SEQ,
	NMR_QTY,
	DNM_QTY,
	YIELD_OPER_FLG,
	OPER_UNIT_CD,
	OPER_STD_QTY,
	OPER_CONV_QTY,
	DEC_PLACE,
	UNIT_CONV_RND_TYP,
	CALC_CTG_CD,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOC_CD,
	ORG.OPER_PTN,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.WG_CD,
	ORG.DISP_SEQ,
	ORG.NMR_QTY,
	ORG.DNM_QTY,
	ORG.YIELD_OPER_FLG,
	ORG.OPER_UNIT_CD,
	ORG.OPER_STD_QTY,
	ORG.OPER_CONV_QTY,
	ORG.DEC_PLACE,
	ORG.UNIT_CONV_RND_TYP,
	ORG.CALC_CTG_CD,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3
FROM
	MGT_CALC_ITM_OPER_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

