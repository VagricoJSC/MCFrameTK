CREATE OR REPLACE VIEW MGT_CALC_IO_EXPNS_AMT(
	CALC_NO,
	CALC_GRP_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	WG_CD,
	ACT_IO_ID,
	ACT_IO_ID_SUB,
	AMT_ADD_TYP,
	EXPNS_CD,
	AMT
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_EXT,
	ORG.WG_CD,
	ORG.ACT_IO_ID,
	ORG.ACT_IO_ID_SUB,
	ORG.AMT_ADD_TYP,
	ORG.EXPNS_CD,
	ORG.AMT
FROM
	MGT_CALC_IO_EXPNS_AMT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

