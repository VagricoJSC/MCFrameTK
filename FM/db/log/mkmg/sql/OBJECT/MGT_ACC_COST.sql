CREATE OR REPLACE VIEW MGT_ACC_COST(
	CALC_NO,
	CALC_GRP_CD,
	INPT_REC_NO,
	WK_REC_NO,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	EXPNS_CD,
	ACT_COST,
	STD_COST,
	SML_INPT_REC_NO,
	TOP_REC_NO,
	LOC_CD,
	STR_LN_CD,
	OPER_COST_FLG,
	EXPNS_TYP,
	DIFF_QTY,
	DIFF_WK,
	DIFF_UP,
	DIFF_RT,
	DIFF_STD,
	DIFF_A,
	DIFF_B,
	DIFF_C,
	DIFF_D,
	DIFF_E,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.INPT_REC_NO,
	ORG.WK_REC_NO,
	ORG.OPER_ACT_NO,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.EXPNS_CD,
	ORG.ACT_COST,
	ORG.STD_COST,
	ORG.SML_INPT_REC_NO,
	ORG.TOP_REC_NO,
	ORG.LOC_CD,
	ORG.STR_LN_CD,
	ORG.OPER_COST_FLG,
	ORG.EXPNS_TYP,
	ORG.DIFF_QTY,
	ORG.DIFF_WK,
	ORG.DIFF_UP,
	ORG.DIFF_RT,
	ORG.DIFF_STD,
	ORG.DIFF_A,
	ORG.DIFF_B,
	ORG.DIFF_C,
	ORG.DIFF_D,
	ORG.DIFF_E,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_ACC_COST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

