CREATE OR REPLACE VIEW MGT_CALC_IO_TRD_$U(
	CALC_NO,
	CALC_GRP_CD,
	ACT_IO_ID,
	ACT_IO_ID_SUB,
	YM,
	TRD_GRP,
	WG_CD,
	OTHER_WG_CD,
	COST_IO_TYP
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ACT_IO_ID,
	ORG.ACT_IO_ID_SUB,
	ORG.YM,
	ORG.TRD_GRP,
	ORG.WG_CD,
	ORG.OTHER_WG_CD,
	ORG.COST_IO_TYP
FROM
	MGT_CALC_IO_TRD_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

