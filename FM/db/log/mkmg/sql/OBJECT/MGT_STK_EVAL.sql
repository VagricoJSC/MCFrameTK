CREATE OR REPLACE VIEW MGT_STK_EVAL(
	CALC_CTG_CD,
	STK_EVAL_CD,
	WG_CD,
	YM,
	MNG_DPT_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	ASST_TYP,
	BASE_QTY,
	UPRI,
	RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_CTG_CD,
	ORG.STK_EVAL_CD,
	ORG.WG_CD,
	ORG.YM,
	ORG.MNG_DPT_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.ASST_TYP,
	ORG.BASE_QTY,
	ORG.UPRI,
	ORG.RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_STK_EVAL_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

