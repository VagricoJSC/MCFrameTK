CREATE OR REPLACE VIEW MGT_WIP_LOC_$U(
	CALC_NO,
	CALC_GRP_CD,
	WG_CD,
	YM,
	MNG_DPT_CD,
	LOC_CD,
	STR_LN_CD,
	OPER_CD,
	OPER_SEQ,
	EXPNS_CD,
	ST_WIP_AMT,
	PROD_AMT,
	INPT_AMT,
	COMP_AMT,
	END_WIP_AMT,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.WG_CD,
	ORG.YM,
	ORG.MNG_DPT_CD,
	ORG.LOC_CD,
	ORG.STR_LN_CD,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.EXPNS_CD,
	ORG.ST_WIP_AMT,
	ORG.PROD_AMT,
	ORG.INPT_AMT,
	ORG.COMP_AMT,
	ORG.END_WIP_AMT,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_WIP_LOC_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

