SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGT_STD_COST(
	CALC_NO,
	CALC_GRP_CD,
	INPT_REC_NO,
	OPER_REC_NO,
	WK_REC_NO,
	EXPNS_CD,
	STD_COST,
	THE_COST,
	SML_INPT_REC_NO,
	SML_OPER_REC_NO,
	OPER_COST_FLG,
	EXPNS_TYP,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.INPT_REC_NO,
	ORG.OPER_REC_NO,
	ORG.WK_REC_NO,
	ORG.EXPNS_CD,
	ORG.STD_COST,
	ORG.THE_COST,
	ORG.SML_INPT_REC_NO,
	ORG.SML_OPER_REC_NO,
	ORG.OPER_COST_FLG,
	ORG.EXPNS_TYP,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_STD_COST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

