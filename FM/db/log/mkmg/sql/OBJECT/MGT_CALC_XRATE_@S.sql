SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGT_CALC_XRATE_$S(
	CALC_NO,
	CALC_GRP_CD,
	FR_CUR_CD,
	TO_CUR_CD,
	XRATE_CD,
	XRATE
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.FR_CUR_CD,
	ORG.TO_CUR_CD,
	ORG.XRATE_CD,
	ORG.XRATE
FROM
	MGT_CALC_XRATE_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

