CREATE OR REPLACE VIEW MGT_CALC_STD_ALC_RATE_$U(
	CALC_NO,
	CALC_GRP_CD,
	ALC_AC_CD,
	DPT_CD,
	LOC_CD,
	OPER_CD,
	BP_CD,
	CTG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	WG_CD,
	ALC_RATE,
	ALC_PTN_CD,
	EXPNS_CD,
	CALC_CTG_CD
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.ALC_AC_CD,
	ORG.DPT_CD,
	ORG.LOC_CD,
	ORG.OPER_CD,
	ORG.BP_CD,
	ORG.CTG_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.WG_CD,
	ORG.ALC_RATE,
	ORG.ALC_PTN_CD,
	ORG.EXPNS_CD,
	ORG.CALC_CTG_CD
FROM
	MGT_CALC_STD_ALC_RATE_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

