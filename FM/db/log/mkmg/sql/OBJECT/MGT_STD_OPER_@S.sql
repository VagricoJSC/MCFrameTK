CREATE OR REPLACE VIEW MGT_STD_OPER_$S(
	CALC_NO,
	CALC_GRP_CD,
	OPER_REC_NO,
	TOP_REC_NO,
	INPT_REC_NO,
	LOC_CD,
	WG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	DISP_SEQ,
	STD_QTY,
	THE_QTY,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.OPER_REC_NO,
	ORG.TOP_REC_NO,
	ORG.INPT_REC_NO,
	ORG.LOC_CD,
	ORG.WG_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.OPER_PTN,
	ORG.OPER_CD,
	ORG.OPER_SEQ,
	ORG.DISP_SEQ,
	ORG.STD_QTY,
	ORG.THE_QTY,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_STD_OPER_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

