CREATE OR REPLACE VIEW MGT_RPT_$U(
	CALC_NO,
	CALC_GRP_CD,
	YM,
	RPT_PTN_CD,
	RPT_KEY_CD,
	RPT_ROW_CD,
	WG_CD,
	DPT_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_JNL_CD,
	ITM_GRP_TYP,
	ITM_GRP_CD,
	RPT_VAL,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CALC_NO,
	ORG.CALC_GRP_CD,
	ORG.YM,
	ORG.RPT_PTN_CD,
	ORG.RPT_KEY_CD,
	ORG.RPT_ROW_CD,
	ORG.WG_CD,
	ORG.DPT_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_JNL_CD,
	ORG.ITM_GRP_TYP,
	ORG.ITM_GRP_CD,
	ORG.RPT_VAL,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MGT_RPT_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

