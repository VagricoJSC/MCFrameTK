FUNCTION F_GET_AVE_FIX (
	I_KEY	IN	MGT_AVE_FIX%ROWTYPE
	)
RETURN MGT_AVE_FIX%ROWTYPE
/*********************************************************
<SYNOPSIS>
	MGT_AVE_FIXのレコードを返す
<REMARKS>

<ARGUMENTS>
<IN>	I_KEY
		MGT_AVE_FIXのキーとなるレコード
<RETURNVALUE>
	対象となるMGT_AVE_FIXのレコード
<HISTORY>
**********************************************************/
AS
	L_REC	MGT_AVE_FIX%ROWTYPE ;
	L_WG_CD	MAPA_META.WG_CD%TYPE ;
BEGIN
	SELECT NVL(t.RUNTIME_WG_CD, I_KEY.WG_CD) INTO L_WG_CD FROM MAM_CALC_GRP t
	WHERE t.CALC_GRP_CD = I_KEY.CALC_GRP_CD ;

	FOR x IN (
		SELECT	t1.*
		FROM	MGT_AVE_FIX t1, MGT_CALC_ITM t2, MGT_CALC_PTN t3
		WHERE	0=0
		AND	t1.CALC_NO = t2.CALC_NO
		AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
		AND	t1.ITM_CD = t2.ITM_CD
		AND	t1.ITM_SUB1 = t2.ITM_SUB1
		AND	t1.ITM_SUB2 = t2.ITM_SUB2
		AND	t1.ITM_SUB3 = t2.ITM_SUB3
		AND	t1.WG_CD = t2.WG_CD
		AND	t2.CALC_NO = t3.CALC_NO
		AND	t2.CALC_GRP_CD = t3.CALC_GRP_CD
		AND	t2.CALC_PTN_CD = t3.CALC_PTN_CD
		AND	t1.CALC_GRP_CD = I_KEY.CALC_GRP_CD
		AND	t1.WG_CD = L_WG_CD
		AND	t1.YM <= I_KEY.YM
		AND	NVL(t1.MNG_DPT_CD, C_NULL_VAL) = DECODE(t3.DPT_TYP, C_UNIT_CALC_CALC, I_KEY.MNG_DPT_CD, C_NULL_VAL)
		AND	t1.ITM_CD = I_KEY.ITM_CD
		AND	t1.ITM_SUB1 = I_KEY.ITM_SUB1
		AND	t1.ITM_SUB2 = I_KEY.ITM_SUB2
		AND	t1.ITM_SUB3 = I_KEY.ITM_SUB3
		AND	t1.LOT_NO = DECODE(t3.LOT_TYP, C_UNIT_CALC_CALC, I_KEY.LOT_NO, C_NULL_VAL)
		AND	t1.SUBLOT_NO = DECODE(t3.SUBLOT_TYP, C_UNIT_CALC_CALC, I_KEY.SUBLOT_NO, C_NULL_VAL)
		AND	t1.SNO1 = DECODE(t3.SNO1_TYP, C_UNIT_CALC_CALC, I_KEY.SNO1, C_NULL_VAL)
		AND	t1.SNO2 = DECODE(t3.SNO2_TYP, C_UNIT_CALC_CALC, I_KEY.SNO2, C_NULL_VAL)
		AND	t1.SNO3 = DECODE(t3.SNO3_TYP, C_UNIT_CALC_CALC, I_KEY.SNO3, C_NULL_VAL)
		AND	t1.SNO4 = DECODE(t3.SNO4_TYP, C_UNIT_CALC_CALC, I_KEY.SNO4, C_NULL_VAL)
		AND	(
			I_KEY.ASST_TYP = C_ASST_OTH AND t1.SPPL_CD = I_KEY.SPPL_CD
			OR
			I_KEY.ASST_TYP <> C_ASST_OTH
			)
		AND	t1.ASST_TYP = I_KEY.ASST_TYP
		AND	t1.AVE_UPRI <> 0
		ORDER BY t1.YM DESC
		)
	LOOP
		L_REC := x ;
		EXIT ;
	END LOOP ;

	RETURN L_REC ;

END F_GET_AVE_FIX ;

PROCEDURE P_INPT (
	I_ERR_FLG IN MAPA_META.FLG%TYPE DEFAULT '1'
	)
/************************************************************************
<SYNOPSIS>
	投入実績費目別原価に金額をセットする
<REMARKS>
	事前にMGW_EXPNS_INPTを作成しておく必要がある
<ARGUMENTS>
<IN>	I_ERR_FLG
		エラーＦＬＧ
<HISTORY>
*************************************************************************/
AS
	L_CNT	NUMBER ;
BEGIN
	--処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SET_EXPNS.P_INPT') ;

	G_PARM_ITM_SUB_TYP := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;
	G_PARM_SNO_TYP := MAPA_COMM.F_GET_PARM('SNO_TYP') ;

	UPDATE	MGT_ACT_INPT t
	SET	t.REC_EVAL_TYP = (
			SELECT	DECODE(w2.AMT_SET_TYP,
					C_SET_STD, C_EVAL_STD,
					C_SET_ZERO, C_EVAL_ZERO,
					C_SET_AVE, C_EVAL_EXPNS,
					C_SET_AVE_STD, C_EVAL_EXPNS,
					NULL
					)
			FROM	MGW_EXPNS_INPT w2
			WHERE	0=0
			AND	w2.ACT_INPT_ID = t.ACT_INPT_ID
			AND	w2.ACT_INPT_ID_SUB = t.ACT_INPT_ID_SUB
		)
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_EXPNS_INPT w
			WHERE	0=0
			AND	w.ACT_INPT_ID = t.ACT_INPT_ID
			AND	w.ACT_INPT_ID_SUB = t.ACT_INPT_ID_SUB
			)
	;

	DELETE	MGT_ACT_INPT_EXPNS x
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_EXPNS_INPT w
			WHERE	0=0
			AND	w.ACT_INPT_ID = x.ACT_INPT_ID
			AND	w.ACT_INPT_ID_SUB = x.ACT_INPT_ID_SUB
			)
	;

	FOR w IN (
		SELECT	w.*
		FROM	MGW_EXPNS_INPT w
		WHERE	0=0
		AND	w.AMT_SET_TYP IN (C_SET_AVE, C_SET_AVE_STD)
		)
	LOOP
		G_AVE_FIX.CALC_GRP_CD := w.CALC_GRP_CD ;
		G_AVE_FIX.WG_CD := w.WG_CD ;
		G_AVE_FIX.YM := w.YM ;
		G_AVE_FIX.MNG_DPT_CD := w.MNG_DPT_CD ;
		G_AVE_FIX.ITM_CD := w.ITM_CD ;
		G_AVE_FIX.ITM_SUB1 := w.ITM_SUB1 ;
		G_AVE_FIX.ITM_SUB2 := w.ITM_SUB2 ;
		G_AVE_FIX.ITM_SUB3 := w.ITM_SUB3 ;
		G_AVE_FIX.LOT_NO := w.LOT_NO ;
		G_AVE_FIX.SUBLOT_NO := w.SUBLOT_NO ;
		G_AVE_FIX.SNO1 := w.SNO1 ;
		G_AVE_FIX.SNO2 := w.SNO2 ;
		G_AVE_FIX.SNO3 := w.SNO3 ;
		G_AVE_FIX.SNO4 := w.SNO4 ;
		G_AVE_FIX.SPPL_CD := w.STK_BP_CD ;
		G_AVE_FIX.ASST_TYP := w.ASST_TYP ;

		G_AVE_FIX := F_GET_AVE_FIX(G_AVE_FIX) ;

		INSERT INTO MGT_ACT_INPT_EXPNS (
			ACT_INPT_ID,
			ACT_INPT_ID_SUB,
			EXPNS_CD,
			AMT
			)
		SELECT	w.ACT_INPT_ID,
			w.ACT_INPT_ID_SUB,
			t.EXPNS_CD,
			MGPA_CALC_ITM_RND.F_RND_AMT(w.QTY * t.ACT_COST / G_AVE_FIX.STD_QTY)
		FROM	MGT_ACC_SML_COST t
		WHERE	0=0
		AND	t.CALC_NO = G_AVE_FIX.CALC_NO
		AND	t.CALC_GRP_CD = G_AVE_FIX.CALC_GRP_CD
		AND	t.TOP_REC_NO = G_AVE_FIX.TOP_REC_NO
		AND	t.ACT_COST <> 0
		;
		L_CNT := SQL%ROWCOUNT ;

		IF L_CNT = 0 THEN
			G_ERR_MSG := FCPA_ERR.MSG_BINDER(
					w.CALC_GRP_CD,
					FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
					w.WG_CD, w.MNG_DPT_CD,
					MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
					w.LOT_NO, w.SUBLOT_NO,
					MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
					w.ASST_TYP,
					w.ACT_INPT_ID, w.ACT_INPT_ID_SUB
					) ;

			G_MSG := FCPA_MSG.MSG_BINDER(
					w.CALC_GRP_CD,
					FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
					w.WG_CD, w.MNG_DPT_CD,
					MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
					w.LOT_NO, w.SUBLOT_NO,
					MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
					w.ASST_TYP,
					w.ACT_INPT_ID, w.ACT_INPT_ID_SUB
					) ;

			IF w.AMT_SET_TYP = C_SET_AVE_STD THEN
				UPDATE	MGT_ACT_INPT t
				SET	t.REC_EVAL_TYP = C_EVAL_STD
				WHERE	0=0
				AND	t.ACT_INPT_ID = w.ACT_INPT_ID
				AND	t.ACT_INPT_ID_SUB = w.ACT_INPT_ID_SUB
				;

				IF I_ERR_FLG = '0' THEN
					FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0042', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
				ELSE
					COMMIT ;
					FCPA_ERR.RAISE_APP_ERR('MGBBD0042', G_ERR_MSG) ;
				END IF ;

			ELSIF I_ERR_FLG = '0' THEN
				UPDATE	MGT_ACT_INPT t
				SET	t.REC_EVAL_TYP = NULL
				WHERE	0=0
				AND	t.ACT_INPT_ID = w.ACT_INPT_ID
				AND	t.ACT_INPT_ID_SUB = w.ACT_INPT_ID_SUB
				;
				FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0041', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
			ELSE
				FCPA_ERR.RAISE_APP_ERR('MGBBD0041', G_ERR_MSG) ;
			END IF ;
		ELSE
			DELETE FROM MGT_ACT_INPT_EXPNS T
			WHERE T.ACT_INPT_ID = w.ACT_INPT_ID
			AND T.ACT_INPT_ID_SUB = w.ACT_INPT_ID_SUB
			AND T.AMT = 0;

			SELECT COUNT(*) INTO L_CNT FROM MGT_ACT_INPT_EXPNS T
			WHERE T.ACT_INPT_ID = w.ACT_INPT_ID
			AND T.ACT_INPT_ID_SUB = w.ACT_INPT_ID_SUB;

			IF L_CNT = 0 THEN
				UPDATE MGT_ACT_INPT T
				SET T.REC_EVAL_TYP = C_EVAL_ZERO
				WHERE T.ACT_INPT_ID = w.ACT_INPT_ID
				AND T.ACT_INPT_ID_SUB = w.ACT_INPT_ID_SUB;

				G_MSG := FCPA_MSG.MSG_BINDER(
						w.CALC_GRP_CD,
						FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
						w.WG_CD, w.MNG_DPT_CD,
						MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
						w.LOT_NO, w.SUBLOT_NO,
						MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
						w.ASST_TYP,
						w.ACT_INPT_ID, w.ACT_INPT_ID_SUB
						) ;
				FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0052', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
			END IF ;
		END IF ;
	END LOOP ;

	--処理が終了しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SET_EXPNS.P_INPT') ;

END P_INPT ;

PROCEDURE P_IO (
	I_ERR_FLG IN MAPA_META.FLG%TYPE DEFAULT '1'
	)
/************************************************************************
<SYNOPSIS>
	入出庫実績費目別原価に金額をセットする
<REMARKS>
	事前にMGW_EXPNS_IOを作成しておく必要がある
<ARGUMENTS>
<IN>	I_ERR_FLG
		エラーＦＬＧ
<HISTORY>
*************************************************************************/
AS
	L_CNT	NUMBER ;
BEGIN
	--処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SET_EXPNS.P_IO') ;

	G_PARM_ITM_SUB_TYP := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;
	G_PARM_SNO_TYP := MAPA_COMM.F_GET_PARM('SNO_TYP') ;

	UPDATE	MGT_ACT_IO t
	SET	t.REC_EVAL_TYP = (
			SELECT	DECODE(w2.AMT_SET_TYP,
					C_SET_STD, C_EVAL_STD,
					C_SET_ZERO, C_EVAL_ZERO,
					C_SET_AVE, C_EVAL_EXPNS,
					C_SET_AVE_STD, C_EVAL_EXPNS,
					NULL
					)
			FROM	MGW_EXPNS_IO w2
			WHERE	0=0
			AND	w2.ACT_IO_ID = t.ACT_IO_ID
			AND	w2.ACT_IO_ID_SUB = t.ACT_IO_ID_SUB
			)
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_EXPNS_IO w
			WHERE	0=0
			AND	w.ACT_IO_ID = t.ACT_IO_ID
			AND	w.ACT_IO_ID_SUB = t.ACT_IO_ID_SUB
		)
	;

	DELETE	MGT_ACT_IO_EXPNS x
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_EXPNS_IO w
			WHERE	0=0
			AND	w.ACT_IO_ID = x.ACT_IO_ID
			AND	w.ACT_IO_ID_SUB = x.ACT_IO_ID_SUB
			)
	;

	FOR w IN (
		SELECT	w.*
		FROM	MGW_EXPNS_IO w
		WHERE	0=0
		AND	w.AMT_SET_TYP IN (C_SET_AVE, C_SET_AVE_STD)
		)
	LOOP
		G_AVE_FIX.CALC_GRP_CD := w.CALC_GRP_CD ;
		G_AVE_FIX.WG_CD := w.WG_CD ;
		G_AVE_FIX.YM := w.YM ;
		G_AVE_FIX.MNG_DPT_CD := w.MNG_DPT_CD ;
		G_AVE_FIX.ITM_CD := w.ITM_CD ;
		G_AVE_FIX.ITM_SUB1 := w.ITM_SUB1 ;
		G_AVE_FIX.ITM_SUB2 := w.ITM_SUB2 ;
		G_AVE_FIX.ITM_SUB3 := w.ITM_SUB3 ;
		G_AVE_FIX.LOT_NO := w.LOT_NO ;
		G_AVE_FIX.SUBLOT_NO := w.SUBLOT_NO ;
		G_AVE_FIX.SNO1 := w.SNO1 ;
		G_AVE_FIX.SNO2 := w.SNO2 ;
		G_AVE_FIX.SNO3 := w.SNO3 ;
		G_AVE_FIX.SNO4 := w.SNO4 ;
		G_AVE_FIX.SPPL_CD := w.STK_BP_CD ;
		G_AVE_FIX.ASST_TYP := w.ASST_TYP ;

		G_AVE_FIX := F_GET_AVE_FIX(G_AVE_FIX) ;

		INSERT INTO MGT_ACT_IO_EXPNS (
			ACT_IO_ID,
			ACT_IO_ID_SUB,
			EXPNS_CD,
			AMT
			)
		SELECT	w.ACT_IO_ID,
			w.ACT_IO_ID_SUB,
			t.EXPNS_CD,
			MGPA_CALC_ITM_RND.F_RND_AMT(w.QTY * t.ACT_COST / G_AVE_FIX.STD_QTY)
		FROM	MGT_ACC_SML_COST t
		WHERE	0=0
		AND	t.CALC_NO = G_AVE_FIX.CALC_NO
		AND	t.CALC_GRP_CD = G_AVE_FIX.CALC_GRP_CD
		AND	t.TOP_REC_NO = G_AVE_FIX.TOP_REC_NO
		AND	t.ACT_COST <> 0
		;
		L_CNT := SQL%ROWCOUNT ;

		IF L_CNT = 0 THEN
			G_ERR_MSG := FCPA_ERR.MSG_BINDER(
					w.CALC_GRP_CD,
					FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
					w.WG_CD, w.MNG_DPT_CD,
					MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
					w.LOT_NO, w.SUBLOT_NO,
					MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
					w.ASST_TYP,
					w.ACT_IO_ID, w.ACT_IO_ID_SUB
					) ;

			G_MSG := FCPA_MSG.MSG_BINDER(
					w.CALC_GRP_CD,
					FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
					w.WG_CD, w.MNG_DPT_CD,
					MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
					w.LOT_NO, w.SUBLOT_NO,
					MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
					w.ASST_TYP,
					w.ACT_IO_ID, w.ACT_IO_ID_SUB
					) ;

			IF w.AMT_SET_TYP = C_SET_AVE_STD THEN
				UPDATE	MGT_ACT_IO t
				SET	t.REC_EVAL_TYP = C_EVAL_STD
				WHERE	0=0
				AND	t.ACT_IO_ID = w.ACT_IO_ID
				AND	t.ACT_IO_ID_SUB = w.ACT_IO_ID_SUB
				;

				IF I_ERR_FLG = '0' THEN
					FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0042', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
				ELSE
					COMMIT ;
					FCPA_ERR.RAISE_APP_ERR('MGBBD0042', G_ERR_MSG) ;
				END IF ;

			ELSIF I_ERR_FLG = '0' THEN
				UPDATE	MGT_ACT_IO t
				SET	t.REC_EVAL_TYP = NULL
				WHERE	0=0
				AND	t.ACT_IO_ID = w.ACT_IO_ID
				AND	t.ACT_IO_ID_SUB = w.ACT_IO_ID_SUB
				;
				FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0041', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
			ELSE
				FCPA_ERR.RAISE_APP_ERR('MGBBD0041', G_ERR_MSG) ;
			END IF ;
		ELSE
			DELETE FROM MGT_ACT_IO_EXPNS T
			WHERE T.ACT_IO_ID = w.ACT_IO_ID
			AND T.ACT_IO_ID_SUB = w.ACT_IO_ID_SUB
			AND T.AMT = 0;

			SELECT COUNT(*) INTO L_CNT FROM MGT_ACT_IO_EXPNS T
			WHERE T.ACT_IO_ID = w.ACT_IO_ID
			AND T.ACT_IO_ID_SUB = w.ACT_IO_ID_SUB;

			IF L_CNT = 0 THEN
				UPDATE MGT_ACT_IO T
				SET T.REC_EVAL_TYP = C_EVAL_ZERO
				WHERE T.ACT_IO_ID = w.ACT_IO_ID
				AND T.ACT_IO_ID_SUB = w.ACT_IO_ID_SUB;

				G_MSG := FCPA_MSG.MSG_BINDER(
						w.CALC_GRP_CD,
						FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
						w.WG_CD, w.MNG_DPT_CD,
						MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
						w.LOT_NO, w.SUBLOT_NO,
						MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
						w.ASST_TYP,
						w.ACT_IO_ID, w.ACT_IO_ID_SUB
						) ;
				FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0052', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
			END IF ;
		END IF ;
	END LOOP ;

	--処理が終了しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SET_EXPNS.P_IO') ;

END P_IO ;

PROCEDURE P_SLS (
	I_ERR_FLG IN MAPA_META.FLG%TYPE DEFAULT '1'
	)
/************************************************************************
<SYNOPSIS>
	売上実績費目別原価に金額をセットする
<REMARKS>
	事前にMGW_EXPNS_SLSを作成しておく必要がある
<ARGUMENTS>
<IN>	I_ERR_FLG
		エラーＦＬＧ
<HISTORY>
*************************************************************************/
AS
	L_CNT	NUMBER ;
BEGIN
	--処理を開始しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_SET_EXPNS.P_SLS') ;

	G_PARM_ITM_SUB_TYP := MAPA_COMM.F_GET_PARM('ITM_SUB_TYP') ;
	G_PARM_SNO_TYP := MAPA_COMM.F_GET_PARM('SNO_TYP') ;

	UPDATE	MGT_ACT_SLS t
	SET	t.REC_EVAL_TYP = (
			SELECT	DECODE(w2.AMT_SET_TYP,
					C_SET_STD, C_EVAL_STD,
					C_SET_ZERO, C_EVAL_ZERO,
					C_SET_AVE, C_EVAL_EXPNS,
					C_SET_AVE_STD,  C_EVAL_EXPNS,
					NULL
					)
			FROM	MGW_EXPNS_SLS w2
			WHERE	0=0
			AND	w2.ACT_SLS_ID = t.ACT_SLS_ID
			AND	w2.ACT_SLS_ID_SUB = t.ACT_SLS_ID_SUB
		)
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_EXPNS_SLS w
			WHERE	0=0
			AND	w.ACT_SLS_ID = t.ACT_SLS_ID
			AND	w.ACT_SLS_ID_SUB = t.ACT_SLS_ID_SUB
			)
	;

	DELETE	MGT_ACT_SLS_EXPNS x
	WHERE	0=0
	AND	EXISTS (
			SELECT	'X'
			FROM	MGW_EXPNS_SLS w
			WHERE	0=0
			AND	w.ACT_SLS_ID = x.ACT_SLS_ID
			AND	w.ACT_SLS_ID_SUB = x.ACT_SLS_ID_SUB
			)
	;

	FOR w IN (
		SELECT	w.*
		FROM	MGW_EXPNS_SLS w
		WHERE	0=0
		AND	w.AMT_SET_TYP IN (C_SET_AVE, C_SET_AVE_STD)
		)
	LOOP
		G_AVE_FIX.CALC_GRP_CD := w.CALC_GRP_CD ;
		G_AVE_FIX.WG_CD := w.WG_CD ;
		G_AVE_FIX.YM := w.YM ;
		G_AVE_FIX.MNG_DPT_CD := w.MNG_DPT_CD ;
		G_AVE_FIX.ITM_CD := w.ITM_CD ;
		G_AVE_FIX.ITM_SUB1 := w.ITM_SUB1 ;
		G_AVE_FIX.ITM_SUB2 := w.ITM_SUB2 ;
		G_AVE_FIX.ITM_SUB3 := w.ITM_SUB3 ;
		G_AVE_FIX.LOT_NO := w.LOT_NO ;
		G_AVE_FIX.SUBLOT_NO := w.SUBLOT_NO ;
		G_AVE_FIX.SNO1 := w.SNO1 ;
		G_AVE_FIX.SNO2 := w.SNO2 ;
		G_AVE_FIX.SNO3 := w.SNO3 ;
		G_AVE_FIX.SNO4 := w.SNO4 ;
		G_AVE_FIX.SPPL_CD := w.STK_BP_CD ;
		G_AVE_FIX.ASST_TYP := w.ASST_TYP ;

		G_AVE_FIX := F_GET_AVE_FIX(G_AVE_FIX) ;

		INSERT INTO MGT_ACT_SLS_EXPNS (
			ACT_SLS_ID,
			ACT_SLS_ID_SUB,
			EXPNS_CD,
			AMT
			)
		SELECT	w.ACT_SLS_ID,
			w.ACT_SLS_ID_SUB,
			t.EXPNS_CD,
			MGPA_CALC_ITM_RND.F_RND_AMT(w.QTY * t.ACT_COST / G_AVE_FIX.STD_QTY)
		FROM	MGT_ACC_SML_COST t
		WHERE	0=0
		AND	t.CALC_NO = G_AVE_FIX.CALC_NO
		AND	t.CALC_GRP_CD = G_AVE_FIX.CALC_GRP_CD
		AND	t.TOP_REC_NO = G_AVE_FIX.TOP_REC_NO
		AND	t.ACT_COST <> 0
		;
		L_CNT := SQL%ROWCOUNT ;

		IF L_CNT = 0 THEN
			G_ERR_MSG := FCPA_ERR.MSG_BINDER(
					w.CALC_GRP_CD,
					FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
					w.WG_CD, w.MNG_DPT_CD,
					MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
					w.LOT_NO, w.SUBLOT_NO,
					MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
					w.ASST_TYP,
					w.ACT_SLS_ID, w.ACT_SLS_ID_SUB
					) ;

			G_MSG := FCPA_MSG.MSG_BINDER(
					w.CALC_GRP_CD,
					FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
					w.WG_CD, w.MNG_DPT_CD,
					MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
					w.LOT_NO, w.SUBLOT_NO,
					MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
					w.ASST_TYP,
					w.ACT_SLS_ID, w.ACT_SLS_ID_SUB
					) ;

			IF w.AMT_SET_TYP = C_SET_AVE_STD THEN
				UPDATE	MGT_ACT_SLS t
				SET	t.REC_EVAL_TYP = C_EVAL_STD
				WHERE	0=0
				AND	t.ACT_SLS_ID = w.ACT_SLS_ID
				AND	t.ACT_SLS_ID_SUB = w.ACT_SLS_ID_SUB
				;

				IF I_ERR_FLG = '0' THEN
					FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0042', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
				ELSE
					COMMIT ;
					FCPA_ERR.RAISE_APP_ERR('MGBBD0042', G_ERR_MSG) ;
				END IF ;

			ELSIF I_ERR_FLG = '0' THEN
				UPDATE	MGT_ACT_SLS t
				SET	t.REC_EVAL_TYP = NULL
				WHERE	0=0
				AND	t.ACT_SLS_ID = w.ACT_SLS_ID
				AND	t.ACT_SLS_ID_SUB = w.ACT_SLS_ID_SUB
				;
				FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0041', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
			ELSE
				FCPA_ERR.RAISE_APP_ERR('MGBBD0041', G_ERR_MSG) ;
			END IF ;
		ELSE
			DELETE FROM MGT_ACT_SLS_EXPNS T
			WHERE T.ACT_SLS_ID = w.ACT_SLS_ID
			AND T.ACT_SLS_ID_SUB = w.ACT_SLS_ID_SUB
			AND T.AMT = 0;

			SELECT COUNT(*) INTO L_CNT FROM MGT_ACT_SLS_EXPNS T
			WHERE T.ACT_SLS_ID = w.ACT_SLS_ID
			AND T.ACT_SLS_ID_SUB = w.ACT_SLS_ID_SUB;

			IF L_CNT = 0 THEN
				UPDATE MGT_ACT_SLS T
				SET T.REC_EVAL_TYP = C_EVAL_ZERO
				WHERE T.ACT_SLS_ID = w.ACT_SLS_ID
				AND T.ACT_SLS_ID_SUB = w.ACT_SLS_ID_SUB;

				G_MSG := FCPA_MSG.MSG_BINDER(
						w.CALC_GRP_CD,
						FCPA_DATE_UTIL.F_TO_CHAR(w.YM, FCPA_DATE_UTIL.Y4M),
						w.WG_CD, w.MNG_DPT_CD,
						MAPA_COMM.F_TO_DISP_ITM(w.ITM_CD, w.ITM_SUB1, w.ITM_SUB2, w.ITM_SUB3, G_PARM_ITM_SUB_TYP),
						w.LOT_NO, w.SUBLOT_NO,
						MAPA_COMM.F_TO_DISP_SNO(w.SNO1, w.SNO2, w.SNO3, w.SNO4, G_PARM_SNO_TYP),
						w.ASST_TYP,
						w.ACT_SLS_ID, w.ACT_SLS_ID_SUB
						) ;
				FCPA_BATCH_LOG.P_DATA_LOG('MGBBD0052', G_MSG, G_LOG_NO, G_LOG_SUB_KEY1, G_LOG_SUB_KEY2) ;
			END IF ;
		END IF ;
	END LOOP ;

	--処理が終了しました。{1}
	FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_SET_EXPNS.P_SLS') ;

END P_SLS ;

END MGPA_SET_EXPNS ;

