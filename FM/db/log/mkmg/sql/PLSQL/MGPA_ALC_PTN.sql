CREATE OR REPLACE PACKAGE BODY MGPA_ALC_PTN
IS
	TYPE DPT_ALC_GRP_LIST IS TABLE OF MAPA_META.DPT_ALC_GRP%TYPE INDEX BY MAPA_META.COST_DPT_CD%TYPE ;
	DPT_ALC_GRP	DPT_ALC_GRP_LIST ;

	TYPE LOC_ALC_GRP_LIST IS TABLE OF MAPA_META.LOC_ALC_GRP%TYPE INDEX BY MAPA_META.LOC_CD%TYPE ;
	LOC_ALC_GRP	LOC_ALC_GRP_LIST ;

	TYPE OPER_ALC_GRP_LIST IS TABLE OF MAPA_META.OPER_ALC_GRP%TYPE INDEX BY MAPA_META.OPER_CD%TYPE ;
	OPER_ALC_GRP	OPER_ALC_GRP_LIST ;

	TYPE BP_ALC_GRP_LIST IS TABLE OF MAPA_META.BP_ALC_GRP%TYPE INDEX BY MAPA_META.BP_CD%TYPE ;
	BP_ALC_GRP	BP_ALC_GRP_LIST ;

	TYPE CTG_ALC_GRP_LIST IS TABLE OF MAPA_META.CTG_ALC_GRP%TYPE INDEX BY MAPA_META.COST_CTG_CD%TYPE ;
	CTG_ALC_GRP	CTG_ALC_GRP_LIST ;

	TYPE ITM_ALC_GRP_LIST IS TABLE OF MAPA_META.ITM_ALC_GRP%TYPE INDEX BY MGPA_META.CONCAT_ITM%TYPE ;
	ITM_ALC_GRP	ITM_ALC_GRP_LIST ;

	TYPE ALC_PTN_LIST IS TABLE OF MAPA_META.ALC_PTN_CD%TYPE INDEX BY MAPA_META.ALC_AC_CD%TYPE ;
	ALC_PTN		ALC_PTN_LIST ;

	TYPE EXPNS_LIST_AC IS TABLE OF MAPA_META.EXPNS_CD%TYPE INDEX BY MAPA_META.ALC_AC_CD%TYPE ;
	EXPNS_AC		EXPNS_LIST_AC ;

	TYPE EXPNS_LIST_RULE IS TABLE OF MAPA_META.EXPNS_CD%TYPE INDEX BY MAPA_META.ALC_PTN_CD%TYPE ;
	EXPNS_RULE		EXPNS_LIST_RULE ;

	G_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;

	G_ITM_DLM	CONSTANT MAPA_META.STR20%TYPE := MGC_STR.ITM_DLM ;

	G_MST_CNT	NUMBER ;

	L_CONCAT_ITM	MGPA_META.CONCAT_ITM%TYPE ;

PROCEDURE P_INI
/**************************************************************************
<SYNOPSIS>
	初期化処理
<REMARKS>
	メモリ内のワークデータをクリアする
<ARGUMENTS>
<HISTORY>
**************************************************************************/
AS
BEGIN
	G_MST_CNT := 0 ;

	DPT_ALC_GRP.DELETE ;
	LOC_ALC_GRP.DELETE ;
	OPER_ALC_GRP.DELETE ;
	BP_ALC_GRP.DELETE ;
	CTG_ALC_GRP.DELETE ;
	ITM_ALC_GRP.DELETE ;
	ALC_PTN.DELETE ;

END P_INI ;

PROCEDURE P_SET_WORK (
	I_CALC_GRP_CD	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_TERM		IN MAPA_META.YM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	対象となる配賦パタン選択マスタのデータを作成する
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_TERM
		期
<HISTORY>
**************************************************************************/
AS
	L_CALC_GRP	MAM_CALC_GRP%ROWTYPE ;
	CURSOR CTG_LIST
	IS
		SELECT	w.CALC_CTG_CD
		FROM	MGW_CALC_CTG w
		WHERE	0=0
		ORDER BY w.CTG_PRIO, w.CALC_CTG_CD
	;

BEGIN
	P_INI() ;

	DELETE MAW_GRP_WG_KEY ;
	L_CALC_GRP := MGPA_CALC_GRP.F_GET_REC(I_CALC_GRP_CD) ;
	IF L_CALC_GRP.RUNTIME_WG_CD IS NULL THEN
		INSERT INTO MAW_GRP_WG_KEY
		SELECT m.CALC_GRP_CD, m.WG_CD FROM MAM_GRP_WG m WHERE m.CALC_GRP_CD = I_CALC_GRP_CD ;
	ELSE
		INSERT INTO MAW_GRP_WG_KEY VALUES (I_CALC_GRP_CD, L_CALC_GRP.RUNTIME_WG_CD) ;
	END IF ;

	DELETE MGW_ALC_PTN_SEL ;
	MGPA_CALC_CTG.P_SET_WORK(I_CALC_GRP_CD, MAC_CALC_CTG_TYP.ALC_PTN_SEL) ;
	FOR L1 IN CTG_LIST LOOP
		INSERT INTO MGW_ALC_PTN_SEL (
			ALC_AC_CD,
			DPT_ALC_GRP,
			LOC_ALC_GRP,
			OPER_ALC_GRP,
			BP_ALC_GRP,
			CTG_ALC_GRP,
			ITM_ALC_GRP,
			WG_CD,
			ALC_PTN_CD,
			EXPNS_CD
			)
		SELECT	m.ALC_AC_CD,
			NVL(m.DPT_ALC_GRP, G_NULL_VAL),
			NVL(m.LOC_ALC_GRP, G_NULL_VAL),
			NVL(m.OPER_ALC_GRP,G_NULL_VAL),
			NVL(m.BP_ALC_GRP,  G_NULL_VAL),
			NVL(m.CTG_ALC_GRP, G_NULL_VAL),
			NVL(m.ITM_ALC_GRP, G_NULL_VAL),
			m.WG_CD,
			m.ALC_PTN_CD,
			m.EXPNS_CD
		FROM	MAM_ALC_PTN_SEL m, MAW_GRP_WG_KEY m2
		WHERE	0=0
		AND	m.TERM = I_TERM
		AND	m.CALC_CTG_CD = L1.CALC_CTG_CD
		AND	m2.CALC_GRP_CD = I_CALC_GRP_CD
		AND	m.WG_CD = m2.WG_CD
		AND	NOT EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.ALC_AC_CD = m.ALC_AC_CD
				AND	w.DPT_ALC_GRP = NVL(m.DPT_ALC_GRP, G_NULL_VAL)
				AND	w.LOC_ALC_GRP = NVL(m.LOC_ALC_GRP, G_NULL_VAL)
				AND	w.OPER_ALC_GRP= NVL(m.OPER_ALC_GRP,G_NULL_VAL)
				AND	w.BP_ALC_GRP  = NVL(m.BP_ALC_GRP,  G_NULL_VAL)
				AND	w.CTG_ALC_GRP = NVL(m.CTG_ALC_GRP, G_NULL_VAL)
				AND	w.ITM_ALC_GRP = NVL(m.ITM_ALC_GRP, G_NULL_VAL)
				AND	w.WG_CD = m.WG_CD
			)
		;
		G_MST_CNT := G_MST_CNT + SQL%ROWCOUNT ;
	END LOOP ;
	FCPA_BATCH_LOG.P_PROC_LOG('MGBDD0008', 'MGW_ALC_PTN_SEL', G_MST_CNT) ;

	IF G_MST_CNT = 0 THEN
		GOTO SKIP_ALC_GRP ;
	END IF ;

	FOR w1 IN (
		SELECT	m.DPT_CD,
			m.DPT_ALC_GRP
		FROM	MAM_COST_DPT m
		WHERE	0=0
		AND	m.TERM = I_TERM
		AND	m.DEL_FLG = '0'
		AND	m.DPT_ALC_GRP IS NOT NULL
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.DPT_ALC_GRP = m.DPT_ALC_GRP
			)
		)
	LOOP
		DPT_ALC_GRP(w1.DPT_CD) := w1.DPT_ALC_GRP ;
	END LOOP ;

	FOR w2 IN (
		SELECT	m.LOC_CD,
			m.LOC_ALC_GRP
		FROM	MAM_LOC m
		WHERE	0=0
		AND	m.DEL_FLG = '0'
		AND	m.LOC_ALC_GRP IS NOT NULL
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.LOC_ALC_GRP = m.LOC_ALC_GRP
			)
		)
	LOOP
		LOC_ALC_GRP(w2.LOC_CD) := w2.LOC_ALC_GRP ;
	END LOOP ;

	FOR w3 IN (
		SELECT	m.OPER_CD,
			m.OPER_ALC_GRP
		FROM	MAM_OPER m
		WHERE	0=0
		AND	m.DEL_FLG = '0'
		AND	m.OPER_ALC_GRP IS NOT NULL
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.OPER_ALC_GRP = m.OPER_ALC_GRP
			)
		)
	LOOP
		OPER_ALC_GRP(w3.OPER_CD) := w3.OPER_ALC_GRP ;
	END LOOP ;

	FOR w4 IN (
		SELECT	m.BP_CD,
			m.BP_ALC_GRP
		FROM	MAM_BP m
		WHERE	0=0
		AND	m.DEL_FLG = '0'
		AND	m.BP_ALC_GRP IS NOT NULL
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.BP_ALC_GRP = m.BP_ALC_GRP
			)
		)
	LOOP
		BP_ALC_GRP(w4.BP_CD) := w4.BP_ALC_GRP ;
	END LOOP ;

	FOR w5 IN (
		SELECT	m.CTG_CD,
			m.CTG_ALC_GRP
		FROM	MAM_COST_CTG m
		WHERE	0=0
		AND	m.DEL_FLG = '0'
		AND	m.CTG_ALC_GRP IS NOT NULL
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.CTG_ALC_GRP = m.CTG_ALC_GRP
			)
		)
	LOOP
		CTG_ALC_GRP(w5.CTG_CD) := w5.CTG_ALC_GRP ;
	END LOOP ;

	FOR w6 IN (
		SELECT	m.ITM_CD,
			m.ITM_SUB1,
			m.ITM_SUB2,
			m.ITM_SUB3,
			m.ITM_ALC_GRP
		FROM	MAM_ITM m
		WHERE	0=0
		AND	m.ITM_ALC_GRP IS NOT NULL
		AND	EXISTS (
				SELECT	'X'
				FROM	MGW_ALC_PTN_SEL w
				WHERE	0=0
				AND	w.ITM_ALC_GRP = m.ITM_ALC_GRP
			)
		)
	LOOP
		L_CONCAT_ITM := w6.ITM_CD || G_ITM_DLM || w6.ITM_SUB1 || G_ITM_DLM || w6.ITM_SUB2 || G_ITM_DLM || w6.ITM_SUB3 ;
		ITM_ALC_GRP(L_CONCAT_ITM) := w6.ITM_ALC_GRP ;
	END LOOP ;

	<<SKIP_ALC_GRP>>
		NULL ;

	FOR w7 IN (
		SELECT	m.ALC_AC_CD,
			m.ALC_PTN_CD
		FROM	MAM_ALC_AC m
		WHERE	0=0
		AND	m.DEL_FLG = '0'
		AND	m.ALC_PTN_CD IS NOT NULL
		)
	LOOP
		ALC_PTN(w7.ALC_AC_CD) := w7.ALC_PTN_CD ;
	END LOOP ;

	FOR w8 IN (
		SELECT	m.ALC_AC_CD,
				m.EXPNS_CD
		FROM	MAM_ALC_AC m
		WHERE	0=0
		AND	m.DEL_FLG = '0'
		AND	m.EXPNS_CD IS NOT NULL
		)
	LOOP
		EXPNS_AC(w8.ALC_AC_CD) := w8.EXPNS_CD ;
	END LOOP ;

	FOR w9 IN (
		SELECT	m.ALC_PTN_CD,
				m.EXPNS_CD
		FROM	MAM_ALC_RULE m
		WHERE	0=0
		AND	m.TERM = I_TERM
		AND	m.DEL_FLG = '0'
		AND	m.EXPNS_CD IS NOT NULL
		)
	LOOP
		EXPNS_RULE(w9.ALC_PTN_CD) := w9.EXPNS_CD ;
	END LOOP ;

END P_SET_WORK ;

PROCEDURE P_GET_ALC_PTN_EXPNS (
	I_ALC_AC_CD	IN MAPA_META.ALC_AC_CD%TYPE,
	I_DPT_CD	IN MAPA_META.COST_DPT_CD%TYPE,
	I_LOC_CD	IN MAPA_META.LOC_CD%TYPE,
	I_OPER_CD	IN MAPA_META.OPER_CD%TYPE,
	I_BP_CD		IN MAPA_META.BP_CD%TYPE,
	I_CTG_CD	IN MAPA_META.COST_CTG_CD%TYPE,
	I_ITM_CD	IN MAPA_META.ITM_CD%TYPE,
	I_ITM_SUB1	IN MAPA_META.ITM_SUB1%TYPE,
	I_ITM_SUB2	IN MAPA_META.ITM_SUB2%TYPE,
	I_ITM_SUB3	IN MAPA_META.ITM_SUB3%TYPE,
	I_WG_CD		IN MAPA_META.WG_CD%TYPE,
	O_ALC_PTN_CD	OUT MAPA_META.ALC_PTN_CD%TYPE,
	O_EXPNS_CD		OUT MAPA_META.EXPNS_CD%TYPE
)
/*********************************************************
<SYNOPSIS>
	使用する配賦パタンＣＤと費目ＣＤを取得する
<REMARKS>

<ARGUMENTS>
<IN>	I_ALC_AC_CD
		配賦科目ＣＤ
<IN>	I_DPT_CD
		部門ＣＤ
<IN>	I_LOC_CD
		場所ＣＤ
<IN>	I_OPER_CD
		工程ＣＤ
<IN>	I_BP_CD
		取引先ＣＤ
<IN>	I_CTG_CD
		品群ＣＤ
<IN>	I_ITM_CD
		品目ＣＤ
<IN>	I_ITM_SUB1
		枝番１
<IN>	I_ITM_SUB2
		枝番２
<IN>	I_ITM_SUB3
		枝番３
<IN>	I_WG_CD
		ワーキンググループＣＤ
<OUT>	O_ALC_PTN_CD
		対象となる配賦パタンＣＤ
<OUT>	O_EXPNS_CD
		対象となる費目ＣＤ
<HISTORY>
**********************************************************/
AS
	L_DPT_ALC_GRP	MAPA_META.DPT_ALC_GRP%TYPE ;
	L_LOC_ALC_GRP	MAPA_META.LOC_ALC_GRP%TYPE ;
	L_OPER_ALC_GRP	MAPA_META.OPER_ALC_GRP%TYPE ;
	L_BP_ALC_GRP	MAPA_META.BP_ALC_GRP%TYPE ;
	L_CTG_ALC_GRP	MAPA_META.CTG_ALC_GRP%TYPE ;
	L_ITM_ALC_GRP	MAPA_META.ITM_ALC_GRP%TYPE ;
BEGIN
	O_ALC_PTN_CD := NULL ;
	O_EXPNS_CD := NULL ;

	IF G_MST_CNT = 0 THEN
		GOTO SKIP_ALC_PTN_SEL ;
	END IF ;

	IF I_DPT_CD IS NOT NULL AND DPT_ALC_GRP.EXISTS(I_DPT_CD) THEN
		L_DPT_ALC_GRP := DPT_ALC_GRP(I_DPT_CD) ;
	ELSE
		L_DPT_ALC_GRP := G_NULL_VAL ;
	END IF ;

	IF I_LOC_CD IS NOT NULL AND LOC_ALC_GRP.EXISTS(I_LOC_CD) THEN
		L_LOC_ALC_GRP := LOC_ALC_GRP(I_LOC_CD) ;
	ELSE
		L_LOC_ALC_GRP := G_NULL_VAL ;
	END IF ;

	IF I_OPER_CD IS NOT NULL AND OPER_ALC_GRP.EXISTS(I_OPER_CD) THEN
		L_OPER_ALC_GRP := OPER_ALC_GRP(I_OPER_CD) ;
	ELSE
		L_OPER_ALC_GRP := G_NULL_VAL ;
	END IF ;

	IF I_BP_CD IS NOT NULL AND BP_ALC_GRP.EXISTS(I_BP_CD) THEN
		L_BP_ALC_GRP := BP_ALC_GRP(I_BP_CD) ;
	ELSE
		L_BP_ALC_GRP := G_NULL_VAL ;
	END IF ;

	IF I_CTG_CD IS NOT NULL AND CTG_ALC_GRP.EXISTS(I_CTG_CD) THEN
		L_CTG_ALC_GRP := CTG_ALC_GRP(I_CTG_CD) ;
	ELSE
		L_CTG_ALC_GRP := G_NULL_VAL ;
	END IF ;

	IF I_ITM_CD IS NOT NULL AND I_ITM_SUB1 IS NOT NULL AND I_ITM_SUB2 IS NOT NULL AND I_ITM_SUB3 IS NOT NULL THEN
		L_CONCAT_ITM := I_ITM_CD || G_ITM_DLM || I_ITM_SUB1 || G_ITM_DLM || I_ITM_SUB2 || G_ITM_DLM || I_ITM_SUB3 ;
		IF ITM_ALC_GRP.EXISTS(L_CONCAT_ITM) THEN
			L_ITM_ALC_GRP := ITM_ALC_GRP(L_CONCAT_ITM) ;
		ELSE
			L_ITM_ALC_GRP := G_NULL_VAL ;
		END IF;
	ELSE
		L_ITM_ALC_GRP := G_NULL_VAL ;
	END IF ;

	FOR x IN (
		SELECT	w.ALC_PTN_CD,
				w.EXPNS_CD
		FROM	MGW_ALC_PTN_SEL w
		WHERE	0=0
		AND	w.ALC_AC_CD	= I_ALC_AC_CD
		AND	(w.DPT_ALC_GRP	= L_DPT_ALC_GRP	 OR w.DPT_ALC_GRP  = G_NULL_VAL)
		AND	(w.LOC_ALC_GRP	= L_LOC_ALC_GRP	 OR w.LOC_ALC_GRP  = G_NULL_VAL)
		AND	(w.OPER_ALC_GRP	= L_OPER_ALC_GRP OR w.OPER_ALC_GRP = G_NULL_VAL)
		AND	(w.BP_ALC_GRP	= L_BP_ALC_GRP	 OR w.BP_ALC_GRP   = G_NULL_VAL)
		AND	(w.CTG_ALC_GRP	= L_CTG_ALC_GRP	 OR w.CTG_ALC_GRP  = G_NULL_VAL)
		AND	(w.ITM_ALC_GRP	= L_ITM_ALC_GRP	 OR w.ITM_ALC_GRP  = G_NULL_VAL)
		AND	w.WG_CD	= I_WG_CD
		ORDER BY
			DECODE(w.DPT_ALC_GRP,  G_NULL_VAL, NULL, w.DPT_ALC_GRP),
			DECODE(w.LOC_ALC_GRP,  G_NULL_VAL, NULL, w.LOC_ALC_GRP),
			DECODE(w.OPER_ALC_GRP, G_NULL_VAL, NULL, w.OPER_ALC_GRP),
			DECODE(w.BP_ALC_GRP,   G_NULL_VAL, NULL, w.BP_ALC_GRP),
			DECODE(w.CTG_ALC_GRP,  G_NULL_VAL, NULL, w.CTG_ALC_GRP),
			DECODE(w.ITM_ALC_GRP,  G_NULL_VAL, NULL, w.ITM_ALC_GRP)
		)
	LOOP
		O_ALC_PTN_CD := x.ALC_PTN_CD ;
		O_EXPNS_CD := x.EXPNS_CD ;
		EXIT ;
	END LOOP ;

	<<SKIP_ALC_PTN_SEL>>
		NULL ;

	IF O_ALC_PTN_CD IS NULL AND ALC_PTN.EXISTS(I_ALC_AC_CD) THEN
		O_ALC_PTN_CD := ALC_PTN(I_ALC_AC_CD) ;
	END IF ;

	IF O_EXPNS_CD IS NULL THEN
		IF EXPNS_AC.EXISTS(I_ALC_AC_CD) THEN
			O_EXPNS_CD := EXPNS_AC(I_ALC_AC_CD) ;
		ELSIF O_ALC_PTN_CD IS NOT NULL AND EXPNS_RULE.EXISTS(O_ALC_PTN_CD) THEN
			O_EXPNS_CD := EXPNS_RULE(O_ALC_PTN_CD) ;
		END IF ;
	END IF ;

END P_GET_ALC_PTN_EXPNS ;

END MGPA_ALC_PTN ;

/
show errors;


