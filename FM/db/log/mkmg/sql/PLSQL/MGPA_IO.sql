CREATE OR REPLACE PACKAGE BODY MGPA_IO
IS

PROCEDURE P_MAIN (
	I_CALC_GRP_CD	IN MAPA_META.CALC_GRP_CD%TYPE,
	I_CALC_NO	IN MAPA_META.CALC_NO%TYPE,
	I_WG_CD	IN	MAPA_META.WG_CD%TYPE DEFAULT NULL
)
/**************************************************************************
<SYNOPSIS>
	受払表データ作成メイン処理
<REMARKS>

<ARGUMENTS>
<IN>	I_CALC_GRP_CD
		計算グループＣＤ
<IN>	I_CALC_NO
		原価計算ＮＯ
<HISTORY>
**************************************************************************/
IS
	C_EVAL_MONTH_AVE	CONSTANT MAPA_META.EVAL_TYP%TYPE := MAC_EVAL_TYP.MONTH_AVE ;
	C_EVAL_TERM_AVE		CONSTANT MAPA_META.EVAL_TYP%TYPE := MAC_EVAL_TYP.TERM_AVE ;
	C_EVAL_STD_UNIT		CONSTANT MAPA_META.EVAL_TYP%TYPE := MAC_EVAL_TYP.STD_UNIT ;

	C_UNIT_CALC_NON		CONSTANT MAPA_META.UNIT_CALC_TYP%TYPE := MAC_UNIT_CALC_TYP.NON ;
	C_UNIT_CALC_CALC	CONSTANT MAPA_META.UNIT_CALC_TYP%TYPE := MAC_UNIT_CALC_TYP.CALC ;

	C_EXPNS_PROD		CONSTANT MAPA_META.EXPNS_TYP%TYPE := MAC_EXPNS_TYP.PROD ;

	C_CALC_REC_ST_STK	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.ST_STK ;
	C_CALC_REC_PURC		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.PURC ;
	C_CALC_REC_COMP		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.COMP ;
	C_CALC_REC_IO		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.IO ;
	C_CALC_REC_INPT		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.INPT ;
	C_CALC_REC_SLS		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.SLS ;
	C_CALC_REC_END_STK	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.END_STK ;
	C_CALC_REC_AVE		CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.AVE ;
	C_CALC_REC_GP_ALC	CONSTANT MGPA_META.CALC_REC_TYP%TYPE := MGC_CALC_REC_TYP.GP_ALC ;

	C_COST_IO_FFR_PROV	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.FFR_PROV ;
	C_COST_IO_ONR_PROV	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.ONR_PROV ;
	C_COST_IO_STK_IN	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_IN ;
	C_COST_IO_STK_OUT	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_OUT ;
	C_COST_IO_STK_IO	CONSTANT MAPA_META.COST_IO_TYP%TYPE := MAC_COST_IO_TYP.STK_IO ;

	C_AC_SLIP_PROD_ITM_SO	CONSTANT MAPA_META.AC_SLIP_TYP%TYPE := MAC_AC_SLIP_TYP.PROD_ITM_SO ;
	C_AC_SLIP_SHIP		CONSTANT MAPA_META.AC_SLIP_TYP%TYPE := MAC_AC_SLIP_TYP.SHIP ;
	C_AC_SLIP_SHIP_RET	CONSTANT MAPA_META.AC_SLIP_TYP%TYPE := MAC_AC_SLIP_TYP.SHIP_RET ;

	C_ASST_PROD		CONSTANT MAPA_META.ASST_TYP%TYPE := MAC_ASST_TYP.CO_PROD ;
	C_ASST_SLS		CONSTANT MAPA_META.ASST_TYP%TYPE := MAC_ASST_TYP.CO_SLS ;

	C_ASSET_MNG_MNG		CONSTANT MAPA_META.ASSET_MNG_TYP%TYPE := MAC_ASSET_MNG_TYP.MNG ;

	C_MAX_CNT	CONSTANT INTEGER := 50000 ; --バルクインサートでの最大レコード数

	C_NULL_VAL	CONSTANT MAPA_META.STR20%TYPE := MAC_STR.NULL_VAL ;

	TYPE LIST_TYPE IS TABLE OF MGT_IO%ROWTYPE INDEX BY BINARY_INTEGER ;
	rec	LIST_TYPE ;
	i	INTEGER ;
	j	INTEGER ;

	L_ARG	MGT_ARG%ROWTYPE ;

	L_CNT	NUMBER ;
	L_MONTHLY_FLG	MAPA_META.FLG%TYPE ;
BEGIN
	IF I_WG_CD IS NULL THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_IO.P_MAIN') ;
	ELSE
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0001', 'MGPA_IO.P_MAIN - ' || I_WG_CD) ;
	END IF ;

	L_ARG := MGPA_ARG.F_GET_ARG(I_CALC_GRP_CD, I_CALC_NO) ;

	IF L_ARG.COST_CALC_TYP != MAC_COST_CALC_TYP.CALC_STK THEN
		GOTO PROC_END ;
	END IF ;

	DELETE MGT_IO t
	WHERE	0=0
	AND	t.CALC_NO = I_CALC_NO
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	(I_WG_CD IS NULL OR t.WG_CD = I_WG_CD)
	;

	SELECT	COUNT(*)
	INTO	L_CNT
	FROM	MGT_CALC_PARM t
	WHERE	0=0
	AND	t.CALC_GRP_CD = I_CALC_GRP_CD
	AND	t.CALC_NO = I_CALC_NO
	AND	t.PARM_KEY = 'SCA_TO'
	AND	t.PARM_VAL IS NOT NULL
	AND	t.PARM_VAL != '0'
	AND	t.PARM_VAL != 'NO'
	;

	IF L_CNT > 0 THEN
		L_MONTHLY_FLG := '1' ;
	ELSE
		L_MONTHLY_FLG := '0' ;
	END IF ;

	i := 0 ;
	FOR x IN (
		SELECT	/*+ORDERED*/
			DISTINCT
			DECODE(t2.EVAL_TYP,
				C_EVAL_TERM_AVE, NULL,
				C_EVAL_STD_UNIT, DECODE(L_MONTHLY_FLG, '0', NULL, t0.YM),
				t0.YM)	YM,
			t0.WG_CD,
			t0.MNG_DPT_CD,
			t0.ITM_CD,
			t0.ITM_SUB1,
			t0.ITM_SUB2,
			t0.ITM_SUB3,
			DECODE(t2.LOT_TYP, C_UNIT_CALC_NON, NULL, t0.LOT_NO)	LOT_NO,
			DECODE(t2.SUBLOT_TYP, C_UNIT_CALC_NON, NULL, t0.SUBLOT_NO)	SUBLOT_NO,
			DECODE(t2.SNO1_TYP, C_UNIT_CALC_NON, NULL, t0.SNO1)	SNO1,
			DECODE(t2.SNO2_TYP, C_UNIT_CALC_NON, NULL, t0.SNO2)	SNO2,
			DECODE(t2.SNO3_TYP, C_UNIT_CALC_NON, NULL, t0.SNO3)	SNO3,
			DECODE(t2.SNO4_TYP, C_UNIT_CALC_NON, NULL, t0.SNO4)	SNO4,
			t0.ASST_TYP,
			t2.LOT_TYP,
			t2.SUBLOT_TYP,
			t2.SNO1_TYP,
			t2.SNO2_TYP,
			t2.SNO3_TYP,
			t2.SNO4_TYP,
			NVL(m.ASSET_MNG_TYP, C_ASSET_MNG_MNG)	ASSET_MNG_TYP
		FROM	MGT_ACC_TOP t0, MGT_CALC_ITM t1, MGT_CALC_PTN t2, MAM_ITM_SRCH m
		WHERE	0=0
		AND	t0.CALC_NO = I_CALC_NO
		AND	t0.CALC_GRP_CD = I_CALC_GRP_CD
		AND	(I_WG_CD IS NULL OR t0.WG_CD = I_WG_CD)
		AND	t0.ITM_CD = m.ITM_CD(+)
		AND	t0.ITM_SUB1 = m.ITM_SUB1(+)
		AND	t0.ITM_SUB2 = m.ITM_SUB2(+)
		AND	t0.ITM_SUB3 = m.ITM_SUB3(+)
		AND	m.DEL_FLG(+) = '0'
		AND	m.RELEASE_FLG(+) = '1'
		AND	t0.ASST_TYP IN (C_ASST_PROD, C_ASST_SLS)
		AND	t0.REPURC_OBLI_FLG = '0'
		AND	t0.CALC_REC_TYP IN (
				C_CALC_REC_ST_STK,
				C_CALC_REC_PURC,
				C_CALC_REC_COMP,
				C_CALC_REC_IO,
				C_CALC_REC_INPT,
				C_CALC_REC_SLS,
				C_CALC_REC_END_STK,
				C_CALC_REC_GP_ALC
			)
		AND	t0.CALC_NO = t1.CALC_NO
		AND	t0.CALC_GRP_CD = t1.CALC_GRP_CD
		AND	t0.ITM_CD = t1.ITM_CD
		AND	t0.ITM_SUB1 = t1.ITM_SUB1
		AND	t0.ITM_SUB2 = t1.ITM_SUB2
		AND	t0.ITM_SUB3 = t1.ITM_SUB3
		AND	t0.WG_CD = t1.WG_CD
		AND	t1.CALC_NO = t2.CALC_NO
		AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD
		AND	t1.CALC_PTN_CD = t2.CALC_PTN_CD
		)
	LOOP
		i := i + 1 ;

		rec(i).CALC_NO	:= I_CALC_NO ;
		rec(i).CALC_GRP_CD := I_CALC_GRP_CD ;
		rec(i).WG_CD := x.WG_CD ;
		rec(i).YM	:= NVL(x.YM, L_ARG.END_YM) ;
		rec(i).YM_SUB	:= x.YM ;
		rec(i).MNG_DPT_CD := x.MNG_DPT_CD ;
		rec(i).ITM_CD	:= x.ITM_CD ;
		rec(i).ITM_SUB1	:= x.ITM_SUB1 ;
		rec(i).ITM_SUB2	:= x.ITM_SUB2 ;
		rec(i).ITM_SUB3	:= x.ITM_SUB3 ;
		rec(i).LOT_NO	:= NVL(x.LOT_NO, C_NULL_VAL) ;
		rec(i).SUBLOT_NO	:= NVL(x.SUBLOT_NO, C_NULL_VAL) ;
		rec(i).SNO1	:= NVL(x.SNO1, C_NULL_VAL) ;
		rec(i).SNO2	:= NVL(x.SNO2, C_NULL_VAL) ;
		rec(i).SNO3	:= NVL(x.SNO3, C_NULL_VAL) ;
		rec(i).SNO4	:= NVL(x.SNO4, C_NULL_VAL) ;
		rec(i).ASST_TYP	:= x.ASST_TYP ;

		rec(i).STD_QTY	:= 0 ;
		rec(i).AVE_UPRI	:= 0 ;
		rec(i).STD_UPRI	:= 0 ;
		rec(i).ST_STK_QTY := 0 ;
		rec(i).ST_STK_AMT := 0 ;
		rec(i).MFG_QTY	:= 0 ;
		rec(i).MFG_AMT	:= 0 ;
		rec(i).PURC_QTY	:= 0 ;
		rec(i).PURC_AMT	:= 0 ;
		rec(i).MFG_GR_QTY := 0 ;
		rec(i).MFG_GR_AMT := 0 ;
		rec(i).OTHR_GR_QTY := 0 ;
		rec(i).OTHR_GR_AMT := 0 ;
		rec(i).ALC_AMT	:= 0 ;
		rec(i).INPT_QTY	:= 0 ;
		rec(i).INPT_AMT	:= 0 ;
		rec(i).PLNT_GI_QTY := 0 ;
		rec(i).PLNT_GI_AMT := 0 ;
		rec(i).OTHR_GI_QTY := 0 ;
		rec(i).OTHR_GI_AMT := 0 ;
		rec(i).PROV_QTY	:= 0 ;
		rec(i).PROV_AMT	:= 0 ;
		rec(i).SLS_QTY	:= 0 ;
		rec(i).SLS_AMT	:= 0 ;
		rec(i).END_STK_QTY := 0 ;
		rec(i).END_STK_AMT := 0 ;
		rec(i).DIFF_QTY	:= 0 ;
		rec(i).DIFF_AMT	:= 0 ;
		rec(i).XPNS_INPT_QTY := 0 ;
		rec(i).XPNS_INPT_AMT := 0 ;

		--受払情報の取得
		FOR y IN (
			SELECT	w.CALC_REC_TYP,
				w.COST_IO_TYP,
				w.AC_SLIP_TYP,
				w.YM,
				SUM(w.QTY)	QTY,
				SUM(w.AMT)	AMT
			FROM	(
				SELECT	/*+USE_NL(t1 t2) INDEX(t1 MGT_ACC_TOP_ALL_IE02) INDEX(t2 MGT_ACC_SML_COST_ALL_IE01)*/
					t1.TOP_REC_NO,
					t1.CALC_REC_TYP,
					t1.COST_IO_TYP,
					t1.AC_SLIP_TYP,
					t1.YM,
					t1.QTY,
					NVL(SUM(t2.ACT_COST), 0)	AMT
				FROM	MGT_ACC_TOP t1, MGT_ACC_SML_COST t2
				WHERE	0=0
				AND	t1.CALC_NO = I_CALC_NO
				AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
				AND	t1.WG_CD = x.WG_CD
				AND	(
					t1.YM = NVL(x.YM, t1.YM)
					OR
					t1.CALC_REC_TYP = C_CALC_REC_END_STK AND t1.YM = ADD_MONTHS(x.YM, -1)
					)
				AND	t1.MNG_DPT_CD = x.MNG_DPT_CD
				AND	t1.ITM_CD = x.ITM_CD
				AND	t1.ITM_SUB1 = x.ITM_SUB1
				AND	t1.ITM_SUB2 = x.ITM_SUB2
				AND	t1.ITM_SUB3 = x.ITM_SUB3
				AND	t1.LOT_NO = NVL(x.LOT_NO, t1.LOT_NO)
				AND	t1.SUBLOT_NO = NVL(x.SUBLOT_NO, t1.SUBLOT_NO)
				AND	t1.SNO1 = NVL(x.SNO1, t1.SNO1)
				AND	t1.SNO2 = NVL(x.SNO2, t1.SNO2)
				AND	t1.SNO3 = NVL(x.SNO3, t1.SNO3)
				AND	t1.SNO4 = NVL(x.SNO4, t1.SNO4)
				AND	t1.ASST_TYP = x.ASST_TYP
				AND	t1.REPURC_OBLI_FLG = '0'
				AND	t1.CALC_REC_TYP IN (
						C_CALC_REC_ST_STK,
						C_CALC_REC_PURC,
						C_CALC_REC_COMP,
						C_CALC_REC_IO,
						C_CALC_REC_INPT,
						C_CALC_REC_SLS,
						C_CALC_REC_END_STK,
						C_CALC_REC_GP_ALC
						)
				AND	t1.CALC_NO = t2.CALC_NO(+)
				AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD(+)
				AND	t1.TOP_REC_NO = t2.TOP_REC_NO(+)
				AND	t2.EXPNS_TYP(+) = C_EXPNS_PROD
				GROUP BY t1.TOP_REC_NO, t1.CALC_REC_TYP, t1.COST_IO_TYP,
					t1.AC_SLIP_TYP, t1.YM, t1.QTY
				) w
			WHERE	0=0
			GROUP BY w.CALC_REC_TYP, w.COST_IO_TYP, w.AC_SLIP_TYP, w.YM
			)
		LOOP
			IF y.CALC_REC_TYP = C_CALC_REC_IO
			AND 	(
				y.COST_IO_TYP IN (C_COST_IO_FFR_PROV, C_COST_IO_STK_IO)
				OR
				y.AC_SLIP_TYP IN (C_AC_SLIP_SHIP, C_AC_SLIP_SHIP_RET)
				)
			THEN
				NULL ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_ST_STK THEN
				rec(i).ST_STK_QTY := rec(i).ST_STK_QTY + y.QTY ;
				rec(i).ST_STK_AMT := rec(i).ST_STK_AMT + y.AMT ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_PURC THEN
				rec(i).PURC_QTY := rec(i).PURC_QTY + y.QTY ;
				rec(i).PURC_AMT := rec(i).PURC_AMT + y.AMT ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_COMP THEN
				rec(i).MFG_QTY := rec(i).MFG_QTY + y.QTY ;
				rec(i).MFG_AMT := rec(i).MFG_AMT + y.AMT ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_INPT THEN
				IF x.ASSET_MNG_TYP = C_ASSET_MNG_MNG THEN
					rec(i).INPT_QTY := rec(i).INPT_QTY + y.QTY ;
					rec(i).INPT_AMT := rec(i).INPT_AMT + y.AMT ;
				ELSE
					rec(i).XPNS_INPT_QTY := rec(i).XPNS_INPT_QTY + y.QTY ;
					rec(i).XPNS_INPT_AMT := rec(i).XPNS_INPT_AMT + y.AMT ;
				END IF;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_IO THEN
				IF y.COST_IO_TYP = C_COST_IO_ONR_PROV THEN
					rec(i).PROV_QTY := rec(i).PROV_QTY + y.QTY ;
					rec(i).PROV_AMT := rec(i).PROV_AMT + y.AMT ;

				ELSIF y.COST_IO_TYP = C_COST_IO_STK_IN THEN
					IF y.AC_SLIP_TYP = C_AC_SLIP_PROD_ITM_SO THEN
						rec(i).MFG_GR_QTY := rec(i).MFG_GR_QTY + y.QTY ;
						rec(i).MFG_GR_AMT := rec(i).MFG_GR_AMT + y.AMT ;
					ELSE
						rec(i).OTHR_GR_QTY := rec(i).OTHR_GR_QTY + y.QTY ;
						rec(i).OTHR_GR_AMT := rec(i).OTHR_GR_AMT + y.AMT ;
					END IF ;

				ELSIF y.COST_IO_TYP = C_COST_IO_STK_OUT THEN
					IF y.AC_SLIP_TYP = C_AC_SLIP_PROD_ITM_SO THEN
						rec(i).PLNT_GI_QTY := rec(i).PLNT_GI_QTY + y.QTY ;
						rec(i).PLNT_GI_AMT := rec(i).PLNT_GI_AMT + y.AMT ;
					ELSE
						rec(i).OTHR_GI_QTY := rec(i).OTHR_GI_QTY + y.QTY ;
						rec(i).OTHR_GI_AMT := rec(i).OTHR_GI_AMT + y.AMT ;
					END IF ;
				END IF ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_SLS THEN
				rec(i).SLS_QTY := rec(i).SLS_QTY + y.QTY ;
				rec(i).SLS_AMT := rec(i).SLS_AMT + y.AMT ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_END_STK THEN
				IF x.YM IS NULL OR x.YM = y.YM THEN
					rec(i).END_STK_QTY := rec(i).END_STK_QTY + y.QTY ;
					rec(i).END_STK_AMT := rec(i).END_STK_AMT + y.AMT ;
				ELSE
					rec(i).ST_STK_QTY := rec(i).ST_STK_QTY + y.QTY ;
					rec(i).ST_STK_AMT := rec(i).ST_STK_AMT + y.AMT ;
				END IF ;

			ELSIF y.CALC_REC_TYP = C_CALC_REC_GP_ALC THEN
				rec(i).ALC_AMT := rec(i).ALC_AMT + y.AMT ;

			END IF ;

		END LOOP ;

		--総平均単価情報の取得
		FOR z IN (
			SELECT	/*+USE_NL(t1 t2) INDEX(t1 MGT_ACC_TOP_ALL_IE02) INDEX(t2 MGT_ACC_SML_COST_ALL_IE01)*/
				t1.TOP_REC_NO,
				t1.QTY,
				NVL(SUM(t2.ACT_COST), 0) ACT_UPRI,
				NVL(SUM(t2.STD_COST), 0) STD_UPRI
			FROM	MGT_ACC_TOP t1, MGT_ACC_SML_COST t2
			WHERE	0=0
			AND	t1.CALC_NO = I_CALC_NO
			AND	t1.CALC_GRP_CD = I_CALC_GRP_CD
			AND	t1.WG_CD = x.WG_CD
			AND	t1.ITM_CD = x.ITM_CD
			AND	t1.ITM_SUB1 = x.ITM_SUB1
			AND	t1.ITM_SUB2 = x.ITM_SUB2
			AND	t1.ITM_SUB3 = x.ITM_SUB3
			AND	(t1.YM = x.YM OR t1.YM = L_ARG.END_YM AND x.YM IS NULL)
			AND	NVL(t1.MNG_DPT_CD, x.MNG_DPT_CD) = x.MNG_DPT_CD
			AND	t1.LOT_NO = DECODE(x.LOT_TYP, C_UNIT_CALC_CALC, x.LOT_NO, t1.LOT_NO)
			AND	t1.SUBLOT_NO = DECODE(x.SUBLOT_TYP, C_UNIT_CALC_CALC, x.SUBLOT_NO, t1.SUBLOT_NO)
			AND	t1.SNO1 = DECODE(x.SNO1_TYP, C_UNIT_CALC_CALC, x.SNO1, t1.SNO1)
			AND	t1.SNO2 = DECODE(x.SNO2_TYP, C_UNIT_CALC_CALC, x.SNO2, t1.SNO2)
			AND	t1.SNO3 = DECODE(x.SNO3_TYP, C_UNIT_CALC_CALC, x.SNO3, t1.SNO3)
			AND	t1.SNO4 = DECODE(x.SNO4_TYP, C_UNIT_CALC_CALC, x.SNO4, t1.SNO4)
			AND	t1.ASST_TYP = x.ASST_TYP
			AND	t1.REPURC_OBLI_FLG = '0'
			AND	t1.CALC_REC_TYP = C_CALC_REC_AVE
			AND	t1.CALC_NO = t2.CALC_NO(+)
			AND	t1.CALC_GRP_CD = t2.CALC_GRP_CD(+)
			AND	t1.TOP_REC_NO = t2.TOP_REC_NO(+)
			AND	t2.EXPNS_TYP(+) = C_EXPNS_PROD
			GROUP BY t1.TOP_REC_NO, t1.QTY
			)
		LOOP
			rec(i).STD_QTY := z.QTY ;
			rec(i).AVE_UPRI := z.ACT_UPRI ;
			rec(i).STD_UPRI := z.STD_UPRI ;
			EXIT ;
		END LOOP ;

		rec(i).DIFF_QTY := 0
			+ rec(i).ST_STK_QTY + rec(i).MFG_QTY
			+ rec(i).PURC_QTY + rec(i).MFG_GR_QTY + rec(i).OTHR_GR_QTY
			- rec(i).INPT_QTY - rec(i).PLNT_GI_QTY - rec(i).OTHR_GI_QTY
			- rec(i).PROV_QTY - rec(i).SLS_QTY - rec(i).END_STK_QTY
			;

		rec(i).DIFF_AMT := 0
			+ rec(i).ST_STK_AMT + rec(i).MFG_AMT
			+ rec(i).PURC_AMT + rec(i).MFG_GR_AMT + rec(i).OTHR_GR_AMT + rec(i).ALC_AMT
			- rec(i).INPT_AMT - rec(i).PLNT_GI_AMT - rec(i).OTHR_GI_AMT
			- rec(i).PROV_AMT - rec(i).SLS_AMT - rec(i).END_STK_AMT
			;

		IF i > 0 AND i >= C_MAX_CNT THEN
			FORALL t IN 1..i
				INSERT INTO MGT_IO VALUES rec(t) ;

			i := 0 ;
			rec.DELETE ;
		END IF ;

	END LOOP ;

	IF i > 0 THEN
		FORALL t IN 1..i
			INSERT INTO MGT_IO VALUES rec(t) ;
	END IF ;

	i := 0 ;
	rec.DELETE ;

	<<PROC_END>>
		NULL ;

	COMMIT ;

	IF I_WG_CD IS NULL THEN
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_IO.P_MAIN') ;
	ELSE
		FCPA_BATCH_LOG.P_PROC_LOG('MGBXD0002', 'MGPA_IO.P_MAIN - ' || I_WG_CD) ;
	END IF ;

END P_MAIN ;

