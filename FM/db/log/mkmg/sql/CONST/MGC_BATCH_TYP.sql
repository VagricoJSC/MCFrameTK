CREATE OR REPLACE PACKAGE BODY MGC_BATCH_TYP
/*****************************
原価バッチ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION WIP_LOC RETURN VARCHAR2 DETERMINISTIC IS -- 場所別仕掛原価データ作成処理
	BEGIN RETURN '01'; END WIP_LOC;
	FUNCTION IO RETURN VARCHAR2 DETERMINISTIC IS -- 原価受払表データ作成処理
	BEGIN RETURN '02'; END IO;
	FUNCTION CARRY RETURN VARCHAR2 DETERMINISTIC IS -- 繰越処理
	BEGIN RETURN '03'; END CARRY;

	FUNCTION IS_WIP_LOC(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 場所別仕掛原価データ作成処理かどうか
	BEGIN
		IF I_VALUE = WIP_LOC THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_WIP_LOC;

	FUNCTION IS_IO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 原価受払表データ作成処理かどうか
	BEGIN
		IF I_VALUE = IO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IO;

	FUNCTION IS_CARRY(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 繰越処理かどうか
	BEGIN
		IF I_VALUE = CARRY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CARRY;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = WIP_LOC
		OR I_VALUE = IO
		OR I_VALUE = CARRY THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION BATCH_NM(
		I_BATCH_TYP IN VARCHAR2
	)RETURN VARCHAR2
	 DETERMINISTIC IS
	BEGIN
		IF (I_BATCH_TYP = WIP_LOC) THEN
			RETURN 'MGPA_WIP_LOC$P_MAIN';
		ELSIF (I_BATCH_TYP = IO) THEN
			RETURN 'MGPA_IO$P_MAIN';
		ELSIF (I_BATCH_TYP = CARRY) THEN
			RETURN 'MGPA_CARRY_OVER$P_MAIN';
		ELSE
			RETURN NULL;
		END IF;
	END BATCH_NM;

	FUNCTION COST_BATCH_FLG(
		I_BATCH_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_BATCH_TYP = WIP_LOC) THEN
			RETURN '1';
		ELSIF (I_BATCH_TYP = IO) THEN
			RETURN '1';
		ELSIF (I_BATCH_TYP = CARRY) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END COST_BATCH_FLG;

	FUNCTION LIST_SORT(
		I_BATCH_TYP IN VARCHAR2
	)RETURN NUMBER
	 DETERMINISTIC IS
	BEGIN
		IF (I_BATCH_TYP = WIP_LOC) THEN
			RETURN 1;
		ELSIF (I_BATCH_TYP = IO) THEN
			RETURN 2;
		ELSIF (I_BATCH_TYP = CARRY) THEN
			RETURN 3;
		ELSE
			RETURN NULL;
		END IF;
	END LIST_SORT;

	FUNCTION BATCH_OUT_FLG(
		I_BATCH_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_BATCH_TYP = WIP_LOC) THEN
			RETURN '1';
		ELSIF (I_BATCH_TYP = IO) THEN
			RETURN '1';
		ELSIF (I_BATCH_TYP = CARRY) THEN
			RETURN '0';
		ELSE
			RETURN '0';
		END IF;
	END BATCH_OUT_FLG;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MGC_BATCH_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MGC_BATCH_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MGC_BATCH_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MGC_BATCH_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MGC_BATCH_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MGC_BATCH_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MGC_BATCH_TYP;

/
show errors;


