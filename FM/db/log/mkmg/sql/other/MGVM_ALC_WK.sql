SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MGVM_ALC_WK(
	ALC_PTN_CD,
	WK_COST_CD,
	TR_ALC_AC_CD,
	TR_ALC_PTN_CD,
	TR_EXPNS_CD
)
AS
SELECT	m1.ALC_PTN_CD,
	m1.WK_COST_CD,
	m1.ALC_AC_CD	TR_ALC_AC_CD,
	m2.ALC_PTN_CD	TR_ALC_PTN_CD,
	m2.EXPNS_CD	TR_EXPNS_CD
FROM	MGW_ARG w1, MAM_ALC_WK m1, MAM_ALC_AC m2
WHERE	0=0
AND	w1.TERM = m1.TERM
AND	m1.ALC_AC_CD = m2.ALC_AC_CD(+)
AND	EXISTS (
		SELECT	'X'
		FROM	MGVM_ALC_RULE x
		WHERE	0=0
		AND	x.ALC_PTN_CD = m1.ALC_PTN_CD
		AND	x.ALC_RULE_TYP = MAC_ALC_RULE_TYP.WK
	)
;

