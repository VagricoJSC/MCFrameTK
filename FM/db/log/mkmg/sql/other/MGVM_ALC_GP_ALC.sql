CREATE OR REPLACE VIEW MGVM_ALC_GP_ALC(
	ALC_PTN_CD,
	GP_ALC_CD
)
AS
SELECT	m1.ALC_PTN_CD,
	m1.GP_ALC_CD
FROM	MGW_ARG w1, MAM_ALC_GP_ALC m1
WHERE	0=0
AND	w1.TERM = m1.TERM
AND	EXISTS (
		SELECT	'X'
		FROM	MGVM_ALC_RULE x
		WHERE	0=0
		AND	x.ALC_PTN_CD = m1.ALC_PTN_CD
		AND	x.ALC_TGT_TYP = MAC_ALC_TGT_TYP.ALC
	)
;

