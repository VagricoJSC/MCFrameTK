CREATE OR REPLACE VIEW MGVT_ST_STK(
	ST_STK_KEY,
	WG_CD,
	GR_DT,
	MNG_DPT_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	BP_CD,
	ASST_TYP,
	QTY,
	REPURC_OBLI_FLG
)
AS
SELECT	t1.ST_STK_KEY,
	NVL(w1.RUNTIME_WG_CD, t1.WG_CD) WG_CD,
	t1.GR_DT,
	t1.MNG_DPT_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.BP_CD,
	t1.ASST_TYP,
	t1.QTY,
	t1.REPURC_OBLI_FLG
FROM	MGW_ARG w1, MGT_CALC_PARM m1, MGT_ST_STK t1,
		(	SELECT CALC_GRP_CD,WG_CD FROM MAM_GRP_WG
			UNION
			SELECT CALC_GRP_CD,RUNTIME_WG_CD WG_CD FROM MGW_ARG 
		) m2
WHERE	0=0
AND	w1.CALC_NO = m1.CALC_NO
AND	w1.CALC_GRP_CD = m1.CALC_GRP_CD
AND	m1.PARM_KEY = 'ETC_STK_CALC_GRP'
AND	m1.PARM_VAL = t1.CALC_GRP_CD
AND	w1.ST_YM = t1.YM
AND	m2.CALC_GRP_CD = w1.CALC_GRP_CD
AND	m2.WG_CD = t1.WG_CD
AND	(
	NOT EXISTS (
		SELECT	'X'
		FROM	MGW_USR_ITM t
		WHERE	0=0
		)
	OR EXISTS (
		SELECT	'X'
		FROM	MGW_USR_ITM x
		WHERE	0=0
		AND	x.ITM_CD = t1.ITM_CD
		AND	x.ITM_SUB1 = t1.ITM_SUB1
		AND	x.ITM_SUB2 = t1.ITM_SUB2
		AND	x.ITM_SUB3 = t1.ITM_SUB3
		)
	)
;

