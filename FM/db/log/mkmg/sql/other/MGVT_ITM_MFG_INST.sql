CREATE OR REPLACE VIEW MGVT_ITM_MFG_INST(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	ITM_MFG_INST_NO,
	MFG_ACT_NO,
	WG_CD,
	MNG_DPT_CD,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	SPPL_CD,
	PO_NO,
	SLO_NO,
	IV_NO,
	ASST_TYP,
	QTY
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.ITM_MFG_INST_NO,
	t1.MFG_ACT_NO,
	t1.WG_CD,
	t1.MNG_DPT_CD,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.SPPL_CD,
	t1.PO_NO,
	t1.SLO_NO,
	t1.IV_NO,
	t1.ASST_TYP,
	t1.QTY
FROM	MGW_ARG w1, MGT_CALC_ITM_MFG_INST t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

