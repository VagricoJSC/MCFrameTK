CREATE OR REPLACE VIEW MGVT_ST_WIP(
	ST_WIP_KEY,
	WG_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	ITM_MFG_INST_NO,
	MFG_ACT_NO,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	LOC_CD,
	STR_LN_CD,
	WIP_QTY,
	WIP_PER
)
AS
SELECT	t1.ST_WIP_KEY,
	NVL(w1.RUNTIME_WG_CD, t1.WG_CD) WG_CD,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.ITM_MFG_INST_NO,
	t1.MFG_ACT_NO,
	t1.OPER_ACT_NO,
	t1.OPER_CD,
	t1.OPER_SEQ,
	t1.LOC_CD,
	t1.STR_LN_CD,
	t1.WIP_QTY,
	t1.WIP_PER
FROM	MGW_ARG w1, MGT_CALC_PARM m1, MGT_ST_WIP t1,
		(	SELECT CALC_GRP_CD,WG_CD FROM MAM_GRP_WG
			UNION
			SELECT CALC_GRP_CD,RUNTIME_WG_CD WG_CD FROM MGW_ARG 
		) m2
WHERE	0=0
AND	w1.CALC_NO = m1.CALC_NO
AND	w1.CALC_GRP_CD = m1.CALC_GRP_CD
AND	m1.PARM_KEY = 'ETC_WIP_CALC_GRP'
AND	m1.PARM_VAL = t1.CALC_GRP_CD
AND	w1.ST_YM = t1.YM
AND	m2.CALC_GRP_CD = w1.CALC_GRP_CD
AND	m2.WG_CD = t1.WG_CD
AND	(
	NOT EXISTS (
		SELECT	'X'
		FROM	MGW_USR_ITM t
		WHERE	0=0
		)
	OR EXISTS (
		SELECT	'X'
		FROM	MGW_USR_ITM x
		WHERE	0=0
		AND	x.ITM_CD = t1.ITM_CD
		AND	x.ITM_SUB1 = t1.ITM_SUB1
		AND	x.ITM_SUB2 = t1.ITM_SUB2
		AND	x.ITM_SUB3 = t1.ITM_SUB3
		)
	)
;

