CREATE OR REPLACE VIEW MGVM_ITM_PURC(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SPPL_CD,
	WG_CD,
	BASE_QTY,
	CUR_CD,
	UPRI,
	BASE_CUR_UPRI,
	COST_RATIO
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.SPPL_CD,
	t1.WG_CD,
	t1.BASE_QTY,
	t1.CUR_CD,
	t1.UPRI,
	t1.BASE_CUR_UPRI,
	t1.COST_RATIO
FROM	MGW_ARG w1, MGT_CALC_ITM_PURC t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

