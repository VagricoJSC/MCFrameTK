CREATE OR REPLACE VIEW MGVM_ITM_OPER(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	OPER_PTN,
	OPER_CD,
	OPER_SEQ,
	WG_CD,
	DISP_SEQ,
	NMR_QTY,
	DNM_QTY,
	YIELD_OPER_FLG,
	OPER_UNIT_CD,
	OPER_STD_QTY,
	OPER_CONV_QTY,
	DEC_PLACE,
	UNIT_CONV_RND_TYP
)
AS
SELECT	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.LOC_CD,
	t1.OPER_PTN,
	t1.OPER_CD,
	t1.OPER_SEQ,
	t1.WG_CD,
	t1.DISP_SEQ,
	t1.NMR_QTY,
	t1.DNM_QTY,
	t1.YIELD_OPER_FLG,
	t1.OPER_UNIT_CD,
	t1.OPER_STD_QTY,
	t1.OPER_CONV_QTY,
	t1.DEC_PLACE,
	t1.UNIT_CONV_RND_TYP
FROM	MGW_ARG w1, MGT_CALC_ITM_OPER t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

