CREATE OR REPLACE VIEW MGVT_INST_WIP(
	WG_CD,
	YM,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	ITM_MFG_INST_NO,
	MFG_ACT_NO,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	LOC_CD,
	STR_LN_CD,
	AC_RSN_CD,
	WIP_QTY,
	WIP_PER
)
AS
SELECT	t1.WG_CD,
	t1.YM,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.ITM_MFG_INST_NO,
	t1.MFG_ACT_NO,
	t1.OPER_ACT_NO,
	t1.OPER_CD,
	t1.OPER_SEQ,
	t1.LOC_CD,
	t1.STR_LN_CD,
	t1.AC_RSN_CD,
	t1.WIP_QTY,
	t1.WIP_PER
FROM	MGW_ARG w1, MGT_CALC_INST_WIP t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

