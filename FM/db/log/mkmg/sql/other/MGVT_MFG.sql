CREATE OR REPLACE VIEW MGVT_MFG(
	WG_CD,
	YM,
	AC_DT,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_EXT,
	ITM_MFG_INST_NO,
	MFG_ACT_NO,
	OPER_ACT_NO,
	OPER_CD,
	OPER_SEQ,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	LOC_CD,
	STR_LN_CD,
	AC_SLIP_TYP,
	AC_RSN_CD,
	EXPNS_CD,
	QTY,
	AMT,
	CUR_CD,
	CUR_AMT,
	XRATE,
	MFG_PER,
	MFG_COST_RATIO,
	ALC_VAL1,
	ALC_VAL2,
	ALC_VAL3,
	ALC_VAL4,
	ALC_VAL5
)
AS
SELECT	t1.WG_CD,
	t1.YM,
	t1.AC_DT,
	t1.ITM_CD,
	t1.ITM_SUB1,
	t1.ITM_SUB2,
	t1.ITM_SUB3,
	t1.ITM_EXT,
	t1.ITM_MFG_INST_NO,
	t1.MFG_ACT_NO,
	t1.OPER_ACT_NO,
	t1.OPER_CD,
	t1.OPER_SEQ,
	t1.LOT_NO,
	t1.SUBLOT_NO,
	t1.SNO1,
	t1.SNO2,
	t1.SNO3,
	t1.SNO4,
	t1.LOC_CD,
	t1.STR_LN_CD,
	t1.AC_SLIP_TYP,
	t1.AC_RSN_CD,
	t1.EXPNS_CD,
	t1.QTY,
	t1.AMT,
	t1.CUR_CD,
	t1.CUR_AMT,
	t1.XRATE,
	t1.MFG_PER,
	t1.MFG_COST_RATIO,
	t1.ALC_VAL1,
	t1.ALC_VAL2,
	t1.ALC_VAL3,
	t1.ALC_VAL4,
	t1.ALC_VAL5
FROM	MGW_ARG w1, MGT_CALC_MFG t1
WHERE	0=0
AND	w1.CALC_NO = t1.CALC_NO
AND	w1.CALC_GRP_CD = t1.CALC_GRP_CD
;

