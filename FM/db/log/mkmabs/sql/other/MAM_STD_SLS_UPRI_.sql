SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_STD_SLS_UPRI_(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	UNIT_CD,
	LOT_QTY,
	CUR_CD,
	WG_CD,
	ST_DT,
	END_DT,
	UPRI,
	UPRI_BF,
	SUB_UPRI1,
	SUB_UPRI2,
	SUB_UPRI3,
	NOT_COST_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT 
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.UNIT_CD,
	ORG.LOT_QTY,
	ORG.CUR_CD,
	ORG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.UPRI,
	ORG.UPRI_BF,
	ORG.SUB_UPRI1,
	ORG.SUB_UPRI2,
	ORG.SUB_UPRI3,
	ORG.NOT_COST_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM 
	MAM_STD_SLS_UPRI_ALL ORG
WHERE 
	0 = 0
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

