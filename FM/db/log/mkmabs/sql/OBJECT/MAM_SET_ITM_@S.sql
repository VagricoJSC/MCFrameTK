CREATE OR REPLACE VIEW MAM_SET_ITM_$S(
	SET_GRP_CD,
	MAIN_ITM_CD,
	MAIN_ITM_SUB1,
	MAIN_ITM_SUB2,
	MAIN_ITM_SUB3,
	MAIN_ITM_UNIT_CD,
	SET_ITM_CD,
	SET_ITM_SUB1,
	SET_ITM_SUB2,
	SET_ITM_SUB3,
	SET_ITM_UNIT_CD,
	MAIN_ITM_QTY,
	SET_ITM_QTY,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SET_GRP_CD,
	ORG.MAIN_ITM_CD,
	ORG.MAIN_ITM_SUB1,
	ORG.MAIN_ITM_SUB2,
	ORG.MAIN_ITM_SUB3,
	ORG.MAIN_ITM_UNIT_CD,
	ORG.SET_ITM_CD,
	ORG.SET_ITM_SUB1,
	ORG.SET_ITM_SUB2,
	ORG.SET_ITM_SUB3,
	ORG.SET_ITM_UNIT_CD,
	ORG.MAIN_ITM_QTY,
	ORG.SET_ITM_QTY,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SET_ITM_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_set_itm'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

