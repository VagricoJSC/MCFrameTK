SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MAM_SPLN_ITM_CONF(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	SPLN_ITM_CD,
	DPT_CD,
	ST_YM,
	END_YM,
	CALC_RATE,
	CALC_SEQ,
	UPRI_UNIT_CD,
	LOT_QTY,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.SPLN_ITM_CD,
	ORG.DPT_CD,
	ORG.ST_YM,
	ORG.END_YM,
	ORG.CALC_RATE,
	ORG.CALC_SEQ,
	ORG.UPRI_UNIT_CD,
	ORG.LOT_QTY,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_SPLN_ITM_CONF_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_spln_itm_conf'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

