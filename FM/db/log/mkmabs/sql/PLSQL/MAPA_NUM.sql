PROCEDURE P_SET_BY_PTN(
	I_BIZ_TYP	IN MAPA_META.NUM_BIZ_TYP%TYPE
)
/**************************************************************************
<SYNOPSIS>
	発番パタンＣＤに対応した発番パタンマスタの設定に従った番号（文字列）を取得する。
	一括発番用。
<REMARKS>
	ワークテーブル（MAW_NUM_ARG）を参照してpeg_no順に発番し、
	発番した番号をnew_noに格納する。
<ARGUMENTS>
<IN>	I_BIZ_TYP
		発番業務区分
**************************************************************************/
IS
	L_NUM		MAPA_META.NUMBERING%TYPE ;

	TYPE NLIST IS TABLE OF MAW_NUM_ARG%ROWTYPE INDEX BY BINARY_INTEGER ;
	L_NUM_LIST	NLIST ;
	idx		BINARY_INTEGER ;
BEGIN
	idx := 0 ;
	FOR x IN (
		SELECT	w.*
		FROM	MAW_NUM_ARG w
		WHERE	0=0
		ORDER BY w.PEG_NO
		)
	LOOP
		P_GET_MAIN(I_BIZ_TYP, x.NUM_PTN_CD, x, L_NUM) ;
		idx := idx + 1 ;
		L_NUM_LIST(idx).PEG_NO := x.PEG_NO ;
		L_NUM_LIST(idx).NEW_NO := L_NUM ;
	END LOOP ;

	FORALL i IN 1..idx
		UPDATE MAW_NUM_ARG m SET m.NEW_NO = L_NUM_LIST(i).NEW_NO WHERE m.PEG_NO = L_NUM_LIST(i).PEG_NO ;

	L_NUM_LIST.DELETE ;
END;

