				L_REC_NUM_PTN.NUM_PAD_STR1,
				L_REC_NUM_PTN.DEF_SEQ_TYP
				);
		P_APPEND(L_ANS, L_REC_NUM_PTN.UNDISP_FLG1,
					I_BIZ_TYP, L_PTN_CD, 'ELM_TYP1', L_FULLCNT, L_DISPCNT) ;
	END IF;
