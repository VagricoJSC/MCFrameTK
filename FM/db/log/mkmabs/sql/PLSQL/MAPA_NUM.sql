PROCEDURE P_CREATE_SEQ (
	I_BIZ_TYP	IN MAPA_META.NUM_BIZ_TYP%TYPE ,
	I_PTN_CD	IN MAPA_META.NUM_PTN_CD%TYPE ,
	I_KEY_ELM	IN MAPA_META.NUMBERING_UNDISP%TYPE ,
	IO_SEQ_TYP	IN OUT MAPA_META.SEQ_TYP%TYPE
)
/**************************************************************************
<SYNOPSIS>
	指定されたコードで MAT_SEQ に新規レコードを作成する。
<REMARKS>
	通常発生しないが排他の関係で指定された引数の中で
	属性項目のもの（IO_SEQ_TYPE）は、引数と異なる物になる可能性がある。
	呼び出し元とは別セッションで実行され、このセッション内でCOMMITを
	発行します。
<ARGUMENTS>
<IN>	I_BIZ_TYP
		作成対象の発番業務区分
<IN>	I_PTN_CD
		作成対象の発番パタンＣＤ
<IN>	I_KEY_ELM
		作成対象のキー要素
<INOUT>	IO_SEQ_TYP
		（引数）作成対象のシーケンス区分。（戻り値）キーに対応するシーケンス区分
**************************************************************************/
IS
	PRAGMA AUTONOMOUS_TRANSACTION; -- 別セッションで実行する

	L_ORA_SEQ_NM	MAPA_META.ORA_OBJ_NM%TYPE ;
	L_BIND		FCPA_ERR.MSG_BINDER ;
	L_DGT		MAPA_META.NUM_NUMBER%TYPE;
	L_MAX_VAL	MAPA_META.NUM_NUMBER%TYPE;
BEGIN
	IF MAC_SEQ_TYP.IS_ORA_SEQ(IO_SEQ_TYP) = '1' THEN
		L_ORA_SEQ_NM := F_GET_NEW_ORA_SEQ_NM() ;
		P_CREATE_ORA_SEQUENCE(I_BIZ_TYP, I_PTN_CD, L_ORA_SEQ_NM) ;

		INSERT INTO MAT_SEQ (
			NUM_BIZ_TYP, NUM_PTN_CD, KEY_ELM,
			SEQ_TYP, ORA_SEQ_NM,
			MIN_VAL,
			MAX_VAL,
			INCREMENT_BY,
			CYCL_FLG,
			LAST_VAL
			)
		VALUES	(
			I_BIZ_TYP, I_PTN_CD, I_KEY_ELM,
			IO_SEQ_TYP, L_ORA_SEQ_NM,
			NULL,
			NULL,
			NULL,
			'0',
			NULL
			) ;

	ELSIF MAC_SEQ_TYP.IS_TBL_SEQ(IO_SEQ_TYP) = '1'  THEN
		L_ORA_SEQ_NM := NULL ;
		L_DGT := F_GET_SEQ_LENGTH(I_BIZ_TYP, I_PTN_CD) ;
		L_MAX_VAL := SUBSTR(MAC_NUM_PROC.SEQ_MAX_VAL_DEF(), 1, L_DGT) ;

		INSERT INTO MAT_SEQ (
			NUM_BIZ_TYP, NUM_PTN_CD, KEY_ELM,
			SEQ_TYP, ORA_SEQ_NM,
			MIN_VAL,
			MAX_VAL,
			INCREMENT_BY,
			CYCL_FLG,
			LAST_VAL
			)
		VALUES	(
			I_BIZ_TYP, I_PTN_CD, I_KEY_ELM,
			IO_SEQ_TYP, L_ORA_SEQ_NM,
			MAC_NUM_PROC.SEQ_MIN_VAL_DEF(),
			L_MAX_VAL,
			MAC_NUM_PROC.SEQ_INC_DEF(),
			MAC_NUM_PROC.SEQ_CYCL_FLG_DEF(),
			MAC_NUM_PROC.LAST_VAL_DEF()
			) ;
	ELSE
		-- シーケンス区分が予期せぬ値だった場合
		L_BIND := FCPA_ERR.MSG_BINDER(I_BIZ_TYP, I_PTN_CD, I_KEY_ELM, IO_SEQ_TYP) ;
		FCPA_ERR.RAISE_APP_ERR('MAUCD0012', L_BIND);
	END IF ;

	COMMIT ;
EXCEPTION
	WHEN DUP_VAL_ON_INDEX THEN
		SELECT	t.SEQ_TYP 
		INTO	IO_SEQ_TYP
		FROM	MAT_SEQ t
		WHERE	0 = 0
		AND	t.NUM_BIZ_TYP = I_BIZ_TYP
		AND	t.NUM_PTN_CD = I_PTN_CD
		AND	t.KEY_ELM = I_KEY_ELM
		;
	WHEN OTHERS THEN
		ROLLBACK ;
		RAISE ;
END P_CREATE_SEQ ;



PROCEDURE P_GET_SEQ_PROC(
	I_REC IN MAT_SEQ%ROWTYPE ,
	O_VAL OUT NUMBER
)
/**************************************************************************
<SYNOPSIS>
	指定された値からカウンタマスタを検索し、次の番号を発番して返します。
<REMARKS>
<ARGUMENTS>
<IN>	I_REC
		発番対象のMAT_SEQのROW
<OUT>	O_VAL
		発番した値
**************************************************************************/
IS
	L_REC		MAT_SEQ%ROWTYPE ;
	L_RET_NUM_VAL	NUMBER ; -- 戻り値を数値にしたもの
	L_MIN_VAL	NUMBER ;
	L_MAX_VAL	NUMBER ;

	L_BIND		FCPA_ERR.MSG_BINDER ;
	E_LOCK_ERR	EXCEPTION ;
BEGIN
	BEGIN
		SELECT	t.* 
		INTO	L_REC
		FROM	MAT_SEQ t
		WHERE	0=0
		AND	t.NUM_BIZ_TYP = I_REC.NUM_BIZ_TYP
		AND	t.NUM_PTN_CD = I_REC.NUM_PTN_CD
		AND	t.KEY_ELM = I_REC.KEY_ELM
		FOR UPDATE ;

		IF I_REC.SEQ_TYP <> L_REC.SEQ_TYP THEN
			-- 別セッションにする／しないの判断とSEQ_TYPが変更されていた場合、
			-- 排他エラーと判断する
			RAISE E_LOCK_ERR ;
		END IF ;
	EXCEPTION
		WHEN E_LOCK_ERR THEN
			L_BIND := FCPA_ERR.MSG_BINDER (SQLCODE, I_REC.NUM_BIZ_TYP, I_REC.NUM_PTN_CD, I_REC.KEY_ELM, I_REC.SEQ_TYP, L_REC.SEQ_TYP) ;
			FCPA_ERR.RAISE_APP_ERR ('MAUCD0009', L_BIND);
		WHEN OTHERS THEN
			L_BIND := FCPA_ERR.MSG_BINDER (SQLCODE, I_REC.NUM_BIZ_TYP, I_REC.NUM_PTN_CD, I_REC.KEY_ELM) ;
			FCPA_ERR.RAISE_APP_ERR ('MAUCD0005', L_BIND);
	END ;

	-- 以後、I_RECを使わない（L_RECを使う）
	IF MAC_SEQ_TYP.IS_TBL_SEQ(L_REC.SEQ_TYP) = '1' THEN
		L_RET_NUM_VAL := L_REC.LAST_VAL ;
		L_RET_NUM_VAL := L_RET_NUM_VAL + L_REC.INCREMENT_BY ;

		L_MIN_VAL := L_REC.MIN_VAL ;
		L_MAX_VAL := L_REC.MAX_VAL ;
		IF L_RET_NUM_VAL < L_MIN_VAL THEN
			L_RET_NUM_VAL := L_MIN_VAL ;
		END IF ;

		IF L_RET_NUM_VAL > L_MAX_VAL THEN
			IF L_REC.CYCL_FLG <> '1' THEN
				-- 自動セット許可ではないのにのカウンタが最大値を超えた
				L_BIND := FCPA_ERR.MSG_BINDER (I_REC.NUM_BIZ_TYP, I_REC.NUM_PTN_CD, I_REC.KEY_ELM) ;
				FCPA_ERR.RAISE_APP_ERR ('MAUCD0007', L_BIND) ;
			ELSE
				L_RET_NUM_VAL := L_MIN_VAL ;
				IF L_RET_NUM_VAL > L_MAX_VAL THEN
					-- 最小値が最大値より大きい場合（＝設定が不正）
					L_BIND := FCPA_ERR.MSG_BINDER (I_REC.NUM_BIZ_TYP, I_REC.NUM_PTN_CD, I_REC.KEY_ELM) ;
					FCPA_ERR.RAISE_APP_ERR ('MAUCD0014', L_BIND) ;
				END IF ;
			END IF ;
		END IF ;

		O_VAL := L_RET_NUM_VAL ;
		-- カウンタの保存
		UPDATE	MAT_SEQ t 
		SET	t.LAST_VAL = O_VAL
		WHERE	0=0
		AND	t.NUM_BIZ_TYP = L_REC.NUM_BIZ_TYP
		AND	t.NUM_PTN_CD = L_REC.NUM_PTN_CD
		AND	t.KEY_ELM = L_REC.KEY_ELM
		;
	ELSE
		-- 要素区分が予期せぬ値だった場合
		L_BIND := FCPA_ERR.MSG_BINDER (
					L_REC.NUM_BIZ_TYP ,
					L_REC.NUM_PTN_CD ,
					L_REC.KEY_ELM ,
					L_REC.SEQ_TYP
					) ;
		FCPA_ERR.RAISE_APP_ERR ('MAUCD0012', L_BIND) ;
	END IF ;
END P_GET_SEQ_PROC;



PROCEDURE P_GET_SEQ_ATNMS(
	I_REC IN MAT_SEQ%ROWTYPE ,
	O_VAL OUT NUMBER
)
/**************************************************************************
<SYNOPSIS>
		別セッションでカウンタ発番処理を起動し発番後コミットします。
<REMARKS>
<ARGUMENTS>
<IN>	I_REC
		発番対象のMAT_SEQのROW
<OUT>	O_VAL
		発番した値
**************************************************************************/
IS
	PRAGMA AUTONOMOUS_TRANSACTION; -- 別セッションで実行する
BEGIN
	P_GET_SEQ_PROC(I_REC, O_VAL) ;
	COMMIT ;
END P_GET_SEQ_ATNMS;



PROCEDURE P_GET_SEQ(
	I_BIZ_TYP	IN MAPA_META.NUM_BIZ_TYP%TYPE,
	I_PTN_CD	IN MAPA_META.NUM_PTN_CD%TYPE,
	I_KEY_ELM	IN MAPA_META.NUMBERING_UNDISP%TYPE,
	I_DEF_SEQ_TYP	IN MAPA_META.SEQ_TYP%TYPE,
	O_VAL	OUT MAPA_META.NUM_SEQ%TYPE
)
/**************************************************************************
<SYNOPSIS>
	引数に対応したシーケンス区分を検索して、それに応じた発番処理を呼び出し、
	発番結果を返します。
<REMARKS>
	この処理では、どの方式で発番するかを決定するだけで、
	ロックは別処理で行う（別セッションを実現するため）
<ARGUMENTS>
<IN>	I_BIZ_TYP
		発番対象の発番業務区分
<IN>	I_PTN_CD
		発番対象の発番パタンＣＤ
<IN>	I_KEY_ELM
		発番対象のキー要素
<IN>	I_DEF_SEQ_TYP
		新規にMAT_SEQを作成する場合に使用するSEQ_TYP
<OUT>	O_VAL
		発番した番号
**************************************************************************/
IS
	L_REC		MAT_SEQ%ROWTYPE ;
	L_SEQ_TYP	MAPA_META.SEQ_TYP%TYPE;
	L_SQL		VARCHAR2(100);	-- オラクルシーケンスを取得するためのＳＱＬ文
	L_ORA_VAL	MAPA_META.NUM_SEQ%TYPE;	-- オラクルシーケンスから取得した値

	E_NO_SEQUENCE EXCEPTION ;
	PRAGMA EXCEPTION_INIT(E_NO_SEQUENCE , -02289); -- ORA-02289: 順序が存在しません

	L_BIND		FCPA_ERR.MSG_BINDER;
BEGIN

	BEGIN
		SELECT	t.*
		INTO	L_REC
		FROM	MAT_SEQ t
		WHERE	0 = 0
		AND	t.NUM_BIZ_TYP = I_BIZ_TYP
		AND	t.NUM_PTN_CD = I_PTN_CD
		AND	t.KEY_ELM = I_KEY_ELM
		;
	EXCEPTION
		WHEN NO_DATA_FOUND THEN
			L_SEQ_TYP := I_DEF_SEQ_TYP ;
			P_CREATE_SEQ(I_BIZ_TYP, I_PTN_CD, I_KEY_ELM, L_SEQ_TYP) ;

			SELECT	t.* 
			INTO	L_REC
			FROM	MAT_SEQ t
			WHERE	0 = 0
			AND	t.NUM_BIZ_TYP = I_BIZ_TYP
			AND	t.NUM_PTN_CD = I_PTN_CD
			AND	t.KEY_ELM = I_KEY_ELM
			;
	END;

	IF MAC_SEQ_TYP.IS_ORA_SEQ(L_REC.SEQ_TYP) = '1' THEN
		BEGIN
			L_SQL := 'SELECT ' || L_REC.ORA_SEQ_NM || '.NEXTVAL FROM DUAL' ;
			EXECUTE IMMEDIATE L_SQL INTO L_ORA_VAL ;
		EXCEPTION
			WHEN E_NO_SEQUENCE THEN
				-- 順序が存在しない場合
				L_BIND := FCPA_ERR.MSG_BINDER (
							SQLCODE,
							L_REC.NUM_BIZ_TYP,
							L_REC.NUM_PTN_CD,
							L_REC.KEY_ELM,
							L_REC.ORA_SEQ_NM
							) ;
				FCPA_ERR.RAISE_APP_ERR ('MAUCD0006', L_BIND);
			WHEN OTHERS THEN
				-- 現状は意味がないけど条件分岐を分けておく
				L_BIND := FCPA_ERR.MSG_BINDER (
							SQLCODE,
							L_REC.NUM_BIZ_TYP,
							L_REC.NUM_PTN_CD,
							L_REC.KEY_ELM,
							L_REC.ORA_SEQ_NM
							) ;
				FCPA_ERR.RAISE_APP_ERR ('MAUCD0006', L_BIND);
		END;
		O_VAL := L_ORA_VAL;
	ELSIF MAC_SEQ_TYP.IS_ATNMS_TRAN(L_REC.SEQ_TYP) = '1' THEN
		P_GET_SEQ_ATNMS(L_REC ,O_VAL);
	ELSE
		P_GET_SEQ_PROC(L_REC ,O_VAL);
	END IF;
END P_GET_SEQ;



