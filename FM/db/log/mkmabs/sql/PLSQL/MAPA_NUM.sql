PROCEDURE P_TO_NUM_NUMBER_CONST(
	I_SRC_STR	IN VARCHAR2,
	I_SRC_ORIGIN	IN VARCHAR2,
	O_DEST_NUM	OUT NUMBER
)
/**************************************************************************
<SYNOPSIS>
	文字列を数値に変換する（定数用）
<REMARKS>
	エラー処理を統一することが目的のファンクション
<ARGUMENTS>
<IN>	I_SRC_STR
		変換対象（数値を表す文字列）
<IN>	I_SRC_ORIGIN
		変換対象の発生元（例外処理で使用する）
<OUT>	O_DEST_NUM
		変換後の数値
**************************************************************************/
AS
	L_BIND		FCPA_ERR.MSG_BINDER;
BEGIN
	O_DEST_NUM := TO_NUMBER(I_SRC_STR) ;
EXCEPTION
WHEN INVALID_NUMBER THEN
	-- MAC_NUM_PROC.LAST_VAL_DEFの設定エラー（数値にできない文字列）
	L_BIND := FCPA_ERR.MSG_BINDER (I_SRC_ORIGIN, I_SRC_STR) ;
	FCPA_ERR.RAISE_APP_ERR ('MAUCD0001', L_BIND) ;

WHEN VALUE_ERROR THEN
	-- 文字列の桁数が数値の精度（桁数）以上の場合
	L_BIND := FCPA_ERR.MSG_BINDER (I_SRC_ORIGIN, I_SRC_STR) ;
	FCPA_ERR.RAISE_APP_ERR ('MAUCD0003', L_BIND) ;

END P_TO_NUM_NUMBER_CONST;



PROCEDURE P_APPEND(
	I_APPEND_STR		IN MAPA_META.NUMBERING_UNDISP%TYPE,
	I_UNDISP_FLG		IN MAPA_META.FLG%TYPE,
	I_BIZ_TYP		IN MAPA_META.NUM_BIZ_TYP%TYPE,
	I_PTN_CD		IN MAPA_META.NUM_PTN_CD%TYPE,
	I_COL_NM		IN VARCHAR2,
	IO_DEST_UNDISP_STR	IN OUT MAPA_META.NUMBERING_UNDISP%TYPE,
	IO_DEST_DISP_STR	IN OUT MAPA_META.NUMBERING%TYPE
)
/**************************************************************************
<SYNOPSIS>
	現在の非表示文字列、表示文字列それぞれに、文字列を追加します。
<REMARKS>
	エラー処理を統一することが主目的の処理
<ARGUMENTS>
<IN>	I_APPND_STR
		結合対象の文字列
<IN>	I_UNDISP_FLG
		非表示フラグ
<IN>	I_BIZ_TYP
		例外が発生した発番業務区分（例外処理で使用する）
<IN>	I_PTN_CD
		例外が発生した発番パタンＣＤ（例外処理で使用する）
<IN>	I_COL_NM
		例外が発生した要素区分のカラム名（例外処理で使用する）
<INOUT>	IO_DEST_UNDISP_STR
		非表示文字列
<INOUT>	IO_DEST_DISP_STR
		表示文字列
**************************************************************************/
AS
	L_BIND	FCPA_ERR.MSG_BINDER;
BEGIN
	BEGIN
		IO_DEST_UNDISP_STR := IO_DEST_UNDISP_STR || I_APPEND_STR ;
	EXCEPTION
	WHEN VALUE_ERROR THEN
		-- 文字列の桁数が数値の精度（桁数）以上の場合
		L_BIND := FCPA_ERR.MSG_BINDER (
				I_BIZ_TYP,
				I_PTN_CD,
				I_COL_NM,
				IO_DEST_UNDISP_STR,
				I_APPEND_STR
				) ;
		FCPA_ERR.RAISE_APP_ERR ('MAUCD0013', L_BIND) ;
	END ;

	BEGIN
		IF I_UNDISP_FLG <> '1' THEN
			IO_DEST_DISP_STR := IO_DEST_DISP_STR || I_APPEND_STR ;
		END IF ;
	EXCEPTION
	WHEN VALUE_ERROR THEN
		-- 文字列の桁数が数値の精度（桁数）以上の場合
		L_BIND := FCPA_ERR.MSG_BINDER (
				I_BIZ_TYP,
				I_PTN_CD,
				I_COL_NM,
				IO_DEST_DISP_STR,
				I_APPEND_STR
				) ;
		FCPA_ERR.RAISE_APP_ERR ('MAUCD0022', L_BIND) ;
	END ;
END P_APPEND ;



FUNCTION F_GET_SEQ_LENGTH (
	I_BIZ_TYP	IN MAPA_META.NUM_BIZ_TYP%TYPE,
	I_PTN_CD	IN MAPA_META.NUM_PTN_CD%TYPE
)
RETURN NUMBER
/**************************************************************************
<SYNOPSIS>
	連番の桁数を取得する。
<REMARKS>
	発番パタンマスタの要素に定義された連番（SEQ）の項目を特定し、
	対応する項目の桁数を返す。
<ARGUMENTS>
<IN>	I_BIZ_TYP
		作成対象の発番業務区分
<IN>	I_PTN_CD
		作成対象の発番パタンＣＤ
**************************************************************************/
IS
BEGIN
	FOR x IN (
		SELECT	m.* 
		FROM	MAM_NUM_PTN m
		WHERE	0=0
		AND	m.NUM_BIZ_TYP = I_BIZ_TYP
		AND	m.NUM_PTN_CD  = I_PTN_CD
		)
	LOOP
		IF x.ELM_TYP1 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT1 ;

		ELSIF x.ELM_TYP2 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT2 ;

		ELSIF x.ELM_TYP3 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT3 ;

		ELSIF x.ELM_TYP4 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT4 ;

		ELSIF x.ELM_TYP5 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT5 ;

		ELSIF x.ELM_TYP6 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT6 ;

		ELSIF x.ELM_TYP7 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT7 ;

		ELSIF x.ELM_TYP8 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT8 ;

		ELSIF x.ELM_TYP9 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT9 ;

		ELSIF x.ELM_TYP10 = MAC_ELM_TYP.SEQ THEN
			RETURN x.ELM_DGT10 ;
		END IF ;
	END LOOP ;

	RETURN 0 ;

END F_GET_SEQ_LENGTH ;



