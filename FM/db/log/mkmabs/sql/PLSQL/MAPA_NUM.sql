		SELECT	m.* 
		INTO	L_REC_NUM_PTN
		FROM	MAM_NUM_PTN m
		WHERE	0=0
		AND	m.NUM_BIZ_TYP = I_BIZ_TYP
		AND	m.NUM_PTN_CD = L_PTN_CD
		;
