FUNCTION F_GET_SEQ(
	I_ORA_SEQ_NM	IN MAPA_META.ORA_OBJ_NM%TYPE
)RETURN NUMBER
/**************************************************************************
<SYNOPSIS>
	指定されたオラクルシーケンスのNEXTVALを返します。
<REMARKS>
	NUMBERING系の発番処理とは異なり、直接シーケンスの値を返す処理。
	よって、NUMBERING系の処理とは、この処理は共有しない。
	シーケンスが無かったら作るなどのカスタマイズを入れる事ができる。
<ARGUMENTS>
<IN>	I_ORA_SEQ_NM
		オラクルシーケンス名
<RETURNVALUE>
	発番した番号（数値）
**************************************************************************/
IS
	L_SQL	VARCHAR2(100);	-- オラクルシーケンスを取得するためのＳＱＬ文
	L_ANS	NUMBER;
	L_BIND	FCPA_ERR.MSG_BINDER;
BEGIN
	L_SQL := 'SELECT ' || I_ORA_SEQ_NM || '.NEXTVAL FROM DUAL';
	EXECUTE IMMEDIATE L_SQL INTO L_ANS ;
	RETURN L_ANS ;
EXCEPTION
	WHEN OTHERS THEN
		L_BIND := FCPA_ERR.MSG_BINDER (SQLCODE, I_ORA_SEQ_NM);
		FCPA_ERR.RAISE_APP_ERR ('MAUCD0015', L_BIND);
END F_GET_SEQ;

