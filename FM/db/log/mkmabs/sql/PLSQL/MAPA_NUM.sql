				L_REC_NUM_PTN.ELM_TYP2,
				L_REC_NUM_PTN.ELM_DGT2,
				L_REC_NUM_PTN.FIX2,
				L_REC_NUM_PTN.NUM_PAD_STR2,
				L_REC_NUM_PTN.DEF_SEQ_TYP
