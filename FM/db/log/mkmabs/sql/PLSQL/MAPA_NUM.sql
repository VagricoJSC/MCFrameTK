PROCEDURE P_CREATE_ORA_SEQUENCE (
	I_BIZ_TYP	IN MAPA_META.NUM_BIZ_TYP%TYPE,
	I_PTN_CD	IN MAPA_META.NUM_PTN_CD%TYPE,
	I_ORA_SEQ_NM	IN MAPA_META.ORA_OBJ_NM%TYPE
)
/**************************************************************************
<SYNOPSIS>
	指定された名称のシーケンスを作成する。
<REMARKS>
	このプロシージャ内でDDL文を発行するため、COMMITが発行される。
	P_CREATE_SEQから本プロシージャを呼ぶ場合は問題がないが、
	直接呼ぶ場合は、別セッションにするなどの対策が必要になる。
<ARGUMENTS>
<IN>	I_BIZ_TYP
		作成対象の発番業務区分
<IN>	I_PTN_CD
		作成対象の発番パタンＣＤ
<IN>	I_ORA_SEQ_NM
		作成対象のシーケンス名
**************************************************************************/
IS
	-- ローカル変数
	L_START_VAL MAPA_META.NUM_NUMBER%TYPE;
	L_TEMP_VAL  MAPA_META.NUM_NUMBER%TYPE;
	L_MAX_VAL   MAPA_META.NUM_NUMBER%TYPE;
	L_DGT       MAPA_META.NUM_NUMBER%TYPE;
	L_CYCLE_STR VARCHAR2(20);
	L_SQL	VARCHAR2(300);

	L_BIND	FCPA_ERR.MSG_BINDER;

	-- 例外
	E_DUP_OBJECT EXCEPTION ;
	PRAGMA EXCEPTION_INIT (E_DUP_OBJECT , -00955); -- オラクルのエラー番号：00955 既に使用されているオブジェクト名です

	E_MIN_GT_MAX EXCEPTION ;
	PRAGMA EXCEPTION_INIT (E_MIN_GT_MAX , -04004); -- オラクルのエラー番号：04004 最小値は最大値より小さい必要があります。

BEGIN
	IF MAC_NUM_PROC.SEQ_CYCL_FLG_DEF() = '1' THEN
		L_CYCLE_STR := 'CYCLE' ;
	ELSE
		L_CYCLE_STR := 'NOCYCLE' ;
	END IF;

	P_TO_NUM_NUMBER_CONST(MAC_NUM_PROC.LAST_VAL_DEF(), 'MAC_NUM_PROC.LAST_VAL_DEF()', L_START_VAL) ;

	-- 文字列が数値として妥当かどうかチェック（戻り値は使用しない）
	P_TO_NUM_NUMBER_CONST(MAC_NUM_PROC.SEQ_INC_DEF(), 'MAC_NUM_PROC.SEQ_INC_DEF()', L_TEMP_VAL) ;
	P_TO_NUM_NUMBER_CONST(MAC_NUM_PROC.SEQ_MIN_VAL_DEF(), 'MAC_NUM_PROC.SEQ_MIN_VAL_DEF()', L_TEMP_VAL) ;
	P_TO_NUM_NUMBER_CONST(MAC_NUM_PROC.SEQ_MAX_VAL_DEF(), 'MAC_NUM_PROC.SEQ_MAX_VAL_DEF()', L_TEMP_VAL) ;

	-- 最大値を要素が指定する連番の桁数に抑える
	IF I_BIZ_TYP IS NOT NULL AND I_PTN_CD IS NOT NULL THEN
		L_DGT := F_GET_SEQ_LENGTH(I_BIZ_TYP, I_PTN_CD) ;
		L_MAX_VAL := SUBSTR(MAC_NUM_PROC.SEQ_MAX_VAL_DEF(), 1, L_DGT) ;
	ELSE
		L_MAX_VAL := MAC_NUM_PROC.SEQ_MAX_VAL_DEF() ;
	END IF;

	L_SQL := 'CREATE SEQUENCE ' || I_ORA_SEQ_NM
				|| ' INCREMENT BY ' || MAC_NUM_PROC.SEQ_INC_DEF()
				|| ' START WITH ' || TO_CHAR(L_START_VAL + 1)
				|| ' MAXVALUE ' || L_MAX_VAL
				|| ' MINVALUE ' || MAC_NUM_PROC.SEQ_MIN_VAL_DEF()
				|| L_CYCLE_STR || ' ' || MAC_NUM_PROC.ORA_SEQ_OPT() ;
	EXECUTE IMMEDIATE L_SQL ;
EXCEPTION
	WHEN E_DUP_OBJECT THEN
		-- SEQUENCE名として使おうと思った名称が、
		-- 何らかのORACLEオブジェクト名として使用されている（＝引数が不正）
		L_BIND := FCPA_ERR.MSG_BINDER(I_ORA_SEQ_NM) ;
		FCPA_ERR.RAISE_APP_ERR ('MAUCD0002', L_BIND) ;
	WHEN E_MIN_GT_MAX THEN
		-- シーケンス作成時に指定した最小値が最大値より小さい
		L_BIND := FCPA_ERR.MSG_BINDER(MAC_NUM_PROC.SEQ_MIN_VAL_DEF(), MAC_NUM_PROC.SEQ_MAX_VAL_DEF()) ;
		FCPA_ERR.RAISE_APP_ERR ('MAUCD0017', L_BIND) ;
END P_CREATE_ORA_SEQUENCE ;



