CREATE OR REPLACE PACKAGE BODY MAC_BP_SET_TYP
/*****************************
取引先出力区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- 使用しない
	BEGIN RETURN 'X'; END NON;
	FUNCTION AR RETURN VARCHAR2 DETERMINISTIC IS -- 売掛先
	BEGIN RETURN '1'; END AR;
	FUNCTION CST RETURN VARCHAR2 DETERMINISTIC IS -- 得意先
	BEGIN RETURN '2'; END CST;
	FUNCTION SPL RETURN VARCHAR2 DETERMINISTIC IS -- 発注先
	BEGIN RETURN '3'; END SPL;
	FUNCTION AP RETURN VARCHAR2 DETERMINISTIC IS -- 買掛先
	BEGIN RETURN '4'; END AP;
	FUNCTION CRE RETURN VARCHAR2 DETERMINISTIC IS -- 入金先/支払先
	BEGIN RETURN '5'; END CRE;
	FUNCTION FIX_CST RETURN VARCHAR2 DETERMINISTIC IS -- 固定値(取引先区分=1)
	BEGIN RETURN '6'; END FIX_CST;
	FUNCTION FIX_SPL RETURN VARCHAR2 DETERMINISTIC IS -- 固定値(取引先区分=2)
	BEGIN RETURN '7'; END FIX_SPL;
	FUNCTION SO_CST RETURN VARCHAR2 DETERMINISTIC IS -- 相殺先(取引先区分=1)
	BEGIN RETURN '8'; END SO_CST;
	FUNCTION SO_SPL RETURN VARCHAR2 DETERMINISTIC IS -- 相殺先(取引先区分=2)
	BEGIN RETURN '9'; END SO_SPL;

	FUNCTION IS_NON(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 使用しないかどうか
	BEGIN
		IF I_VALUE = NON THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_NON;

	FUNCTION IS_AR(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売掛先かどうか
	BEGIN
		IF I_VALUE = AR THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AR;

	FUNCTION IS_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 得意先かどうか
	BEGIN
		IF I_VALUE = CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CST;

	FUNCTION IS_SPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 発注先かどうか
	BEGIN
		IF I_VALUE = SPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SPL;

	FUNCTION IS_AP(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 買掛先かどうか
	BEGIN
		IF I_VALUE = AP THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_AP;

	FUNCTION IS_CRE(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入金先/支払先かどうか
	BEGIN
		IF I_VALUE = CRE THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CRE;

	FUNCTION IS_FIX_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 固定値(取引先区分=1)かどうか
	BEGIN
		IF I_VALUE = FIX_CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FIX_CST;

	FUNCTION IS_FIX_SPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 固定値(取引先区分=2)かどうか
	BEGIN
		IF I_VALUE = FIX_SPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_FIX_SPL;

	FUNCTION IS_SO_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 相殺先(取引先区分=1)かどうか
	BEGIN
		IF I_VALUE = SO_CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SO_CST;

	FUNCTION IS_SO_SPL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 相殺先(取引先区分=2)かどうか
	BEGIN
		IF I_VALUE = SO_SPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SO_SPL;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = NON
		OR I_VALUE = AR
		OR I_VALUE = CST
		OR I_VALUE = SPL
		OR I_VALUE = AP
		OR I_VALUE = CRE
		OR I_VALUE = FIX_CST
		OR I_VALUE = FIX_SPL
		OR I_VALUE = SO_CST
		OR I_VALUE = SO_SPL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_BP_SET_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_BP_SET_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_BP_SET_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_BP_SET_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_BP_SET_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_BP_SET_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_BP_SET_TYP;

/
show errors;


