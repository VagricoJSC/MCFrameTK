CREATE OR REPLACE PACKAGE BODY MAC_COEF_CONFIG_TYP
/*****************************
配賦係数構成区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION CONFIG RETURN VARCHAR2 DETERMINISTIC IS -- 配賦係数構成マスタ
	BEGIN RETURN '1'; END CONFIG;
	FUNCTION ITM_JNL RETURN VARCHAR2 DETERMINISTIC IS -- 品目仕訳
	BEGIN RETURN '2'; END ITM_JNL;
	FUNCTION ITM_GRP1 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類１
	BEGIN RETURN 'A'; END ITM_GRP1;
	FUNCTION ITM_GRP2 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類２
	BEGIN RETURN 'B'; END ITM_GRP2;
	FUNCTION ITM_GRP3 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類３
	BEGIN RETURN 'C'; END ITM_GRP3;
	FUNCTION ITM_GRP4 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類４
	BEGIN RETURN 'D'; END ITM_GRP4;
	FUNCTION ITM_GRP5 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類５
	BEGIN RETURN 'E'; END ITM_GRP5;
	FUNCTION ITM_GRP6 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類６
	BEGIN RETURN 'F'; END ITM_GRP6;
	FUNCTION ITM_GRP7 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類７
	BEGIN RETURN 'G'; END ITM_GRP7;
	FUNCTION ITM_GRP8 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類８
	BEGIN RETURN 'H'; END ITM_GRP8;
	FUNCTION ITM_GRP9 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類９
	BEGIN RETURN 'I'; END ITM_GRP9;
	FUNCTION ITM_GRP10 RETURN VARCHAR2 DETERMINISTIC IS -- 品目分類１０
	BEGIN RETURN 'J'; END ITM_GRP10;
	FUNCTION NON RETURN VARCHAR2 DETERMINISTIC IS -- 指定なし
	BEGIN RETURN 'X'; END NON;

	FUNCTION IS_CONFIG(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 配賦係数構成マスタかどうか
	BEGIN
		IF I_VALUE = CONFIG THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CONFIG;

	FUNCTION IS_ITM_JNL(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目仕訳かどうか
	BEGIN
		IF I_VALUE = ITM_JNL THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_JNL;

	FUNCTION IS_ITM_GRP1(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類１かどうか
	BEGIN
		IF I_VALUE = ITM_GRP1 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP1;

	FUNCTION IS_ITM_GRP2(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類２かどうか
	BEGIN
		IF I_VALUE = ITM_GRP2 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP2;

	FUNCTION IS_ITM_GRP3(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類３かどうか
	BEGIN
		IF I_VALUE = ITM_GRP3 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP3;

	FUNCTION IS_ITM_GRP4(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類４かどうか
	BEGIN
		IF I_VALUE = ITM_GRP4 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP4;

	FUNCTION IS_ITM_GRP5(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類５かどうか
	BEGIN
		IF I_VALUE = ITM_GRP5 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP5;

	FUNCTION IS_ITM_GRP6(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類６かどうか
	BEGIN
		IF I_VALUE = ITM_GRP6 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP6;

	FUNCTION IS_ITM_GRP7(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類７かどうか
	BEGIN
		IF I_VALUE = ITM_GRP7 THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_GRP7;

	FUNCTION IS_ITM_GRP8(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目分類８かどうか
