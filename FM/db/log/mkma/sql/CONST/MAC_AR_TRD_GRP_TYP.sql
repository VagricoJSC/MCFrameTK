CREATE OR REPLACE PACKAGE BODY MAC_AR_TRD_GRP_TYP
/*****************************
債権取引グループ区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION SLS RETURN VARCHAR2 DETERMINISTIC IS -- 売上
	BEGIN RETURN '1'; END SLS;
	FUNCTION SLS_RTN RETURN VARCHAR2 DETERMINISTIC IS -- 売上返品
	BEGIN RETURN '2'; END SLS_RTN;
	FUNCTION SLS_DSCNT RETURN VARCHAR2 DETERMINISTIC IS -- 売上値引
	BEGIN RETURN '3'; END SLS_DSCNT;
	FUNCTION RCV RETURN VARCHAR2 DETERMINISTIC IS -- 入金
	BEGIN RETURN '4'; END RCV;
	FUNCTION SETOFF RETURN VARCHAR2 DETERMINISTIC IS -- 相殺
	BEGIN RETURN '5'; END SETOFF;
	FUNCTION ARSW RETURN VARCHAR2 DETERMINISTIC IS -- 債権残高振替
	BEGIN RETURN '6'; END ARSW;
	FUNCTION TAX_DIFF RETURN VARCHAR2 DETERMINISTIC IS -- 税差額
	BEGIN RETURN '7'; END TAX_DIFF;

	FUNCTION IS_SLS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上かどうか
	BEGIN
		IF I_VALUE = SLS THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS;

	FUNCTION IS_SLS_RTN(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上返品かどうか
	BEGIN
		IF I_VALUE = SLS_RTN THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_RTN;

	FUNCTION IS_SLS_DSCNT(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上値引かどうか
	BEGIN
		IF I_VALUE = SLS_DSCNT THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLS_DSCNT;

	FUNCTION IS_RCV(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 入金かどうか
	BEGIN
		IF I_VALUE = RCV THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_RCV;

	FUNCTION IS_SETOFF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 相殺かどうか
	BEGIN
		IF I_VALUE = SETOFF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SETOFF;

	FUNCTION IS_ARSW(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 債権残高振替かどうか
	BEGIN
		IF I_VALUE = ARSW THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ARSW;

	FUNCTION IS_TAX_DIFF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 税差額かどうか
	BEGIN
		IF I_VALUE = TAX_DIFF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_TAX_DIFF;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = SLS
		OR I_VALUE = SLS_RTN
		OR I_VALUE = SLS_DSCNT
		OR I_VALUE = RCV
		OR I_VALUE = SETOFF
		OR I_VALUE = ARSW
		OR I_VALUE = TAX_DIFF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_AR_TRD_GRP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_AR_TRD_GRP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_AR_TRD_GRP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_AR_TRD_GRP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_AR_TRD_GRP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_AR_TRD_GRP_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_AR_TRD_GRP_TYP;

/
