CREATE OR REPLACE PACKAGE BODY MAC_SLS_UPRI_IMP_TYP
/*****************************
販売単価取込区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION STD RETURN VARCHAR2 DETERMINISTIC IS -- 標準販売単価
	BEGIN RETURN '1'; END STD;
	FUNCTION ITM RETURN VARCHAR2 DETERMINISTIC IS -- 品目販売単価
	BEGIN RETURN '2'; END ITM;
	FUNCTION CST RETURN VARCHAR2 DETERMINISTIC IS -- 得意先販売単価
	BEGIN RETURN '3'; END CST;
	FUNCTION STD_ITM RETURN VARCHAR2 DETERMINISTIC IS -- 標準販売単価＋品目販売単価
	BEGIN RETURN '4'; END STD_ITM;
	FUNCTION STD_ITM_CST RETURN VARCHAR2 DETERMINISTIC IS -- 標準販売単価＋品目販売単価＋得意先販売単価
	BEGIN RETURN '5'; END STD_ITM_CST;

	FUNCTION IS_STD(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準販売単価かどうか
	BEGIN
		IF I_VALUE = STD THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD;

	FUNCTION IS_ITM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目販売単価かどうか
	BEGIN
		IF I_VALUE = ITM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM;

	FUNCTION IS_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 得意先販売単価かどうか
	BEGIN
		IF I_VALUE = CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_CST;

	FUNCTION IS_STD_ITM(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準販売単価＋品目販売単価かどうか
	BEGIN
		IF I_VALUE = STD_ITM THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD_ITM;

	FUNCTION IS_STD_ITM_CST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 標準販売単価＋品目販売単価＋得意先販売単価かどうか
	BEGIN
		IF I_VALUE = STD_ITM_CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_STD_ITM_CST;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = STD
		OR I_VALUE = ITM
		OR I_VALUE = CST
		OR I_VALUE = STD_ITM
		OR I_VALUE = STD_ITM_CST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_SLS_UPRI_IMP_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_SLS_UPRI_IMP_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_SLS_UPRI_IMP_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_SLS_UPRI_IMP_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_SLS_UPRI_IMP_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_SLS_UPRI_IMP_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_SLS_UPRI_IMP_TYP;

/
