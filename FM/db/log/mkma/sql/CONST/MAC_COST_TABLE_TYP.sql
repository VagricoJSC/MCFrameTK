CREATE OR REPLACE PACKAGE BODY MAC_COST_TABLE_TYP
/*****************************
原価テーブル区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION ITM_MFG_INST RETURN VARCHAR2 DETERMINISTIC IS -- 品目製造指図情報
	BEGIN RETURN 'ITM_MFG_INST'; END ITM_MFG_INST;
	FUNCTION ACT_PURC_IF RETURN VARCHAR2 DETERMINISTIC IS -- 購買実績ＩＦ
	BEGIN RETURN 'ACT_PURC_IF'; END ACT_PURC_IF;
	FUNCTION ACT_SLS_IF RETURN VARCHAR2 DETERMINISTIC IS -- 売上実績ＩＦ
	BEGIN RETURN 'ACT_SLS_IF'; END ACT_SLS_IF;

	FUNCTION IS_ITM_MFG_INST(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 品目製造指図情報かどうか
	BEGIN
		IF I_VALUE = ITM_MFG_INST THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ITM_MFG_INST;

	FUNCTION IS_ACT_PURC_IF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 購買実績ＩＦかどうか
	BEGIN
		IF I_VALUE = ACT_PURC_IF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACT_PURC_IF;

	FUNCTION IS_ACT_SLS_IF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 売上実績ＩＦかどうか
	BEGIN
		IF I_VALUE = ACT_SLS_IF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_ACT_SLS_IF;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = ITM_MFG_INST
		OR I_VALUE = ACT_PURC_IF
		OR I_VALUE = ACT_SLS_IF THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION LIST_SORT(
		I_COST_TABLE_TYP IN VARCHAR2
	)RETURN NUMBER
	 DETERMINISTIC IS
	BEGIN
		IF (I_COST_TABLE_TYP = ITM_MFG_INST) THEN
			RETURN 1;
		ELSIF (I_COST_TABLE_TYP = ACT_PURC_IF) THEN
			RETURN 2;
		ELSIF (I_COST_TABLE_TYP = ACT_SLS_IF) THEN
			RETURN 3;
		ELSE
			RETURN NULL;
		END IF;
	END LIST_SORT;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_COST_TABLE_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_COST_TABLE_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_COST_TABLE_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_COST_TABLE_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_COST_TABLE_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_COST_TABLE_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_COST_TABLE_TYP;

/
show errors;


