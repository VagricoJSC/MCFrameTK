	FUNCTION IS_ACT_PURC_IF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 購買実績ＩＦであるか
	FUNCTION IS_ACT_SLS_IF(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC ; -- 売上実績ＩＦであるか

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC; -- 定数に含まれるかどうか
