CREATE OR REPLACE PACKAGE BODY MAC_TGT_COL_TYP
/*****************************
対象項目区分の定数定義パッケージ本体
******************************/
IS

	FUNCTION PO_NO RETURN VARCHAR2 DETERMINISTIC IS -- 発注ＮＯ
	BEGIN RETURN 'PO_NO'; END PO_NO;
	FUNCTION SLO_NO RETURN VARCHAR2 DETERMINISTIC IS -- 受注ＮＯ
	BEGIN RETURN 'SLO_NO'; END SLO_NO;
	FUNCTION IV_NO RETURN VARCHAR2 DETERMINISTIC IS -- インボイスＮＯ
	BEGIN RETURN 'IV_NO'; END IV_NO;

	FUNCTION IS_PO_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 発注ＮＯかどうか
	BEGIN
		IF I_VALUE = PO_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_PO_NO;

	FUNCTION IS_SLO_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 受注ＮＯかどうか
	BEGIN
		IF I_VALUE = SLO_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_SLO_NO;

	FUNCTION IS_IV_NO(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- インボイスＮＯかどうか
	BEGIN
		IF I_VALUE = IV_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END IS_IV_NO;

	FUNCTION CONTAINS(I_VALUE IN VARCHAR2) RETURN CHAR DETERMINISTIC IS -- 定数に含まれるかどうか
	BEGIN
		IF I_VALUE = PO_NO
		OR I_VALUE = SLO_NO
		OR I_VALUE = IV_NO THEN
			RETURN '1';
		END IF;
		RETURN '0';
	END CONTAINS;


	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2) IS -- 定数に含まれるかどうか
		BEGIN
		CONTAINS_EX(I_VALUE, 'FCBCC5011');
	END CONTAINS_EX;
	PROCEDURE CONTAINS_EX(I_VALUE IN VARCHAR2, I_MSG_ID IN VARCHAR2, I_BIND IN FCPA_ERR.MSG_BINDER DEFAULT NULL) IS -- 定数に含まれるかどうか
		L_BIND FCPA_ERR.MSG_BINDER;
	BEGIN
		IF CONTAINS(I_VALUE) = '0' THEN
			IF  I_BIND IS NULL THEN
				L_BIND := FCPA_ERR.MSG_BINDER (I_VALUE);
			ELSE
				L_BIND := I_BIND;
			END IF;
			FCPA_ERR.RAISE_APP_ERR (I_MSG_ID, L_BIND);
		END IF;
	END CONTAINS_EX;

	FUNCTION LIST_SORT(
		I_TGT_COL_TYP IN VARCHAR2
	)RETURN NUMBER
	 DETERMINISTIC IS
	BEGIN
		IF (I_TGT_COL_TYP = PO_NO) THEN
			RETURN 1;
		ELSIF (I_TGT_COL_TYP = SLO_NO) THEN
			RETURN 2;
		ELSIF (I_TGT_COL_TYP = IV_NO) THEN
			RETURN 3;
		ELSE
			RETURN NULL;
		END IF;
	END LIST_SORT;

	FUNCTION IS_ITM_MFG_INST(
		I_TGT_COL_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_TGT_COL_TYP = PO_NO) THEN
			RETURN '1';
		ELSIF (I_TGT_COL_TYP = SLO_NO) THEN
			RETURN '1';
		ELSIF (I_TGT_COL_TYP = IV_NO) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_ITM_MFG_INST;

	FUNCTION IS_ACT_PURC_IF(
		I_TGT_COL_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_TGT_COL_TYP = PO_NO) THEN
			RETURN '1';
		ELSIF (I_TGT_COL_TYP = SLO_NO) THEN
			RETURN '1';
		ELSIF (I_TGT_COL_TYP = IV_NO) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_ACT_PURC_IF;

	FUNCTION IS_ACT_SLS_IF(
		I_TGT_COL_TYP IN VARCHAR2
	)RETURN CHAR
	 DETERMINISTIC IS
	BEGIN
		IF (I_TGT_COL_TYP = PO_NO) THEN
			RETURN '0';
		ELSIF (I_TGT_COL_TYP = SLO_NO) THEN
			RETURN '1';
		ELSIF (I_TGT_COL_TYP = IV_NO) THEN
			RETURN '1';
		ELSE
			RETURN '0';
		END IF;
	END IS_ACT_SLS_IF;

	FUNCTION K2NAME(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2NAME('MAC_TGT_COL_TYP', I_KEY, I_LCL_CD);
	END K2NAME;

	FUNCTION V2NAME(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2NAME('MAC_TGT_COL_TYP', I_VALUE, I_LCL_CD);
	END V2NAME;

	FUNCTION K2RMRKS(I_KEY IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- キーから定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.KEY2RMRKS('MAC_TGT_COL_TYP', I_KEY, I_LCL_CD);
	END K2RMRKS;

	FUNCTION V2RMRKS(I_VALUE IN VARCHAR2, I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 値から定数備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.STR2RMRKS('MAC_TGT_COL_TYP', I_VALUE, I_LCL_CD);
	END V2RMRKS;
	FUNCTION GRP_NAME(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ名を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_NAME('MAC_TGT_COL_TYP', I_LCL_CD);
	END GRP_NAME;

	FUNCTION GRP_RMRKS(I_LCL_CD IN VARCHAR2 DEFAULT NULL) RETURN VARCHAR2 -- 定数グループ備考を取得する
	IS
	BEGIN
		RETURN FCPA_CONST.GRP_RMRKS('MAC_TGT_COL_TYP', I_LCL_CD);
	END GRP_RMRKS;
	-- CUSTOMIZE BEGIN

	-- CUSTOMIZE END

END MAC_TGT_COL_TYP;

