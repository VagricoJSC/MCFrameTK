CREATE OR REPLACE VIEW MAM_PRE_ALC_CTG_$S(
	PRE_ALC_RATE_CD,
	CALC_CTG_CD,
	WG_CD,
	TERM,
	DATA_PLN_SA_TYP,
	DATA_ACT_SA_TYP,
	KEY_PLN_SA_TYP,
	KEY_ACT_SA_TYP,
	KEY_PLN_YM,
	KEY_ACT_YM,
	RATE_COEFF_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PRE_ALC_RATE_CD,
	ORG.CALC_CTG_CD,
	ORG.WG_CD,
	ORG.TERM,
	ORG.DATA_PLN_SA_TYP,
	ORG.DATA_ACT_SA_TYP,
	ORG.KEY_PLN_SA_TYP,
	ORG.KEY_ACT_SA_TYP,
	ORG.KEY_PLN_YM,
	ORG.KEY_ACT_YM,
	ORG.RATE_COEFF_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_PRE_ALC_CTG_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_pre_alc_ctg'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

