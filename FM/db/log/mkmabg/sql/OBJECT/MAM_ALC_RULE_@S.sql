CREATE OR REPLACE VIEW MAM_ALC_RULE_$S(
	ALC_PTN_CD,
	TERM,
	ALC_TGT_TYP,
	ALC_RULE_TYP,
	EXPNS_CD,
	DIFF_CALC_TYP,
	RND_TYP,
	DEC_PLACE,
	ALC_COEF_CD,
	COEF_LIMIT_FLG,
	ASST_TYP,
	NON_MINUS_FLG,
	NON_OS_FLG,
	SCST_ALC_FLG,
	STD_ALC_FLG,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ALC_PTN_CD,
	ORG.TERM,
	ORG.ALC_TGT_TYP,
	ORG.ALC_RULE_TYP,
	ORG.EXPNS_CD,
	ORG.DIFF_CALC_TYP,
	ORG.RND_TYP,
	ORG.DEC_PLACE,
	ORG.ALC_COEF_CD,
	ORG.COEF_LIMIT_FLG,
	ORG.ASST_TYP,
	ORG.NON_MINUS_FLG,
	ORG.NON_OS_FLG,
	ORG.SCST_ALC_FLG,
	ORG.STD_ALC_FLG,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_ALC_RULE_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_alc_rule'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

