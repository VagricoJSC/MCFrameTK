CREATE OR REPLACE VIEW MAM_REC_EVAL_SET_$S(
	SET_TGT_TYP,
	AC_SLIP_TYP,
	AC_RSN_CD,
	CALC_CTG_CD,
	WG_CD,
	ST_DT,
	END_DT,
	AMT_SET_TYP,
	CALC_GRP_CD,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.SET_TGT_TYP,
	ORG.AC_SLIP_TYP,
	ORG.AC_RSN_CD,
	ORG.CALC_CTG_CD,
	ORG.WG_CD,
	ORG.ST_DT,
	ORG.END_DT,
	ORG.AMT_SET_TYP,
	ORG.CALC_GRP_CD,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_REC_EVAL_SET_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_rec_eval_set'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

