SET SQLBLANKLINES ON

CREATE OR REPLACE TRIGGER MAM_COST_IO_CONF_ALL_TR_L
AFTER INSERT OR UPDATE ON MAM_COST_IO_CONF_ALL
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW
DECLARE
	SME BOOLEAN;
BEGIN
	IF (:OLD.IO_COL_NM IS NOT NULL AND :NEW.IO_COL_NM IS NOT NULL) THEN
		SME := (:OLD.IO_COL_NM = :NEW.IO_COL_NM);
	ELSE
		SME := (:OLD.IO_COL_NM IS NULL AND :NEW.IO_COL_NM IS NULL);
	END IF;
	IF NOT SME THEN GOTO MDIFF; END IF;
	<<MDIFF>>
	IF INSERTING OR (UPDATING AND NOT SME) THEN
	MERGE INTO MAM_COST_IO_CONF_LCL_ALL LCL
		USING  DUAL
		ON (0=0
			AND LCL.LCL_CD = FCPA_CONTEXT.F_GET_DEF_LOCALE_CD
			AND LCL.COST_IO_ID = :NEW.COST_IO_ID
			AND LCL.IO_COL_CD = :NEW.IO_COL_CD
			AND LCL.CO_CD = :NEW.CO_CD
		)
		WHEN MATCHED THEN
			UPDATE
			SET
				LCL.IO_COL_NM=:NEW.IO_COL_NM,
				LCL.INS_USR_ID=:NEW.INS_USR_ID,
				LCL.INS_USR_NM=:NEW.INS_USR_NM,
				LCL.INS_FUNC_ID=:NEW.INS_FUNC_ID,
				LCL.UPD_USR_ID=:NEW.UPD_USR_ID,
				LCL.UPD_USR_NM=:NEW.UPD_USR_NM,
				LCL.UPD_FUNC_ID=:NEW.UPD_FUNC_ID,
				LCL.UPD_SRV_REQ_NO=:NEW.UPD_SRV_REQ_NO
		WHEN NOT MATCHED THEN
			INSERT(
				LCL_CD,
				COST_IO_ID,
				IO_COL_CD,
				IO_COL_NM,
				CO_CD,
				INS_USR_ID,
				INS_USR_NM,
				INS_FUNC_ID,
				UPD_USR_ID,
				UPD_USR_NM,
				UPD_FUNC_ID,
				UPD_SRV_REQ_NO
			)VALUES(
				FCPA_CONTEXT.F_GET_DEF_LOCALE_CD,
				:NEW.COST_IO_ID,
				:NEW.IO_COL_CD,
				:NEW.IO_COL_NM,
				:NEW.CO_CD,
				:NEW.INS_USR_ID,
				:NEW.INS_USR_NM,
				:NEW.INS_FUNC_ID,
				:NEW.UPD_USR_ID,
				:NEW.UPD_USR_NM,
				:NEW.UPD_FUNC_ID,
				:NEW.UPD_SRV_REQ_NO
			)
		;
	END IF;
END;

/
show errors;


