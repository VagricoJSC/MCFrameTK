CREATE OR REPLACE VIEW MAM_COEF_AUTO_$S(
	ALC_COEF_CD,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	LOC_CD,
	OPER_CD,
	BP_CD,
	UNIT_CD,
	ITM_JNL_CD,
	ITM_GRP_TYP,
	ITM_GRP_CD,
	TERM,
	COEF_VAL,
	MEMO1,
	MEMO2,
	MEMO3,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.ALC_COEF_CD,
	ORG.LOT_NO,
	ORG.SUBLOT_NO,
	ORG.SNO1,
	ORG.SNO2,
	ORG.SNO3,
	ORG.SNO4,
	ORG.LOC_CD,
	ORG.OPER_CD,
	ORG.BP_CD,
	ORG.UNIT_CD,
	ORG.ITM_JNL_CD,
	ORG.ITM_GRP_TYP,
	ORG.ITM_GRP_CD,
	ORG.TERM,
	ORG.COEF_VAL,
	ORG.MEMO1,
	ORG.MEMO2,
	ORG.MEMO3,
	ORG.DEL_FLG,
	ORG.DEL_USR_ID,
	ORG.DEL_USR_NM,
	ORG.DEL_TS,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MAM_COEF_AUTO_ALL ORG
WHERE
	0 = 0
	AND (ORG.DEL_FLG = '0' OR MAPA_CONTEXT.F_GET_DEL_FLG_CTL = '0' OR EXISTS( SELECT 1 FROM MAW_DEL_FLG_CTL W WHERE LOWER(W.TBL_NM) = 'mam_coef_auto'))
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

