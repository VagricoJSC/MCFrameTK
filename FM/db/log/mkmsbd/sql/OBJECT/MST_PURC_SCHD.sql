SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MST_PURC_SCHD(
	PURC_SCHD_NO,
	ARR_PR_NO,
	ARR_SCHD_NO,
	PURC_SCHD_DT,
	TRD_UNIT_SCHD_QTY,
	TRD_UNIT_CD,
	BASE_UNIT_SCHD_QTY,
	BASE_UNIT_ABORT_QTY,
	BASE_UNIT_PURC_QTY,
	BASE_UNIT_TEMP_PURC_QTY,
	BASE_UNIT_ACCPT_DFCT_QTY,
	BASE_UNIT_CD,
	NON_PURC_FLG,
	CMPL_FLG,
	ABORT_FLG,
	PURC_SPLIT_FLG,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PURC_SCHD_NO,
	ORG.ARR_PR_NO,
	ORG.ARR_SCHD_NO,
	ORG.PURC_SCHD_DT,
	ORG.TRD_UNIT_SCHD_QTY,
	ORG.TRD_UNIT_CD,
	ORG.BASE_UNIT_SCHD_QTY,
	ORG.BASE_UNIT_ABORT_QTY,
	ORG.BASE_UNIT_PURC_QTY,
	ORG.BASE_UNIT_TEMP_PURC_QTY,
	ORG.BASE_UNIT_ACCPT_DFCT_QTY,
	ORG.BASE_UNIT_CD,
	ORG.NON_PURC_FLG,
	ORG.CMPL_FLG,
	ORG.ABORT_FLG,
	ORG.PURC_SPLIT_FLG,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PURC_SCHD_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

