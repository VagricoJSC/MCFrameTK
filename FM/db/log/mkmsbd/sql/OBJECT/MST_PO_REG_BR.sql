CREATE OR REPLACE VIEW MST_PO_REG_BR(
	BATCH_DATA_NO,
	BATCH_LOG_NO,
	LOG_SUB_KEY1,
	LOG_SUB_KEY2,
	EXE_STS_TYP,
	PO_SCHD_NO,
	WG_CD,
	SPPL_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	ITM_NM,
	PO_SCHD_DT,
	DLV_RQST_TM,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.BATCH_DATA_NO,
	ORG.BATCH_LOG_NO,
	ORG.LOG_SUB_KEY1,
	ORG.LOG_SUB_KEY2,
	ORG.EXE_STS_TYP,
	ORG.PO_SCHD_NO,
	ORG.WG_CD,
	ORG.SPPL_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.ITM_NM,
	ORG.PO_SCHD_DT,
	ORG.DLV_RQST_TM,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PO_REG_BR_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

