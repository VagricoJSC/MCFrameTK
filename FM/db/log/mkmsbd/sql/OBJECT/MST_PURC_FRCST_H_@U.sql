CREATE OR REPLACE VIEW MST_PURC_FRCST_H_$U(
	PURC_FRCST_NO,
	PF_DT,
	SPPL_CD,
	WG_CD,
	PF_USR_CD,
	PF_DPT_CD,
	PF_RPT_NO,
	PF_RPT_ID,
	PF_RPT_DT,
	PF_RPT_FLG,
	DEL_FLG,
	DEL_PF_RPT_ID,
	DEL_PF_RPT_DT,
	DEL_PF_RPT_FLG,
	RPT_RMRKS,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.PURC_FRCST_NO,
	ORG.PF_DT,
	ORG.SPPL_CD,
	ORG.WG_CD,
	ORG.PF_USR_CD,
	ORG.PF_DPT_CD,
	ORG.PF_RPT_NO,
	ORG.PF_RPT_ID,
	ORG.PF_RPT_DT,
	ORG.PF_RPT_FLG,
	ORG.DEL_FLG,
	ORG.DEL_PF_RPT_ID,
	ORG.DEL_PF_RPT_DT,
	ORG.DEL_PF_RPT_FLG,
	ORG.RPT_RMRKS,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_PURC_FRCST_H_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

