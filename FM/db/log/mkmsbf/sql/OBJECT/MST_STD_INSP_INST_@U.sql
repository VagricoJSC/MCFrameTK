	STD_INSP_INST_NO,
	INSP_TYP,
	INSP_NO,
	INSP_FREQ,
	INSP_SEQ,
	INSP_POINT_CD,
	INSP_QLQN_TYP,
	QN_OUT_MIN,
	QN_OUT_MAX,
	SIGN_OUT_MIN_TYP,
	SIGN_OUT_MAX_TYP,
	QN_IN_MIN,
	QN_IN_MAX,
	SIGN_IN_MIN_TYP,
	SIGN_IN_MAX_TYP,
	TRD_UNIT_CD,
	QN_INT_DIGIT,
	QN_INT_FRAC,
	QL_STD_VAL,
	ADD_POINT_FLG,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.STD_INSP_INST_NO,
	ORG.INSP_TYP,
	ORG.INSP_NO,
	ORG.INSP_FREQ,
	ORG.INSP_SEQ,
	ORG.INSP_POINT_CD,
	ORG.INSP_QLQN_TYP,
	ORG.QN_OUT_MIN,
	ORG.QN_OUT_MAX,
	ORG.SIGN_OUT_MIN_TYP,
	ORG.SIGN_OUT_MAX_TYP,
	ORG.QN_IN_MIN,
	ORG.QN_IN_MAX,
	ORG.SIGN_IN_MIN_TYP,
	ORG.SIGN_IN_MAX_TYP,
	ORG.TRD_UNIT_CD,
	ORG.QN_INT_DIGIT,
	ORG.QN_INT_FRAC,
	ORG.QL_STD_VAL,
	ORG.ADD_POINT_FLG,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_STD_INSP_INST_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

