CREATE OR REPLACE VIEW MBC_BULK_IMP_CTG_$S(
	TABLE_CTG,
	TABLE_CTG_NM,
	TABLE_CTG_SEQ,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.TABLE_CTG,
	LCL.TABLE_CTG_NM,
	ORG.TABLE_CTG_SEQ,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MBC_BULK_IMP_CTG_ALL ORG,
	mbc_bulk_imp_ctg_lcl_all LCL
WHERE
	0 = 0
	AND ORG.TABLE_CTG = LCL.TABLE_CTG(+)
	AND ORG.CO_CD = LCL.CO_CD(+)
	AND FCPA_CONTEXT.F_GET_LOCALE = LCL.LCL_CD(+)
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

