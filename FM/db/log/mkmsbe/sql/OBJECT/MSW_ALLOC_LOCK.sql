SET SQLBLANKLINES ON

CREATE GLOBAL TEMPORARY TABLE MSW_ALLOC_LOCK
(ITM_CD VARCHAR2 (40 char) NOT NULL,
ITM_SUB1 VARCHAR2 (5 char) DEFAULT '*' NOT NULL,
ITM_SUB2 VARCHAR2 (5 char) DEFAULT '*' NOT NULL,
ITM_SUB3 VARCHAR2 (5 char) DEFAULT '*' NOT NULL,
LOC_CD VARCHAR2 (20 char) NOT NULL
) ON COMMIT PRESERVE ROWS;


-- FOR DYNAMIC SAMPLING
DECLARE
	L_S VARCHAR2(30);
	L_T VARCHAR2(30);
BEGIN
	L_S:=SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
	L_T:='MSW_ALLOC_LOCK';
	DBMS_STATS.DELETE_TABLE_STATS(L_S, L_T);
	DBMS_STATS.LOCK_TABLE_STATS(L_S, L_T);
END;

/
show errors;


