CREATE OR REPLACE VIEW MST_STKTK_$S(
	CTRL_TGT_DT,
	LOC_CD,
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	STKTK_TYP,
	WG_CD,
	STKTK_STS_TYP,
	STKTK_ST_TM,
	DIFF_UPD_TM,
	ACT_DPT_CD,
	ACT_USR_CD,
	IO_CTRL_FLG,
	ACT_QTY_KEEP_FLG,
	STKTK_RPT_PRNT_FLG,
	DIFF_RPT_PRNT_FLG,
	STKTK_RPT_RMRKS,
	INTR_RMRKS,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
	)
AS
SELECT
	ORG.CTRL_TGT_DT,
	ORG.LOC_CD,
	ORG.ITM_CD,
	ORG.ITM_SUB1,
	ORG.ITM_SUB2,
	ORG.ITM_SUB3,
	ORG.STKTK_TYP,
	ORG.WG_CD,
	ORG.STKTK_STS_TYP,
	ORG.STKTK_ST_TM,
	ORG.DIFF_UPD_TM,
	ORG.ACT_DPT_CD,
	ORG.ACT_USR_CD,
	ORG.IO_CTRL_FLG,
	ORG.ACT_QTY_KEEP_FLG,
	ORG.STKTK_RPT_PRNT_FLG,
	ORG.DIFF_RPT_PRNT_FLG,
	ORG.STKTK_RPT_RMRKS,
	ORG.INTR_RMRKS,
	ORG.SUB_CHAR1,
	ORG.SUB_CHAR2,
	ORG.SUB_CHAR3,
	ORG.INS_USR_ID,
	ORG.INS_USR_NM,
	ORG.INS_TS,
	ORG.INS_FUNC_ID,
	ORG.UPD_CNTR,
	ORG.UPD_USR_ID,
	ORG.UPD_USR_NM,
	ORG.UPD_TS,
	ORG.UPD_FUNC_ID,
	ORG.UPD_SRV_REQ_NO
FROM
	MST_STKTK_ALL ORG
WHERE
	0 = 0
	
	AND ORG.CO_CD = FCPA_CONTEXT.F_GET_CO_CD
;

