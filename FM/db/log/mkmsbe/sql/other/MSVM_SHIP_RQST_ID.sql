SET SQLBLANKLINES ON

CREATE OR REPLACE VIEW MSVM_SHIP_RQST_ID(
	SHIP_RQST_ID_TYP,
	SHIP_RQST_ID_CD,
	SHIP_RQST_ID_NM,
	SHIP_RQST_ID_ALT_NM1,
	SHIP_RQST_ID_ALT_NM2,
	SHIP_RQST_ID_ALT_NM3,
	SHIP_RQST_ID_ALT_NM4,
	CNTRY_CD,
	CNTRY_NM,
	SITE_CD,
	SITE_NM,
	LG_GRP_CD,
	LG_GRP_NM,
	DEL_FLG,
	DEL_USR_ID,
	DEL_USR_NM,
	DEL_TS
)
AS
-- 得意先
SELECT
	MSC_SHIP_RQST_ID_TYP.CST,
	M1.BP_CD,
	M1.BP_NM,
	M1.BP_ALT_NM1,
	M1.BP_ALT_NM2,
	M1.BP_ALT_NM3,
	M1.BP_ALT_NM4,
	M1.CNTRY_CD,
	M2.CNTRY_NM,
	NULL,
	NULL,
	NULL,
	NULL,
	M1.DEL_FLG,
	M1.DEL_USR_ID,
	M1.DEL_USR_NM,
	M1.DEL_TS
FROM
	MAM_BP M1
	LEFT JOIN MAM_CNTRY M2 ON (M2.CNTRY_CD = M1.CNTRY_CD)
WHERE
	M1.CST_FLG = '1'
UNION ALL
-- 発注先
SELECT
	MSC_SHIP_RQST_ID_TYP.SPPL,
	M1.BP_CD,
	M1.BP_NM,
	M1.BP_ALT_NM1,
	M1.BP_ALT_NM2,
	M1.BP_ALT_NM3,
	M1.BP_ALT_NM4,
	M1.CNTRY_CD,
	M2.CNTRY_NM,
	NULL,
	NULL,
	NULL,
	NULL,
	M1.DEL_FLG,
	M1.DEL_USR_ID,
	M1.DEL_USR_NM,
	M1.DEL_TS
FROM
	MAM_BP M1
	LEFT JOIN MAM_CNTRY M2 ON (M2.CNTRY_CD = M1.CNTRY_CD)
WHERE
	M1.SPPL_FLG = '1'
UNION ALL
-- 場所
SELECT
	MSC_SHIP_RQST_ID_TYP.LOC,
	M1.LOC_CD,
	M1.LOC_NM,
	NULL,
	NULL,
	NULL,
	NULL,
	NULL,
	NULL,
	M1.SITE_CD,
	M2.SITE_NM,
	M1.LG_GRP_CD,
	M3.LG_GRP_NM,
	M1.DEL_FLG,
	M1.DEL_USR_ID,
	M1.DEL_USR_NM,
	M1.DEL_TS
FROM
	MAM_LOC M1
	LEFT JOIN MAM_SITE M2 ON (M2.SITE_CD = M1.SITE_CD)
	LEFT JOIN MAM_LG_GRP M3 ON (M3.LG_GRP_CD = M1.LG_GRP_CD)
	LEFT JOIN MAM_BP M4 ON (M4.BP_CD = M1.SPPL_CD)
WHERE
	M1.SPPL_CD is null
;

