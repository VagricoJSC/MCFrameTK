CREATE OR REPLACE VIEW MSVT_AVL_STK(
	ITM_CD,
	ITM_SUB1,
	ITM_SUB2,
	ITM_SUB3,
	LOC_CD,
	STR_LN_CD,
	STK_ARRV_BP_CD,
	LOT_NO,
	SUBLOT_NO,
	SNO1,
	SNO2,
	SNO3,
	SNO4,
	FIX_NO_TYP,
	FIX_NO,
	PACK_UNIT_CD,
	GD_CD,
	IN_XFR_TYP,
	QUALITY_TYP,
	ASST_TYP,
	STK_INSP_TYP,
	STK_ID_TYP,
	STK_BP_CD,
	PACK_UNIT_QTY,
	BASE_UNIT_QTY,
	SUB_CHAR1,
	SUB_CHAR2,
	SUB_CHAR3,
	INS_USR_ID,
	INS_USR_NM,
	INS_TS,
	INS_FUNC_ID,
	UPD_CNTR,
	UPD_USR_ID,
	UPD_USR_NM,
	UPD_TS,
	UPD_FUNC_ID,
	UPD_SRV_REQ_NO
)
AS
SELECT
	T1.*
FROM
	MST_STK T1
WHERE 0=0
AND T1.IN_XFR_TYP = MSC_IN_XFR_TYP.IN_LOC
AND T1.STK_INSP_TYP = MSC_STK_INSP_TYP.FIN
AND T1.STK_ID_TYP IN (MSC_STK_ID_TYP.COSTK, MSC_STK_ID_TYP.CSTSTK, MSC_STK_ID_TYP.RNT_RCV, MSC_STK_ID_TYP.ACCPT_DFCT, MSC_STK_ID_TYP.NCV_RCV, MSC_STK_ID_TYP.ONR_PROV)
AND (T1.STK_ARRV_BP_CD = MAC_STR.NULL_VAL
	OR EXISTS (
		SELECT 'X'
		FROM MAM_LOC M1
		WHERE 0=0
		AND M1.LOC_CD = T1.LOC_CD AND M1.SPPL_CD IS NOT NULL))
;

