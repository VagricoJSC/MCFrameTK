-- このAmazon RDS対応版SQLファイルは、マスターユーザで実行する必要があります。
-- SYS.V_$SESSIONの参照権限を与えるためです。
-- ユーザの表領域などがデフォルトのままですので
-- 本番環境構築時に使用する際は、注意してください。
-- このスクリプトは、SQL*Plusから実行することを前提としています。

CREATE USER &1
IDENTIFIED BY &2
DEFAULT TABLESPACE USERS
TEMPORARY TABLESPACE TEMP
PROFILE DEFAULT
QUOTA UNLIMITED ON USERS
/

GRANT ALTER SESSION TO &1
/
GRANT CREATE PROCEDURE TO &1
/
GRANT CREATE SEQUENCE TO &1
/
GRANT CREATE SESSION TO &1
/
GRANT CREATE SYNONYM TO &1
/
GRANT CREATE TABLE TO &1
/
GRANT CREATE TRIGGER TO &1
/
GRANT CREATE VIEW TO &1
/
GRANT SELECT ON SYS.V_$SESSION TO &1
/
GRANT SELECT ON SYS.V_$PROCESS TO &1
/
EXEC RDSADMIN.RDSADMIN_UTIL.GRANT_SYS_OBJECT('GV_$SESSION', '&1')
/
EXEC RDSADMIN.RDSADMIN_UTIL.GRANT_SYS_OBJECT('GV_$PROCESS', '&1')
/
GRANT EXECUTE ON RDSADMIN.RDSADMIN_UTIL TO &1
/
GRANT EXECUTE ON DBMS_CRYPTO TO &1
/
WHENEVER SQLERROR CONTINUE
GRANT CREATE JOB TO &1
/