CREATE OR REPLACE FUNCTION FSC_MODULE_ID$CONTAINS(IN I_VALUE VARCHAR) RETURNS CHAR(1) AS -- 定数に含まれるかどうか
$BODY$ BEGIN
	IF I_VALUE = FSC_MODULE_ID$Framework()
	OR I_VALUE = FSC_MODULE_ID$SystemAdmin()
	OR I_VALUE = FSC_MODULE_ID$xApps()
	OR I_VALUE = FSC_MODULE_ID$Trial()
	OR I_VALUE = FSC_MODULE_ID$FrameManager()
	OR I_VALUE = FSC_MODULE_ID$MasterAdmin()
	OR I_VALUE = FSC_MODULE_ID$Bcomm()
	OR I_VALUE = FSC_MODULE_ID$CostManagement()
	OR I_VALUE = FSC_MODULE_ID$SCM()
	OR I_VALUE = FSC_MODULE_ID$SDCordova()
	OR I_VALUE = FSC_MODULE_ID$NX()
	OR I_VALUE = FSC_MODULE_ID$MultiDevice()
	OR I_VALUE = FSC_MODULE_ID$ESB()
	OR I_VALUE = FSC_MODULE_ID$PLM()
	OR I_VALUE = FSC_MODULE_ID$PZ()
	OR I_VALUE = FSC_MODULE_ID$PB()
	OR I_VALUE = FSC_MODULE_ID$CFP() THEN
		RETURN '1';
	END IF;
	RETURN '0';
END;
$BODY$ LANGUAGE plpgsql IMMUTABLE;


CREATE OR REPLACE PROCEDURE FSC_MODULE_ID$CONTAINS_EX(IN I_VALUE VARCHAR, IN I_MSG_ID VARCHAR, IN I_BIND VARCHAR[] DEFAULT NULL::VARCHAR[]) AS -- 定数に含まれるかどうか
$BODY$ DECLARE
	L_BIND VARCHAR[];
BEGIN
	IF FSC_MODULE_ID$CONTAINS(I_VALUE) = '0' THEN
		IF  I_BIND IS NULL THEN
			L_BIND := FCPA_ERR$MSG_BINDER (I_VALUE);
		ELSE
			L_BIND := I_BIND;
		END IF;
		CALL FCPA_ERR$RAISE_APP_ERR (I_MSG_ID, L_BIND);
	END IF;
END;
$BODY$ LANGUAGE plpgsql;
